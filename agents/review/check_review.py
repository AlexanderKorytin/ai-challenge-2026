провалов = 0


def проверить(название: str, условие: bool, подробно: str = "") -> None:
    global провалов
    if условие:
        print(f"ок      {название}")
    else:
        провалов += 1
        print(f"ПРОВАЛ  {название}" + (f": {подробно}" if подробно else ""))


def _git(каталог: Path, *доводы: str) -> None:
    subprocess.run(["git", "-C", str(каталог), "-c", "user.name=п", "-c", "user.email=п@п", *доводы],
                   check=True, capture_output=True)


def хранилище(каталог: Path) -> None:
    """Основа `main` и вершина `правка`: правка в двух местах, новый, удалённый, переименованный
    и двоичный файлы, участок только из удалённых строк, удалённая строка вида `-- текст`."""
    _git(каталог, "init", "-q", "-b", "main")
    строки = [f"строка_{н} = {н}" for н in range(1, 41)]
    (каталог / "пакет").mkdir()
    (каталог / "пакет" / "модуль.py").write_text("def первая():\n    return 1\n" + "\n".join(строки) + "\ndef вторая():\n    return 2\n", "utf-8")
    (каталог / "лишний.py").write_text("x = 1\n", "utf-8")
    (каталог / "старое.md").write_text("# Старое\nтекст\n", "utf-8")
    (каталог / "запрос.sql").write_text("select 1;\n-- примечание\nselect 2;\n" + "\n".join(строки) + "\n", "utf-8")
    (каталог / "знаки.py").write_bytes(b"a = 1\rb = 2\n\x0c\nc = 3\n")
    _git(каталог, "add", "-A")
    _git(каталог, "commit", "-q", "-m", "основа")
    _git(каталог, "checkout", "-q", "-b", "правка")
    (каталог / "пакет" / "модуль.py").write_text("def первая():\n    return 10\n" + "\n".join(строки) + "\ndef вторая():\n    return 20\n", "utf-8")
    (каталог / "лишний.py").unlink()
    (каталог / "новый.py").write_text("y = 2\n", "utf-8")
    _git(каталог, "mv", "старое.md", "новое.md")
    (каталог / "запрос.sql").write_text("select 1;\nselect 2;\n" + "\n".join(строки) + "\n", "utf-8")
    (каталог / "с пробелом.py").write_text("z = 1\n", "utf-8")
    (каталог / "знаки.py").write_bytes(b"a = 1\rb = 2\n\x0c\nc = 3\nd = 4\n")
    (каталог / "картинка.bin").write_bytes(bytes(range(256)) * 4)
    _git(каталог, "add", "-A")
    _git(каталог, "commit", "-q", "-m", "правка")


def разбор() -> None:
    with tempfile.TemporaryDirectory() as врем:
        каталог = Path(врем)
        хранилище(каталог)
        изменения = review.git(каталог, "diff", "--no-color", "--no-ext-diff", "main...правка")
        участки = review.разобрать(изменения)
        по_файлу: dict[str, list[review.Участок]] = {}
        for у in участки:
            по_файлу.setdefault(у.файл, []).append(у)
        проверить("разбор: участки есть у правленого, нового, удалённого файла и нет у переименованного и двоичного",
                  sorted(по_файлу) == ["запрос.sql", "знаки.py", "лишний.py", "новый.py", "пакет/модуль.py", "с пробелом.py"],
                  repr(sorted(по_файлу)))
        проверить("разбор: строки делит только перевод строки — `\\r` и `\\x0c` внутри файла счёт не сбивают",
                  [(у.изменённые, у.места) for у in по_файлу.get("знаки.py", [])] == [(["d = 4"], [4])],
                  repr([(у.изменённые, у.места) for у in по_файлу.get("знаки.py", [])]))
        модуль = по_файлу.get("пакет/модуль.py", [])
        проверить("разбор: две далёкие правки одного файла — два участка со своими строками",
                  len(модуль) == 2 and модуль[0].изменённые == ["    return 1", "    return 10"]
                  and модуль[1].изменённые == ["    return 2", "    return 20"] and модуль[0].строка == 1 and модуль[1].строка > 30,
                  repr([(у.строка, у.изменённые) for у in модуль]))
        проверить("разбор: новый файл — строка 1 и добавленные строки",
                  [(у.строка, у.изменённые) for у in по_файлу.get("новый.py", [])] == [(1, ["y = 2"])])
        проверить("разбор: удалённый файл назван старым путём",
                  [у.изменённые for у in по_файлу.get("лишний.py", [])] == [["x = 1"]])
        проверить("разбор: удалённая строка «-- текст» остаётся строкой участка, а не началом файла",
                  [у.изменённые for у in по_файлу.get("запрос.sql", [])] == [["-- примечание"]],
                  repr([у.изменённые for у in по_файлу.get("запрос.sql", [])]))
        проверить("разбор: текст участка начинается с его заголовка", all(у.текст.startswith("@@ ") for у in участки))
        проверить("разбор: место правки — номер строки новой версии",
                  модуль[0].места == [2, 2] and [у.места for у in по_файлу.get("запрос.sql", [])] == [[2]],
                  repr(модуль[0].места))
        файлы = review.изменённые_файлы(каталог, "main", "правка")
        первый, второй = (review.запрос(у, файлы["пакет/модуль.py"]) for у in модуль)
        проверить("запрос: объявление, задетое правкой, и участок; соседнего объявления нет",
                  первый.startswith("def первая():\n    return 10") and первый.endswith(модуль[0].текст)
                  and "def вторая" not in первый.split("@@")[0] and второй.startswith("def вторая():\n    return 20"),
                  первый[:80])
        проверить("запрос: у удалённого файла и не Python — один участок",
                  review.запрос(по_файлу["лишний.py"][0], None) == по_файлу["лишний.py"][0].текст
                  and review.запрос(по_файлу["запрос.sql"][0], файлы["запрос.sql"]) == по_файлу["запрос.sql"][0].текст)
        проверить("файлы: полный текст вершины; удалённого и двоичного файла нет",
                  sorted(файлы) == ["запрос.sql", "знаки.py", "новое.md", "новый.py", "пакет/модуль.py", "с пробелом.py"]
                  and "return 20" in файлы["пакет/модуль.py"], repr(sorted(файлы)))
        текст = review.сообщение([], [], "M\tпакет/модуль.py", {"а.py": "x\ny\x0cz\n"}, изменения)
        проверить("сообщение: четыре блока по порядку и номера строк у текста файла",
                  [с for с in текст.splitlines() if с.startswith("# ")] ==
                  ["# Найдено в документации", "# Найдено в коде", "# Изменённые файлы", "# Изменения"]
                  and "    1  x\n    2  y\x0cz\n\n# Изменения" in текст)
        проверить("просмотр: без изменений — текст «Изменений нет», ключ не нужен",
                  "Изменений нет" in review.asyncio.run(review.просмотр(каталог, "main", "main", каталог / "нет.sqlite")))
        код = review.главная(["--repo", str(каталог), "--base", "main", "--head", "правка", "--out", str(каталог / "итог.md")])
        проверить("запуск: без ключа — код 1 и файл --out не создан", код == 1 and not (каталог / "итог.md").exists())
        код = review.главная(["--repo", str(каталог), "--base", "main", "--head", "нет-такой", "--out", str(каталог / "итог.md")])
        проверить("запуск: неизвестная ссылка — код 1", код == 1 and not (каталог / "итог.md").exists())


class ПодставнойПоиск:
    def __init__(self, выдача: dict[str, list[str]]) -> None:
        self.выдача, self.вызовы, self.окно = выдача, [], 10

    def отобрать(self, вопрос, режим, k1, k2, порог):
        self.вызовы.append((режим, k1, k2, порог))
        if len(вопрос.splitlines()) > self.окно:
            raise review.эм.ПереполнениеОкна("длинно")
        куски = [рр.Найденный(Кусок(имя, "code", "ф.py", "ф.py", имя, 0, 1, имя), 1.0, 0.9) for имя in self.выдача[вопрос]]
        return рр.Итог(куски, len(куски), len(куски), 0.9)


class ПоискПоЗнакам(ПодставнойПоиск):
    """Окно в знаках: строка длиннее четырёх знаков не помещается."""

    def отобрать(self, вопрос, режим, k1, k2, порог):
        if len(вопрос) > 4:
            raise review.эм.ПереполнениеОкна("длинно")
        self.вызовы.append(вопрос)
        return рр.Итог([], 0, 0, None)


def _длинная_строка() -> bool:
    поиск = ПоискПоЗнакам({})
    review.найти([review.Участок("г.jsonl", "", 1, [], [], "абвгдежз")], {}, поиск)
    return поиск.вызовы == ["абвг", "дежз"]


def поиск_и_ответ() -> None:
    а, б = review.Участок("а.py", "", 1, ["x"], [1], "@@ а"), review.Участок("б.py", "", 1, ["y"], [1], "@@ б")
    поиск = ПодставнойПоиск({"@@ а": ["к1", "к2"], "@@ б": ["к2", "к3"]})
    найденные = review.найти([а, б], {}, поиск)
    проверить("поиск: повтор куска отброшен, порядок — первое появление",
              [н.кусок.chunk_id for н in найденные] == ["к1", "к2", "к3"])
    проверить("поиск: режим heuristic с числами дня 31 на каждый участок", поиск.вызовы == [("heuristic", 50, 5, 0.50)] * 2)
    проверить("поиск: одна строка длиннее окна делится по знакам, ищут обе половины", _длинная_строка())
    длинный = review.Участок("в.sql", "", 1, [], [], "раз\nдва\nтри\nчетыре")
    узкий = ПодставнойПоиск({"раз": ["к1"], "два": ["к2"], "три": ["к3"], "четыре": []})
    узкий.окно = 1
    проверить("поиск: запрос длиннее окна делится пополам, ищет каждая часть",
              [н.кусок.chunk_id for н in review.найти([длинный], {}, узкий)] == ["к1", "к2", "к3"])
    полный = "\n\n".join(f"{р}\nнет" for р in review.РАЗДЕЛЫ)
    проверить("ответ: три раздела на месте — недостающих нет", review.недостающие_разделы(полный) == [])
    проверить("ответ: без одного раздела — он назван",
              review.недостающие_разделы(полный.replace(review.РАЗДЕЛЫ[1], "## Прочее")) == [review.РАЗДЕЛЫ[1]])
    итог = review.оформить(полный, [], найденные, "модель", 2, {"prompt_tokens": 10, "completion_tokens": 3}, "abc1234")
    проверить("оформление: метка первой строкой, опора и строка с моделью",
              итог.startswith(review.МЕТКА + "\n") and "- `ф.py › к1`" in итог and "- ничего не найдено" in итог
              and "Вершина `abc1234`, модель `модель`, участков изменений: 2, токенов: 10 на входе, 3 на выходе." in итог)


if __name__ == "__main__":
    разбор()
    поиск_и_ответ()
    sys.exit(1 if провалов else 0)
