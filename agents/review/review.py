"""Просмотр кода: изменения между двумя ссылками git → текст с замечаниями.

Один запуск — один просмотр. Программа:

1. берёт изменения `git diff <base>...<head>` и делит их на участки;
2. на каждый участок ищет в индексе просмотра `rag/review.sqlite` куски документации
   (стратегия `structure`) и куски кода (стратегия `code`) — режим `heuristic` сервера поиска;
3. отдаёт DeepSeek изменения, полный текст изменённых файлов и найденное;
4. печатает ответ из трёх разделов и список кусков, на которые ответ опирался.

Запускает её конвейер `.github/workflows/review.yml` на каждый запрос на слияние; на своей
машине она работает так же:

    uv run --project agents/review agents/review/review.py --base main --head <ветка>

Код из рабочей копии программа не исполняет: она только читает его командами `git`. У модели
инструментов нет. Текст изменений — чужие данные, и инструкция называет их данными.

Код выхода 0 — текст записан целиком; 1 — причина одной строкой в поток ошибок, файл `--out`
не создаётся. Окружение: `DEEPSEEK_API_KEY`; `REVIEW_MODEL` — модель, по умолчанию умолчание
`myharness`; `OLLAMA_HOST` — служба с `bge-m3` для вектора запроса.
"""

