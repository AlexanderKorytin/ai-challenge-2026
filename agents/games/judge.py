"""Отбор игры местной моделью: «подходит» или «не подходит» и причина одной фразой.

Ход задания ведёт программа, а модель только судит одну игру за запрос. Причина — замер дня
31: местная модель зовёт инструменты не каждый раз, а пропущенный вызов в задании без человека
— тихая потеря недели. Ответ — по схеме JSON (`response_format` профиля `отбор-игр`), поэтому
числового порога нет: модель отвечает словом.

Агент — `Agent` `myharness` без хранилища разговора: каждая игра судится с чистого листа, и
вердикт по одной игре не влияет на следующую. Обмен пишется в журнал прогонов `myharness`.
"""

from __future__ import annotations

import json
import os
from dataclasses import dataclass
from pathlib import Path

from myharness import api, invariants, profiles
from myharness.agent import Agent

import taste
from steam_store import Игра

ПРОФИЛЬ = "отбор-игр"
# Местная рабочая модель проекта (CLAUDE.md, раздел «Стек»). Переопределяется окружением —
# модель на Маке может смениться, а код заданий от этого не зависит.
МОДЕЛЬ = os.environ.get("GAMES_LOCAL_MODEL") or "ollama/qwen3.5:9b-q4_K_M-32k"


@dataclass(frozen=True)
class Вердикт:
    подходит: bool
    причина: str


def профиль() -> profiles.Profile:
    найден, предупреждения = profiles.load(ПРОФИЛЬ)
    if найден.source is None:
        raise RuntimeError(f"профиль {ПРОФИЛЬ} не загружен: {'; '.join(предупреждения)}")
    return найден


def запрос(каталог: Path, игра: Игра, профиль_отбора: profiles.Profile) -> str:
    """Текст запроса: вкус, инварианты папки, игра. Инварианты идут здесь же, а не только
    фильтром программы: модель должна знать, почему отвергнуты похожие игры."""
    список, _ = invariants.собрать(каталог, None, профиль_отбора)
    блок = invariants.блок(список)
    жанры = ", ".join(игра.жанры) or "не указаны"
    части = [
        "## Вкус человека",
        taste.вкус(каталог) or "(вкус не записан)",
    ]
    if блок:
        части += ["", блок]
    части += [
        "",
        "## Игра",
        f"Название: {игра.имя}",
        f"Жанры: {жанры}",
        f"Выход: {игра.дата_текст or 'не объявлен'}",
        f"Оценка пользователей Steam: {игра.отзывы.текст()}",
        f"Описание: {игра.описание or 'нет'}",
    ]
    return "\n".join(части)


def разобрать(текст: str) -> Вердикт:
    """Вердикт из ответа. Не разобрался — `ValueError` с текстом ответа: задание пишет его в
    ленту, а не принимает молчание за «не подходит»."""
    try:
        данные = json.loads(текст)
    except json.JSONDecodeError:
        raise ValueError(f"ответ модели — не JSON: {текст[:300]!r}") from None
    if not isinstance(данные, dict) or not isinstance(данные.get("подходит"), bool):
        raise ValueError(f"в ответе модели нет поля «подходит»: {текст[:300]!r}")
    return Вердикт(данные["подходит"], " ".join(str(данные.get("причина") or "").split()))


async def судить(клиент: api.Clients, каталог: Path, игра: Игра) -> Вердикт:
    профиль_отбора = профиль()
    агент = Agent(ПРОФИЛЬ, профиль_отбора)
    ход = await агент.exchange(клиент, МОДЕЛЬ, запрос(каталог, игра, профиль_отбора))
    if not ход.ok:
        raise RuntimeError(f"местная модель не ответила: {ход.error or ход.status}")
    return разобрать(ход.text)
