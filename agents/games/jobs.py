"""Задания по расписанию: день — синхронизация, скидки, выход игр, предложения; неделя — сверка
вкуса, обновление календаря, пересборка RAG, будущие выпуски.

Ход ведёт программа, модель только судит одну игру за запрос. Запрет, покупку, показанную игру и
прежний отказ при том же вкусе программа отсеивает ДО модели — это гарантия.

**Десять игр** — число пользователя 2026-10-16: «во все не переиграть». День доливает открытые
предложения до 10, неделя добавляет в календарь не больше 10 новых выпусков.

**Один круг за запуск.** По каждой метке берётся первая страница выдачи, где остались годные
кандидаты; кандидаты всех меток судятся по убыванию оценки SteamDB, пока не набрано нужное.
Недобранное доберёт следующий запуск. «До конца выдачи» при отборе, отвергающем всё, гоняло бы
местную модель часами: в выдаче метки — десятки тысяч игр.

Запуск: `python jobs.py week|day`. Любой сбой — запись «сбой» в ленте, уведомление macOS и код
выхода 1: агент без человека не молчит неделю.
"""

