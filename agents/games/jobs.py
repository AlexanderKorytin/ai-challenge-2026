class УжеИдёт(RuntimeError):
    """Задание того же рода уже идёт в другом процессе (кнопка веба и служба launchd)."""


def _замок(род: str):
    """Замок файла на род задания: веб и служба — разные процессы, и без него оба считали бы
    «нужно = 10 − открытых» и довели бы открытые предложения до 20. Не блокирует: занят —
    `УжеИдёт`."""
    путь = agent_env.данные() / f"задание-{род}.lock"
    путь.parent.mkdir(parents=True, exist_ok=True)
    файл = open(путь, "w")
    try:
        fcntl.flock(файл, fcntl.LOCK_EX | fcntl.LOCK_NB)
    except BlockingIOError:
        файл.close()
        raise УжеИдёт(f"задание «{род}» уже идёт") from None
    return файл


async def запустить(род: str, каталог: Path | None = None) -> Итог:
    """Магазин Steam, учётка по ключу, местная модель, RAG. Сбой — в ленту, затем наверх."""
    import itad
    import steam_account

    каталог = каталог or Path.cwd()
    имя = "неделя" if род == "week" else "день"
    тайны = secrets_store.Тайны()
    клиент_модели = None
    замок = None
    try:
        замок = _замок(род)
        тайны = secrets_store.загрузить()
        клиент_модели = api.Clients(тайны.deepseek_ключ)
        индекс = similar.Индекс()
        async with ss.клиент() as к:
            магазин = Магазин(
                найти=lambda метка, будущие, страница: ss.найти_с_отзывами(к, метка, будущие=будущие, страница=страница),
                игра=lambda номер: ss.игра(к, номер, с_отзывами=False),
            )
            учётка = None
            if тайны.steam_ключ and тайны.steamid:
                учётка = Учётка(
                    библиотека=lambda: steam_account.библиотека(к, тайны.steam_ключ, тайны.steamid),
                    список_желаемого=lambda: steam_account.список_желаемого(к, тайны.steamid, тайны.steam_ключ),
                )
            минимум = (lambda номер: itad.минимум(к, тайны.itad_ключ, номер)) if тайны.itad_ключ else None

            async def судья(игра: ss.Игра) -> judge.Вердикт:
                try:
                    # Векторы — отдельным потоком: служба Ollama грузит модель секундами, а цикл
                    # событий веба (задание из кнопки) не должен замирать.
                    похожие = similar.блок(await asyncio.to_thread(индекс.похожие, игра))
                except Exception:  # служба векторов не ответила — отбор без RAG, а не без отбора
                    похожие = ""
                return await judge.судить(клиент_модели, каталог, игра, похожие)

            if род == "week":
                return await неделя(каталог, магазин, судья, индекс)
            return await день(каталог, магазин, судья, учётка, минимум)
    except УжеИдёт:
        raise
    except BaseException as exc:
        текст = secrets_store.скрыть(f"Задание «{имя}» упало: {type(exc).__name__}: {exc}", тайны)
        if isinstance(exc, asyncio.CancelledError):
            текст = f"Задание «{имя}» прервано: служба остановлена"
        try:
            с = games_db.открыть()
            try:
                games_db.в_ленту(с, "сбой", текст)
            finally:
                с.close()
        finally:
            await asyncio.shield(уведомить(текст))
        raise
    finally:
        if клиент_модели is not None:
            await клиент_модели.aclose()
        if замок is not None:
            замок.close()


def main(доводы: list[str]) -> int:
    if доводы not in (["week"], ["day"]):
        print("запуск: python jobs.py week|day", file=sys.stderr)
        return 2
    try:
        итог = asyncio.run(запустить(доводы[0], agent_env.данные()))
    except УжеИдёт as exc:
        # Задание из кнопки веба ещё идёт: служба не дублирует его и не считает это сбоем.
        в_ленту_итог(f"Задание по расписанию пропущено: {exc} (запущено кнопкой)")
        print(str(exc))
        return 0
    except Exception as exc:  # запись в ленте и уведомление уже сделаны
        print(f"сбой: {type(exc).__name__}", file=sys.stderr)
        return 1
    print(итог.текст("неделя" if доводы[0] == "week" else "день"))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
