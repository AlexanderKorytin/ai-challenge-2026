СВЕРКА = timedelta(days=182)

Судья = Callable[[ss.Игра], Awaitable[judge.Вердикт]]


@dataclass
class Магазин:
    """Магазин заданий. В проверках подменяется: сети у них нет. `найти` отдаёт номера страницы
    выдачи со сводкой отзывов — по ней кандидаты упорядочиваются без запроса на каждую игру."""

    найти: Callable[[int, bool, int], Awaitable[list[tuple[int, ss.Отзывы]]]]
    игра: Callable[[int], Awaitable[ss.Игра | None]]


НЕ_ИГРА = "не игра"  # отпечаток отказа для записи магазина, которая не игра (род не меняется)


@dataclass
class Учётка:
    """Учётная запись Steam: библиотека и список желаемого. Нет ключа — `None` вместо учётки."""

    библиотека: Callable[[], Awaitable[list]]
    список_желаемого: Callable[[], Awaitable[list[int]]]


# Исторический минимум цены (IsThereAnyDeal): номер Steam → объект с полями цена, валюта, когда.
Минимум = Callable[[int], Awaitable[object | None]]


@dataclass
class Итог:
    нужно: int = 0
    кандидатов: int = 0
    судимо: int = 0
    подошло: list[str] = field(default_factory=list)
    ошибки_разбора: list[str] = field(default_factory=list)
    сбои_магазина: list[str] = field(default_factory=list)
    жалобы_критериев: list[str] = field(default_factory=list)

    def текст(self, имя: str) -> str:
        if self.нужно <= 0:
            return f"{имя}: открытых предложений уже {НУЖНО}, новых не искал"
        части = [
            f"{имя}: нужно {self.нужно}, кандидатов {self.кандидатов}, судимо {self.судимо}, "
            f"подошло {len(self.подошло)}"
        ]
        if self.подошло:
            части.append("подошли: " + ", ".join(self.подошло))
        if self.ошибки_разбора:
            части.append(f"ответ модели не разобран {len(self.ошибки_разбора)} раз: {self.ошибки_разбора[0]}")
        if self.сбои_магазина:
            части.append(f"магазин не отдал {len(self.сбои_магазина)} игр: {self.сбои_магазина[0]}")
        if self.жалобы_критериев:
            части.append("строки «Критериев» не того вида пропущены: " + "; ".join(self.жалобы_критериев))
        return ". ".join(части)


def _показать(текст: str) -> None:
    строка = текст.replace("\\", "\\\\").replace('"', '\\"')
    try:
        subprocess.run(
            ["osascript", "-e", f'display notification "{строка}" with title "Игровой агент"'],
            check=False, capture_output=True, timeout=10,
        )
    except (OSError, subprocess.SubprocessError):
        pass


async def уведомить(текст: str) -> None:
    """Системное уведомление macOS отдельным потоком: `osascript` не держит цикл событий веба.
    Сбой показа не роняет задание — запись в ленте уже есть."""
    await asyncio.to_thread(_показать, текст)


def _в_ленту(с, род: str, текст: str) -> None:
    """Строка ленты с ключами, вычищенными из текста: текст ошибки чужой библиотеки может
    нести адрес запроса, а в адресе — ключ."""
    try:
        текст = secrets_store.скрыть(текст, secrets_store.загрузить())
    except Exception:  # noqa: BLE001 — не прочли тайны: прятать нечего, ключа у процесса нет
        pass
    games_db.в_ленту(с, род, текст)


def _с_прежними_отзывами(с, игра: ss.Игра, сводка: ss.Отзывы | None = None) -> ss.Игра:
    """Отзывы берутся из выдачи поиска, а не отдельным запросом. Игра пришла не из поиска
    (скидки, календарь) — сводка остаётся прежней из хранилища, а не стирается пустой."""
    if сводка is not None and сводка.всего > 0:
        return replace(игра, отзывы=сводка)
    if игра.отзывы.всего > 0:
        return игра
    запись = games_db.игра(с, игра.номер)
    if запись and запись.get("отзывы_всего"):
        return replace(игра, отзывы=ss.Отзывы(
            запись.get("отзывы_сводка") or "", int(запись.get("отзывы_положительных") or 0), int(запись["отзывы_всего"])
        ))
    return игра


def _сумма(копейки: int, валюта: str) -> str:
    # Регион `cc=ru` даёт рубли; другая валюта подписывается своим кодом, а не «руб.».
    return f"{копейки / 100:.0f} руб." if валюта in ("RUB", "") else f"{копейки / 100:.2f} {валюта}"


def _игра_из_записи(запись: dict) -> ss.Игра:
    return ss.Игра(
        номер=int(запись["номер"]), имя=запись.get("имя") or str(запись["номер"]),
        описание=запись.get("описание") or "", жанры=tuple(запись.get("жанры") or ()),
    )


