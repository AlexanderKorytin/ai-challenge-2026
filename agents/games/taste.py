"""Вкус человека: разделы карточки папки агента и запреты на игры.

Своего хранилища у вкуса нет. Он живёт в карточке папки `myharness` (`project_card`): папка —
каталог агента, и знание о вкусе верно ровно для него. Так у вкуса сразу есть всё, что карточка
уже умеет: запись под замком, запасная копия при замене и «Ограничения», которые `myharness`
сам отправляет в каждый запрос блоком «Инварианты».

Кто что пишет:

- четыре раздела вкуса (`РАЗДЕЛЫ`) пишет модель инструментом `save_taste` — целиком, заменой
  карточки: опрос о вкусе проводят заново, и старые строки, которых человек уже не подтверждал,
  оставаться не должны;
- раздел «Ограничения» пишет только человек — кнопкой «минус» под предложенной игрой. Строка
  запрета становится инвариантом `П…`, и модель не может ни завести её, ни снять.

Модуль ходит только на диск, и только через `project_card`. В сеть не ходит.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass
from pathlib import Path

from myharness import memory, project_card
from myharness.agent import Инструменты
from steam_store import Игра, Метка

РАЗДЕЛЫ = ("Любимые игры", "Общее", "Критерии", "Нежелательное")
РАЗДЕЛ_КРИТЕРИЕВ = "Критерии"

ИСТОЧНИК_МОДЕЛИ = "модель"
ИСТОЧНИК_ЧЕЛОВЕКА = "человек"

СОХРАНИТЬ_ВКУС = "save_taste"

ВЕС_МИН = 1
ВЕС_МАКС = 5

# Вид строки «Критериев»: `<имя> (<номер>) — <вес>`. Тире любое из трёх: модель и человек
# пишут их вперемешку, и отвергать строку за дефис вместо тире — придирка к форме, а не к смыслу.
# Имя берётся нежадно до ПОСЛЕДНИХ скобок с номером: в имени метки скобки возможны.
_КРИТЕРИЙ = re.compile(r"^\s*(?P<имя>.+?)\s*\(\s*(?P<номер>\d+)\s*\)\s*[—–-]\s*(?P<вес>\d+)\s*$")

ВИД_КРИТЕРИЯ = "<имя метки> (<номер метки>) — <вес 1…5>, например «Ролевая игра (122) — 3»"

# Вид строки запрета. Номер — в последних скобках строки: в имени игры скобки бывают
# («Half-Life 2 (2004)»), а номер игры в магазине всегда последний.
ЗАПРЕТ_НАЧАЛО = "Не предлагать:"
_ЗАПРЕТ = re.compile(r"^\s*Не предлагать:\s*(?P<имя>.*?)\s*\(\s*(?P<номер>\d+)\s*\)\s*$", re.IGNORECASE)


@dataclass(frozen=True)
class Критерий:
    метка: int
    имя: str
    вес: int


def _разобрать_критерий(строка: str) -> Критерий | None:
    """Строка «Критериев» → критерий; строка не того вида или вес вне 1…5 — `None`."""
    найдено = _КРИТЕРИЙ.match(строка)
    if найдено is None:
        return None
    вес = int(найдено["вес"])
    if not ВЕС_МИН <= вес <= ВЕС_МАКС:
        return None
    return Критерий(int(найдено["номер"]), найдено["имя"], вес)


def _карточка(каталог: Path) -> project_card.Карточка | None:
    # Жалобы на нечитаемую карточку здесь не нужны: их показывает `myharness` при каждом
    # запросе блоком инвариантов, а для вкуса нечитаемая карточка равна отсутствующей.
    карточка, _жалобы = project_card.load(каталог)
    return карточка


def критерии(каталог: Path) -> tuple[list[Критерий], list[str]]:
    """Критерии вкуса и жалобы на строки не того вида. Карточки нет — оба списка пусты.

    Плохая строка не ломает остальные: её мог вписать руками человек, и подбор по годным
    строкам лучше, чем никакого подбора."""
    карточка = _карточка(каталог)
    if карточка is None:
        return [], []
    годные: list[Критерий] = []
    жалобы: list[str] = []
    for строка in карточка.пункты(РАЗДЕЛ_КРИТЕРИЕВ):
        критерий = _разобрать_критерий(строка)
        if критерий is None:
            жалобы.append(f"строка «{строка}» раздела «{РАЗДЕЛ_КРИТЕРИЕВ}» не того вида: {ВИД_КРИТЕРИЯ}")
        else:
            годные.append(критерий)
    return годные, жалобы


def номер_запрета(строка: str) -> int | None:
    найдено = _ЗАПРЕТ.match(строка)
    return int(найдено["номер"]) if найдено is not None else None


def запреты(каталог: Path) -> set[int]:
    """Номера игр, которые человек запретил предлагать.

    Строку «Ограничений» другого вида человек мог написать сам («без хорроров»). Она остаётся
    инвариантом для модели, но номера игры в ней нет, и ошибкой она не считается."""
    карточка = _карточка(каталог)
    if карточка is None:
        return set()
    номера = (номер_запрета(строка) for строка in карточка.пункты(project_card.РАЗДЕЛ_ОГРАНИЧЕНИЙ))
    return {номер for номер in номера if номер is not None}


def опрос_пройден(каталог: Path) -> bool:
    """Опрос о вкусе пройден, если в карточке есть непустой раздел «Критерии»."""
    карточка = _карточка(каталог)
    return карточка is not None and bool(карточка.пункты(РАЗДЕЛ_КРИТЕРИЕВ))


def вкус(каталог: Path) -> str:
    """Текст четырёх разделов вкуса для запроса модели. Карточки нет — пустая строка.

    «Ограничений» здесь нет намеренно: их уже несёт блок «Инварианты», и второй экземпляр тех же
    строк в запросе был бы вторым каналом рядом с работающим."""
    карточка = _карточка(каталог)
    if карточка is None:
        return ""
    части: list[str] = []
    for раздел in РАЗДЕЛЫ:
        строки = карточка.пункты(раздел)
        if строки:
            части.append(f"## {раздел}\n" + "\n".join(f"- {строка}" for строка in строки))
    return "\n\n".join(части)


def строка_запрета(игра: Игра) -> str:
    return f"{ЗАПРЕТ_НАЧАЛО} {' '.join(игра.имя.split())} ({игра.номер})"


def запретить(каталог: Path, игра: Игра) -> tuple[bool, str]:
    """Запрет человека на игру: строка в «Ограничения». Повтор того же запрета — не ошибка."""
    строка = строка_запрета(игра)
    карточка = _карточка(каталог)
    if карточка is None:
        новая, итог = project_card.create(
            каталог, {project_card.РАЗДЕЛ_ОГРАНИЧЕНИЙ: [строка]}, источник=ИСТОЧНИК_ЧЕЛОВЕКА
        )
        return (True, строка) if новая is not None else (False, итог)
    готово, итог = project_card.add_line(
        карточка, project_card.РАЗДЕЛ_ОГРАНИЧЕНИЙ, строка, источник=ИСТОЧНИК_ЧЕЛОВЕКА
    )
    if not готово and итог == memory.УЖЕ_ЗАПИСАНО:
        return True, строка
    return готово, итог


def снять_запрет(каталог: Path, номер: int) -> tuple[bool, str]:
    """Снимает запрет на игру с этим номером. Запрета нет — `(False, текст)`.

    Снимаются ВСЕ строки с этим номером: одна игра могла попасть в запреты дважды под разными
    именами (магазин переименовал её между нажатиями), и снять запрет наполовину значило бы
    оставить его в силе."""
    карточка = _карточка(каталог)
    if карточка is None:
        return False, f"запрета на игру {номер} нет — карточки ещё нет"
    места = [
        место
        for место, строка in enumerate(карточка.пункты(project_card.РАЗДЕЛ_ОГРАНИЧЕНИЙ), 1)
        if номер_запрета(строка) == номер
    ]
    if not места:
        return False, f"запрета на игру {номер} нет"
    убранные: list[str] = []
    # С конца: `remove_line` берёт номер строки, каким он показан человеку (с единицы), и
    # снятие нижней строки не сдвигает номера верхних.
    for место in reversed(места):
        готово, итог = project_card.remove_line(
            карточка, project_card.РАЗДЕЛ_ОГРАНИЧЕНИЙ, место, источник=ИСТОЧНИК_ЧЕЛОВЕКА
        )
        if not готово:
            return False, итог
        убранные.append(итог)
    return True, "; ".join(reversed(убранные))


def _схема() -> dict:
    строки = {"type": "array", "items": {"type": "string"}}
    return {
        "type": "function",
        "function": {
            "name": СОХРАНИТЬ_ВКУС,
            "description": (
                "Записать вкус человека в карточку целиком, когда опрос о вкусе закончен. "
                "Прежний вкус заменяется. Запреты на игры сюда не входят: их ставит только человек."
            ),
            "parameters": {
                "type": "object",
                "properties": {
                    "разделы": {
                        "type": "object",
                        "properties": {
                            "Любимые игры": {**строки, "description": "Игры, которые человек назвал любимыми, по строке на игру."},
                            "Общее": {**строки, "description": "Что человек любит в играх, короткими строками."},
                            "Критерии": {
                                **строки,
                                "description": f"Метки магазина с весом, по строке на метку: {ВИД_КРИТЕРИЯ}. "
                                "Номер метки — только из списка меток магазина.",
                            },
                            "Нежелательное": {**строки, "description": "Что человеку в играх не нравится, короткими строками."},
                        },
                        "required": list(РАЗДЕЛЫ),
                        "additionalProperties": False,
                    },
                },
                "required": ["разделы"],
            },
        },
    }


def _проверить(доводы: str, метки: dict[int, Метка]) -> tuple[dict[str, list[str]] | None, str]:
    """Доводы `save_taste` → разделы для записи либо текст отказа модели."""
    try:
        разобранные = json.loads(доводы or "{}")
    except json.JSONDecodeError as exc:
        return None, f"доводы не читаются как JSON: {exc}"
    разделы = разобранные.get("разделы") if isinstance(разобранные, dict) else None
    if not isinstance(разделы, dict):
        return None, "нужен довод «разделы» — объект с четырьмя разделами: " + ", ".join(РАЗДЕЛЫ)
    # Берём только четыре раздела вкуса. Ключ «Ограничения» и любой другой, присланный моделью,
    # отбрасывается: замена карточки чужим разделом стёрла бы написанное человеком.
    отобранные: dict[str, list[str]] = {}
    for раздел in РАЗДЕЛЫ:
        строки = разделы.get(раздел)
        if not isinstance(строки, list) or not all(isinstance(с, str) for с in строки):
            # Раздел обязателен: запись заменяет карточку, и пропущенный раздел исчез бы молча.
            return None, f"раздел «{раздел}» обязателен и должен быть списком строк (пустой список — если писать нечего)"
        отобранные[раздел] = [" ".join(с.split()) for с in строки if с.strip()]

    плохие: list[str] = []
    увиденные: set[int] = set()
    for строка in отобранные[РАЗДЕЛ_КРИТЕРИЕВ]:
        критерий = _разобрать_критерий(строка)
        if критерий is None:
            плохие.append(f"«{строка}» — не того вида или вес вне {ВЕС_МИН}…{ВЕС_МАКС}")
        elif критерий.метка not in метки:
            плохие.append(f"«{строка}» — метки {критерий.метка} нет в списке меток магазина")
        elif критерий.метка in увиденные:
            плохие.append(f"«{строка}» — метка {критерий.метка} уже названа другой строкой")
        else:
            увиденные.add(критерий.метка)
    if плохие:
        return None, (
            "вкус не записан, карточка не тронута. Плохие строки «Критериев»:\n"
            + "\n".join(f"- {п}" for п in плохие)
            + f"\nВид строки: {ВИД_КРИТЕРИЯ}. Исправь строки и вызови {СОХРАНИТЬ_ВКУС} снова."
        )
    if not увиденные:
        # Без критериев подбирать не по чему, а опрос считался бы непройденным: модель думала бы,
        # что записала вкус, а человек получал бы опрос заново.
        return None, f"вкус не записан: в «Критериях» нет ни одной строки. Вид строки: {ВИД_КРИТЕРИЯ}"
    return отобранные, ""


def набор(каталог: Path, метки: list[Метка]) -> Инструменты:
    """Инструмент `save_taste` для обмена опроса о вкусе.

    Каталог и метки запоминаются здесь: вызов посреди обмена пишет в карточку ЭТОЙ папки и
    сверяет номера с ЭТИМ списком меток."""
    по_номеру = {метка.номер: метка for метка in метки}

    async def исполнить(имя: str, доводы: str) -> str:
        if имя != СОХРАНИТЬ_ВКУС:
            return f"нет такого инструмента: {имя}"
        try:
            разделы, отказ = _проверить(доводы, по_номеру)
            if разделы is None:
                return отказ
            карточка, итог = project_card.create(каталог, разделы, источник=ИСТОЧНИК_МОДЕЛИ)
            if карточка is None:
                return f"вкус не записан: {итог}"
            return f"вкус записан: {len(разделы[РАЗДЕЛ_КРИТЕРИЕВ])} критериев"
        except Exception as exc:  # noqa: BLE001 — модель должна узнать о сбое текстом, а не потерять обмен
            return f"вкус не записан: {type(exc).__name__}: {exc}"

    return Инструменты(схемы=[_схема()], исполнить=исполнить)
