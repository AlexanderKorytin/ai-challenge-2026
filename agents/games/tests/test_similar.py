"""RAG истории на подменённых векторах: ближайшие по косинусу и дописанное видно сразу."""

import numpy as np

import similar
from steam_store import Игра

ОСИ = {"хоррор": 0, "ферма": 1, "тактика": 2}


def считать(тексты):
    # Вектор — по словам-осям: проверка смотрит на порядок, а не на модель.
    return np.array([[float(сл in т.lower()) for сл in ОСИ] for т in тексты], dtype=np.float32) + 0.01


def test_похожие_и_дописать(tmp_path):
    индекс = similar.Индекс(считать, tmp_path / "s.sqlite")
    индекс.пересобрать([
        similar.Документ(1, "Outlast", "Outlast хоррор", "минус: скучно"),
        similar.Документ(2, "Stardew", "Stardew ферма", "120 ч"),
    ])
    кандидат = Игра(номер=9, имя="Phasmophobia", описание="хоррор с друзьями")
    первый = индекс.похожие(кандидат)[0][1]
    assert первый.имя == "Outlast" and первый.отметка == "минус: скучно"
    индекс.дописать(similar.Документ(3, "Dead Space", "Dead Space хоррор хоррор", "плюс"))
    assert индекс.размер() == 3
    assert "Outlast — минус: скучно" in similar.блок(индекс.похожие(кандидат))


def test_сама_игра_не_похожа_на_себя_и_пустой_индекс(tmp_path):
    индекс = similar.Индекс(считать, tmp_path / "s.sqlite")
    assert индекс.похожие(Игра(номер=1, имя="x")) == [] and similar.блок([]) == ""
    индекс.дописать(similar.Документ(1, "Outlast", "хоррор", "минус"))
    assert индекс.похожие(Игра(номер=1, имя="Outlast", описание="хоррор")) == []


