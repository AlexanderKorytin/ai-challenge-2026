"""Проверки модуля `taste`: без сети и без ключа, всё на диске во временном каталоге."""

from __future__ import annotations

import asyncio
import json
from pathlib import Path

from myharness import invariants, project_card
from myharness.profiles import builtin_default
from steam_store import Игра, Метка

import taste

МЕТКИ = [Метка(122, "Ролевая игра"), Метка(1662, "Выживание")]

ГОДНЫЕ = {
    "Любимые игры": ["Baldur's Gate 3"],
    "Общее": ["любит долгие сюжетные игры"],
    "Критерии": ["Ролевая игра (122) — 3", "Выживание (1662) - 5"],
    "Нежелательное": ["соревновательные игры по сети"],
}


def сохранить(каталог: Path, разделы: dict, метки: list[Метка] = МЕТКИ) -> str:
    набор = taste.набор(каталог, метки)
    return asyncio.run(набор.исполнить(taste.СОХРАНИТЬ_ВКУС, json.dumps({"разделы": разделы}, ensure_ascii=False)))


def файл_карточки(каталог: Path) -> Path:
    return project_card.card_path(каталог)


def test_схема_в_формате_myharness(каталоги: Path) -> None:
    набор = taste.набор(каталоги, МЕТКИ)
    функция = набор.схемы[0]["function"]
    assert набор.схемы[0]["type"] == "function"
    assert функция["name"] == "save_taste"
    assert функция["parameters"]["properties"]["разделы"]["required"] == list(taste.РАЗДЕЛЫ)


def test_годный_вкус_записан(каталоги: Path) -> None:
    assert taste.опрос_пройден(каталоги) is False
    assert taste.вкус(каталоги) == ""
    ответ = сохранить(каталоги, ГОДНЫЕ)
    assert ответ == "вкус записан: 2 критериев"
    список, жалобы = taste.критерии(каталоги)
    assert taste.Критерий(122, "Ролевая игра", 3) in список
    assert taste.Критерий(1662, "Выживание", 5) in список
    assert жалобы == []
    assert taste.опрос_пройден(каталоги) is True
    текст = taste.вкус(каталоги)
    for раздел in taste.РАЗДЕЛЫ:
        assert f"## {раздел}" in текст
    # Карточка лежит в уведённом каталоге состояния, а не в домашнем.
    assert str(файл_карточки(каталоги)).startswith(str(каталоги.parent / "state"))


def test_чужая_метка_отвергнута_карточка_не_тронута(каталоги: Path) -> None:
    сохранить(каталоги, ГОДНЫЕ)
    до = файл_карточки(каталоги).read_text(encoding="utf-8")
    плохие = {**ГОДНЫЕ, "Критерии": ["Выживание (1662) — 2", "Стратегия (9) — 4"]}
    ответ = сохранить(каталоги, плохие)
    assert "не записан" in ответ
    assert "Стратегия (9) — 4" in ответ
    # Годная строка в перечень плохих не попадает.
    assert "Выживание (1662) — 2" not in ответ
    assert файл_карточки(каталоги).read_text(encoding="utf-8") == до
    # Парная: тот же набор, номер метки из списка магазина — записано.
    годные = {**ГОДНЫЕ, "Критерии": ["Ролевая игра (122) — 3", "Стратегия (9) — 4"]}
    ответ = сохранить(каталоги, годные, [*МЕТКИ, Метка(9, "Стратегия")])
    assert ответ == "вкус записан: 2 критериев"
    assert taste.Критерий(9, "Стратегия", 4) in taste.критерии(каталоги)[0]


def test_вес_вне_пределов_отвергнут(каталоги: Path) -> None:
    ответ = сохранить(каталоги, {**ГОДНЫЕ, "Критерии": ["Ролевая игра (122) — 7"]})
    assert "не записан" in ответ and "Ролевая игра (122) — 7" in ответ
    assert not файл_карточки(каталоги).exists()


def test_строка_без_номера_в_жалобах(каталоги: Path) -> None:
    сохранить(каталоги, ГОДНЫЕ)
    карточка, _ = project_card.load(каталоги)
    готово, _ = project_card.add_line(карточка, "Критерии", "Ролевая игра — 3")
    assert готово
    список, жалобы = taste.критерии(каталоги)
    assert len(список) == 2
    assert all(к.имя != "Ролевая игра — 3" for к in список)
    assert len(жалобы) == 1 and "Ролевая игра — 3" in жалобы[0]


def test_запрет_становится_инвариантом(каталоги: Path) -> None:
    игра = Игра(1086940, "Baldur's Gate 3")
    готово, строка = taste.запретить(каталоги, игра)
    assert готово and строка == "Не предлагать: «Baldur's Gate 3» (1086940)"
    assert taste.запреты(каталоги) == {1086940}
    # Повтор — не ошибка, вторая строка не появляется.
    assert taste.запретить(каталоги, игра)[0] is True
    список, жалобы = invariants.собрать(каталоги, None, builtin_default())
    assert жалобы == []
    assert [(и.номер, и.текст) for и in список] == [("П1", строка)]


def test_запрет_человека_переживает_save_taste(каталоги: Path) -> None:
    игра = Игра(1086940, "Baldur's Gate 3")
    taste.запретить(каталоги, игра)
    ответ = сохранить(каталоги, {**ГОДНЫЕ, "Ограничения": ["что-то от модели"]})
    assert ответ == "вкус записан: 2 критериев"
    карточка, _ = project_card.load(каталоги)
    assert карточка.пункты(project_card.РАЗДЕЛ_ОГРАНИЧЕНИЙ) == ["Не предлагать: «Baldur's Gate 3» (1086940)"]
    assert taste.запреты(каталоги) == {1086940}
    assert "что-то от модели" not in файл_карточки(каталоги).read_text(encoding="utf-8")


def test_снять_запрет(каталоги: Path) -> None:
    taste.запретить(каталоги, Игра(10, "Первая"))
    taste.запретить(каталоги, Игра(20, "Вторая (2004)"))
    карточка, _ = project_card.load(каталоги)
    project_card.add_line(карточка, project_card.РАЗДЕЛ_ОГРАНИЧЕНИЙ, "без хорроров")
    assert taste.запреты(каталоги) == {10, 20}
    готово, _ = taste.снять_запрет(каталоги, 20)
    assert готово
    assert taste.запреты(каталоги) == {10}
    assert taste.снять_запрет(каталоги, 10)[0] is True
    assert taste.запреты(каталоги) == set()
    # Своя строка человека не тронута.
    карточка, _ = project_card.load(каталоги)
    assert карточка.пункты(project_card.РАЗДЕЛ_ОГРАНИЧЕНИЙ) == ["без хорроров"]
    готово, текст = taste.снять_запрет(каталоги, 999)
    assert готово is False and "999" in текст


def test_снять_запрет_без_карточки(каталоги: Path) -> None:
    assert taste.снять_запрет(каталоги, 1)[0] is False


def test_плохие_доводы_текстом(каталоги: Path) -> None:
    набор = taste.набор(каталоги, МЕТКИ)
    ответ = asyncio.run(набор.исполнить("save_taste", "{не json"))
    assert "JSON" in ответ
    без_раздела = {к: в for к, в in ГОДНЫЕ.items() if к != "Общее"}
    assert "«Общее» обязателен" in сохранить(каталоги, без_раздела)
    assert not файл_карточки(каталоги).exists()
