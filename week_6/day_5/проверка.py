def по_ssh(узел: str, команда: str, ввод: str | None = None) -> subprocess.CompletedProcess:
    """Команда на узле по ssh. Код 255 — ssh не установил соединение (на пути от Мака так бывает:
    два прогона 2026-10-09 упали на первом вызове); такой вызов повторяется до трёх раз, причина
    печатается. Команды замера только читают, повтор их не искажает."""
    for попытка in (1, 2, 3):
        итог = subprocess.run(["ssh", "-o", "ConnectTimeout=20", узел, команда], input=ввод, capture_output=True, text=True)
        if итог.returncode != 255:
            return итог
        print(f"  ssh {узел}: соединение не установлено, попытка {попытка}: {итог.stderr.strip()[-120:]}", flush=True)
        time.sleep(3)
    return итог


def токен(клиент: str) -> str:
    вывод = по_ssh("challenge-mcp", f"grep ^LLM_TOKEN_{клиент}= /opt/challenge/llm-gateway.env | cut -d= -f2")
    значение = вывод.stdout.strip()
    if not значение:
        raise SystemExit(f"на сервере нет токена клиента {клиент}")
    return значение


def запрос(путь: str, тело: dict | None, ключ: str | None, корень: str = АДРЕС) -> dict:
    """Один запрос. Возвращает код, заголовки, разобранное тело и время в секундах."""
    заголовки = {"Content-Type": "application/json"}
    if ключ:
        заголовки["Authorization"] = f"Bearer {ключ}"
    данные = json.dumps(тело).encode() if тело is not None else None
    начало = time.monotonic()
    try:
        with urllib.request.urlopen(urllib.request.Request(корень + путь, данные, заголовки)) as ответ:
            код, шапка, сырое = ответ.status, dict(ответ.headers), ответ.read()
    except urllib.error.HTTPError as отказ:
        код, шапка, сырое = отказ.code, dict(отказ.headers), отказ.read()
    except OSError as сбой:
        return {"код": 0, "шапка": {}, "тело": {}, "с": time.monotonic() - начало, "сбой": str(сбой)}
    try:
        разобранное = json.loads(сырое)
    except ValueError:
        разобранное = {}
    return {"код": код, "шапка": шапка, "тело": разобранное, "с": time.monotonic() - начало}


def упорный(путь: str, тело: dict | None, ключ: str | None) -> dict:
    """Запрос раздела «Доступ»: сбой соединения повторяется один раз. Раздел проверяет права,
    а не сеть; сбои сети считает раздел «Стабильность»."""
    итог = запрос(путь, тело, ключ)
    return запрос(путь, тело, ключ) if итог["код"] == 0 else итог


def сейчас() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def время_шлюза(с: str, по: str) -> str:
    """Длительность чатов, которые шлюз отдал до конца (код 200, поток не оборван), по его
    журналу за отрезок: число, медиана и максимум, с.
    Так время работы службы отделяется от времени пути между клиентом и сервером."""
    программа = (
        "import json,statistics,sys\n"
        "r=[json.loads(l) for l in open('/var/lib/private/llm-gateway/journal.jsonl')]\n"
        f"m=[x['мс']/1000 for x in r if '{с}'<=x['время']<='{по}' and x['путь']=='/v1/chat/completions' and x['код']==200 and x.get('оборван') is False]\n"
        "print(f'{len(m)} {statistics.median(m):.1f} {max(m):.1f}' if m else '0 0 0')\n"
    )
    вывод = по_ssh("challenge-mcp", "python3 -", программа)
    try:
        число, медиана, максимум = вывод.stdout.split()
    except ValueError:
        return "журнал шлюза не прочитан"
    return f"{число} запросов, медиана {медиана} с, максимум {максимум} с"


def залпом(тела: list[dict], ключи_по_кругу: list[str]) -> tuple[list[dict], float]:
    """Все запросы уходят одновременно, каждый в своём потоке."""
    итоги: list[dict | None] = [None] * len(тела)

    def один(номер: int) -> None:
        итоги[номер] = запрос("/v1/chat/completions", тела[номер], ключи_по_кругу[номер % len(ключи_по_кругу)])

    начало = time.monotonic()
    потоки = [threading.Thread(target=один, args=(номер,)) for номер in range(len(тела))]
    for поток in потоки:
        поток.start()
    for поток in потоки:
        поток.join()
    return [итог for итог in итоги if итог is not None], time.monotonic() - начало


def чат(текст: str, предел: int = 200) -> dict:
    return {
        "model": МОДЕЛЬ,
        "reasoning_effort": "none",
        "max_tokens": предел,
        "messages": [{"role": "user", "content": текст}],
    }


def ответ_модели(итог: dict) -> str:
    try:
        return итог["тело"]["choices"][0]["message"]["content"].strip().replace("\n", " ")
    except (KeyError, IndexError, TypeError):
        return ""


def признак(итог: dict) -> str:
    ошибка = итог["тело"].get("error") if isinstance(итог["тело"], dict) else None
    return ошибка.get("code", "") if isinstance(ошибка, dict) else str(ошибка or "")


def сбои(итоги: list[dict]) -> str:
    """Запросы без кода ответа: соединение не установилось либо оборвалось."""
    причины = [итог.get("сбой", "") for итог in итоги if итог["код"] == 0]
    if not причины:
        return "Сбоев соединения нет."
    return f"Сбоев соединения — {len(причины)} (в таблице код 0): " + "; ".join(sorted(set(причины))) + "."


def сводка(итоги: list[dict], общее: float) -> str:
    успешные = [итог for итог in итоги if итог["код"] == 200]
    времена = [итог["с"] for итог in успешные]
    выход = sum(итог["тело"].get("usage", {}).get("completion_tokens", 0) for итог in успешные)
    коды = ", ".join(f"{код}: {[итог['код'] for итог in итоги].count(код)}" for код in sorted({итог["код"] for итог in итоги}))
    if not времена:
        return f"| {len(итоги)} | 0 | — | — | — | — | {коды} |"
    return (
        f"| {len(итоги)} | {len(успешные)} | {statistics.median(времена):.1f} | {min(времена):.1f} | "
        f"{max(времена):.1f} | {выход / общее:.1f} | {коды} |"
    )


