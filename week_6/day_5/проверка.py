def main() -> int:
    доводы = argparse.ArgumentParser(description="Замер условия дня 30")
    доводы.add_argument("--с", dest="узел", default="challenge", help="имя ssh второго узла сети")
    # Умолчания малы намеренно: условие просит «несколько запросов», сервер учебный (1 ядро).
    доводы.add_argument("--подряд", type=int, default=5)
    доводы.add_argument("--разом", type=int, default=2)
    доводы.add_argument("--итог", default="проверка.md", help="файл итога; «-» — только на экран")
    выбор = доводы.parse_args()
    ключи = {клиент: токен(клиент) for клиент in ("mac", "challenge")}
    строки = [
        "# День 30. Проверка службы",
        "",
        f"Прогон `проверка.py` {datetime.now():%Y-%m-%d %H:%M}: подряд {выбор.подряд}, одновременно {выбор.разом}.",
        "",
    ]
    доступ(ключи, выбор.узел, строки)
    стабильность(ключи, выбор.подряд, выбор.разом, строки)
    ограничения(ключи, строки)
    текст = "\n".join(строки) + "\n"
    # Страховка: токены в итог не попадают ни при каком сбое разбора.
    for значение in ключи.values():
        текст = текст.replace(значение, "<токен>")
    if выбор.итог == "-":
        print(текст)
    else:
        with open(выбор.итог, "w", encoding="utf-8") as файл:
            файл.write(текст)
        print(f"итог записан в {выбор.итог}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
