"""Книга правил Betrayal at Baldur's Gate: PDF издателя → Markdown → индекс поиска.

Запуск из папки дня: `uv run --with pymupdf правила.py`. Текст правил защищён авторским правом
и в git не идёт: PDF, Markdown и индекс лежат в `test/правила/` (см. `.gitignore`).

Вёрстка книги — две колонки с врезками в рамках, и порядок текста в файле PDF с порядком чтения
не совпадает. Программа восстанавливает его по геометрии:

- основной текст страницы идёт левой колонкой сверху вниз, затем правой;
- врезка — блоки внутри светлой залитой рамки. Она откладывается и встаёт своим разделом перед
  первым заголовком основного текста на следующих страницах: так она не рвёт абзац, который
  обтекает, и стоит после раздела своей страницы;
- пункт списка свёрстан двумя блоками (первая строка и продолжение с отступом) — они склеиваются;
- абзац, продолженный в другой колонке или на другой странице со строчной буквы, склеивается;
- подписи картинок и таблица номеров сценариев набраны кеглем меньше 8,4 — они выбрасываются.

Заголовки берутся по шрифту: `TiamatCondensedSC` от 16 — раздел (`##`); `TiamatText-Bold` 12 и
10, `CronosPro-BoldDisp` 10 — подраздел (`###`). В разделе `GLOSSARY` подразделом становится
каждый термин: иначе словарь шёл бы одним куском в 13 тысяч знаков. Оглавление выбрасывается:
это перечень заголовков, и поиск находил бы его по любому вопросу. По этим заголовкам режет
нарезка `structure` проекта `rag`.
"""

from __future__ import annotations

import hashlib
import re
import subprocess
import sys
import urllib.request
from dataclasses import dataclass, field
from pathlib import Path

import pymupdf

АДРЕС = "https://media.wizards.com/2017/avalon_hill/BaBG_Rulebook.pdf"
ОТПЕЧАТОК = "0a08615fa1132a71bf28879ec693e59b99b0a75e9774471db54bc2a98e16a882"
ПАПКА = Path(__file__).resolve().parent
КАТАЛОГ = ПАПКА / "test" / "правила"
PDF = КАТАЛОГ / "BaBG_Rulebook.pdf"
MARKDOWN = КАТАЛОГ / "md" / "rulebook.md"
ИНДЕКС = КАТАЛОГ / "правила.sqlite"
RAG = Path.home() / "challenge" / "main" / "rag"
# Страницы без правил: 1 — адреса службы поддержки, 2 — обложка, 22 — авторы, 23–24 — пустые заметки.
ЛИШНИЕ_СТРАНИЦЫ = {1, 2, 22, 23, 24}
КОЛОНТИТУЛ = re.compile(r"^RULES \| \d+$|^\d+ \| RULES$")
ОГЛАВЛЕНИЕ = "TABLE OF CONTENTS"
СЛОВАРЬ = "GLOSSARY"
ТЕРМИН = re.compile(r"^([^:]{2,40}):")
МЕТКА_ПУНКТА = re.compile(r"^w\s?w\s*(?=[A-Z])")
НАИМЕНЬШИЙ_КЕГЛЬ = 8.4
ОТСТУП_ПРОДОЛЖЕНИЯ = 5  # продолжение пункта списка свёрстано правее его первой строки на 9 единиц


def скачать() -> None:
    if not PDF.is_file():
        PDF.parent.mkdir(parents=True, exist_ok=True)
        запрос = urllib.request.Request(АДРЕС, headers={"User-Agent": "Mozilla/5.0"})
        with urllib.request.urlopen(запрос) as ответ:
            PDF.write_bytes(ответ.read())
    отпечаток = hashlib.sha256(PDF.read_bytes()).hexdigest()
    if отпечаток != ОТПЕЧАТОК:
        sys.exit(f"правила: отпечаток {PDF.name} — {отпечаток}, ожидался {ОТПЕЧАТОК}")


def уровень(размер: float, шрифт: str) -> int:
    """2 — раздел, 3 — подраздел, 0 — обычный текст."""
    if шрифт.startswith("TiamatCondensedSC") and размер >= 16:
        return 2
    if шрифт.startswith("TiamatText-Bold") and round(размер, 1) in (12.0, 10.0):
        return 3
    if шрифт.startswith("CronosPro-BoldDisp") and round(размер, 1) == 10.0:
        return 3
    return 0


@dataclass
class Часть:
    вид: str  # "заголовок" | "абзац" | "пункт"
    текст: str
    уровень: int = 0
    x0: float = 0.0
    строк: int = 1


@dataclass
class Поток:
    """Последовательность частей одного русла текста: основного либо одной врезки."""
    части: list[Часть] = field(default_factory=list)

    def заголовок(self, ур: int, текст: str) -> None:
        последняя = self.части[-1] if self.части else None
        # Заголовок в две строки вёрстки — один заголовок.
        if последняя and последняя.вид == "заголовок" and последняя.уровень == ур and последняя.строк < 0:
            последняя.текст += " " + текст
        else:
            self.части.append(Часть("заголовок", текст, ур, строк=-1))

    def закрыть_заголовок(self) -> None:
        if self.части and self.части[-1].вид == "заголовок":
            self.части[-1].строк = 1

    def абзац(self, текст: str, x0: float, новый: bool = False) -> None:
        self.закрыть_заголовок()
        последняя = self.части[-1] if self.части else None
        пункт = МЕТКА_ПУНКТА.match(текст)
        if пункт:
            self.части.append(Часть("пункт", текст[пункт.end():], x0=x0))
        elif not новый and последняя and последняя.вид == "пункт" and x0 > последняя.x0 + ОТСТУП_ПРОДОЛЖЕНИЯ:
            последняя.текст += " " + текст
        elif not новый and последняя and последняя.вид == "абзац" and текст[:1].islower():
            последняя.текст += " " + текст
        else:
            self.части.append(Часть("абзац", текст, x0=x0))


def рамки(страница: pymupdf.Page) -> list[pymupdf.Rect]:
    """Светлые залитые рамки врезок: уже страницы и колонки-полторы, выше одной строки."""
    итог = []
    for рисунок in страница.get_drawings():
        заливка, прямоугольник = рисунок.get("fill"), рисунок["rect"]
        if заливка and min(заливка) > 0.85 and 100 < прямоугольник.width < 250 and прямоугольник.height > 30:
            итог.append(прямоугольник)
    return итог


def в_markdown(документ: pymupdf.Document) -> tuple[str, int]:
    """Текст книги с заголовками и число заголовков."""
    основной = Поток([Часть("заголовок", "Betrayal at Baldur's Gate — Rulebook", 1)])
    отложенные: list[Поток] = []
    раздел = ""

    def разобрать(блок: dict, поток: Поток, врезка: bool) -> None:
        nonlocal раздел
        первый_абзац_блока = True
        for линия in блок["lines"]:
            отрезки = [о for о in линия["spans"] if о["text"].strip() and о["size"] >= НАИМЕНЬШИЙ_КЕГЛЬ]
            if not отрезки:
                continue
            текст = re.sub(r"\s+", " ", "".join(о["text"] for о in отрезки)).strip()
            if КОЛОНТИТУЛ.match(текст):
                continue
            ур = уровень(max(о["size"] for о in отрезки), отрезки[0]["font"])
            if ур:
                if not врезка:
                    закрыто = not (поток.части and поток.части[-1].вид == "заголовок" and поток.части[-1].строк < 0
                                   and поток.части[-1].уровень == ур)
                    if закрыто:
                        # Врезки встают перед новым заголовком основного текста.
                        for отложенный in отложенные:
                            поток.части += отложенный.части
                        отложенные.clear()
                поток.заголовок(ур, текст)
                if ур == 2 and not врезка:
                    раздел = " ".join(ч.текст for ч in поток.части[-1:])
                continue
            if not врезка and поток.части and поток.части[-1].вид == "заголовок" and поток.части[-1].уровень == 2:
                раздел = поток.части[-1].текст
            термин = ТЕРМИН.match(текст) if (not врезка and раздел == СЛОВАРЬ
                                              and отрезки[0]["font"] == "CronosPro-Bold") else None
            if термин:
                поток.заголовок(3, термин.group(1).strip())
                поток.закрыть_заголовок()
                поток.абзац(текст, линия["bbox"][0], новый=True)
                первый_абзац_блока = False
                continue
            # Строки одного блока — один абзац; первая строка блока решает, продолжение ли это.
            # Пункт списка начинает новую часть и посреди блока.
            if МЕТКА_ПУНКТА.match(текст):
                поток.абзац(текст, линия["bbox"][0], новый=True)
                первый_абзац_блока = False
            elif первый_абзац_блока:
                поток.абзац(текст, блок["bbox"][0])
                первый_абзац_блока = False
            else:
                поток.закрыть_заголовок()
                последняя = поток.части[-1]
                if последняя.вид == "заголовок":
                    поток.абзац(текст, блок["bbox"][0], новый=True)
                else:
                    последняя.текст += " " + текст

    for страница in документ:
        if страница.number + 1 in ЛИШНИЕ_СТРАНИЦЫ:
            continue
        середина = страница.rect.width / 2
        свои_рамки = рамки(страница)
        блоки = [б for б in страница.get_text("dict")["blocks"] if "lines" in б]
        страничные: list[Поток] = []
        во_врезках: dict[int, list[dict]] = {}
        в_основном: list[dict] = []
        for блок in блоки:
            центр = pymupdf.Point((блок["bbox"][0] + блок["bbox"][2]) / 2, (блок["bbox"][1] + блок["bbox"][3]) / 2)
            номер = next((н for н, рамка in enumerate(свои_рамки) if рамка.contains(центр)), None)
            if номер is None:
                в_основном.append(блок)
            else:
                во_врезках.setdefault(номер, []).append(блок)
        for свои in во_врезках.values():
            врезка = Поток()
            for блок in sorted(свои, key=lambda б: б["bbox"][1]):
                разобрать(блок, врезка, True)
            врезка.закрыть_заголовок()
            if врезка.части:
                страничные.append(врезка)
        for блок in sorted(в_основном, key=lambda б: (б["bbox"][0] >= середина, б["bbox"][1])):
            разобрать(блок, основной, False)
        отложенные += страничные
    основной.закрыть_заголовок()
    for отложенный in отложенные:
        основной.части += отложенный.части

    строки: list[str] = []
    заголовков = 0
    for часть in основной.части:
        if часть.вид == "заголовок":
            строки.append("#" * часть.уровень + " " + часть.текст)
            заголовков += часть.уровень > 1
        elif часть.вид == "пункт":
            строки.append("- " + часть.текст)
        else:
            строки.append(часть.текст)
    текст = "\n\n".join(строки) + "\n"
    # Оглавление — от своего заголовка до следующего заголовка раздела.
    текст, вырезано = re.subn(rf"## {ОГЛАВЛЕНИЕ}\n.*?(?=\n## )", "", текст, flags=re.DOTALL)
    return текст, заголовков - вырезано


def главная() -> None:
    скачать()
    текст, заголовков = в_markdown(pymupdf.open(PDF))
    MARKDOWN.parent.mkdir(parents=True, exist_ok=True)
    MARKDOWN.write_text(текст, "utf-8")
    print(f"правила: {len(текст)} знаков, заголовков {заголовков} → {MARKDOWN}")
    if "--без-индекса" in sys.argv:
        return
    subprocess.run(["uv", "run", "-q", "--project", str(RAG), str(RAG / "cli.py"), "--index", str(ИНДЕКС),
                    "index", "--corpus", str(MARKDOWN.parent), "--strategy", "structure"], check=True)


if __name__ == "__main__":
    главная()
