"""Проверки чистых функций `оценка.py` и `наряд.py` без сети, службы и журнала.

Запуск из папки дня: `uv run проверки.py`. Код выхода 1 при хоть одном провале.
"""

from __future__ import annotations

import json
import sys
import tempfile
from pathlib import Path

import наряд
import оценка

провалов = 0


def проверить(название: str, условие: bool, подробно: str = "") -> None:
    global провалов
    if условие:
        print(f"ок      {название}")
    else:
        провалов += 1
        print(f"ПРОВАЛ  {название}" + (f": {подробно}" if подробно else ""))


ТРИ = "## Правило\nМожно [2].\n\n## Сцена\nТемно.\n\n## Что дальше\nКуда идёшь?"
части = оценка.разделы(ТРИ)
проверить("разделы: три заголовка по порядку — тексты разделов",
          части == {"Правило": "Можно [2].", "Сцена": "Темно.", "Что дальше": "Куда идёшь?"}, repr(части))
проверить("разделы: без одного заголовка — None (парная)", оценка.разделы(ТРИ.replace("## Сцена\n", "")) is None)
проверить("разделы: иной порядок — None", оценка.разделы("Сцена\nа\nПравило\nб\nЧто дальше\nв") is None)
проверить("разделы: жирный заголовок с двоеточием и слово в тексте раздела",
          оценка.разделы("**Правило:** да, правило простое.\n**Сцена:** мрак.\n**Что дальше:** выбирай.")
          == {"Правило": "да, правило простое.", "Сцена": "мрак.", "Что дальше": "выбирай."})
проверить("разделы: строки текста, начатые словами заголовков, формой не считаются",
          оценка.разделы("Правило гласит, что можно.\nСцена меняется.\nЧто дальше будешь делать?") is None)
проверить("разделы: верхний регистр и решётки читаются",
          оценка.разделы("### ПРАВИЛО\nа\n### СЦЕНА\nб\n### ЧТО ДАЛЬШЕ\nв") == {"Правило": "а", "Сцена": "б", "Что дальше": "в"})
проверить("разделы: заголовки «Правило.» и «Что дальше?» читаются",
          оценка.разделы("**Правило.**\nа\n## Сцена\nб\n## Что дальше?\nв") == {"Правило": "а", "Сцена": "б", "Что дальше": "в"})
проверить("разделы: слово «Правило» посреди строки заголовком не считается",
          оценка.разделы("Это Правило такое.\nСцена\nа\nЧто дальше\nб") is None)

НАЙДЕННОЕ = (оценка.ЗАГОЛОВОК_НАЙДЕННОГО + "\n\n[1] rulebook.md › ON YOUR TURN › MOVE · structure:rulebook.md:9 (0.612)\ntext [7] inside\n\n"
             "[2] rulebook.md › GLOSSARY › move · structure:rulebook.md:60 (0.540)\nmore\n\nСколько шагов?")
найдено = оценка.найденные_разделы(НАЙДЕННОЕ)
проверить("найденное: имена разделов по порядку, последнее звено цепочки", найдено == ["MOVE", "move"], repr(найдено))
проверить("найденное: без блока найденного — пусто", оценка.найденные_разделы("Сколько шагов?") == [])
проверить("ссылки: [2] при двух кусках — годна и в нужный раздел", оценка.ссылки("см. [2]", найдено, ["move"]) == (True, True))
проверить("ссылки: [7] при двух кусках — не годна (парная)", оценка.ссылки("см. [7]", найдено, ["move"]) == (False, False))
проверить("ссылки: годна, но раздел не тот", оценка.ссылки("см. [1]", найдено, ["move"]) == (True, False))
проверить("ссылки: ссылок нет — не годна", оценка.ссылки("без ссылок", найдено, ["move"]) == (False, False))
проверить("ссылки: список [1, 2] и промежуток [1-2] читаются",
          оценка.ссылки("см. [1, 2]", найдено, ["move"]) == (True, True) and оценка.ссылки("см. [1-2]", найдено, ["move"]) == (True, True))
проверить("ссылки: в списке номер вне найденного — не годна (парная)", оценка.ссылки("см. [1, 3]", найдено, ["move"]) == (False, False))
проверить("токены: ответ — выход без рассуждений",
          оценка.токены_ответа({"usage": {"completion_tokens": 2208, "completion_tokens_details": {"reasoning_tokens": 1990}}}) == (218, 1990)
          and оценка.токены_ответа({"usage": {"completion_tokens": 300}}) == (300, 0))

проверить("разнообразие: одинаковые тексты — 0", оценка.расстояние("кот идёт в подвал", "Кот идёт в подвал.") == 0)
проверить("разнообразие: общих слов нет — 1 (парная)", оценка.расстояние("кот идёт", "пёс спит") == 1)
проверить("разнообразие: пустой текст в пару не идёт", оценка.расстояние("", "кот идёт") is None and оценка.расстояние("", "") is None)
проверить("разнообразие: половина слов общая", оценка.расстояние("кот идёт", "кот спит") == 1 - 1 / 3)
проверить("вымысел: у ответа с разделами берётся «Что дальше», без разделов — весь ответ",
          оценка.вымысел(ТРИ) == "Куда идёшь?" and оценка.вымысел("просто текст") == "просто текст")

проверить("доля русского: английское в скобках и кавычках не считается",
          оценка.доля_русского("Бросок силы (Might roll) и `haunt`") == 1.0)
проверить("доля русского: английский текст вне скобок считается (парная)",
          оценка.доля_русского("сила Might") == 4 / 9, repr(оценка.доля_русского("сила Might")))

имя = наряд.имя_задания("t07", 2, "q03")
разбор = оценка.ЗАДАНИЕ.match(имя)
проверить("имя задания: наряд пишет, оценка читает", bool(разбор) and (разбор["настройка"], разбор["прогон"], разбор["задание"]) == ("t07", "2", "q03"), имя)
проверить("имя задания: сценарий партии", bool(оценка.ЗАДАНИЕ.match(наряд.имя_задания("after", 1, "party"))))
проверить("имя задания: чужое имя не читается", оценка.ЗАДАНИЕ.match("q01-local") is None)
проверить("имя модели: без окна — основа, с окном — tavern:<квант>-<окно>",
          наряд.имя_модели("qwen3.5:9b-q4_K_M", None) == "qwen3.5:9b-q4_K_M" and наряд.имя_модели("qwen3.5:9b-q8_0", 8192) == "tavern:q8-8192")

with tempfile.TemporaryDirectory() as каталог:
    журнал = Path(каталог) / "ж.jsonl"
    запись = lambda agent, index, ответ, run="А", status="ok": json.dumps(
        {"agent": agent, "index": index, "response": ответ, "status": status, "run_id": run}, ensure_ascii=False)
    журнал.write_text("\n".join([
        запись("do.1-q01", 1, "старый"), запись("do.1-q02", 1, "удачный"), запись("do.1-q03", 1, "сбой", "А", "error"),
        *[запись("do.1-party", н, f"старая {н}") for н in (1, 2, 3)], запись("чужое", 1, "мимо"),
        запись("do.1-q01", 1, "новый", "Б"), запись("do.1-q02", 1, "сбой", "Б", "error"),
        запись("do.1-party", 1, "новая 1", "Б"), запись("do.1-party", 2, "сбой", "Б", "error")]) + "\n", "utf-8")
    прочитано = оценка.журнал(журнал)
    свои = прочитано[("do", 1)]
    проверить("журнал: повтор заменяет прежний запуск задания", [з["response"] for з in свои["q01"]] == ["новый"], repr(свои["q01"]))
    проверить("журнал: упавший повтор не оставляет старого удачного ответа (парная)", свои["q02"] == [] and свои["q03"] == [])
    проверить("журнал: партия — только последний запуск и только до сбоя, старые реплики не подмешаны",
              [з["response"] for з in свои["party"]] == ["новая 1"], repr(свои["party"]))
    проверить("журнал: чужое имя мимо", list(прочитано) == [("do", 1)])
    длина = Path(каталог) / "д.jsonl"
    длина.write_text("\n".join([
        json.dumps({"agent": "do.1-q01", "index": 1, "response": "", "status": "error", "finish_reason": "length", "run_id": "А"}),
        json.dumps({"agent": "do.1-q02", "index": 1, "response": "", "status": "error", "finish_reason": None, "run_id": "А"})]) + "\n", "utf-8")
    исходы = оценка.журнал(длина)[("do", 1)]
    проверить("журнал: исчерпанное окно — запись остаётся пустым ответом; прочий сбой — задания нет (парная)",
              len(исходы["q01"]) == 1 and исходы["q02"] == [], repr(исходы))
    try:
        оценка.найденное_либо_стоп({"agent": "do.1-q01", "index": 1, "messages": [{"content": "Вопрос без блока"}]})
        остановлено = False
    except SystemExit:
        остановлено = True
    разделы_найденного, блок = оценка.найденное_либо_стоп({"messages": [{"content": НАЙДЕННОЕ}]})
    проверить("найденное: запись без кусков останавливает оценку; с кусками — блок без реплики игрока",
              остановлено and разделы_найденного == ["MOVE", "move"] and блок.endswith("more") and "Сколько шагов?" not in блок)

    вызовы: list[dict] = []
    def подставной(тело: dict) -> str:
        вызовы.append(тело)
        return json.dumps({"правило": "верно", "продолжает": True, "новое": False, "выбор": True, "вымысел_как_правило": False, "довод": "д"})
    файл = Path(каталог) / "в.json"
    судья = оценка.Судья(файл, подставной)
    первый = судья.ответ("р", "о", "н", "ответ")
    судья.ответ("р", "о", "н", "ответ")
    проверить("судья: тот же вход — один вызов, вердикт из файла", len(вызовы) == 1 and оценка.Судья(файл, подставной).ответ("р", "о", "н", "ответ") == первый and len(вызовы) == 1)
    судья.ответ("р", "о", "н", "другой ответ")
    проверить("судья: другой ответ — новый вызов (парная)", len(вызовы) == 2)
    было = len(вызовы)
    пустая = {"agent": "do.1-q01", "index": 1, "response": "", "status": "error", "finish_reason": "length",
              "messages": [{"content": НАЙДЕННОЕ}], "elapsed_ms": 1000, "usage": {"completion_tokens": 9, "completion_tokens_details": {"reasoning_tokens": 9}}}
    полная = {**пустая, "response": ТРИ, "status": "ok", "finish_reason": "stop"}
    вопрос = {"n": 1, "вид": "чужой", "реплика": "р", "ожидание": "о", "разделы": []}
    оценённый = оценка.оценить_ответ(вопрос, пустая, судья)
    проверить("пустой ответ: вердикт «пусто» без вызова судьи, длина ответа 0",
              оценённый["вердикт"]["правило"] == "пусто" and len(вызовы) == было and оценённый["токены"] == 0, repr(оценённый["вердикт"]))
    оценка.оценить_ответ(вопрос, полная, судья)
    проверить("непустой ответ: судья вызван (парная)", len(вызовы) == было + 1)
    судья_партии = оценка.Судья(Path(каталог) / "п.json", lambda тело: вызовы.append(тело) or '{"помнит": true, "противоречит": false, "довод": "д"}')
    сценарий = {"asks": ["один", "два", "три"], "связи": {"2": "с2", "3": "с3"}}
    было = len(вызовы)
    партия = оценка.оценить_партию([полная, полная, пустая], сценарий, судья_партии)
    проверить("партия: отвечено — только непустые; пустой ответ судье не идёт и «помнит» не получает",
              партия["реплик"] == 2 and партия["судимых"] == 2 and партия["помнит"] == 1 and len(вызовы) == было + 1, repr(партия))
    try:
        оценка.Судья(Path(каталог) / "г.json", lambda тело: json.dumps(
            {"правило": "почти", "продолжает": True, "новое": True, "выбор": True, "вымысел_как_правило": False})).ответ("р", "о", "н", "а")
        отвергнут = False
    except ValueError:
        отвергнут = True
    проверить("судья: вердикт не из четырёх слов — ValueError, в файл не идёт", отвергнут and not (Path(каталог) / "г.json").exists())

sys.exit(1 if провалов else 0)
