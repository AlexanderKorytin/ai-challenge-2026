def _число(значение: float | None, знаков: int = 2) -> str:
    return "—" if значение is None else f"{значение:.{знаков}f}".replace(".", ",")


def _из(сколько: int, всего: int) -> str:
    return f"{сколько} из {всего}"


def отчёт(все_строки: list[dict], набор: str, ожидаемые: list[int], правил: int) -> str:
    строки = [с for с in все_строки if с["ответы"]]
    if not строки:
        return отчёт_партий(все_строки)
    части = [f"Реплики набора: {набор} — {len(ожидаемые)}, из них вида «правило» {правил}. Строка — «настройка.прогон».", ""]
    for с in строки:
        нет = sorted(set(ожидаемые) - {о["n"] for о in с["ответы"]})
        if нет:
            части += [f"**`{с['имя']}`: нет ответа на реплики {', '.join(f'q{n:02d}' for n in нет)}** — задания нет в журнале либо оно упало; "
                      f"в счёт идут {len(с['ответы'])} реплик, знаменатели строки меньше.", ""]
    части += [
             "### Правило", "",
             "| Настройка | Верно | Частично | Неверно | Ложный отказ | Отказ на чужих | Ответа нет | Ссылка годна | Ссылка в нужный раздел | Вымысел как правило |",
             "|---|---|---|---|---|---|---|---|---|---|"]
    for с in строки:
        правила = [о for о in с["ответы"] if о["вид"] == "правило"]
        чужие = [о for о in с["ответы"] if о["вид"] == "чужой"]
        счёт = lambda слово: sum(о["вердикт"]["правило"] == слово for о in правила)
        части.append(f"| `{с['имя']}` | {_из(счёт('верно'), len(правила))} | {счёт('частично')} | {счёт('неверно')} | {счёт('отказ')} | "
                     f"{_из(sum(о['вердикт']['правило'] == 'отказ' for о in чужие), len(чужие))} | "
                     f"{sum(о['вердикт']['правило'] == 'пусто' for о in с['ответы'])} | "
                     f"{_из(sum(о['ссылка'] for о in правила), len(правила))} | {_из(sum(о['в_нужный'] for о in правила), len(правила))} | "
                     f"{_из(sum(о['вердикт']['вымысел_как_правило'] for о in с['ответы']), len(с['ответы']))} |")
    части += ["", "### Форма и фантазия", "",
              "Разнообразие считается по разделу «Что дальше»; у ответа без трёх разделов — по всему ответу. "
              "Пустые ответы в разнообразие и в долю русского не идут. "
              "У строк с разным числом ответов «по форме» столбцы разнообразия сравнивают разные тексты.", "",
              "| Настройка | Три раздела | Доля русского | Продолжает | Новое | Выбор | Разнообразие между репликами | Разнообразие между прогонами |",
              "|---|---|---|---|---|---|---|---|"]
    for с in строки:
        о, всего = с["ответы"], len(с["ответы"])
        части.append(f"| `{с['имя']}` | {_из(sum(а['форма'] for а in о), всего)} | {_число(среднее(а['русский'] for а in о))} | "
                     f"{_из(sum(а['вердикт']['продолжает'] for а in о), всего)} | {_из(sum(а['вердикт']['новое'] for а in о), всего)} | "
                     f"{_из(sum(а['вердикт']['выбор'] for а in о), всего)} | {_число(между_репликами(о))} | {_число(с['между_прогонами'])} |")
    части += ["", "### Скорость и ресурсы", "",
              "Время ответа — поиск и обмен вместе; у первой реплики прогона в нём загрузка модели. Скорость — весь выход "
              "(ответ и рассуждения) на время обмена, в котором есть и чтение запроса. Длина ответа — по непустым ответам; "
              "рассуждения, время и скорость — по всем обменам, включая те, где ответа нет.", "",
              "| Настройка | Модель | Время ответа, с (медиана / наибольшее) | Токенов выхода в секунду | Ответ, токенов (медиана / наибольший) | Рассуждения, токенов (медиана) | Обрывов по длине | Память, ГБ | В видеоядре | Окно |",
              "|---|---|---|---|---|---|---|---|---|---|"]
    for с in строки:
        о, р = с["ответы"], с["ресурсы"]
        времена = [а["время"] / 1000 for а in о]
        токены = [а["токены"] for а in о if а["токены"] is not None and а["ответ"].strip()] or [0]
        память = f"{р['size'] / 1e9:.1f}".replace(".", ",") if р.get("size") else "—"
        ядро = f"{р['size_vram'] / р['size'] * 100:.0f} %" if р.get("size") and р.get("size_vram") is not None else "—"
        части.append(f"| `{с['имя']}` | `{р.get('основа') or р.get('модель', '—')}` | {_число(statistics.median(времена), 1)} / {_число(max(времена), 1)} | "
                     f"{_число(statistics.median([а['скорость'] for а in о if а['скорость']]), 1)} | "
                     f"{statistics.median(токены):.0f} / {max(токены)} | {statistics.median([а['токены_рассуждений'] for а in о]):.0f} | "
                     f"{sum(а['обрыв'] for а in о)} | {память} | {ядро} | {р.get('context_length', '—')} |")
    партии = [с for с in все_строки if с["партия"]]
    if партии:
        части += ["", "### Партия из 8 ходов", "",
                  "| Настройка | Реплик отвечено | Помнит прошлое | Противоречит прошлому | Три раздела | Наибольший запрос, токенов | Обрывов по длине | Время хода, с (медиана) |",
                  "|---|---|---|---|---|---|---|---|"]
        for с in партии:
            п = с["партия"]
            части.append(f"| `{с['имя']}` | {_из(п['реплик'], п['из'])} | {_из(п['помнит'], п['судимых'])} | {_из(п['противоречит'], п['судимых'])} | "
                         f"{_из(п['форма'], п['реплик'])} | {п['наибольший_запрос']} | {п['обрывов']} | {_число(п['время'] / 1000 if п['время'] else None, 1)} |")
    return "\n".join(части) + "\n"


def ответы_текстом(строки: list[dict], вопросы: dict[int, dict]) -> str:
    части = ["", "### Ответы", ""]
    for с in строки:
        for о in с["ответы"]:
            в = о["вердикт"]
            части += [f"#### `{с['имя']}` q{о['n']:02d} — {в['правило']}", "", f"Игрок: {вопросы[о['n']]['реплика']}", "",
                      "```text", о["ответ"].strip(), "```", "", f"Судья: {в.get('довод', '')}", ""]
    return "\n".join(части)


def главная() -> None:
    разбор = argparse.ArgumentParser(prog="оценка")
    разбор.add_argument("--настройка", action="append", required=True)
    разбор.add_argument("--набор", choices=["подбор", "итог", "все"], default="подбор")
    разбор.add_argument("--out", type=Path)
    разбор.add_argument("--ответы", action="store_true", help="дописать тексты ответов")
    доводы = разбор.parse_args()
    вопросы = {з["n"]: з for з in map(json.loads, НАБОР.read_text("utf-8").splitlines())}
    сценарий = json.loads(СЦЕНАРИЙ.read_text("utf-8"))
    записи, память, судья = журнал(ЖУРНАЛ), ресурсы(РЕСУРСЫ), Судья(ВЕРДИКТЫ)
    ожидаемые = [n for n in sorted(вопросы) if доводы.набор in ("все", вопросы[n]["набор"])]
    строки = []
    for настройка in доводы.настройка:
        прогоны = sorted(п for н, п in записи if н == настройка)
        if not прогоны:
            sys.exit(f"оценка: записей настройки {настройка!r} в журнале нет")
        оценённые: dict[int, list[dict]] = {}
        for прогон in прогоны:
            задания = записи[(настройка, прогон)]
            ответы = [оценить_ответ(вопросы[n], задания[f"q{n:02d}"][0], судья) for n in ожидаемые if задания.get(f"q{n:02d}")]
            оценённые[прогон] = ответы
            партия = задания.get("party")
            if not ответы and not партия:
                continue
            свои = память.get((настройка, прогон), {})
            чужие_модели = {з.get("model") for список in задания.values() for з in список} - {f"ollama/{свои.get('модель')}"}
            if свои and чужие_модели:
                sys.exit(f"оценка: {настройка}.{прогон} — в журнале модель {sorted(map(str, чужие_модели))}, "
                         f"а строка ресурсов снята с {свои.get('модель')}")
            строки.append({"имя": f"{настройка}.{прогон}", "ответы": ответы, "ресурсы": свои,
                           "партия": оценить_партию(партия, сценарий, судья) if партия else None,
                           "между_прогонами": между_прогонами(оценённые[прогоны[0]], ответы) if прогон != прогоны[0] else None})
            print(f"\rоценено: {настройка}.{прогон}", end="", file=sys.stderr, flush=True)
    print(file=sys.stderr)
    с_ответами = [с for с in строки if с["ответы"]]
    текст = отчёт(строки, доводы.набор, ожидаемые, sum(вопросы[n]["вид"] == "правило" for n in ожидаемые))
    if доводы.ответы:
        текст += ответы_текстом(с_ответами, вопросы)
    if доводы.out:
        доводы.out.write_text(текст, "utf-8")
        print(f"записано: {доводы.out}")
    else:
        print(текст)


