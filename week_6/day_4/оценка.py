# ── разбор ответа ────────────────────────────────────────────────────────────

def разделы(ответ: str) -> dict[str, str] | None:
    """Тексты трёх разделов; `None`, если хоть одного заголовка нет или порядок иной."""
    имена = {имя.lower(): имя for имя in РАЗДЕЛЫ}
    места = [(имена[м.group(1).lower()], м.start(), м.end()) for м in ЗАГОЛОВОК_РАЗДЕЛА.finditer(ответ)]
    первые: list[tuple[str, int, int]] = []
    for имя, начало, конец in места:
        if имя not in [и for и, _, _ in первые]:
            первые.append((имя, начало, конец))
    if tuple(и for и, _, _ in первые) != РАЗДЕЛЫ:
        return None
    границы = [начало for _, начало, _ in первые[1:]] + [len(ответ)]
    return {имя: ответ[конец:граница].strip() for (имя, _, конец), граница in zip(первые, границы)}


def доля_русского(ответ: str) -> float | None:
    вне = re.sub(r"\([^()]*\)|`[^`]*`", " ", ответ)
    буквы = [б for б in вне if б.isalpha()]
    return sum("а" <= б.lower() <= "я" or б.lower() == "ё" for б in буквы) / len(буквы) if буквы else None


def найденные_разделы(отправленное: str) -> list[str]:
    """Имена разделов найденных кусков по порядку номеров (последнее звено цепочки заголовков)."""
    if not отправленное.startswith(ЗАГОЛОВОК_НАЙДЕННОГО):
        return []
    итог: list[str] = []
    for совпало in ЗАГОЛОВОК_КУСКА.finditer(отправленное):
        if int(совпало.group(1)) != len(итог) + 1:
            break
        итог.append(совпало.group(2).split(" › ")[-1])
    return итог


def ссылки(текст: str, найдено: list[str], нужные: list[str]) -> tuple[bool, bool]:
    """(ссылка годна, ссылка в нужный раздел)."""
    номера: list[int] = []
    for группа in ССЫЛКА.findall(текст):
        числа = [int(ч) for ч in re.findall(r"\d+", группа)]
        if re.search(r"[\-–]", группа) and len(числа) == 2 and числа[0] <= числа[1]:
            числа = list(range(числа[0], числа[1] + 1))
        номера += числа
    годна = bool(номера) and all(1 <= н <= len(найдено) for н in номера)
    в_нужный = any(1 <= н <= len(найдено) and найдено[н - 1] in нужные for н in номера)
    return годна, в_нужный


def слова(текст: str) -> set[str]:
    return {с.lower() for с in СЛОВО.findall(текст)}


def расстояние(а: str, б: str) -> float | None:
    """Расстояние Жаккара между множествами слов: 0 — одни и те же слова, 1 — общих нет.
    Пустой текст в пару не идёт (`None`): пустой ответ против любого дал бы 1 и завысил разнообразие."""
    А, Б = слова(а), слова(б)
    return 1 - len(А & Б) / len(А | Б) if А and Б else None


def вымысел(ответ: str) -> str:
    части = разделы(ответ)
    return части["Что дальше"] if части else ответ


def последнее_сообщение(запись: dict) -> str:
    содержание = (запись.get("messages") or [{}])[-1].get("content") or ""
    return содержание if isinstance(содержание, str) else ""


# ── журнал ───────────────────────────────────────────────────────────────────

def журнал(путь: Path) -> dict[tuple[str, int], dict[str, list[dict]]]:
    """(настройка, прогон) → задание → удачные записи ПОСЛЕДНЕГО запуска задания по номеру обмена.

    Повтор задания заменяет прежний запуск целиком: записи двух `run_id` не смешиваются. Обмены
    берутся до первого сбоя: упавшая реплика партии обрывает её, упавшая реплика набора даёт
    пустой список — задание не отвечено. Исключение — обмен, где модель исчерпала окно (см.
    `исчерпано`): он остаётся последней записью задания и считается пустым ответом."""
    запуски: dict[tuple[str, int], dict[str, tuple[str, list[dict]]]] = {}
    for строка in путь.read_text("utf-8").splitlines():
        запись = json.loads(строка)
        имя = ЗАДАНИЕ.match(запись.get("agent") or "")
        if not имя:
            continue
        задания = запуски.setdefault((имя["настройка"], int(имя["прогон"])), {})
        прежний = задания.get(имя["задание"])
        if прежний is None or прежний[0] != запись.get("run_id"):
            задания[имя["задание"]] = (запись.get("run_id"), [запись])
        else:
            прежний[1].append(запись)
    итог: dict[tuple[str, int], dict[str, list[dict]]] = {}
    for ключ, задания in запуски.items():
        итог[ключ] = {}
        for задание, (_, записи) in задания.items():
            удачные: list[dict] = []
            for запись in sorted(записи, key=lambda з: int(з.get("index") or 1)):
                if запись.get("status") != "ok":
                    if исчерпано(запись):
                        удачные.append(запись)
                    break
                удачные.append(запись)
            итог[ключ][задание] = удачные
    return итог


def исчерпано(запись: dict) -> bool:
    """Модель израсходовала окно или предел длины и ответа не дала: `myharness` пишет такой обмен
    сбоем с `finish_reason: length`. Это исход модели, а не сбой прогона: он идёт в счёт пустым ответом."""
    return запись.get("status") != "ok" and запись.get("finish_reason") == "length"


def ресурсы(путь: Path) -> dict[tuple[str, int], dict]:
    итог: dict[tuple[str, int], dict] = {}
    if путь.is_file():
        for строка in путь.read_text("utf-8").splitlines():
            запись = json.loads(строка)
            итог[(запись["настройка"], запись["прогон"])] = запись
    return итог


# ── судья ────────────────────────────────────────────────────────────────────

class Судья:
    """Вердикты по отпечатку входа; файл дописывается после каждого нового вердикта."""

    def __init__(self, путь: Path, спросить=None) -> None:
        self._путь = путь
        self._спросить = спросить
        self._данные: dict[str, dict] = json.loads(путь.read_text("utf-8")) if путь.is_file() else {}

    def _вердикт(self, инструкция: str, вход: str, проверить) -> dict:
        отпечаток = hashlib.sha256(json.dumps([МОДЕЛЬ_СУДЬИ, инструкция, вход], ensure_ascii=False).encode()).hexdigest()
        if отпечаток in self._данные:
            return self._данные[отпечаток]
        if self._спросить is None:
            import rewrite  # ключ DeepSeek читается из настроек myharness только здесь
            self._спросить = rewrite.спросить
        сырой = self._спросить({"model": МОДЕЛЬ_СУДЬИ, "response_format": {"type": "json_object"},
                                "messages": [{"role": "system", "content": инструкция}, {"role": "user", "content": вход}]})
        try:
            данные = json.loads(сырой)
        except ValueError:
            raise ValueError(f"судья вернул не JSON: {сырой[:200]!r}") from None
        if not isinstance(данные, dict) or not проверить(данные):
            raise ValueError(f"судья вернул ответ не того вида: {сырой[:200]!r}")
        self._данные[отпечаток] = данные
        временный = self._путь.with_name(self._путь.name + ".tmp")
        временный.write_text(json.dumps(self._данные, ensure_ascii=False, indent=1) + "\n", "utf-8")
        os.replace(временный, self._путь)
        return данные

    def ответ(self, реплика: str, ожидание: str, найденное: str, ответ: str) -> dict:
        вход = f"РЕПЛИКА:\n{реплика}\n\nОЖИДАНИЕ:\n{ожидание}\n\nНАЙДЕННОЕ:\n{найденное}\n\nОТВЕТ:\n{ответ}"
        годен = lambda д: д.get("правило") in ПРАВИЛО and all(
            isinstance(д.get(к), bool) for к in ("продолжает", "новое", "выбор", "вымысел_как_правило"))
        return self._вердикт(ИНСТРУКЦИЯ_СУДЬИ, вход, годен)

    def партия(self, прошлое: str, реплика: str, связь: str, ответ: str) -> dict:
        вход = f"ПРОШЛОЕ:\n{прошлое}\n\nРЕПЛИКА:\n{реплика}\n\nСВЯЗЬ:\n{связь}\n\nОТВЕТ:\n{ответ}"
        годен = lambda д: isinstance(д.get("помнит"), bool) and isinstance(д.get("противоречит"), bool)
        return self._вердикт(ИНСТРУКЦИЯ_СУДЬИ_ПАРТИИ, вход, годен)


# ── меры ─────────────────────────────────────────────────────────────────────

def найденное_либо_стоп(запись: dict) -> tuple[list[str], str]:
    """(разделы найденных кусков, блок найденного без реплики игрока). Поиск режима `base` без порога
    куски отдаёт всегда: запись без них — сбой поиска, и счесть её ответом модели нельзя."""
    отправленное = последнее_сообщение(запись)
    найдено = найденные_разделы(отправленное)
    if not найдено:
        sys.exit(f"оценка: в записи {запись.get('agent')} (обмен {запись.get('index')}) нет найденных кусков — "
                 f"поиск не состоялся, прогон надо повторить")
    return найдено, отправленное.rsplit("\n\n", 1)[0]


def токены_ответа(запись: dict) -> tuple[int | None, int]:
    """(токены самого ответа, токены рассуждений): `completion_tokens` службы несёт их суммой."""
    usage = запись.get("usage") or {}
    рассуждения = (usage.get("completion_tokens_details") or {}).get("reasoning_tokens") or 0
    выход = usage.get("completion_tokens")
    return (None if выход is None else выход - рассуждения), рассуждения


def оценить_ответ(вопрос: dict, запись: dict, судья: Судья) -> dict:
    ответ = запись.get("response") or ""
    найдено, найденное = найденное_либо_стоп(запись)
    части = разделы(ответ)
    годна, в_нужный = ссылки(части["Правило"] if части else ответ, найдено, вопрос["разделы"])
    usage = запись.get("usage") or {}
    время = (запись.get("elapsed_ms") or 0) + (запись.get("search_ms") or 0)
    свои, рассуждения = токены_ответа(запись)
    вердикт = судья.ответ(вопрос["реплика"], вопрос["ожидание"], найденное, ответ) if ответ.strip() else ПУСТОЙ_ВЕРДИКТ
    return {"n": вопрос["n"], "вид": вопрос["вид"], "ответ": ответ, "форма": части is not None,
            "русский": доля_русского(ответ), "ссылка": годна, "в_нужный": в_нужный, "найдено": len(найдено),
            "обрыв": запись.get("finish_reason") == "length", "токены": свои, "токены_рассуждений": рассуждения,
            "запрос": usage.get("prompt_tokens"), "время": время, "модель": запись.get("model"),
            "скорость": (usage.get("completion_tokens") or 0) / запись["elapsed_ms"] * 1000 if запись.get("elapsed_ms") else None,
            "вердикт": вердикт}


def оценить_партию(записи: list[dict], сценарий: dict, судья: Судья) -> dict:
    реплики, связи = сценарий["asks"], сценарий["связи"]
    for запись in записи:
        найденное_либо_стоп(запись)
    вердикты = []
    for номер in range(2, len(записи) + 1):
        ответ = записи[номер - 1].get("response") or ""
        if not ответ.strip():
            # Пустой ответ судье не отдаётся, как и у реплик набора.
            вердикты.append({"помнит": False, "противоречит": False, "довод": "ответ пуст"})
            continue
        прошлое = "\n\n".join(f"Игрок: {реплики[и]}\nВедущий: {записи[и].get('response') or ''}" for и in range(номер - 1))
        вердикты.append(судья.партия(прошлое, реплики[номер - 1], связи[str(номер)], ответ))
    запросы = [(з.get("usage") or {}).get("prompt_tokens") or 0 for з in записи]
    return {"реплик": sum(bool((з.get("response") or "").strip()) for з in записи), "из": len(реплики), "помнит": sum(в["помнит"] for в in вердикты),
            "противоречит": sum(в["противоречит"] for в in вердикты), "судимых": len(вердикты),
            "наибольший_запрос": max(запросы, default=0), "запросы": запросы,
            "обрывов": sum(з.get("finish_reason") == "length" for з in записи),
            "форма": sum(разделы(з.get("response") or "") is not None for з in записи),
            "время": statistics.median((з.get("elapsed_ms") or 0) + (з.get("search_ms") or 0) for з in записи) if записи else None}


def среднее(значения) -> float | None:
    значения = [з for з in значения if з is not None]
    return sum(значения) / len(значения) if значения else None


def между_репликами(ответы: list[dict]) -> float | None:
    return среднее(расстояние(вымысел(а["ответ"]), вымысел(б["ответ"])) for а, б in itertools.combinations(ответы, 2))


def между_прогонами(первый: list[dict], второй: list[dict]) -> float | None:
    по_номеру = {о["n"]: о for о in второй}
    return среднее(расстояние(вымысел(о["ответ"]), вымысел(по_номеру[о["n"]]["ответ"])) for о in первый if о["n"] in по_номеру)


