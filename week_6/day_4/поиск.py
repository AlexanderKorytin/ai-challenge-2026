"""Выбор поиска по книге правил: у скольких реплик нужный раздел стоит в первых пяти.

Запуск из папки дня: `uv run --project ~/challenge/main/rag поиск.py [--сверить] [--out поиск.md]`.

Кандидатов два, оба — режим `base` сервера `rag/server.py` (косинус `bge-m3`, K = 5):

- `base` — русская реплика игрока против английского текста правил как есть;
- `base+rw` — перед поиском реплику переписывает местная модель (`rag/rewrite.py` с
  `RAG_REWRITE_MODEL`): к словам вопроса она дописывает английские соответствия.

Правило выбора записано до замера: больше реплик вида «правило» с нужным разделом в первых
пяти; при равенстве — `base`, у него нет второго запроса к модели. Режим `heuristic` и пороги
не берутся: порог пришлось бы подбирать, а день меряет модель, а не поиск.

`--сверить` поиска не запускает: проверяет, что каждый раздел из поля `разделы` контрольного
набора есть среди разделов кусков индекса.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
from pathlib import Path

ПАПКА = Path(__file__).resolve().parent
RAG = Path.home() / "challenge" / "main" / "rag"
sys.path.insert(0, str(RAG))

import server  # noqa: E402
import store  # noqa: E402

ИНДЕКС = ПАПКА / "test" / "правила" / "правила.sqlite"
НАБОР = ПАПКА / "контроль.jsonl"
МОДЕЛЬ_ПЕРЕПИСЫВАНИЯ = "ollama/qwen3.5:9b-q4_K_M-32k"
K = 5
ЗАГОЛОВОК_КУСКА = re.compile(r"^\[(\d+)\] (\S+) › (.*) · (\S+) \(([\d.]+)\)$", re.MULTILINE)
КАНДИДАТЫ = {"base": False, "base+rw": True}


def набор() -> list[dict]:
    return [json.loads(строка) for строка in НАБОР.read_text("utf-8").splitlines() if строка.strip()]


def последний(раздел: str) -> str:
    """Имя самого раздела без цепочки вышестоящих."""
    return раздел.split(" › ")[-1]


def сверить() -> int:
    куски, _ = store.куски(ИНДЕКС, "structure")
    имена = {последний(к.section or к.title) for к in куски}
    бед = 0
    for запись in набор():
        if запись["вид"] == "правило" and not запись["разделы"]:
            print(f"q{запись['n']:02d}: у реплики вида «правило» нет разделов")
            бед += 1
        for раздел in запись["разделы"]:
            if раздел not in имена:
                print(f"q{запись['n']:02d}: раздела «{раздел}» нет в индексе")
                бед += 1
    print(f"сверка: кусков {len(куски)}, разделов {len(имена)}, бед {бед}")
    return бед


def найденные(текст: str) -> list[tuple[str, float]]:
    """[(раздел, счёт)] по порядку выдачи."""
    return [(последний(м.group(3)), float(м.group(5))) for м in ЗАГОЛОВОК_КУСКА.finditer(текст)]


def замер() -> dict[str, list[dict]]:
    поиск = server.открыть_поиск(ИНДЕКС)
    итог: dict[str, list[dict]] = {}
    for имя, переписывать in КАНДИДАТЫ.items():
        настройки = server.Настройки(режим="base", переписывать=переписывать, k2=K)
        строки = []
        for запись in набор():
            выдача = найденные(server.найти_текст(запись["реплика"], поиск, настройки))
            места = [место for место, (раздел, _) in enumerate(выдача, 1) if раздел in запись["разделы"]]
            строки.append({"n": запись["n"], "вид": запись["вид"], "место": места[0] if места else None,
                           "первый": выдача[0][0], "близость": выдача[0][1]})
            print(f"\r{имя}: {len(строки)}/25", end="", file=sys.stderr, flush=True)
        print(file=sys.stderr)
        итог[имя] = строки
    return итог


def отчёт(итог: dict[str, list[dict]]) -> str:
    части = ["# Выбор поиска по книге правил", "",
             "Индекс — книга правил, нарезка `structure`. Режим `base`, K = 5. Реплики — `контроль.jsonl`.", "",
             "| Кандидат | Раздел в первых пяти | Раздел на первом месте | Лучшая близость чужих реплик |", "|---|---|---|---|"]
    счёт = {}
    for имя, строки in итог.items():
        правила = [с for с in строки if с["вид"] == "правило"]
        чужие = [с for с in строки if с["вид"] == "чужой"]
        в_пяти = sum(с["место"] is not None for с in правила)
        счёт[имя] = в_пяти
        близости = ", ".join(f"{с['близость']:.3f}" for с in чужие)
        части.append(f"| `{имя}` | {в_пяти} из {len(правила)} | {sum(с['место'] == 1 for с in правила)} из {len(правила)} | {близости} |")
    выбран = max(КАНДИДАТЫ, key=lambda имя: (счёт[имя], имя == "base"))
    части += ["", f"**Выбран `{выбран}`**: правило выбора — больше реплик с разделом в первых пяти, при равенстве `base`.", "",
              "## По репликам", "", "Место нужного раздела в выдаче; прочерк — в первых пяти его нет. В скобках — раздел на первом месте.", "",
              "| Реплика | " + " | ".join(f"`{имя}`" for имя in итог) + " |", "|---|" + "---|" * len(итог)]
    for номер in range(25):
        ячейки = []
        for строки in итог.values():
            с = строки[номер]
            место = "чужая" if с["вид"] == "чужой" else (str(с["место"]) if с["место"] else "—")
            ячейки.append(f"{место} ({с['первый']}, {с['близость']:.3f})")
        части.append(f"| q{итог['base'][номер]['n']:02d} | " + " | ".join(ячейки) + " |")
    return "\n".join(части) + "\n"


def главная() -> None:
    разбор = argparse.ArgumentParser(prog="поиск")
    разбор.add_argument("--сверить", action="store_true")
    разбор.add_argument("--out", type=Path)
    доводы = разбор.parse_args()
    if доводы.сверить:
        sys.exit(1 if сверить() else 0)
    os.environ["RAG_REWRITE_MODEL"] = МОДЕЛЬ_ПЕРЕПИСЫВАНИЯ
    текст = отчёт(замер())
    if доводы.out:
        доводы.out.write_text(текст, "utf-8")
        print(f"записано: {доводы.out}")
    else:
        print(текст)


if __name__ == "__main__":
    главная()
