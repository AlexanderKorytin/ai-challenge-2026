import json

import pytest

from calories.measure import НаборНегоден, замерить, показать

from conftest import блюдо, служба


def набор(tmp_path, *строки):
    путь = tmp_path / "контроль.jsonl"
    путь.write_text("\n".join(json.dumps(с, ensure_ascii=False) for с in строки) + "\n", encoding="utf-8")
    return путь


def test_три_числа_итога(tmp_path):
    путь = набор(
        tmp_path,
        {"блюдо": "а", "ккал_100": 100, "ги": 50},
        {"блюдо": "б", "ккал_100": 200, "ги": 80},
    )
    клиент = служба(блюдо(ккал_100=110, ги=60), блюдо(ккал_100=150, ги=75))
    итог = замерить(путь, клиент=клиент)
    assert итог.ошибка_ккал == pytest.approx((10 + 25) / 2)
    assert итог.ошибка_ги == pytest.approx((10 + 5) / 2)
    assert итог.разряд_верен == 0.5  # «а»: низкий → средний; «б»: высокий → высокий
    assert "низкий → средний" in показать(итог)


def test_блюдо_без_оценки_не_входит_в_средние(tmp_path):
    путь = набор(
        tmp_path,
        {"блюдо": "а", "ккал_100": 100, "ги": 50},
        {"блюдо": "б", "ккал_100": 100, "ги": 50},
        {"блюдо": "в", "ккал_100": 100, "ги": 50},
    )
    клиент = служба(блюдо(ккал_100=100, ги=50), блюдо(еда=False), блюдо(ккал_100=5000))
    итог = замерить(путь, клиент=клиент)
    assert (итог.блюд, итог.без_оценки) == (3, 2)
    assert итог.ошибка_ккал == 0 and итог.ошибка_ги == 0 and итог.разряд_верен == 1
    текст = показать(итог)
    assert "без оценки: не еда" in текст and "5000" in текст


def test_пустой_итог_без_средних(tmp_path):
    итог = замерить(набор(tmp_path, {"блюдо": "а", "ккал_100": 100, "ги": 50}), клиент=служба(блюдо(еда=False)))
    assert итог.ошибка_ккал is None
    assert "Средняя" not in показать(итог)


@pytest.mark.parametrize("плохая", [
    "не json",
    '{"блюдо": "б", "ги": 50}',
    '{"блюдо": "б", "ккал_100": 0, "ги": 50}',
    '{"блюдо": "б", "ккал_100": "сто", "ги": 50}',
    '{"блюдо": "", "ккал_100": 100, "ги": 50}',
])
def test_негодная_строка_набора_названа_до_первого_запроса(tmp_path, плохая):
    путь = tmp_path / "контроль.jsonl"
    путь.write_text('{"блюдо": "а", "ккал_100": 100, "ги": 50}\n' + плохая + "\n", encoding="utf-8")
    запросы = []
    with pytest.raises(НаборНегоден, match="строка 2"):
        замерить(путь, клиент=служба(блюдо(), блюдо(), запросы=запросы))
    assert запросы == []


def test_нет_файла_и_пустой_набор(tmp_path):
    with pytest.raises(НаборНегоден):
        замерить(tmp_path / "нет.jsonl")
    (tmp_path / "пусто.jsonl").write_text("\n", encoding="utf-8")
    with pytest.raises(НаборНегоден):
        замерить(tmp_path / "пусто.jsonl")
