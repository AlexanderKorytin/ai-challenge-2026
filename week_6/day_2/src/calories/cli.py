"""Команда `калории`: разбор доводов, печать ответа, разговор."""

import argparse
import re
import sys

from . import ollama
from .core import Блюдо, оценить, подобрать
from .measure import НаборНегоден, замерить, показать
from .ollama import МоделиНет, ОтветНегоден, СлужбаНедоступна

ОГОВОРКА = "Числа назвала местная модель. Не для врачебных решений."
_ЧИСЛО = re.compile(r"(\d+(?:[.,]\d+)?)\s*(?:ккал)?", re.IGNORECASE)


def _прямой(блюдо: Блюдо) -> str:
    название = блюдо.название[:1].upper() + блюдо.название[1:]
    return "\n".join([
        f"{название} — оценка модели",
        f"  калорийность          {блюдо.ккал_100:.0f} ккал на 100 г",
        f"  порция                {блюдо.порция_г:.0f} г → {блюдо.ккал_порции:.0f} ккал",
        f"  гликемический индекс  {блюдо.ги:.0f} ({блюдо.разряд})",
        ОГОВОРКА,
    ])


def _обратный(ккал: float, блюда: list[Блюдо], просили: int) -> str:
    ширина = max(len(б.название) for б in блюда)
    вывод = [f"Блюда с порцией около {ккал:g} ккал — оценка модели"]
    for б in блюда:
        вывод.append(
            f"  {б.название:<{ширина}}  {б.порция_г:>4.0f} г  {б.ккал_порции:>5.0f} ккал "
            f"({б.ккал_порции - ккал:+.0f})  ГИ {б.ги:.0f} ({б.разряд})"
        )
    if len(блюда) < просили:
        вывод.append(f"Годных блюд модель назвала меньше просимого: {len(блюда)} из {просили}.")
    вывод.append(ОГОВОРКА)
    return "\n".join(вывод)


def _ход(сделано: int, всего: int) -> None:
    """Строка хода подбора; только в терминале, чтобы не попадать в перенаправленный вывод."""
    if not sys.stderr.isatty():
        return
    текст = f"Оцениваю блюда: {сделано} из {всего}"
    sys.stderr.write("\r" + (" " * len(текст) + "\r" if сделано == всего else текст))
    sys.stderr.flush()


def ответить(строка: str, блюд: int) -> str:
    """Строка из одного числа — подбор блюд, любая другая — оценка блюда."""
    строка = строка.strip()
    if not строка:
        return "Назови блюдо или число килокалорий."
    if число := _ЧИСЛО.fullmatch(строка):
        ккал = float(число.group(1).replace(",", "."))
        if ккал <= 0:
            return "Число килокалорий должно быть больше нуля."
        return _обратный(ккал, подобрать(ккал, блюд, ход=_ход), блюд)
    блюдо = оценить(строка)
    if блюдо is None:
        return f"Не знаю такого блюда: {строка}"
    return _прямой(блюдо)


def _отказ(ошибка: Exception) -> str:
    if isinstance(ошибка, СлужбаНедоступна):
        return f"Служба Ollama не отвечает по адресу {ollama.адрес()} ({ошибка}). Запусти: ollama serve"
    if isinstance(ошибка, МоделиНет):
        return (
            f"Служба по адресу {ollama.адрес()} ответила 404 на модель {ollama.модель()} ({ошибка}). "
            "Список моделей: ollama list. Другую модель называет переменная CALORIES_MODEL."
        )
    if isinstance(ошибка, НаборНегоден):
        return f"Контрольный набор не принят: {ошибка}"
    return f"Ответ модели не принят: {ошибка}"


_ОТКАЗЫ = (СлужбаНедоступна, МоделиНет, ОтветНегоден, НаборНегоден)


def _предупредить_о_чужом_адресе() -> None:
    try:
        if not ollama.местный():
            print(
                f"Внимание: OLLAMA_HOST указывает на другую машину ({ollama.адрес()}). "
                "Запросы уйдут туда, а не местной службе.",
                file=sys.stderr,
            )
    except СлужбаНедоступна:
        pass  # негодный адрес назовёт первый же запрос


def _разговор(блюд: int) -> int:
    print("Назови блюдо или число килокалорий. Пустая строка завершает.")
    while True:
        try:
            строка = input("> ").strip()
        except (EOFError, KeyboardInterrupt):
            print()
            return 0
        if not строка:
            return 0
        try:
            print(ответить(строка, блюд))
        except _ОТКАЗЫ as ошибка:
            print(_отказ(ошибка))
        except KeyboardInterrupt:
            print("\nПрервано.")


def main(argv: list[str] | None = None) -> int:
    разбор = argparse.ArgumentParser(
        prog="калории",
        description="Калорийность и гликемический индекс блюда от местной модели Ollama.",
    )
    разбор.add_argument("запрос", nargs="*", help="название блюда либо число килокалорий; без довода — разговор")
    разбор.add_argument("--блюд", type=int, default=5, help="сколько блюд назвать на число килокалорий (умолчание 5)")
    разбор.add_argument("--замер", nargs="?", const="контроль.jsonl", metavar="ФАЙЛ",
                        help="сверить модель с контрольным набором (умолчание контроль.jsonl)")
    доводы = разбор.parse_args(argv)
    if доводы.блюд < 1:
        разбор.error("--блюд: нужно целое число от 1")
    if доводы.замер is not None and (доводы.запрос or not доводы.замер.strip()):
        разбор.error("--замер: назови файл набора через знак равенства (--замер=ФАЙЛ) и не называй блюдо")
    _предупредить_о_чужом_адресе()
    try:
        if доводы.замер is not None:
            print(показать(замерить(доводы.замер)))
        elif доводы.запрос:
            print(ответить(" ".join(доводы.запрос), доводы.блюд))
        else:
            return _разговор(доводы.блюд)
    except _ОТКАЗЫ as ошибка:
        print(_отказ(ошибка), file=sys.stderr)
        return 1
    except KeyboardInterrupt:
        print("\nПрервано.", file=sys.stderr)
        return 130
    return 0


if __name__ == "__main__":
    sys.exit(main())
