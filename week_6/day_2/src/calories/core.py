"""Два направления утилиты: блюдо → числа и килокалории → блюда."""

import math
from dataclasses import dataclass

from .ollama import ОтветНегоден, спросить

# Столько даёт чистый жир: выше калорийность на 100 г не бывает.
ПРЕДЕЛ_ККАЛ_100 = 900

_ЧИСЛА = {
    "ккал_100": {"type": "number"},
    "порция_г": {"type": "number"},
    "ги": {"type": "number"},
}

СХЕМА_БЛЮДА = {
    "type": "object",
    "properties": {"еда": {"type": "boolean"}, **_ЧИСЛА},
    "required": ["еда", "ккал_100", "порция_г", "ги"],
}

СИСТЕМА_БЛЮДА = (
    "Ты справочник по питанию. Назови калорийность блюда на 100 г (ккал_100), "
    "вес обычной порции в граммах (порция_г) и гликемический индекс (ги). "
    "Если названное не еда и не напиток, поставь еда=false. Ответ в JSON."
)

СИСТЕМА_ПОДБОРА = (
    "Ты справочник по питанию. Человек называет число килокалорий. Назови блюда, обычная "
    "порция которых даёт примерно столько. Блюда разные: суп, второе, каша, салат, выпечка, "
    "десерт, фрукты, напитки. Называй только названия, коротко, без веса и пояснений. "
    "Ответ в JSON."
)

# Модель называет имён втрое больше просимого: программе нужен выбор, а числа блюда
# модель называет отдельным запросом, который цели не знает и под неё не подгоняет.
ЗАПАС_ИМЁН = 3


def разряд(ги: float) -> str:
    if ги <= 55:
        return "низкий"
    if ги < 70:
        return "средний"
    return "высокий"


@dataclass(frozen=True)
class Блюдо:
    название: str
    ккал_100: float
    порция_г: float
    ги: float

    @property
    def ккал_порции(self) -> float:
        return self.ккал_100 * self.порция_г / 100

    @property
    def разряд(self) -> str:
        return разряд(self.ги)


def _число(запись: dict, поле: str) -> float:
    значение = запись.get(поле)
    if isinstance(значение, bool) or not isinstance(значение, (int, float)) or not math.isfinite(значение):
        raise ОтветНегоден(f"поле «{поле}» не число: {значение!r}")
    return float(значение)


def _блюдо(название: str, запись: dict) -> Блюдо:
    блюдо = Блюдо(название, _число(запись, "ккал_100"), _число(запись, "порция_г"), _число(запись, "ги"))
    if not 0 <= блюдо.ккал_100 <= ПРЕДЕЛ_ККАЛ_100:
        raise ОтветНегоден(
            f"«{название}»: калорийность {блюдо.ккал_100:g} ккал на 100 г невозможна "
            f"(допустимо от 0 до {ПРЕДЕЛ_ККАЛ_100})"
        )
    if блюдо.порция_г <= 0:
        raise ОтветНегоден(f"«{название}»: вес порции {блюдо.порция_г:g} г невозможен")
    if блюдо.ги < 0:
        raise ОтветНегоден(f"«{название}»: гликемический индекс {блюдо.ги:g} невозможен")
    return блюдо


def оценить(название: str, **kw) -> Блюдо | None:
    """Числа блюда от модели. None — модель сказала, что это не еда."""
    ответ = спросить(СИСТЕМА_БЛЮДА, f"Блюдо: {название}", СХЕМА_БЛЮДА, **kw)
    еда = ответ.get("еда")
    if not isinstance(еда, bool):
        raise ОтветНегоден(f"«{название}»: в ответе нет признака «еда»: {ответ!r}")
    if not еда:
        return None
    return _блюдо(название, ответ)


def подобрать(ккал: float, число: int, *, ход=None, **kw) -> list[Блюдо]:
    """Блюда с порцией около заданных килокалорий, ближайшие первыми.

    Запросов 1 + число * ЗАПАС_ИМЁН: имена блюд, затем `оценить` на каждое имя.
    `ход(сделано, всего)` зовётся перед каждой оценкой и после последней.
    """
    имён = число * ЗАПАС_ИМЁН
    схема = {
        "type": "object",
        "properties": {
            "блюда": {"type": "array", "minItems": имён, "maxItems": имён, "items": {"type": "string"}}
        },
        "required": ["блюда"],
    }
    ответ = спросить(СИСТЕМА_ПОДБОРА, f"Килокалорий в порции: {ккал:g}. Блюд: {имён}.", схема, **kw)
    записи = ответ.get("блюда")
    if not isinstance(записи, list):
        raise ОтветНегоден("модель не назвала блюд")
    имена = []
    for запись in записи:
        имя = запись.strip() if isinstance(запись, str) else ""
        if not имя:
            raise ОтветНегоден(f"блюдо без названия: {запись!r}")
        if имя.lower() not in {и.lower() for и in имена}:
            имена.append(имя)
    if not имена:
        raise ОтветНегоден("модель не назвала ни одного блюда")
    блюда = []
    for номер, имя in enumerate(имена):
        if ход:
            ход(номер, len(имена))
        if (блюдо := оценить(имя, **kw)) is not None:
            блюда.append(блюдо)
    if ход:
        ход(len(имена), len(имена))
    if not блюда:
        raise ОтветНегоден("модель не признала едой ни одно из названных ею блюд")
    return sorted(блюда, key=lambda б: abs(б.ккал_порции - ккал))[:число]
