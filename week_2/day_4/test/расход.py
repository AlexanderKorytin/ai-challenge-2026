"""Расход по ходам одного разговора: до сжатия и после.

Всё внутри ОДНОГО диалога. Вход растёт с каждым ходом, потому что вся история уходит в
запрос заново; на сжатии старые пары заменяются выжимкой, и вход падает. Это и есть
«расход токенов до/после» из задания — до сжатия и после него, в одном разговоре.

Деньги считаются здесь, действующей таблицей тарифов: в записях журнала их нет намеренно —
тариф живёт на стороне поставщика и протухнет, а токены останутся токенами.

Запуск: uv run расход.py [файл журнала]
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

from myharness import tokens

ЖУРНАЛ = Path(sys.argv[1] if len(sys.argv) > 1 else "myharness-journal.jsonl")


def записи() -> list[dict]:
    if not ЖУРНАЛ.exists():
        sys.exit(f"журнала нет: {ЖУРНАЛ}")
    return [
        json.loads(строка)
        for строка in ЖУРНАЛ.read_text(encoding="utf-8").splitlines()
        if строка.strip()
    ]


def главное() -> None:
    все = записи()
    разговор = [з for з in все if not з.get("agent")]
    служебные = [з for з in все if з.get("agent") == "сжиматель"]
    if not разговор:
        sys.exit("в журнале нет ходов разговора")

    print(f"\n{'═' * 78}")
    print(f"Разговор: {len(разговор)} ходов, заходов сжимателя {len(служебные)}\n")
    print(f"{'ход':>4} {'вход':>9} {'память':>9} {'выход':>7} {'сжато':>6} {'забыто':>7} {'с':>6}")

    деньги = 0.0
    предыдущий_вход = None
    for запись in разговор:
        расход = tokens.normalize(запись.get("usage") or {})
        деньги += tokens.price(запись.get("usage") or {}, запись.get("model", "")) or 0.0
        вход = расход["prompt_tokens"]
        сжато = запись.get("compacted_pairs") or ""
        забыто = запись.get("forgotten_pairs") or ""
        print(
            f"{запись.get('index', 0):>4} {вход:>9} {запись.get('history_tokens', 0):>9} "
            f"{расход['completion_tokens']:>7} {сжато:>6} {забыто:>7} "
            f"{запись.get('elapsed_ms', 0) / 1000:>6.1f}"
        )
        # Падение входа посреди растущего разговора бывает ровно по одной причине — сжатие.
        # Отмечаем его прямо в таблице: иначе цифру приходится искать глазами.
        if предыдущий_вход is not None and вход < предыдущий_вход:
            сжатие = запись.get("compact") or {}
            print(
                f"     └ ВХОД УПАЛ на {предыдущий_вход - вход} токенов"
                + (f"; за выжимкой {сжатие['покрыто_пар']} пар, пересжатий {сжатие.get('поколение', '?')}" if сжатие else "")
            )
        предыдущий_вход = вход

    for запись in служебные:
        расход = tokens.normalize(запись.get("usage") or {})
        деньги += tokens.price(запись.get("usage") or {}, запись.get("model", "")) or 0.0
        print(f"     · заход сжимателя: вход {расход['prompt_tokens']}, выход {расход['completion_tokens']}")

    входы = [tokens.normalize(з.get("usage") or {})["prompt_tokens"] for з in разговор]
    print(f"\n  наибольший вход за ход: {max(входы)}")
    print(f"  вход на последнем ходу: {входы[-1]}")
    print(f"  деньги за весь разговор, включая сжиматель: ${деньги:.4f}\n")


if __name__ == "__main__":
    главное()
