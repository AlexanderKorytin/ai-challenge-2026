"""Разбор ответа на 15-м ходу: сколько из четырёх соглашений модель соблюла.

Соглашения задавались на ходах 1–4 и больше в разговоре не упоминались. К пятнадцатому ходу
профиль «сжатие» держит их только пересказом, профиль «полная» — дословно. Ответ на 15-м
проверяется механически, а не на глаз: мера — число от 0 до 4.

Запуск: uv run разбор.py [файл журнала]
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ЖУРНАЛ = Path(sys.argv[1] if len(sys.argv) > 1 else "myharness-journal.jsonl")

# Четыре соглашения, каждое проверяется своим образцом по РАЗОБРАННОМУ объекту, а не по тексту:
# в тексте «ST-123456» нашлось бы и в пояснении, которого мы не просили.
СОГЛАШЕНИЯ = {
    "имена полей с приставкой st_": lambda о: bool(о)
    and all(re.fullmatch(r"st_[a-zа-яё0-9_]+", к) for к in о),
    "время со смещением +03:00": lambda о: any(
        isinstance(з, str) and з.strip().endswith("+03:00") for з in о.values()
    ),
    "сумма целым числом": lambda о: any(
        isinstance(з, int) and not isinstance(з, bool)
        for к, з in о.items()
        if any(м in к for м in ("сум", "тенге", "amount", "price", "cost", "kzt", "tng"))
    ),
    "идентификатор ST- и шесть цифр": lambda о: any(
        isinstance(з, str) and re.fullmatch(r"ST-\d{6}", з.strip()) for з in о.values()
    ),
}


def выемка_объекта(текст: str) -> dict | None:
    """Достать объект JSON из ответа, даже если модель обернула его пояснением.

    Терпимость здесь не поблажка: провалить прогон из-за фразы «вот пример:» значило бы
    приписать сжатию поражение, к которому оно отношения не имеет."""
    if not текст:
        return None
    начало, конец = текст.find("{"), текст.rfind("}")
    if начало < 0 or конец <= начало:
        return None
    try:
        разобранное = json.loads(текст[начало : конец + 1])
    except (ValueError, RecursionError):
        return None
    return разобранное if isinstance(разобранное, dict) else None


def плоские_ключи(узел, ключи: list[str] | None = None) -> list[str]:
    """Все имена полей со всей глубины: соглашение об именах действует везде.

    В списки заходим наравне со словарями. Первая версия этого не делала, и разбор промахнулся
    на живом прогоне: модель разложила часть заявки по массивам, идентификатор оказался внутри,
    и проверка объявила соглашение нарушенным там, где оно было соблюдено."""
    ключи = ключи if ключи is not None else []
    if isinstance(узел, dict):
        for имя, значение in узел.items():
            ключи.append(имя)
            плоские_ключи(значение, ключи)
    elif isinstance(узел, list):
        for элемент in узел:
            плоские_ключи(элемент, ключи)
    return ключи


def плоские_значения(узел, плоско: dict | None = None, счёт: list | None = None) -> dict:
    """Все значения со всей глубины, включая лежащие внутри списков.

    Имена в ключах могут повторяться на разных уровнях, поэтому неповторяющееся имя собираем
    сами: образцам важны сами значения, а не то, как поле называлось."""
    плоско = плоско if плоско is not None else {}
    счёт = счёт if счёт is not None else [0]
    if isinstance(узел, dict):
        for имя, значение in узел.items():
            if isinstance(значение, (dict, list)):
                плоские_значения(значение, плоско, счёт)
            else:
                счёт[0] += 1
                плоско[f"{имя}#{счёт[0]}"] = значение
    elif isinstance(узел, list):
        for элемент in узел:
            плоские_значения(элемент, плоско, счёт)
    return плоско


# Маркеры соглашений: если они всплыли в ответах ходов 5–14, значит модель повторила
# соглашение сама, окно его не потеряло и обе ветки ответят верно. Такой прогон загрязнён и
# в выводы не идёт — об этом честнее сказать, чем предъявить красивое число.
МАРКЕРЫ = ("st_", "+03:00", "ST-", "тенге", "KZT")


def записи() -> list[dict]:
    if not ЖУРНАЛ.exists():
        sys.exit(f"журнала нет: {ЖУРНАЛ}")
    строки = []
    for строка in ЖУРНАЛ.read_text(encoding="utf-8").splitlines():
        if строка.strip():
            запись = json.loads(строка)
            # Заходы служебных агентов (архивариус, сжиматель) — не ходы разговора.
            if not запись.get("agent"):
                строки.append(запись)
    return строки


def разобрать(имя: str, прогон: list[dict]) -> None:
    print(f"\n{'═' * 78}\n{имя}: {len(прогон)} ходов\n")
    if len(прогон) < 15:
        print(f"  прогон неполный — ходов {len(прогон)}, нужно 15")
        return

    протечка = [
        (н, м)
        for н, запись in enumerate(прогон[4:14], start=5)
        for м in МАРКЕРЫ
        if м in (запись.get("response") or "")
    ]
    if протечка:
        print("  ЗАГРЯЗНЁН: соглашения всплыли в середине разговора —", протечка)
        print("  вывод по качеству делать нельзя: окно их не потеряло\n")

    объект = выемка_объекта(прогон[14].get("response") or "")
    if объект is None:
        print("  на 15-м ходу объект JSON не разобран — ответ:", (прогон[14].get("response") or "")[:120])
        return

    ключи = плоские_ключи(объект)
    значения = плоские_значения(объект)
    соблюдено = 0
    for название, образец in СОГЛАШЕНИЯ.items():
        предмет = ключи if "имена полей" in название else значения
        держится = bool(образец(предмет))
        соблюдено += держится
        print(f"  [{'ДА ' if держится else 'НЕТ'}] {название}")
    print(f"\n  соблюдено соглашений: {соблюдено} из 4")


def главное() -> None:
    все = записи()
    прогоны: dict[str, list[dict]] = {}
    for запись in все:
        имя = (запись.get("profile") or {}).get("name") or "без профиля"
        прогоны.setdefault(имя, []).append(запись)
    for имя, прогон in прогоны.items():
        разобрать(имя, прогон)


if __name__ == "__main__":
    главное()
