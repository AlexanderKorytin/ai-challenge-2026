"""Собрать документ «на грани окна»: первый запрос проходит, диалог упирается в потолок.

Задание просит показать диалог, превышающий предел модели. Отдельный заведомо огромный
документ показал бы только отказ на входе — а это не диалог, это неудачный запрос. Интереснее
и честнее другое: документ подобран так, что ПЕРВЫЙ вопрос проходит, а каждый следующий обмен
съедает остаток окна, пока разговор в него не упрётся. Тогда видно ровно то, что просят: как
токены влияют на поведение агента по ходу разговора.

Целимся в токены, а не в мегабайты: русский текст весит около 1.85 байта на знак и около 3.2
знака на токен, поэтому «файл на 3.7 МБ» — это 664 тысячи токенов, а не миллион.

Числа взяты не из документации, а из ответов сервера (проверено 2026-09-09):

* окно — 1 048 576 токенов, а не «1M»: сервер называет его сам в тексте отказа;
* `max_tokens` считается ВНУТРИ окна — в отказе сервер складывает сообщения и запрошенный ответ;
* запрос на 1 026 275 токенов сервер принял, ответил и списал деньги, то есть молча ничего
  не обрезал: до потолка он честно читает всё.

Блоки пронумерованы, чтобы обрезку начала — если она где-то случится — было видно по ответу
на вопрос «какой номер у первого блока».

Запуск: uv run собрать_стог.py
"""

from pathlib import Path

from myharness import tokens

ИГОЛКА = (
    "СЕКРЕТНЫЙ ФАКТ: любимое блюдо главного инженера DeepSeek — "
    "жареные пельмени с чесночным соусом."
)
ГЛУБИНА = 0.85  # где прячем иголку: ближе к концу, там модели ошибаются чаще
ЗДЕСЬ = Path(__file__).parent

MAX_TOKENS_ПРОФИЛЯ = 2000  # столько профиль просит на ответ, и они тоже внутри окна
ОБЁРТКА_И_ВОПРОС = 200  # надбавка разговора плюс сам вопрос, с запасом
# Запас, с которым проходит ПЕРВЫЙ запрос. Он же — то, что съедят следующие обмены: пара
# «вопрос — ответ» весит около сотни токенов, значит на втором-третьем вопросе разговор
# упрётся в потолок. Меньше запас — переполнение раньше, но выше риск не пройти с первого раза.
ЗАПАС = 400

ЦЕЛЬ = tokens.CONTEXT_WINDOW - MAX_TOKENS_ПРОФИЛЯ - ОБЁРТКА_И_ВОПРОС - ЗАПАС


def блок(номер: int) -> str:
    return (
        f"Блок {номер:06d}. Космический корабль движется по заданной траектории. "
        "Бортовые системы функционируют в штатном режиме. Давление в норме. "
    )


def собрать(сколько: int) -> tuple[str, int]:
    """Текст из стольких-то блоков с иголкой на заданной глубине."""
    место = int(сколько * ГЛУБИНА)
    куски = [блок(номер) for номер in range(1, сколько + 1)]
    куски.insert(место, ИГОЛКА + " ")
    return "".join(куски), место


# Считать число блоков делением цели на вес первого блока нельзя: номера блоков тоже
# токенизируются, и «000001» с «023772» весят по-разному. Промах выходит около двух
# процентов — это двадцать тысяч токенов запаса вместо четырёхсот, то есть переполнения
# в разговоре не случилось бы вовсе. Поэтому собираем, взвешиваем и поправляем число блоков,
# пока не попадём в цель с точностью до сотни токенов.
сколько = ЦЕЛЬ // tokens.count_text(блок(1))
for попытка in range(6):
    текст, место = собрать(сколько)
    вес = tokens.count_text(текст)
    промах = ЦЕЛЬ - вес
    if abs(промах) <= 100:
        break
    сколько += int(промах / (вес / сколько))

путь = ЗДЕСЬ / "стог.txt"
путь.write_text(текст, encoding="utf-8")
первый_запрос = вес + ОБЁРТКА_И_ВОПРОС + MAX_TOKENS_ПРОФИЛЯ

print(f"стог.txt: {вес:,} токенов · {сколько:,} блоков · иголка после блока {место:,} "
      f"(подобрано за {попытка + 1} попыток)")
print(f"           {путь.stat().st_size / 1024 / 1024:.2f} МБ")
print(f"первый запрос вместе с ответом: {первый_запрос:,} из {tokens.CONTEXT_WINDOW:,} — "
      f"запас {tokens.CONTEXT_WINDOW - первый_запрос:,} токенов")
print("этого запаса хватает на один-два обмена: дальше разговор упрётся в потолок")
