"""Собрать два стога с иголкой: один почти во всё окно модели, второй — за окном.

Зачем два. Отказ сервера показывает только, что граница есть. Он не показывает, как ведёт
себя разговор У границы: сколько стоит, сколько ждать и находит ли модель нужную строку,
когда вокруг неё миллион токенов мусора. Поэтому стога два: «влезает» и «не влезает».

Целимся в ТОКЕНЫ, а не в мегабайты. Русский текст в UTF-8 весит около 1.85 байта на знак и
около 3.2 знака на токен, поэтому «файл на 3.7 МБ» — это 664 тысячи токенов, а вовсе не
миллион: по размеру файла о переполнении судить нельзя. Считаем тем же словарём, которым
harness считает разговор.

Блоки пронумерованы не для красоты. Если DeepSeek на переполнении не откажет, а молча
обрежет начало запроса, это надо увидеть: у модели можно спросить номер первого блока, и
ответ покажет, с какого места она на самом деле читала.
"""

from pathlib import Path

from myharness import tokens

ИГОЛКА = (
    "СЕКРЕТНЫЙ ФАКТ: любимое блюдо главного инженера DeepSeek — "
    "жареные пельмени с чесночным соусом."
)
ГЛУБИНА = 0.85  # где прячем иголку: ближе к концу, там модели ошибаются чаще
ЗДЕСЬ = Path(__file__).parent

# Сколько токенов должно быть в каждом стоге. Первый — с запасом под вопрос и ответ, чтобы
# запрос прошёл. Второй — заведомо за окном: пятьдесят тысяч токенов сверх предела, чтобы
# отказ был не пограничным случаем, а однозначным.
СТОГА = {
    "стог_влезает.txt": 900_000,
    "стог_за_окном.txt": tokens.CONTEXT_WINDOW + 50_000,
}


def блок(номер: int) -> str:
    return (
        f"Блок {номер:06d}. Космический корабль движется по заданной траектории. "
        "Бортовые системы функционируют в штатном режиме. Давление в норме. "
    )


def собрать(цель: int) -> tuple[str, int, int]:
    """Стог ровно нужного веса в токенах. Возвращает текст, число блоков и место иголки."""
    вес_блока = tokens.count_text(блок(1))
    сколько = цель // вес_блока
    место = int(сколько * ГЛУБИНА)
    куски = [блок(номер) for номер in range(1, сколько + 1)]
    куски.insert(место, ИГОЛКА + " ")
    return "".join(куски), сколько, место


for имя, цель in СТОГА.items():
    текст, блоков, место = собрать(цель)
    путь = ЗДЕСЬ / имя
    путь.write_text(текст, encoding="utf-8")
    весит = tokens.count_text(текст)
    print(
        f"{имя}: {весит:>9,} токенов · {блоков:>6,} блоков · "
        f"иголка после блока {место:,} · {путь.stat().st_size / 1024 / 1024:.2f} МБ"
    )
