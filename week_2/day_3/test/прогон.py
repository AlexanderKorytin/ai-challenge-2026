"""Три диалога на живом API: короткий, длинный и переполненный.

Зачем скрипт, а не разговор руками: сравнивать надо одинаковое. Тридцать вопросов, заданных
человеком, различались бы длиной и темой, и рост расхода пришлось бы отделять от разброса
вопросов. Здесь вопросы одинаковой длины и одного рода, поэтому в журнале видно ровно то, что
мы хотим показать, — как растёт цена от накопленной истории, а не от самих вопросов.

Интерфейс не поднимается: собеседник (`Agent`) от него не зависит, и это единственная проверка
той независимости делом, а не декларацией. Журнал пишется тот же самый, что у разговора с
экрана, — его потом читает `таблица.py`.

Запуск: uv run прогон.py
"""

from __future__ import annotations

import asyncio
import os
import sys
from pathlib import Path
from uuid import uuid4

ЗДЕСЬ = Path(__file__).parent
os.environ.setdefault("MYHARNESS_JOURNAL", str(ЗДЕСЬ / "myharness-journal.jsonl"))

from myharness import config, profiles, tokens  # noqa: E402
from myharness.agent import Agent  # noqa: E402
from myharness.api import DeepSeekClient  # noqa: E402

МОДЕЛЬ = "deepseek-v4-flash"

# Короткие ответы — не экономия, а условие опыта: нам нужен рост ВХОДА от накопленной истории,
# а разброс длины ответов его бы замаскировал.
ИНСТРУКЦИЯ = "Отвечай ровно одним коротким предложением, без вступлений и пояснений."

ВОПРОС_ПРО_ИГОЛКУ = (
    "Внимательно прочитай этот документ и ответь: какое любимое блюдо у главного инженера "
    "DeepSeek? Если информации в тексте нет, так и скажи."
)

ВОПРОСЫ = [
    "Назови одно небесное тело и одно его свойство.",
    "Назови другое небесное тело и одно его свойство.",
    "Назови третье небесное тело и одно его свойство.",
]


def профиль(**поля) -> profiles.Profile:
    """Собеседник для сценария: та же инструкция, свои поля сверх неё."""
    return profiles.Profile(name=поля.pop("имя"), system=ИНСТРУКЦИЯ, **поля)


async def диалог(клиент, имя: str, профиль_агента, вопросы: list[str]) -> Agent:
    """Один диалог подряд, одним собеседником: история копится от вопроса к вопросу."""
    прогон = uuid4().hex[:8]
    агент = Agent(имя, профиль_агента)
    print(f"\n── {имя}: {len(вопросы)} обменов, run_id {прогон}")
    for номер, вопрос in enumerate(вопросы, 1):
        обмен = await агент.exchange(клиент, МОДЕЛЬ, вопрос, agent=имя, run_id=прогон)
        расход = tokens.normalize(обмен.usage)
        цена = tokens.price(обмен.usage, МОДЕЛЬ)
        пометка = ""
        if обмен.dropped_pairs:
            пометка += f"  ← память обрезана на {обмен.dropped_pairs} пар"
        if обмен.over_budget:
            пометка += "  ← ушло сверх предела"
        if not обмен.ok:
            пометка += f"  ← {обмен.status}: {(обмен.error or '')[:60]}"
        print(
            f"  {номер:>2}  вход {расход['prompt_tokens']:>6}  "
            f"из кэша {расход['prompt_cache_hit_tokens']:>6}  "
            f"выход {расход['completion_tokens']:>5}  "
            f"рассуждения {расход['reasoning_tokens']:>5}  "
            f"Σ {агент.session_usage['total_tokens']:>7}  "
            f"{tokens.format_price(цена):>9}{пометка}"
        )
    return агент


async def main() -> None:
    # Без довода идут все три сценария; с именем — только он. Перезапускать длинный диалог
    # ради правки в третьем значило бы платить за то, что уже посчитано.
    только = sys.argv[1] if len(sys.argv) > 1 else ""
    ключ = config.load().api_key
    if not ключ:
        sys.exit("ключа DeepSeek нет — заполните ~/.config/myharness/config.json")
    клиент = DeepSeekClient(ключ)
    try:
        # 1. Короткий диалог: три обмена, история почти ничего не весит.
        if not только or только == "короткий":
            await диалог(клиент, "короткий", профиль(имя="короткий"), ВОПРОСЫ)

        # 2. Длинный: тридцать обменов теми же по длине вопросами. Вход растёт квадратично —
        # каждая новая пара уезжает в каждый следующий запрос заново.
        if not только or только == "длинный":
            длинные = [f"Назови небесное тело номер {n} и одно его свойство." for n in range(1, 31)]
            await диалог(клиент, "длинный", профиль(имя="длинный"), длинные)

        # 3. Переполнение своего предела. Число выбрано по замеру, а не на глаз: обёртка
        # запроса стоит 83 токена, инструкция и вопрос — ещё около тридцати, значит при
        # пределе в 250 на историю остаётся сотня с небольшим, то есть две-три пары. Первый
        # заход с пределом 900 не сработал вовсе: за десять коротких обменов вход дорос лишь
        # до 471, обрезка не понадобилась, и сценарий проверил не то, ради чего заведён.
        # 3. За окном модели. Свой предел (`/budget`) сегодня не показываем: задание просит
        # диалог, превышающий лимит МОДЕЛИ, а это другая поломка — не тихая потеря памяти,
        # а разговор, который не начинается вовсе. Стоит прогон ноль: отвергнутый на входе
        # запрос не тарифицируется.
        if not только or только == "за-окном":
            стог = (ЗДЕСЬ / "стог_за_окном.txt").read_text(encoding="utf-8")
            вес = tokens.count_messages(
                [{"role": "system", "content": стог}, {"role": "user", "content": ВОПРОС_ПРО_ИГОЛКУ}]
            )
            print(f"\n── за окном: один запрос весом {вес:,} токенов при окне {tokens.CONTEXT_WINDOW:,}")
            за_окном = profiles.Profile(name="за-окном", system=стог)
            обмен = await диалог(клиент, "за-окном", за_окном, [ВОПРОС_ПРО_ИГОЛКУ])
            последний = обмен.history()[-1]["content"] if обмен.history() else ""
            if последний:
                print("  СЕРВЕР ОТВЕТИЛ — значит запрос он не отверг, а обрезал сам:")
                print(f"  {последний[:300]}")
            else:
                print("  сервер запрос отверг — ответа нет, деньги не списаны")

    finally:
        await клиент.aclose()


asyncio.run(main())
