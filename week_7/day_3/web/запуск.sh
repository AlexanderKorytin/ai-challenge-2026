#!/bin/sh
# Учебный веб-чат поддержки на http://127.0.0.1:8790 — только этот компьютер: входа с паролем нет.
# Пути профилей, состояния, журнала и рабочих данных задаёт app.py, окружение их перекрывает.
ROOT="$(cd "$(dirname "$0")" && pwd)"
cd "$ROOT"
exec uv run --project "$ROOT" uvicorn app:app --host 127.0.0.1 --port 8790
