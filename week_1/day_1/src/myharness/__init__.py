"""Точка входа пакета — намеренно лёгкая.

Раньше здесь стояло `from .cli import main`, и это значило вот что: ЛЮБОЙ импорт вида
`import myharness.<что угодно>` сначала выполнял этот файл и втягивал весь `cli` вместе с
`prompt_toolkit`. Проверить агента в отрыве от интерфейса было нельзя — терминал приезжал
сам собой; завести режим, работающий без терминала, тоже нельзя было по той же причине.

Поэтому `cli` здесь не импортируется на уровне модуля. Сначала разбираются ключи (`args` —
только `argparse`), и лишь потом, уже зная режим, загружается то, что именно этому режиму
нужно.
"""

from __future__ import annotations

import sys

from . import args as args_mod

__all__ = ["main"]


def main() -> int:
    """Выбрать режим по ключам и запустить его. Код возврата уходит в оболочку."""
    parsed = args_mod.parse_args()

    if parsed.batch:
        # Честное состояние на сегодня, а не заглушка на будущее: модуль `batch` появится
        # следующим блоком работ, и тогда эта ветка станет его вызовом — с передачей
        # `parsed.batch` и `parsed.concurrency`. Пока режима нет, мы об этом прямо говорим
        # и возвращаем ненулевой код, чтобы вызывающий сценарий не принял отказ за успех.
        print("пакетный режим ещё не готов", file=sys.stderr)
        return 1

    # Интерфейс загружаем только здесь: до этой строки `prompt_toolkit` в памяти нет.
    from . import cli

    # Ключи уже разобраны — `cli` их не разбирает повторно, а получает готовыми.
    cli.main(parsed)
    return 0
