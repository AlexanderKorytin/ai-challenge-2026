#: Метка конца потока результатов. Отдельный объект, а не `None`: `None` — законное
#: значение внутри результата, и спутать их значило бы оборвать поток на полуслове.
КОНЕЦ = object()


# --- состояние приложения -----------------------------------------------------


class Состояние:
    """Клиент API и нумерация прогонов — то немногое, что живёт между запросами.

    Нумерация держится в памяти, а не вычитывается из журнала на каждое нажатие: пока
    прогон идёт, журнал ещё дописывается, и чтение посреди прогона выдало бы номера,
    которые уже заняты клетками в работе.

    Номер здесь один на весь опыт, а не свой у каждой клетки, потому что `run.run_all`
    нумерует все клетки одним числом: строка таблицы — это один прогон, взятый сразу по
    четырём клеткам. Отдельные счётчики позволили бы столбцам разъехаться, и строка
    перестала бы означать один момент опыта.

    Здесь же признак «опыт идёт»: одновременных прогонов быть не должно, и следить за этим
    обязан сервер, а не кнопка на странице. Кнопка защищает одну вкладку, а платит за все
    сервер: вторая вкладка, обновление страницы посреди прогона или переподключение
    браузера дают второе обращение к `/run` мимо любой блокировки кнопки.
    """

    def __init__(self) -> None:
        self.клиент: api.DeepSeekClient | None = None
        # От ключа хранится только отпечаток: по нему видно, что ключ сменился (человек
        # выполнил `/auth`, пока сервер поднят), а сам секрет в памяти приложения не лежит.
        self.отпечаток_ключа: str | None = None
        self.замок = asyncio.Lock()
        # Отдельный замок под признак прогона: у него своя область ответственности, и
        # общий с клиентом рано или поздно свёлся бы к взятию одного замка под другим.
        self.замок_прогона = asyncio.Lock()
        self.опыт_идёт: bool = False
        self.занято: int = 0

    def прочитать_собранное(self) -> None:
        """Наибольший занятый номер прогона из журнала — начало нумерации.

        Берётся максимум по всем клеткам: если прошлый опыт оборвался на середине строки,
        часть клеток уже успела занять номер, и продолжать надо за ним, а не за отставшими.
        """
        self.занято = max(run.collected_repeats().values(), default=0)

    def занять(self, count: int) -> int:
        """Отводит `count` подряд идущих номеров прогонов и возвращает первый из них.

        Номера отводятся до начала прогона, а не по его окончании: два одновременных
        нажатия кнопки не должны получить один и тот же номер. Отведённые номера не
        возвращаются даже при сбое — провалившаяся клетка тоже занимает своё место в
        журнале, и повторное использование её номера смешало бы две разные попытки под
        одним `run_key`.
        """
        начало = self.занято + 1
        self.занято = начало + count - 1
        return начало

    async def начать_прогон(self) -> bool:
        """Занимает право на прогон. `False` означает «опыт уже идёт, второму места нет».

        Проверка и установка признака идут под замком и без единого `await` между собой,
        поэтому два обращения к `/run`, пришедшие в один момент, не могут оба увидеть
        свободно.

        Признак нужен именно на сервере. На странице кнопка блокируется на время прогона,
        но эта защита действует ровно в той вкладке, где нажали: открытая вторая вкладка,
        обновление страницы посреди прогона и переподключение браузера дают новое
        обращение к `/run` с чистой кнопкой. Деньги при этом платит сервер, и порядок
        запросов держит тоже он — значит и запрет принадлежит ему.

        Цена пропущенного второго прогона не только в деньгах. `run.run_all` ведёт клетки
        строго по одной затем, чтобы запросы не дрались за очередь у провайдера; два
        обхода разом это ломают, времена вырастают у обоих и ложатся в медианы как
        свойство модели. По данным такую порчу не отличить от правды — журнал получится
        безупречным, потому что номера прогонов у двух обходов не пересекутся.
        """
        async with self.замок_прогона:
            if self.опыт_идёт:
                return False
            self.опыт_идёт = True
            return True

    def закончить_прогон(self) -> None:
        """Освобождает право на прогон. Зовётся из `finally`, всегда.

        Без замка и без `await` намеренно: снятие признака безусловно, а гонки здесь нет —
        проверка и установка в `начать_прогон` не разделены точкой ожидания. Заодно это
        избавляет от ожидания замка в `finally` у генератора, которого закрывают на
        полуслове.

        Снимать признак обязательно в `finally`, рядом со снятием задачи: иначе один
        обрыв связи запер бы страницу до перезапуска сервера, и человек жал бы кнопку
        впустую, не понимая, почему ничего не происходит.
        """
        self.опыт_идёт = False

    async def клиент_для(self, api_key: str) -> api.DeepSeekClient:
        """Клиент API — один на приложение, заводится при первом обращении.

        Новый клиент на каждый запрос означал бы новый пул соединений на каждое нажатие
        кнопки; при двадцати клетках подряд это заметно дороже одного общего. Прогрев
        соединения (`run.warmup`) без общего клиента и вовсе терял бы смысл: прогретое
        соединение умирало бы вместе с породившим его клиентом.
        """
        отпечаток = hashlib.sha256(api_key.encode("utf-8")).hexdigest()
        async with self.замок:
            if self.клиент is None or self.отпечаток_ключа != отпечаток:
                await self.закрыть_клиента()
                self.клиент = api.DeepSeekClient(api_key)
                self.отпечаток_ключа = отпечаток
            return self.клиент

    async def закрыть_клиента(self) -> None:
        if self.клиент is not None:
            await self.клиент.aclose()
            self.клиент = None
            self.отпечаток_ключа = None


состояние = Состояние()


# --- события потока -----------------------------------------------------------


def кадр(данные: dict[str, Any]) -> str:
    """Одно событие потока сервера: `data: <json>` и пустая строка как разделитель.

    Русский текст идёт как есть (`ensure_ascii=False`), а переносы строк внутри ответа
    модели JSON экранирует сам — событие остаётся однострочным, как того требует формат.
    """
    return "data: " + json.dumps(данные, ensure_ascii=False) + "\n\n"


def событие_клетки(итог: run.CellResult) -> dict[str, Any]:
    """Готовая клетка в виде события. Ключа доступа здесь нет и быть не может.

    Все поля берутся из итога как есть, включая цену: её считает обход прогона
    (`run.run_all`) по снимку тарифа на момент отправки запроса, и то же самое число
    ложится в журнал. Пересчитать её здесь значило бы завести второй источник одной
    цифры — а расходятся такие пары молча.

    `ttft_ms` и `ttfa_ms` могут быть `None`, и подменять их нулём нельзя: ноль читается
    как «ответ пришёл мгновенно» и полноправно входит в среднее, тогда как `None` честно
    говорит «замера не было». Показать разницу — дело страницы.
    """
    return {
        "kind": "cell",
        "cell_id": итог.cell_id,
        "repetition": итог.repetition,
        "answer": итог.answer,
        "usage": итог.usage,
        "ttft_ms": итог.ttft_ms,
        "ttfa_ms": итог.ttfa_ms,
        "total_ms": итог.total_ms,
        "tokens_per_sec": итог.tokens_per_sec,
        # Больше единицы означает, что за оборванные попытки провайдеру тоже заплачено,
        # а их расход в `usage` не попал: на странице это должно быть видно, иначе цена
        # такой клетки выглядит полной, хотя учтена лишь последняя попытка.
        "attempts": итог.attempts,
        "cost": итог.cost,
        "finish_reason": итог.finish_reason,
        "status": итог.status,
        "error": итог.error,
    }


def событие_ошибки(сообщение: str) -> dict[str, Any]:
    return {"kind": "error", "message": сообщение}


def описание_сбоя(исключение: BaseException) -> str:
    return f"{type(исключение).__name__}: {исключение}"


# --- поток прогона ------------------------------------------------------------


async def _опыт(
    клиент: api.DeepSeekClient,
    начало: int,
    положить: Callable[[run.CellResult], None],
) -> None:
    """Прогрев соединения, затем весь опыт целиком.

    Прогрев стоит именно здесь, перед первым боевым вызовом, а не в жизненном цикле
    приложения: сервер может простоять поднятым час до нажатия кнопки, и соединение,
    прогретое на запуске, к этому моменту давно закрыто. Свой сбой прогрев гасит сам —
    отменять из-за него платные вызовы было бы разменом наоборот.
    """
    await run.warmup(клиент)
    await run.run_all(клиент, начало, REPEATS, положить)


async def поток_прогона() -> AsyncIterator[str]:
    """События одного нажатия кнопки: клетка за клеткой, затем `done` или `error`.

    Параметров нет: вопрос в опыте дня один, а меняются клетки — их прогоняются все.

    Одновременный опыт ровно один. Второму подключившемуся уходит событие ошибки, и решает
    это сервер, а не блокировка кнопки на странице: кнопка защищает одну вкладку, а платит
    за все и держит порядок запросов сервер. Подробнее — в `Состояние.начать_прогон`.

    Связь устроена через `asyncio.Queue`. `run.run_all` зовёт `on_result` как обычную
    функцию из своего асинхронного кода — отдать оттуда значение наружу нельзя, а положить
    в очередь можно: `put_nowait` у неограниченной очереди не ждёт и не роняет вызывающего.
    Генератор потока разбирает очередь и отдаёт события браузеру по одному. Без очереди
    пришлось бы дождаться конца `run_all` и вывалить все двадцать ответов разом — на
    странице это выглядело бы как «ничего не происходит, потом всё сразу», а идёт опыт
    минутами.

    Конец прогона отмечает `add_done_callback`: он кладёт в ту же очередь метку `КОНЕЦ`.
    Очередь соблюдает порядок, поэтому метка приходит после всех результатов — ни один из
    них не теряется.
    """
    # Настройки читаются на каждый прогон: человек мог выполнить `/auth` уже после того,
    # как сервер был поднят.
    настройки = load_config()
    if not настройки.is_authorized:
        yield кадр(событие_ошибки(НЕТ_КЛЮЧА))
        return

    try:
        клиент = await состояние.клиент_для(настройки.api_key)
    except Exception as исключение:  # noqa: BLE001 — сбой отдаём событием, а не пятисотым
        yield кадр(событие_ошибки(описание_сбоя(исключение)))
        return

    # Право на прогон занимается до отвода номеров: номера отдаются навсегда, и выдать их
    # прогону, которому мы тут же откажем, значило бы навсегда пробить дырку в таблице.
    if not await состояние.начать_прогон():
        yield кадр(событие_ошибки(ПРОГОН_ИДЁТ))
        return

    задача: asyncio.Task[None] | None = None
    try:
        начало = состояние.занять(REPEATS)
        очередь: asyncio.Queue[Any] = asyncio.Queue()
        задача = asyncio.create_task(_опыт(клиент, начало, очередь.put_nowait))
        задача.add_done_callback(lambda _: очередь.put_nowait(КОНЕЦ))

        while True:
            элемент = await очередь.get()
            if элемент is КОНЕЦ:
                break
            yield кадр(событие_клетки(элемент))

        if задача.cancelled():
            yield кадр(событие_ошибки("прогон прерван"))
        elif (сбой := задача.exception()) is not None:
            yield кадр(событие_ошибки(описание_сбоя(сбой)))
        else:
            yield кадр({"kind": "done", "collected": состояние.занято})
    finally:
        # Браузер закрыли или страницу обновили — генератор закрывают на полуслове.
        # Прогон в этом случае снимаем: платить за ответы, которых никто не увидит, незачем.
        if задача is not None and not задача.done():
            задача.cancel()
            with contextlib.suppress(asyncio.CancelledError):
                await задача
        # Право на прогон освобождается при любом исходе, включая обрыв связи и сбой при
        # заведении задачи. Оставленный признак запер бы страницу до перезапуска сервера.
        состояние.закончить_прогон()


# --- приложение ---------------------------------------------------------------


@asynccontextmanager
async def жизненный_цикл(app: FastAPI) -> AsyncIterator[None]:
    """Нумерация прогонов читается на запуске, клиент API закрывается на остановке."""
    состояние.прочитать_собранное()
    try:
        yield
    finally:
        await состояние.закрыть_клиента()


app = FastAPI(title="Клетки моделей", lifespan=жизненный_цикл)


# HEAD перечислен рядом с GET намеренно: FastAPI, в отличие от Starlette, сам его не
# добавляет, и проверка вида `curl -sI` получала бы 405 вместо ответа страницы.
@app.api_route("/", methods=["GET", "HEAD"], response_class=HTMLResponse)
def страница() -> HTMLResponse:
    """Разметка страницы, читается с диска на каждый запрос.

    Именно на каждый, а не один раз на запуске: правка разметки видна по обновлению
    страницы, без перезапуска сервера. Страница локальная и маленькая — чтение файла
    здесь дешевле неудобства.
    """
    try:
        текст = PAGE_PATH.read_text(encoding="utf-8")
    except OSError:
        return HTMLResponse(ЗАГЛУШКА_СТРАНИЦЫ)
    return HTMLResponse(текст)


@app.get("/settings")
def состав_опыта() -> dict[str, Any]:
    """Клетки, число прогонов и текст вопроса — оттуда же, откуда их берёт прогон.

    Страница рисует столбцы по этому ответу, а не по своему списку. Иначе правка `CELLS`
    в `models/cells.py` оставила бы на странице старые столбцы, и каждая клетка молча
    падала бы в прочерк — отказ без единого сообщения.

    Вопрос идёт сюда же, а не вшивается в разметку, по той же причине: показанный на
    странице текст обязан быть тем самым, который уходит в API, иначе страница врёт о том,
    что спрашивали.
    """
    return {
        "cells": [
            {
                "id": клетка.id,
                "title": клетка.title,
                "role": клетка.role,
                "model": клетка.model,
                "thinking": клетка.thinking,
            }
            for клетка in CELLS
        ],
        "repeats": REPEATS,
        "question": QUESTION_TEXT,
    }


@app.get("/run")
def прогон() -> StreamingResponse:
    """Поток событий опыта: `REPEATS` прогонов, в каждом — все четыре клетки."""
    return StreamingResponse(
        поток_прогона(),
        media_type="text/event-stream",
        headers={
            "Cache-Control": "no-cache",
            # Просьба к возможному посреднику не копить ответ в буфере: смысл всей затеи
            # в том, чтобы клетки заполнялись по одной.
            "X-Accel-Buffering": "no",
        },
    )


@app.get("/summary")
def сводка() -> dict[str, Any]:
    """Сводка по журналу и вывод дня — без единого обращения к API.

    Страница опрашивает этот маршрут раз в три секунды, чтобы цифры догоняли таблицу по
    ходу прогона. Поэтому он обязан быть дешёвым и, главное, бесплатным: обращение к API
    отсюда означало бы платный вызов каждые три секунды всё время, пока открыта вкладка.
    Читается только журнал прогонов и файл вывода с диска.
    """
    return {
        "summary": summary.сводка(summary.читать_журнал()),
        "verdict": summary.вывод_из_файла(),
    }


def main() -> None:
    print(f"страница опыта: http://{HOST}:{PORT}  (Ctrl+C — остановить)")
    uvicorn.run(app, host=HOST, port=PORT, log_level="warning")


if __name__ == "__main__":
    main()
