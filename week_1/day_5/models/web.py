"""Локальная страница опыта: один вопрос на четырёх клетках, ответы по мере готовности.

Приложение делает четыре вещи: отдаёт страницу, отдаёт состав опыта, ведёт поток событий
прогона и отдаёт сводку по журналу. Вся расчётная часть лежит в соседних модулях
(`models.run`, `models.pricing`, `models.summary`) — здесь только связь между прогоном и
браузером.

    uv run python -m models.web
"""

