"""Тариф DeepSeek: ставки за миллион токенов, пиковые часы и расчёт денег по `usage`.

Здесь только арифметика и данные тарифа: ни запросов к API, ни чтения файлов. Деньги
считаются не в момент показа страницы, а по снимку тарифа, записанному в журнал вместе
с прогоном, — тариф провайдера меняется, и без записанной ставки пересчитать прошлую
неделю будет уже нечем.
"""

from __future__ import annotations

from datetime import UTC, datetime
from typing import Any

#: День, на который списаны ставки ниже. Лежит в каждом снимке: по нему видно, каким
#: тарифом посчитана запись, даже если тариф с тех пор сменился.
ДАТА_ТАРИФА: str = "2026-09-04"

#: Откуда переписаны цифры. Тоже уходит в снимок, чтобы спорную цену можно было
#: проверить по первоисточнику, а не по памяти.
ИСТОЧНИК: str = "https://api-docs.deepseek.com/quick_start/pricing"

# --- ставки -------------------------------------------------------------------
#
# Доллары за миллион токенов. Цифры взяты из опубликованного тарифа и ПОДЛЕЖАТ СВЕРКЕ
# С ЛИЧНЫМ КАБИНЕТОМ: опубликованная страница отстаёт от фактического счёта, а на скидки
# и акции она не смотрит вовсе. Фактические цифры даёт пользователь после своего прогона.
#
# Именно ради этой сверки в журнал прогонов кладётся поле `usage` целиком, а не одна
# посчитанная сумма: имея сырые токены, любую новую цену можно применить к уже
# записанным прогонам задним числом, не делая ни одного нового вызова к API.

ЦЕНЫ: dict[str, dict[str, float]] = {
    "deepseek-v4-flash": {"cache_hit": 0.007, "cache_miss": 0.22, "output": 0.66},
    "deepseek-v4-pro": {"cache_hit": 0.022, "cache_miss": 0.66, "output": 1.98},
}

# --- пиковые часы -------------------------------------------------------------
#
# Часы по UTC: начало включительно, конец исключительно. В эти окна DeepSeek берёт вдвое.

ПИКОВЫЕ_ОКНА: tuple[tuple[int, int], ...] = ((1, 4), (6, 10))
МНОЖИТЕЛЬ_ПИКА: float = 2.0


def множитель_пика(момент: datetime) -> float:
    """Надбавка за пиковый час: 2.0 внутри окна, 1.0 снаружи.

    Момент без часового пояса отклоняется, а не толкуется как UTC. Местное время Мака
    молча сошло бы за UTC, граница пикового окна уехала бы на три часа — и цена целой
    половины прогона ошиблась бы ровно вдвое, оставшись на экране правдоподобным числом.
    Отказ считать заметен сразу, тихо неверный счёт не заметен никогда.
    """
    if момент.tzinfo is None or момент.utcoffset() is None:
        raise ValueError(
            "нужен момент с часовым поясом: без пояса непонятно, "
            "попадает ли вызов в пиковое окно UTC, и цена ошибётся вдвое"
        )
    час = момент.astimezone(UTC).hour
    for начало, конец in ПИКОВЫЕ_ОКНА:
        if начало <= час < конец:
            return МНОЖИТЕЛЬ_ПИКА
    return 1.0


def снимок(model: str, момент: datetime) -> dict[str, Any]:
    """Ставки тарифа, зафиксированные на момент вызова, — для записи в журнал.

    Снимок нужен потому, что тариф живёт своей жизнью: без записанной на момент вызова
    ставки пересчитать прогон через неделю невозможно — не с чем сверять. Цены хранятся
    базовыми, непиковыми, а надбавка лежит рядом отдельным множителем: так по одной
    записи видно и саму ставку, и причину, по которой вызов вышел дороже. Хранили бы
    уже удвоенные цены — пиковую клетку нельзя было бы отличить от подорожавшего тарифа.

    Неизвестная модель роняет расчёт `KeyError` с именем модели в тексте: опечатка
    должна остановить прогон, а не посчитаться молча по нулям.
    """
    цены = ЦЕНЫ[model]
    множитель = множитель_пика(момент)
    return {
        "model": model,
        "cache_hit": цены["cache_hit"],
        "cache_miss": цены["cache_miss"],
        "output": цены["output"],
        "peak": множитель != 1.0,
        "multiplier": множитель,
        "tariff_date": ДАТА_ТАРИФА,
        "source": ИСТОЧНИК,
    }


def _число_токенов(usage: dict[str, Any], поле: str) -> float | None:
    """Значение поля учёта токенов: число не меньше нуля либо `None`, если поля нет.

    Проверка стоит здесь, а не в формуле, потому что негодное значение должно называть
    себя по имени. Отрицательное число, пропущенное молча, дало бы отрицательную
    стоимость: она ушла бы в журнал и вычлась из итога дня, не подняв шума. Строка
    вместо числа без этой проверки падает `TypeError` из середины формулы — по такому
    сообщению не понять, какое поле ответа испорчено.

    Отказ считать, а не тихое зажатие нулём: в этом модуле уже принято правило, что
    заметный отказ лучше незаметно неверного счёта. Прогон от этого не рушится —
    вызывающий код заворачивает сбой клетки в `status="error"`, и аномалия становится
    видна вместо того, чтобы раствориться в правдоподобной сумме.

    `bool` отклоняется отдельно: в Python он подкласс `int`, и `True` посчиталось бы
    за один токен вместо того, чтобы указать на испорченный ответ.
    """
    значение = usage.get(поле)
    if значение is None:
        return None
    if isinstance(значение, bool) or not isinstance(значение, (int, float)):
        # ruff предлагает здесь `TypeError`, и для библиотеки он был бы прав. Но негодный
        # тип и отрицательное число — это одна и та же беда с одной и той же причиной:
        # испорченное поле в ответе API. Вызывающий код ловит их одним `except ValueError`
        # и заворачивает клетку в `status="error"`; два разных класса исключения на один
        # случай развели бы обработку на две ветки без всякой пользы.
        raise ValueError(  # noqa: TRY004
            f"учёт токенов, поле {поле!r}: ожидалось число, получено {значение!r}"
        )
    if значение < 0:
        raise ValueError(
            f"учёт токенов, поле {поле!r}: число не может быть отрицательным, "
            f"получено {значение!r}"
        )
    return значение


def стоимость(usage: dict[str, Any], снимок: dict[str, Any]) -> float:
    """Деньги за один вызов по учёту токенов и снимку тарифа.

    Расчёт отделён от снимка намеренно: снимок отвечает за то, какая ставка действовала,
    а эта функция — за то, сколько токенов по ней прошло. Разделение и позволяет
    пересчитать старый журнал под уточнённые цены.
    """
    hit = _число_токенов(usage, "prompt_cache_hit_tokens")
    miss = _число_токенов(usage, "prompt_cache_miss_tokens")
    prompt = _число_токенов(usage, "prompt_tokens") or 0
    out = _число_токенов(usage, "completion_tokens") or 0

    # Полная разбивка по промежуточному хранилищу имеет приоритет над `prompt_tokens`:
    # у DeepSeek `prompt_tokens` — это сумма попаданий и промахов, и сложение всех трёх
    # посчитало бы вход дважды.
    #
    # Разбивки нет вовсе — весь вход идёт по ставке промаха: считать такой вход бесплатным
    # значило бы молча терять деньги, расход был, а в отчёте дня его нет. Промах — верхняя
    # оценка, ошибка уходит в безопасную сторону.
    #
    # Пришла ровно одна половина разбивки — недостающая выводится вычитанием из
    # `prompt_tokens`. Иначе остаток входа пропал бы из счёта совсем: при 1000 токенов
    # входа и одной известной сотне попаданий терялось бы девятьсот, то есть недосчёт
    # в сотни раз — и, в отличие от прочих допущений здесь, в опасную сторону.
    # `max(..., 0)` на случай, если половины и сумма не сойдутся: отрицательный остаток
    # не токены, а испорченный ответ, и он не должен уменьшать счёт.
    if hit is None and miss is None:
        hit = 0.0
        miss = prompt
    elif hit is None:
        hit = max(prompt - miss, 0)
    elif miss is None:
        miss = max(prompt - hit, 0)

    # Отдельного слагаемого токенам рассуждений не нужно: у DeepSeek они входят
    # в `completion_tokens` и тарифицируются как выход. В журнале они лежат отдельным
    # полем не ради денег, а потому что именно там прячется основной расход клеток
    # с рассуждениями. ЕСЛИ ЖИВОЙ ПРОГОН ПОКАЖЕТ, ЧТО РАССУЖДЕНИЯ ПРИХОДЯТ СВЕРХ
    # `completion_tokens`, — формула правится здесь, добавлением четвёртого слагаемого.
    за_миллион = (
        hit * снимок["cache_hit"] + miss * снимок["cache_miss"] + out * снимок["output"]
    )
    return за_миллион / 1_000_000 * снимок["multiplier"]
