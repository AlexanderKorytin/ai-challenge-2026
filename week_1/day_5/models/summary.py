"""Сводка по журналу прогонов: медианы времени, суммы токенов, деньги и отношения.

Здесь только арифметика по уже записанному: ни одного обращения к API. Сводка сворачивает
два десятка записей журнала в четыре столбца таблицы, а подменённое число выглядит на
странице ровно так же убедительно, как верное, — поэтому каждое решение о том, что во что
входит, объяснено прямо у места, где считается.

Через весь модуль проходят три правила:

* Столбцы берутся из `models.cells.CELLS`, а не из журнала. Клетка, у которой упали все
  прогоны, обязана остаться в таблице пустой: исчезнувший столбец читается как
  непоставленный опыт, а не как провалившийся, и вывод дня делается по недостающей
  четверти данных, ничем этого не обнаруживая.
* Время считается по успешным записям, расход — по всем. У упавшего вызова время это
  время до отказа, а не до ответа, зато токены и деньги потрачены по-настоящему.
* Ни одна испорченная запись не роняет сводку целиком. Страница опрашивает этот модуль
  раз в несколько секунд по ходу живого прогона — ровно тогда, когда журнал дописывается,
  — и отказ здесь стирает с экрана не одну негодную строку, а всю уже посчитанную
  таблицу, посреди оплаченного опыта. Негодное значение выбрасывается поимённо, а там,
  где это скрыло бы потерю денег, оставляет жалобу в журнале сообщений.
"""

from __future__ import annotations

import json
import logging
import math
from pathlib import Path
from statistics import median
from typing import Any

from models import run
from models.cells import CELLS, ВЕРНЫЙ_ОТВЕТ, by_id

#: Клетка, с которой сравниваются остальные. Это низ лестницы «слабая → сильная»: вопрос
#: опыта звучит «во сколько раз дороже и медленнее рассуждения и старшая модель», и
#: осмысленный ответ получается только при сравнении с самым дешёвым вариантом.
БАЗОВАЯ_КЛЕТКА: str = "flash_plain"

#: Сюда уходят жалобы на негодные значения в записях: молча терять их нельзя, а поднимать
#: выше — значит ронять показ страницы из-за одной испорченной строки журнала.
ЖУРНАЛ_СООБЩЕНИЙ = logging.getLogger(__name__)

# Опечатка в имени базовой клетки не должна проходить молча. Неизвестное имя не роняет
# ни один расчёт: сводка вернётся целой, просто все восемь отношений окажутся пустыми — а
# пустая колонка «во сколько раз» читается как «нечего сравнивать», то есть как свойство
# прогона, а не как сломанная настройка. Отказ при загрузке модуля заметен сразу.
if БАЗОВАЯ_КЛЕТКА not in {клетка.id for клетка in CELLS}:
    raise ValueError(
        f"базовая клетка {БАЗОВАЯ_КЛЕТКА!r} не значится в описании опыта: "
        f"сравнивать не с чем, отношения вышли бы пустыми во всех столбцах"
    )

#: Вердикт, который требование формы обязывает поставить первым словом ответа. Пара
#: перечислена здесь потому, что нули по обоим исходам нужны и той клетке, где записей нет
#: вовсе: столбец без строки «да» читается как «такого ответа не бывает», а не как
#: «такого ответа не случилось».
ВЕРДИКТЫ: tuple[str, ...] = ("да", "нет")

#: Ключ для ответов, из которых вердикт достать не удалось: модель не выполнила требование
#: формы, либо вызов упал и ответа нет вовсе. Это исход опыта наравне с двумя другими, а
#: не отсутствие данных: невыполненное требование формы — тоже поведение клетки.
БЕЗ_ВЕРДИКТА: str = "нет вердикта"

#: Ключ для попаданий в верный ответ. Считается поверх трёх исходов, а не вместо них:
#: «верных» — это часть строки своего вердикта, и сумма трёх исходов даёт число записей.
ВЕРНЫХ: str = "верных"

# Верный ответ обязан быть одним из вердиктов, иначе попаданий не будет никогда, а
# таблица покажет честный ноль в строке «верных» и ничем не выдаст, что сверять было не с
# чем. Расхождение между описанием опыта и разбором ответа должно падать при загрузке.
if ВЕРНЫЙ_ОТВЕТ not in ВЕРДИКТЫ:
    raise ValueError(
        f"верный ответ {ВЕРНЫЙ_ОТВЕТ!r} не значится среди вердиктов {ВЕРДИКТЫ}: "
        f"сверять вердикт не с чем, попаданий не нашлось бы ни одного"
    )

#: Величины прогона, по которым в таблице показываются медиана и разброс.
#
# Времени здесь три, и это главное утверждение дня: «время ответа» не одно число.
# `ttft_ms` — до первого признака жизни, `ttfa_ms` — до первого слова самого ответа,
# `total_ms` — до конца. У клетки с рассуждениями между первыми двумя пролегают секунды
# молчаливого обдумывания, и разница видна только тогда, когда обе величины стоят рядом в
# одном столбце. Показанная по одной клетке, она требует от человека щёлкать по пяти
# прогонам каждого из четырёх столбцов и складывать медиану в уме.
_ВЕЛИЧИНЫ: tuple[str, ...] = ("ttft_ms", "ttfa_ms", "total_ms", "tokens_per_sec")

#: Виды токенов и поля `usage`, из которых они берутся. Ставки этих видов различаются в
#: десятки раз, поэтому суммы держатся врозь: слитые в одну, они дали бы правдоподобное
#: число, из которого нельзя понять, на чём именно тратится клетка с рассуждениями.
_ВИДЫ_ТОКЕНОВ: tuple[tuple[str, str], ...] = (
    ("cache_hit", "prompt_cache_hit_tokens"),
    ("cache_miss", "prompt_cache_miss_tokens"),
    ("output", "completion_tokens"),
)


# --- чтение журнала -----------------------------------------------------------


def читать_журнал(path: Path = run.DATA_PATH) -> list[dict]:
    """Пригодные к разбору непрогревочные записи журнала, в порядке записи.

    Отсутствие файла — это состояние до первого прогона, а не сбой: страница сводки
    открывается раньше, чем в опыте появляется хоть что-нибудь, и отказ вместо пустого
    списка закрыл бы её насовсем.

    Негодная строка пропускается, а не роняет разбор. Журнал дописывается по ходу живого
    прогона, страница обновляется сама, и попасть на середину дописываемой строки —
    обычное дело, а не порча файла: прочитанное до неё остаётся годным.

    Файл читается с заменой негодных байтов (`errors="replace"`), и это не мелочь.
    Записи журнала содержат русский текст ответа, буква в UTF-8 занимает два байта, и
    обрыв приходится на середину буквы чаще, чем на промежуток между ними. Такой хвост
    роняет не разбор JSON, а само декодирование файла — то есть мимо `except` ниже. С
    заменой битый хвост просто не разбирается как JSON и отсеивается штатно, а всё
    прочитанное до него доходит до страницы.

    Прогревочные записи выброшены здесь же. Прогрев платит за установку соединения и в
    таблицу не идёт: посчитанный наравне с остальными, он занизил бы медиану времени той
    клетки, которой достался.
    """
    path = Path(path)
    if not path.exists():
        return []

    записи: list[dict] = []
    with path.open(encoding="utf-8", errors="replace") as файл:
        for сырая in файл:
            строка = сырая.strip()
            if not строка:
                continue
            try:
                запись = json.loads(строка)
            except json.JSONDecodeError:
                continue
            # Годной записью считается только словарь: список и голая строка — тоже
            # правильный JSON, но полей прогона в них нет.
            if not isinstance(запись, dict):
                continue
            if запись.get("warmup"):
                continue
            записи.append(запись)
    return записи


# --- разбор одной записи ------------------------------------------------------


def _число(значение: Any) -> float | None:
    """Числовая величина записи либо `None`, если её нет или она негодна.

    `bool` отсеивается отдельно, хотя и является подклассом `int`: `True` в поле времени
    сошёл бы за одну миллисекунду и тихо сдвинул медиану вместо того, чтобы обнаружить
    испорченную запись.

    «Не число» и «бесконечность» отсеиваются тоже. Они истинны, они проходят все проверки
    на тип и на ноль, а дальше заражают всё, к чему прикоснутся: сумма денег с одним `nan`
    целиком `nan`, отношение к такому основанию тоже `nan`, и в ячейке таблицы встаёт не
    число, а слово — причём сводка при этом отработает без единой жалобы.
    """
    if isinstance(значение, bool) or not isinstance(значение, (int, float)):
        return None
    if not math.isfinite(значение):
        return None
    return значение


def _счётчик(значение: Any) -> int | None:
    """Счётчик токенов либо `None`, если значение негодно.

    Отрицательное число считается негодным наравне с нечисловым — так же, как в
    `models.pricing._число_токенов`. Расхождение здесь было бы хуже самой порчи: один
    модуль отказывался бы считать деньги по такой записи, другой показывал бы её токены
    в таблице как ни в чём не бывало, и человек читал бы два несогласованных числа об
    одном и том же прогоне.
    """
    число = _число(значение)
    if число is None or число < 0:
        return None
    return int(число)


def _целое(значение: Any) -> int:
    """Счётчик токенов, где негодное значение считается нулём.

    Ноль вместо отказа потому, что счётчики складываются по всем записям подряд, включая
    упавшие: у оборвавшегося вызова часть полей `usage` может не прийти вовсе, и ронять
    из-за этого сводку целого дня — дороже, чем недосчитать один вид токенов. Сырой
    `usage` при этом остаётся в журнале, и точную разбивку всегда можно пересчитать по
    нему заново.
    """
    счёт = _счётчик(значение)
    return 0 if счёт is None else счёт


def _токены_рассуждений(usage: dict[str, Any]) -> int:
    """Токены рассуждений в любой из двух форм, которыми их присылает провайдер.

    Форму выбирает провайдер, а не мы: то `completion_tokens_details.reasoning_tokens`,
    то плоское `reasoning_tokens` на верхнем уровне. Понята одна из двух — расход
    рассуждений в половине записей молча становится нулём, и клетка с рассуждениями
    выглядит в таблице такой же дешёвой, как клетка без них.

    Вложенная форма выигрывает только годным значением, а не самим наличием ключа. Пустое
    `completion_tokens_details.reasoning_tokens` рядом с заполненным плоским полем —
    ровно тот случай, когда проверка на ключ затёрла бы известное число нулём.
    """
    подробности = usage.get("completion_tokens_details")
    if isinstance(подробности, dict):
        вложенное = _счётчик(подробности.get("reasoning_tokens"))
        if вложенное is not None:
            return вложенное
    return _целое(usage.get("reasoning_tokens"))


def _расход(записи: list[dict]) -> dict[str, int]:
    """Суммы токенов по видам за все переданные записи."""
    итог = {вид: 0 for вид, _ in _ВИДЫ_ТОКЕНОВ}
    итог["reasoning"] = 0
    for запись in записи:
        usage = запись.get("usage")
        if not isinstance(usage, dict):
            continue
        for вид, поле in _ВИДЫ_ТОКЕНОВ:
            итог[вид] += _целое(usage.get(поле))
        итог["reasoning"] += _токены_рассуждений(usage)
    return итог


def _деньги(записи: list[dict], имя: str) -> float:
    """Сумма поля `cost` по всем записям; негодная цена — ноль и жалоба в журнал.

    Ноль здесь по той же причине, что и у токенов: ронять показ страницы из-за одной
    испорченной записи дороже, чем недосчитать её цену. Но у денег, в отличие от токенов,
    тихое умолчание опаснее — деньги и есть то, ради чего сводка существует, и занижённый
    итог дня выглядит на странице обычным числом. Поэтому пропуск не молчит: жалоба
    называет клетку и прогон, чтобы недостачу можно было объяснить, а не гадать о ней.
    Сырой `usage` остаётся в журнале, и цену всегда можно пересчитать по нему заново.
    """
    итог = 0.0
    for запись in записи:
        деньги = _число(запись.get("cost"))
        if деньги is None:
            ЖУРНАЛ_СООБЩЕНИЙ.warning(
                "клетка %s, прогон %s: цена негодна (%r), в сумму дня не вошла",
                имя,
                запись.get("run_key"),
                запись.get("cost"),
            )
            continue
        итог += деньги
    return итог


def _вердикты(записи: list[dict]) -> dict[str, int]:
    """Три исхода по вердикту и число попаданий в верный ответ.

    Считается по всем записям, включая упавшие. У упавшего вызова ответа нет, а значит нет
    и вердикта — и это честно ложится в «нет вердикта»: клетка, которая не отвечает,
    отличается от клетки, которая отвечает неверно, но обе одинаково не дали верного
    ответа, и обе должны быть видны в таблице.

    Посторонняя строка в поле — тоже «нет вердикта». Журнал пишут не только наши руки:
    правило разбора ответа может смениться, а старые записи останутся, и вердикт вида
    «возможно» не должен ни тихо пропасть, ни притвориться одним из двух исходов.

    «Верных» считается поверх трёх исходов, а не вместо них: сумма трёх даёт число записей
    клетки, а попадания — это часть строки своего вердикта. Сверка идёт с
    `cells.ВЕРНЫЙ_ОТВЕТ`, а не с зашитой здесь строкой: смена верного ответа обязана
    менять и разметку, иначе таблица начнёт считать попаданиями промахи.
    """
    итог = {вердикт: 0 for вердикт in ВЕРДИКТЫ}
    итог[БЕЗ_ВЕРДИКТА] = 0
    итог[ВЕРНЫХ] = 0
    for запись in записи:
        вердикт = запись.get("verdict")
        # Проверка идёт по `ВЕРДИКТЫ`, а не по ключам итога: иначе запись со словом
        # «верных» в поле вердикта попала бы в счётчик попаданий.
        if not isinstance(вердикт, str) or вердикт not in ВЕРДИКТЫ:
            итог[БЕЗ_ВЕРДИКТА] += 1
            continue
        итог[вердикт] += 1
        if вердикт == ВЕРНЫЙ_ОТВЕТ:
            итог[ВЕРНЫХ] += 1
    return итог


def _разброс(записи: list[dict], поле: str) -> dict[str, float | None]:
    """Медиана и края одной величины по переданным записям.

    Медиана берётся по отсортированным значениям, а на чётном числе — как среднее двух
    средних: взять любое из них значило бы получить число, зависящее от порядка записи в
    журнал, и на экране оно выглядело бы столь же правдоподобным.

    Края считаются по тому же набору, что и медиана: в таблице они стоят рядом с ней и
    читаются как её края — посчитанные по другому набору, они тихо соврут о том,
    насколько клетка нестабильна.

    Пустая величина выбрасывает саму себя, а не всю запись. Пустое здесь законно и без
    порчи данных: `tokens_per_sec` пуст, когда знаменатель вышел нулевым, а `ttfa_ms` —
    когда ответ не пришёл вовсе и мерить было нечего, хотя `total_ms` при этом измерен
    честно. Выброшенная целиком, такая запись унесла бы с собой исправные замеры.
    """
    значения = [ч for ч in (_число(з.get(поле)) for з in записи) if ч is not None]
    if not значения:
        return {"median": None, "min": None, "max": None}
    return {
        "median": median(значения),
        "min": min(значения),
        "max": max(значения),
    }


# --- сводка -------------------------------------------------------------------


def _столбец(cell_id: str, записи: list[dict]) -> dict[str, Any]:
    """Один столбец таблицы по записям своей клетки.

    Описание клетки (`title`, `role`, `model`, `thinking`) берётся из `models.cells`, а не
    из записей: это свойство опыта, а не отдельного вызова. Иначе одна порченая запись
    переименовала бы целый столбец, и таблица начала бы утверждать, что опыт ставился не
    на той модели.
    """
    клетка = by_id(cell_id)
    успешные = [з for з in записи if з.get("status") == "ok"]

    столбец: dict[str, Any] = {
        "cell_id": клетка.id,
        "title": клетка.title,
        "role": клетка.role,
        "model": клетка.model,
        "thinking": клетка.thinking,
        "n": len(успешные),
        "errors": len(записи) - len(успешные),
    }
    for величина in _ВЕЛИЧИНЫ:
        столбец[величина] = _разброс(успешные, величина)

    # Расход считается по всем записям, включая упавшие: за частично пришедший ответ
    # провайдер всё равно берёт деньги, и итог дня, посчитанный по одним успешным,
    # занижен ровно на самые дорогие — оборвавшиеся — вызовы.
    столбец["tokens"] = _расход(записи)

    # Вердикты — заглавная величина дня: ради них к вопросу добавлено требование формы,
    # и считаются они так же по всем записям, по той же причине, что и расход.
    столбец["verdicts"] = _вердикты(записи)

    # Деньги складываются из поля `cost`, посчитанного в момент прогона по тогдашнему
    # тарифу, а не пересчитываются по нынешним ставкам. Пересчёт молча разошёлся бы с
    # журналом при первой же смене тарифа: прошлая неделя начала бы стоить сегодняшних
    # денег, и обнаружить это было бы нечем — порядок величины остаётся прежним.
    столбец["cost"] = _деньги(записи, клетка.id)
    return столбец


def сводка(записи: list[dict]) -> dict[str, Any]:
    """Четыре столбца таблицы и имя базовой клетки — по записям журнала.

    Столбцы идут в порядке `CELLS` и присутствуют все четыре всегда, даже если журнал
    пуст: порядок «слабая → средняя → сильная» — часть замысла опыта и читается слева
    направо, а сортировка по журналу переставила бы столбцы по случайности прогона.

    Записи неизвестных клеток отбрасываются: столбец, которого нет в описании опыта,
    нечем ни назвать, ни объяснить.
    """
    по_клеткам: dict[str, list[dict]] = {клетка.id: [] for клетка in CELLS}
    for запись in записи:
        идентификатор = запись.get("cell_id")
        if isinstance(идентификатор, str) and идентификатор in по_клеткам:
            по_клеткам[идентификатор].append(запись)

    столбцы = [_столбец(клетка.id, по_клеткам[клетка.id]) for клетка in CELLS]
    _проставить_отношения(столбцы)
    return {"base": БАЗОВАЯ_КЛЕТКА, "cells": столбцы}


def _проставить_отношения(столбцы: list[dict[str, Any]]) -> None:
    """Дописывает в столбцы `cost_ratio` и `time_ratio` — сравнение с базовой клеткой.

    Деньги сравниваются суммами, время — медианами, и это не небрежность: деньги за
    прогон складываются, а время не складывается — сумма времени зависела бы от числа
    повторов, а не от клетки.

    Знаменатели у двух отношений разные и обнуляются порознь. Негодный один не повод
    терять другой: основание бывает бесплатным, но исправно измеренным — первый же прогон
    по бесплатной квоте стёр бы из таблицы всё сравнение по времени.

    Нулевое или отсутствующее основание даёт `None`, а не деление на ноль: падение
    посреди показа страницы и `inf` в ячейке обнаруживаются одинаково поздно — на живом
    прогоне, когда базовая клетка отвалилась, а остальные уже посчитаны и оплачены.
    """
    # Базовая клетка заведомо среди столбцов: её имя проверено при загрузке модуля.
    основание = next(с for с in столбцы if с["cell_id"] == БАЗОВАЯ_КЛЕТКА)
    деньги_основания = основание["cost"]
    время_основания = основание["total_ms"]["median"]

    for столбец in столбцы:
        столбец["cost_ratio"] = (
            столбец["cost"] / деньги_основания if деньги_основания else None
        )
        время = столбец["total_ms"]["median"]
        столбец["time_ratio"] = (
            время / время_основания if время_основания and время is not None else None
        )
