"""Прогон одной клетки опыта, замер времени и запись итога в журнал.

Клетка — это пара «модель + режим рассуждений» (`models.cells`), прогон — один запрос
к API по вопросу дня. Модуль умеет ровно две вещи: сходить в API за ответом и собрать
запись журнала, откуда её потом читают сводка и страница сравнения.

Ключ доступа сюда не попадает: клиент приходит готовым от вызывающего, а тот берёт ключ
из настроек инструмента (`myharness.config.load()`). В журнал ключ попасть не может,
потому что писать в него нечего — модуль его не видит.

Деньги здесь не считаются: снимок тарифа и стоимость приходят в `build_record` готовыми.
Так запись остаётся проверяемой без часов и без тарифа, а сам тариф живёт в одном месте —
в `models.pricing`.
"""

from __future__ import annotations

import asyncio
import json
import logging
import subprocess
import time
from contextlib import aclosing
from dataclasses import dataclass, field
from datetime import UTC, datetime
from functools import lru_cache
from pathlib import Path

from models.cells import QUESTION_TEXT, Cell, cell_params

# --- настройки прогона --------------------------------------------------------

#: Журнал прогонов: одна строка JSON на прогон. Путь абсолютный, считается от расположения
#: модуля, а не от места запуска: живой прогон ведётся из песочницы `test/`, а журнал должен
#: лечь туда же, где его ищут сводка и страница сравнения, — в `day_5/data/`.
DATA_PATH = Path(__file__).resolve().parent.parent / "data" / "runs.jsonl"

#: Паузы перед второй и последующими попытками, секунды.
ПАУЗЫ_ПОПЫТОК: tuple[int, ...] = (1, 2)

#: Сколько раз пробуем прогон, прежде чем признать его проваленным. Выведено из числа пауз:
#: первая попытка идёт без паузы, каждая следующая — со своей. Связывать эти две величины
#: вручную нельзя: правка одной дала бы `IndexError` на последней попытке, и вылезло бы это
#: только на живом прогоне, посреди оплаченных запросов.
ATTEMPTS: int = len(ПАУЗЫ_ПОПЫТОК) + 1

#: Текст ошибки для клетки, в которую вопреки настройке пришли рассуждения.
ОШИБКА_РАССУЖДЕНИЙ = "пришли рассуждения при выключенном thinking"

#: Сюда уходят жалобы на сбой записи и показа: молча терять их нельзя, а поднимать выше —
#: значит ронять прогон из-за того, что кто-то закрыл браузер.
ЖУРНАЛ_СООБЩЕНИЙ = logging.getLogger(__name__)


# --- итог одного прогона ------------------------------------------------------


@dataclass
class CellResult:
    """Что вышло из одного прогона клетки.

    Изменяемый (в отличие от `Cell`) намеренно: значение копится по ходу потока событий,
    и заводить новый объект на каждый кусок ответа было бы расточительно.

    Три величины времени лежат порознь, а не одной длительностью, потому что опыт дня
    меряет именно разницу между ними: `ttft_ms` — сколько модель молчит до первого
    признака жизни, `ttfa_ms` — до первого слова самого ответа. У клетки с рассуждениями
    эти величины расходятся, у клетки без них совпадают, и в этом расхождении весь смысл.
    """

    cell_id: str
    repetition: int
    answer: str = ""
    finish_reason: str | None = None
    usage: dict = field(default_factory=dict)
    ttft_ms: int = 0  # до первого события любого рода
    ttfa_ms: int = 0  # до первого события с содержимым ответа
    total_ms: int = 0
    tokens_per_sec: float | None = None
    warmup: bool = False
    status: str = "ok"  # "ok" | "error"
    error: str | None = None


# --- имена и служебные сведения -----------------------------------------------


def run_key(cell_id: str, repetition: int) -> str:
    """Имя прогона вида `flash_plain_r3` — идентификатор клетки и номер повтора."""
    return f"{cell_id}_r{repetition}"


@lru_cache(maxsize=1)
def code_version() -> str:
    """Короткая фиксация git, на которой сделан прогон, или `"unknown"`.

    Записи живут дольше памяти о них: через месяц по журналу надо понять, каким кодом он
    собран. Ответ запоминается: за один прогон код не меняется, а вызывать git на каждую
    из десятков записей незачем.

    Любой сбой (нет git, каталог не репозиторий, пустой репозиторий) — это `"unknown"`,
    а не исключение: отсутствие приписки не повод терять собранные данные.
    """
    try:
        готово = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"],
            cwd=Path(__file__).resolve().parent,
            capture_output=True,
            text=True,
            timeout=5,
            check=False,
        )
    except (OSError, subprocess.SubprocessError):
        return "unknown"
    if готово.returncode != 0:
        return "unknown"
    return готово.stdout.strip() or "unknown"


# --- запись в журнал ----------------------------------------------------------


def build_record(
    result: CellResult,
    cell: Cell,
    params: dict,
    снимок: dict,
    cost: float,
) -> dict:
    """Словарь одной строки журнала.

    Запись самодостаточна: в ней лежит полный текст вопроса, модель, режим рассуждений,
    параметры запроса, снимок тарифа и фиксация кода. Читать её можно, не имея под рукой
    ни этого модуля, ни набора клеток той версии, на которой прогон делался, — а вопрос
    и тариф живут в коде и меняются, тогда как запись остаётся свидетельством о прошлом.

    Снимок тарифа и стоимость приходят готовыми: считать их здесь значило бы привязать
    сборку записи к текущему часу (надбавка за пик) и к текущей цене, и проверить её
    стало бы нечем.
    """
    return {
        "run_key": run_key(result.cell_id, result.repetition),
        "cell_id": result.cell_id,
        "repetition": result.repetition,
        "timestamp": datetime.now(UTC).isoformat(),
        "model": cell.model,
        "thinking": cell.thinking,
        "question_text": QUESTION_TEXT,
        "params": params,
        "answer": result.answer,
        "finish_reason": result.finish_reason,
        "usage": result.usage,
        "ttft_ms": result.ttft_ms,
        "ttfa_ms": result.ttfa_ms,
        "total_ms": result.total_ms,
        "tokens_per_sec": result.tokens_per_sec,
        "pricing": снимок,
        "cost": cost,
        "warmup": result.warmup,
        "status": result.status,
        "error": result.error,
        "code_version": code_version(),
    }


def append_record(record: dict, path: Path = DATA_PATH) -> None:
    """Дописывает одну строку JSON в журнал, заводя недостающие каталоги.

    Русский текст сохраняется как есть (`ensure_ascii=False`): журнал читают глазами при
    разборе прогона, а экранированные последовательности вида `\\u043e` читать невозможно.
    """
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a", encoding="utf-8") as файл:
        файл.write(json.dumps(record, ensure_ascii=False) + "\n")


def collected_repeats(path: Path = DATA_PATH) -> dict[str, int]:
    """По каждой клетке — наибольший номер повтора среди её непрогревочных записей.

    Это ответ на вопрос «с какого номера продолжать»: следующий прогон начинается с
    `значение + 1`. Статус записи здесь не смотрится намеренно: номер, по которому в
    журнал уже писалось, занят навсегда. Считай мы занятыми только успешные номера,
    целиком упавший последний прогон — обрыв связи под конец, обычное дело — освободил бы
    свой номер, следующее нажатие кнопки выдало бы тот же, и в журнале появились бы две
    записи с одним `run_key`. Ключ перестал бы быть именем прогона, а сводка молча теряла
    бы одну из двух записей, причём какую — как повезёт с порядком обхода.

    Размен принят сознательно: целиком провалившийся прогон держит свой номер навсегда, и
    строка таблицы останется неполной. Дырка в таблице видна человеку и объясняется
    записями об ошибке, а две записи с одним ключом не видны никому.

    Прогревочные записи — исключение: прогрев платит за установку соединения и в таблицу
    не идёт, поэтому и номера он не занимает. Иначе каждый прогрев сдвигал бы нумерацию
    настоящих прогонов, и в таблице появлялись бы пропущенные номера.

    Отбор идёт по пригодности записи к разбору, а не по её статусу: пропускается всё, из
    чего нельзя достать пару «клетка — номер», — не JSON, не словарь, нестроковый
    `cell_id`, нецелый или отсутствующий `repetition`. Испорченная строка не роняет
    разбор файла: журнал дописывается по ходу живого прогона, и оборванная на полуслове
    последняя строка — обычное дело.

    Клетка, о которой в журнале нет ни одной пригодной записи, в словаре отсутствует.
    """
    path = Path(path)
    if not path.exists():
        return {}

    собрано: dict[str, int] = {}
    with path.open(encoding="utf-8") as файл:
        for сырая in файл:
            строка = сырая.strip()
            if not строка:
                continue
            try:
                запись = json.loads(строка)
            except json.JSONDecodeError:
                continue
            if not isinstance(запись, dict):
                continue
            if запись.get("warmup"):
                continue
            идентификатор = запись.get("cell_id")
            повтор = запись.get("repetition")
            # `bool` — подкласс `int`, а `True` в роли номера повтора это мусор, а не единица.
            if not isinstance(идентификатор, str) or not isinstance(повтор, int):
                continue
            if isinstance(повтор, bool):
                continue
            if повтор > собрано.get(идентификатор, 0):
                собрано[идентификатор] = повтор
    return собрано


# --- прогон -------------------------------------------------------------------


def _скорость(итог: CellResult) -> float | None:
    """Токенов ответа в секунду, считая от первого события потока, либо `None`.

    Знаменатель берётся от первого события, а не от отправки запроса: до первого события
    модель ещё думает, и включив это молчание в знаменатель, мы измеряли бы не скорость
    выдачи, а смесь скорости с задержкой — причём число вышло бы столь же правдоподобным.

    Нулевой или отрицательный знаменатель (весь ответ пришёл одним куском, часы не успели
    тикнуть) — это `None`: скорость неизвестна, а не бесконечна.
    """
    знаменатель = (итог.total_ms - итог.ttft_ms) / 1000
    if знаменатель <= 0:
        return None
    токены = итог.usage.get("completion_tokens")
    if isinstance(токены, bool) or not isinstance(токены, (int, float)):
        return None
    return токены / знаменатель


async def run_cell(
    client,
    cell: Cell,
    repetition: int,
    warmup: bool = False,
) -> CellResult:
    """Один запрос к API: ответ, три величины времени, расход токенов и скорость выдачи.

    Устройство: до `ATTEMPTS` попыток с паузами `ПАУЗЫ_ПОПЫТОК`. Каждая попытка заводит
    свой пустой итог — куски прошлой, оборванной попытки не должны склеиваться с новым
    ответом. Время меряется по каждой попытке отдельно: в записи стоит время той попытки,
    чей ответ и сохранён.

    Исключение наружу не выходит: исчерпав попытки, прогон возвращается со `status="error"`
    и текстом последней ошибки. Один упавший прогон не должен ронять весь опыт — иначе
    единственный сбой сети стоил бы всех уже оплаченных запросов.
    """
    последняя_ошибка = ""
    for попытка in range(ATTEMPTS):
        if попытка:
            await asyncio.sleep(ПАУЗЫ_ПОПЫТОК[попытка - 1])

        итог = CellResult(cell_id=cell.id, repetition=repetition, warmup=warmup)
        куски: list[str] = []
        рассуждения = False
        первое_событие: float | None = None
        первый_ответ: float | None = None
        начало = time.perf_counter()
        try:
            поток = client.stream_chat(
                cell.model,
                [{"role": "user", "content": QUESTION_TEXT}],
                cell_params(cell),
            )
            # `aclosing` закрывает поток явно, если попытка оборвалась исключением. Иначе
            # закрытие достаётся сборщику мусора, и в stderr сыплются жалобы на незакрытые
            # асинхронные генераторы — этот шум описан прямо в `myharness/api.py`.
            async with aclosing(поток) as события:
                async for событие in события:
                    # Часы снимаются первым же делом, до разбора события, до записи в
                    # журнал и до отправки на страницу. Замер обязан говорить о модели,
                    # а не о том, сколько заняла отрисовка на нашей стороне.
                    сейчас = time.perf_counter()
                    if первое_событие is None:
                        первое_событие = сейчас
                    if событие.kind == "content":
                        if первый_ответ is None:
                            первый_ответ = сейчас
                        куски.append(событие.text)
                    elif событие.kind == "reasoning":
                        рассуждения = True
                    elif событие.kind == "meta":
                        итог.finish_reason = событие.finish_reason
                        итог.usage = событие.usage
        except Exception as исключение:  # noqa: BLE001 — сбой прогона не роняет опыт
            последняя_ошибка = f"{type(исключение).__name__}: {исключение}"
            continue

        конец = time.perf_counter()
        if первое_событие is not None:
            итог.ttft_ms = int((первое_событие - начало) * 1000)
        if первый_ответ is not None:
            итог.ttfa_ms = int((первый_ответ - начало) * 1000)
        итог.total_ms = int((конец - начало) * 1000)
        итог.answer = "".join(куски)
        итог.tokens_per_sec = _скорость(итог)
        if рассуждения and not cell.thinking:
            # Рассуждения при выключенном режиме означают, что настройка не применилась:
            # сервер ответил не тем режимом, о котором просили. По времени и деньгам такой
            # прогон принадлежит другому столбцу таблицы, и ставить его в один ряд с
            # остальными нельзя. Ответ всё же сохраняем — по нему видно, что именно пришло.
            итог.status = "error"
            итог.error = ОШИБКА_РАССУЖДЕНИЙ
        return итог

    return CellResult(
        cell_id=cell.id,
        repetition=repetition,
        warmup=warmup,
        status="error",
        error=последняя_ошибка,
    )
