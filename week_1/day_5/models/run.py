"""Прогон одной клетки опыта, замер времени, вердикт и запись итога в журнал.

Клетка — это пара «модель + режим рассуждений» (`models.cells`), прогон — один запрос
к API по вопросу дня. Модуль умеет ровно две вещи: сходить в API за ответом и собрать
запись журнала, откуда её потом читают сводка и страница сравнения.

Ключ доступа сюда не попадает: клиент приходит готовым от вызывающего, а тот берёт ключ
из настроек инструмента (`myharness.config.load()`). В журнал ключ попасть не может,
потому что писать в него нечего — модуль его не видит.

Деньги в сборку записи не приходят посчитанными изнутри: снимок тарифа и стоимость
`build_record` получает готовыми. Так запись остаётся проверяемой без часов и без тарифа,
а сам тариф живёт в одном месте — в `models.pricing`. Считает деньги обход прогона
(`run_all`), у которого есть и момент вызова, и ответ API с расходом токенов.
"""

