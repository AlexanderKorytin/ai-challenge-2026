def _скорость(итог: CellResult) -> float | None:
    """Токенов ответа в секунду, считая от первого события потока, либо `None`.

    Знаменатель берётся от первого события, а не от отправки запроса: до первого события
    модель ещё думает, и включив это молчание в знаменатель, мы измеряли бы не скорость
    выдачи, а смесь скорости с задержкой — причём число вышло бы столь же правдоподобным.

    Нулевой или отрицательный знаменатель (весь ответ пришёл одним куском, часы не успели
    тикнуть) — это `None`: скорость неизвестна, а не бесконечна. Незамеренное время
    первого события — тоже `None`: считать от нуля значило бы приписать модели скорость,
    которую никто не мерил.

    Ноль токенов ответа за ненулевое время — та же неизвестность, а не скорость «ноль
    токенов в секунду». Ноль, попав в медиану столбца полноправным значением, занизил бы
    её тем сильнее, чем чаще ответ приходил пустым, — то есть ровно на тех клетках, где
    и без того что-то не так.
    """
    if итог.ttft_ms is None:
        return None
    знаменатель = (итог.total_ms - итог.ttft_ms) / 1000
    if знаменатель <= 0:
        return None
    токены = итог.usage.get("completion_tokens")
    if isinstance(токены, bool) or not isinstance(токены, (int, float)):
        return None
    if токены <= 0:
        return None
    return токены / знаменатель


def request_params(cell: Cell, max_tokens: int | None = None) -> dict[str, Any]:
    """Параметры запроса для клетки, при надобности с потолком длины ответа.

    Потолок стоит отдельным необязательным доводом, а не выводится из признака прогрева:
    «это прогревочный вызов» и «обрежь ответ» — две разные вещи, и связав их, мы завели бы
    скрытую зависимость, из-за которой боевая клетка однажды молча получила бы потолок.

    Возвращается всегда свежая копия (её делает `cell_params`): вложенный `thinking`,
    розданный по ссылке, попал бы одним объектом во все записи журнала.
    """
    параметры = cell_params(cell)
    if max_tokens is not None:
        параметры["max_tokens"] = max_tokens
    return параметры


async def run_cell(
    client,
    cell: Cell,
    repetition: int,
    warmup: bool = False,
    max_tokens: int | None = None,
) -> CellResult:
    """Один запрос к API: ответ, три величины времени, расход токенов и скорость выдачи.

    Устройство: до `ATTEMPTS` попыток с паузами `ПАУЗЫ_ПОПЫТОК`. Каждая попытка заводит
    свой пустой итог — куски прошлой, оборванной попытки не должны склеиваться с новым
    ответом. Время меряется по каждой попытке отдельно: в записи стоит время той попытки,
    чей ответ и сохранён. Число понадобившихся попыток остаётся в `attempts`: за оборванную
    попытку провайдер тоже берёт деньги, а её расход в `usage` не попадает, и без этого
    числа итог дня занижен ровно на тех клетках, которые вели себя хуже прочих.

    Исключение наружу не выходит: исчерпав попытки, прогон возвращается со `status="error"`
    и текстом последней ошибки. Один упавший прогон не должен ронять весь опыт — иначе
    единственный сбой сети стоил бы всех уже оплаченных запросов.
    """
    последняя_ошибка = ""
    for попытка in range(ATTEMPTS):
        if попытка:
            await asyncio.sleep(ПАУЗЫ_ПОПЫТОК[попытка - 1])

        итог = CellResult(cell_id=cell.id, repetition=repetition, warmup=warmup)
        куски: list[str] = []
        рассуждения = False
        первое_событие: float | None = None
        первый_ответ: float | None = None
        начало = time.perf_counter()
        try:
            поток = client.stream_chat(
                cell.model,
                [{"role": "user", "content": QUESTION_TEXT}],
                request_params(cell, max_tokens),
            )
            # `aclosing` закрывает поток явно, если попытка оборвалась исключением. Иначе
            # закрытие достаётся сборщику мусора, и в stderr сыплются жалобы на незакрытые
            # асинхронные генераторы — этот шум описан прямо в `myharness/api.py`.
            async with aclosing(поток) as события:
                async for событие in события:
                    # Часы снимаются первым же делом, до разбора события, до записи в
                    # журнал и до отправки на страницу. Замер обязан говорить о модели,
                    # а не о том, сколько заняла отрисовка на нашей стороне.
                    сейчас = time.perf_counter()
                    if первое_событие is None:
                        первое_событие = сейчас
                    if событие.kind == "content":
                        if первый_ответ is None:
                            первый_ответ = сейчас
                        куски.append(событие.text)
                    elif событие.kind == "reasoning":
                        рассуждения = True
                    elif событие.kind == "meta":
                        итог.finish_reason = событие.finish_reason
                        # Тип проверяется здесь, у самой границы, а не у каждого
                        # читателя. Приди в `usage` не словарь — `None` от сервера,
                        # который не прислал учёта, — и `итог.usage.get(...)` уронил бы
                        # прогон `AttributeError` уже за пределами этого `try`, унеся с
                        # собой все оставшиеся оплаченные клетки. Защита у входа
                        # избавляет от неё каждого, кто это поле потом читает.
                        итог.usage = (
                            событие.usage if isinstance(событие.usage, dict) else {}
                        )
        except Exception as исключение:  # noqa: BLE001 — сбой прогона не роняет опыт
            последняя_ошибка = f"{type(исключение).__name__}: {исключение}"
            continue

        конец = time.perf_counter()
        if первое_событие is not None:
            итог.ttft_ms = int((первое_событие - начало) * 1000)
        if первый_ответ is not None:
            итог.ttfa_ms = int((первый_ответ - начало) * 1000)
        итог.total_ms = int((конец - начало) * 1000)
        итог.answer = "".join(куски)
        # Вердикт достаётся здесь, сразу после склейки: разметка перестала быть чтением
        # глазами и стала измерением, а измеряемая величина обязана лежать в той же
        # записи журнала, что и ответ, из которого она получена. Достань её потом
        # страница или сводка — они разбирали бы текст по своим правилам, и два разбора
        # разошлись бы молча.
        итог.verdict = extract_verdict(итог.answer)
        итог.attempts = попытка + 1
        итог.tokens_per_sec = _скорость(итог)
        if рассуждения and not cell.thinking:
            # Рассуждения при выключенном режиме означают, что настройка не применилась:
            # сервер ответил не тем режимом, о котором просили. По времени и деньгам такой
            # прогон принадлежит другому столбцу таблицы, и ставить его в один ряд с
            # остальными нельзя. Ответ всё же сохраняем — по нему видно, что именно пришло.
            итог.status = "error"
            итог.error = ОШИБКА_РАССУЖДЕНИЙ
        elif первый_ответ is None:
            # Ни одного события с содержимым: ответа нет, мерить нечего, `ttfa_ms`
            # остался незамеренным. Такой прогон бывает законно, но успешным он
            # притворяться не должен — иначе сводка усреднит его наравне с настоящими.
            # Проверка идёт после рассуждений: если сервер ответил не тем режимом,
            # об этом надо говорить в первую очередь, пустота — уже следствие.
            итог.status = "error"
            итог.error = ОШИБКА_ПУСТОГО_ОТВЕТА
        return итог

    return CellResult(
        cell_id=cell.id,
        repetition=repetition,
        warmup=warmup,
        attempts=ATTEMPTS,
        status="error",
        error=последняя_ошибка,
    )


# --- прогрев и обход прогона ---------------------------------------------------


def _стоимость_прогона(usage: dict, снимок: dict, имя: str) -> float:
    """Деньги за один вызов, а при испорченном учёте токенов — ноль и жалоба в журнал.

    `models.pricing.стоимость` отказывается считать по негодному `usage` (отрицательное
    число, строка вместо числа) — и правильно делает: тихо посчитанная неверная сумма
    ушла бы в итог дня, не подняв шума. Но ронять из-за неё прогон нельзя: ответ уже
    получен и уже оплачен. Поэтому цена такой клетки — `0.0`, а сырой `usage` всё равно
    ложится в журнал, и деньги пересчитаются по нему задним числом.
    """
    try:
        return pricing.стоимость(usage, снимок)
    except ValueError:
        ЖУРНАЛ_СООБЩЕНИЙ.exception(
            "учёт токенов клетки %s негоден, цена не посчитана", имя
        )
        return 0.0


def _посчитать_деньги(итог: CellResult, снимок: dict, имя: str) -> None:
    """Кладёт снимок тарифа и посчитанную по нему цену в сам итог.

    Именно в итог, а не сразу в запись журнала: тот же объект уходит на страницу через
    `on_result`, и цифра на экране обязана быть той же самой, что в журнале. Посчитай
    страница цену сама — она взяла бы свой снимок тарифа, по своему моменту, и у клетки
    на границе пикового окна два числа разошлись бы вдвое, ничем себя не выдав.
    """
    итог.pricing = снимок
    итог.cost = _стоимость_прогона(итог.usage, снимок, имя)


async def warmup(client, path: Path = DATA_PATH) -> None:
    """Один дешёвый вызов до начала опыта, чтобы соединение уже стояло.

    Зачем. Первый вызов после старта процесса платит сверх ответа за установление
    соединения — разрешение имени, TCP, TLS. Без прогрева эта плата целиком попала бы в
    замер первого боевого прогона и выглядела бы свойством модели, хотя она свойство
    процесса. Прогрев переносит её на вызов, который никто не меряет.

    Здесь и только здесь запросу задаётся потолок длины (`ПОТОЛОК_ПРОГРЕВА`), и причина
    ровно одна: прогревочный ответ не измеряется и не читается, платить за полный ответ,
    которого никто не увидит, незачем. Боевым клеткам потолок запрещён — он обрезал бы
    клетки с рассуждениями сильнее прочих и сам создавал бы ту разницу, которую опыт
    измеряет.

    Разбор потока свой не заводится: вызов идёт через тот же `run_cell`, что и боевые
    клетки. Прогрев обязан пройти ровно тем же путём, иначе он прогреет не то; а копия
    разбора рано или поздно разошлась бы с оригиналом молча.

    Итог уходит в журнал с `warmup=True` и никуда больше: на страницу он не показывается
    (`on_result` тут нет вовсе) и номера прогона не занимает — `collected_repeats`
    прогревочные записи пропускает.

    Неудавшийся прогрев остаётся жалобой в `ЖУРНАЛ_СООБЩЕНИЙ` и записи не оставляет:
    сообщать в данных нечего — соединение не установилось, денег не потрачено. Опыт
    от этого не отменяется: прогрев — удобство, а не его условие.
    """
    клетка = КЛЕТКА_ПРОГРЕВА
    имя = run_key(клетка.id, НОМЕР_ПРОГРЕВА)
    try:
        # Снимок берётся до отправки, по тому же правилу, что и в `run_all`: надбавка за
        # пиковый час относится к моменту, в который вызов ушёл, а не вернулся.
        снимок = pricing.снимок(клетка.model, datetime.now(UTC))
        итог = await run_cell(
            client,
            клетка,
            НОМЕР_ПРОГРЕВА,
            warmup=True,
            max_tokens=ПОТОЛОК_ПРОГРЕВА,
        )
        if итог.status != "ok":
            ЖУРНАЛ_СООБЩЕНИЙ.warning("прогрев соединения не удался: %s", итог.error)
            return
        _посчитать_деньги(итог, снимок, имя)
        append_record(
            build_record(итог, клетка, request_params(клетка, ПОТОЛОК_ПРОГРЕВА)), path
        )
    except Exception:  # noqa: BLE001 — сбой прогрева не отменяет платный опыт
        ЖУРНАЛ_СООБЩЕНИЙ.exception("прогрев соединения не удался")


async def run_all(
    client,
    start_repetition: int,
    count: int,
    on_result: Callable[[CellResult], None],
    path: Path = DATA_PATH,
) -> None:
    """Весь опыт: `count` прогонов, в каждом — все клетки `CELLS`, строго по одному.

    Строго последовательно, без `asyncio.Semaphore` и без `asyncio.gather`. В дне 4 клетки
    летели по четыре сразу, и там это было уместно: измерялось содержимое ответа. Здесь
    измеряется время, и одновременные запросы испортили бы ровно то, ради чего опыт
    ставится. Они дерутся и за наш событийный цикл — пока один поток разбирает событие,
    остальные ждут своей очереди на разбор, и это ожидание ляжет в их замер, — и за
    очередь на стороне провайдера. Разброс времени начал бы выглядеть свойством модели,
    хотя он был бы свойством момента запуска.

    Внешний цикл — по номерам прогонов, внутренний — по клеткам. Порядок именно такой,
    чтобы прерванный на середине опыт оставлял целые прогоны, а не половину столбцов с
    пятью повторами и половину без единого.

    Сначала запись, потом показ. Гарантия у этого порядка одна и скромная: попытка
    записать клетку делается раньше, чем клетка показана. Совпадения экрана с журналом он
    не даёт — отказ записи логируется, и показ идёт своим чередом, потому что ронять из-за
    диска оплаченный прогон нельзя. Но при обратном порядке к тому же расхождению
    добавилось бы второе, устранимое: показ, упавший на закрытом браузере, уносил бы с
    собой и запись клетки, которая на самом деле состоялась.

    Ни отказ записи, ни отказ показа прогон не роняют: обе беды уходят в
    `ЖУРНАЛ_СООБЩЕНИЙ` и остаются внутри своей клетки. `on_result` — это отправка в поток
    событий страницы, и она падает от простого закрытия браузера; уронив на этом прогон,
    мы выбросили бы уже оплаченные ответы и не досчитали бы оставшиеся клетки.

    Деньги считаются здесь, потому что здесь есть обе недостающие сборке записи величины:
    момент вызова (от него зависит надбавка за пиковый час) и ответ API с расходом
    токенов. Снимок тарифа берётся **до** запроса, а не после: считать надбавку по
    времени возврата значило бы приписать вызову цену того часа, в который он закончился,
    а не того, в который ушёл, — и клетка на границе пикового окна ошиблась бы вдвое.
    Посчитанное ложится в сам итог, и на страницу уходит та же цифра, что в журнал.
    """
    for повтор in range(start_repetition, start_repetition + count):
        for клетка in CELLS:
            имя = run_key(клетка.id, повтор)
            параметры = request_params(клетка)
            снимок = pricing.снимок(клетка.model, datetime.now(UTC))

            итог = await run_cell(client, клетка, повтор)

            _посчитать_деньги(итог, снимок, имя)
            try:
                append_record(build_record(итог, клетка, параметры), path)
            except Exception:  # noqa: BLE001 — отказ записи не отменяет оплаченную работу
                ЖУРНАЛ_СООБЩЕНИЙ.exception("клетка %s не записана в журнал", имя)
            try:
                on_result(итог)
            except Exception:  # noqa: BLE001 — отказ показа не отменяет оплаченную работу
                ЖУРНАЛ_СООБЩЕНИЙ.exception("обработчик клетки %s отказал", имя)
