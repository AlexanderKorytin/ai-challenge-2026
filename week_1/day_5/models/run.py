# --- итог одного прогона ------------------------------------------------------


@dataclass
class CellResult:
    """Что вышло из одного прогона клетки.

    Изменяемый (в отличие от `Cell`) намеренно: значение копится по ходу потока событий,
    и заводить новый объект на каждый кусок ответа было бы расточительно.

    Три величины времени лежат порознь, а не одной длительностью, потому что опыт дня
    меряет именно разницу между ними: `ttft_ms` — сколько модель молчит до первого
    признака жизни, `ttfa_ms` — до первого слова самого ответа. У клетки с рассуждениями
    эти величины расходятся, у клетки без них совпадают, и в этом расхождении весь смысл.

    Незамеренное время — это `None`, а не ноль. Ноль здесь был бы ложью: он читается как
    «ответ пришёл мгновенно» и полноправно входит в среднее, занижая заглавную величину
    дня. Отсутствие замера обязано называть себя отсутствием.

    Цена и снимок тарифа лежат прямо в итоге, а не только в записи журнала. Причина —
    единственный источник цифры: страница получает итог через `on_result` и обязана
    показать ровно то число, которое легло в журнал. Считай она цену сама, у клетки,
    начатой до границы пикового окна и законченной после неё, экран разошёлся бы с
    журналом ровно вдвое — и молча.
    """

    cell_id: str
    repetition: int
    answer: str = ""
    #: Первое слово ответа, приведённое к «да» или «нет», либо `None`, если вердикта в
    #: ответе не нашлось. `None` — это не сбой, а наблюдение: модель не выполнила
    #: требование формы, и по столбцам таких случаев видно, кому оно далось хуже.
    #: На `status` вердикт не влияет: клетка, ответившая не по форме, остаётся
    #: полноправной в замерах времени и денег — она ведь ответила, и за неё заплачено.
    verdict: str | None = None
    finish_reason: str | None = None
    usage: dict = field(default_factory=dict)
    ttft_ms: int | None = None  # до первого события любого рода
    ttfa_ms: int | None = None  # до первого события с содержимым ответа
    total_ms: int = 0
    tokens_per_sec: float | None = None
    #: Сколько попыток понадобилось. Больше единицы означает, что за оборванные попытки
    #: провайдеру тоже заплачено, а их расход в `usage` не попал: считать деньги по такой
    #: клетке можно только с оглядкой на это число.
    attempts: int = 1
    cost: float = 0.0
    pricing: dict = field(default_factory=dict)
    warmup: bool = False
    status: str = "ok"  # "ok" | "error"
    error: str | None = None


# --- имена и служебные сведения -----------------------------------------------


def run_key(cell_id: str, repetition: int) -> str:
    """Имя прогона вида `flash_plain_r3` — идентификатор клетки и номер повтора."""
    return f"{cell_id}_r{repetition}"


@lru_cache(maxsize=1)
def code_version() -> str:
    """Короткая фиксация git, на которой сделан прогон, или `"unknown"`.

    Записи живут дольше памяти о них: через месяц по журналу надо понять, каким кодом он
    собран. Ответ запоминается: за один прогон код не меняется, а вызывать git на каждую
    из десятков записей незачем.

    Любой сбой (нет git, каталог не репозиторий, пустой репозиторий) — это `"unknown"`,
    а не исключение: отсутствие приписки не повод терять собранные данные.
    """
    try:
        готово = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"],
            cwd=Path(__file__).resolve().parent,
            capture_output=True,
            text=True,
            timeout=5,
            check=False,
        )
    except (OSError, subprocess.SubprocessError):
        return "unknown"
    if готово.returncode != 0:
        return "unknown"
    return готово.stdout.strip() or "unknown"


# --- запись в журнал ----------------------------------------------------------


def build_record(result: CellResult, cell: Cell, params: dict) -> dict:
    """Словарь одной строки журнала.

    Запись самодостаточна: в ней лежит полный текст вопроса, модель, режим рассуждений,
    параметры запроса, снимок тарифа и фиксация кода. Читать её можно, не имея под рукой
    ни этого модуля, ни набора клеток той версии, на которой прогон делался, — а вопрос
    и тариф живут в коде и меняются, тогда как запись остаётся свидетельством о прошлом.

    Снимок тарифа и стоимость берутся из самого итога, посчитанные в момент прогона.
    Считать их здесь значило бы привязать сборку записи к текущему часу (надбавка за пик)
    и к текущей цене, и проверить её стало бы нечем. А главное — цифра остаётся одна на
    всех: и в журнале, и на странице, которой тот же итог уходит через `on_result`.
    """
    return {
        "run_key": run_key(result.cell_id, result.repetition),
        "cell_id": result.cell_id,
        "repetition": result.repetition,
        "timestamp": datetime.now(UTC).isoformat(),
        "model": cell.model,
        "thinking": cell.thinking,
        "question_text": QUESTION_TEXT,
        "params": params,
        "answer": result.answer,
        "verdict": result.verdict,
        "finish_reason": result.finish_reason,
        "usage": result.usage,
        "ttft_ms": result.ttft_ms,
        "ttfa_ms": result.ttfa_ms,
        "total_ms": result.total_ms,
        "tokens_per_sec": result.tokens_per_sec,
        "attempts": result.attempts,
        "pricing": result.pricing,
        "cost": result.cost,
        "warmup": result.warmup,
        "status": result.status,
        "error": result.error,
        "code_version": code_version(),
    }


def append_record(record: dict, path: Path = DATA_PATH) -> None:
    """Дописывает одну строку JSON в журнал, заводя недостающие каталоги.

    Русский текст сохраняется как есть (`ensure_ascii=False`): журнал читают глазами при
    разборе прогона, а экранированные последовательности вида `\\u043e` читать невозможно.
    """
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a", encoding="utf-8") as файл:
        файл.write(json.dumps(record, ensure_ascii=False) + "\n")


def collected_repeats(path: Path = DATA_PATH) -> dict[str, int]:
    """По каждой клетке — наибольший номер повтора среди её непрогревочных записей.

    Это ответ на вопрос «с какого номера продолжать»: следующий прогон начинается с
    `значение + 1`. Статус записи здесь не смотрится намеренно: номер, по которому в
    журнал уже писалось, занят навсегда. Считай мы занятыми только успешные номера,
    целиком упавший последний прогон — обрыв связи под конец, обычное дело — освободил бы
    свой номер, следующее нажатие кнопки выдало бы тот же, и в журнале появились бы две
    записи с одним `run_key`. Ключ перестал бы быть именем прогона, а сводка молча теряла
    бы одну из двух записей, причём какую — как повезёт с порядком обхода.

    Размен принят сознательно: целиком провалившийся прогон держит свой номер навсегда, и
    строка таблицы останется неполной. Дырка в таблице видна человеку и объясняется
    записями об ошибке, а две записи с одним ключом не видны никому.

    Прогревочные записи — исключение: прогрев платит за установку соединения и в таблицу
    не идёт, поэтому и номера он не занимает. Иначе каждый прогрев сдвигал бы нумерацию
    настоящих прогонов, и в таблице появлялись бы пропущенные номера.

    Отбор идёт по пригодности записи к разбору, а не по её статусу: пропускается всё, из
    чего нельзя достать пару «клетка — номер», — не JSON, не словарь, нестроковый
    `cell_id`, нецелый или отсутствующий `repetition`. Испорченная строка не роняет
    разбор файла: журнал дописывается по ходу живого прогона, и оборванная на полуслове
    последняя строка — обычное дело.

    Клетка, о которой в журнале нет ни одной пригодной записи, в словаре отсутствует.
    """
    path = Path(path)
    if not path.exists():
        return {}

    собрано: dict[str, int] = {}
    # `errors="replace"` не косметика: декодирование идёт построчно, до `json.loads`, и
    # журнал пишется русскими буквами как есть (`ensure_ascii=False`). Оборванная на
    # полуслове последняя строка рвётся посреди многобайтового символа, и строгое
    # декодирование бросило бы `UnicodeDecodeError` мимо `except json.JSONDecodeError`
    # ниже — то есть закрыло бы доступ ко всему журналу целиком из-за одного хвоста.
    # С заменой битый хвост просто не разберётся как JSON и отсеется там, где положено.
    with path.open(encoding="utf-8", errors="replace") as файл:
        for сырая in файл:
            строка = сырая.strip()
            if not строка:
                continue
            try:
                запись = json.loads(строка)
            except json.JSONDecodeError:
                continue
            if not isinstance(запись, dict):
                continue
            if запись.get("warmup"):
                continue
            идентификатор = запись.get("cell_id")
            повтор = запись.get("repetition")
            # `bool` — подкласс `int`, а `True` в роли номера повтора это мусор, а не единица.
            if not isinstance(идентификатор, str) or not isinstance(повтор, int):
                continue
            if isinstance(повтор, bool):
                continue
            # Наличие ключа проверяется отдельно от сравнения: `собрано.get(..., 0)`
            # молча выбросил бы клетку, все записи которой имеют номер ноль или меньше.
            # Такой клетки в опыте быть не должно, но пропасть из словаря она обязана
            # только вместе с журналом, а не из-за выбранного значения по умолчанию.
            if идентификатор not in собрано or повтор > собрано[идентификатор]:
                собрано[идентификатор] = повтор
    return собрано


