"""Клетки опыта, вопрос дня и параметры запроса для каждой клетки.

Здесь только данные: ни запросов к API, ни клиентов, ни чтения файлов. Клетка — это
пара «модель + режим рассуждений», то есть один столбец таблицы прогонов; всё
остальное в опыте одинаково, чтобы разница в ответах говорила о клетке, а не о том,
что вопрос или параметры кому-то достались другие.
"""

from __future__ import annotations

import copy
import re
from dataclasses import dataclass
from typing import Any

# --- описание клетки ----------------------------------------------------------


@dataclass(frozen=True)
class Cell:
    """Одна клетка опыта — столбец таблицы прогонов.

    Неизменяемый (`frozen=True`) намеренно: один и тот же объект клетки обслуживает
    все прогоны своего столбца, и случайная правка поля испортила бы не один прогон,
    а весь столбец разом — причём задним числом, потому что уже показанные прогоны
    ссылаются на тот же объект.
    """

    id: str
    title: str
    role: str
    model: str
    thinking: bool


# --- набор клеток -------------------------------------------------------------
#
# У DeepSeek по API доступны всего две модели, поэтому лестницу «слабая → средняя →
# сильная» нельзя выстроить одним размером весов: третьей ступени просто неоткуда
# взяться. Средняя ступень строится второй осью — режимом рассуждений: та же младшая
# модель, но ей позволено думать перед ответом.
#
# Четвёртая клетка, pro_plain, — контрольная. Без неё нельзя ответить на главный
# вопрос опыта: закрывает ли включение рассуждений у младшей модели весь разрыв до
# старшей, или часть разрыва держится на самой модели. Сравнивать есть с чем только
# тогда, когда старшая модель прогнана в обоих режимах.

CELLS: tuple[Cell, ...] = (
    Cell(
        id="flash_plain",
        title="flash без рассуждений",
        role="слабая",
        model="deepseek-v4-flash",
        thinking=False,
    ),
    Cell(
        id="flash_think",
        title="flash с рассуждениями",
        role="средняя",
        model="deepseek-v4-flash",
        thinking=True,
    ),
    Cell(
        id="pro_plain",
        title="pro без рассуждений",
        role="контрольная",
        model="deepseek-v4-pro",
        thinking=False,
    ),
    Cell(
        id="pro_think",
        title="pro с рассуждениями",
        role="сильная",
        model="deepseek-v4-pro",
        thinking=True,
    ),
)

_ПО_ИДЕНТИФИКАТОРУ: dict[str, Cell] = {клетка.id: клетка for клетка in CELLS}


def by_id(cell_id: str) -> Cell:
    """Клетка по идентификатору. Неизвестный идентификатор — KeyError."""
    return _ПО_ИДЕНТИФИКАТОРУ[cell_id]


# --- вопрос дня ---------------------------------------------------------------
#
# Задача на рассуждение, где верный ответ противоречит первому впечатлению. Веларий —
# знаменитый тент Колизея, и вопрос сформулирован так, будто он может чем-то помочь
# ночному освещению. Помочь он не может: это плотная ткань, она свет **загораживает**,
# а не распределяет. Вдобавок веларий накрывал трибуны, а не арену, и полная луна
# светит примерно в четыреста тысяч раз слабее солнца — освещать арену там нечем в
# принципе. Верный ответ — **нет**.
#
# Чтобы ответить, модели надо свести три области сразу: астрономию (яркость луны и её
# положение в полночь), устройство Колизея (что именно накрывал веларий) и свойства
# льняной ткани. Ошибиться можно в любой из трёх, и ошибка в любой даёт «да».
#
# В отличие от прошлых вопросов дня, к тексту добавлена **одна** инструкция о форме
# ответа: первым словом «да» или «нет». Это сознательная смена подхода. Раньше добавок
# избегали, чтобы не подсказывать модели наличие подвоха; здесь подвоха в форме нет —
# вопрос прямой, и требование назвать ответ первым словом ничего о нём не сообщает.
# Зато оно превращает разметку из чтения глазами в измерение: вердикт достаётся из
# ответа программой и считается по столбцам без участия человека.

ТЕКСТ_ЗАДАЧИ = (
    "Представь, что в древнем Риме в Колизее решили провести гладиаторский бой ровно "
    "в полночь при абсолютно безоблачном небе и полной луне. Организаторы хотят, чтобы "
    "арена была максимально освещена лунным светом, но при этом зрители на верхних "
    "ярусах не страдали от резких теней. Поможет ли им в этом знаменитый веларий "
    "(тент Колизея)? Обоснуй свой ответ, учитывая астрономию, архитектуру Колизея "
    "и свойства материалов того времени"
)

#: Единственная добавка к тексту задачи. Отдельной строкой и отдельным именем, чтобы
#: в журнале и в отчёте было видно, что именно мы просили сверх самой задачи.
ТРЕБОВАНИЕ_ФОРМЫ = "Первым словом ответа напиши да или нет."

QUESTION_TEXT: str = f"{ТЕКСТ_ЗАДАЧИ}\n\n{ТРЕБОВАНИЕ_ФОРМЫ}"

#: Верный ответ. Записан здесь, а не в отчёте, чтобы разметка была проверяема кодом,
#: а не памятью: подсчёт попаданий сверяется именно с этим значением.
ВЕРНЫЙ_ОТВЕТ = "нет"


#: Сколько прогонов делается по одному нажатию кнопки.
#:
#: Трёх хватает, чтобы отличить «почти всегда путается» от «почти всегда угадывает», и не
#: хватает для статистически значимых утверждений — выводы из таблицы формулируются
#: осторожно. Ровно столько же было в дне 4, и по той же причине.
#:
#: Верхнюю границу задала не статистика, а время. На этом вопросе клетки с рассуждениями
#: думают по 40–90 секунд, и один прогон всех четырёх клеток занимает около двух минут.
#: Пять прогонов — это четверть часа непрерывной записи экрана, большую часть которой
#: таблица просто ждёт. Нажать кнопку второй раз никто не мешает: прогоны допишутся
#: следующими номерами, а не затрут собранное.
REPEATS: int = 3


# --- разбор ответа ------------------------------------------------------------
#
# Слово целиком, вместе с внутренними дефисами. Дефис внутрь взят намеренно: без него
# «да-да» распалось бы на «да» и хвост, то есть вердикт читался бы по началу слова —
# ровно та ошибка, из-за которой «нетривиальный» превратился бы в «нет». Цифры и
# подчёркивание из букв исключены (`[^\W\d_]`), чтобы слово не срасталось с разметкой.
#
# Оформление отдельно снимать не нужно: звёздочки, кавычки, знак заголовка, дефис
# пункта списка, номер пункта и знаки препинания буквами не являются и в слово не
# попадают — «**Нет**», ««Нет»», «### Нет» и «1. Нет» дают одно и то же слово.
_СЛОВО = re.compile(r"[^\W\d_]+(?:-[^\W\d_]+)*")

#: Что считается вердиктом. Ровно два слова — других вариантов вопрос не предполагает,
#: а додумывать их («ага», «конечно», «увы») значило бы решать за модель.
ВЕРДИКТЫ = frozenset({"да", "нет"})


def extract_verdict(answer: str) -> str | None:
    """Вердикт «да»/«нет» из ответа модели или None, если ни того ни другого нет.

    Берётся **первое встреченное в ответе отдельное слово** «да» или «нет», где угодно
    в тексте — не обязательно первое слово ответа. Форма ответа при разметке не важна:
    «Однозначно нет» и «Ответ: нет» — это «нет», модель ответила по существу, и
    наказывать её за невыполненную просьбу назвать вердикт первым словом мы не будем.
    Сама просьба из текста вопроса не убрана: она делает разбор надёжнее, просто её
    невыполнение больше ничего не стоит.

    Слово сверяется целиком, а не по началу: «нетривиальный», «недостаточно», «нету»,
    «даже» начинаются с нужных букв, но вердиктами не являются. По той же причине не
    считается вердиктом удвоение через дефис: «да-да» — другое слово, и за ним почти
    всегда идёт возражение.

    **Принятая цена правила.** Ответ «Если бы речь шла о солнце — да, но здесь нет»
    будет размечен как «да», хотя по смыслу он отрицательный. Это не недосмотр: чтобы
    разобрать такую фразу, нужен судья, разбирающий смысл, а заводить его мы
    сознательно не стали — судья ошибается по-своему, и его ошибки не видны, в отличие
    от этой. Случай закреплён отдельной проверкой.

    Пустой и отсутствующий ответ (обрыв обмена с API) вердикта не дают и разбор не
    роняют.
    """
    if not answer:
        return None
    for совпадение in _СЛОВО.finditer(answer):
        слово = совпадение.group().lower()
        if слово in ВЕРДИКТЫ:
            return слово
    return None


# --- параметры запроса --------------------------------------------------------
#
# Больше в запросе не задаётся ничего: ни потолка длины (`max_tokens`), ни
# температуры, ни формата ответа. Потолок длины особенно вреден именно здесь — он
# обрезал бы клетки с рассуждениями и не обрезал остальные, то есть сам создавал бы
# ту разницу, которую опыт измеряет. Сервер применит свои умолчания, одинаковые для
# всех четырёх клеток.

#: Заготовки параметров. Рассуждения у DeepSeek включены по умолчанию, поэтому
#: включать их нечем — выключение задаётся явно, включение молчанием.
_БЕЗ_РАССУЖДЕНИЙ: dict[str, Any] = {"thinking": {"type": "disabled"}}
_С_РАССУЖДЕНИЯМИ: dict[str, Any] = {}


def cell_params(cell: Cell) -> dict[str, Any]:
    """Параметры запроса для клетки — всегда свежая глубокая копия.

    Копия, а не общая заготовка, потому что внутри лежит вложенный словарь
    `thinking`. Розданный по ссылке, он попал бы одним и тем же объектом в каждую
    запись журнала прогонов, и одна случайная правка переписала бы задним числом
    параметры всего прогона — журнал перестал бы быть свидетельством о том, что
    на самом деле уходило в API.
    """
    заготовка = _С_РАССУЖДЕНИЯМИ if cell.thinking else _БЕЗ_РАССУЖДЕНИЙ
    return copy.deepcopy(заготовка)
