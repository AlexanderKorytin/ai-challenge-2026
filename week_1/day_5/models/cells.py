"""Клетки опыта, вопрос дня и параметры запроса для каждой клетки.

Здесь только данные: ни запросов к API, ни клиентов, ни чтения файлов. Клетка — это
пара «модель + режим рассуждений», то есть один столбец таблицы прогонов; всё
остальное в опыте одинаково, чтобы разница в ответах говорила о клетке, а не о том,
что вопрос или параметры кому-то достались другие.
"""

from __future__ import annotations

import copy
from dataclasses import dataclass
from typing import Any

# --- описание клетки ----------------------------------------------------------


@dataclass(frozen=True)
class Cell:
    """Одна клетка опыта — столбец таблицы прогонов.

    Неизменяемый (`frozen=True`) намеренно: один и тот же объект клетки обслуживает
    все прогоны своего столбца, и случайная правка поля испортила бы не один прогон,
    а весь столбец разом — причём задним числом, потому что уже показанные прогоны
    ссылаются на тот же объект.
    """

    id: str
    title: str
    role: str
    model: str
    thinking: bool


# --- набор клеток -------------------------------------------------------------
#
# У DeepSeek по API доступны всего две модели, поэтому лестницу «слабая → средняя →
# сильная» нельзя выстроить одним размером весов: третьей ступени просто неоткуда
# взяться. Средняя ступень строится второй осью — режимом рассуждений: та же младшая
# модель, но ей позволено думать перед ответом.
#
# Четвёртая клетка, pro_plain, — контрольная. Без неё нельзя ответить на главный
# вопрос опыта: закрывает ли включение рассуждений у младшей модели весь разрыв до
# старшей, или часть разрыва держится на самой модели. Сравнивать есть с чем только
# тогда, когда старшая модель прогнана в обоих режимах.

CELLS: tuple[Cell, ...] = (
    Cell(
        id="flash_plain",
        title="flash без рассуждений",
        role="слабая",
        model="deepseek-v4-flash",
        thinking=False,
    ),
    Cell(
        id="flash_think",
        title="flash с рассуждениями",
        role="средняя",
        model="deepseek-v4-flash",
        thinking=True,
    ),
    Cell(
        id="pro_plain",
        title="pro без рассуждений",
        role="контрольная",
        model="deepseek-v4-pro",
        thinking=False,
    ),
    Cell(
        id="pro_think",
        title="pro с рассуждениями",
        role="сильная",
        model="deepseek-v4-pro",
        thinking=True,
    ),
)

_ПО_ИДЕНТИФИКАТОРУ: dict[str, Cell] = {клетка.id: клетка for клетка in CELLS}


def by_id(cell_id: str) -> Cell:
    """Клетка по идентификатору. Неизвестный идентификатор — KeyError."""
    return _ПО_ИДЕНТИФИКАТОРУ[cell_id]


# --- вопрос дня ---------------------------------------------------------------
#
# Текст уходит в API дословно, без единой добавки о формате ответа. Добавка была бы
# подсказкой: любое указание, как оформить ответ, сообщает модели, что в задаче есть
# подвох и её проверяют, — и стирает ту самую разницу между клетками, ради которой
# ставится опыт. Тире в тексте — длинное («—»), это часть дословной формулировки,
# а не оформление исходного текста.
#
# Задача-ловушка, и ловушка здесь двойная. Отвлекающие признаки не просто присутствуют,
# они перевешивают: пешком до мойки сто метров, а на машине — четыре километра через
# развязку в больших пробках. Любой расчёт «как быстрее добраться» уверенно скажет
# «пешком». Но добираться нужно не самому: моют машину, и без неё на мойке делать
# нечего. Девятнадцатый этаж и подземная парковка добавлены к тому же — они удлиняют
# путь до автомобиля и подталкивают оставить его дома.
#
# Верный ответ — на машине. Обоснование модель вправе давать любое, лишь бы по смыслу.

QUESTION_TEXT: str = (
    "Я сижу дома на 19 этаже мне нужно помыть машину. "
    "Она на подземной парковке дома. "
    "Автомойка находится в 100 метрах от дома. "
    "Погода отличная, а на дорогах большие пробки и ехать нужно через развязку "
    "4 километра. "
    "Как лучше добраться — пешком или на машине"
)

#: Сколько прогонов делается по одному нажатию кнопки. Пяти хватает, чтобы отличить
#: «почти всегда путается» от «почти всегда угадывает», и не хватает для
#: статистически значимых утверждений — выводы из таблицы формулируются осторожно.
REPEATS: int = 5


# --- параметры запроса --------------------------------------------------------
#
# Больше в запросе не задаётся ничего: ни потолка длины (`max_tokens`), ни
# температуры, ни формата ответа. Потолок длины особенно вреден именно здесь — он
# обрезал бы клетки с рассуждениями и не обрезал остальные, то есть сам создавал бы
# ту разницу, которую опыт измеряет. Сервер применит свои умолчания, одинаковые для
# всех четырёх клеток.

#: Заготовки параметров. Рассуждения у DeepSeek включены по умолчанию, поэтому
#: включать их нечем — выключение задаётся явно, включение молчанием.
_БЕЗ_РАССУЖДЕНИЙ: dict[str, Any] = {"thinking": {"type": "disabled"}}
_С_РАССУЖДЕНИЯМИ: dict[str, Any] = {}


def cell_params(cell: Cell) -> dict[str, Any]:
    """Параметры запроса для клетки — всегда свежая глубокая копия.

    Копия, а не общая заготовка, потому что внутри лежит вложенный словарь
    `thinking`. Розданный по ссылке, он попал бы одним и тем же объектом в каждую
    запись журнала прогонов, и одна случайная правка переписала бы задним числом
    параметры всего прогона — журнал перестал бы быть свидетельством о том, что
    на самом деле уходило в API.
    """
    заготовка = _С_РАССУЖДЕНИЯМИ if cell.thinking else _БЕЗ_РАССУЖДЕНИЙ
    return copy.deepcopy(заготовка)
