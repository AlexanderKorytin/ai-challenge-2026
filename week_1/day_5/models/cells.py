"""Клетки опыта, вопрос дня и параметры запроса для каждой клетки.

Здесь только данные: ни запросов к API, ни клиентов, ни чтения файлов. Клетка — это
пара «модель + режим рассуждений», то есть один столбец таблицы прогонов; всё
остальное в опыте одинаково, чтобы разница в ответах говорила о клетке, а не о том,
что вопрос или параметры кому-то достались другие.
"""

from __future__ import annotations

import copy
import re
from dataclasses import dataclass
from typing import Any

# --- описание клетки ----------------------------------------------------------


@dataclass(frozen=True)
class Cell:
    """Одна клетка опыта — столбец таблицы прогонов.

    Неизменяемый (`frozen=True`) намеренно: один и тот же объект клетки обслуживает
    все прогоны своего столбца, и случайная правка поля испортила бы не один прогон,
    а весь столбец разом — причём задним числом, потому что уже показанные прогоны
    ссылаются на тот же объект.
    """

    id: str
    title: str
    role: str
    model: str
    thinking: bool


# --- набор клеток -------------------------------------------------------------
#
# У DeepSeek по API доступны всего две модели, поэтому лестницу «слабая → средняя →
# сильная» нельзя выстроить одним размером весов: третьей ступени просто неоткуда
# взяться. Средняя ступень строится второй осью — режимом рассуждений: та же младшая
# модель, но ей позволено думать перед ответом.
#
# Четвёртая клетка, pro_plain, — контрольная. Без неё нельзя ответить на главный
# вопрос опыта: закрывает ли включение рассуждений у младшей модели весь разрыв до
# старшей, или часть разрыва держится на самой модели. Сравнивать есть с чем только
# тогда, когда старшая модель прогнана в обоих режимах.

CELLS: tuple[Cell, ...] = (
    Cell(
        id="flash_plain",
        title="flash без рассуждений",
        role="слабая",
        model="deepseek-v4-flash",
        thinking=False,
    ),
    Cell(
        id="flash_think",
        title="flash с рассуждениями",
        role="средняя",
        model="deepseek-v4-flash",
        thinking=True,
    ),
    Cell(
        id="pro_plain",
        title="pro без рассуждений",
        role="контрольная",
        model="deepseek-v4-pro",
        thinking=False,
    ),
    Cell(
        id="pro_think",
        title="pro с рассуждениями",
        role="сильная",
        model="deepseek-v4-pro",
        thinking=True,
    ),
)

_ПО_ИДЕНТИФИКАТОРУ: dict[str, Cell] = {клетка.id: клетка for клетка in CELLS}


def by_id(cell_id: str) -> Cell:
    """Клетка по идентификатору. Неизвестный идентификатор — KeyError."""
    return _ПО_ИДЕНТИФИКАТОРУ[cell_id]


# --- вопрос дня ---------------------------------------------------------------
#
# Логическая задача о пяти складах — разновидность известной загадки Эйнштейна. Пять
# складов в ряд, у каждого свой цвет, профессия работника, напиток, еда и зверь;
# четырнадцать подсказок задают всё однозначно.
#
# Подвох в самом вопросе: пиццы среди подсказок нет вовсе. Названы котлета, хлеб,
# пельмени и макароны — четыре еды из пяти, и пицца это та самая пятая, о которой
# не сказано ничего. Найти её можно только решив задачу целиком: сначала расставить
# всё остальное, а пицца окажется в единственной оставшейся клетке. Ровно так же в
# исходной загадке ищут владельца рыбки.
#
# Решение единственное, проверено полным перебором всех перестановок:
#
#   склад | цвет    | профессия   | напиток | еда      | зверь
#     1   | белый   | плотник     | вино    | ПИЦЦА    | медведь
#     2   | красный | электрик    | водка   | хлеб     | тигр
#     3   | зелёный | каменщик    | коньяк  | пельмени | пума
#     4   | синий   | портной     | виски   | макароны | леопард
#     5   | жёлтый  | программист | ром     | котлета  | пятый
#
# Верный ответ — **плотник**.
#
# Текст задачи приведён дословно, добавлены только переводы строк между подсказками:
# в исходной записи точки шли без пробелов, и подсказки слипались в одну строку.
# Смысл от переносов не меняется, а читаемость — и на странице, и в кадре видео —
# меняется сильно.

ТЕКСТ_ЗАДАЧИ = """Реши логическую задачу:
На улице стоят пять складов.
Каменщик работает в зеленом складе.
У портного есть леопард.
На желтом складе едят котлету.
Электрик ест хлеб.
Желтый склад стоит сразу справа от синего склада.
Тот, кто пьет коньяк разводит пуму.
В белом складе пьют вино.
В центральном складе едят пельмени.
Плотник работает на первом складе.
Сосед того, кто пьет водку, держит медведя.
На складе по соседству с тем, в котором держат тигра, пьют вино.
Тот, кто пьет виски, ест макароны.
Программист пьет ром.
Плотник работает рядом с красным складом.
Кто ест пиццу?"""

#: Единственная добавка к тексту задачи, и сделана она ради зрителя записи экрана:
#: ответ виден с одного взгляда, без вчитывания в абзац рассуждений. На разметку она
#: не влияет — засчитывается ответ где угодно в тексте.
ТРЕБОВАНИЕ_ФОРМЫ = "Первым словом ответа напиши профессию."

QUESTION_TEXT: str = f"{ТЕКСТ_ЗАДАЧИ}\n\n{ТРЕБОВАНИЕ_ФОРМЫ}"

#: Все ответы, которые считаются ответом по существу. Здесь это пять профессий из
#: условия: назвать можно любую, верна одна.
ВЕРДИКТЫ = frozenset({"каменщик", "портной", "электрик", "плотник", "программист"})

#: Верный ответ. Записан здесь, а не в отчёте, чтобы разметка была проверяема кодом,
#: а не памятью: подсчёт попаданий сверяется именно с этим значением, и страница
#: берёт его отсюда же через настройки, а не вшивает в разметку.
ВЕРНЫЙ_ОТВЕТ = "плотник"


#: Сколько прогонов делается по одному нажатию кнопки.
#:
#: Трёх хватает, чтобы отличить «почти всегда путается» от «почти всегда угадывает», и не
#: хватает для статистически значимых утверждений — выводы из таблицы формулируются
#: осторожно. Ровно столько же было в дне 4, и по той же причине.
#:
#: Верхнюю границу задала не статистика, а время. На этом вопросе клетки с рассуждениями
#: думают по 40–90 секунд, и один прогон всех четырёх клеток занимает около двух минут.
#: Пять прогонов — это четверть часа непрерывной записи экрана, большую часть которой
#: таблица просто ждёт. Нажать кнопку второй раз никто не мешает: прогоны допишутся
#: следующими номерами, а не затрут собранное.
REPEATS: int = 1


# --- разбор ответа ------------------------------------------------------------
#
# Оформление, которым модель обрамляет первое слово: пробелы и переводы строк,
# звёздочки жирного начертания, знак цитаты и заголовка, кавычки любого вида, тире
# и дефис пункта списка, номер пункта («1.», «2)»). Всё это стоит **перед** словом и
# к самому слову не относится — иначе вердикт терялся бы из-за одной звёздочки.
_ОФОРМЛЕНИЕ = r"""(?:[\s*_>#`«»"'“”‘’\-–—]|\d+[.)])*"""

# Слово целиком, вместе с внутренними дефисами. Дефис внутрь взят намеренно: без него
# «плотник-краснодеревщик» распалось бы на «плотник» и хвост, то есть вердикт читался
# бы по началу слова — ровно та ошибка, из-за которой «плотничает» превратилось бы в
# «плотник». Цифры и подчёркивание из букв исключены (`[^\W\d_]`), чтобы слово не
# срасталось с разметкой.
_ПЕРВОЕ_СЛОВО = re.compile(_ОФОРМЛЕНИЕ + r"([^\W\d_]+(?:-[^\W\d_]+)*)")


def extract_verdict(answer: str) -> str | None:
    """Профессия из первого слова ответа или None, если первым словом её нет.

    Вердикт берётся **только из первого слова** и по тексту не разыскивается. Причина
    в самой задаче: она решается таблицей, и модель почти наверняка назовёт по ходу
    разбора все пять профессий — в порядке подсказок, а не в порядке складов. Первое
    встреченное в тексте слово из `ВЕРДИКТЫ` было бы тогда словом из рассуждения, а не
    ответом: мы измеряли бы порядок изложения. Требование назвать профессию первым
    словом стоит прямо в тексте вопроса, так что спрос по первому слову честен.

    Цена решения признаётся прямо: ответ, начатый с «Разберём подсказки», останется
    без вердикта, даже если внизу стоит верный вывод. Это не потеря — пустая клетка
    означает «ответила не по форме» и проверяема глазами по сохранённому тексту, тогда
    как подхваченное из рассуждения слово выглядело бы полноценным ответом и молча
    искажало бы подсчёт попаданий.

    Слово сверяется целиком и только в именительном падеже — так, как профессия
    называется в ответе. Сравнение по началу слова приняло бы за вердикт «плотничает»,
    «программирование» и «электричество», а отделять окончания по-настоящему умеет
    лишь морфологический разбор — отдельная библиотека и отдельный источник ошибок
    ради одной клетки таблицы. Нераспознанный вердикт виден в таблице пустой клеткой,
    распознанный неверно — не виден никак.

    Пустой и отсутствующий ответ (обрыв обмена с API) вердикта не дают и разбор не
    роняют.
    """
    if not answer:
        return None
    совпадение = _ПЕРВОЕ_СЛОВО.match(answer)
    if совпадение is None:
        return None
    слово = совпадение.group(1).lower()
    return слово if слово in ВЕРДИКТЫ else None


# --- параметры запроса --------------------------------------------------------
#
# Больше в запросе не задаётся ничего: ни потолка длины (`max_tokens`), ни
# температуры, ни формата ответа. Потолок длины особенно вреден именно здесь — он
# обрезал бы клетки с рассуждениями и не обрезал остальные, то есть сам создавал бы
# ту разницу, которую опыт измеряет. Сервер применит свои умолчания, одинаковые для
# всех четырёх клеток.

#: Заготовки параметров. Рассуждения у DeepSeek включены по умолчанию, поэтому
#: включать их нечем — выключение задаётся явно, включение молчанием.
_БЕЗ_РАССУЖДЕНИЙ: dict[str, Any] = {"thinking": {"type": "disabled"}}
_С_РАССУЖДЕНИЯМИ: dict[str, Any] = {}


def cell_params(cell: Cell) -> dict[str, Any]:
    """Параметры запроса для клетки — всегда свежая глубокая копия.

    Копия, а не общая заготовка, потому что внутри лежит вложенный словарь
    `thinking`. Розданный по ссылке, он попал бы одним и тем же объектом в каждую
    запись журнала прогонов, и одна случайная правка переписала бы задним числом
    параметры всего прогона — журнал перестал бы быть свидетельством о том, что
    на самом деле уходило в API.
    """
    заготовка = _С_РАССУЖДЕНИЯМИ if cell.thinking else _БЕЗ_РАССУЖДЕНИЙ
    return copy.deepcopy(заготовка)
