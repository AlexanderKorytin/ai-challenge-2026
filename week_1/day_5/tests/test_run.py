"""Проверки замера времени и журнала прогонов.

Проверяется `models.run` — модуль, который делает один вызов к API, засекает три
величины времени, собирает запись журнала и знает, какие номера прогонов уже заняты.

Почему это нельзя проверить глазами. Всё, что здесь измеряется, на странице прогона
выглядит одинаково правдоподобно и в верном, и в неверном случае:

1. Три величины времени. `ttft_ms` считается по первому событию любого рода, `ttfa_ms` —
   по первому событию с содержимым ответа. Перепутать их местами легко, а на экране
   разница будет в десятки миллисекунд — ровно там, где и должна быть настоящая разница
   между клетками с рассуждениями и без. Опыт дня меряет именно эту разницу, и подмена
   одной величины другой стёрла бы весь его смысл.
2. Токены в секунду. Число получится в разумных пределах при любом знаменателе — хоть
   от начала запроса, хоть от первого события. Отличить одно от другого по экрану нельзя.
3. Занятые номера прогонов. Ошибка видна только тем, что в журнале со временем заводятся
   две записи с одним ключом, и обнаруживается это на сводной странице через несколько
   прогонов, когда переделывать уже дорого.
4. Ключ доступа в записи. Журнал уходит в репозиторий; утёкший ключ на экране не виден
   вообще никак — он виден потом и посторонним.
5. Устойчивость к сбою. Одна упавшая клетка не должна ронять прогон: без этого
   единственный сбой сети стоил бы всех уже оплаченных запросов.

Сети в проверках нет: клиент подменяется заглушкой.

Класс события берётся настоящий — `myharness.api.StreamEvent`, а не свой похожий
датакласс. Причина: заглушка обязана скармливать `run_cell` ровно те объекты, которые
придут от живого клиента. Свой двойник разошёлся бы с оригиналом молча — переименованное
поле сломало бы прогон, а проверки продолжали бы проходить.

Модуль `models.run` на момент написания этих проверок ещё не существует — они обязаны
падать. Код пишется следующим шагом, под уже зафиксированные здесь ожидания.
"""

