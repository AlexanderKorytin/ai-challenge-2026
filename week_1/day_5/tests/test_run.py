def рассуждение(текст: str = "прикидываю") -> StreamEvent:
    """Событие с ходом мысли — содержимым ответа не считается."""
    return StreamEvent(kind="reasoning", text=текст)


def содержимое(текст: str) -> StreamEvent:
    """Событие с куском ответа."""
    return StreamEvent(kind="content", text=текст)


def завершение(usage: dict[str, Any] | None = None) -> StreamEvent:
    """Последнее событие потока: причина остановки и расход токенов."""
    return StreamEvent(
        kind="meta",
        finish_reason="stop",
        usage=dict(ОБРАЗЕЦ_РАСХОДА if usage is None else usage),
    )


class ЗаглушкаКлиента:
    """Клиент без сети: отдаёт заданную последовательность событий.

    Умеет три вещи, которых требуют проверки: выдержать паузу перед событием (чтобы
    величины времени различались), уронить первые несколько вызовов заданным исключением
    и посчитать, сколько раз к нему обратились. Список событий повторяется на каждом
    вызове — так проверка не зависит от того, повторяет ли `run_cell` попытку.
    """

    def __init__(
        self,
        события: list[StreamEvent],
        задержки: list[float] | None = None,
        сбоев: int = 0,
    ) -> None:
        self.события = list(события)
        self.задержки = (
            list(задержки) if задержки is not None else [0.0] * len(self.события)
        )
        assert len(self.задержки) == len(self.события), "на каждое событие своя пауза"
        self.сбоев = сбоев
        self.вызовы = 0
        self.запросы: list[dict[str, Any]] = []

    def stream_chat(
        self, model: str, messages: list[dict[str, Any]], params: dict[str, Any]
    ):
        """Считает обращение сразу, а не при первом чтении потока."""
        self.вызовы += 1
        self.запросы.append({"model": model, "messages": messages, "params": params})
        return self._поток(self.вызовы)

    async def _поток(self, номер: int):
        if номер <= self.сбоев:
            raise RuntimeError(f"сбой сети №{номер}")
        for событие, пауза in zip(self.события, self.задержки):
            if пауза:
                await asyncio.sleep(пауза)
            yield событие


def убрать_паузы(monkeypatch: pytest.MonkeyPatch) -> None:
    """Обнуляет ожидание между попытками, чтобы проверка на сбой не шла минуты.

    Паузы между попытками нужны живому прогону и мешают проверке: сам предмет проверки —
    не длительность ожидания, а итог после исчерпания попыток.
    """

    async def без_ожидания(_секунд: float, *args: Any, **kwargs: Any) -> None:
        return None

    monkeypatch.setattr(asyncio, "sleep", без_ожидания)
    if hasattr(модуль_прогона, "asyncio"):
        monkeypatch.setattr(
            модуль_прогона.asyncio, "sleep", без_ожидания, raising=False
        )
    if hasattr(модуль_прогона, "ПАУЗЫ_ПОПЫТОК"):
        monkeypatch.setattr(
            модуль_прогона,
            "ПАУЗЫ_ПОПЫТОК",
            tuple(0.0 for _ in range(ATTEMPTS)),
            raising=False,
        )


def строки(записи: list[dict[str, Any]]) -> str:
    """Готовый текст журнала из готовых записей — для проверок разбора."""
    return "".join(json.dumps(запись, ensure_ascii=False) + "\n" for запись in записи)


def итог_образец(**правки: Any) -> CellResult:
    """Заполненный `CellResult`, от которого отталкиваются проверки записи журнала."""
    основа: dict[str, Any] = {
        "cell_id": "flash_plain",
        "repetition": 2,
        "answer": "Пешком: сто метров — это ближе, чем выехать со двора.",
        "finish_reason": "stop",
        "usage": dict(ОБРАЗЕЦ_РАСХОДА),
        "ttft_ms": 310,
        "ttfa_ms": 420,
        "total_ms": 1900,
        "tokens_per_sec": 125.8,
        "warmup": False,
        "status": "ok",
        "error": None,
    }
    основа.update(правки)
    return CellResult(**основа)


def обойти(значение: Any) -> list[str]:
    """Все строки, встреченные в значении вглубь: словари, списки, ключи, значения."""
    найдено: list[str] = []
    if isinstance(значение, str):
        найдено.append(значение)
    elif isinstance(значение, dict):
        for ключ, вложенное in значение.items():
            найдено.extend(обойти(ключ))
            найдено.extend(обойти(вложенное))
    elif isinstance(значение, (list, tuple, set)):
        for вложенное in значение:
            найдено.extend(обойти(вложенное))
    return найдено


