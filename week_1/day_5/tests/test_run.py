def test_ключа_доступа_в_записи_нет_ни_под_каким_именем(
    monkeypatch: pytest.MonkeyPatch,
):
    """Обход записи вглубь не находит строки ключа ни в значении, ни в имени поля.

    Журнал уходит в репозиторий. Ключ туда попасть не должен — ни отдельным полем, ни
    внутри параметров, ни в тексте ошибки. Проверяется поиском подстроки по всему дереву,
    а не по списку известных имён: опасно как раз поле, о котором никто не подумал.
    """
    monkeypatch.setenv("DEEPSEEK_API_KEY", ОБРАЗЕЦ_КЛЮЧА)
    запись = build_record(
        итог_образец(status="error", error="сеть недоступна"),
        by_id("flash_plain"),
        {"thinking": {"type": "disabled"}},
        dict(ОБРАЗЕЦ_ТАРИФА),
        0.000521,
    )
    все_строки = обойти(запись)
    assert все_строки, (
        "обход не должен возвращать пустоту — иначе проверка ничего не значит"
    )
    for строка in все_строки:
        assert ОБРАЗЕЦ_КЛЮЧА not in строка
        assert "sk-" not in строка


