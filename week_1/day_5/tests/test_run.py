def test_сбой_на_всех_попытках_не_роняет_прогон(monkeypatch: pytest.MonkeyPatch):
    """Исключение наружу не выходит: клетка помечается ошибкой и прогон идёт дальше.

    Одна упавшая клетка не должна ронять прогон целиком — иначе единственный сбой сети
    стоил бы всех уже оплаченных запросов, сделанных до него.
    """
    убрать_паузы(monkeypatch)
    клиент = ЗаглушкаКлиента([содержимое("не дойдёт"), завершение()], сбоев=ATTEMPTS)

    итог = asyncio.run(run_cell(клиент, by_id("flash_plain"), 1))

    assert итог.status == "error"
    assert клиент.вызовы == ATTEMPTS
    # В тексте — последняя ошибка, а не первая: чинить придётся по ней.
    assert f"сбой сети №{ATTEMPTS}" in (итог.error or "")
    assert итог.cell_id == "flash_plain"
    assert итог.repetition == 1


def test_успех_со_второй_попытки(monkeypatch: pytest.MonkeyPatch):
    """Один сбой сети — не повод терять клетку: вторая попытка даёт обычный итог."""
    убрать_паузы(monkeypatch)
    клиент = ЗаглушкаКлиента([содержимое("Пешком."), завершение()], сбоев=1)

    итог = asyncio.run(run_cell(клиент, by_id("flash_plain"), 4))

    assert итог.status == "ok"
    assert итог.error is None
    assert итог.answer == "Пешком."
    assert итог.usage["completion_tokens"] == ОБРАЗЕЦ_РАСХОДА["completion_tokens"]
    assert клиент.вызовы == 2


def test_рассуждения_при_выключенном_режиме_помечают_клетку_ошибкой(
    monkeypatch: pytest.MonkeyPatch,
):
    """Пришли рассуждения в клетку без рассуждений — замер испорчен, ответ сохранён.

    Рассуждения при выключенном режиме означают, что настройка не применилась: сервер
    ответил не тем режимом, о котором просили. Замер такой клетки нельзя ставить рядом с
    остальными — по времени и деньгам она принадлежит другому столбцу таблицы. Ответ при
    этом сохраняется: он пригодится при разборе, чем именно отличился этот прогон.
    """
    убрать_паузы(monkeypatch)
    клиент = ЗаглушкаКлиента(
        [рассуждение("а ведь просили не думать"), содержимое("Пешком."), завершение()]
    )

    итог = asyncio.run(run_cell(клиент, by_id("flash_plain"), 1))

    assert итог.status == "error"
    assert итог.error == ОШИБКА_РАССУЖДЕНИЙ
    assert итог.answer == "Пешком."


