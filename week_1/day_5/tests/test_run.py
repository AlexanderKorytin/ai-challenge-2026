# --- журнал, оборванный посреди русской буквы ------------------------------------------


def test_обрыв_посреди_многобайтового_символа_не_роняет_разбор(tmp_path):
    """Последняя строка обрезана внутри русской буквы — прочитанное всё равно возвращается.

    Журнал пишется русскими буквами как есть (`ensure_ascii=False`), а читается в тот
    момент, когда прогон его дописывает. По-русски «полуслово» рвётся посреди символа, и
    строгое декодирование бросило бы `UnicodeDecodeError` ещё до `json.loads` — то есть
    мимо перехвата и на весь файл сразу. Проверка на латинице этого не ловит: там любой
    срез декодируется.
    """
    путь = tmp_path / "runs.jsonl"
    append_record(
        {"cell_id": "flash_plain", "repetition": 2, "answer": ОБРАЗЕЦ_ОТВЕТА},
        путь,
    )
    хвост = json.dumps(
        {
            "cell_id": "flash_plain",
            "repetition": 3,
            "answer": "Пиццу ищут перебором, а находят вычитанием",
        },
        ensure_ascii=False,
    ).encode("utf-8")
    # Срез приходится на продолжающий байт (`10xxxxxx`) — значит символ разрезан пополам.
    срезы = [i for i in range(1, len(хвост)) if хвост[i] & 0xC0 == 0x80]
    assert срезы, "в хвосте должны быть многобайтовые символы, иначе проверка пустая"
    with путь.open("ab") as файл:
        файл.write(хвост[: срезы[-1]])

    with pytest.raises(UnicodeDecodeError):
        путь.read_text(encoding="utf-8")
    assert collected_repeats(путь) == {"flash_plain": 2}


