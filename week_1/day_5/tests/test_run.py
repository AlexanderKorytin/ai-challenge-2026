def test_запись_заводит_каталоги_и_хранит_русский_текст(tmp_path):
    """Недостающие каталоги создаются, русские буквы остаются буквами.

    `ensure_ascii=False` не мелочь оформления: журнал читают глазами при разборе
    прогона, а `\\u043f\\u0435\\u0448` глазами не читается.
    """
    путь = tmp_path / "которого" / "нет" / "runs.jsonl"
    append_record({"cell_id": "flash_plain", "answer": "Пешком"}, путь)

    assert путь.exists()
    текст = путь.read_text(encoding="utf-8")
    assert "Пешком" in текст
    assert "\\u043f" not in текст
    assert json.loads(текст.splitlines()[0])["answer"] == "Пешком"


def test_вторая_запись_дописывается_а_не_затирает(tmp_path):
    """Две записи подряд дают две строки. Перезапись стоила бы всего прогона."""
    путь = tmp_path / "runs.jsonl"
    append_record({"cell_id": "flash_plain", "repetition": 1}, путь)
    append_record({"cell_id": "flash_plain", "repetition": 2}, путь)

    строки_файла = путь.read_text(encoding="utf-8").splitlines()
    assert len(строки_файла) == 2
    assert [json.loads(строка)["repetition"] for строка in строки_файла] == [1, 2]


