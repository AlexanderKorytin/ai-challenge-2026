# --- заглушка для обхода прогона ----------------------------------------------------


class ЗаглушкаОбхода:
    """Клиент без сети, следящий за одновременностью и порядком обращений.

    Отличий от `ЗаглушкаКлиента` два, и оба нужны только обходу прогона.

    Первое: заглушка считает, сколько потоков читается одновременно, и запоминает
    наибольшее число. Проверить это можно, лишь по-настоящему уступая управление внутри
    выдачи событий (`await asyncio.sleep(0)`): без уступки сопрограмма клетки досчитала бы
    до конца одним куском, и одновременности не возникло бы даже у `asyncio.gather` —
    проверка проходила бы и на неверном коде.

    Второе: заглушка ведёт список обращений в порядке поступления — по нему видно, каким
    порядком обходятся клетки и прогоны.
    """

    def __init__(
        self, usage: dict[str, Any] | None = None, ронять: bool = False
    ) -> None:
        self.usage = dict(ОБРАЗЕЦ_РАСХОДА if usage is None else usage)
        self.ронять = ронять
        self.запросы: list[dict[str, Any]] = []
        self.внутри = 0
        self.наибольшая_одновременность = 0

    @property
    def клетки(self) -> list[tuple[str, bool]]:
        """Обращения парами «модель, режим рассуждений» — в порядке поступления.

        Режим восстанавливается по параметрам запроса, а не по нашей памяти о клетке:
        выключение задаётся явным `thinking`, включение — его отсутствием.
        """
        return [
            (запрос["model"], "thinking" not in запрос["params"])
            for запрос in self.запросы
        ]

    def stream_chat(
        self, model: str, messages: list[dict[str, Any]], params: dict[str, Any]
    ):
        self.запросы.append({"model": model, "messages": messages, "params": params})
        return self._поток()

    async def _поток(self):
        if self.ронять:
            raise RuntimeError("сбой сети")
        self.внутри += 1
        self.наибольшая_одновременность = max(
            self.наибольшая_одновременность, self.внутри
        )
        try:
            await asyncio.sleep(0)
            yield содержимое(ОБРАЗЕЦ_ОТВЕТА)
            await asyncio.sleep(0)
            yield завершение(self.usage)
        finally:
            self.внутри -= 1


def записи_журнала(путь) -> list[dict[str, Any]]:
    """Разобранные строки журнала — то, что реально легло на диск."""
    if not путь.exists():
        return []
    return [
        json.loads(строка)
        for строка in путь.read_text(encoding="utf-8").splitlines()
        if строка.strip()
    ]


