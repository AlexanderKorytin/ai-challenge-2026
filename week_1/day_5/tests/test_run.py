def test_битые_строки_журнала_пропускаются_а_не_роняют_разбор(tmp_path):
    """Одна испорченная строка не должна закрывать доступ ко всему журналу.

    Строка может оборваться на записи, если прогон убили посередине. Разбор обязан
    пройти мимо неё и вернуть всё остальное — иначе журнал станет нечитаемым целиком.
    """
    путь = tmp_path / "runs.jsonl"
    путь.write_text(
        "\n".join(
            [
                json.dumps(
                    {"cell_id": "flash_plain", "repetition": 2}, ensure_ascii=False
                ),
                "",
                "   ",
                '{"cell_id": "flash_plain", "repetition"',
                "это вовсе не JSON",
                "[1, 2, 3]",
                '"просто строка"',
                "42",
                json.dumps({"repetition": 7}, ensure_ascii=False),
                json.dumps({"cell_id": 5, "repetition": 7}, ensure_ascii=False),
                json.dumps({"cell_id": "flash_plain"}, ensure_ascii=False),
                json.dumps(
                    {"cell_id": "flash_plain", "repetition": "два"}, ensure_ascii=False
                ),
                json.dumps(
                    {"cell_id": "flash_plain", "repetition": 1.5}, ensure_ascii=False
                ),
                json.dumps(
                    {"cell_id": "flash_plain", "repetition": None}, ensure_ascii=False
                ),
            ]
        )
        + "\n",
        encoding="utf-8",
    )
    assert collected_repeats(путь) == {"flash_plain": 2}


