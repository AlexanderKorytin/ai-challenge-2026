def test_время_до_первого_события_меньше_времени_до_первого_ответа():
    """Рассуждения приходят раньше ответа — значит `ttft_ms` строго меньше `ttfa_ms`.

    Это и есть предмет опыта: сколько модель молчит до первого признака жизни и сколько
    до первого слова ответа. Если обе величины считать по одному и тому же событию,
    разница между клетками с рассуждениями и без исчезнет.
    """
    клиент = ЗаглушкаКлиента(
        [
            рассуждение(),
            содержимое("Пешком"),
            содержимое(": тут сто метров."),
            завершение(),
        ],
        задержки=[0.03, 0.03, 0.02, 0.02],
    )
    итог = asyncio.run(run_cell(клиент, by_id("flash_think"), 1))

    assert итог.status == "ok"
    assert итог.answer == "Пешком: тут сто метров."
    assert 0 < итог.ttft_ms < итог.ttfa_ms <= итог.total_ms


def test_без_рассуждений_обе_величины_совпадают():
    """Первое же событие несёт ответ — до первого события и до первого ответа одно и то же."""
    клиент = ЗаглушкаКлиента(
        [содержимое("Пешком."), содержимое(" Так быстрее."), завершение()],
        задержки=[0.03, 0.02, 0.02],
    )
    итог = asyncio.run(run_cell(клиент, by_id("flash_plain"), 1))

    assert итог.status == "ok"
    assert итог.ttft_ms == итог.ttfa_ms
    assert итог.ttfa_ms <= итог.total_ms


def test_токены_в_секунду_считаются_от_первого_события():
    """Скорость выдачи — `completion_tokens` на время от первого события до конца.

    Ожидание считается из тех самых величин, которые вернул сам `run_cell`, а не из
    заданных заглушке пауз. Причина: время здесь настоящее, планировщик задач добавляет
    свои миллисекунды, и сверка с паузами проверяла бы точность часов, а не формулу.
    Сверять же надо именно формулу: знаменатель от начала запроса вместо первого события
    дал бы столь же правдоподобное число.
    """
    клиент = ЗаглушкаКлиента(
        [содержимое("Пешком."), завершение()],
        задержки=[0.03, 0.05],
    )
    итог = asyncio.run(run_cell(клиент, by_id("flash_plain"), 1))

    assert итог.total_ms > итог.ttft_ms, "нужен ненулевой знаменатель"
    ожидание = ОБРАЗЕЦ_РАСХОДА["completion_tokens"] / (
        (итог.total_ms - итог.ttft_ms) / 1000
    )
    assert итог.tokens_per_sec == pytest.approx(ожидание, rel=0.01)
    assert итог.tokens_per_sec > 0


def test_нулевой_знаменатель_даёт_пусто_а_не_деление_на_ноль(
    monkeypatch: pytest.MonkeyPatch,
):
    """Весь ответ пришёл одним куском — скорость неизвестна, а не бесконечна.

    Часы подменяются на стоящие, чтобы случай был воспроизводимым: на настоящих часах
    ноль миллисекунд между первым событием и концом выпадает не каждый раз, и проверка
    то заходила бы в эту ветку, то нет.
    """

    def остановленные_часы() -> float:
        return 1000.0

    monkeypatch.setattr(time, "perf_counter", остановленные_часы)
    if hasattr(модуль_прогона, "perf_counter"):
        monkeypatch.setattr(
            модуль_прогона, "perf_counter", остановленные_часы, raising=False
        )

    клиент = ЗаглушкаКлиента([содержимое("Пешком."), завершение()])
    итог = asyncio.run(run_cell(клиент, by_id("flash_plain"), 1))

    assert итог.status == "ok"
    assert итог.total_ms == итог.ttft_ms == 0
    assert итог.tokens_per_sec is None


