// обращения к API.
//
// Браузера в работе нет, а проверять надо именно поведение — что нарисовано в клетке,
// когда вердикта не оказалось, закрывается ли поток по концу прогона, не ходит ли
// страница к серверу посреди прогона. Поэтому здесь заведена подмена того немногого, что
// страница требует от браузера: `document` на десяток методов, `fetch` с заготовленными
// ответами и `EventSource`, в который события кладутся руками. Скрипт страницы вынимается
// из разметки как есть и исполняется в отдельном окружении (`node:vm`) поверх этой
// подмены — проверяется тот самый код, который уйдёт в браузер, а не его пересказ.
//
// Запуск (из каталога дня):  node tests/проба_страницы.mjs
//
// Ни одного обращения к DeepSeek здесь нет и быть не может: маршрут `/run` подменён,
