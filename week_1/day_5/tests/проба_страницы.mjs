/** Поднимает страницу в своём окружении и отдаёт ручки для проверок.
 *
 *  Окружение своё на каждый стенд, а не одно на всю пробу: страница читает настройки один
 *  раз при загрузке, и проверить поведение при других настройках (например, когда сервер
 *  не прислал верного ответа) можно только на отдельно поднятой странице. */
function поднять(настройки, сводка) {
  const реестр = new Map(идентификаторы.map((id) => [id, new Узел("div")]));
  const обращения = [];
  const потоки = [];
  const стенд = { реестр, обращения, потоки, сводка };

  const document = {
    createElement: (т) => new Узел(т),
    createTextNode: (т) => new Текст(т),
    getElementById: (id) => реестр.get(id) || null,
  };

  function fetch(адрес) {
    обращения.push(адрес);
    const тело = адрес === "/settings" ? настройки : стенд.сводка;
    return Promise.resolve({ ok: true, status: 200, json: () => Promise.resolve(тело) });
  }

  class EventSource {
    constructor(адрес) { this.url = адрес; this.закрыт = false; потоки.push(this); }
    close() { this.закрыт = true; }
  }

  const контекст = vm.createContext({
    document, fetch, EventSource, setInterval, clearInterval, console, Number, Math, isFinite,
  });
  vm.runInContext(код, контекст, { filename: "page.js" });

  стенд.узел = (id) => реестр.get(id);
  стенд.тело = реестр.get("тело");
  стенд.кнопка = реестр.get("запустить");
  стенд.нажать = () => стенд.кнопка.listeners.click[0]();
  стенд.событие = (о) => потоки[потоки.length - 1].onmessage({ data: JSON.stringify(о) });
  стенд.вид = (номер) => реестр.get("виды").children[номер].children[0].listeners.change[0]();
  // Клетка таблицы прогонов: строка по порядку, столбец по номеру клетки опыта.
  стенд.клетка = (строка, столбец) => стенд.тело.children[строка].children[столбец + 1];
  return стенд;
}

