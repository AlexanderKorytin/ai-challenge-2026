def test_токены_складываются_по_каждому_виду_отдельно():
    """Попадание в промежуточное хранилище, промах, выход и рассуждения — четыре суммы.

    Ставки этих видов различаются в десятки раз, а строка «токены» в таблице объясняет
    цену клетки. Слитые в одну сумму, они дали бы правдоподобное число, из которого
    нельзя понять, на чём именно клетка с рассуждениями тратит деньги.
    """
    записи = [
        запись("flash_plain", 1, hit=10, miss=200, output=3000, reasoning=40_000),
        запись("flash_plain", 2, hit=1, miss=20, output=300, reasoning=4_000),
    ]
    столбец = клетка_сводки(сводка(записи), "flash_plain")

    assert столбец["tokens"] == {
        "cache_hit": 11,
        "cache_miss": 220,
        "output": 3300,
        "reasoning": 44_000,
    }


def test_обе_формы_токенов_рассуждений_понимаются():
    """Рассуждения приходят и вложенными в `completion_tokens_details`, и на верхнем уровне.

    Форму выбирает провайдер, а не мы. Понята одна из двух — расход рассуждений в
    половине записей молча становится нулём, и клетка с рассуждениями выглядит
    в таблице такой же дешёвой, как клетка без них.
    """
    вложенная = запись("flash_think", 1, reasoning=1500, рассуждения_подробностями=True)
    плоская = запись("flash_think", 2, reasoning=500, рассуждения_подробностями=False)

    assert вложенная["usage"]["completion_tokens_details"]["reasoning_tokens"] == 1500
    assert плоская["usage"]["reasoning_tokens"] == 500

    assert клетка_сводки(сводка([вложенная]), "flash_think")["tokens"]["reasoning"] == 1500
    assert клетка_сводки(сводка([плоская]), "flash_think")["tokens"]["reasoning"] == 500
    оба = клетка_сводки(сводка([вложенная, плоская]), "flash_think")
    assert оба["tokens"]["reasoning"] == 2000


def test_токены_упавших_записей_тоже_складываются():
    """За неудачный вызов провайдер берёт деньги, если ответ успел частично прийти.

    Из медиан времени такая запись выброшена, а из расхода — нет: токены уже потрачены.
    Иначе итог дня по деньгам занижен ровно на самые дорогие, оборвавшиеся вызовы.
    """
    записи = [
        запись("pro_think", 1, hit=100, miss=200, output=300, reasoning=400),
        запись("pro_think", 2, hit=1, miss=2, output=3, reasoning=4, status="error"),
    ]
    столбец = клетка_сводки(сводка(записи), "pro_think")

    assert столбец["n"] == 1
    assert столбец["errors"] == 1
    assert столбец["tokens"] == {
        "cache_hit": 101,
        "cache_miss": 202,
        "output": 303,
        "reasoning": 404,
    }


