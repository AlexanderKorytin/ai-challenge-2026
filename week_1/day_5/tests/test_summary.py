def test_вывод_читается_из_файла_а_без_файла_даёт_none(tmp_path):
    """Файла ещё нет — `None`, а не пустая строка и не отказ.

    Вывод пишется человеком после прогона, поэтому его отсутствие — обычное состояние
    страницы, а не сбой. Пустая строка вместо `None` не даёт отличить «ещё не написан»
    от «написан и пуст», и страница показала бы пустой раздел вместо приглашения.
    """
    отсутствующий = tmp_path / "вывод.md"
    assert вывод_из_файла(отсутствующий) is None

    отсутствующий.write_text("Вывод дня.\n", encoding="utf-8")
    assert вывод_из_файла(отсутствующий) == "Вывод дня.\n"


def test_вывод_возвращается_дословно_с_переводами_строк(tmp_path):
    """Русские буквы остаются буквами, разбивка на абзацы — разбивкой.

    Вывод показывается на странице как есть: съеденные переводы строк слепят абзацы
    в сплошное полотно, а неверная кодировка превращает текст в набор вопросительных
    знаков — и то и другое портит единственную часть отчёта, написанную человеком.
    """
    путь = tmp_path / "вывод.md"
    текст = "# Вывод\n\nПешком быстрее — сто метров.\n\n- Клетка «flash» путается.\n"
    путь.write_text(текст, encoding="utf-8")

    assert вывод_из_файла(путь) == текст
