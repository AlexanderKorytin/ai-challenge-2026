def test_деньги_складываются_из_поля_записи_а_не_пересчитываются():
    """Итог клетки — сумма полей `cost`, посчитанных в момент прогона по тогдашнему тарифу.

    Пересчёт по нынешним ставкам молча разошёлся бы с журналом при первой же смене тарифа:
    прошлая неделя начала бы стоить сегодняшних денег. Стоимость записей здесь намеренно
    не сходится с их расходом токенов — пересчёт выдал бы себя цифрой другого порядка.
    """
    записи = [
        запись("flash_plain", 1, hit=500_000, miss=500_000, output=500_000, cost=0.000001),
        запись("flash_plain", 2, hit=500_000, miss=500_000, output=500_000, cost=0.000002),
        запись("flash_plain", 3, hit=500_000, miss=500_000, output=500_000, cost=0.000004),
    ]
    столбец = клетка_сводки(сводка(записи), "flash_plain")

    assert столбец["cost"] == pytest.approx(0.000007)


