def test_отношения_считаются_по_суммам_денег_и_медианам_времени():
    """«Во столько раз дороже» — по суммарной стоимости, «во столько медленнее» — по медианам.

    Две величины сравниваются по-разному не случайно: деньги за прогон складываются, а
    время не складывается — сумма времени зависела бы от числа повторов, а не от клетки.
    """
    записи = [
        запись("flash_plain", 1, total_ms=100, cost=0.001),
        запись("flash_plain", 2, total_ms=300, cost=0.001),
        запись("pro_think", 1, total_ms=400, cost=0.003),
        запись("pro_think", 2, total_ms=800, cost=0.003),
    ]
    итог = сводка(записи)
    столбец = клетка_сводки(итог, "pro_think")

    # Основание: деньги 0.002, медиана времени 200. У клетки: деньги 0.006, медиана 600.
    assert столбец["cost"] == pytest.approx(0.006)
    assert столбец["total_ms"]["median"] == pytest.approx(600.0)
    assert столбец["cost_ratio"] == pytest.approx(3.0)
    assert столбец["time_ratio"] == pytest.approx(3.0)


def test_пустое_основание_даёт_none_а_не_деление_на_ноль():
    """У базовой клетки нет ни одной успешной записи — оба отношения `None` у всех клеток.

    Деление на ноль здесь — либо падение посреди показа страницы, либо `inf` в ячейке
    таблицы. Оба исхода обнаруживаются в самый неподходящий момент: на живом прогоне,
    когда базовая клетка отвалилась, а остальные уже посчитаны и оплачены.
    """
    записи = [
        запись("flash_plain", 1, status="error", cost=0.0),
        запись("pro_think", 1, total_ms=400, cost=0.003),
    ]
    итог = сводка(записи)

    for столбец in итог["cells"]:
        assert столбец["cost_ratio"] is None
        assert столбец["time_ratio"] is None


def test_нулевая_стоимость_основания_обнуляет_только_отношение_денег():
    """Основание бесплатное, но измеренное: денег не с чем сравнивать, время — есть.

    Знаменатели у двух отношений разные, и негодный один не повод терять другой: иначе
    первый же прогон по бесплатной квоте стёр бы из таблицы всё сравнение по времени.
    """
    записи = [
        запись("flash_plain", 1, total_ms=100, cost=0.0),
        запись("flash_plain", 2, total_ms=300, cost=0.0),
        запись("pro_think", 1, total_ms=400, cost=0.003),
        запись("pro_think", 2, total_ms=800, cost=0.003),
    ]
    итог = сводка(записи)

    основание = клетка_сводки(итог, БАЗОВАЯ_КЛЕТКА)
    assert основание["cost_ratio"] is None
    assert основание["time_ratio"] == pytest.approx(1.0)

    столбец = клетка_сводки(итог, "pro_think")
    assert столбец["cost_ratio"] is None
    assert столбец["time_ratio"] == pytest.approx(3.0)


