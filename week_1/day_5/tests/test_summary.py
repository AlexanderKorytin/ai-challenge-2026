def test_все_четыре_клетки_есть_даже_на_пустом_журнале():
    """Пустой журнал даёт четыре столбца с нулями, а не пустую таблицу.

    Пропуск столбца скрыл бы от человека, что прогон неполон: таблица из трёх клеток
    читается как законченный опыт, и вывод дня делается по трети недостающих данных.
    """
    итог = сводка([])

    assert итог["base"] == БАЗОВАЯ_КЛЕТКА == "flash_plain"
    assert len(итог["cells"]) == len(CELLS) == 4
    for столбец in итог["cells"]:
        assert столбец["n"] == 0
        assert столбец["errors"] == 0
        for величина in ("ttft_ms", "total_ms", "tokens_per_sec"):
            assert столбец[величина] == {"median": None, "min": None, "max": None}
        assert столбец["tokens"] == {
            "cache_hit": 0,
            "cache_miss": 0,
            "output": 0,
            "reasoning": 0,
        }
        assert столбец["cost"] == pytest.approx(0.0)


def test_порядок_клеток_совпадает_с_порядком_в_описании_опыта():
    """Столбцы идут в порядке `CELLS`: слева слабая клетка, справа сильная.

    Порядок — часть замысла опыта: лестница «слабая → средняя → сильная» читается слева
    направо. Сортировка по журналу переставила бы столбцы по случайности прогона.
    """
    записи = [запись("pro_think", 1), запись("flash_think", 1)]
    итог = сводка(записи)
    assert [с["cell_id"] for с in итог["cells"]] == [к.id for к in CELLS]


def test_описание_клетки_берётся_из_опыта_а_не_из_записи():
    """`title`, `role`, `model` и `thinking` приходят из `CELLS`, что бы ни лежало в записи.

    Описание клетки — свойство опыта, а не отдельного вызова. Иначе одна порченая запись
    переименовала бы целый столбец, и таблица начала бы утверждать, что опыт ставился
    не на той модели.
    """
    итог = сводка([запись("flash_plain", 1, model="совсем-другая-модель")])
    столбец = клетка_сводки(итог, "flash_plain")

    образец = by_id("flash_plain")
    assert столбец["title"] == образец.title == "flash без рассуждений"
    assert столбец["role"] == образец.role == "слабая"
    assert столбец["model"] == образец.model == "deepseek-v4-flash"
    assert столбец["thinking"] is False


# --- медиана и разброс -------------------------------------------------------------


def test_медиана_на_нечётном_числе_записей_это_средний_элемент():
    """Три записи — медиана средняя по величине, а не средняя по порядку в журнале.

    Величины намеренно записаны вразнобой: реализация без сортировки взяла бы вторую
    записанную и на этом наборе ошиблась бы втрое.
    """
    записи = [
        запись("flash_plain", 1, total_ms=100, ttft_ms=30),
        запись("flash_plain", 2, total_ms=300, ttft_ms=90),
        запись("flash_plain", 3, total_ms=200, ttft_ms=60),
    ]
    столбец = клетка_сводки(сводка(записи), "flash_plain")

    assert столбец["n"] == 3
    assert столбец["total_ms"]["median"] == pytest.approx(200)
    assert столбец["ttft_ms"]["median"] == pytest.approx(60)


def test_медиана_на_чётном_числе_записей_это_среднее_двух_средних():
    """Четыре записи — медиана посередине между вторым и третьим значением.

    Взять любое из двух средних значило бы получить число, зависящее от порядка записи
    в журнал, — и оно всё равно выглядело бы правдоподобным.
    """
    записи = [
        запись("flash_plain", 1, total_ms=100, ttft_ms=10),
        запись("flash_plain", 2, total_ms=500, ttft_ms=70),
        запись("flash_plain", 3, total_ms=200, ttft_ms=30),
        запись("flash_plain", 4, total_ms=300, ttft_ms=50),
    ]
    столбец = клетка_сводки(сводка(записи), "flash_plain")

    assert столбец["n"] == 4
    assert столбец["total_ms"]["median"] == pytest.approx(250.0)
    assert столбец["ttft_ms"]["median"] == pytest.approx(40.0)


def test_наименьшее_и_наибольшее_считаются_по_тем_же_записям():
    """Разброс берётся из того же набора, что и медиана.

    Разброс в таблице стоит рядом с медианой и читается как её края: край, посчитанный
    по другому набору, тихо соврёт о том, насколько клетка нестабильна.
    """
    записи = [
        запись("flash_plain", 1, total_ms=100, ttft_ms=30, tokens_per_sec=10.0),
        запись("flash_plain", 2, total_ms=300, ttft_ms=90, tokens_per_sec=50.0),
        запись("flash_plain", 3, total_ms=200, ttft_ms=60, tokens_per_sec=30.0),
    ]
    столбец = клетка_сводки(сводка(записи), "flash_plain")

    assert столбец["total_ms"]["min"] == 100
    assert столбец["total_ms"]["max"] == 300
    assert столбец["ttft_ms"]["min"] == 30
    assert столбец["ttft_ms"]["max"] == 90
    assert столбец["tokens_per_sec"]["min"] == pytest.approx(10.0)
    assert столбец["tokens_per_sec"]["max"] == pytest.approx(50.0)


def test_упавшие_записи_не_входят_в_медиану_но_считаются_в_сбоях():
    """Три успешных и одна упавшая: `n = 3`, `errors = 1`, медиана — по трём успешным.

    У упавшего вызова время — это время до отказа, а не до ответа. Смешанное с успешными,
    оно перекашивает медиану в любую сторону: оборвался быстро — клетка выглядит шустрой,
    отвалился по ожиданию — безнадёжно медленной.
    """
    записи = [
        запись("flash_plain", 1, total_ms=100),
        запись("flash_plain", 2, total_ms=200),
        запись("flash_plain", 3, total_ms=300),
        запись("flash_plain", 4, total_ms=10_000, tokens_per_sec=None, status="error"),
    ]
    столбец = клетка_сводки(сводка(записи), "flash_plain")

    assert столбец["n"] == 3
    assert столбец["errors"] == 1
    # По всем четырём медиана вышла бы 250 — тоже правдоподобное число.
    assert столбец["total_ms"]["median"] == pytest.approx(200)
    assert столбец["total_ms"]["max"] == 300


def test_клетка_где_упало_всё_остаётся_в_сводке_с_пустыми_величинами():
    """Ни одной успешной записи — столбец на месте, `n = 0`, `errors` больше нуля.

    Исчезнувший столбец выглядит как непоставленный опыт, а не как провалившийся, — и
    самая интересная новость дня (клетка не отвечает вовсе) пропала бы из таблицы.
    """
    записи = [
        запись("pro_think", 1, status="error"),
        запись("pro_think", 2, status="error"),
    ]
    столбец = клетка_сводки(сводка(записи), "pro_think")

    assert столбец["n"] == 0
    assert столбец["errors"] == 2
    assert столбец["total_ms"] == {"median": None, "min": None, "max": None}
    assert столбец["ttft_ms"] == {"median": None, "min": None, "max": None}
    assert столбец["tokens_per_sec"] == {"median": None, "min": None, "max": None}


def test_пустая_скорость_выбрасывает_величину_а_не_всю_запись():
    """`tokens_per_sec` равный `None` не участвует в своей медиане, но время записи считается.

    Скорость пуста, когда знаменатель вышел нулевым, — это про одну величину, а не про
    негодный прогон. Выброшенная целиком, такая запись унесла бы с собой исправно
    измеренное время и тихо уменьшила бы `n`.
    """
    записи = [
        запись("flash_plain", 1, total_ms=100, tokens_per_sec=10.0),
        запись("flash_plain", 2, total_ms=200, tokens_per_sec=20.0),
        запись("flash_plain", 3, total_ms=300, tokens_per_sec=None),
    ]
    столбец = клетка_сводки(сводка(записи), "flash_plain")

    assert столбец["n"] == 3
    assert столбец["total_ms"]["median"] == pytest.approx(200)
    assert столбец["total_ms"]["max"] == 300
    assert столбец["tokens_per_sec"]["median"] == pytest.approx(15.0)
    assert столбец["tokens_per_sec"]["max"] == pytest.approx(20.0)


