def test_негодные_строки_и_прогрев_пропускаются(tmp_path):
    """Пустая строка, не-JSON, JSON-список и прогревочная запись в разбор не идут.

    Прогревочный вызов платит за соединение и в таблицу не идёт: посчитанный наравне
    с остальными, он занизил бы медиану времени той клетки, которой достался прогрев.
    """
    путь = tmp_path / "runs.jsonl"
    путь.write_text(
        "\n".join(
            [
                json.dumps(запись("flash_plain", 1), ensure_ascii=False),
                "",
                "   ",
                "это вовсе не JSON",
                "[1, 2, 3]",
                '"просто строка"',
                json.dumps(запись("flash_plain", 9, warmup=True), ensure_ascii=False),
                json.dumps(запись("pro_think", 2), ensure_ascii=False),
            ]
        )
        + "\n",
        encoding="utf-8",
    )
    записи = читать_журнал(путь)
    assert [з["run_key"] for з in записи] == ["flash_plain_r1", "pro_think_r2"]


def test_отсутствующий_файл_журнала_даёт_пустой_список(tmp_path):
    """Журнала ещё нет — это состояние первого запуска, а не повод падать.

    Страница сводки открывается до первого прогона: отказ вместо пустого списка закрыл бы
    её насовсем и до того, как в опыте появилось хоть что-нибудь.
    """
    assert читать_журнал(tmp_path / "нет-такого.jsonl") == []


def test_оборванная_последняя_строка_не_роняет_разбор(tmp_path):
    """Файл кончается посреди записи — прочитанное до неё возвращается.

    Журнал дописывается по ходу живого прогона, а страница сводки обновляется сама.
    Попасть на середину дописываемой строки — обычное дело, а не порча файла.
    """
    путь = tmp_path / "runs.jsonl"
    целая = json.dumps(запись("flash_plain", 1), ensure_ascii=False)
    путь.write_text(целая + "\n" + '{"cell_id": "pro_think", "repet', encoding="utf-8")

    записи = читать_журнал(путь)
    assert [з["run_key"] for з in записи] == ["flash_plain_r1"]


