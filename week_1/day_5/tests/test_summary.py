"""Проверки сводки по журналу прогонов: медианы, разброс, токены, деньги, отношения.

Проверяется `models.summary` — модуль, который читает журнал прогонов и сворачивает его
в четыре столбца таблицы: медиана и разброс времени, суммы токенов по видам, деньги и
отношения к базовой клетке.

Почему это нельзя проверить глазами. Сводка — это одно число вместо двадцати записей,
и подменённое число выглядит на странице ровно так же убедительно, как верное:

1. Медиана. Взята ли она по успешным записям или по всем, посчитана ли на чётном числе
   как среднее двух средних или как случайный из них — на экране это одно и то же
   правдоподобное «1900 мс». Разница вылезет только там, где одна упавшая запись с
   огромным временем перекосит вывод дня.
2. Пропущенный столбец. Клетка, у которой все прогоны упали, легче всего исчезает из
   сводки совсем — и человек читает таблицу как полную, не зная, что четверти опыта нет.
3. Деньги. Пересчёт по тарифу вместо суммы записанного поля `cost` даёт число того же
   порядка, но расходящееся с журналом: при смене тарифа сводка начнёт врать про прошлое,
   ничем этого не обнаружив.
4. Отношения. Делить на клетку, у которой нет ни одной успешной записи, — это либо
   падение посреди показа страницы, либо `inf` в ячейке. Оба исхода видны поздно.
5. Разбор журнала. Оборванная последняя строка — обычное дело: журнал дописывается по ходу
   живого прогона, и страница обновляется прямо во время записи.

Ни сети, ни настоящего журнала здесь нет: все проверки читают и пишут только во временный
каталог `tmp_path`.

Модуль `models.summary` на момент написания этих проверок ещё не существует — они обязаны
падать. Код пишется следующим шагом, под уже зафиксированные здесь ожидания.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import pytest

from models.cells import CELLS, QUESTION_TEXT, by_id
from models.summary import (
    БАЗОВАЯ_КЛЕТКА,
    ВЫВОД_PATH,
    вывод_из_файла,
    сводка,
    читать_журнал,
)

#: Снимок тарифа в записи журнала. Здесь он только для полноты состава записи: сводка
#: обязана брать деньги из поля `cost`, а не пересчитывать их по этим ставкам заново.
ОБРАЗЕЦ_ТАРИФА: dict[str, Any] = {
    "model": "deepseek-v4-flash",
    "cache_hit": 0.007,
    "cache_miss": 0.22,
    "output": 0.66,
    "peak": False,
    "multiplier": 1.0,
    "tariff_date": "2026-09-04",
    "source": "https://api-docs.deepseek.com/quick_start/pricing",
}


# --- сбор записей ------------------------------------------------------------------


def запись(
    cell_id: str,
    номер: int = 1,
    *,
    ttft_ms: int | None = 300,
    total_ms: int | None = 1000,
    tokens_per_sec: float | None = 100.0,
    hit: int = 0,
    miss: int = 0,
    output: int = 0,
    reasoning: int = 0,
    рассуждения_подробностями: bool = True,
    cost: float = 0.0,
    status: str = "ok",
    warmup: bool = False,
    model: str | None = None,
) -> dict[str, Any]:
    """Запись журнала со всеми полями, из немногих осмысленных для сводки параметров.

    Состав полей взят из `test_run.test_состав_записи_журнала_перечислен_поимённо`: сводка
    получает записи не из проверок, а из настоящего журнала, и обеднённый словарь скрыл бы
    обращение к полю, которого в записи нет.

    `рассуждения_подробностями` выбирает, какой из двух форм записаны токены рассуждений:
    вложенной `completion_tokens_details.reasoning_tokens` или плоской `reasoning_tokens`.
    Обе приходят от провайдера, и обе модуль обязан понимать.
    """
    клетка = by_id(cell_id)
    usage: dict[str, Any] = {
        "prompt_tokens": hit + miss,
        "prompt_cache_hit_tokens": hit,
        "prompt_cache_miss_tokens": miss,
        "completion_tokens": output,
    }
    if рассуждения_подробностями:
        usage["completion_tokens_details"] = {"reasoning_tokens": reasoning}
    else:
        usage["reasoning_tokens"] = reasoning
    return {
        "run_key": f"{cell_id}_r{номер}",
        "cell_id": cell_id,
        "repetition": номер,
        "timestamp": "2026-09-04T12:00:00+00:00",
        "model": клетка.model if model is None else model,
        "thinking": клетка.thinking,
        "question_text": QUESTION_TEXT,
        "params": {},
        "answer": "Пешком." if status == "ok" else "",
        "finish_reason": "stop" if status == "ok" else None,
        "usage": usage,
        "ttft_ms": ttft_ms,
        "ttfa_ms": ttft_ms,
        "total_ms": total_ms,
        "tokens_per_sec": tokens_per_sec,
        "pricing": dict(ОБРАЗЕЦ_ТАРИФА),
        "cost": cost,
        "warmup": warmup,
        "status": status,
        "error": None if status == "ok" else "сеть недоступна",
        "code_version": "0000000",
    }


def клетка_сводки(итог: dict[str, Any], cell_id: str) -> dict[str, Any]:
    """Столбец сводки по идентификатору клетки. Отсутствие столбца — сразу отказ."""
    найденные = [с for с in итог["cells"] if с["cell_id"] == cell_id]
    assert найденные, f"в сводке нет клетки {cell_id!r}"
    return найденные[0]


