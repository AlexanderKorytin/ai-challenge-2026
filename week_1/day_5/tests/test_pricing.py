"""Проверки тарифа: пиковые часы и расчёт денег по `usage`.

Проверяется `models.pricing` — модуль, который знает цены DeepSeek за миллион токенов,
пиковые окна по UTC и формулу стоимости вызова.

Почему это нельзя проверить глазами. Ошибка в тарифе не видна на экране: страница прогона
покажет ровное число долларов и в правильном, и в неправильном случае — разница вылезет
только в личном кабинете через месяц. Три источника такой ошибки и ловятся здесь:

1. Граница пикового окна. Час туда или сюда — и вся клетка посчитана вдвое дешевле
   или вдвое дороже. По числу на экране это не отличить.
2. Часовой пояс. Наивный `datetime` молча берёт местное время Мака; в Москве это
   сдвиг на три часа, то есть половина прогона попадает не в то окно.
3. Слагаемые. Попадание в кэш дешевле промаха в тридцать раз. Если сложить их по одной
   ставке или потерять вход без разбивки по кэшу, итог останется правдоподобным числом.

Модуль `models.pricing` на момент написания этих проверок ещё не существует — они обязаны
падать. Код пишется следующим шагом, под уже зафиксированные здесь ожидания.
"""

from datetime import UTC, datetime, timedelta, timezone

import pytest

from models.pricing import (
    ДАТА_ТАРИФА,
    ИСТОЧНИК,
    МНОЖИТЕЛЬ_ПИКА,
    ЦЕНЫ,
    множитель_пика,
    снимок,
    стоимость,
)

#: Часы, вокруг которых крутятся проверки. Пиковые окна — ((1, 4), (6, 10)) по UTC.
НЕПИКОВЫЙ_ЧАС = datetime(2026, 9, 4, 12, 0, tzinfo=UTC)
ПИКОВЫЙ_ЧАС = datetime(2026, 9, 4, 3, 0, tzinfo=UTC)


def момент(час: int, минута: int = 0) -> datetime:
    """Момент указанного часа UTC того же дня — чтобы в проверках стояли только часы."""
    return datetime(2026, 9, 4, час, минута, tzinfo=UTC)


# --- Пиковые часы ------------------------------------------------------------------


def test_множитель_пика_внутри_окон_и_снаружи():
    """Середина каждого окна — надбавка, середина промежутка — обычная цена."""
    assert множитель_пика(момент(3, 0)) == МНОЖИТЕЛЬ_ПИКА == 2.0
    assert множитель_пика(момент(7, 30)) == 2.0
    assert множитель_пика(момент(5, 0)) == 1.0
    assert множитель_пика(момент(12, 0)) == 1.0


def test_граница_первого_окна_01_00_уже_пик():
    """Начало окна включительно: в 01:00 надбавка уже действует."""
    assert множитель_пика(момент(1, 0)) == 2.0


def test_граница_первого_окна_04_00_уже_не_пик():
    """Конец окна исключительно: в 04:00 надбавки уже нет."""
    assert множитель_пика(момент(4, 0)) == 1.0


def test_граница_второго_окна_06_00_уже_пик():
    """Начало второго окна включительно."""
    assert множитель_пика(момент(6, 0)) == 2.0


def test_граница_второго_окна_10_00_уже_не_пик():
    """Конец второго окна исключительно."""
    assert множитель_пика(момент(10, 0)) == 1.0


def test_минута_до_первого_окна_не_пик():
    """00:59 — ещё обычная цена. Проверка на сдвиг границы на час назад."""
    assert множитель_пика(момент(0, 59)) == 1.0


def test_последняя_минута_первого_окна_пик():
    """03:59 — ещё надбавка. Проверка на сдвиг границы на час вперёд."""
    assert множитель_пика(момент(3, 59)) == 2.0


def test_наивное_время_отклоняется():
    """Без часового пояса считать нельзя.

    Местное время Мака молча сошло бы за UTC, и граница пикового часа уехала бы
    на три часа: полночи прогона посчиталось бы не по той ставке. Лучше отказ,
    чем тихо неверный счёт.
    """
    # Пояс не задаётся намеренно — именно это и проверяется, поэтому
    # замечание ruff о недостающем поясе здесь снято осознанно.
    наивный = datetime(2026, 9, 4, 3, 0)  # noqa: DTZ001
    assert наивный.tzinfo is None
    with pytest.raises(ValueError):
        множитель_пика(наивный)


def test_время_другого_пояса_приводится_к_utc():
    """06:30 в поясе +03:00 — это 03:30 UTC, то есть пик."""
    москва = timezone(timedelta(hours=3))
    момент_мск = datetime(2026, 9, 4, 6, 30, tzinfo=москва)
    assert момент_мск.astimezone(UTC).hour == 3
    assert множитель_пика(момент_мск) == 2.0


# --- Снимок тарифа -----------------------------------------------------------------


def test_состав_снимка_в_непиковый_час():
    """Снимок несёт восемь полей: цены, признак пика, множитель и происхождение цифр."""
    записан = снимок("deepseek-v4-flash", НЕПИКОВЫЙ_ЧАС)
    assert set(записан) == {
        "model",
        "cache_hit",
        "cache_miss",
        "output",
        "peak",
        "multiplier",
        "tariff_date",
        "source",
    }
    assert записан["model"] == "deepseek-v4-flash"
    assert записан["peak"] is False
    assert записан["multiplier"] == 1.0
    assert записан["cache_hit"] == ЦЕНЫ["deepseek-v4-flash"]["cache_hit"]
    assert записан["cache_miss"] == ЦЕНЫ["deepseek-v4-flash"]["cache_miss"]
    assert записан["output"] == ЦЕНЫ["deepseek-v4-flash"]["output"]
    assert записан["tariff_date"] == ДАТА_ТАРИФА
    assert записан["source"] == ИСТОЧНИК


def test_снимок_в_пиковый_час_хранит_базовые_цены():
    """Надбавка отмечена признаком и множителем, но цены в снимке остаются базовыми.

    Так по одной записи журнала видно и ставку тарифа, и причину надбавки. Если бы снимок
    хранил уже удвоенные цены, было бы не отличить пиковую клетку от подорожавшего тарифа.
    """
    записан = снимок("deepseek-v4-flash", ПИКОВЫЙ_ЧАС)
    assert записан["peak"] is True
    assert записан["multiplier"] == 2.0
    базовые = ЦЕНЫ["deepseek-v4-flash"]
    assert записан["cache_hit"] == базовые["cache_hit"]
    assert записан["cache_miss"] == базовые["cache_miss"]
    assert записан["output"] == базовые["output"]


def test_неизвестная_модель_даёт_ошибку_с_именем():
    """Опечатка в имени клетки должна остановить прогон, а не посчитаться по нулям."""
    with pytest.raises(KeyError) as отказ:
        снимок("deepseek-v9-turbo", НЕПИКОВЫЙ_ЧАС)
    assert "deepseek-v9-turbo" in str(отказ.value)


# --- Стоимость ---------------------------------------------------------------------


def test_стоимость_одного_слагаемого_равна_тарифу():
    """Ровно миллион токенов попадания в кэш стоит ровно тарифную ставку."""
    usage = {
        "prompt_cache_hit_tokens": 1_000_000,
        "prompt_cache_miss_tokens": 0,
        "completion_tokens": 0,
    }
    деньги = стоимость(usage, снимок("deepseek-v4-flash", НЕПИКОВЫЙ_ЧАС))
    assert деньги == pytest.approx(0.007)


def test_три_слагаемых_считаются_раздельно():
    """Попадание, промах и выход идут по своим ставкам, а не по одной общей.

    Ожидаемое значение собирается тут же из отдельных слагаемых — видно, что именно
    складывается. Ставки различаются в десятки раз, поэтому подмена одной другой даёт
    правдоподобное, но неверное число.
    """
    usage = {
        "prompt_cache_hit_tokens": 500_000,
        "prompt_cache_miss_tokens": 250_000,
        "completion_tokens": 100_000,
    }
    цены = ЦЕНЫ["deepseek-v4-flash"]
    ожидание = (
        500_000 * цены["cache_hit"]
        + 250_000 * цены["cache_miss"]
        + 100_000 * цены["output"]
    ) / 1_000_000
    деньги = стоимость(usage, снимок("deepseek-v4-flash", НЕПИКОВЫЙ_ЧАС))
    assert деньги == pytest.approx(ожидание)


def test_пиковый_час_удваивает_цену():
    """Один и тот же расход токенов в пик стоит ровно вдвое дороже."""
    usage = {
        "prompt_cache_hit_tokens": 500_000,
        "prompt_cache_miss_tokens": 250_000,
        "completion_tokens": 100_000,
    }
    обычная = стоимость(usage, снимок("deepseek-v4-flash", НЕПИКОВЫЙ_ЧАС))
    пиковая = стоимость(usage, снимок("deepseek-v4-flash", ПИКОВЫЙ_ЧАС))
    assert обычная > 0
    assert пиковая / обычная == pytest.approx(2.0)


def test_пустая_usage_даёт_ноль():
    """Ответ без учёта токенов не роняет расчёт: отсутствующие поля считаются нулями."""
    assert стоимость({}, снимок("deepseek-v4-flash", НЕПИКОВЫЙ_ЧАС)) == pytest.approx(
        0.0
    )


def test_вход_без_разбивки_по_кэшу_считается_промахом():
    """Есть только `prompt_tokens` — весь вход идёт по ставке промаха.

    Считать такой вход бесплатным значило бы молча терять деньги: расход был, а в отчёте
    дня его нет. Промах — верхняя оценка, ошибка идёт в безопасную сторону.
    """
    usage = {"prompt_tokens": 1000, "completion_tokens": 0}
    цены = ЦЕНЫ["deepseek-v4-flash"]
    ожидание = 1000 * цены["cache_miss"] / 1_000_000
    деньги = стоимость(usage, снимок("deepseek-v4-flash", НЕПИКОВЫЙ_ЧАС))
    assert деньги == pytest.approx(ожидание)
    assert деньги > 0


def test_разбивка_по_кэшу_важнее_prompt_tokens():
    """Когда есть и разбивка, и общий `prompt_tokens`, берётся разбивка.

    У DeepSeek `prompt_tokens` — это сумма попаданий и промахов. Сложить их с ним значило бы
    посчитать вход дважды.
    """
    usage = {
        "prompt_tokens": 1_000_000,
        "prompt_cache_hit_tokens": 900_000,
        "prompt_cache_miss_tokens": 100_000,
        "completion_tokens": 0,
    }
    цены = ЦЕНЫ["deepseek-v4-flash"]
    по_разбивке = (
        900_000 * цены["cache_hit"] + 100_000 * цены["cache_miss"]
    ) / 1_000_000
    деньги = стоимость(usage, снимок("deepseek-v4-flash", НЕПИКОВЫЙ_ЧАС))
    assert деньги == pytest.approx(по_разбивке)


def test_разные_модели_дают_разную_цену():
    """Старшая клетка дороже младшей на одном и том же расходе токенов."""
    usage = {
        "prompt_cache_hit_tokens": 500_000,
        "prompt_cache_miss_tokens": 250_000,
        "completion_tokens": 100_000,
    }
    flash = стоимость(usage, снимок("deepseek-v4-flash", НЕПИКОВЫЙ_ЧАС))
    pro = стоимость(usage, снимок("deepseek-v4-pro", НЕПИКОВЫЙ_ЧАС))
    assert pro > flash


# --- Негодный учёт токенов ----------------------------------------------------------
#
# Этих проверок изначально не было, и зазор нашёлся ровно здесь. Поля учёта приходят
# из чужого ответа: там бывает `null`, там может не быть половины разбивки, а испорченное
# значение обязано остановить расчёт, а не превратиться в правдоподобную сумму.


def test_prompt_tokens_равный_null_не_роняет_расчёт():
    """`null` в поле учёта — то же самое, что отсутствие поля: ноль, а не падение.

    В ответе API пустое поле приходит именно как `null`. Расчёт, падающий `TypeError`
    из середины формулы, отменял бы прогон целой клетки на ровном месте.
    """
    usage = {"prompt_tokens": None, "completion_tokens": None}
    деньги = стоимость(usage, снимок("deepseek-v4-flash", НЕПИКОВЫЙ_ЧАС))
    assert деньги == pytest.approx(0.0)


def test_одна_половина_разбивки_дополняется_из_prompt_tokens():
    """Пришла только одна половина разбивки — вторая выводится из `prompt_tokens`.

    Без этого остаток входа пропадал бы из счёта: при тысяче токенов входа и одной
    известной сотне попаданий терялось бы девятьсот. Ошибка ушла бы в недосчёт, то есть
    в опасную сторону, — в отличие от прочих допущений тарифа, которые завышают.
    """
    цены = ЦЕНЫ["deepseek-v4-flash"]
    записан = снимок("deepseek-v4-flash", НЕПИКОВЫЙ_ЧАС)

    известны_попадания = {
        "prompt_tokens": 1000,
        "prompt_cache_hit_tokens": 200,
        "completion_tokens": 0,
    }
    ожидание = (200 * цены["cache_hit"] + 800 * цены["cache_miss"]) / 1_000_000
    assert стоимость(известны_попадания, записан) == pytest.approx(ожидание)

    известны_промахи = {
        "prompt_tokens": 1000,
        "prompt_cache_miss_tokens": 300,
        "completion_tokens": 0,
    }
    ожидание = (700 * цены["cache_hit"] + 300 * цены["cache_miss"]) / 1_000_000
    assert стоимость(известны_промахи, записан) == pytest.approx(ожидание)


@pytest.mark.parametrize(
    "поле",
    [
        "prompt_cache_hit_tokens",
        "prompt_cache_miss_tokens",
        "completion_tokens",
        "prompt_tokens",
    ],
)
def test_отрицательные_токены_отклоняются_с_именем_поля(поле):
    """Отрицательный расход — испорченный ответ, а не скидка.

    Посчитанный молча, он дал бы отрицательную стоимость: она ушла бы в журнал и вычлась
    из итога дня, не подняв шума. Имя поля обязано быть в тексте отказа — иначе искать
    испорченное поле придётся глазами по всему ответу.
    """
    usage = {поле: -1_000_000}
    with pytest.raises(ValueError) as отказ:
        стоимость(usage, снимок("deepseek-v4-flash", НЕПИКОВЫЙ_ЧАС))
    assert поле in str(отказ.value)


def test_строка_вместо_числа_даёт_ValueError_а_не_TypeError():
    """Отказ должен называть поле, а не падать арифметикой из середины формулы.

    `TypeError` от умножения строки на ставку не говорит, какое поле ответа испорчено,
    и разбирательство начинается с чтения кода вместо чтения сообщения.
    """
    usage = {"completion_tokens": "1000"}
    with pytest.raises(ValueError) as отказ:
        стоимость(usage, снимок("deepseek-v4-flash", НЕПИКОВЫЙ_ЧАС))
    assert "completion_tokens" in str(отказ.value)


def test_логическое_значение_не_считается_за_число_токенов():
    """`True` в поле учёта — испорченный ответ, а не один токен.

    В Python `bool` — подкласс `int`, поэтому обычная проверка на число пропустила бы
    его, и расход посчитался бы равным единице. Молчаливая единица здесь опаснее отказа:
    она выглядит как настоящий, просто очень дешёвый вызов.
    """
    usage = {"prompt_cache_miss_tokens": True}
    with pytest.raises(ValueError) as отказ:
        стоимость(usage, снимок("deepseek-v4-flash", НЕПИКОВЫЙ_ЧАС))
    assert "prompt_cache_miss_tokens" in str(отказ.value)
