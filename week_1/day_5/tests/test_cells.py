"""Проверки разбора вердикта из ответа модели — `models.cells.extract_verdict`.

Почему на это нужны проверки, а не взгляд глазами. Вердикт — измеряемая величина дня:
по нему считается доля попаданий в каждой клетке. Ошибка разбора не видна на странице —
таблица покажет ровный столбец и в правильном, и в неправильном случае, а разница
всплывёт только в выводах, которые к тому времени уже написаны. Два вида ошибки и
ловятся здесь:

1. **Слишком строгий разбор** теряет вердикты, которые модель дала: она обрамляет слово
   чем угодно — звёздочками, кавычками, пунктом списка, заголовком — и нередко подводит
   к нему издалека («Однозначно нет», «Ответ: нет»). Ответ по существу засчитывается
   независимо от формы, поэтому потерянный так вердикт — это занижённые попадания.
2. **Слишком вольный разбор** сочиняет вердикты, которых не было: «нетривиальный»,
   «нету», «даже» начинаются с нужных букв, но вердиктами не являются. Пустая клетка
   честнее подменённой.

Ни сети, ни файлов проверки не трогают: разбирается чистый текст.
"""

from models.cells import extract_verdict

# --- вердикт распознаётся --------------------------------------------------------


def test_вердикт_голым_словом_в_любом_регистре():
    """Простейший случай: ответ состоит из одного вердикта."""
    assert extract_verdict("нет") == "нет"
    assert extract_verdict("Нет") == "нет"
    assert extract_verdict("НЕТ") == "нет"
    assert extract_verdict("да") == "да"
    assert extract_verdict("Да") == "да"
    assert extract_verdict("ДА") == "да"


def test_вердикт_с_оформлением_жирным():
    """Звёздочки вокруг слова — самая частая привычка модели."""
    assert extract_verdict("**Нет**") == "нет"
    assert extract_verdict("**нет**, веларий только помешает") == "нет"
    assert extract_verdict("**Да**, но с оговорками") == "да"


def test_вердикт_со_знаком_препинания_после_слова():
    """После вердикта модель ставит что угодно — знак к слову не относится."""
    assert extract_verdict("Нет.") == "нет"
    assert extract_verdict("Нет,") == "нет"
    assert extract_verdict("Нет — веларий тут не поможет.") == "нет"
    assert extract_verdict("Нет: свет он загораживает.") == "нет"
    assert extract_verdict("Нет!") == "нет"
    assert extract_verdict("Да.") == "да"


def test_вердикт_в_кавычках():
    """Кавычки любого вида — оформление, а не часть слова."""
    assert extract_verdict("«Нет»") == "нет"
    assert extract_verdict('"Нет"') == "нет"
    assert extract_verdict("«Да», хотя и не полностью.") == "да"


def test_вердикт_после_пустых_строк_и_пробелов():
    """Пустое начало ответа не должно стоить нам вердикта."""
    assert extract_verdict("\n\n   Нет, не поможет.") == "нет"
    assert extract_verdict("   \t Да") == "да"


def test_вердикт_в_списке_и_цитате():
    """Пункт списка и цитата — тоже оформление вокруг слова."""
    assert extract_verdict("- Нет") == "нет"
    assert extract_verdict("1. Нет") == "нет"
    assert extract_verdict("> Нет") == "нет"
    assert extract_verdict("* Да, отчасти") == "да"


def test_вердикт_в_заголовке():
    """Модель нередко выносит вердикт в заголовок разметки."""
    assert extract_verdict("### Нет") == "нет"
    assert extract_verdict("## Да, поможет") == "да"


def test_вердикт_после_перевода_строки_внутри_оформления():
    """Оформление и само слово могут стоять на разных строках."""
    assert extract_verdict("**\nНет**, веларий свет загораживает.") == "нет"
    assert extract_verdict("###\n\nДа") == "да"


def test_вердикт_не_первым_словом_тоже_считается():
    """Ответ по существу засчитывается независимо от того, выполнена ли форма.

    Модель, начавшая с «Однозначно нет» или «Ответ: нет», ответила ровно то же самое —
    просто не так, как её просили. Наказывать её за это мы не будем.
    """
    assert extract_verdict("Однозначно нет, веларий не поможет.") == "нет"
    assert extract_verdict("Ответ: нет") == "нет"
    assert extract_verdict("Скорее нет, чем да.") == "нет"
    assert extract_verdict("Скорее да, чем нет.") == "да"


def test_вердикт_в_конце_длинного_рассуждения():
    """Клетки с рассуждениями подводят к вердикту издалека — его надо дождаться."""
    ответ = (
        "Это интересный вопрос, и он требует свести три области сразу.\n\n"
        "Начнём с астрономии: полная луна светит примерно в четыреста тысяч раз\n"
        "слабее солнца. Далее архитектура: веларий накрывал трибуны, а не арену.\n"
        "Наконец, материалы: плотная льняная ткань свет задерживает.\n\n"
        "Нет."
    )
    assert extract_verdict(ответ) == "нет"


def test_первое_встреченное_слово_даже_вопреки_смыслу():
    """Принятая цена правила «первое встреченное»: здесь разметка ошибётся.

    По смыслу ответ отрицательный, но первым в тексте стоит «да», и вердиктом станет
    оно. Разбирать смысл фразы значит заводить судью — этого мы сознательно не делаем,
    и проверка стоит здесь затем, чтобы следующий читатель не счёл поведение
    недосмотром.
    """
    assert extract_verdict("Если бы речь шла о солнце — да, но здесь нет.") == "да"


# --- вердикта нет ----------------------------------------------------------------


def test_слово_берётся_целиком_а_не_по_началу():
    """Другое слово, начинающееся с тех же букв, вердиктом не является."""
    assert extract_verdict("Нетривиальный вопрос.") is None
    assert extract_verdict("Недостаточно данных.") is None
    assert extract_verdict("Нету однозначного ответа.") is None
    assert extract_verdict("Нетто-эффект отрицательный.") is None
    assert extract_verdict("Дать однозначный ответ трудно.") is None
    assert extract_verdict("Даже полная луна слишком слаба.") is None


def test_удвоение_через_дефис_вердиктом_не_считается():
    """«Да-да» — оборот рассуждения вслух, а не вердикт, и решено считать его пустым.

    Слово тут другое: не «да», а «да-да». Признать его за «да» значило бы разбирать
    вердикт по началу слова — ровно то, из-за чего «нетривиальный» превратился бы в
    «нет». Вдобавок «да-да, но» по смыслу почти всегда предваряет возражение, то есть
    в вердикт превратилось бы то, что вердиктом не задумывалось. Последняя строка это
    и показывает: удвоение пропущено, а взято настоящее слово следом.
    """
    assert extract_verdict("Да-да, конечно.") is None
    assert extract_verdict("Нет-нет, ни в коем случае.") is None
    assert extract_verdict("Да-да, но всё же нет.") == "нет"


def test_ответ_без_вердикта():
    """Ни «да», ни «нет» в тексте не встретилось — клетка остаётся пустой."""
    assert extract_verdict("Возможно.") is None
    assert extract_verdict("Веларий тут не поможет.") is None


def test_пустой_ввод_не_роняет_разбор():
    """Пустого и отсутствующего ответа хватает при обрыве обмена с API."""
    assert extract_verdict("") is None
    assert extract_verdict("     ") is None
    assert extract_verdict("\n\n\t") is None
    assert extract_verdict(None) is None


def test_оформление_без_слова_не_роняет_разбор():
    """Ответ из одной разметки — тоже вход, на котором нельзя упасть."""
    assert extract_verdict("**") is None
    assert extract_verdict("### ") is None
    assert extract_verdict("1. 2. 3.") is None
