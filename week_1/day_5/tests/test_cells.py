"""Проверки разбора вердикта из ответа модели — `models.cells.extract_verdict`.

Вердикт вопроса дня — одна из пяти профессий (`models.cells.ВЕРДИКТЫ`), верна из них
`плотник`. Берётся он из **первого слова** ответа: задача решается таблицей, и модель
по ходу разбора называет все пять профессий, так что искать профессию по всему тексту
значило бы измерять порядок изложения, а не ответ.

Почему на разбор нужны проверки, а не взгляд глазами: вердикт — измеряемая величина
дня, по нему считается попадание каждой клетки. Ошибка разбора не видна на странице —
таблица покажет ровный столбец и в правильном, и в неправильном случае, — а прогонов
всего четыре, по одному на клетку, так что одна испорченная клетка это четверть данных.
Два вида ошибки и ловятся здесь:

1. **Слишком строгий разбор** теряет ответ, который модель дала по форме: она
   обрамляет первое слово звёздочками, кавычками, заголовком, пунктом списка.
2. **Слишком вольный разбор** сочиняет вердикт, которого не было: «плотничает»,
   «программирование», «электричество» начинаются с тех же букв, а слово из
   рассуждения — вовсе не ответ. Пустая клетка честнее подменённой.

Ни сети, ни файлов проверки не трогают: разбирается чистый текст.
"""

from models.cells import extract_verdict

# --- вердикт распознаётся --------------------------------------------------------


def test_вердикт_голым_словом_в_любом_регистре():
    """Простейший случай: ответ состоит из одной профессии."""
    assert extract_verdict("плотник") == "плотник"
    assert extract_verdict("Плотник") == "плотник"
    assert extract_verdict("ПЛОТНИК") == "плотник"
    assert extract_verdict("портной") == "портной"
    assert extract_verdict("Программист") == "программист"
    assert extract_verdict("КАМЕНЩИК") == "каменщик"


def test_вердикт_с_оформлением_жирным():
    """Звёздочки вокруг слова — самая частая привычка модели."""
    assert extract_verdict("**Плотник**") == "плотник"
    assert extract_verdict("**Плотник** — первый склад, белый.") == "плотник"
    assert extract_verdict("**электрик**, если верить подсказке про хлеб") == "электрик"


def test_вердикт_со_знаком_препинания_после_слова():
    """После вердикта модель ставит что угодно — знак к слову не относится."""
    assert extract_verdict("Плотник.") == "плотник"
    assert extract_verdict("Плотник,") == "плотник"
    assert extract_verdict("Плотник — он работает на первом складе.") == "плотник"
    assert extract_verdict("Плотник: белый склад, вино, медведь.") == "плотник"
    assert extract_verdict("Плотник!") == "плотник"
    assert extract_verdict("Портной?") == "портной"


def test_вердикт_в_кавычках():
    """Кавычки любого вида — оформление, а не часть слова."""
    assert extract_verdict("«Плотник»") == "плотник"
    assert extract_verdict('"Плотник"') == "плотник"
    assert extract_verdict("«Каменщик», хотя я не уверен.") == "каменщик"


def test_вердикт_после_пустых_строк_и_пробелов():
    """Пустое начало ответа не должно стоить нам вердикта."""
    assert extract_verdict("\n\n   Плотник, он на первом складе.") == "плотник"
    assert extract_verdict("   \t Программист") == "программист"


def test_вердикт_в_списке_и_цитате():
    """Пункт списка и цитата — тоже оформление вокруг слова."""
    assert extract_verdict("- Плотник") == "плотник"
    assert extract_verdict("1. Плотник") == "плотник"
    assert extract_verdict("> Плотник") == "плотник"
    assert extract_verdict("* Электрик") == "электрик"


def test_вердикт_в_заголовке():
    """Модель нередко выносит ответ в заголовок разметки."""
    assert extract_verdict("### Плотник") == "плотник"
    assert extract_verdict("## Плотник\n\nОн работает на первом складе.") == "плотник"


def test_вердикт_после_перевода_строки_внутри_оформления():
    """Оформление и само слово могут стоять на разных строках."""
    assert extract_verdict("**\nПлотник**, первый склад.") == "плотник"
    assert extract_verdict("###\n\nПортной") == "портной"


# --- вердикта нет: ответ не по форме ----------------------------------------------


def test_вердикт_не_первым_словом_не_считается():
    """Ответ мимо формы — честно пустая клетка, а не вердикт.

    Профессия в тексте есть, но требование назвать её первым словом не выполнено.
    Засчитать её значило бы разрешить себе искать профессию по тексту, а в ответе,
    расписанном таблицей, найденное так слово — случайное.
    """
    assert extract_verdict("Ответ: плотник") is None
    assert extract_verdict("Пиццу ест плотник.") is None
    assert extract_verdict("Я думаю, что это программист.") is None


def test_ответ_начатый_с_разбора_вердикта_не_даёт():
    """Самый вероятный вид ответа — и он останется без вердикта. Так и задумано.

    Именно ради этого случая вердикт и берётся из первого слова. По ходу разбора
    названы все пять профессий, причём в порядке подсказок: первой попадается
    «каменщик», хотя вывод модели — «плотник» и он верен. Правило «первое встреченное
    слово» подставило бы сюда «каменщик» и молча испортило бы подсчёт; пустая клетка
    же прямо говорит «ответила не по форме» и проверяема глазами по тексту ответа.
    """
    ответ = (
        "Разберём подсказки по порядку.\n"
        "Каменщик работает в зелёном складе — значит, зелёный не первый.\n"
        "Электрик ест хлеб, портной держит леопарда, программист пьёт ром.\n"
        "Остаётся один склад и одна еда.\n\n"
        "Ответ: плотник."
    )
    assert extract_verdict(ответ) is None


def test_ответ_таблицей_вердикта_не_даёт():
    """Таблица-решение вердикта не даёт, даже если верный ответ стоит в первой строке.

    Прежнее правило («первое встреченное») угадало бы здесь верно, но по совпадению:
    плотник оказался первым лишь потому, что работает на первом складе. Совпадение —
    не измерение, и такой ответ честнее пометить как «не по форме».
    """
    ответ = (
        "| склад | профессия   | еда      |\n"
        "|-------|-------------|----------|\n"
        "| 1     | плотник     | пицца    |\n"
        "| 2     | электрик    | хлеб     |\n"
        "| 3     | каменщик    | пельмени |\n"
        "| 4     | портной     | макароны |\n"
        "| 5     | программист | котлета  |\n\n"
        "Пиццу ест плотник."
    )
    assert extract_verdict(ответ) is None


def test_вежливое_вступление_вердикта_не_даёт():
    """Клетки без рассуждений любят начинать с вступления — вердикта не будет.

    Проверка стоит здесь как предупреждение: пустые клетки в таблице ожидаемы и
    означают форму, а не отказ модели отвечать.
    """
    assert extract_verdict("Давайте решим эту задачу шаг за шагом.") is None
    assert extract_verdict("Конечно! Плотник.") is None


# --- вердикта нет: слово не то ----------------------------------------------------


def test_слово_берётся_целиком_а_не_по_началу():
    """Однокоренное слово — не профессия из ответа."""
    assert extract_verdict("Плотничает тот, кто ест пиццу.") is None
    assert extract_verdict("Программирование тут ни при чём.") is None
    assert extract_verdict("Электричество в древнем складе не водилось.") is None
    assert extract_verdict("Каменщицкая работа выполнена в зелёном складе.") is None


def test_падежная_форма_вердиктом_не_считается():
    """Засчитывается только именительный падеж — решение осознанное, с ценой.

    Соблазн велик: «плотнику» это тот же плотник. Но признать падежи значило бы
    сравнивать по началу слова, и тогда рядом с «плотника» вердиктом стало бы
    «плотничает», а рядом с «каменщика» — «каменщицкая». Отделять окончания
    по-настоящему умеет только морфологический разбор, а это отдельная библиотека и
    отдельный источник ошибок ради одной клетки таблицы.

    Цена здесь невелика именно потому, что смотрим мы на первое слово: профессию,
    названную в ответ на вопрос, ставят в именительный падеж — косвенный падеж первым
    словом означает, что модель начала фразу, а не назвала ответ.
    """
    assert extract_verdict("Плотнику достаётся пицца.") is None
    assert extract_verdict("Плотника и спросите.") is None
    assert extract_verdict("Плотником я бы её назвал.") is None
    assert extract_verdict("Портного тут нет.") is None


def test_составное_слово_через_дефис_вердиктом_не_считается():
    """Слово с внутренним дефисом — другое слово, и это тот же приём, что выше.

    Дефис намеренно взят внутрь слова: без него разбор читал бы вердикт по началу
    слова и «плотничает» превратилось бы в «плотник».
    """
    assert extract_verdict("Плотник-краснодеревщик.") is None
    assert extract_verdict("Плотник-краснодеревщик, а точнее просто плотник.") is None


def test_ответ_без_профессии():
    """Ни одной из пяти профессий в ответе нет — клетка остаётся пустой."""
    assert extract_verdict("Никто из них.") is None
    assert extract_verdict("Задача не имеет решения.") is None
    assert extract_verdict("Пиццы среди подсказок нет вовсе.") is None


def test_пустой_ввод_не_роняет_разбор():
    """Пустого и отсутствующего ответа хватает при обрыве обмена с API."""
    assert extract_verdict("") is None
    assert extract_verdict("     ") is None
    assert extract_verdict("\n\n\t") is None
    assert extract_verdict(None) is None


def test_оформление_без_слова_не_роняет_разбор():
    """Ответ из одной разметки — тоже вход, на котором нельзя упасть."""
    assert extract_verdict("**") is None
    assert extract_verdict("### ") is None
    assert extract_verdict("1. 2. 3.") is None
