"""Проверки состава вопросов и извлечения значения из ответа модели.

Написаны до самого модуля `temperature.questions`: сначала проверки, потом код.
Пока модуля нет, сбор проверок падает — это ожидаемый исход.
"""

import pytest

from temperature.questions import (
    QUESTIONS,
    REPEATS,
    TEMPERATURES,
    by_id,
    extract_value,
)

# --- извлечение числа (answer_kind == "number") -------------------------------


def test_число_берётся_из_строки_ответа():
    вопрос = by_id("apples")
    ответ = "Считаем: 3 - 1 = 2, затем 2 + 4 = 6, делим пополам.\nответ: 3"
    assert extract_value(вопрос, ответ) == "3"


def test_число_берётся_несмотря_на_регистр_и_лишние_пробелы():
    вопрос = by_id("apples")
    ответ = "Рассуждение опускаем.\nОтвет:  3"
    assert extract_value(вопрос, ответ) == "3"


def test_число_отсутствует_когда_строки_ответа_нет():
    вопрос = by_id("apples")
    ответ = "Маша разделила яблоки поровну, каждому досталось по три штуки."
    assert extract_value(вопрос, ответ) is None


def test_из_двух_строк_ответа_берётся_последняя():
    вопрос = by_id("apples")
    ответ = "Сначала посчитаем неверно.\nответ: 2\nПерепроверим себя.\nответ: 3"
    assert extract_value(вопрос, ответ) == "3"


def test_отрицательное_число_извлекается_вместе_со_знаком():
    вопрос = by_id("apples")
    ответ = "Яблок не хватило.\nответ: -1"
    assert extract_value(вопрос, ответ) == "-1"


# --- извлечение статуса (answer_kind == "status") -----------------------------


def test_статус_неизвестно_извлекается():
    вопрос = by_id("poet")
    ответ = "статус: неизвестно\nТакого поэта в моих сведениях нет."
    assert extract_value(вопрос, ответ) == "неизвестно"


def test_статус_известно_извлекается():
    вопрос = by_id("poet")
    ответ = "статус: известно\nЭто поэт Серебряного века."
    assert extract_value(вопрос, ответ) == "известно"


def test_статус_отсутствует_когда_слова_статус_нет():
    вопрос = by_id("poet")
    ответ = "Про этого поэта мне ничего не известно."
    assert extract_value(вопрос, ответ) is None


# --- вопросы без извлечения (answer_kind == "none") ---------------------------


@pytest.mark.parametrize("идентификатор", ["metaphor", "code"])
@pytest.mark.parametrize(
    "ответ",
    [
        "",
        "Свободный текст без всяких меток.",
        "ответ: 3",
        "статус: известно",
    ],
)
def test_для_вопросов_без_извлечения_значения_нет(идентификатор, ответ):
    вопрос = by_id(идентификатор)
    assert extract_value(вопрос, ответ) is None


# --- состав набора ------------------------------------------------------------


def test_вопросов_ровно_пять():
    assert len(QUESTIONS) == 5


def test_идентификаторы_вопросов_заданы_в_ожидаемом_порядке():
    assert tuple(вопрос.id for вопрос in QUESTIONS) == (
        "apples",
        "apples_hard",
        "poet",
        "metaphor",
        "code",
    )


def test_температуры_заданы_тремя_значениями():
    assert TEMPERATURES == (0.0, 0.7, 1.2)


def test_повторов_три():
    assert REPEATS == 3


@pytest.mark.parametrize("вопрос", QUESTIONS, ids=lambda в: в.id)
def test_у_каждого_вопроса_есть_подпись_текст_и_допустимый_вид_ответа(вопрос):
    assert вопрос.title.strip()
    assert вопрос.text.strip()
    assert вопрос.answer_kind in {"number", "status", "none"}


def test_по_каждому_идентификатору_находится_свой_вопрос():
    for вопрос in QUESTIONS:
        assert by_id(вопрос.id) is вопрос


def test_неизвестный_идентификатор_поднимает_KeyError():
    with pytest.raises(KeyError):
        by_id("нет-такого-вопроса")


@pytest.mark.parametrize(
    ("идентификатор", "вид_ответа"),
    [
        ("apples", "number"),
        ("apples_hard", "number"),
        ("poet", "status"),
        ("metaphor", "none"),
        ("code", "none"),
    ],
)
def test_вид_ответа_закреплён_за_каждым_вопросом(идентификатор, вид_ответа):
    # Без этой проверки вид ответа закреплён лишь у тех вопросов, что заняты в проверках
    # извлечения. Реализация, объявившая, скажем, `apples_hard` видом "none", прошла бы весь
    # набор, а число из ответа перестало бы извлекаться — и вскрылось бы уже на живом прогоне.
    assert by_id(идентификатор).answer_kind == вид_ответа


@pytest.mark.parametrize("вопрос", QUESTIONS, ids=lambda в: в.id)
def test_вопрос_нельзя_изменить_после_создания(вопрос):
    # Question объявлен как @dataclass(frozen=True): вопросы общие на всю сетку прогонов,
    # и случайная правка поля испортила бы сразу все ячейки таблицы.
    with pytest.raises(AttributeError):
        вопрос.title = "подменённая подпись"


# --- число: значение берётся целиком либо не берётся вовсе ---------------------


@pytest.mark.parametrize(
    "ответ",
    [
        "ответ: 3.5",
        "ответ: 3,5",
        "ответ: 1 000",
    ],
    ids=["точка", "запятая", "разделитель разрядов"],
)
def test_нецелое_число_не_извлекается_по_кускам(ответ):
    # Отсечь дробную часть или разряды молча — значит показать человеку неверное число.
    # Пустая клетка заметна и терпима, подменённое значение вводит в заблуждение.
    вопрос = by_id("apples")
    assert extract_value(вопрос, ответ) is None


def test_хвост_из_букв_числу_не_мешает():
    вопрос = by_id("apples")
    assert extract_value(вопрос, "ответ: 3 яблока") == "3"


# --- метка, выделенная разметкой ----------------------------------------------


@pytest.mark.parametrize(
    "ответ",
    [
        "**ответ: 3**",
        "**ответ:** 3",
        "- ответ: 3",
        "* ответ: 3",
        "## ответ: 3",
        "> ответ: 3",
    ],
    ids=["жирным целиком", "жирная метка", "дефис", "звёздочка", "заголовок", "цитата"],
)
def test_число_извлекается_из_строки_с_разметкой(ответ):
    # Вопрос просит «строго одну строку», и модель охотно оформляет её как итог.
    # Оформление не должно превращаться в пропуск значения.
    вопрос = by_id("apples")
    assert extract_value(вопрос, ответ) == "3"


@pytest.mark.parametrize(
    "ответ",
    [
        "**статус:** неизвестно",
        "**статус: неизвестно**",
        "- статус: неизвестно",
    ],
    ids=["жирная метка", "жирным целиком", "дефис"],
)
def test_статус_извлекается_из_строки_с_разметкой(ответ):
    вопрос = by_id("poet")
    assert extract_value(вопрос, ответ) == "неизвестно"


# --- границы слова и начала строки --------------------------------------------


def test_статус_не_подхватывается_из_начала_другого_слова():
    вопрос = by_id("poet")
    assert extract_value(вопрос, "статус: известное имя, но не поэта") is None


def test_метка_посреди_фразы_не_считается_ответом():
    # Метка ищется с начала строки: иначе в неё полезут обороты из рассуждения вслух.
    вопрос = by_id("apples")
    assert extract_value(вопрос, "Итак, получаем ответ: 3") is None
