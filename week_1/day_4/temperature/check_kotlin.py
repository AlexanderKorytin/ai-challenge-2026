"""Разбор ответов на вопрос про код: что прислала модель и работает ли это.

Вопрос `code` просит написать на Kotlin проверку строки на палиндром и вернуть **только**
блок кода. Отсюда два разных вопроса к каждому ответу, и модуль отвечает на оба порознь:

* соблюдена ли форма — есть ли блок кода и нет ли текста вне него;
* работает ли содержимое — собирается ли код и верно ли отвечает на пяти случаях.

Оценок «хорошо» и «плохо» модуль не выносит: он печатает факты, выводы делает человек.

Разбор текста и сборка разделены намеренно. Разбор — чистые функции над строками, они
работают везде и проверяются автоматически. Сборка требует установленной Android Studio;
нет её — модуль честно говорит, что сборка пропущена, и продолжает разбор текста.

Запуск: `uv run python -m temperature.check_kotlin`.
"""

from __future__ import annotations

import json
import os
import re
import subprocess
import sys
import tempfile
from collections import defaultdict
from dataclasses import dataclass
from pathlib import Path

# --- откуда берутся данные и инструменты ----------------------------------------------------

#: Журнал прогонов. Путь абсолютный, считается от расположения модуля, а не от места запуска:
#: живой прогон ведётся из песочницы `test/`, а журнал лежит в `day_4/data/`.
DATA_PATH = Path(__file__).resolve().parent.parent / "data" / "grid.jsonl"

#: Компилятор Kotlin и среда Java из установленной Android Studio. Отдельно ставить нечего:
#: в студии лежит и то, и другое. `kotlinc` — сценарий оболочки, и без `JAVA_HOME` в окружении
#: он не находит среду, поэтому переменная передаётся подпроцессу явно.
KOTLINC = Path("/Applications/Android Studio.app/Contents/plugins/Kotlin/kotlinc/bin/kotlinc")
JAVA_HOME = Path("/Applications/Android Studio.app/Contents/jbr/Contents/Home")

#: Идентификатор разбираемого вопроса в журнале прогонов.
ВОПРОС = "code"

#: Случаи, на которых проверяется присланная функция: строка и ожидаемый ответ.
#:
#: «А роза упала на лапу Азора» ждёт `true` намеренно: это палиндром, если чистить пробелы,
#: знаки и регистр. Реализация, которая этого не делает, на этом случае не сойдётся — и это
#: наблюдение о качестве кода, а не дефект проверки. Пустая строка и один символ — края,
#: на которых чаще всего падают самодельные проверки по индексам.
СЛУЧАИ: tuple[tuple[str, bool], ...] = (
    ("довод", True),
    ("А роза упала на лапу Азора", True),
    ("", True),
    ("к", True),
    ("не палиндром", False),
)

#: Пределы ожидания подпроцессов, секунды. Сборка идёт около пяти секунд, но первый запуск
#: после перезагрузки прогревает диск дольше; запуск собранного — доли секунды, а долгое
#: ожидание тут означает зацикленную реализацию.
ПРЕДЕЛ_СБОРКИ = 300
ПРЕДЕЛ_ЗАПУСКА = 60


# --- разбор текста ответа -------------------------------------------------------------------

# Блок кода: строка-ограничитель (с указанием языка или без), содержимое, закрывающая строка.
# Ограничители ищутся только в начале строки (флаг MULTILINE) — тройные кавычки посреди
# фразы ограничителем не считаются. Содержимое берётся нежадно, поэтому из ответа с
# несколькими блоками достаётся первый. Незакрытый блок не совпадает вовсе: ответ, упёршийся
# в предел длины, обрывается на полуслове, и выдавать его огрызок за код нельзя.
_БЛОК = re.compile(r"^[ \t]*```[^\n]*\n(?P<код>.*?)^[ \t]*```[ \t]*$", re.DOTALL | re.MULTILINE)

# Имя в Kotlin: буква или подчёркивание, дальше буквы, цифры, подчёркивания. `[^\W\d]` —
# это «то, что входит в \w, но не цифра», то есть буква любого алфавита или подчёркивание.
_ИМЯ = r"[^\W\d]\w*"

# Обычная функция: один параметр типа String, возвращает Boolean. Пробелы допускаются
# всюду, где Kotlin их допускает, — модель охотно расставляет их по-своему.
_ОБЫЧНАЯ = re.compile(
    rf"\bfun\s+({_ИМЯ})\s*\(\s*{_ИМЯ}\s*:\s*String\s*\)\s*:\s*Boolean\b"
)

# Функция-расширение: параметра нет, проверяемая строка — приёмник (`this`).
_РАСШИРЕНИЕ = re.compile(rf"\bfun\s+String\s*\.\s*({_ИМЯ})\s*\(\s*\)\s*:\s*Boolean\b")


def extract_code(answer: str) -> str | None:
    """Содержимое блока кода без строк-ограничителей, либо None, если блока нет.

    Пустые строки по краям содержимого срезаются, отступы внутри сохраняются: они значимы
    для чтения, а для сборки безразличны.
    """
    совпадение = _БЛОК.search(answer)
    if совпадение is None:
        return None
    return совпадение.group("код").strip("\n")


def has_preamble(answer: str) -> bool:
    """Есть ли в ответе текст вне блока кода.

    Пустые строки и пробелы вокруг блока текстом не считаются: они не нарушают требование
    «ничего, кроме блока». Ответ без блока вовсе — это сплошной текст вне блока, то есть
    преамбула: требование не выполнено ни в какой части.
    """
    совпадение = _БЛОК.search(answer)
    if совпадение is None:
        return bool(answer.strip())
    до = answer[: совпадение.start()]
    после = answer[совпадение.end() :]
    return bool(до.strip() or после.strip())


def function_name(code: str) -> str | None:
    """Имя функции «строка → Boolean» в коде, либо None, если такой функции нет.

    Берётся первая по тексту подходящая функция, а не первая вообще: ответы часто начинаются
    со вспомогательной (`fun clean(s: String): String`), и вызывать надо не её.

    У функции-расширения (`fun String.isPalindrome(): Boolean`) параметра нет — проверяемая
    строка приходит приёмником. Имя такой функции возвращается вместе с приёмником,
    `String.isPalindrome`: вызов у неё другой формы (`s.isPalindrome()` против
    `isPalindrome(s)`), и по одному короткому имени его не построить. Разбирает эту разницу
    `call_expression`.
    """
    кандидаты: list[tuple[int, str]] = []
    for совпадение in _ОБЫЧНАЯ.finditer(code):
        кандидаты.append((совпадение.start(), совпадение.group(1)))
    for совпадение in _РАСШИРЕНИЕ.finditer(code):
        кандидаты.append((совпадение.start(), f"String.{совпадение.group(1)}"))
    if not кандидаты:
        return None
    return min(кандидаты)[1]


def call_expression(name: str) -> str:
    """Как вызвать функцию с именем `name` для строки в переменной `s`."""
    if name.startswith("String."):
        return f"s.{name.removeprefix('String.')}()"
    return f"{name}(s)"


# --- сборка и запуск ---------------------------------------------------------------------


def _строка_kotlin(значение: str) -> str:
    """Строковый литерал Kotlin из строки Python.

    Экранируется и знак доллара: в Kotlin он открывает подстановку значения, и строка
    с ним без экранирования либо не соберётся, либо подставит чужое.
    """
    экранированное = значение.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$")
    return f'"{экранированное}"'


def main_kt(name: str) -> str:
    """Текст файла `main.kt`, который прогоняет функцию `name` по всем случаям.

    Печатается пара «ожидалось|получилось» на случай: сравнивать разбором вывода надёжнее,
    чем полагаться на код возврата, — так видно, сколько именно случаев сошлось.
    """
    случаи = ",\n".join(
        f"        {_строка_kotlin(строка)} to {'true' if ожидание else 'false'}"
        for строка, ожидание in СЛУЧАИ
    )
    return (
        "fun main() {\n"
        "    val cases = listOf(\n"
        f"{случаи},\n"
        "    )\n"
        "    for ((s, expected) in cases) {\n"
        f"        val got = {call_expression(name)}\n"
        '        println("$expected|$got")\n'
        "    }\n"
        "}\n"
    )


@dataclass
class ИтогСборки:
    """Что вышло из сборки и запуска одного ответа."""

    собралось: bool
    сошлось: int
    ошибка: str | None = None


def причина_пропуска() -> str | None:
    """Почему сборка невозможна на этой машине, либо None, если всё на месте."""
    if not KOTLINC.exists():
        return f"нет компилятора Kotlin по пути {KOTLINC}"
    if not JAVA_HOME.exists():
        return f"нет среды Java по пути {JAVA_HOME}"
    return None


def _первая_строка(текст: str) -> str:
    """Первая непустая строка вывода — короткая суть отказа для печати в отчёт."""
    for строка in текст.splitlines():
        if строка.strip():
            return строка.strip()
    return "без объяснений"


def _сошлось(вывод: str) -> int:
    """Сколько случаев из напечатанных сошлись: половины строки «ожидалось|получилось» равны."""
    счёт = 0
    for строка in вывод.splitlines():
        ожидалось, разделитель, получилось = строка.strip().partition("|")
        if разделитель and ожидалось == получилось:
            счёт += 1
    return счёт


def build_and_run(code: str, name: str) -> ИтогСборки:
    """Собирает код ответа вместе с проверочным `main.kt` и запускает собранное.

    Работа идёт во временном каталоге, который удаляется сам: в проект и в репозиторий не
    попадает ни исходников ответа, ни собранного архива.
    """
    with tempfile.TemporaryDirectory(prefix="проверка-kotlin-") as имя_каталога:
        каталог = Path(имя_каталога)
        (каталог / "ответ.kt").write_text(code + "\n", encoding="utf-8")
        (каталог / "main.kt").write_text(main_kt(name), encoding="utf-8")
        архив = каталог / "проверка.jar"
        окружение = {**os.environ, "JAVA_HOME": str(JAVA_HOME)}

        try:
            сборка = subprocess.run(
                [str(KOTLINC), "ответ.kt", "main.kt", "-include-runtime", "-d", архив.name],
                cwd=каталог,
                env=окружение,
                capture_output=True,
                text=True,
                timeout=ПРЕДЕЛ_СБОРКИ,
                check=False,
            )
        except subprocess.TimeoutExpired:
            return ИтогСборки(False, 0, f"сборка не уложилась в {ПРЕДЕЛ_СБОРКИ} с")
        if сборка.returncode != 0:
            return ИтогСборки(False, 0, _первая_строка(сборка.stderr or сборка.stdout))

        try:
            запуск = subprocess.run(
                [str(JAVA_HOME / "bin" / "java"), "-jar", архив.name],
                cwd=каталог,
                env=окружение,
                capture_output=True,
                text=True,
                timeout=ПРЕДЕЛ_ЗАПУСКА,
                check=False,
            )
        except subprocess.TimeoutExpired:
            return ИтогСборки(True, 0, f"запуск не уложился в {ПРЕДЕЛ_ЗАПУСКА} с")

        сошлось = _сошлось(запуск.stdout)
        if запуск.returncode != 0:
            # Собралось, но упало на выполнении — часть случаев могла успеть напечататься.
            return ИтогСборки(True, сошлось, _первая_строка(запуск.stderr))
        return ИтогСборки(True, сошлось)


# --- разбор журнала и печать отчёта -----------------------------------------------------


def записи_вопроса(path: Path = DATA_PATH) -> list[dict]:
    """Удачные записи вопроса про код из журнала прогонов, по порядку появления.

    Испорченные строки журнала пропускаются молча: журнал дописывается по ходу живого
    прогона, и оборванная последняя строка — обычное дело, а не повод отказаться от разбора
    всего остального.
    """
    отобранные: list[dict] = []
    with Path(path).open(encoding="utf-8") as файл:
        for строка in файл:
            строка = строка.strip()
            if not строка:
                continue
            try:
                запись = json.loads(строка)
            except json.JSONDecodeError:
                continue
            if not isinstance(запись, dict):
                continue
            if запись.get("question_id") != ВОПРОС or запись.get("status") != "ok":
                continue
            # Температура и номер прогона идут в подписи строк и в сводку. Запись без них
            # или с чужим типом уронила бы разбор на выводе, уже после оплаченной сборки,
            # поэтому такие отсеиваются здесь — как это делает и `grid.collected_repeats`.
            if not isinstance(запись.get("temperature"), (int, float)):
                continue
            if not isinstance(запись.get("repetition"), int) or isinstance(
                запись.get("repetition"), bool
            ):
                continue
            отобранные.append(запись)
    return отобранные


def отчёт(path: Path = DATA_PATH) -> None:
    """Печатает разбор всех удачных ответов на вопрос про код и сводку по температурам."""
    путь = Path(path)
    if not путь.exists():
        print(f"журнала прогонов нет: {путь}")
        print("живой прогон ещё не делался — разбирать нечего")
        return

    записи = записи_вопроса(путь)
    if not записи:
        print(f"в журнале {путь} нет удачных записей вопроса «{ВОПРОС}»")
        print("живой прогон этого вопроса ещё не делался — разбирать нечего")
        return

    пропуск = причина_пропуска()
    print(f"разбор ответов на вопрос «{ВОПРОС}»: записей — {len(записи)}, журнал {путь}")
    if пропуск:
        print(f"сборка пропущена: {пропуск}")
        print("разбор текста ответов идёт как обычно")
    print()

    # «с кодом» — ответы, из которых удалось достать блок и имя функции: только их и
    # собираем. Считать их отдельно от «всего» обязательно, иначе ответ без блока попал бы
    # в сводку как «не собралось», хотя собирать было нечего.
    сводка: dict[float, dict[str, int]] = defaultdict(
        lambda: {
            "всего": 0,
            "с кодом": 0,
            "собралось": 0,
            "сошлось": 0,
            "случаев": 0,
            "преамбула": 0,
        }
    )

    for запись in записи:
        температура = запись.get("temperature")
        повтор = запись.get("repetition")
        ответ = запись.get("answer") or ""
        код = extract_code(ответ)
        преамбула = has_preamble(ответ)
        имя = function_name(код) if код is not None else None

        строка = сводка[температура]
        строка["всего"] += 1
        строка["преамбула"] += int(преамбула)

        начало = f"  t={температура:<4} прогон {повтор}"
        хвост = f"преамбула: {'да' if преамбула else 'нет'}"

        if код is None:
            print(f"{начало}  блока кода нет                                        {хвост}")
            continue
        if имя is None:
            print(f"{начало}  функции «строка → Boolean» нет                        {хвост}")
            continue

        if пропуск:
            print(f"{начало}  функция: {имя:<24} сборка: пропущена       {хвост}")
            continue

        итог = build_and_run(код, имя)
        строка["с кодом"] += 1
        строка["собралось"] += int(итог.собралось)
        строка["сошлось"] += итог.сошлось
        строка["случаев"] += len(СЛУЧАИ)
        состояние = (
            f"случаев сошлось: {итог.сошлось}/{len(СЛУЧАИ)}"
            if итог.собралось
            else "не собралось"
        )
        print(f"{начало}  функция: {имя:<24} {состояние:<24}{хвост}")
        if итог.ошибка:
            print(f"        причина: {итог.ошибка}")

    print()
    print("сводка по температурам:")
    for температура in sorted(сводка):
        строка = сводка[температура]
        часть = (
            f"с кодом {строка['с кодом']}/{строка['всего']}, "
            f"собралось {строка['собралось']}/{строка['с кодом']}, "
            f"случаев сошлось {строка['сошлось']}/{строка['случаев']}"
            if not пропуск
            else f"ответов {строка['всего']}, сборка пропущена"
        )
        print(f"  t={температура:<4} {часть}, с преамбулой {строка['преамбула']}")


if __name__ == "__main__":
    # Путь к журналу можно назвать доводом: рядом с рабочим `data/grid.jsonl` живут
    # отложенные прогоны (например `data/grid-проба.jsonl`), и разбирать их правкой кода
    # неудобно.
    отчёт(Path(sys.argv[1]) if len(sys.argv) > 1 else DATA_PATH)
