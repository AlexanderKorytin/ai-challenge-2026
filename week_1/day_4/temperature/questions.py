#: Температуры, при которых прогоняется каждый вопрос.
TEMPERATURES: tuple[float, ...] = (0.0, 0.7, 1.2, 2.0)

#: Сколько раз повторяется вопрос при каждой температуре.
REPEATS: int = 3

_ПО_ИДЕНТИФИКАТОРУ: dict[str, Question] = {вопрос.id: вопрос for вопрос in QUESTIONS}


def by_id(question_id: str) -> Question:
    """Вопрос по идентификатору. Неизвестный идентификатор — KeyError."""
    return _ПО_ИДЕНТИФИКАТОРУ[question_id]


# --- разбор ответа ------------------------------------------------------------


def _выражение_метки(слово: str, значение: str) -> re.Pattern[str]:
    """Выражение для итоговой строки вида «метка: значение».

    Строка ищется с начала строки (флаг MULTILINE), поэтому итог находится где угодно
    в ответе, но оборот из рассуждения вслух («итак, получаем ответ: 3») меткой не
    считается. Между началом строки и меткой допускается оформление, которым модель
    охотно выделяет итог: пункт списка, цитата, заголовок, звёздочки жирного начертания
    вокруг метки или вокруг всей строки. Перевод строки внутрь не пускается — иначе
    выражение перескочит на следующую строку рассуждения и выдаст чужое значение.
    """
    оформление_и_метка = r"^[ \t>*#\-]*\*{0,2}" + слово + r"\*{0,2}[ \t]*:[ \t]*\*{0,2}[ \t]*"
    return re.compile(оформление_и_метка + значение, re.IGNORECASE | re.MULTILINE)


# Запрет справа не даёт взять число по кусочкам: цифра, точка или запятая сразу за
# числом означают, что число на этом не кончилось (3.5 или 3,5), а пробел с цифрой —
# что дальше идут разряды (1 000). В таких случаях лучше пустая клетка, чем показанное
# человеку «3» вместо 3.5. Хвост из букв (3 яблока) числу не мешает.
_ЧИСЛО = _выражение_метки("ответ", r"(-?\d+)(?![\d.,]|[ \t]+\d)")

# Дата берётся до конца строки: она бывает какой угодно формы («12 марта 1834 года»,
# «1834»), и разбирать её на части незачем — значение показывается человеку как есть.
# Метка пишется и через пробел, и через подчёркивание.
_ДАТА_РОЖДЕНИЯ = _выражение_метки("дата[ _]рождения", r"(.+?)[ \t]*$")

#: Чем модель заполняет поле, когда даты у неё нет. Это отказ, а не значение: показать
#: прочерк в клетке значило бы выдать отсутствие ответа за ответ.
ОТКАЗ_ВМЕСТО_ДАТЫ = {"—", "-", "–", "?", "неизвестно", "нет данных", "н/д"}


def extract_value(question: Question, answer: str) -> str | None:
    """Сравнимое значение из ответа модели или None, если его нет.

    Число берётся из **последней** строки «ответ: …»: модель, рассуждая вслух, нередко
    называет промежуточный итог, а потом себя поправляет — верным считается последнее
    слово. Дата рождения, наоборот, берётся из **первой** строки «дата рождения: …»:
    так задан формат ответа, а дальше по тексту дата может встретиться внутри пояснения
    или в перечне фактов.

    Прочерк и слова вроде «неизвестно» в поле даты значением не считаются: это отказ,
    а показать его как значение — выдать отсутствие ответа за ответ.

    Значение либо распознано целиком, либо не распознано вовсе: неполное значение
    (обрезанная дробь, первый разряд числа, начало другого слова) не возвращается —
    пустая клетка честнее подменённой.
    """
    if question.answer_kind == "number":
        совпадения = _ЧИСЛО.findall(answer)
        return совпадения[-1] if совпадения else None

    if question.answer_kind == "birthdate":
        совпадение = _ДАТА_РОЖДЕНИЯ.search(answer)
        if совпадение is None:
            return None
        дата = совпадение.group(1).strip().strip("*").strip()
        return дата if дата and дата.lower() not in ОТКАЗ_ВМЕСТО_ДАТЫ else None

    return None
