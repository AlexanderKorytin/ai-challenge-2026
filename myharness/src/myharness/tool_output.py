"""Большой результат инструмента — в файл, длинная ошибка — началом и концом.

Правило Claude Code для MCP (`code.claude.com/docs/en/mcp.md`): успешный результат длиннее
50 000 знаков или 25 000 токенов (`MAX_MCP_OUTPUT_TOKENS`) ложится в файл сеанса, модель получает
путь и начало и дочитывает файл инструментом `Read`. Ошибка длиннее примерно 11 000 знаков
сокращается до первых и последних 5000. Без предела бывает беда дня 31: `search_files` вернул
3,8 МБ, и DeepSeek отказал ошибкой 400.

Обёртка, а не правка агента: агент не знает диска (требование `agent`), а каталог выгрузки у
собеседника и у наряда разный. Файлы не удаляются — Claude Code хранит их рядом с сеансом.
"""

from __future__ import annotations

import asyncio
import json
import os
from collections.abc import Callable
from pathlib import Path
from uuid import uuid4

from . import memory, tokens
from .agent import Инструменты

ПРЕДЕЛ_ЗНАКОВ = 50_000
ПРЕДЕЛ_ТОКЕНОВ = 25_000
ПЕРЕМЕННАЯ_ПРЕДЕЛА = "MYHARNESS_MAX_TOOL_OUTPUT_TOKENS"
НАЧАЛО = 2000
ПРЕДЕЛ_ОШИБКИ = 11_000
КРАЙ_ОШИБКИ = 5000


def каталог_выгрузки(cwd: Path) -> Path:
    """Каталог больших результатов рабочего каталога — в каталоге состояния, рядом с разговорами."""
    return memory.state_dir() / "tool-results" / memory.project_key(cwd)


def _предел_токенов() -> int:
    значение = os.environ.get(ПЕРЕМЕННАЯ_ПРЕДЕЛА)
    if значение and значение.isdigit() and int(значение) > 0:
        return int(значение)
    return ПРЕДЕЛ_ТОКЕНОВ


def _велик(текст: str, модель: str) -> bool:
    if len(текст) > ПРЕДЕЛ_ЗНАКОВ:
        return True
    предел = _предел_токенов()
    # Токен не короче знака: текст не длиннее предела в знаках считать незачем.
    return len(текст) > предел and tokens.count_text(текст, модель) > предел


ДЛИНА_СТРОКИ = 2000


def _для_чтения(текст: str) -> str:
    """Текст файла выгрузки, который `Read` дочитает по строкам.

    Ответ MCP часто приходит одной строкой JSON в десятки тысяч знаков, а `Read` листает
    строками и обрезает строку длиннее 2000 знаков. JSON раскладывается по строкам, прочие
    сверхдлинные строки переносятся кусками по 2000 знаков: ни один знак не теряется."""
    try:
        текст = json.dumps(json.loads(текст), ensure_ascii=False, indent=1)
    except (ValueError, RecursionError):
        pass
    строки = []
    for строка in текст.split("\n"):
        строки.extend(строка[i : i + ДЛИНА_СТРОКИ] for i in range(0, max(len(строка), 1), ДЛИНА_СТРОКИ))
    return "\n".join(строки)


def _выгрузить(текст: str, каталог: Path) -> Path:
    if _внутри_состояния(каталог):
        memory.make_private_dir(каталог)
    else:
        каталог.mkdir(parents=True, exist_ok=True, mode=0o700)
    путь = каталог / f"{uuid4().hex}.txt"
    дескриптор = os.open(путь, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(дескриптор, "w", encoding="utf-8") as файл:
        файл.write(текст)
    return путь


def _внутри_состояния(каталог: Path) -> bool:
    корень = memory.state_dir()
    return корень in каталог.parents


def с_выгрузкой(набор: Инструменты | None, каталог: Path, модель: Callable[[], str]) -> Инструменты | None:
    """Тот же набор, но большой результат уходит в файл `каталог`, а длинная ошибка сокращается.

    Схемы и жалоба набора не меняются. Отмена проходит насквозь."""
    if набор is None:
        return None
    исходный = набор.исполнить

    async def исполнить(имя: str, доводы: str) -> str:
        try:
            текст = await исходный(имя, доводы)
        except asyncio.CancelledError:
            raise
        except Exception as exc:  # noqa: BLE001 — ошибка уходит модели текстом, агент её оформит
            сообщение = str(exc)
            if len(сообщение) <= ПРЕДЕЛ_ОШИБКИ:
                raise
            пропущено = len(сообщение) - 2 * КРАЙ_ОШИБКИ
            raise RuntimeError(
                f"{сообщение[:КРАЙ_ОШИБКИ]}\n… пропущено {пропущено} знаков …\n{сообщение[-КРАЙ_ОШИБКИ:]}"
            ) from exc
        if not isinstance(текст, str) or not _велик(текст, модель()):
            return текст
        записано = _для_чтения(текст)
        путь = _выгрузить(записано, каталог)
        # Начало — из записанного файла: номера строк `Read` совпадут с показанным.
        return (
            f"Результат слишком велик ({len(текст)} знаков) и сохранён в {путь}. Начало:\n"
            f"{записано[:НАЧАЛО]}\n…\nЧитай файл инструментом Read с offset и limit."
        )

    return Инструменты(схемы=набор.схемы, исполнить=исполнить, жалоба=набор.жалоба)
