"""Что делать с тем, что человек ввёл: команда это или вопрос модели.

Одна развилка на весь инструмент. Строка, начинающаяся с «/», уходит в свою команду; всё
остальное становится единицей очереди и отправляется тому агенту, чья панель сейчас активна.
Сюда же сходятся две особые строки: ответ на вопрос о ключе и своё значение параметра —
инструмент их ждёт, и обычным вопросом они быть не могут.

Команды ввозятся по имени модуля, а не поимённо: в раздаче видно, к какой семье принадлежит
каждая, и семья читается вместе со строкой, которая её зовёт.
"""

from __future__ import annotations

import asyncio

from . import background, helpdoc, recognizer, ui
from . import agents_panel, commands_context, commands_memory, commands_model, commands_params
from . import commands_project, commands_task
from . import screens as screens_mod
from .conversation import open_new_session
from .output import append_log, replace_log
from . import state as state_mod
from .state import Request, State
from .workers import pane_worker

# Строка, которую человек видит, ПОКА идёт запрос распознавателя. Запрос этот занимает около
# секунды, и секунда тишины после нажатия Enter читается как «инструмент не принял строку»:
# человек жмёт Enter второй раз.
#
# Живёт она ровно столько, сколько идёт разбор, и уступает место итогу — строке записи, строке
# отказа, причине сбоя. На ложном зачине её место занимает обычный ход дела: эхо и ответ
# собеседника, никаких следов разбора. Замирать ей, как строке обмена, нельзя: столбец
# замерших строк заведён под рост расхода ДИАЛОГА, а распознаватель — служебный запрос, и
# встань он в тот же столбец, тот перестал бы отвечать на свой вопрос. Расход его при этом не
# теряется: он уходит в общую сумму копилкой выбывших и виден в `Σ` и в `/tokens`, ровно как
# расход архивариуса.
ОЖИДАНИЕ_РАСПОЗНАВАНИЯ = "разбираю, куда это положить"

# Что говорится второй реплике с зачином, пришедшей, пока разбирается первая.
ВТОРАЯ_РЕПЛИКА = "предыдущую реплику ещё разбираю — эта ушла обычным вопросом"


async def handle_command(text: str, state: State) -> bool:
    parts = text.split(maxsplit=1)
    cmd = parts[0].lower()
    arg = parts[1].strip() if len(parts) > 1 else ""
    if cmd in ("/exit", "/quit"):
        return True
    if state.switching_profile:
        append_log(
            state,
            ui.error_fragments("сначала дождитесь завершения смены профиля"),
        )
        return False
    if cmd == "/help":
        if not arg:
            commands_model.open_help_picker(state)
        else:
            подходящие = helpdoc.найти(arg)
            if len(подходящие) == 1:
                append_log(state, helpdoc.фрагменты(подходящие[0]))
            else:
                append_log(state, helpdoc.ошибка(arg, подходящие))
    elif cmd == "/auth":
        commands_model.cmd_auth(state)
    elif cmd == "/model":
        await commands_model.cmd_model(state, arg)
    elif cmd == "/profile":
        await commands_model.cmd_profile(state, arg)
    elif cmd == "/params":
        commands_params.cmd_params(state)
    elif cmd == "/set":
        commands_params.cmd_set(state, arg)
    elif cmd == "/system":
        # На панели исполнителя показываем его инструкцию: именно её там свернули до строки.
        # На главном экране — ТОЧНЫЙ текст, уходящий в запрос: системную часть со всеми
        # слоями и эфемерный хвост. Это единственная мера человека против незаметного роста
        # памяти, и показывать вместо неё одну инструкцию профиля значило бы её отменить.
        source = state.screen.pane.profile
        if source is None:
            # Хвост берём у поставщика напрямую, а не через агента: агент жалобу глотает —
            # ему нельзя ронять взвешивание, — а `/system` заведена ровно затем, чтобы
            # человек видел правду о своём запросе, включая причину, по которой слоя нет.
            try:
                хвост = state_mod.work_block(state)
            except Exception as exc:  # noqa: BLE001 — поставщик рабочей памяти ходит на диск
                хвост = ""
                append_log(state, ui.error_fragments(f"рабочее состояние не прочитано: {exc}"))
            # Карточку спрашиваем у поставщика ОТДЕЛЬНО, хотя она уже внутри `system_text`:
            # там её берёт `блок_карточки`, а он жалобу глотает — ему нельзя ронять
            # взвешивание. `/system` же обещает точный текст запроса, и молча показать его
            # без карточки значило бы соврать именно в той команде, которая заведена против
            # вранья о составе запроса.
            try:
                state_mod.project_block()
            except Exception as exc:  # noqa: BLE001 — поставщик карточки ходит на диск
                append_log(state, ui.error_fragments(f"карточка проекта не прочитана: {exc}"))
            append_log(
                state,
                ui.request_text_fragments(state.main_agent.system_text(), хвост),
            )
        else:
            append_log(
                state,
                ui.system_prompt_fragments(source.name, source.system),
            )
    elif cmd == "/strategy":
        commands_model.cmd_strategy(state, arg)
    elif cmd == "/facts":
        commands_memory.cmd_facts(state, arg)
    elif cmd == "/branch":
        await commands_memory.cmd_branch(state, arg)
    elif cmd == "/team":
        agents_panel.cmd_team(state, arg)
    elif cmd == "/mouse":
        commands_params.toggle_mouse(state)
    elif cmd == "/clear":
        # Идущий заход сжимателя снимаем ПЕРВЫМ делом. Своего итога он после этого не
        # применит и без отмены — применение сверяется с поколением памяти, — но платить за
        # запрос, чей итог заведомо выброшен, незачем.
        background.отменить(state.сжиматель)
        # Выжимку и заготовку убирает сам агент (`forget`): оставь их — и человек, стёрший
        # разговор, продолжил бы говорить с моделью, которая помнит его пересказ.
        state.main_agent.forget()
        commands_context.сбросить_счёт_отказов(state)
        # Мало забыть разговор в памяти: не открой мы новую сессию, следующий запуск поднял
        # бы очищенное обратно с диска — издевательство, а не очистка.
        open_new_session(state)
        append_log(
            state,
            ui.system_fragments("главный разговор очищен — начат новый разговор"),
        )
    elif cmd == "/context":
        commands_context.cmd_context(state)
    elif cmd == "/compact":
        commands_context.cmd_compact(state)
    elif cmd == "/project":
        commands_project.cmd_project(state, arg)
    elif cmd == "/task":
        commands_task.cmd_task(state, arg)
    elif cmd == "/remember":
        commands_memory.cmd_remember(state, arg)
    elif cmd == "/memory":
        commands_memory.cmd_memory(state, arg)
    elif cmd == "/invariants":
        commands_memory.cmd_invariants(state, arg)
    elif cmd == "/forget":
        commands_memory.cmd_forget(state, arg)
    elif cmd == "/tokens":
        commands_context.cmd_tokens(state)
    elif cmd == "/budget":
        commands_context.cmd_budget(state, arg)
    else:
        append_log(
            state,
            ui.error_fragments(f"неизвестная команда: {cmd} (см. /help)"),
        )
    return False


async def handle_submit(
    raw_text: str,
    state: State,
    *,
    destination_screen: screens_mod.Screen | None = None,
    destination_pane: screens_mod.Pane | None = None,
) -> None:
    if state.awaiting_key:
        state.awaiting_key = False
        await commands_model.do_auth(raw_text, state)
        return

    if state.awaiting_custom:
        commands_params.apply_custom_value(state, raw_text)
        return

    text = raw_text.strip()
    if not text:
        return

    # Идёт интервью о проекте: строка человека — это ответ на заданный вопрос, а не вопрос
    # модели.
    #
    # Командой считаем только ИЗВЕСТНОЕ имя, а не всякую строку с косой чертой впереди. На
    # вопрос «где что лежит?» человек отвечает `/opt/challenge`, и съеденный как «неизвестная
    # команда» ответ ломал бы обряд на самом естественном месте: пара не записана, вопрос не
    # переспрошен, интервью молча ждёт.
    if not ui.известная_команда(text):
        from . import interview

        if interview.идёт(state):
            # Ответ принимаем только с ГЛАВНОГО экрана: обряд идёт там, и строка, набранная
            # на экране способов или стратегии, адресована их собеседнику. Съешь мы её —
            # соседний экран онемел бы, а человек увидел бы не ошибку, а ничего.
            адресат = destination_screen or (
                state.screen if state.screen.interactive else state.main
            )
            if адресат is state.main:
                await interview.принять_ответ(state, text)
                return
            # Имя обряда — у его рода, по той же причине, что и в подсказке Ctrl+C: обрядов
            # два, и чужое имя послало бы человека искать то, чего он не начинал.
            идущий = state.интервью.род if state.интервью is not None else None
            append_log(
                state,
                ui.hint_fragments(
                    f"идёт {идущий.имя if идущий is not None else 'интервью о проекте'}"
                    " — ответьте на главном экране"
                ),
                destination_pane or адресат.pane,
            )
            return

    if text.startswith("/"):
        if await handle_command(text, state):
            if state.app is not None:
                state.app.exit()
        return

    if not state.config.is_authorized:
        append_log(state, ui.hint_fragments("сначала авторизуйтесь: /auth"))
        return

    addressed_screen = destination_screen or (
        state.screen if state.screen.interactive else state.main
    )
    addressed_pane = destination_pane or addressed_screen.pane
    if state.switching_profile:
        append_log(
            state,
            ui.error_fragments("нельзя отправить вопрос: выполняется смена профиля"),
            addressed_pane,
        )
        return
    # Естественная запись — последнее звено развилки, и место у него выбрано не «где-нибудь
    # перед отправкой». Каждая проверка выше отсекает свой род строк, и ни одну из них
    # распознавателю отдавать нельзя:
    #
    # — ответ о ключе и своё значение параметра инструмент ЖДЁТ, и обычным вопросом они быть
    #   не могут, не то что записью в память;
    # — ответ на вопрос интервью адресован обряду: съешь его распознаватель — пара не
    #   записана, вопрос не переспрошен, интервью молча ждёт;
    # — команда называет слой сама, и распознавать в ней нечего;
    # — без ключа спрашивать некого, и человека уже отправили на `/auth`;
    # — при смене профиля вопрос не принимается вовсе, а оплатить запрос и следом отказаться
    #   отправить строку значило бы взять деньги ни за что.
    #
    # Ниже этого места остаётся только постановка в очередь, то есть отправка собеседнику, —
    # а от неё естественная запись как раз и уводит.
    if addressed_screen is state.main and recognizer.есть_зачин(text):
        if not state.идёт_распознавание:
            await _естественная_запись(state, text, addressed_pane)
            return
        # Пока идёт первое распознавание, второго не заводим: два запроса подряд стоят вдвое,
        # а человек, набравший вторую строку, ещё не видел судьбы первой.
        #
        # Но и молча отправить её собеседнику нельзя. Человек просил запомнить — записи нет,
        # пришёл ответ, и ни строки объяснения: он решит, что запись сделана, и узнает об
        # обратном через неделю, когда её не окажется. Молчание оправдано ровно в одном
        # месте развилки — при честном «это не запись», где человек записывать и не просил.
        #
        # Порядок строк тут смысловой, а не косметический: подсказка идёт ПОСЛЕ эха, иначе
        # человек читает «эта ушла обычным вопросом» раньше, чем видит, какая «эта». И она
        # печатается ТОЛЬКО когда строка правда ушла: откажи очередь сменой профиля — и
        # подсказка встала бы прямо над отказом, двумя соседними строками, спорящими друг
        # с другом.
        if _в_главную_очередь(state, text, addressed_pane, эхо=True):
            append_log(state, ui.hint_fragments(ВТОРАЯ_РЕПЛИКА), addressed_pane)
        return

    if addressed_screen is state.main:
        _в_главную_очередь(state, text, addressed_pane, эхо=True)
    else:
        request = Request(content=text, pane=addressed_pane)
        executor = pane_worker(state, addressed_pane)
        was_busy = executor.busy or not executor.queue.empty()
        if not executor.enqueue(request):
            append_log(
                state,
                ui.error_fragments("экран закрывается — вопрос не принят"),
                addressed_pane,
            )
            return
        append_log(state, ui.user_fragments(text), addressed_pane)
        if was_busy:
            append_log(
                state,
                ui.queued_fragments(executor.queue.qsize()),
                addressed_pane,
            )


def _в_главную_очередь(
    state: State, text: str, pane: screens_mod.Pane, *, эхо: bool
) -> bool:
    """Вопрос в общую очередь главного экрана. `False` — не принят, и человеку сказано почему.

    Вынесено из `handle_submit` затем, что путей сюда стало два: обычный и тот, где реплику
    сперва отдали распознавателю и получили «это не запись». Второй путь строку человека уже
    напечатал — он обязан был показать её сразу, пока идёт запрос, — и `эхо=False` держит
    обещание «одна реплика показана один раз». Скопируй мы эти четыре строки вместо выноса,
    два места разошлись бы на первой же правке очереди: одно считало бы позицию, другое нет.

    Смену профиля проверяем ЗДЕСЬ, у самой двери в очередь, а не только наверху развилки.
    Наверху между проверкой и постановкой не было ни одного ожидания, а теперь есть целый
    запрос распознавателя, и в эту секунду человек успевает набрать `/profile другой`.
    `strategies.switch_profile` держится на прямо записанном обещании «новые единицы на время
    ожидания отклоняет `handle_submit`»: он ждёт `queue.join()`, и единица, проскочившая в
    очередь после ожидания, досталась бы уже другому собеседнику — вопрос, заданный профилю
    А, получил бы ответ профиля Б и лёг бы в его разговор, следом за строкой «история диалога
    очищена». Слова человеку те же, что и наверху: одна беда — одна формулировка.
    """
    if state.switching_profile:
        append_log(
            state,
            ui.error_fragments("нельзя отправить вопрос: выполняется смена профиля"),
            pane,
        )
        return False
    if эхо:
        append_log(state, ui.user_fragments(text), pane)
    was_busy = state.busy or not state.queue.empty()
    state.queue.put_nowait(Request(content=text, pane=pane))
    if was_busy:
        append_log(state, ui.queued_fragments(state.queue.qsize()), pane)
    return True


def _снять_ожидание(state: State, pane: screens_mod.Pane, at: int, length: int) -> None:
    """Убрать живую строку разбора из ленты, НЕ сдвигая ничего, что легло ниже неё.

    Строка эта временная: она объясняет секундную паузу и уступает место итогу. Но просто
    вырезать её из ленты нельзя, и причина не в красоте. Пока шёл разбор, ниже могли лечь
    чужие строки — эхо второй реплики, ответ собеседника на неё, — а идущий обмен ПОМНИТ
    НОМЕР своей строки ожидания и обновляет её заменой среза десять раз в секунду. Вырежи мы
    свою строку — все номера ниже уехали бы на её длину, и обмен принялся бы затирать чужой
    кусок ленты. Молча: ни исключения, ни следа, только каша на экране.

    Поэтому длина ленты остаётся прежней, а фрагменты становятся пустыми — на экране от них
    не остаётся ничего, включая перевод строки, и счётчики строк `replace_log` пересчитывает
    сам, разницей. Тот же приём, каким заголовок размышлений встаёт на место идущего, только
    там постоянство длины нужно ради собственного номера, а здесь — ради чужих.
    """
    replace_log(state, pane, at, length, [("", "")] * length)


async def _естественная_запись(state: State, text: str, pane: screens_mod.Pane) -> None:
    """Реплика начиналась с зачина: спрашиваем адрес и кладём строку в названный слой.

    Единственное обещание, которое здесь держится на каждом пути: **набранное человеком не
    пропадает**. Распознаватель ошибся, не ответил, упал, ответил «это не запись» — строка всё
    равно уходит обычным вопросом собеседнику, ровно как если бы распознавателя не было вовсе.
    Потерять её было бы худшим из возможных исходов: человек видит своё эхо в ленте, ответа
    нет, записи нет, и объяснения тоже нет.

    Обратный случай — адрес НАЗВАН. Тогда реплика была просьбой запомнить, а не вопросом, и
    собеседнику она не адресована: отправить её значило бы заплатить за ответ на просьбу,
    которую уже разобрали. Что случилось со строкой, человек читает в ленте — и удачная
    запись, и отказ хранилища, и замок «Ограничений» называют себя сами, а отказ вдобавок
    даёт готовую команду с тем же текстом.

    Панель захватывается ОДИН раз, до запроса, и дальше все до единой строки этого пути идут
    в неё — включая те, что печатает `записать`. За секунду разбора человек успевает уйти на
    соседний экран клавишей Tab, и подтверждение, отправленное «в текущий экран», уехало бы
    туда, а на главном остались бы эхо и пустое место — картинка, неотличимая от молча
    съеденной строки, то есть ровно та, которую всё звено обещает не допустить.
    """
    # Эхо печатаем ЗДЕСЬ, до запроса, и ровно один раз. До запроса потому, что он идёт около
    # секунды, и всё это время человек обязан видеть, что строка принята. Один раз потому,
    # что обычный путь вопроса зовётся отсюда с `эхо=False`: напечатай он своё — одна реплика
    # показалась бы дважды, и человек решил бы, что отправил её два раза.
    append_log(state, ui.user_fragments(text), pane)
    ожидание = ui.system_fragments(ОЖИДАНИЕ_РАСПОЗНАВАНИЯ)
    место_ожидания = len(pane.log)
    append_log(state, ожидание, pane)
    # Признак поднимается до ЕДИНСТВЕННОГО здесь ожидания, и между ним и проверкой в развилке
    # нет ни одного `await`: каждое нажатие Enter заводит свою задачу, и уступи мы управление
    # хоть раз, вторая реплика успела бы проскочить проверку, пока первая ещё не поднялась.
    state.идёт_распознавание = True
    адрес: recognizer.Адрес | None = None
    причина = ""  # непуста ТОЛЬКО когда запрос ушёл к серверу — договор `спросить`
    беда = ""  # исключение: об оплате оно не говорит ничего, и выдавать его за причину нельзя
    try:
        адрес, причина = await recognizer.спросить(state, text)
    except asyncio.CancelledError:
        # Отмену заказывает человек — выходом из инструмента. Глотать её нельзя, а класть
        # строку в очередь уже некуда: читать эту очередь никто не станет. Живую строку при
        # этом снимаем: висеть в ленте настоящим временем ей больше не о чем.
        _снять_ожидание(state, pane, место_ожидания, len(ожидание))
        raise
    except Exception as exc:  # noqa: BLE001 — распознаватель ходит и в сеть, и на диск
        # Договор `спросить`: прочие беды разбирает развилка ввода, потому что решение о
        # набранной человеком строке принимается здесь, а не там. Решение одно и то же на
        # любую беду — сказать её человеку и отправить строку вопросом.
        #
        # А вот СЛОВА разные, и держать их врозь обязательно. Договор `спросить` обещает:
        # причина непуста ровно тогда, когда запрос ушёл к серверу. Исключение же прилетает и
        # оттуда, где денег не потрачено вовсе — `вход` ходит на диск и зовёт `Path.cwd()`,
        # который падает в унесённом каталоге, и агента к этому мигу ещё нет. Сложи мы беду
        # в ту же переменную — человек читал бы «сбой обмена» там, где обмена не было вовсе,
        # и договор врал бы о поведении, а поведение о договоре.
        беда = str(exc) or exc.__class__.__name__
    finally:
        state.идёт_распознавание = False

    # Разбор кончился — настоящему времени в ленте больше не место. Снимаем строку ДО того,
    # как напечатан итог: иначе итог встал бы под «разбираю, куда это положить», и человек
    # прочёл бы его как обещание, а не как сделанное.
    _снять_ожидание(state, pane, место_ожидания, len(ожидание))

    if адрес is not None:
        # Ответ `записать` здесь намеренно не разбирается: легла строка или отказал замок —
        # реплика в обоих случаях была просьбой запомнить, и собеседнику она не адресована.
        # Отправь мы отказанную строку вопросом — человек получил бы поверх честного «раздел
        # „Ограничения“ пишете только вы» ещё и ответ модели на ту же строку, то есть оплату
        # за разговор, которого не просил.
        try:
            recognizer.записать(state, адрес, pane)
        except Exception as exc:  # noqa: BLE001 — запись ходит на диск и зовёт `Path.cwd()`
            # Единственный путь этого звена, который иначе кончался бы полной тишиной:
            # исключение отсюда ушло бы в задачу нажатия, где его снимают и не печатают
            # ничего. У человека остались бы эхо, оплаченный запрос — и ни записи, ни
            # ответа, ни причины. Проглотить беду мы не вправе, а решать за него, что
            # делать дальше, не из чего: слова его, адрес разобран, отказал диск.
            #
            # «Не вышло» тут сказать нельзя: беда могла случиться и ПОСЛЕ того, как строка
            # легла, — на перечитывании слоя ради номера отмены. Утверждать надо ровно то,
            # что известно: случилась беда, вот она.
            append_log(
                state,
                ui.error_fragments(
                    f"при записи случилась беда: {str(exc) or exc.__class__.__name__}"
                ),
                pane,
            )
            # Адрес разобран, значит команду собрать есть из чего — и вернуть её человеку
            # обязаны: набранное им живёт сейчас только эхом в ленте. Замок «Ограничений» и
            # отказ «рабочей задачи нет» команду возвращают, и третий отказ одного звена
            # вести себя иначе не вправе.
            команда = recognizer.команда_записи(адрес)
            if команда:
                append_log(state, ui.hint_fragments(f"проверьте и повторите: {команда}"), pane)
        return
    if причина:
        # Оплаченный сбой: запрос состоялся, деньги ушли, адреса нет. Молчание здесь оставило
        # бы человека с необъяснённой задержкой и без записи — и он повторил бы реплику,
        # заплатив второй раз за то же самое.
        append_log(
            state,
            ui.error_fragments(f"куда это положить, не разобрал: {причина}"),
            pane,
        )
    elif беда:
        # Про деньги здесь молчим намеренно: обмена могло и не быть. Сказано ровно то, что
        # известно, — разбор оборвался, вот чем.
        append_log(
            state,
            ui.error_fragments(f"разобрать, куда это положить, не удалось: {беда}"),
            pane,
        )
    # Пустая причина — честный ответ «это не запись»: реплика уходит вопросом МОЛЧА, и в
    # ленте не остаётся ни следа разбора. Строка о том, что записывать нечего, стояла бы на
    # каждой второй просьбе «запиши функцию» и не сообщала бы человеку ничего, чего он и так
    # не видит по ответу собеседника.
    _в_главную_очередь(state, text, pane, эхо=False)
