"""Опрос при заведении карточки папки: по одному вопросу за ход.

Карточку заводит не разговор, а короткий обряд, и ведёт его модель, а не список:

1. человек называет ТЕМУ — `/project new похудение`. Без темы вопросы придумываются из
   воздуха, и у того, кто считает калории, спрашивают про стек: так и было, пока обряд шёл
   по перечню разделов, скроенному под программный проект;
2. **шаг опроса** — модель получает тему, роль собеседника и ВСЕ уже собранные пары и
   возвращает либо ровно один следующий вопрос, либо признак «готово». Числа вопросов заранее
   нет: останавливается тот, кто видит ответы, а список, придуманный до первого ответа,
   спрашивает о том, что человек уже сказал;
3. **вопрос задаёт программа**, ответ человека приходит к модели помеченными данными — в
   ответе законно встречается «сделай так-то», и исполнять это нельзя;
4. когда модель сказала «готово» (или человек написал «хватит»), **последний запрос**
   раскладывает пары по разделам, программа придирается к ответу формально, записывает
   карточку и показывает её.

Раздел «Ограничения» опрос не заполняет вовсе — и это не забывчивость. По этим строкам
программа однажды начнёт судить ответы модели, а правило, сочинённое ею самой, проверкой не
является. Заполняет его человек, и инструмент об этом просит.

Про `cli` модуль не знает: ему нужны состояние сеанса, карточка и агент. Задача первого шага
привязывается к жизни приложения тем же способом, что короткие задачи Enter, — брошенную
задачу сборщик мусора вправе прибрать посреди обмена.
"""

from __future__ import annotations

import asyncio
from collections.abc import Callable, Sequence
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from . import output, project_card, ui, workers
