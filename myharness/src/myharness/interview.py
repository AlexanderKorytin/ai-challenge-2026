"""Интервью при открытии проекта: два запроса к модели, а между ними вопросы человеку.

Карточку папки заводит не разговор, а короткий обряд с двумя платными обменами:

1. **первый запрос** — «вот инструкция собеседника и имя папки, что нужно выяснить у
   человека»; ответ объектом JSON со списком из трёх-пяти вопросов;
2. **вопросы задаёт программа**, по одному в ленте, дожидаясь ответа. Обмена с моделью между
   вопросами НЕТ;
3. **второй запрос** — пары «вопрос — ответ» превращаются в разделы карточки;
4. программа придирается к ответу формально, записывает карточку и показывает её.

Почему вопросы задаёт программа, а не модель в свободной беседе. Беседа даёт пересказ вместо
карточки, а ответ человека, пришедший отдельной репликой, модель читает как указание. Здесь
он уходит помеченными данными (`project_card.card_request`), и «сделай так-то» внутри ответа
остаётся текстом ответа, а не поручением.

Раздел «Ограничения» интервью не заполняет вовсе — и это не забывчивость. По этим строкам
программа будет судить ответы модели на нарушение, а правило, сочинённое самой моделью для
проверки собственных ответов, — не проверка, а её видимость. Запрет стоит трижды: в
инструкции второго запроса, в разборе ответа и в самой записи карточки. Здесь остаётся
сказать об этом человеку словами — иначе раздел останется пустым, и судить будет нечего.

Модуль знает про карточку (`project_card`), обмен (`agent`), ленту (`output`, `ui`) и
состояние сеанса. Про `cli` не знает: его зовут сверху — команда `/project new` и общая
развилка ввода.

Всё, что интервью печатает, идёт в ГЛАВНЫЙ экран, а не туда, где человек стоит сейчас.
Причина: обряд растянут на несколько нажатий Enter, человек волен между ними перейти на
соседнюю вкладку, и нитка вопросов расползлась бы по экранам. Главный экран есть всегда, и
карточка принадлежит ему же.
"""

from __future__ import annotations

import asyncio
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from . import output, project_card, ui, workers
from .agent import Agent
from .conversation import забыть_счёт_занятости
from .state import State

# Под этим источником карточка подписывается в заголовке файла. Он же отличает её от карточки,
# написанной человеком: `project_card.create` по нему запирает раздел «Ограничения».
ИСТОЧНИК = "интервью"


@dataclass
class Интервью:
    """Один идущий обряд: где заводим карточку, о чём уже спросили и чего ждём.

    Живёт в `state.интервью`, и пока оно там — строка человека это ответ на заданный вопрос,
    а не вопрос модели.

    Профиль держим ссылкой на сам объект, а не именем: смена профиля заменяет объект целиком
    (а заодно стирает историю и заводит нового собеседника), и сверка по тождеству замечает
    даже переключение на профиль с тем же именем.
    """

    каталог: Path
    профиль: Any  # Profile; подсказка типа не стоит ввоза — так же, как у `state.интервью`
    вопросы: list[str] = field(default_factory=list)
    пары: list[tuple[str, str]] = field(default_factory=list)
    # Идёт запрос к модели: строка человека сейчас не ответ — отвечать ещё не на что.
    ждёт_модель: bool = True


def идёт(state: State) -> bool:
    """Идёт ли интервью прямо сейчас. По нему общая развилка ввода решает, чья эта строка."""
    return state.интервью is not None


def начать(state: State) -> None:
    """Завести интервью: первый запрос уходит в фон, а команда возвращается сразу.

    Синхронна намеренно: `/project new` не имеет права держать ввод, пока модель думает над
    списком вопросов. Сам обмен уезжает отдельной задачей.
    """
    if идёт(state):
        # Когда идёт запрос к модели, заданного вопроса на экране нет, и советовать «ответьте
        # на заданный вопрос» значило бы послать человека искать то, чего не видно.
        ждёт = state.интервью.ждёт_модель
        _сказать(
            state,
            ui.hint_fragments(
                "интервью уже идёт — ждём ответа модели; прервать: /project отмена"
                if ждёт
                else "интервью уже идёт — ответьте на заданный вопрос; прервать: /project отмена"
            ),
        )
        return
    if state.client is None:
        # Интервью — это два платных обмена, без ключа его начинать не с чем. Говорим до
        # того, как завели состояние: иначе инструмент принялся бы ловить ответы на вопросы,
        # которых никто не задавал.
        _сказать(state, ui.hint_fragments("интервью спрашивает модель — сначала /auth"))
        return

    каталог = Path.cwd()
    прежняя, жалобы = project_card.load(каталог)
    if прежняя is None and жалобы:
        # Файл лежит, но карточкой не читается. Записать поверх него `create` откажется, и
        # узнать об этом после двух оплаченных запросов — худший из возможных порядков.
        for жалоба in жалобы:
            _сказать(state, ui.error_fragments(жалоба))
        _сказать(
            state,
            ui.hint_fragments(
                "поправьте файл руками или уберите его — интервью не начинаю, "
                "чтобы не платить за два запроса впустую"
            ),
        )
        return

    интервью = Интервью(каталог=каталог, профиль=state.profile)
    state.интервью = интервью
    if прежняя is not None:
        _сказать(
            state,
            ui.system_fragments(
                f"карточка папки {каталог.name} уже есть — интервью заменит её; "
                "раздел «Ограничения» при этом сохранится"
            ),
        )
    _сказать(
        state,
        ui.system_fragments(f"интервью о папке {каталог.name}: спрашиваю у модели, что выяснить"),
    )
    # Задача привязывается к жизни приложения тем же способом, что и короткие задачи Enter:
    # брошенную задачу сборщик мусора вправе прибрать посреди обмена, а при выходе её надо
    # снять и дождаться — иначе поверх прощального экрана вылезет «задача уничтожена, а она
    # ещё работала». Своей фоновой службы (`background.Служба`) интервью не заводит: её
    # никто не снимал бы при выходе, а трогать выход ради одного обряда незачем.
    workers.track_submission(state, asyncio.create_task(_первый_запрос(state, интервью)))


async def принять_ответ(state: State, текст: str) -> None:
    """Строка человека как ответ на заданный вопрос.

    Зовётся общей развилкой ввода с ГЛАВНОГО экрана, когда `идёт` сказал «да» и строка не
    известная команда. «Известная», а не «начинается с косой черты», — потому что на вопрос
    «где что лежит?» человек отвечает `/opt/challenge`, и съеденный такой ответ ломал бы
    главный сценарий обряда на самом естественном месте.
    """
    интервью = state.интервью
    if интервью is None:
        return

    if интервью.ждёт_модель:
        # Вопроса на экране сейчас нет. Эта ветвь стоит ПЕРВОЙ, и порядок здесь важен: когда
        # идёт второй запрос, ответы человека уже полны и оплачены, и смена профиля их не
        # отменяет — знание о папке не зависит от того, кто о ней говорит. Поставь сверку
        # профиля выше, и карточка, за которую заплачено дважды, выбрасывалась бы ровно на
        # финишной прямой, а человеку предлагалось заплатить ещё дважды.
        _сказать(
            state,
            ui.hint_fragments("интервью ждёт ответа модели — строка не принята, повторите её"),
        )
        return

    if state.switching_profile or интервью.профиль is not state.profile:
        # Собеседник, чьей инструкцией придуманы вопросы, уходит или уже ушёл, а вопросы ещё
        # не отвечены. Бросить состояние как есть нельзя вдвойне: интервью ело бы дальше
        # каждую строку человека, адресованную новому собеседнику, и тот молчал бы, а причины
        # не было бы видно.
        _прибрать(state, интервью)
        # Строку человека отражаем в ленте: она набрана и отправлена, и пропасть бесследно
        # не имеет права — иначе человек не знает, дошла она или нет.
        _сказать(state, ui.user_fragments(текст))
        _сказать(
            state,
            ui.error_fragments("профиль сменился посреди интервью — строка не принята, карточка не записана"),
        )
        _сказать(state, ui.hint_fragments("завести её заново: /project new"))
        return

    # Ответ печатаем сами: общая развилка ввода на этом пути молчит, и без строки в ленте
    # остались бы одни вопросы, без единого следа того, что человек на них сказал.
    _сказать(state, ui.user_fragments(текст))
    интервью.пары.append((интервью.вопросы[len(интервью.пары)], текст))
    if len(интервью.пары) < len(интервью.вопросы):
        _задать_вопрос(state, интервью)
        return
    интервью.ждёт_модель = True
    await _второй_запрос(state, интервью)


def отменить(state: State) -> bool:
    """Прервать идущее интервью по слову человека. `False` — прерывать было нечего.

    Явный выход нужен потому, что обряд растянут на несколько нажатий Enter, и передумавший
    человек иначе заперт: либо отвечай на оставшиеся вопросы, либо перезапускай инструмент.
    Уже оплаченный первый запрос при этом пропадает — и об этом говорится вслух.
    """
    интервью = state.интервью
    if интервью is None:
        return False
    собирается = интервью.ждёт_модель and len(интервью.пары) == len(интервью.вопросы) and интервью.вопросы
    if собирается:
        # Ответы уже ушли на сборку карточки: оплачены оба запроса, и карточка вот-вот ляжет
        # на диск. Отменить её здесь значило бы выбросить и деньги, и ответы человека за
        # секунду до готового итога — причём ради того, чтобы «прервать зависшее».
        _сказать(
            state,
            ui.hint_fragments(
                "ответы уже ушли на сборку карточки — дождитесь, она вот-вот будет записана"
            ),
        )
        return True
    _прибрать(state, интервью)
    _сказать(state, ui.system_fragments("интервью прервано — карточка не записана"))
    оплачено = "оба запроса уже оплачены" if интервью.пары else "запрос на вопросы уже оплачен"
    _сказать(state, ui.hint_fragments(f"{оплачено}; начать заново: /project new"))
    return True


async def _первый_запрос(state: State, интервью: Интервью) -> None:
    """«Что выяснить у человека» — и первый вопрос на экране.

    Идёт отдельной задачей, поэтому ловит всё: выпущенное отсюда исключение никому бы не
    досталось, а человек остался бы перед инструментом, который ест его строки и молчит.
    """
    вход = project_card.questions_request(интервью.профиль.system, интервью.каталог.name)
    try:
        текст, ошибка = await _обмен(state, project_card.questions_profile(), вход)
    except asyncio.CancelledError:
        # Отмену заказывает человек (выход из инструмента): состояние прибираем, а само
        # исключение отдаём наружу — глотать отмену нельзя.
        _прибрать(state, интервью)
        raise
    except Exception as exc:
        _неудача(state, интервью, str(exc))
        return
    if текст is None:
        _неудача(state, интервью, ошибка)
        return
    if state.интервью is not интервью:
        # Пока шёл запрос, интервью бросили. Вопросы задавать некому.
        return
    try:
        интервью.вопросы = project_card.parse_questions(текст)
    except ValueError as exc:
        # Непригодный ответ — это не «спрашивать нечего»: пустой список увёл бы человека в
        # карточку без единого вопроса, а запрос уже оплачен.
        _неудача(state, интервью, str(exc))
        return
    интервью.ждёт_модель = False
    _сказать(
        state,
        ui.system_fragments(
            f"вопросов будет {len(интервью.вопросы)}; отвечайте строкой, "
            "а чтобы выйти, не отвечая, — /project отмена"
        ),
    )
    _задать_вопрос(state, интервью)


async def _второй_запрос(state: State, интервью: Интервью) -> None:
    """Пары «вопрос — ответ» превращаются в разделы карточки, карточка ложится на диск."""
    _сказать(state, ui.system_fragments("ответы собраны — прошу модель разложить их по разделам"))
    try:
        текст, ошибка = await _обмен(
            state, project_card.card_profile(), project_card.card_request(интервью.пары)
        )
    except asyncio.CancelledError:
        _прибрать(state, интервью)
        raise
    except Exception as exc:
        _неудача(state, интервью, str(exc))
        return
    if текст is None:
        _неудача(state, интервью, ошибка)
        return
    if state.интервью is not интервью:
        # Интервью бросили, пока шёл запрос: писать карточку из ответов, за которыми человек
        # уже не стоит, нельзя. Смена профиля сюда НЕ относится и карточку не отменяет —
        # ответы даны человеком и полны, а знание о папке от персоны не зависит.
        return
    try:
        разделы = project_card.parse_card(текст)
    except ValueError as exc:
        _неудача(state, интервью, str(exc))
        return

    # Формальные придирки называем вслух, но карточку из-за них не выбрасываем: обе они —
    # признаки, а не приговор («разделов мало», «похоже на пересказ»), судить о содержании
    # по смыслу программа не может. Решает человек, глядя на карточку, — а чтобы глядеть,
    # она должна быть записана и показана.
    for жалоба in project_card.проверить_карточку(разделы):
        _сказать(state, ui.error_fragments(f"карточка вышла сомнительной: {жалоба}"))

    прежняя_карточка = project_card.load(интервью.каталог)[0]
    # Копию кладёт `create`, и кладёт не всегда: карточку, писанную моделью, он поверх
    # человеческой копии не пишет. Поэтому запоминаем не «прежняя была», а время файла копии
    # — по нему видно, обновилась она этой заменой или лежит прежняя, постарше.
    копия = project_card.прежний_путь(интервью.каталог)
    копия_до = копия.stat().st_mtime if копия.exists() else None
    карточка, сообщение = project_card.create(интервью.каталог, разделы, источник=ИСТОЧНИК)
    _прибрать(state, интервью)
    if карточка is None:
        _сказать(state, ui.error_fragments(f"карточка не записана: {сообщение}"))
        return
    # Карточка уедет в системную часть следующего запроса и утяжелит его. Полоска занятости
    # узнать об этом сама не может: карточка лежит на диске, а её отпечаток видит только
    # память и профиль.
    забыть_счёт_занятости(state)
    _сказать(state, ui.system_fragments(f"карточка проекта «{сообщение}» записана интервью"))
    _сказать(state, ui.card_fragments(карточка))
    if прежняя_карточка is not None and копия.exists():
        # Интервью заменяет карточку целиком, и прежняя могла быть лучше новой — особенно
        # когда придирки выше уже напечатаны. Путь к копии называем всегда, но говорим правду
        # о том, что в ней: заменилась она этой заменой или там лежит карточка постарше.
        обновилась = копия_до is None or копия.stat().st_mtime > копия_до
        _сказать(
            state,
            ui.hint_fragments(
                f"прежняя карточка сохранена рядом: {копия} — если новая вышла хуже, верните её оттуда руками"
                if обновилась
                else f"рядом лежит копия ПОСТАРШЕ — заменённую карточку писала модель, и копией её не заменяли: {копия}"
            ),
        )
    _сказать(
        state,
        ui.hint_fragments(
            "раздел «Ограничения» интервью не заполняет вовсе: по этим строкам программа "
            "будет судить ответы модели, а правило, сочинённое самой моделью, проверкой не "
            "является — впишите его сами: /project Ограничения <текст>"
        ),
    )


async def _обмен(state: State, профиль: Any, вход: str) -> tuple[str | None, str]:
    """Один платный обмен интервьюера. `(текст, "")` — удача, `(None, причина)` — нет.

    Агент одноразовый: памяти у интервьюера нет, каждый запрос самодостаточен. Расход его
    обмена уходит в копилку выбывших — интервьюер живёт вне панелей, а значит и вне обхода
    агентов сеанса, и без этой строки его деньги не попали бы в итог никогда.

    `retire` стоит в `finally`: обмен, оборвавшийся посередине, тоже мог быть оплачен, и
    тратить деньги человека молча нельзя ни на каком пути.
    """
    агент = Agent(project_card.ИМЯ_ИНТЕРВЬЮЕРА, профиль)
    обмен = None
    try:
        обмен = await агент.exchange(
            state.client, state.model, вход, agent=project_card.ИМЯ_ИНТЕРВЬЮЕРА
        )
    finally:
        state.retire([агент])
        # Деньги считаем ОТДЕЛЬНО от токенов: копилка выбывших несёт токены, а рубли
        # копятся по ходу и по тарифу той модели, которой обмен сделан. Интервью ходит
        # `state.model`, то есть возможно и дорогой моделью, и запускает его человек —
        # промолчать об этих деньгах значило бы показать `/tokens`, который врёт вниз.
        if обмен is not None:
            цена = output.turn_price(обмен)
            if цена is None:
                state.session_cost_known = False
            else:
                state.session_cost += цена
    if not обмен.ok:
        return None, обмен.error or "неизвестная причина"
    if обмен.finish_reason == "length":
        # Обрыв по длине — не «ответить нечего», а «мы не дали договорить»: оборванный JSON
        # не разбирается вовсе, и путать эти два случая нельзя.
        return None, "ответ оборван по длине"
    return обмен.text, ""


def _задать_вопрос(state: State, интервью: Интервью) -> None:
    """Очередной вопрос в ленту. Номер виден, чтобы человек знал, сколько осталось."""
    номер = len(интервью.пары) + 1
    вопрос = интервью.вопросы[len(интервью.пары)]
    _сказать(
        state,
        ui.system_fragments(f"вопрос {номер} из {len(интервью.вопросы)}: {вопрос}"),
    )


def _неудача(state: State, интервью: Интервью, причина: str) -> None:
    """Интервью сорвалось. Карточка не пишется, а о потраченных деньгах говорится вслух.

    Говорим и тогда, когда интервью уже бросили: запрос оплачен независимо от того, ждёт ли
    ещё кто-то его ответа, и молча съесть деньги человека нельзя.
    """
    _прибрать(state, интервью)
    _сказать(state, ui.error_fragments(f"интервью не удалось: {причина}"))
    _сказать(
        state,
        ui.hint_fragments(
            "запрос к модели уже оплачен, карточка не записана; "
            "повторить — /project new, завести руками — /project <раздел> <текст>"
        ),
    )


def _прибрать(state: State, интервью: Интервью) -> None:
    """Убрать состояние, если оно всё ещё наше.

    Сверка по тождеству обязательна: обнули мы поле вслепую, сорвавшееся интервью отменило бы
    заодно то, которое человек успел начать заново.
    """
    if state.интервью is интервью:
        state.интервью = None


def _сказать(state: State, fragments: list[tuple[str, str]]) -> None:
    """Строка в главный экран. Показ ленты обновляет сам `append_log`."""
    output.append_log(state, fragments, state.main)
