# Под этим источником карточка подписывается в заголовке файла. Он же отличает её от карточки,
# написанной человеком: `project_card.create` по нему запирает раздел «Ограничения».
ИСТОЧНИК = "интервью"

# Чем человек говорит «спрашивать больше не о чем». Слово, а не команда: он в этот момент
# отвечает на вопрос, и просить его вспомнить косую черту — лишний шаг.
# «Всё» и «все» сюда НЕ входят намеренно: это законный ответ на вопрос «что вы едите?», и
# закончить им опрос значило бы оборвать обряд на ровном месте.
СЛОВА_ХВАТИТ = frozenset({"хватит", "достаточно", "стоп"})


@dataclass(frozen=True)
class Род:
    """Чем один обряд отличается от другого: слова, запросы, разбор и запись итога.

    Ход обряда — по одному вопросу за ход, ответ человека данными, право сказать «хватит»,
    сборка из того, что есть, отмена и приборка — общий: он вылизан карточкой папки, и
    заводить ему копию ради второго обряда значило бы чинить потом обе. Различаются ровно
    четыре вещи: как назвать обряд человеку, о чём спросить модель, как разобрать её ответ и
    что сделать с итогом.

    Ни одно поле не имеет умолчания: род, забывший сказать, чем кончается неудача, оставил бы
    человека без вести о потраченных деньгах.
    """

    имя: str  # как обряд называется человеку: «интервью», «мастер профиля»
    итог_не_записан: str  # «карточка не записана», «профиль не записан»
    прерван: str  # «интервью прервано», «мастер профиля прерван»
    не_удался: str  # «интервью не удалось», «мастер профиля не справился»
    итог_вот_вот: str  # «карточка вот-вот будет записана», «профиль вот-вот будет записан»
    команда_заново: str  # «/project new», «/profile new»
    команда_заново_с_доводом: str  # с доводом, каким его набирает человек
    команда_отмены: str  # «/project отмена», «/profile отмена»
    агент: str  # под каким именем обряд ходит к модели: журнал и копилка выбывших
    подсказка_после_неудачи: str  # что делать, когда обряд сорвался
    сборка_объявление: str  # что говорим, отправляя последний запрос обряда
    подготовить: Callable[[State, "Интервью"], bool]  # False — не начинать; сообщения печатает сам
    шаг_запрос: Callable[["Интервью"], tuple[Any, str]]  # (профиль запроса, текст запроса)
    шаг_разбор: Callable[[str], str | None]  # вопрос либо None — «хватит»; ValueError — мусор
    итог_запрос: Callable[["Интервью"], tuple[Any, str]]
    итог_записать: Callable[[State, "Интервью", str], None]  # разбор, запись и показ итога


@dataclass
class Интервью:
    """Один идущий обряд: где заводим карточку, о чём уже спросили и чего ждём.

    Живёт в `state.интервью`, и пока оно там — строка человека это ответ на заданный вопрос,
    а не вопрос модели.

    Профиль держим ссылкой на сам объект, а не именем: смена профиля заменяет объект целиком
    (а заодно стирает историю и заводит нового собеседника), и сверка по тождеству замечает
    даже переключение на профиль с тем же именем.
    """

    каталог: Path
    профиль: Any  # Profile; подсказка типа не стоит ввоза — так же, как у `state.интервью`
    # Чем этот обряд отличается от прочих. Подставляется в `начать` и дальше не меняется.
    род: "Род | None" = None
    # Исходная реплика человека, которой он описал занятие. У карточки пусто: там обряд
    # начинается с темы, а описания нет вовсе.
    описание: str = ""
    # Записи о человеке и уже заведённые профили на момент начала обряда. Снимаются один раз:
    # обряд идёт несколько ходов, и список, перечитанный на каждом шаге, менялся бы под
    # ответами архивариуса прямо посреди опроса.
    записи: list[str] = field(default_factory=list)
    доступные: list[str] = field(default_factory=list)
    # Тема, названная человеком в `/project new <название>`. Без неё модель спрашивает о том,
    # что придумает сама, — и у человека, считающего калории, спрашивает про стек.
    тема: str = ""
    # Заданный сейчас вопрос: их больше не список, они приходят по одному.
    вопрос: str = ""
    пары: list[tuple[str, str]] = field(default_factory=list)
    # Идёт запрос к модели: строка человека сейчас не ответ — отвечать ещё не на что.
    ждёт_модель: bool = True
    # Идёт ИМЕННО сборка карточки — последний запрос обряда. Отдельное поле, а не сравнение
    # чисел: «ждём следующий вопрос» и «ждём карточку» надо различать, потому что во втором
    # случае оплачены все обмены и ответы полны, и отменять там нечего, кроме потерь.
    собирает: bool = False


def идёт(state: State) -> bool:
    """Идёт ли интервью прямо сейчас. По нему общая развилка ввода решает, чья эта строка."""
    return state.интервью is not None


def начать(
    state: State,
    тема: str = "",
    *,
    род: Род | None = None,
    описание: str = "",
    записи: Sequence[str] = (),
    доступные: Sequence[str] = (),
) -> None:
    """Завести обряд: первый запрос уходит в фон, а команда возвращается сразу.

    Синхронна намеренно: команда не имеет права держать ввод, пока модель думает над первым
    вопросом. Сам обмен уезжает отдельной задачей.

    `род` решает, что за обряд идёт; умолчание — карточка папки, ради которой обряд и заведён.
    Записи о человеке и список заведённых профилей снимаются ОДИН раз, здесь: обряд идёт
    несколько ходов, и перечитывай мы их на каждом шаге, список менялся бы под ответами
    архивариуса прямо посреди опроса.
    """
    обряд = род or РОД_КАРТОЧКИ
    if идёт(state):
        # Когда идёт запрос к модели, заданного вопроса на экране нет, и советовать «ответьте
        # на заданный вопрос» значило бы послать человека искать то, чего не видно.
        идущий = state.интервью.род or РОД_КАРТОЧКИ
        ждёт = state.интервью.ждёт_модель
        _сказать(
            state,
            ui.hint_fragments(
                f"{идущий.имя} уже идёт — ждём ответа модели; прервать: {идущий.команда_отмены}"
                if ждёт
                else f"{идущий.имя} уже идёт — ответьте на заданный вопрос; прервать: {идущий.команда_отмены}"
            ),
        )
        return
    if state.client is None:
        # Обряд — это платные обмены, без ключа его начинать не с чем. Говорим до того, как
        # завели состояние: иначе инструмент принялся бы ловить ответы на вопросы, которых
        # никто не задавал.
        _сказать(state, ui.hint_fragments(f"{обряд.имя} спрашивает модель — сначала /auth"))
        return

    интервью = Интервью(
        каталог=Path.cwd(),
        профиль=state.profile,
        тема=" ".join(тема.split()),
        род=обряд,
        описание=описание.strip(),
        записи=list(записи),
        доступные=list(доступные),
    )
    if not обряд.подготовить(state, интервью):
        # Род сказал «не начинать» и сам объяснил человеку почему — например, файл карточки
        # лежит, но не читается. Узнать об этом после двух оплаченных запросов — худший из
        # возможных порядков. У мастера профиля такой заслон неполон: имени профиля до сборки
        # ещё не существует, и занятость имени выясняется только после обоих обменов.
        return
    state.интервью = интервью
    # Задача привязывается к жизни приложения тем же способом, что и короткие задачи Enter:
    # брошенную задачу сборщик мусора вправе прибрать посреди обмена, а при выходе её надо
    # снять и дождаться — иначе поверх прощального экрана вылезет «задача уничтожена, а она
    # ещё работала». Своей фоновой службы (`background.Служба`) обряд не заводит: её никто не
    # снимал бы при выходе, а трогать выход ради одного обряда незачем.
    workers.track_submission(state, asyncio.create_task(_шаг_опроса(state, интервью)))


async def принять_ответ(state: State, текст: str) -> None:
    """Строка человека как ответ на заданный вопрос.

    Зовётся общей развилкой ввода с ГЛАВНОГО экрана, когда `идёт` сказал «да» и строка не
    известная команда. «Известная», а не «начинается с косой черты», — потому что на вопрос
    «где что лежит?» человек отвечает `/opt/challenge`, и съеденный такой ответ ломал бы
    главный сценарий обряда на самом естественном месте.
    """
    интервью = state.интервью
    if интервью is None:
        return

    род = интервью.род or РОД_КАРТОЧКИ

    if интервью.ждёт_модель:
        # Вопроса на экране сейчас нет. Эта ветвь стоит ПЕРВОЙ, и порядок здесь важен: когда
        # идёт второй запрос, ответы человека уже полны и оплачены, и смена профиля их не
        # отменяет — знание о папке не зависит от того, кто о ней говорит. Поставь сверку
        # профиля выше, и карточка, за которую заплачено дважды, выбрасывалась бы ровно на
        # финишной прямой, а человеку предлагалось заплатить ещё дважды.
        _сказать(
            state,
            ui.hint_fragments(f"{род.имя} ждёт ответа модели — строка не принята, повторите её"),
        )
        return

    if state.switching_profile or интервью.профиль is not state.profile:
        # Собеседник, чьей инструкцией придуманы вопросы, уходит или уже ушёл, а вопросы ещё
        # не отвечены. Бросить состояние как есть нельзя вдвойне: интервью ело бы дальше
        # каждую строку человека, адресованную новому собеседнику, и тот молчал бы, а причины
        # не было бы видно.
        прибрать(state, интервью)
        # Строку человека отражаем в ленте: она набрана и отправлена, и пропасть бесследно
        # не имеет права — иначе человек не знает, дошла она или нет.
        _сказать(state, ui.user_fragments(текст))
        _сказать(
            state,
            ui.error_fragments(
                f"профиль сменился посреди обряда — строка не принята, {род.итог_не_записан}"
            ),
        )
        _сказать(state, ui.hint_fragments(f"начать заново: {род.команда_заново}"))
        return

    # Ответ печатаем сами: общая развилка ввода на этом пути молчит, и без строки в ленте
    # остались бы одни вопросы, без единого следа того, что человек на них сказал.
    _сказать(state, ui.user_fragments(текст))
    if текст.strip().casefold() in СЛОВА_ХВАТИТ:
        # Человек закончил опрос сам. Это его право: он видит, сколько уже рассказал, лучше
        # модели. Карточка собирается из того, что есть.
        if not интервью.пары and not интервью.описание:
            # Ответов нет, и собирать не из чего: у карточки содержание рождается только из
            # них. У мастера профиля есть описание человека — там «хватит» законно означает
            # «собери из того, что я уже написал».
            прибрать(state, интервью)
            _сказать(state, ui.system_fragments(f"{род.прерван} — {род.итог_не_записан}"))
            _сказать(
                state,
                ui.hint_fragments(
                    f"запрос на первый вопрос уже оплачен; начать заново: {род.команда_заново_с_доводом}"
                ),
            )
            return
        интервью.ждёт_модель = True
        await _второй_запрос(state, интервью)
        return
    интервью.пары.append((интервью.вопрос, текст))
    интервью.ждёт_модель = True
    # Следующий вопрос спрашиваем у модели, а не берём из списка: она видит все ответы разом
    # и решает, осталось ли что-то, без чего карточка будет хуже.
    await _шаг_опроса(state, интервью)


def отменить(state: State) -> bool:
    """Прервать идущее интервью по слову человека. `False` — прерывать было нечего.

    Явный выход нужен потому, что обряд растянут на несколько нажатий Enter, и передумавший
    человек иначе заперт: либо отвечай на оставшиеся вопросы, либо перезапускай инструмент.
    Уже оплаченный первый запрос при этом пропадает — и об этом говорится вслух.
    """
    интервью = state.интервью
    if интервью is None:
        return False
    род = интервью.род or РОД_КАРТОЧКИ
    if интервью.собирает:
        # Ответы уже ушли на сборку карточки: оплачены оба запроса, и карточка вот-вот ляжет
        # на диск. Отменить её здесь значило бы выбросить и деньги, и ответы человека за
        # секунду до готового итога — причём ради того, чтобы «прервать зависшее».
        _сказать(
            state,
            ui.hint_fragments(f"ответы уже ушли на сборку — дождитесь, {род.итог_вот_вот}"),
        )
        return True
    прибрать(state, интервью)
    _сказать(state, ui.system_fragments(f"{род.прерван} — {род.итог_не_записан}"))
    оплачено = "оба запроса уже оплачены" if интервью.пары else "запрос на вопросы уже оплачен"
    _сказать(state, ui.hint_fragments(f"{оплачено}; начать заново: {род.команда_заново}"))
    return True


async def _шаг_опроса(state: State, интервью: Интервью) -> None:
    """Один шаг опроса: спросить у модели следующий вопрос — или узнать, что хватит.

    Отдельной задачей, поэтому ловит всё: выпущенное отсюда исключение никому бы не досталось,
    а человек остался бы перед инструментом, который ест его строки и молчит.

    Опрос идёт ПО ОДНОМУ вопросу, и решает модель, а не число: она видит уже собранные ответы
    и останавливается, когда знает главное. Список вопросов, придуманный заранее, спрашивал бы
    о том, что человек уже сказал, — и не спрашивал бы о том, что открылось по ходу.
    """
    род = интервью.род or РОД_КАРТОЧКИ
    профиль_запроса, вход = род.шаг_запрос(интервью)
    try:
        текст, ошибка = await _обмен(state, профиль_запроса, вход, род.агент)
    except asyncio.CancelledError:
        # Отмену заказывает человек (выход из инструмента): состояние прибираем, а само
        # исключение отдаём наружу — глотать отмену нельзя.
        прибрать(state, интервью)
        raise
    except Exception as exc:
        _неудача(state, интервью, str(exc))
        return
    if текст is None:
        _неудача(state, интервью, ошибка)
        return
    if state.интервью is not интервью:
        # Пока шёл запрос, обряд бросили. Спрашивать некого.
        return
    try:
        вопрос = род.шаг_разбор(текст)
    except ValueError as exc:
        if интервью.пары:
            # Шаг не понят, но ответы человека уже собраны и оплачены. Выбросить их вместе с
            # обрядом значило бы наказать человека за сбой модели: идём собирать итог из
            # того, что есть, и говорим, что случилось.
            _сказать(
                state,
                ui.error_fragments(f"шаг опроса не понят ({exc}) — собираю из ответов"),
            )
            await _второй_запрос(state, интервью)
            return
        # Ответов ещё нет — собирать не из чего.
        _неудача(state, интервью, str(exc))
        return
    if вопрос is None:
        if not интервью.пары:
            # Модель говорит «хватит», не спросив ничего. У карточки собирать нечего: её
            # содержание рождается ТОЛЬКО из ответов. У мастера профиля есть описание,
            # написанное человеком, и по нему профиль собирается без единого вопроса.
            if not интервью.описание:
                _неудача(state, интервью, "модель не задала ни одного вопроса")
                return
        интервью.вопрос = ""
        await _второй_запрос(state, интервью)
        return
    интервью.вопрос = вопрос
    интервью.ждёт_модель = False
    if len(интервью.пары) == 0:
        _сказать(
            state,
            ui.hint_fragments(
                f"отвечайте строкой; «хватит» закончит опрос, {род.команда_отмены} — выйдет"
            ),
        )
    _задать_вопрос(state, интервью)


async def _второй_запрос(state: State, интервью: Интервью) -> None:
    """Собранное превращается в итог обряда: карточку папки либо профиль занятия."""
    род = интервью.род or РОД_КАРТОЧКИ
    интервью.собирает = True
    _сказать(state, ui.system_fragments(род.сборка_объявление))
    профиль_запроса, вход = род.итог_запрос(интервью)
    try:
        текст, ошибка = await _обмен(state, профиль_запроса, вход, род.агент)
    except asyncio.CancelledError:
        прибрать(state, интервью)
        raise
    except Exception as exc:
        _неудача(state, интервью, str(exc))
        return
    if текст is None:
        _неудача(state, интервью, ошибка)
        return
    if state.интервью is not интервью:
        # Обряд бросили, пока шёл запрос: писать итог из ответов, за которыми человек уже не
        # стоит, нельзя. Смена профиля сюда НЕ относится и итога не отменяет — ответы даны
        # человеком и полны, а знание о папке от персоны не зависит.
        return
    try:
        род.итог_записать(state, интервью, текст)
    except Exception as exc:  # noqa: BLE001 — см. ниже, ловим весь класс, а не один вид
        # Ловим НЕ ТОЛЬКО `ValueError` (непригодный ответ модели), и это решение оплачено:
        # `NameError` в записи профиля уходил в задачу `track_submission`, где исключение
        # снимается ради чистоты вывода. Человек получал за два оплаченных обмена ПУСТУЮ
        # ленту, а состояние обряда оставалось живым — инструмент молча ел каждую следующую
        # строку. Любая беда записи обязана стать видимой неудачей с прибранным состоянием.
        _неудача(state, интервью, str(exc) or exc.__class__.__name__)


async def _обмен(state: State, профиль: Any, вход: str, имя: str) -> tuple[str | None, str]:
    """Один платный обмен интервьюера. `(текст, "")` — удача, `(None, причина)` — нет.

    Агент одноразовый: памяти у интервьюера нет, каждый запрос самодостаточен. Расход его
    обмена уходит в копилку выбывших — интервьюер живёт вне панелей, а значит и вне обхода
    агентов сеанса, и без этой строки его деньги не попали бы в итог никогда.

    `retire` стоит в `finally`: обмен, оборвавшийся посередине, тоже мог быть оплачен, и
    тратить деньги человека молча нельзя ни на каком пути.
    """
    агент = Agent(имя, профиль)
    обмен = None
    try:
        обмен = await агент.exchange(state.client, state.model, вход, agent=имя)
    finally:
        state.retire([агент])
        # Деньги считаем ОТДЕЛЬНО от токенов: копилка выбывших несёт токены, а рубли
        # копятся по ходу и по тарифу той модели, которой обмен сделан. Интервью ходит
        # `state.model`, то есть возможно и дорогой моделью, и запускает его человек —
        # промолчать об этих деньгах значило бы показать `/tokens`, который врёт вниз.
        if обмен is not None:
            цена = output.turn_price(обмен)
            if цена is None:
                state.session_cost_known = False
            else:
                state.session_cost += цена
        else:
            # Обмен оборвался (выход из инструмента посреди обряда). Токены копилка выбывших
            # уже забрала, а цены у нас нет — и делать вид, что рублёвый итог точен, нельзя:
            # человек прочёл бы его как «вот столько потрачено», недосчитав этот запрос.
            state.session_cost_known = False
    if not обмен.ok:
        return None, обмен.error or "неизвестная причина"
    if обмен.finish_reason == "length":
        # Обрыв по длине — не «ответить нечего», а «мы не дали договорить»: оборванный JSON
        # не разбирается вовсе, и путать эти два случая нельзя.
        return None, "ответ оборван по длине"
    return обмен.text, ""


def _задать_вопрос(state: State, интервью: Интервью) -> None:
    """Очередной вопрос в ленту. Номер виден, чтобы человек знал, сколько осталось."""
    номер = len(интервью.пары) + 1
    вопрос = интервью.вопрос
    # Вопрос — своей строкой и своим видом: он ждёт ответа прямо сейчас, и в ленте, где всё
    # прочее серое и служебное, его надо отличать от отчётов инструмента с одного взгляда.
    _сказать(state, ui.question_fragments(номер, вопрос))


def _неудача(state: State, интервью: Интервью, причина: str) -> None:
    """Интервью сорвалось. Карточка не пишется, а о потраченных деньгах говорится вслух.

    Говорим и тогда, когда интервью уже бросили: запрос оплачен независимо от того, ждёт ли
    ещё кто-то его ответа, и молча съесть деньги человека нельзя.
    """
    род = интервью.род or РОД_КАРТОЧКИ
    прибрать(state, интервью)
    _сказать(state, ui.error_fragments(f"{род.не_удался}: {причина}"))
    _сказать(state, ui.hint_fragments(род.подсказка_после_неудачи))


def прибрать(state: State, интервью: Интервью) -> None:
    """Убрать состояние, если оно всё ещё наше.

    Сверка по тождеству обязательна: обнули мы поле вслепую, сорвавшееся интервью отменило бы
    заодно то, которое человек успел начать заново.
    """
    if state.интервью is интервью:
        state.интервью = None


def _сказать(state: State, fragments: list[tuple[str, str]]) -> None:
    """Строка в главный экран. Показ ленты обновляет сам `append_log`."""
    output.append_log(state, fragments, state.main)


# --- Род карточки папки: обряд, ради которого весь этот ход и заведён ---------------------


def _подготовить_карточку(state: State, интервью: Интервью) -> bool:
    """Что сказать и что проверить до первого платного запроса карточки."""
    прежняя, жалобы = project_card.load(интервью.каталог)
    if прежняя is None and жалобы:
        # Файл лежит, но карточкой не читается. Записать поверх него `create` откажется, и
        # узнать об этом после двух оплаченных запросов — худший из возможных порядков.
        for жалоба in жалобы:
            _сказать(state, ui.error_fragments(жалоба))
        _сказать(
            state,
            ui.hint_fragments(
                "поправьте файл руками или уберите его — интервью не начинаю, "
                "чтобы не платить за два запроса впустую"
            ),
        )
        return False
    if прежняя is not None:
        _сказать(
            state,
            ui.system_fragments(
                f"карточка папки {интервью.каталог.name} уже есть — интервью заменит её; "
                "раздел «Ограничения» при этом сохранится"
            ),
        )
    _сказать(
        state,
        ui.system_fragments(
            f"интервью о папке {интервью.каталог.name}"
            + (f", тема: {интервью.тема}" if интервью.тема else "")
            + " — спрашиваю у модели, с чего начать"
        ),
    )
    return True


def _шаг_запрос_карточки(интервью: Интервью) -> tuple[Any, str]:
    return project_card.questions_profile(), project_card.questions_request(
        интервью.профиль.system, интервью.каталог.name, интервью.тема, интервью.пары
    )


def _итог_запрос_карточки(интервью: Интервью) -> tuple[Any, str]:
    return project_card.card_profile(), project_card.card_request(интервью.пары, интервью.тема)


def _записать_карточку(state: State, интервью: Интервью, текст: str) -> None:
    """Ответ модели — в разделы, разделы — в файл карточки, файл — на экран."""
    разделы, отброшенные = project_card.parse_card(текст)
    # Формальные придирки называем вслух, но карточку из-за них не выбрасываем: обе они —
    # признаки, а не приговор («разделов мало», «похоже на пересказ»), судить о содержании
    # по смыслу программа не может. Решает человек, глядя на карточку, — а чтобы глядеть,
    # она должна быть записана и показана.
    for имя in отброшенные:
        # Молча выбросить раздел нельзя: в нём строка, за которую заплачен обмен, и человек
        # должен знать, что её нет и где её место.
        _сказать(
            state,
            ui.hint_fragments(
                f"раздел «{имя}» отброшен — имена, начинающиеся с «Ограничен», пишете только вы: "
                "/project Ограничения: <текст>"
            ),
        )
    for жалоба in project_card.проверить_карточку(разделы):
        _сказать(state, ui.error_fragments(f"карточка вышла сомнительной: {жалоба}"))

    прежняя_карточка = project_card.load(интервью.каталог)[0]
    # Копию кладёт `create`, и кладёт не всегда: карточку, писанную моделью, он поверх
    # человеческой копии не пишет. Поэтому запоминаем не «прежняя была», а время файла копии
    # — по нему видно, обновилась она этой заменой или лежит прежняя, постарше.
    копия = project_card.прежний_путь(интервью.каталог)
    копия_до = копия.stat().st_mtime if копия.exists() else None
    карточка, сообщение = project_card.create(интервью.каталог, разделы, источник=ИСТОЧНИК)
    прибрать(state, интервью)
    if карточка is None:
        _сказать(state, ui.error_fragments(f"карточка не записана: {сообщение}"))
        return
    # Карточка уедет в системную часть следующего запроса и утяжелит его. Полоска занятости
    # узнать об этом сама не может: карточка лежит на диске, а её отпечаток видит только
    # память и профиль.
    забыть_счёт_занятости(state)
    _сказать(state, ui.system_fragments(f"карточка проекта «{сообщение}» записана интервью"))
    _сказать(state, ui.card_fragments(карточка))
    if прежняя_карточка is not None and копия.exists():
        # Интервью заменяет карточку целиком, и прежняя могла быть лучше новой — особенно
        # когда придирки выше уже напечатаны. Путь к копии называем всегда, но говорим правду
        # о том, что в ней: заменилась она этой заменой или там лежит карточка постарше.
        обновилась = копия_до is None or копия.stat().st_mtime > копия_до
        _сказать(
            state,
            ui.hint_fragments(
                f"прежняя карточка сохранена рядом: {копия} — если новая вышла хуже, верните её оттуда руками"
                if обновилась
                else f"рядом лежит копия ПОСТАРШЕ — заменённую карточку писала модель, и копией её не заменяли: {копия}"
            ),
        )
    _сказать(
        state,
        ui.hint_fragments(
            "раздел «Ограничения» интервью не заполняет вовсе: по этим строкам программа "
            "будет судить ответы модели, а правило, сочинённое самой моделью, проверкой не "
            "является — впишите его сами: /project Ограничения: <текст>"
        ),
    )


