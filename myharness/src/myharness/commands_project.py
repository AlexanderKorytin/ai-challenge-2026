"""Команда `/project` — карточка проекта: показать, дописать, завести интервью.

Карточка принадлежит папке, а не персоне: две персоны в одной папке видят одну карточку, и
это решение, а не упущение. Устройство взято с образца, который у нас перед глазами: файл
соглашений в корне репозитория отдельно, память о человеке отдельно.

Раздел «Ограничения» правит только человек — команда передаёт это хранилищу источником.
Причина узкая: по этим строкам программа однажды начнёт судить ответы модели на нарушение,
и правило, сочинённое самой моделью, проверкой не является.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

from . import project_card, ui
from .conversation import забыть_счёт_занятости
from .output import append_log
from .commands_task import номер_строки as _номер
from .state import State

# Слова команды — здесь, в самой команде, и отсюда же их берёт подсказка. Держи их копией в
# подсказках — и переименование слова здесь оставило бы подсказку врать, а проверку зелёной.
СЛОВО_NEW = "new"
СЛОВО_ОТМЕНА = "отмена"
СЛОВО_ЗАБЫТЬ = "забыть"
СЛОВА_КОМАНДЫ: tuple[str, ...] = (СЛОВО_NEW, СЛОВО_ОТМЕНА, СЛОВО_ЗАБЫТЬ)
# Чем человек называет всю карточку, когда просит убрать её целиком.
ВСЯ_КАРТОЧКА: tuple[str, ...] = ("карточку", "карточка", "всё", "все")

ПОДСКАЗКА = (
    "/project — показать карточку; /project new <тема> — завести интервью; /project отмена — "
    "прервать идущее; /project <раздел> <текст> — дописать; /project забыть <раздел> <номер> "
    "— убрать строку; /project забыть карточку — убрать целиком. Раздел называете вы сами, "
    "имя отделяется двоеточием — например: "
    + ", ".join(f"{имя}:" for имя in project_card.РАЗДЕЛЫ_ПОДСКАЗКА)
)


def cmd_project(state: State, arg: str) -> None:
    """`/project` без довода — показать карточку; `new` — интервью; иначе — дописать раздел."""
    каталог = Path.cwd()
    текст = arg.strip()

    if not текст:
        карточка, жалобы = project_card.load(каталог)
        for предупреждение in жалобы:
            append_log(state, ui.error_fragments(предупреждение))
        if карточка is None:
            if жалобы:
                # Файл лежит, но карточкой не читается. Советовать `/project new` тут нельзя:
                # он откажется затирать этот файл, и совет заведомо упёрся бы в отказ.
                append_log(
                    state,
                    ui.hint_fragments("поправьте файл руками или уберите его — затирать его я не буду"),
                )
                return
            append_log(
                state,
                ui.hint_fragments(
                    f"у папки {каталог.name} карточки нет — /project new заведёт её интервью"
                ),
            )
            return
        append_log(state, ui.card_fragments(карточка))
        return

    части = текст.split(maxsplit=1)
    if части[0].lower() == СЛОВО_ОТМЕНА and len(части) == 1:
        from . import interview

        if not interview.отменить(state):
            append_log(state, ui.hint_fragments("интервью сейчас не идёт — отменять нечего"))
        return
    if части[0].lower() == СЛОВО_ЗАБЫТЬ:
        _забыть(state, каталог, части[1].strip() if len(части) > 1 else "")
        return
    if части[0].lower() == СЛОВО_NEW:
        # Поздний ввоз: интервью тянет за собой агента и клиент, а показ карточки — нет.
        from . import interview

        # Название — это ТЕМА папки, и она уходит модели первым же словом. Без неё вопросы
        # придумываются из воздуха: у человека, который считает калории, спрашивают про стек.
        тема = части[1] if len(части) > 1 else ""
        if not тема.strip():
            append_log(
                state,
                ui.hint_fragments(
                    "назовите тему — по ней модель и будет спрашивать: /project new похудение"
                ),
            )
            return
        interview.начать(state, тема)
        return

    # Имя раздела человек придумывает сам, и оно бывает из нескольких слов. Где оно кончается,
    # программа знать не может — отсюда двоеточие как явный разделитель (см. `_разделить`).
    карточка, жалобы = project_card.load(каталог)
    имя, остаток = _разделить(текст, карточка)
    if имя is None:
        # Отказ у разбора один: имя не нашлось. Второй способ отказать — по длине имени —
        # был снят вместе с пределом, и развилка «своя причина или общая» ушла за ним: мёртвая
        # ветвь читается как отказ, которого не бывает.
        append_log(
            state,
            ui.error_fragments(
                f"не понял, где имя раздела в «{текст}» — отделите его двоеточием: "
                "/project Режим: три приёма пищи"
            ),
        )
        append_log(state, ui.hint_fragments(ПОДСКАЗКА))
        return
    if not остаток:
        append_log(state, ui.hint_fragments(f"нужен текст: /project {имя} <строка>"))
        return

    if карточка is None and жалобы:
        # Жалобу печатаем ОДИН раз: `create` вернёт её же, и повтор той же строки читается
        # как две разные беды.
        for предупреждение in жалобы:
            append_log(state, ui.error_fragments(предупреждение))
        append_log(
            state,
            ui.hint_fragments("поправьте файл руками или уберите его — затирать его я не буду"),
        )
        return
    if карточка is None:
        # Первая строка заводит карточку: требовать интервью ради одной строки значило бы
        # платить за два запроса там, где человек уже знает, что хочет записать.
        карточка, сообщение = project_card.create(каталог, {имя: [остаток]}, источник="человек")
        if карточка is None:
            append_log(state, ui.error_fragments(сообщение))
            return
        забыть_счёт_занятости(state)
        append_log(
            state,
            ui.system_fragments(f"карточка проекта заведена; {имя}: «{остаток}» — {_отмена(имя, 1)}"),
        )
        return

    # Новый раздел или знакомый — решаем ДО записи: после неё он в карточке в любом случае.
    # Новость это разная, и человек пролистывает вторую не глядя; раздел-опечатку он обязан
    # заметить с первого взгляда, иначе показ вместо снятого предела ничего не стоит.
    новый = имя not in карточка.разделы
    записано, сообщение = project_card.add_line(карточка, имя, остаток, источник="человек")
    if not записано:
        append_log(state, ui.error_fragments(сообщение))
        return
    забыть_счёт_занятости(state)
    начало = f"новый раздел «{имя}»" if новый else имя
    append_log(
        state,
        ui.system_fragments(
            f"{начало}: «{сообщение}» — {_отмена(имя, len(карточка.пункты(имя)))}"
        ),
    )


def _отмена(имя: str, номер: int) -> str:
    """Чем убрать только что записанную строку.

    Хвост этот — не вежливость, а замена снятому пределу на длину имени раздела. Потолок
    держал командный путь от строки, где двоеточие стоит не разделителем («я хочу записать вот
    что: строку»); сняли его в обмен на «показали, что завелось, и назвали, чем отменить» — и
    обещание это обязан давать тот самый путь, а не соседний.

    Имя печатается КАК ЕСТЬ, не строчными: строчное имя слитно с текстом через двоеточие
    читается эхом набранного, а не заголовком раздела, — и раздел-предложение в ленте
    неотличим от дописывания в знакомый раздел.
    """
    return f"убрать: /project забыть {имя} {номер}"


def _разделить(текст: str, карточка: Any) -> tuple[str | None, str]:
    """Отделяет имя раздела от текста строки. Не разобрали — `(None, "")`.

    Правил два, и порядок между ними важнее их самих.

    1. **Двоеточие, за которым пробел или конец строки** — явный разделитель:
       `/project Режим сна: восемь часов`. Требование пробела само отсекает `8:00` и
       `http://a.b`, поэтому текст с двоеточием внутри не рвётся.
    2. **Совпадение с разделом, который в карточке уже есть** — так человек дописывает в
       знакомый раздел, не ставя разделителя: `/project Режим три приёма`. Самое длинное
       совпадение, иначе «Где» перебило бы «Где что лежит».

    Явное правило идёт ПЕРВЫМ. Обратный порядок я уже пробовал: он ломает противоположный
    случай — новый раздел, чьё имя начинается с имени существующего, завести нельзя вовсе, и
    `/project Режим сна: восемь часов` молча уходит в «Режим» строкой «сна: восемь часов».
    Молча — это здесь главное слово: ни отказа, ни предупреждения, только два двоеточия в
    отчёте.
    """
    строка = текст.strip()
    for место, знак in enumerate(строка):
        if знак != ":":
            continue
        хвост = строка[место + 1 :]
        if хвост and not хвост[0].isspace():
            continue
        имя = project_card.привести_имя(строка[:место])
        if not имя:
            return None, ""
        # Длину имени не меряем: человек поставил двоеточие, то есть сказал границу явно, и
        # спорить с ним числом слов не о чем. Ошибся — увидит в ленте, какой раздел завёлся, и
        # уберёт его `/project забыть`.
        return имя, хвост.strip()
    if карточка is not None:
        слова = строка.split()
        # Перебираем ВСЕ длины, от самой длинной к короткой: разделы карточки называет человек,
        # и потолка на число слов у них нет. Самое длинное совпадение первым — иначе «Где»
        # перебило бы «Где что лежит».
        for длина in range(len(слова), 0, -1):
            имя = project_card.нормализовать_раздел(" ".join(слова[:длина]), карточка)
            if имя in карточка.разделы:
                return имя, " ".join(слова[длина:]).strip()
    return None, ""


def _забыть(state: State, каталог: Path, остаток: str) -> None:
    """`/project забыть <раздел> <номер>` и `/project забыть карточку`.

    Удаление карточки целиком — отдельное слово, а не пустой довод: пустой довод здесь значил
    бы «убрать всё», и одна лишняя клавиша стирала бы работу интервью.
    """
    if not остаток:
        append_log(
            state,
            ui.hint_fragments(
                "нужен раздел и номер строки: /project забыть Цель 2; убрать целиком: /project забыть карточку"
            ),
        )
        return
    if остаток.casefold() in ВСЯ_КАРТОЧКА:
        # Печатаем карточку ДО удаления — вторая сеть под копией и первая защита от опечатки:
        # человек видит, что именно исчезает, ровно как при закрытии задачи.
        прежняя, _ = project_card.load(каталог)
        if прежняя is not None:
            append_log(state, ui.card_fragments(прежняя))
        убрана, сообщение, (путь_копии, копия_постарше) = project_card.remove_card(каталог)
        if not убрана:
            append_log(state, ui.error_fragments(сообщение))
            return
        забыть_счёт_занятости(state)
        append_log(state, ui.system_fragments(сообщение))
        if путь_копии is not None:
            append_log(
                state,
                ui.hint_fragments(
                    f"рядом лежит копия ПОСТАРШЕ — эту карточку копией не заменяли: {путь_копии}"
                    if копия_постарше
                    else f"копия лежит рядом: {путь_копии}"
                ),
            )
        return

    куски = остаток.rsplit(maxsplit=1)
    номер = _номер(куски[1]) if len(куски) == 2 else None
    if номер is None:
        append_log(
            state,
            ui.hint_fragments("нужен раздел и номер строки: /project забыть Цель 2 (номера показывает /project)"),
        )
        return
    карточка, жалобы = project_card.load(каталог)
    for предупреждение in жалобы:
        append_log(state, ui.error_fragments(предупреждение))
    if карточка is None:
        append_log(
            state,
            ui.error_fragments(
                "поправьте файл руками или уберите его — затирать его я не буду"
                if жалобы
                else "карточки у этой папки нет — удалять нечего"
            ),
        )
        return
    убрана, сообщение = project_card.remove_line(карточка, куски[0], номер, источник="человек")
    if not убрана:
        append_log(state, ui.error_fragments(сообщение))
        return
    забыть_счёт_занятости(state)
    append_log(state, ui.system_fragments(f"убрано из карточки: {сообщение}"))
