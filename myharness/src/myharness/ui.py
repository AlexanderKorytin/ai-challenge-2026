def _plural(count: int, one: str, few: str, many: str) -> str:
    """Русское склонение по числу: 1 пара, 2 пары, 5 пар.

    Строка о восстановлении разговора встречает человека при каждом запуске, и «3 пар»
    в ней читается как недоделка инструмента."""
    if count % 10 == 1 and count % 100 != 11:
        return one
    if 2 <= count % 10 <= 4 and not 12 <= count % 100 <= 14:
        return few
    return many


def _clock(ts: str) -> str:
    """Часы и минуты отметки времени по местным часам человека — пустая строка, если
    отметки нет или она нечитаема.

    В файле время лежит в UTC (иначе переезд между поясами перепутал бы порядок записей),
    а человек сверяет его со своими часами на стене."""
    try:
        return datetime.fromisoformat(ts).astimezone().strftime("%H:%M")
    except (TypeError, ValueError):
        return ""


def restored_fragments(
    loaded: int,
    saved: int,
    last_ts: str,
    *,
    за_выжимкой: int = 0,
    забыто_дословно: int = 0,
    снято_пунктов: int = 0,
) -> Fragments:
    """Строка о поднятом разговоре: сколько пар в памяти, сколько их в файле, что за выжимкой.

    Первые числа названы по той же причине, по которой называется число выброшенных обрезкой:
    молча подставленный прошлый разговор человек отлаживает как «модель отвечает не на то»,
    а разницу между «помню три пары» и «в файле их двенадцать» иначе взять неоткуда.

    Строка ОДНА, и выжимка не заводит себе второй. Отчёт о восстановлении читают один раз, в
    первую секунду запуска, и разбитый на три строки он читается как три разных события,
    хотя событие одно: вот столько разговора у модели есть, вот столько — в пересказе, вот
    столько нет нигде. Отсюда и порядок чисел: сперва то, что помнится дословно, потом то,
    что помнится пересказом, потом потери.

    `забыто_дословно` и `снято_пунктов` называются рядом с парами за выжимкой намеренно:
    «за выжимкой 8 пар» без них обещает пересказ всего ушедшего разговора, а часть его не
    лежит нигде. Снятые пункты считаются ПУНКТАМИ, а не парами: пункт парам не сопоставлен.

    Сами реплики и текст выжимки в ленту не печатаются — решение пользователя: экран остаётся
    чистым, память при этом полная. Прочесть выжимку целиком можно `/context`, и здесь же
    названа эта команда: другого места, где человек узнал бы о ней вовремя, нет."""
    пары = _plural(loaded, "пара", "пары", "пар")
    сохранено = _plural(saved, "сохранённой", "сохранённых", "сохранённых")
    текст = f"восстановлен разговор: {loaded} {пары} из {saved} {сохранено}"
    часы = _clock(last_ts)
    if часы:
        текст += f", последняя {часы}"
    if за_выжимкой > 0:
        текст += f", за выжимкой {за_выжимкой} {_plural(за_выжимкой, 'пара', 'пары', 'пар')}"
        оговорки = []
        if забыто_дословно > 0:
            забыта = _plural(забыто_дословно, "забыта", "забыты", "забыты")
            оговорки.append(f"из них {забыто_дословно} {забыта} дословно")
        if снято_пунктов > 0:
            оговорки.append(f"при переполнении снято пунктов: {снято_пунктов}")
        if оговорки:
            текст += " (" + "; ".join(оговорки) + ")"
        текст += " — выжимка целиком: /context"
    return system_fragments(текст)


def trimmed_fragments(выброшено: int, *, сжатие: bool) -> Fragments:
    """Строка об обрезке памяти: сколько пар ушло из неё ДОСЛОВНО, без пересказа.

    Одна формулировка на два случая, и различаются они хвостом. Сжатие выключено — пары
    просто выброшены, и добавить нечего. Сжатие включено — значит, их обязана была подобрать
    выжимка, и не подобрала: хвост «выжимка не поспела» отвечает на вопрос, который иначе
    человек задаёт себе сам («у меня же включено сжатие, почему забыли?»).

    От строки о сжатии (`compacted_fragments`) отделена намеренно, и это требование, а не
    вкус: замена дословного текста пересказом и потеря без пересказа — два разных исхода с
    разной ценой. После замены содержание разговора у модели есть, после потери его нет
    нигде. По этой паре строк человек и решает, звать ли `/compact` руками."""
    пар = _plural(выброшено, "пара", "пары", "пар")
    выброшена = _plural(выброшено, "выброшена", "выброшено", "выброшено")
    текст = f"память обрезана: {выброшена} {выброшено} {пар} «вопрос — ответ»"
    if сжатие:
        текст += " — забыты дословно, выжимка не поспела"
    return system_fragments(текст)


def compacted_fragments(заменено: int, пройдено: int) -> Fragments:
    """Строка о сжатии: сколько пар заменено пересказом и сколько пройдено разговором.

    Числа именно эти два, и второе — не сумма первых. `пройдено` считает всё, что ушло из
    памяти за жизнь разговора: и пересказанное, и забытое дословно. Назови мы вместо него
    «столько-то пар за пересказом» — человек считал бы, что в выжимке лежит весь ушедший
    разговор, а часть его не лежит нигде.

    Самого пересказа в ленте нет намеренно: выжимка — тысячи знаков, и лента после первого
    же сжатия стала бы нечитаемой. Прочесть её целиком можно командой `/context`. То же
    решение, по которому не печатаются восстановленные с диска реплики."""
    заменена = _plural(заменено, "пара заменена", "пары заменены", "пар заменены")
    пар = _plural(пройдено, "пара", "пары", "пар")
    return system_fragments(
        f"память сжата: {заменено} {заменена} пересказом — разговором пройдено {пройдено} {пар}"
    )


