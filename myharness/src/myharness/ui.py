def meta_fragments(
    finish_reason: str | None,
    usage: dict[str, Any],
    profile: str,
    cost: str | None = None,
) -> Fragments:
    """Строка под ответом: чем кончилось, что пришло из кэша, во что обошлось, каким профилем.

    Ни токенов, ни времени здесь НЕТ, и это не упущение. И то и другое стоит строкой выше —
    в замершей строке ожидания, за которой человек следил глазами весь обмен. Повтори их
    тут — и рядом оказались бы два набора чисел об одном и том же; читающий стал бы искать,
    чем они отличаются, хотя не отличаются они ничем. Правило одно на оба числа: половина
    правила («токены убрали, время оставили») хуже, чем никакого, — по ней не догадаешься,
    чему эта строка вообще посвящена.

    Попадания в кэш названы отдельно, потому что это единственное число, объясняющее цену:
    вход из кэша дешевле промаха в тридцать раз, и обмен на одинаковый вход может стоить и
    доллар, и три цента. Когда попаданий нет, о них молчим: «из кэша 0» занимает место и не
    сообщает ничего.

    Деньги приходят готовой строкой, а не числом: считает их `tokens`, и он же знает, что
    сказать при незнакомом тарифе. Посчитай их здесь — вторая формула цены разошлась бы с
    первой на первой же правке тарифа.
    """
    parts: list[str] = []
    if finish_reason:
        parts.append(FINISH_REASONS.get(finish_reason, finish_reason))
    cache_hits = usage.get("prompt_cache_hit_tokens") if isinstance(usage, dict) else None
    # `bool` отсеиваем наравне с нечислами: `usage` приходит от сервера, а True напечаталось
    # бы как «из кэша 1» — правдоподобное число, которого не было.
    if isinstance(cache_hits, int) and not isinstance(cache_hits, bool) and cache_hits > 0:
        parts.append(f"из кэша {format_exact(cache_hits)}")
    if cost:
        parts.append(cost)
    parts.append(f"профиль: {profile}")
    style = "class:meta.warn" if finish_reason == "length" else "class:meta"
    return [(style, "· " + "  ·  ".join(parts)), ("", "\n")]


def params_fragments(profile_name: str, values: dict[str, Any], system: str | None) -> Fragments:
    out: Fragments = [("class:system", f"· параметры профиля «{profile_name}»"), ("", "\n")]
    for name in params_mod.ORDER:
        spec = params_mod.SPECS[name]
        value = values.get(name)
        shown = params_mod.format_value(value)
        out.append(("", f"  {spec.title:<22} "))
        out.append(("class:model" if value is not None else "class:dim", shown))
        reason = params_mod.inapplicable_reason(name, values)
        if reason and value is not None:
            out.append(("class:hint", f"   ← {reason}"))
        out.append(("", "\n"))
    if system:
        first_line = system.strip().splitlines()[0]
        preview = first_line[:60] + ("…" if len(first_line) > 60 else "")
        out.append(("", "  системная инструкция  "))
        out.append(("class:model", preview))
        out.append(("", "\n"))
    else:
        out.append(("", "  системная инструкция  "))
        out.append(("class:dim", "не задана"))
        out.append(("", "\n"))
    out.append(("class:dim", "  изменить: /set <параметр>\n"))
    return out


def profile_list_fragments(items: list[tuple[str, Any]], active: str) -> Fragments:
    out: Fragments = [("class:system", "· профили генерации"), ("", "\n")]
    for name, source in items:
        mark = "●" if name == active else "○"
        out.append(("", f"  {mark} {name}"))
        if source is not None:
            out.append(("class:dim", f"   {source}"))
        else:
            out.append(("class:dim", "   встроенный"))
        out.append(("", "\n"))
    out.append(("class:dim", "  переключить: /profile <имя> · сохранить текущий: /profile save <имя>\n"))
    return out


def _percent(part: int, whole: int) -> str:
    """Доля в процентах для снимка расхода. Дно у неё то же, что у цены в `format_price`:
    «0.0 %» на месте настоящей доли читается как «ничего не занято», а занято может быть уже
    несколько тысяч токенов — просто окно у модели в миллион."""
    if whole <= 0:
        return "—"
    доля = part / whole * 100
    if 0 < доля < 0.1:
        return "< 0.1 %"
    return f"{доля:.1f} %"


def tokens_report_fragments(
    model: str,
    *,
    history: int,
    pairs: int,
    overhead: int,
    system: int,
    restored: int,
    runs: int,
    usage: dict[str, Any],
    budget: int,
    cost: str,
) -> Fragments:
    """Снимок расхода по `/tokens`: что уйдёт в следующий запрос и во что обошёлся сеанс.

    Две половины снимка отвечают на разные вопросы, и смешивать их нельзя. Первая — про
    БУДУЩЕЕ: сколько весит разговор, который уедет в модель следующим запросом, и близко ли
    дно окна. Вторая — про ПРОШЛОЕ: сколько обменов уже сделано и сколько за них заплачено.
    Человек зовёт команду ради одного из двух, и строка, отвечающая сразу на оба, не отвечает
    ни на один.

    Занятое окно берём вместе с надбавкой обёртки, а строкой ниже вес истории — без неё.
    Разница между числами не описка: в окно уходит весь запрос целиком, а решение «пора ли
    звать /clear» принимается по весу того, что агент помнит, — обёртку `/clear` не уберёт.

    Поднятые с диска пары названы отдельной строкой и только когда они есть. Иначе расход
    выглядит необъяснимым: обменов ноль, денег потрачено ноль, а первый же запрос уходит
    тяжёлым — потому что разговор поднят из прошлого запуска и оплачен будет сейчас.

    Деньги приходят готовой строкой — по той же причине, что и в `meta_fragments`: считает
    их `tokens`, он же знает, что сказать при незнакомом тарифе. Вторая формула цены
    разошлась бы с первой на первой же правке тарифа.
    """
    # Системная инструкция — часть каждого запроса, и молчать о ней нельзя: профиль дня
    # кладёт в неё документ на миллион токенов, и снимок, считающий одну лишь память, показал
    # бы «занято 1 354» там, где занят почти весь контекст. Замечено на живом прогоне.
    занято = system + history + overhead
    пар_истории = _plural(pairs, "паре", "парах", "парах")
    обменов = _plural(runs, "обмен", "обмена", "обменов")
    # Строки собираем в переменные, а не прямо во фрагментах: там пропущенная запятая
    # склеила бы соседние куски в одну строку молча, и подпись стиля уехала бы на строку ниже.
    окно = (
        f"· окно «{model}»: {format_exact(tokens_mod.CONTEXT_WINDOW)}, "
        f"следующий запрос займёт {format_exact(занято)} ({_percent(занято, tokens_mod.CONTEXT_WINDOW)})"
    )
    out: Fragments = [
        ("class:system", окно),
        ("", "\n"),
        (
            "class:dim",
            f"  история: {format_exact(history)} в {pairs} {пар_истории} — этот вес уйдёт в следующий запрос\n",
        ),
    ]
    if system:
        # Инструкцию называем отдельной строкой, а не прячем в «занято»: человек должен видеть,
        # что бóльшую часть окна съедает не его разговор, а документ, положенный профилем, —
        # и что /clear эту часть не уберёт.
        out.append(
            (
                "class:dim",
                f"  системная инструкция: {format_exact(system)} — уходит в каждый запрос, "
                "/clear её не трогает\n",
            )
        )
    if restored:
        поднято = _plural(restored, "пара", "пары", "пар")
        out.append(
            (
                "class:dim",
                f"  с диска поднято {restored} {поднято} — в итог сеанса не входят, в запрос — да\n",
            )
        )
    вход = format_exact(int(usage.get("prompt_tokens") or 0))
    выход = format_exact(int(usage.get("completion_tokens") or 0))
    рассуждения = format_exact(int(usage.get("reasoning_tokens") or 0))
    сеанс = (
        f"  сеанс: {runs} {обменов}, вход {вход}, выход {выход} "
        f"(из них рассуждения {рассуждения}), {cost}\n"
    )
    out.append(("class:dim", сеанс))
    if budget > 0:
        out.append(("class:dim", f"  предел веса запроса: {format_exact(budget)} (/budget 0 — снять)\n"))
    else:
        out.append(("class:dim", "  предел веса запроса не задан (/budget <токены> — задать)\n"))
    if not tokens_mod.exact():
        # Приблизительны ровно два верхних числа: их считаем мы сами. Расход сеанса назвал
        # сервер, и валить его в ту же оговорку значило бы наводить тень на точные числа.
        out.append(
            ("class:dim", "  словаря нет: вес истории и занятое окно — оценка, расход сеанса точен\n")
        )
    return out


# ──────────────────── полоска занятости контекста над строкой ввода ────────────────────

# Ниже этой ширины окна полоска не рисуется вовсе. Три десятка знаков на всю шкалу дают шаг
# в три процента: полоска врёт больше, чем сообщает. Подпись при этом остаётся — в узком
# окне она и точнее, и полезнее, потому что называет и ограничитель, и его числа.
ПОЛОСКА_МИН_ШИРИНА = 40
# Длиннее этого шкалу не тянем, сколько бы места ни было. Знак шкалы на широком окне стоит
# полпроцента, а точности это не прибавляет: доля всё равно предсказание, а не замер. Зато
# полоска во всю ширину монитора читается как аварийная надпись, чем она не является.
ПОЛОСКА_МАКС_ШИРИНА = 60
# Где стоит тонкая отметка: доля ближайшего ограничителя, при которой заводится фоновая
# заготовка выжимки. Число берётся ЗДЕСЬ и там из одного места по смыслу: покажи полоска
# одно, а заведись заготовка по другому — отметка стояла бы не там, где что-то происходит.
ОТМЕТКА_ЗАГОТОВКИ = 0.8
ЗНАК_ЗАПОЛНЕНИЯ = "▓"
ЗНАК_ЖЁЛОБА = "░"
ЗНАК_ОТМЕТКИ = "┊"


def _склонение_единиц(count: int, единицы: str) -> str:
    """Единицы ограничителя, склонённые по числу: «2 пары», «5 токенов».

    Поле `единицы` у ограничителя лежит в одной форме («пар», «токенов») — она годится для
    подписи «9 из 15 пар», но не для «сверх порога на 1 пару»."""
    if единицы == "пар":
        return _plural(count, "пара", "пары", "пар")
    return _plural(count, "токен", "токена", "токенов")


def _числа_ограничителя(ограничитель: Any) -> str:
    """Числа ближайшего ограничителя для подписи — свои у каждого рода.

    Единицы не приводятся к общей мерке намеренно: пересчитать пары в токены можно, а
    обратно нельзя, и «9 из 15» человеку понятнее любой пересчитанной доли.

    Форма «СКОЛЬКО ЕСТЬ из СКОЛЬКИХ СРАБОТАЕТ» — одна на все ограничители, и это не
    единообразие ради единообразия. Первая сборка называла у порога сжатия сам порог и окно
    модели («5 242 из 1 048 576 токенов»), и рядом с «9 из 15» это читалось одинаково, а
    значило противоположное: в одном месте первое число — набранное, в другом — то, куда
    идём. Человек прочёл бы «набрано пять тысяч из миллиона» и решил, что до сжатия далеко,
    ровно когда до него один ход.

    Окно модели у порога сжатия называется, но ОТДЕЛЬНО и в скобках: порог задан долей окна,
    то есть числом, которого человек не видел нигде, и без окна непонятно, откуда он взялся.
    У предела веса окна нет: предел человек задал сам командой `/budget`, объяснять его
    происхождение нечем."""
    if ограничитель.имя == agent_mod.ПОРОГ_СЖАТИЯ:
        доля_окна = ограничитель.порог / tokens_mod.CONTEXT_WINDOW * 100
        return (
            f"{format_exact(ограничитель.текущее)} из {format_exact(ограничитель.порог)} токенов"
            f" ({доля_окна:.2f} % окна модели)".replace(".", ",")
        )
    if ограничитель.имя == agent_mod.ПРЕДЕЛ_ВЕСА:
        return f"{format_exact(ограничитель.текущее)} из {format_exact(ограничитель.порог)} токенов"
    return f"{ограничитель.текущее} из {ограничитель.порог}"


def _подпись_занятости(ограничитель: Any) -> str:
    """Строка под полоской: доля до срабатывания, имя ближайшего ограничителя и его числа.

    Имя в подписи — не украшение. Доля без имени отвечает «сколько-то процентов чего-то»:
    62 % до окна по парам и 62 % до порога веса — разные события в разные моменты, а на одном
    разговоре ближайший ограничитель меняется по ходу дела.

    Доля отсекается вниз, а не округляется: округлённые 99.6 % показали бы «100 % до сжатия»
    там, где сжатие ещё не сработало, — то есть соврали бы ровно про то событие, ради
    которого полоска и заведена.

    Перебор говорится отдельным числом, а не долей: доля выше единицы не поднимается (иначе
    полоску пришлось бы рисовать длиннее жёлоба), и «на сколько ушли сверх» ей не сказать."""
    if ограничитель.перебор > 0:
        начало = (
            f"сверх порога на {format_exact(ограничитель.перебор)} "
            f"{_склонение_единиц(ограничитель.перебор, ограничитель.единицы)}"
        )
    else:
        начало = f"{int(ограничитель.доля * 100)} % до сжатия"
    return f"{начало} · {ограничитель.имя}, {_числа_ограничителя(ограничитель)}"


def _полоска(доля: float, ширина: int) -> Fragments:
    """Сама шкала: заполнение, жёлоб и тонкая отметка на восьми десятых.

    Знаки собираются по одному, а соседние одного стиля склеиваются: отметка стоит посреди
    шкалы и режет её на куски в произвольном месте, а раскладывать три случая («отметка
    внутри заполнения», «на границе», «в жёлобе») руками — три места, где можно ошибиться
    ровно на один знак."""
    заполнено = min(ширина, int(доля * ширина))
    отметка = min(ширина - 1, int(ОТМЕТКА_ЗАГОТОВКИ * ширина))
    куски: Fragments = []
    for место in range(ширина):
        if место == отметка:
            стиль, знак = "class:gauge.mark", ЗНАК_ОТМЕТКИ
        elif место < заполнено:
            стиль, знак = "class:gauge.fill", ЗНАК_ЗАПОЛНЕНИЯ
        else:
            стиль, знак = "class:gauge.trough", ЗНАК_ЖЁЛОБА
        if куски and куски[-1][0] == стиль:
            куски[-1] = (стиль, куски[-1][1] + знак)
        else:
            куски.append((стиль, знак))
    return куски


def context_bar_fragments(ограничитель: Any, width: int) -> Fragments:
    """Полоска занятости целиком: шкала и подпись под ней. Пустой список — полоски нет.

    Правый край шкалы — ближайший ДЕЙСТВУЮЩИЙ ограничитель, а не окно модели и не порог
    сжатия. Порог при умолчании равен восьми десятым окна, то есть сотням тысяч токенов, а
    обычный разговор весит тысячи: полоска, привязанная к нему, стояла бы пустой всегда и не
    отвечала бы ни на один вопрос. Ближайший ограничитель — это то, что вот-вот случится.

    Ограничитель приходит готовым, а не считается здесь: считает его `СчётЗанятости`, который
    помнит постоянную часть веса. Отрисовка зовётся на каждое нажатие клавиши, и полезь она
    за весом сама — набор текста упёрся бы в счёт токенов по всей памяти разговора.

    Высота — две строки, и в узком окне остаётся одна: подпись. Отступ от строки ввода задаёт
    раскладка, а не эта сборка: пустая строка внутри фрагментов уехала бы вместе с полоской
    туда, куда её поставят."""
    if ограничитель is None:
        return []
    подпись: Fragments = [("class:gauge.label", _подпись_занятости(ограничитель)), ("", "\n")]
    if width < ПОЛОСКА_МИН_ШИРИНА:
        return подпись
    return [*_полоска(ограничитель.доля, min(width, ПОЛОСКА_МАКС_ШИРИНА)), ("", "\n"), *подпись]


class СчётЗанятости:
    """Ближайший ограничитель для полоски — с запомненной постоянной частью веса.

    Заведён ради одного требования: полоска пересчитывается на КАЖДОЕ нажатие клавиши, а
    постоянная часть веса (инструкция, блок фактов, блок выжимки, память) — на каждое
    изменение памяти. Считай мы всё заново между двумя буквами, ввод на длинном разговоре
    заметно отставал бы от клавиатуры — та самая беда, из-за которой счёт токенов уже
    запоминается.

    Блок фактов счёт читает САМ и держит при себе. Источник фактов ходит на диск, и это
    единственная причина, по которой у класса вообще есть состояние: читай его отрисовка
    напрямую, каждая набранная буква оборачивалась бы обходом каталога памяти с чтением
    файлов. По той же причине `system_text()` агента здесь не зовётся ни разу.
    """

    def __init__(self, факты: Callable[[], list[str]] | None = None) -> None:
        self._факты = факты
        self._блок_фактов = ""
        self._основа: list[Any] | None = None
        self._отметка: tuple | None = None

    def сбросить(self) -> None:
        """Забыть запомненное: следующий вопрос пересчитает постоянную часть с нуля.

        Зовётся там, где изменилось то, чего в отметке нет и быть не может, — глобальные
        факты (`/remember`, `/forget`, находка архивариуса) и очистка разговора. Отметка
        ловит память и профиль; факты живут на диске, и сторожить их опросом значило бы
        ходить на диск ровно затем, чтобы узнать, что ходить было незачем."""
        self._основа = None
        self._отметка = None

    def _отпечаток(self, агент: Any, model: str) -> tuple:
        """По чему видно, что постоянная часть веса изменилась.

        Числа здесь только дешёвые: ни одного прохода словарём токенов. `history()` отдаёт
        копию списка — это десятки словарей, а не тысячи, и цена копии несравнима с ценой
        токенизации всей памяти. Длина памяти обязательна: без неё `/clear` на разговоре, где
        обрезка ещё ни разу не срабатывала, оставил бы полоску показывать стёртые пары.

        Поколение выжимки, а не сама выжимка: пересжатие меняет блок в системной части, и
        полоска обязана после него упасть — в этом её смысл."""
        выжимка = агент.выжимка()
        профиль = агент.profile
        return (
            id(агент),
            len(агент.history()),
            агент.runs,
            агент.passed_pairs,
            выжимка.поколение if выжимка is not None else -1,
            профиль.system,
            профиль.keep_history,
            профиль.history_window,
            профиль.budget_tokens,
            профиль.compact_at,
            model,
        )

    def _прочесть_факты(self) -> str:
        """Блок глобальных фактов — тот же, что уходит в системную часть запроса.

        Ошибку источника глотаем: это полоска, а не отправка. Уронить показ занятости из-за
        попорченного файла памяти значило бы обменять подсказку на потерю всего интерфейса."""
        if self._факты is None:
            return ""
        try:
            return memory_mod.facts_block(self._факты())
        except Exception:  # noqa: BLE001 — источник фактов приходит снаружи
            return ""

    def ближайший(self, агент: Any, набранное: str = "", *, model: str = "") -> Any:
        """Ограничитель, по которому рисуется полоска. `None` — полоски нет вовсе.

        Полоски нет при выключенном сжатии, и это не следствие, а решение: она заведена как
        счёт до сжатия, и без сжатия мерила бы дорогу к обычному забыванию, о котором и так
        говорит строка в ленте. Цена решения названа честно: человек, выключивший
        `compact_at`, теряет вместе со сжатием и предупреждение о близкой потере пар.

        Пока ближайшим стоит окно по числу пар, набранный текст не взвешивается вовсе —
        считать нечего: вопрос ещё не стал парой и на заполнение не влияет. Это же и самый
        частый случай на коротком разговоре, то есть самый частый набор текста.

        Вес набранного ПРИБАВЛЯЕТСЯ к постоянной части, а не пересчитывается вместе с ней:
        вес запроса складывается из веса реплик поштучно, и добавка нового вопроса от памяти
        не зависит. Приблизительности здесь нет — это то же число, что дал бы полный пересчёт.
        """
        if агент is None or агент.profile.compact_at <= 0:
            return None
        отметка = self._отпечаток(агент, model)
        if self._основа is None or отметка != self._отметка:
            self._блок_фактов = self._прочесть_факты()
            # Пустой вопрос намеренно: постоянная часть — это вес запроса БЕЗ набранного
            # текста, и добавка считается отдельно на каждое нажатие.
            self._основа = агент.ограничители("", facts=self._блок_фактов, model=model)
            self._отметка = отметка
        if not self._основа:
            return None
        ближайший = max(self._основа, key=lambda ограничитель: ограничитель.доля)
        if not набранное or ближайший.имя == agent_mod.ОКНО_ПО_ПАРАМ:
            return ближайший
        добавка = tokens_mod.count_text(набранное)
        с_вопросом = [
            replace(ограничитель, текущее=ограничитель.текущее + добавка)
            if ограничитель.единицы == "токенов"
            else ограничитель
            for ограничитель in self._основа
        ]
        # Тот же выбор, что у заготовки выжимки: наибольшая доля, а при равных — тот, кто
        # режет раньше (порядок списка — порядок обрезки). Разойдись эти двое в правиле, и
        # отметка на восьми десятых стояла бы не там, где заводится заготовка.
        return max(с_вопросом, key=lambda ограничитель: ограничитель.доля)


def system_prompt_fragments(profile_name: str, system: str | None) -> Fragments:
    if not system:
        return system_fragments(f"в профиле «{profile_name}» системная инструкция не задана")
    out: Fragments = [("class:system", f"· системная инструкция профиля «{profile_name}»"), ("", "\n")]
    for line in system.splitlines():
        out.append(("class:dim", f"  {line}\n"))
    return out


