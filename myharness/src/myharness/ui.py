def _row_click(on_click: Callable[[int], None], index: int) -> Callable[[MouseEvent], Any]:
    def handler(mouse_event: MouseEvent) -> Any:
        if mouse_event.event_type == MouseEventType.MOUSE_UP:
            on_click(index)
            return None
        return NotImplemented  # прочие события мыши пусть обрабатывает prompt_toolkit

    return handler


# Сколько строк списка показываем разом. Набор из двух групп поднимает полтора десятка
# агентов, и список во весь их рост съел бы пол-экрана — того самого, ради которого агентов и
# поднимали. Двенадцать строк умещаются даже в невысокое окно, а остальные показывает окно
# прокрутки: строка, на которой стоит пользователь, видна всегда.
PANEL_ROWS_MAX = 12

# Подсказка над списком агентов набирается из частей по ширине окна. Одной строкой её
# держать нельзя: строка не переносится (`wrap_lines=False`), и всё, что не влезло, окно
# срезало бы справа — посреди слова, без всякого признака, что там что-то было.
#
# Порядок частей — от менее угадываемого к более угадываемому: отбрасываем с конца, и
# уходить первым должно то, что человек попробует сам. Щелчок по строке пробуют все,
# переход на экран по номеру угадывается по номерам на вкладках, а про Ctrl+R не
# догадается никто — он и стоит выше, среди тех, что показываются даже в узком окне.
PANEL_HINT_PARTS = (
    "Shift+←/→ — экран",
    "Alt+←/→ — панель",
    "↑/↓ — агент",
    "Ctrl+R — размышления",
    "Alt+N — экран по номеру",
    "клик — перейти",
)


def panel_hint(width: int) -> str:
    """Подсказка ровно по ширине окна: части складываются, пока помещаются.

    Первую часть отдаём даже когда и она не влезает: обрезанная подсказка всё же говорит,
    что клавиши тут есть, а пустая строка над списком не говорит ничего и только съедает
    высоту. Один знак ширины оставлен под отбивку слева, с которой строку и печатают."""
    hint = PANEL_HINT_PARTS[0]
    for part in PANEL_HINT_PARTS[1:]:
        longer = f"{hint} · {part}"
        if len(longer) + 1 > width:
            break
        hint = longer
    return hint


def panel_slice(count: int, active: int, limit: int = PANEL_ROWS_MAX) -> tuple[int, int]:
    """Какой отрезок списка показать. Окно ведём за выбранной строкой, а не за началом списка:
    закрашенный кружок означает «вы здесь», и спрятать его значило бы соврать."""
    if count <= limit:
        return 0, count
    start = max(0, min(active - limit // 2, count - limit))
    return start, start + limit


def _clip(text: str, width: int) -> str:
    """Обрезать до ширины колонки. Многоточие ставим вместо последнего знака, а не после него:
    иначе строка вылезает за ширину и переносится, ломая сетку списка."""
    if width <= 0:
        return ""
    if len(text) <= width:
        return text
    return text[: width - 1] + "…" if width > 1 else "…"


def agent_panel_fragments(
    rows: list[tuple[str, str, str, int, int, int]],
    active: int,
    width: int,
    on_click: Callable[[int], None],
) -> Fragments:
    """Список агентов под строкой ввода: строка на агента, главный разговор первой строкой.

    На вход — (состояние, имя, занятие, миллисекунды, токены, число обменов) по строке на
    агента, номер строки, на которой стоит пользователь, ширина окна и переход по номеру.

    Кружок слева говорит, на кого мы смотрим сейчас, а не что с агентом происходит:
    состояние несут цвет имени и колонка занятия. Двух разных смыслов на один значок не
    вешаем — список читают мельком.

    Время и расход прижаты к правому краю: сравнивать их глазом можно только когда числа
    стоят друг под другом. Каждая строка добивается пробелами до полной ширины, потому что
    обработчик щелчка висит на самой строке — попасть мышью надо в строку, а не в буквы.

    Расход помечен знаком «Σ» и набран тем же стилем, что итог в строке ожидания: знаки на
    экране означают одно и то же везде, иначе их приходится каждый раз перечитывать.
    """
    start, end = panel_slice(len(rows), active)
    shown = rows[start:end]
    name_width = min(max((len(name) for _, name, _, _, _, _ in shown), default=0), 22)
    meta_width = 9 + 2 + 8  # время, отбивка, токены
    task_width = max(8, width - 3 - name_width - 2 - meta_width - 1)

    out: Fragments = [("class:agents.hint", " " + panel_hint(width)), ("", "\n")]
    if start:
        out += [("class:agents", f" ↑ выше ещё {start}"), ("", "\n")]
    for offset, (status, name, task, total_ms, total_tokens, runs) in enumerate(shown):
        index = start + offset
        current = index == active
        handler = _row_click(on_click, index)
        _, mark_style = STATUS_MARKS.get(status, STATUS_MARKS[screens_mod.IDLE])
        elapsed = format_duration(total_ms) if runs else "—"
        line: Fragments = [
            (mark_style, " ● " if current else " ○ "),
            ("class:agents.name.active" if current else "class:agents.name", _clip(name, name_width).ljust(name_width)),
            ("class:agents", "  "),
            (mark_style if status in (screens_mod.BUSY, screens_mod.ERROR) else "class:agents",
             _clip(task, task_width).ljust(task_width)),
        ]
        if runs:
            # Знак итога, а не входящих: в колонке стоит ВЕСЬ расход агента — вход, выход и
            # размышления вместе. Стрелка «↓» тут означала бы «столько пришло от модели», и
            # число, прочитанное по такой пометке, оказалось бы втрое больше правды. Пометка,
            # врущая про смысл числа, дороже неверного числа: неверное число видно, а из-за
            # неверной пометки перестают верить и всем остальным числам на экране.
            #
            # Столбцов «↑» и «↓» в списке нет намеренно. Список отвечает на один вопрос —
            # кто из агентов дороже, — и для него хватает одного столбца. Три столбца съели
            # бы колонку занятия, а её и читают чаще всего. Разбивка живёт там, где ей место:
            # в замерших строках самого агента и в отчёте `/tokens`.
            число = format_tokens(total_tokens)
            # Отступ отдаём приглушённому фрагменту, а само число — стилю итога: тот же приём,
            # что и в строке ожидания, чтобы во фрагменте числа лежало только число.
            отступ = " " * max(0, 8 - 2 - len(число))
            line.append(("class:agents.meta", f"{elapsed:>9}  {отступ}Σ "))
            line.append(("class:tokens.sum", число))
        else:
            line.append(("class:agents.meta", f"{elapsed:>9}  {'—':>8}"))
        used = sum(len(text) for _, text in line)
        line.append(("class:agents", " " * max(0, width - used)))
        out += [(style, text, handler) for style, text in line]
        out.append(("", "\n"))
    if end < len(rows):
        out += [("class:agents", f" ↓ ниже ещё {len(rows) - end}"), ("", "\n")]
    return out


def pane_title_fragments(title: str, status: str, active: bool) -> Fragments:
    """Заголовок панели: чьи это ответы и что с ними сейчас. Активная панель подсвечена —
    её прокручивают и разворачивают."""
    mark, _ = STATUS_MARKS.get(status, STATUS_MARKS[screens_mod.IDLE])
    style = "class:pane.title.active" if active else "class:pane.title"
    return [(style, f" {'▸ ' if active else ''}{title} {mark}")]


# Слово к значку состояния. Значок один в один тот же, что на вкладках (`STATUS_MARKS`), —
# иначе в двух местах экрана одно и то же состояние выглядело бы по-разному. Слово рядом
# нужно потому, что список читают, когда что-то пошло не так, и гадать по одному значку в
# такой момент — лишняя работа.
AGENT_STATE_WORDS: dict[str, str] = {
    screens_mod.IDLE: "ждёт",
    screens_mod.BUSY: "занят",
    screens_mod.DONE: "готов",
    screens_mod.ERROR: "ошибка",
}


def agent_occupation(status: str, task: str, profile_name: str) -> str:
    """Чем агент занят — вторая колонка списка агентов.

    Пока агент работает, показываем начало его вопроса: список читают именно затем, чтобы
    понять, кто над чем сидит. Освободился — показываем имя профиля: вопрос уже отвечен, и
    держать его в строке значит выдавать прошлое за настоящее. Оборвался — говорим об этом
    словом, а не одним значком: искать глазами цвет в такой момент лишняя работа.

    Вопрос сворачиваем до первой строки: многострочный вопрос разорвал бы сетку списка.
    """
    if status == screens_mod.BUSY:
        first = next((line for line in task.strip().splitlines() if line.strip()), "")
        return first.strip() or profile_name
    if status == screens_mod.ERROR:
        return f"{AGENT_STATE_WORDS[screens_mod.ERROR]} · {profile_name}"
    return profile_name


def format_duration(ms: int) -> str:
    """Время работы по-человечески: до минуты — секундами, дальше — минутами и секундами.

    «382.4 с» формально верно и нечитаемо: чтобы понять, много это или мало, приходится
    делить в уме. Доли секунды после минуты не нужны — на таком масштабе они ничего не решают.

    Округляем ДО сравнения с минутой, а не после. Иначе 59.98 с проходит проверку «меньше
    шестидесяти», а печатается как «60.0 с» — время, которого не бывает: шестьдесят секунд
    называются минутой. Ошибка живёт ровно две сотых секунды в час и потому не ловится
    глазами вовсе."""
    seconds = round(ms / 1000, 1)
    if seconds < 60:
        return f"{seconds:.1f} с"
    return f"{int(seconds) // 60} м {int(seconds) % 60} с"


def format_tokens(count: int) -> str:
    """Расход токенов: до тысячи — как есть, дальше «92.4k», от миллиона «1.2M».

    Считать нули в «92417» глазом невозможно, а в списке важен порядок величины: кто из
    агентов съел заметно больше остальных. Ступень на миллионе заведена по той же причине,
    по какой и первая: «1204.0k» возвращает читателя к счёту нулей, ради ухода от которого
    сокращение и придумано, а миллион токенов за день разговора набирается легко."""
    if count < 1000:
        return str(count)
    if count < 1_000_000:
        return f"{count / 1000:.1f}k"
    return f"{count / 1_000_000:.1f}M"


# Чем кончилось ожидание. Знаков ровно три, и выбирает их вызывающая сторона: строка
# ожидания не знает и не должна знать, отменил человек запрос сам или оборвалась сеть.
WAIT_MARKS = {"ok": "✓", "error": "✗", "cancelled": "⊘"}

# Слово, которым живая строка говорит о себе в настоящем времени. Вынесено в имя, потому что
# в замершем виде на его месте остаётся ровно столько же пробелов: длина берётся отсюда и
# разъехаться с самим словом уже не может.
WAITING_WORD = "думаю… "

# Ширины колонок строки ожидания. Замершие строки остаются в ленте одна под другой, и по
# столбцу чисел человек читает рост расхода за весь диалог. Пока колонки гуляют, столбец
# читается как каша; выровненный — сам становится таблицей роста.
#
# Это МИНИМАЛЬНАЯ ширина, а не максимальная: число, не влезшее в колонку, расширяет её, но
# не обрезается никогда. Обрезанное число расхода — не число, а обманка: «1 234…» человек
# прочтёт как тысячу с небольшим, хотя там миллион, и на этом примет решение о бюджете.
# Кривая на одну строку колонка — цена, которую за честность платить не жалко.
COLUMN_ELAPSED = 8  # влезает и «59.9 с», и «1 м 1 с»
COLUMN_OUT = 10  # влезает «1 000 000» и с тильдой приблизительного счёта
COLUMN_IN = 7
COLUMN_SESSION = 8


def _column_pad(value: str, width: int) -> str:
    """Пробелы слева, прижимающие значение к правому краю колонки.

    Отступ отдаётся приглушённому фрагменту-разделителю, а не фрагменту с числом: так во
    фрагменте числа лежит только само число. Тому, кто станет это число подсвечивать или
    читать, не придётся сначала обстригать пробелы.
    """
    return " " * max(0, width - len(value))


def waiting_fragments(
    mark: str,
    elapsed: float,
    outgoing: int,
    incoming: int,
    session: int,
    *,
    exact: bool = True,
    frozen: bool = False,
) -> Fragments:
    """Строка под вопросом, пока идёт обмен, и она же — замершая — после его конца.

    Живая: `⠹ думаю… 3.2 с   ↑ 1 247   ↓ 83   Σ 12.4k`. Замершая: то же самое, но вместо
    кадра вращения знак исхода и без слова «думаю…» — работа кончилась, и говорить о ней в
    настоящем времени было бы неправдой.

    Поля постоянной ширины, числа прижаты к правому краю своей колонки. Замершие строки
    остаются в ленте одна под другой, и человек читает по ним рост расхода за диалог —
    столбец с гуляющими колонками для этого не годится. Колонка задаёт минимум: число шире
    колонки её расширяет, но не обрезается (см. `_column_pad`).

    Два числа обмена показаны до единицы, а итог сеанса — сокращением, и это не небрежность.
    Расход обмена сверяют с окном модели и с бюджетом, там важна единица; у итога сеанса
    важен порядок величины, и считать в нём нули глазами человек всё равно не станет.

    Строка одна и та же в обоих видах нарочно: человек следит за растущими числами глазами,
    и если бы после ответа они прыгнули на другое место экрана, сравнить «сколько было в
    середине» с «сколько вышло всего» стало бы невозможно.

    Отсюда же главное свойство списка: **число фрагментов не зависит ни от исхода, ни от
    точности счёта**. Замершая строка встаёт на место живой заменой среза в ленте вывода, и
    срез задан номерами фрагментов — разъедься длина, и весь напечатанный ниже вывод поехал
    бы вслед за ней. Поэтому слово «думаю…» в замершем виде не выбрасывается из списка, а
    заменяется таким же числом пробелов. Пустая строка на его месте была бы короче на семь
    знакомест — и все три числа прыгнули бы влево ровно в тот миг, когда человек их читает.
    Пробелы держат и место в срезе, и колонку на экране; заодно в списке не остаётся
    фрагментов нулевой длины, которые обход по знакам вправе выбросить.

    Знак `~` перед исходящим числом означает, что счёт приблизительный (словаря нет, считаем
    по знакам). Ставится он внутрь того же фрагмента, что и само число: отдельным фрагментом
    он снова менял бы длину списка. Врать точностью тут нельзя — по этому числу человек
    решает, не пора ли обрывать затянувшийся запрос.
    """
    время = format_duration(round(elapsed * 1000))
    исходящие = ("" if exact else "~") + format_exact(outgoing)
    входящие = format_exact(incoming)
    итог = format_tokens(session)
    return [
        ("class:dim", f"{mark} "),
        ("class:dim", " " * len(WAITING_WORD) if frozen else WAITING_WORD),
        ("class:dim", f"{_column_pad(время, COLUMN_ELAPSED)}{время}   ↑ {_column_pad(исходящие, COLUMN_OUT)}"),
        ("class:tokens.out", исходящие),
        ("class:dim", f"   ↓ {_column_pad(входящие, COLUMN_IN)}"),
        ("class:tokens.in", входящие),
        ("class:dim", f"   Σ {_column_pad(итог, COLUMN_SESSION)}"),
        ("class:tokens.sum", итог),
        ("", "\n"),
    ]


def reasoning_head_fragments(tokens: int | None, seconds: float | None) -> Fragments:
    """Заголовок свёрнутых размышлений: `▸ размышления · 180 токенов · 4.1 с`.

    Свёрнуты они потому, что черновик модели длиннее ответа в разы и вытеснил бы с экрана
    сам ответ. Но молча прятать то, за что человек заплатил, нельзя — заголовок называет
    цену черновика числом и говорит, чем его развернуть.

    Названо то, что известно, а не «всё или ничего»: токены и время приходят из разных мест
    и не обязаны появляться разом. Умолчи мы о числе, потому что рядом не хватает секунд, —
    законченные размышления выглядели бы незаконченными, а человек не увидел бы цены, которую
    уже заплатил. Короткий вид остаётся только на случай, когда не известно ничего.

    Длина списка фрагментов одна во всех видах, и строка ровно одна — по той же причине, что
    и у строки ожидания: готовый заголовок встаёт на место идущего заменой среза в ленте
    вывода. Многоточие короткого вида вынесено во второй фрагмент нарочно — иначе тот остался
    бы пустым, а фрагмент нулевой длины обход по знакам вправе выбросить.
    """
    части: list[str] = []
    if tokens is not None:
        части.append(f"{tokens} {_plural(tokens, 'токен', 'токена', 'токенов')}")
    if seconds is not None:
        части.append(format_duration(round(seconds * 1000)))
    if части:
        заголовок = "▸ размышления · " + " · ".join(части)
        подсказка = "   Ctrl+R — развернуть"
    else:
        заголовок = "▸ размышления"
        подсказка = "…"
    return [
        (screens_mod.REASONING_HEAD, заголовок),
        (screens_mod.REASONING_HEAD, подсказка),
        ("", "\n"),
    ]


# Разделитель разрядов: неразрывный пробел (U+00A0). Вынесен в имя, потому что знак невидим
# в исходном тексте, и любая уборка пробелов молча превратила бы его в обычный.
NBSP = "\u00a0"


def format_exact(count: int) -> str:
    """Точное число с разделением разрядов узким неразрывным пробелом: «1 247».

    Пара к `format_tokens` и её противоположность по назначению. Расход одного обмена
    сверяют с окном модели и с остатком бюджета, а для такой сверки «1.2k» бесполезно:
    разница между 1200 и 1299 решает, влезет следующий вопрос в окно или нет. Округлять то,
    ради чего инструмент и считает токены, нельзя.

    Разделитель — неразрывный пробел (`NBSP` выше), а не обычный: обычный дал бы терминалу
    право перенести строку посреди числа, и «1 247» на узком окне разъехалось бы на два
    разных числа. Узкий неразрывный (U+202F) читался бы теснее и был бы красивее, но часть
    терминальных шрифтов рисует его нулевой ширины — число слипается в «1247», и разделение
    пропадает вовсе. Ширина важнее красоты.
    """
    return f"{count:,}".replace(",", NBSP)


