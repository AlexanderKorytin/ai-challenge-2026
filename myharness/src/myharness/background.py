"""Скелет фоновой служебной работы: заход, который идёт сам по себе и никем не ожидается.

Таких служб в инструменте уже не одна: архивариус вычитывает из разговора факты о человеке,
сжиматель ужимает разросшуюся историю выжимкой. Смысл у них разный, и сливать их нельзя — а
скелет один и тот же, и он состоит из правил, каждое из которых закрывает свою беду:

— «заход уже идёт — второго не заводить»: два одинаковых захода прочтут один и тот же кусок
  разговора, сделают одну и ту же работу и заплатят за неё дважды;
— «о сбое сказать один раз за сеанс»: причина сбоя обычно постоянная (нет сети, нет денег на
  счёте), а заходов за сеанс много, и повторяющаяся строка вытеснила бы из ленты сами ответы;
— «отдельная задача, которую никто не ждёт»: служебная работа не имеет права задерживать ни
  ответ модели, ни ввод следующего вопроса.

Скопировать этот скелет второй раз значило бы завести два места, которые молча разойдутся:
поправят одно, забудут другое, и одна служба станет вести себя не как другая без всякой на то
причины. Поэтому он живёт здесь, а службы держат при себе только то, что у них правда своё.

Про `cli` модуль не знает и знать не должен: он ниже всех — его зовут службы, а состояние
сеанса остаётся их заботой.
"""

from __future__ import annotations

import asyncio
from collections.abc import Coroutine
from dataclasses import dataclass
from typing import Any

# Сколько отказов ПОДРЯД служба имеет право получить, прежде чем её выключат до конца сеанса.
# Смысл предела не в экономии, а в достоинстве: если служба не работает, честнее сказать об
# этом один раз и замолчать, чем ходить к модели впустую весь сеанс.
ПРЕДЕЛ_ОТКАЗОВ = 3


@dataclass
class Служба:
    """Состояние одной фоновой службы: идущий заход и её счёт отказов.

    Держим саму задачу, а не признак «идёт»: по задаче видно и что заход ещё не кончился
    (второго заводить нельзя), и что его есть чего дождаться при выходе, — признак же
    рассказал бы только первое.
    """

    имя: str  # «архивариус», «сжиматель» — этим же именем служба зовётся в ленте
    задача: asyncio.Task | None = None
    предупреждён: bool = False  # о сбое говорим не больше раза за сеанс
    # Отказы считаются ПОДРЯД, а не всего за сеанс: три разрозненных сбоя за долгий рабочий
    # день — это работающая служба и три неудачных минуты, и выключать её за это неправильно.
    отказов_подряд: int = 0
    выключена: bool = False  # предел отказов исчерпан — до конца сеанса не пытаемся


def идёт(служба: Служба) -> bool:
    """Идёт ли заход прямо сейчас.

    По этому и решается, заводить ли второй: положить заход поверх идущего значило бы
    потерять ссылку на первый — дождаться его при выходе стало бы нечем.
    """
    return служба.задача is not None and not служба.задача.done()


def завести(служба: Служба, сопрограмма: Coroutine[Any, Any, Any]) -> None:
    """Завести фоновый заход отдельной задачей.

    Задача НИКЕМ не ожидается намеренно: служебная работа не имеет права задержать ни ответ
    модели, ни ввод следующего вопроса. Ссылку на неё мы всё же держим в поле — брошенную
    задачу сборщик мусора вправе прибрать посреди работы, да и дождаться её при выходе иначе
    было бы нечем.
    """
    служба.задача = asyncio.create_task(сопрограмма)


def отказ(служба: Служба) -> bool:
    """Отметить неудачный заход. `True` — предел исчерпан, служба выключена до конца сеанса.

    Отказ — это «заход не дал результата», а НЕ «сеть не ответила». Граница проходит по концу
    захода целиком, вместе с применением итога: удался обмен с моделью, а записать его итог не
    вышло (нет прав на каталог, полон диск) — это отказ. Иначе счёт лгал бы самым обидным
    образом: служба, у которой ломается только применение итога, чередовала бы «успех» и
    «отказ», предела не достигала бы никогда и весь сеанс платила бы за запросы впустую.
    Отсюда правило для вызывающих: `успех` зовётся в самом конце удачного пути захода, а не
    сразу после ответа модели.

    Возвращаемое значение — не отчёт, а поручение: вызывающий по нему печатает человеку одну
    строку о том, что служба замолчала. Молча выключаться нельзя — человек считал бы, что
    служба работает, а она стоит. Поэтому `True` отдаётся РОВНО ОДИН раз — на переходе через
    предел: отдавай мы его и на каждом следующем отказе, честный вызывающий печатал бы ту же
    строку снова и снова, то есть ровно ту беду, от которой скелет и защищает правилом «о
    сбое раз за сеанс».

    Отмена (`asyncio.CancelledError`) отказом НЕ считается и сюда не приходит: отмену
    заказывает сам человек (Ctrl+C, очистка разговора), и считать её отказом значило бы дать
    ему выключить себе службу, ничего об этом не узнав. Само исключение отмены службы обязаны
    пробрасывать наружу, а не глотать вместе с прочими.
    """
    if служба.выключена:
        # Выключенную службу считать дальше незачем, а сказать о ней второй раз — вредно.
        return False
    служба.отказов_подряд += 1
    if служба.отказов_подряд >= ПРЕДЕЛ_ОТКАЗОВ:
        служба.выключена = True
        return True
    return False


def успех(служба: Служба) -> None:
    """Отметить удачный заход: счёт отказов подряд обнуляется.

    Зовётся в САМОМ КОНЦЕ удачного пути захода — после того, как итог применён, — а не сразу
    после ответа модели: удачным считается доведённый до конца заход, и никакой другой
    (почему именно так — в пояснении к `отказ`).

    Без этого обнуления «подряд» превратилось бы в «всего», и служба выключалась бы после трёх
    разрозненных сбоев за долгий сеанс, проработав между ними сотню удачных заходов.
    """
    служба.отказов_подряд = 0


def отменить(служба: Служба) -> None:
    """Снять идущий заход и забыть о нём.

    Нужна там, где почва из-под захода уходит: разговор очистили, а заход был заведён над
    прежним — применять его итог уже нельзя. Поле обнуляется здесь же: отменённая задача
    висела бы в состоянии, и `идёт` о ней говорил бы правду, а вот дожидаться её при выходе
    было бы незачем.

    Чего эта отмена НЕ обещает — и на что поэтому нельзя опираться. `cancel` доставляет отмену
    только на ближайшем ожидании: пока заход идёт по участку без `await` (у архивариуса это
    цикл записи фактов, где ожиданий нет вовсе), он доработает участок до конца — уже после
    того, как `идёт` начал говорить `False` и вызывающий вправе завести второй заход. Ждать
    отмену здесь нельзя: очистка разговора обязана быть немедленной, а не «через запрос к
    модели». Значит, применение итога защищается не отменой, а сверкой на стороне вызывающего:
    у сжимателя это поколение памяти, которое растёт при очистке разговора, — заход со старым
    поколением свой итог просто не применяет.
    """
    if служба.задача is not None:
        служба.задача.cancel()
    служба.задача = None
