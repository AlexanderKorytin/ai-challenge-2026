"""Архивариус: отдельный агент, который вычитывает из разговора факты о человеке.

Второй слой памяти — глобальный: он про пользователя, а не про папку, и живёт в
`memory.facts_dir()`. Руками его пополняет команда `/remember`, а сам собой — этот агент.

Почему отдельный агент, а не инструмент у главного. Запись факта — это не «модель сама
пишет файл», а «модель называет факт, программа его записывает». Отдельный дешёвый запрос с
`response_format: json_object` даёт то же поведение без цикла вызовов инструментов, без
разрешений на запись файлов и без переделки сердцевины агента. Когда инструменты появятся,
архивариус заменяется самозаписью агента **без изменения формата хранилища**.

Почему раз в пять обменов, а не на каждом. Факт редко лежит в одной паре: «меня зовут
Александр» плюс «я из Kotlin-мира» плюс «люблю синий» — три реплики, и по одной паре за раз
архивариус видит обрывки. Читая накопленный кусок разом, он видит их вместе: реже — не
только дешевле, но и точнее. Названная цена: при `kill -9` последние до пяти обменов в
глобальную память не попадут. Сам разговор при этом цел — он пишется сразу и дословно.

Про `cli` модуль не знает — знать ему нужно только состояние, которое ему передали. Тот же
приём, что в `team` и `methods`: иначе вышел бы круг (`cli` импортирует архивариуса).

Общий с другими фоновыми службами скелет — «заход уже идёт», «о сбое раз за сеанс»,
«отдельная задача, которую никто не ждёт» — живёт в `background`. Здесь остаётся только то,
что у архивариуса своё: раз в пять обменов, дешёвая модель, инструкция и разбор ответа.
"""

from __future__ import annotations

import asyncio
import json
from typing import TYPE_CHECKING

from . import background, memory, output, ui
from .agent import Agent
from .profiles import Profile

if TYPE_CHECKING:  # только подсказка типов — на выполнении круга не возникает
    from .cli import State

# Через сколько обменов главного разговора архивариус заходит за фактами.
EVERY_N = 5

# Сколько ждать последнего захода при выходе. Заставлять человека ждать выхода дольше —
# хуже, чем потерять несколько фактов: разговор от этого не страдает, он записан дословно.
EXIT_WAIT_SECONDS = 5.0

# Имя архивариуса в журнале прогонов: по нему его запросы отличаются от разговора человека.
AGENT_NAME = "архивариус"

# Модель — самая дешёвая: работа архивариуса это выписка из готового текста, а не
# рассуждение. Модель держим здесь, а не в профиле: `Profile` описывает, КАК спрашивать, а
# не У КОГО — имя модели в harness живёт отдельно от профиля.
ARCHIVIST_MODEL = "deepseek-v4-flash"

# Текст утверждён пользователем и переносится сюда дословно. Три ограничения в нём закрывают
# три конкретные беды: «только слова человека» — иначе в память уедет то, что насочиняла
# модель; «без догадок» — иначе через месяц там окажется «предпочитает краткие ответы»,
# потому что человек однажды сказал «короче»; «самодостаточная строка» — иначе факт «как
# договорились вчера» окажется бесполезен в папке, где никакого «вчера» нет.
#
# Слово «json» и пример структуры обязаны стоять в самой инструкции: без них DeepSeek
# отклоняет запрос с `response_format: json_object`.
ARCHIVIST_INSTRUCTION = """Ты ведёшь память об одном человеке — пользователе инструмента.
Тебе дают кусок его разговора с моделью. Найди в нём факты О САМОМ ЧЕЛОВЕКЕ
и его работе, которые останутся верными и через месяц, в любом другом разговоре.

Записывай:
— как его зовут и как к нему обращаться;
— чем он занимается, какой опыт, на каких языках и в каком стеке работает;
— устойчивые предпочтения: язык общения, желаемый стиль ответов, что любит и не любит;
— обстановку работы: какие машины и серверы, где лежат проекты, чем собирает;
— решения о его проектах, принятые надолго.

НЕ записывай:
— содержание задачи, о которой шла речь, — это разговор, а не человек;
— сиюминутное: «сейчас спешит», «сегодня устал»;
— то, что сказала модель. Только то, что сказал сам человек;
— свои догадки. Не сказано прямо — не факт.

Каждый факт — одна короткая строка, понятная без разговора.
Плохо: «любит то, что мы обсуждали». Хорошо: «любимый цвет — синий».
Нечего записать — верни пустой список, это нормальный ответ.

Ответ строго json: {"факты": ["зовут Александр", "любимый цвет — синий"]}"""

# Ключ, под которым архивариус отдаёт список. Он же стоит в примере внутри инструкции —
# держим одной строкой, чтобы разбор и инструкция не разъехались молча.
FACTS_KEY = "факты"


def archivist_profile() -> Profile:
    """Профиль, с которым архивариус ходит к модели.

    `keep_history=False`: каждый заход самодостаточен — на вход приходит готовый кусок
    разговора. Помни архивариус прошлые заходы, второй тащил бы в запрос весь первый, платя
    за один и тот же текст дважды.

    Рассуждения выключены, температура низкая: выписка фактов из готового текста — работа
    механическая, и фантазия здесь только вредит. `json_object` снимает разбор обёрток вида
    «вот факты:» вокруг ответа.

    Профиль собирается заново на каждый вызов: словарь `params` изменяем, а правит его
    фоновая задача — общий на всех словарь она однажды поправила бы соседу.
    """
    return Profile(
        name=AGENT_NAME,
        system=ARCHIVIST_INSTRUCTION,
        keep_history=False,
        params={
            "temperature": 0.2,
            "max_tokens": 512,
            "response_format": {"type": "json_object"},
            "thinking": {"type": "disabled"},
        },
    )


def extract_request(pairs: list[tuple[str, str]]) -> str:
    """Кусок разговора в том виде, в каком его читает архивариус.

    Реплики подписаны: вся инструкция стоит на различии «сказал человек» и «сказала модель»,
    и без подписей отличить одно от другого в сплошном тексте нечем.
    """
    куски: list[str] = []
    for вопрос, ответ in pairs:
        куски.append(f"Человек: {вопрос.strip()}")
        куски.append(f"Модель: {ответ.strip()}")
    return "\n\n".join(куски)


def parse_facts(raw: str) -> list[str]:
    """Список фактов из ответа архивариуса. Терпим к мусору: пустой список, а не исключение.

    Архивариус работает фоновой задачей, и исключение отсюда никто не увидит — оно всплывёт
    предупреждением сборщика мусора где-то посреди чужого вывода. Поэтому не JSON, не
    объект, нет поля, поле не список, элемент не строка — всё это ровно то же самое, что
    «фактов не нашлось»: заход прошёл впустую, разговор не пострадал.

    Нестроковый элемент выбрасывается поштучно, а не вместе со всем списком: один сбойный
    элемент не повод терять соседние честные факты.
    """
    try:
        разобранное = json.loads(raw)
    except (json.JSONDecodeError, TypeError, ValueError):
        return []
    if not isinstance(разобранное, dict):
        return []
    список = разобранное.get(FACTS_KEY)
    if not isinstance(список, list):
        return []
    факты: list[str] = []
    for элемент in список:
        if not isinstance(элемент, str):
            continue
        # Факт — одна строка: перевод строки внутри схлопывается, как и в самом хранилище.
        текст = " ".join(элемент.split())
        if not текст or len(текст) > memory.FACT_CHARS_MAX:
            continue
        факты.append(текст)
    return факты


def running(state: State) -> bool:
    """Идёт ли заход прямо сейчас."""
    return background.идёт(state.архивариус)


def due(state: State) -> bool:
    """Пора ли заводить заход.

    Два условия сверх счётчика. Первое — выключатель из настроек инструмента: выключен сбор,
    значит архивариус не запускается ни разу, и запросов за него никто не платит. Второе —
    заход уже идёт: два архивариуса разом прочли бы один и тот же кусок разговора и выписали
    из него одни и те же факты, заплатив дважды.
    """
    return state.config.remember and state.since_archive >= EVERY_N and not running(state)


def last_pairs(state: State, count: int) -> list[tuple[str, str]]:
    """Последние пары «вопрос — ответ» главного разговора.

    Память агент отдаёт копией и сообщениями подряд; здесь она складывается обратно в пары.
    Непарный хвост невозможен (`remember` кладёт обе реплики разом), но проверку оставляем:
    складывать пары из списка нечётной длины значило бы приписать вопросу чужой ответ.
    """
    сообщения = state.main_agent.history()
    пары: list[tuple[str, str]] = []
    for номер in range(0, len(сообщения) - 1, 2):
        вопрос, ответ = сообщения[номер], сообщения[номер + 1]
        if вопрос["role"] == "user" and ответ["role"] == "assistant":
            пары.append((вопрос["content"], ответ["content"]))
    return пары[-count:] if count > 0 else пары


async def run(state: State) -> None:
    """Один заход архивариуса: прочесть накопленный кусок разговора и выписать из него факты.

    Показывать по ходу нечего, поэтому обработчик событий потока агенту не передаётся:
    панели у архивариуса нет, а перебивать разговор человека чужим потоком нельзя. Виден
    только результат — каждый новый факт объявляется в ленте. Скрыт сам запрос, но не то,
    что архивариус запомнил: молчаливого роста памяти не бывает, иначе выдумку архивариуса
    нечем заметить и нечего убирать.
    """
    if state.client is None:
        return
    пары = last_pairs(state, EVERY_N)
    if not пары:
        # Разговора ещё нет (или профиль его не копит) — выписывать не из чего, и платить
        # за запрос впустую незачем.
        return
    try:
        агент = Agent(AGENT_NAME, archivist_profile())
        обмен = await агент.exchange(state.client, ARCHIVIST_MODEL, extract_request(пары), agent=AGENT_NAME)
        # Архивариус живёт вне панелей, а значит и вне обхода агентов сеанса: без этой строки
        # его расход не попадал бы в итог никогда. Это единственная трата, которую человек не
        # заказывал вручную, — и молчать именно о ней было бы хуже всего.
        state.retire([агент])
        if not обмен.ok:
            # Счёт отказов ведём, а возвращённое значение и `выключена` НЕ читаем — и это
            # решение, а не недосмотр. Архивариус и до общего скелета повторял попытки
            # бесконечно; выключать его по `ПРЕДЕЛ_ОТКАЗОВ` значило бы поменять его поведение
            # заодно с переносом скелета, а такие перемены делаются отдельно и осознанно.
            background.отказ(state.архивариус)
            warn(state, обмен.error)
            return
        for текст in parse_facts(обмен.text):
            добавлен, сообщение = memory.add_fact(текст, source=AGENT_NAME)
            if добавлен:
                # Новый факт уедет в системную часть следующего запроса и утяжелит его.
                # Полоска занятости узнать об этом сама не может: факты лежат на диске, а её
                # отпечаток видит только память и профиль. Зовём через само состояние, а не
                # через `cli`: архивариус про интерфейс не знает и знать не должен — на этом
                # стоит его проверка без терминала.
                if state.занятость is not None:
                    state.занятость.сбросить()
                output.append_log(state, ui.fact_added_fragments(сообщение), state.main)
            # Отказ хранилища вслух не называем: чаще всего это «уже записано» — обычный
            # ход работы, а не беда, и строка о нём после каждого захода была бы шумом.
        # Заход считается удачным ЗДЕСЬ, в самом конце, а не сразу после ответа модели:
        # удачный обмен с падающей записью фактов (нет прав на каталог, полон диск) — это
        # неудачный заход. Отметь мы успех раньше, счёт чередовал бы «успех» и «отказ», предела
        # не достиг бы никогда, и служба, которая по нему выключается, платила бы за запросы
        # весь сеанс при начисто сломанном применении итога.
        background.успех(state.архивариус)
    except asyncio.CancelledError:
        # Отмену заказывает человек (Ctrl+C, выход по сроку), и отказом службы она не
        # считается: счёт отказов её не замечает, а само исключение уходит наружу.
        raise
    except Exception as exc:
        # Заход живёт отдельной задачей, которую никто не ждёт: выпущенное отсюда исключение
        # никому бы не досталось — оно всплыло бы предупреждением сборщика мусора посреди
        # чужого вывода, уже после того, как причину искать негде.
        background.отказ(state.архивариус)
        warn(state, str(exc))


def warn(state: State, error: str | None) -> None:
    """Сказать о сбое архивариуса — не больше одного раза за сеанс.

    То же правило, что у журнала прогонов, и по той же причине: причина сбоя обычно
    постоянная (нет сети, нет денег на счёте), а заходов за сеанс много, и повторяющаяся
    строка вытеснила бы из ленты сами ответы. Молчать совсем тоже нельзя: человек считал бы,
    что память пополняется, а она стоит.
    """
    if state.архивариус.предупреждён:
        return
    state.архивариус.предупреждён = True
    output.append_log(
        state,
        ui.error_fragments(f"архивариус не смог пополнить память: {error or 'неизвестная причина'}"),
        state.main,
    )


def start(state: State) -> None:
    """Завести фоновый заход, если пора.

    Задача создаётся ОТДЕЛЬНО от задачи запроса и никем не ожидается: архивариус не имеет
    права задерживать ни ответ, ни ввод следующего вопроса. Счётчик обнуляется здесь же —
    иначе следующий обмен завёл бы второй заход поверх идущего.
    """
    if not due(state):
        return
    state.since_archive = 0
    background.завести(state.архивариус, run(state))


async def finish(state: State) -> None:
    """Последний заход при выходе — и не дольше `EXIT_WAIT_SECONDS`.

    Без него всё, о чём говорили после прошлого захода (до четырёх обменов), в глобальную
    память не попало бы вовсе. Ждать при этом сколько угодно нельзя: выход из инструмента
    обязан быть быстрым, и потеря нескольких фактов дешевле, чем повисший на минуту `/exit`.

    Условие «был хоть один обмен» отсекает пустой запрос при выходе сразу после запуска.
    """
    if not running(state) and state.config.remember and state.since_archive > 0:
        state.since_archive = 0
        background.завести(state.архивариус, run(state))
    задача = state.архивариус.задача
    if задача is None or задача.done():
        return
    # `asyncio.wait`, а не `wait_for`: он не выпускает наружу ни отмену задачи, ни её
    # исключение. Выход не имеет права упасть из-за вспомогательного механизма — человек уже
    # сказал «выхожу», и показать ему ошибку всё равно негде: интерфейс закрыт.
    _, не_успевшие = await asyncio.wait({задача}, timeout=EXIT_WAIT_SECONDS)
    for невыполненная in не_успевшие:
        невыполненная.cancel()
