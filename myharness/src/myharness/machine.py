ПОЛЕ = "stages"


@dataclass(frozen=True)
class Стадия:
    имя: str
    цель: str = ""
    # Стадия, выход из которой открывает только человек.
    утверждение: bool = False
    # Профили, которые созываются на этой стадии; группа профиля (`agents`) здесь ни при чём.
    консилиум: tuple[str, ...] = ()
    # Разрешённые переходы; пусто — стадия конечная.
    дальше: tuple[str, ...] = ()


def имя_стадии(текст: str) -> str:
    """Единственный способ привести имя стадии: пробелы схлопнуты, верхний регистр.

    Им пользуются и карта профиля, и `/task этап`: два разных приведения дали бы стадию,
    которую команда поставила, а карта не находит.
    """
    return " ".join(текст.split()).upper()


@dataclass(frozen=True)
class Карта:
    стадии: tuple[Стадия, ...]

    def стадия(self, имя: str) -> Стадия | None:
        ключ = имя_стадии(имя)
        return next((с for с in self.стадии if с.имя == ключ), None)

    @property
    def начальная(self) -> Стадия:
        return self.стадии[0]

    def конечная(self, имя: str) -> bool:
        с = self.стадия(имя)
        return с is not None and not с.дальше


def _имена(
    raw: Any, поле: str, стадия: str, жалобы: list[str]
) -> list[str]:
    """Список строк из поля стадии; не список и не строки отбрасываются вслух."""
    if raw is None:
        return []
    if not isinstance(raw, list):
        жалобы.append(
            f"поле «{ПОЛЕ}»: у стадии «{стадия}» «{поле}» — не список имён, пропущено"
        )
        return []
    итог: list[str] = []
    for элемент in raw:
        if not isinstance(элемент, str) or not элемент.strip():
            жалобы.append(
                f"поле «{ПОЛЕ}»: у стадии «{стадия}» в «{поле}» {элемент!r} — не имя, пропущено"
            )
            continue
        итог.append(элемент.strip())
    return итог


def разобрать_карту(
    raw: Any,
    есть_профиль: Callable[[str], bool],
    *,
    свой_профиль: str | tuple[str, ...] = "",
) -> tuple[Карта | None, list[str]]:
    """Карта из значения json профиля и жалобы человеку.

    `свой_профиль` — имя профиля или несколько его имён (имя файла и поле `name` json могут
    расходиться): консилиум, называющий любое из них, отбрасывается — профиль себя не созывает.

    `есть_профиль` не отбрасывает имя консилиума, а только предупреждает: перечень профилей
    зависит от каталога запуска, и отброшенное здесь имя стёрлось бы с диска при первой же
    записи профиля. Годность имени окончательно проверяется при созыве.

    `None` без жалоб — поля нет. `None` с жалобой — поле есть, но годной карты из него не
    собрать: нет ни одной стадии, ни одной конечной (задачу не завершить), или у стадии были
    заданы переходы, а годных не осталось (стадия стала бы конечной против воли автора).
    """
    свои = {свой_профиль} if isinstance(свой_профиль, str) else set(свой_профиль)
    свои.discard("")
    if raw is None:
        return None, []
    жалобы: list[str] = []
    if not isinstance(raw, list):
        жалобы.append(f"поле «{ПОЛЕ}» — не список стадий, пропущено")
        return None, жалобы

    # Первый проход собирает стадии с сырыми переходами: проверить переход можно только
    # после того, как известны все имена карты — переход вперёд по списку законен.
    черновик: list[tuple[str, str, bool, tuple[str, ...], list[str], bool]] = []
    занятые: set[str] = set()
    for номер, элемент in enumerate(raw, start=1):
        if not isinstance(элемент, dict):
            жалобы.append(f"поле «{ПОЛЕ}»: элемент {номер} — не описание стадии, пропущен")
            continue
        сырое_имя = элемент.get("name")
        if not isinstance(сырое_имя, str) or not сырое_имя.strip():
            жалобы.append(f"поле «{ПОЛЕ}»: у элемента {номер} нет имени стадии «name», пропущен")
            continue
        имя = имя_стадии(сырое_имя)
        if имя in занятые:
            жалобы.append(
                f"поле «{ПОЛЕ}»: стадия «{имя}» указана повторно — второе описание пропущено"
            )
            continue
        занятые.add(имя)

        цель = элемент.get("goal", "")
        if not isinstance(цель, str):
            жалобы.append(f"поле «{ПОЛЕ}»: у стадии «{имя}» цель «goal» — не текст, пропущена")
            цель = ""
        утверждение = элемент.get("approval", False)
        if not isinstance(утверждение, bool):
            жалобы.append(
                f"поле «{ПОЛЕ}»: у стадии «{имя}» «approval» — не true/false, взято false"
            )
            утверждение = False

        консилиум: list[str] = []
        for профиль in _имена(элемент.get("council"), "council", имя, жалобы):
            if профиль in свои:
                жалобы.append(
                    f"поле «{ПОЛЕ}»: у стадии «{имя}» консилиум называет сам профиль "
                    f"«{профиль}» — пропущен"
                )
            elif профиль in консилиум:
                жалобы.append(
                    f"поле «{ПОЛЕ}»: у стадии «{имя}» профиль «{профиль}» в консилиуме "
                    f"указан повторно — пропущен"
                )
            else:
                if not есть_профиль(профиль):
                    жалобы.append(
                        f"поле «{ПОЛЕ}»: профиль «{профиль}» для консилиума стадии «{имя}» "
                        f"не найден — проверю при созыве"
                    )
                консилиум.append(профиль)

        сырые_переходы = элемент.get("next")
        # Переходы заданы, если поле не пусто: пустой список и отсутствие поля — конечная стадия.
        заданы = сырые_переходы is not None and not (
            isinstance(сырые_переходы, list) and not сырые_переходы
        )
        переходы = _имена(сырые_переходы, "next", имя, жалобы)
        черновик.append((имя, цель.strip(), утверждение, tuple(консилиум), переходы, заданы))

    стадии: list[Стадия] = []
    негодна = False
    for имя, цель, утверждение, консилиум, переходы, заданы in черновик:
        дальше: list[str] = []
        for переход in переходы:
            куда = имя_стадии(переход)
            if куда not in занятые:
                жалобы.append(
                    f"поле «{ПОЛЕ}»: у стадии «{имя}» переход в неизвестную стадию "
                    f"«{куда}» — пропущен"
                )
            elif куда in дальше:
                жалобы.append(
                    f"поле «{ПОЛЕ}»: у стадии «{имя}» переход в «{куда}» указан повторно — пропущен"
                )
            else:
                дальше.append(куда)
        if заданы and not дальше:
            жалобы.append(
                f"поле «{ПОЛЕ}»: у стадии «{имя}» не осталось ни одного годного перехода — "
                f"карта не принята"
            )
            негодна = True
        стадии.append(Стадия(имя, цель, утверждение, консилиум, tuple(дальше)))

    if негодна:
        return None, жалобы

    if not стадии:
        жалобы.append(f"поле «{ПОЛЕ}»: не осталось ни одной годной стадии — карта пропущена")
        return None, жалобы
    if not any(not с.дальше for с in стадии):
        жалобы.append(
            f"поле «{ПОЛЕ}»: нет ни одной конечной стадии (без «next») — задачу не завершить, "
            f"карта пропущена"
        )
        return None, жалобы
    return Карта(tuple(стадии)), жалобы


def в_список(карта: Карта) -> list[dict[str, Any]]:
    """Карта в вид json профиля — обратное `разобрать_карту`."""
    итог: list[dict[str, Any]] = []
    for с in карта.стадии:
        элемент: dict[str, Any] = {"name": с.имя}
        if с.цель:
            элемент["goal"] = с.цель
        if с.утверждение:
            элемент["approval"] = True
        if с.консилиум:
            элемент["council"] = list(с.консилиум)
        элемент["next"] = list(с.дальше)
        итог.append(элемент)
    return итог


