"""Автомат задачи: карта стадий, которую задаёт профиль.

Карта — упорядоченный список стадий. Первая стадия — начальная, стадия без переходов —
конечная. Модель называет переход, а проверяет его программа по этой карте; поэтому карта
разбирается строго: мусор отбрасывается вслух, профиль при этом не падает.

Порядок импорта — условие работоспособности: `profiles` импортирует этот модуль ДО того, как
определён `Profile`. Поэтому на верхнем уровне модуль не имеет права импортировать ни
`profiles`, ни `state`, ни `team`, ни `agent`, ни `output` — только внутри функций или под
`TYPE_CHECKING`. `workspace` тоже импортирует отсюда (`имя_стадии`), и обратного импорта
`workspace` на верхнем уровне быть не должно.
"""

