"""Клиент MCP: файл серверов, подстановка переменных, соединение и список инструментов.

Файл серверов — `.mcp.json` рабочего каталога в формате Claude Code (`mcpServers`): так один и
тот же файл годится и нашему инструменту, и Claude Code, и человеку не надо вести два списка.
Запись stdio — `command`/`args`/`env`, запись HTTP — `type: "http"`/`url`/`headers`.

Модуль ничего не держит между вызовами: файл читается при каждом вызове, соединение живёт
внутри одного вызова. Держать соединения открытыми имеет смысл, когда инструменты вызывает
модель; сегодня их только перечисляют, и долгоживущий процесс сервера был бы лишним состоянием.

Предел ожидания опроса — как у Claude Code: 30 секунд на весь опрос сервера (запуск,
согласование, список), переопределяется переменной `MCP_TIMEOUT` в миллисекундах — то же имя и
те же единицы, чтобы одна настройка действовала на оба инструмента. Без предела зависший
stdio-сервер вешал бы опрос навсегда: у сессии stdio своего предела чтения нет, а опрос всех
серверов ждёт каждого.

Чего модуль НЕ делает, и почему:

- не вызывает инструменты — это следующий день, мост к DeepSeek;
- не проверяет имя сервера и тайны в заголовках — это разбор команды `/mcp add`: файл пишет и
  человек руками, и отказывать ему в чтении собственного файла было бы неуместно;
- не пишет в журнал и не знает интерфейса — показ целиком на команде;
- не ставит предела числу страниц списка: его нет и у образца, а потолок, придуманный здесь,
  молча отрезал бы инструменты большого сервера.
"""

from __future__ import annotations

import asyncio
import contextlib
import json
import os
import re
from collections.abc import AsyncIterator, Mapping
from contextlib import AsyncExitStack, asynccontextmanager
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Literal

import anyio
from mcp import ClientSession, StdioServerParameters
from mcp.client.stdio import stdio_client
from mcp.client.streamable_http import create_mcp_http_client, streamable_http_client
from mcp.types import InitializeResult, PaginatedRequestParams

ИМЯ_ФАЙЛА = ".mcp.json"

# Ключ верхнего уровня — как у Claude Code, иначе файл перестал бы быть общим.
_КЛЮЧ = "mcpServers"

# Предел опроса — число и имя переменной взяты у Claude Code, а не придуманы здесь.
ПЕРЕМЕННАЯ_ПРЕДЕЛА = "MCP_TIMEOUT"
ПРЕДЕЛ_ПО_УМОЛЧАНИЮ_МС = 30_000

# `${ИМЯ}` и `${ИМЯ:-умолчание}` — ровно те два вида, что понимает Claude Code. Голый `$ИМЯ` не
# трогается: в доводах команды знак доллара бывает и буквальным.
_ПЕРЕМЕННАЯ = re.compile(r"\$\{([A-Za-z_][A-Za-z0-9_]*)(?::-([^}]*))?\}")


@dataclass(frozen=True)
class Сервер:
    """Запись файла серверов, как она лежит, — без подстановки переменных.

    Подстановка откладывается до соединения нарочно: запись с `${GITHUB_TOKEN}` должна
    читаться и переписываться, даже когда переменная не задана, и тайна не должна оседать
    в памяти дольше одного соединения.
    """

    имя: str
    способ: Literal["stdio", "http"]
    команда: str | None = None
    доводы: tuple[str, ...] = ()
    окружение: dict[str, str] = field(default_factory=dict)
    адрес: str | None = None
    заголовки: dict[str, str] = field(default_factory=dict)


@dataclass(frozen=True)
class НегоднаяЗапись:
    """Запись файла, которую этот инструмент не умеет опросить, и почему.

    Файл общий с Claude Code, и в нём законны записи, которых у нас нет (например, SSE). Одна
    такая запись не должна отнимать у человека остальные серверы, поэтому она не роняет чтение
    файла, а доходит до итога своего сервера причиной сбоя.
    """

    имя: str
    причина: str


@dataclass(frozen=True)
class Инструмент:
    сервер: str
    имя: str  # как отдал сервер: SEP-986 допускает в нём `.`, и здесь оно не проверяется
    описание: str  # полностью; "" если сервер описания не дал
    схема: dict  # input_schema как есть

    @property
    def полное_имя(self) -> str:
        # Приставка сервера — как у Claude Code: два сервера вправе назвать инструмент
        # одинаково, и без неё имена столкнутся.
        return f"mcp__{self.сервер}__{self.имя}"


@dataclass(frozen=True)
class Итог:
    """Итог опроса одного сервера. При сбое инструменты пусты, а причина — одной строкой."""

    сервер: Сервер | НегоднаяЗапись
    имя_на_сервере: str | None
    протокол: str | None
    инструменты: tuple[Инструмент, ...]
    сбой: str | None


class ОшибкаФайла(Exception):
    """Файл серверов испорчен целиком (не JSON, не объект), имя занято или неизвестно."""


class НетПеременной(KeyError):
    """Переменная из `${ИМЯ}` не задана и умолчания у неё нет.

    Наследник `KeyError` — по договору; своё имя и своя строка нужны потому, что `str()` у
    `KeyError` — имя в кавычках, и в строке сбоя человек не понял бы, чего не хватает.
    """

    def __init__(self, имя: str) -> None:
        super().__init__(имя)
        self.имя = имя

    def __str__(self) -> str:
        return f"не задана переменная окружения {self.имя}"


def подставить(текст: str, окружение: Mapping[str, str]) -> str:
    """Заменяет `${ИМЯ}` и `${ИМЯ:-умолчание}` значениями из `окружение`.

    Незаданная переменная без умолчания — `НетПеременной(имя)`: ошибка называет ИМЯ, а не
    значение, поэтому никакая тайна в текст ошибки попасть не может. Пустая переменная, как и в
    оболочке при `:-`, считается незаданной.
    """

    def замена(m: re.Match[str]) -> str:
        имя, умолчание = m.group(1), m.group(2)
        значение = окружение.get(имя)
        if значение:
            return значение
        if умолчание is not None:
            return умолчание
        raise НетПеременной(имя)

    return _ПЕРЕМЕННАЯ.sub(замена, текст)


# --- файл серверов -------------------------------------------------------------------------


def _сырой(путь: Path) -> dict[str, Any]:
    """Весь документ файла как словарь; нет файла — пустой. Прочие ключи сохраняются для записи."""
    try:
        текст = путь.read_text(encoding="utf-8")
    except FileNotFoundError:
        return {}
    except OSError as exc:
        raise ОшибкаФайла(f"не удалось прочитать {путь}: {exc}") from exc
    try:
        документ = json.loads(текст)
    except json.JSONDecodeError as exc:
        raise ОшибкаФайла(f"{путь} — не JSON: {exc}") from exc
    if not isinstance(документ, dict):
        raise ОшибкаФайла(f"{путь}: верхний уровень должен быть объектом")
    серверы = документ.get(_КЛЮЧ, {})
    if not isinstance(серверы, dict):
        raise ОшибкаФайла(f"{путь}: «{_КЛЮЧ}» должен быть объектом")
    return документ


class _НеТотВид(Exception):
    """Запись не того вида; внутри модуля превращается в `НегоднаяЗапись`."""


def _строки(ключ: str, значение: Any, вид: type) -> Any:
    if вид is list:
        if not isinstance(значение, list) or not all(isinstance(x, str) for x in значение):
            raise _НеТотВид(f"«{ключ}» должен быть списком строк")
    elif not isinstance(значение, dict) or not all(
        isinstance(k, str) and isinstance(v, str) for k, v in значение.items()
    ):
        raise _НеТотВид(f"«{ключ}» должен быть объектом строк")
    return значение


def _запись(имя: str, данные: Any) -> Сервер:
    if not isinstance(данные, dict):
        raise _НеТотВид("запись должна быть объектом")
    вид = данные.get("type")
    # Явный `type` старше догадки по набору ключей: запись `stdio` с забытым `url` — всё равно
    # stdio, как её и понимает Claude Code.
    if вид is None:
        if "url" in данные:
            вид = "http"
        elif "command" in данные:
            вид = "stdio"
        else:
            raise _НеТотВид("нет ни «url», ни «command»")
    if вид == "sse":
        raise _НеТотВид("SSE не поддерживается, нужен type \"http\"")
    if вид == "http":
        адрес = данные.get("url")
        if not isinstance(адрес, str) or not адрес:
            raise _НеТотВид("у HTTP-сервера нет «url»")
        return Сервер(
            имя=имя,
            способ="http",
            адрес=адрес,
            заголовки=dict(_строки("headers", данные.get("headers", {}), dict)),
        )
    if вид == "stdio":
        команда = данные.get("command")
        if not isinstance(команда, str) or not команда:
            raise _НеТотВид("«command» должна быть непустой строкой")
        return Сервер(
            имя=имя,
            способ="stdio",
            команда=команда,
            доводы=tuple(_строки("args", данные.get("args", []), list)),
            окружение=dict(_строки("env", данные.get("env", {}), dict)),
        )
    raise _НеТотВид(f"неизвестный type {вид!r}")


def прочитать(путь: Path) -> list[Сервер | НегоднаяЗапись]:
    """Записи файла в порядке файла; нет файла — пустой список.

    Негодная запись приходит `НегоднаяЗапись` на своём месте, а не роняет чтение: опросить
    остальные серверы можно и без неё. `ОшибкаФайла` — только когда испорчен весь файл.
    """
    записи: list[Сервер | НегоднаяЗапись] = []
    for имя, данные in _сырой(путь).get(_КЛЮЧ, {}).items():
        try:
            записи.append(_запись(имя, данные))
        except _НеТотВид as exc:
            записи.append(НегоднаяЗапись(имя, str(exc)))
    return записи


def _в_словарь(сервер: Сервер) -> dict[str, Any]:
    # Поле `type` пишется всегда, как делает `claude mcp add`: запись читается однозначно и
    # без догадки по набору ключей.
    if сервер.способ == "http":
        return {"type": "http", "url": сервер.адрес, "headers": dict(сервер.заголовки)}
    return {
        "type": "stdio",
        "command": сервер.команда,
        "args": list(сервер.доводы),
        "env": dict(сервер.окружение),
    }


def _записать(путь: Path, документ: dict[str, Any]) -> None:
    """Появление файла одним движением: черновик рядом, затем подмена имени.

    Черновик в том же каталоге — иначе `os.replace` между файловыми системами не атомарен.
    Права: у существующего файла — его собственные, выставленные черновику до первой записанной
    строки (человек мог закрыть файл с тайнами от чужих глаз, и перезапись не должна ни на миг
    его открыть); у нового — обычные по umask, как у `claude mcp add`.
    """
    черновик = путь.parent / f".{путь.name}.{os.getpid()}.tmp"
    содержимое = json.dumps(документ, ensure_ascii=False, indent=2) + "\n"
    try:
        try:
            прежние: int | None = путь.stat().st_mode & 0o777
        except FileNotFoundError:
            прежние = None
        # Черновик прошлой упавшей записи того же процесса убирается: иначе `O_EXCL` отказал бы.
        with contextlib.suppress(FileNotFoundError):
            черновик.unlink()
        # Режим при создании урезается umask; поэтому прежние права ставятся ещё и `fchmod` —
        # до записи содержимого, так что открытого окна нет.
        fd = os.open(черновик, os.O_WRONLY | os.O_CREAT | os.O_EXCL, прежние if прежние is not None else 0o666)
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            if прежние is not None:
                os.fchmod(f.fileno(), прежние)
            f.write(содержимое)
        os.replace(черновик, путь)
    except OSError as exc:
        with contextlib.suppress(OSError):
            черновик.unlink()
        raise ОшибкаФайла(f"не удалось записать {путь}: {exc}") from exc


def добавить(путь: Path, сервер: Сервер) -> None:
    """Дописывает запись в конец `mcpServers`, сохраняя прочие ключи и порядок прочих серверов."""
    документ = _сырой(путь)
    серверы = документ.setdefault(_КЛЮЧ, {})
    if сервер.имя in серверы:
        raise ОшибкаФайла(f"сервер {сервер.имя} уже есть в {путь}")
    серверы[сервер.имя] = _в_словарь(сервер)
    _записать(путь, документ)


def убрать(путь: Path, имя: str) -> None:
    """Убирает запись (и негодную тоже); неизвестное имя — `ОшибкаФайла` с именами имеющихся."""
    документ = _сырой(путь)
    серверы = документ.get(_КЛЮЧ, {})
    if имя not in серверы:
        имеющиеся = ", ".join(серверы) or "нет ни одного"
        raise ОшибкаФайла(f"сервера {имя} нет в {путь}; имеющиеся: {имеющиеся}")
    del серверы[имя]
    _записать(путь, документ)


# --- соединение ----------------------------------------------------------------------------


@asynccontextmanager
async def _соединение(
    сервер: Сервер, ответ_http: dict[str, str]
) -> AsyncIterator[tuple[ClientSession, InitializeResult]]:
    среда = os.environ
    async with AsyncExitStack() as стек:
        if сервер.способ == "stdio":
            параметры = StdioServerParameters(
                command=подставить(сервер.команда or "", среда),
                args=[подставить(d, среда) for d in сервер.доводы],
                # Родительское окружение целиком плюс своё поверх — как у Claude Code: без
                # родительского `PATH` запускатель вроде `uvx` не найдёт даже себя.
                env={**среда, **{k: подставить(v, среда) for k, v in сервер.окружение.items()}},
            )
            # Поток ошибок процесса сервера — в никуда: иначе чужие строки лягут поверх экрана
            # prompt_toolkit. Причину сбоя это не прячет — она приходит исключением.
            приёмник = стек.enter_context(open(os.devnull, "w", encoding="utf-8"))
            чтение, запись = await стек.enter_async_context(stdio_client(параметры, errlog=приёмник))
        else:
            заголовки = {k: подставить(v, среда) for k, v in сервер.заголовки.items()}
            адрес = подставить(сервер.адрес or "", среда)
            клиент = await стек.enter_async_context(create_mcp_http_client(headers=заголовки))

            # Библиотека подменяет ответ сервера с ошибкой заглушкой «Server returned an error
            # response», и человек не отличил бы отказ в доступе от упавшего сервера. Ловушка
            # запоминает только код и стандартную фразу — ни заголовков, ни тела. Только ответы
            # на POST: закрывающий сеанс DELETE получает 405 у серверов без его поддержки, и этот
            # код приписался бы к чужой причине.
            async def запомнить(ответ: Any) -> None:
                if ответ.request.method == "POST" and ответ.status_code >= 400 and "код" not in ответ_http:
                    ответ_http["код"] = f"HTTP {ответ.status_code} {ответ.reason_phrase}".strip()

            клиент.event_hooks["response"].append(запомнить)
            потоки = await стек.enter_async_context(streamable_http_client(адрес, http_client=клиент))
            чтение, запись = потоки[0], потоки[1]
        сессия = await стек.enter_async_context(ClientSession(чтение, запись))
        ответ = await сессия.initialize()
        yield сессия, ответ


@asynccontextmanager
async def соединение(
    сервер: Сервер, ответ_http: dict[str, str] | None = None
) -> AsyncIterator[tuple[ClientSession, InitializeResult]]:
    """Открывает соединение, согласует протокол и отдаёт сессию с ответом согласования.

    Незаданная переменная — `НетПеременной` до запуска процесса или обращения к сети. Предела
    ожидания здесь нет: его ставит тот, кто держит соединение, — `список` ставит свой.
    `ответ_http` — приёмник кода ответа сервера HTTP с ошибкой для `описать_сбой`.
    """
    async with _соединение(сервер, ответ_http if ответ_http is not None else {}) as пара:
        yield пара


def предел() -> float:
    """Предел опроса в секундах из `MCP_TIMEOUT` (миллисекунды) или 30 с по умолчанию.

    Кривое значение — `ValueError` с именем переменной, а не тихое умолчание: человек задал
    предел нарочно, и молча подменить его другим значило бы спрятать его ошибку.
    """
    текст = os.environ.get(ПЕРЕМЕННАЯ_ПРЕДЕЛА)
    if текст is None or not текст.strip():
        return ПРЕДЕЛ_ПО_УМОЛЧАНИЮ_МС / 1000
    try:
        мс = int(текст.strip())
    except ValueError:
        мс = 0
    if мс <= 0:
        raise ValueError(
            f"{ПЕРЕМЕННАЯ_ПРЕДЕЛА} должна быть целым положительным числом миллисекунд"
        )
    return мс / 1000


def секунды(предел: float) -> str:
    return f"{предел:g}".replace(".", ",")


def _глубинная(exc: BaseException) -> BaseException:
    """Самая глубокая причина: anyio заворачивает сбой в группы, порой вложенные."""
    while isinstance(exc, BaseExceptionGroup) and exc.exceptions:
        exc = exc.exceptions[0]
    return exc


def _тайны(сервер: Сервер) -> list[str]:
    """Значения, которые не должны появиться в строке сбоя.

    Подстановка сама ошибается именем, но сообщение библиотеки может процитировать адрес,
    команду, заголовок или окружение. Поэтому вычищается значение КАЖДОЙ подставленной
    переменной во всех полях — оно могло стать и частью длинной строки, — и все значения
    заголовков и `env` целиком, буквальные тоже.
    """
    значения: list[str] = []
    for текст in (*сервер.заголовки.values(), *сервер.окружение.values()):
        значения.append(текст)
        with contextlib.suppress(KeyError):
            значения.append(подставить(текст, os.environ))
    поля = (
        сервер.адрес or "",
        сервер.команда or "",
        *сервер.доводы,
        *сервер.заголовки.values(),
        *сервер.окружение.values(),
    )
    for текст in поля:
        for m in _ПЕРЕМЕННАЯ.finditer(текст):
            значения.append(os.environ.get(m.group(1)) or m.group(2) or "")
    # Длинные первыми: иначе замена короткого значения внутри длинного оставит хвост тайны.
    return sorted({з for з in значения if з}, key=len, reverse=True)


def значения_переменных(сервер: Сервер) -> list[str]:
    """Значения переменных, подставленных в любое поле записи, — длинные первыми.

    Для текста, который надо сохранить как есть (ошибка инструмента для модели): в отличие от
    `вычистить`, здесь нет буквальных значений заголовков и `env` — короткое буквальное `1`
    вырезалось бы из чисел ответа.
    """
    поля = (
        сервер.адрес or "",
        сервер.команда or "",
        *сервер.доводы,
        *сервер.заголовки.values(),
        *сервер.окружение.values(),
    )
    значения = {
        os.environ.get(m.group(1)) or m.group(2) or ""
        for текст in поля
        for m in _ПЕРЕМЕННАЯ.finditer(текст)
    }
    return sorted((з for з in значения if з), key=len, reverse=True)


def вычистить(текст: str, сервер: Сервер) -> str:
    for тайна in _тайны(сервер):
        текст = текст.replace(тайна, "***")
    return " ".join(текст.split())  # одной строкой: сообщения бывают многострочными


async def все_инструменты(сессия: ClientSession, сервер: str) -> tuple[Инструмент, ...]:
    """Список инструментов сервера целиком, по всем страницам.

    Одно место листания на опрос `/mcp` и на соединение для модели (`mcp_tools`): два цикла
    по курсору разошлись бы молча, и модель видела бы не те инструменты, что показ.
    """
    инструменты: list[Инструмент] = []
    курсор: str | None = None
    while True:
        страница = await сессия.list_tools(
            params=PaginatedRequestParams(cursor=курсор) if курсор is not None else None
        )
        инструменты.extend(
            Инструмент(
                сервер=сервер,
                имя=t.name,
                описание=t.description or "",
                схема=dict(t.input_schema),
            )
            for t in страница.tools
        )
        курсор = страница.next_cursor
        if курсор is None:
            return tuple(инструменты)


def описать_сбой(exc: BaseException, сервер: Сервер, ответ_http: dict[str, str]) -> str:
    """Причина сбоя сервера одной строкой, без тайн.

    Самая глубокая причина из групп anyio; своя `НетПеременной` — без имени класса, она уже
    говорит по-человечески; код ответа HTTP с ошибкой — в скобках, потому что библиотека
    подменяет его заглушкой.
    """
    причина = _глубинная(exc)
    if isinstance(причина, НетПеременной):
        текст = str(причина)
    else:
        текст = f"{type(причина).__name__}: {причина}"
    if "код" in ответ_http:
        текст = f"{текст} ({ответ_http['код']})"
    return вычистить(текст, сервер)


async def список(сервер: Сервер | НегоднаяЗапись) -> Итог:
    """Соединяется, берёт список инструментов целиком по всем страницам, закрывает соединение.

    Исключений не выпускает — любой сбой, включая группы исключений anyio, истёкший предел и
    негодную запись файла, ложится в `сбой`. Предел охватывает весь опрос: запуск, согласование
    и список; по его истечении соединение закрывается и процесс сервера убирается. Отмена задачи
    не глотается: её ждёт тот, кто отменял.
    """
    if isinstance(сервер, НегоднаяЗапись):
        return Итог(сервер, None, None, (), сервер.причина)
    имя_на_сервере: str | None = None
    протокол: str | None = None
    ответ_http: dict[str, str] = {}
    try:
        срок = предел()
    except ValueError as exc:
        return Итог(сервер, None, None, (), str(exc))
    # Своя рамка отмены, а не `fail_after`: истечение предела узнаётся по рамке, а не по типу
    # исключения — `TimeoutError` из глубины библиотеки (например, чтение HTTP) пределом не
    # является, и назвать его «сервер не ответил за 30 с» значило бы соврать.
    рамка = anyio.CancelScope(deadline=anyio.current_time() + срок)
    тишина = f"сервер не ответил за {секунды(срок)} с"
    try:
        with рамка:
            async with _соединение(сервер, ответ_http) as (сессия, ответ):
                имя_на_сервере = ответ.server_info.name
                протокол = str(ответ.protocol_version)
                инструменты = await все_инструменты(сессия, сервер.имя)
    except Exception as exc:  # noqa: BLE001 — договор: сбой сервера не выходит наружу
        if рамка.cancel_called:
            текст = вычистить(тишина, сервер)
            if "код" in ответ_http:
                текст = f"{текст} ({ответ_http['код']})"
        else:
            текст = описать_сбой(exc, сервер, ответ_http)
        return Итог(сервер, имя_на_сервере, протокол, (), текст)
    if рамка.cancel_called:
        return Итог(сервер, имя_на_сервере, протокол, (), тишина)
    return Итог(сервер, имя_на_сервере, протокол, tuple(инструменты), None)


async def список_всех(путь: Path) -> list[Итог]:
    """Опрашивает все записи файла одновременно; итоги — в порядке файла.

    Медленный сервер не задерживает остальных дольше своего предела, а сбой одного не мешает
    прочим: `список` исключений не выпускает. Испорченный целиком файл — `ОшибкаФайла`:
    опрашивать нечего.
    """
    return list(await asyncio.gather(*(список(с) for с in прочитать(путь))))
