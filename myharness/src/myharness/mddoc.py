"""Документ вида «заголовок плюс разделы»: разбор и сборка.

Такой документ читают и пишут два хранилища сразу — рабочая память задачи и карточка проекта.
Формат выбран не для программы, а для человека: он правит эти файлы руками и читает их
глазами, поэтому не JSON. Ровно тот же приём уже работает у файлов записей в `memory`.

Модуль чистый: ни диска, ни сети, ни терминала. Исключений наружу не выпускает вовсе —
испорченный файл памяти не имеет права мешать работе инструмента, и решение «что делать с
неполным документом» принимает тот, кто его читает, а не разбор.
"""

from __future__ import annotations

from collections.abc import Iterable, Mapping
from dataclasses import dataclass, field

ГРАНИЦА = "---"
НАЧАЛО_РАЗДЕЛА = "## "


@dataclass
class Документ:
    """Разобранный документ: заголовок парами «ключ — значение» и разделы по порядку."""

    заголовок: dict[str, str] = field(default_factory=dict)
    разделы: list[tuple[str, str]] = field(default_factory=list)

    def раздел(self, имя: str) -> str:
        """Тело раздела по имени; нет раздела — пустая строка.

        Сравнение по очищенному имени без учёта регистра: человек правит файл руками и
        напишет то «## План», то «##  план». Отличать эти два заголовка значило бы терять
        написанное из-за пробела."""
        ключ = имя.strip().casefold()
        for название, тело in self.разделы:
            if название.strip().casefold() == ключ:
                return тело
        return ""

    def пункты(self, имя: str) -> list[str]:
        """Тело раздела списком: строки «- текст» без тире, прочие строки как есть.

        Пустые строки выбрасываются: в разделе, где человек оставил пробел между пунктами,
        пустой пункт был бы не пунктом, а следом форматирования."""
        собранные: list[str] = []
        for строка in self.раздел(имя).splitlines():
            очищенная = строка.strip()
            if not очищенная:
                continue
            if очищенная.startswith("- "):
                очищенная = очищенная[2:].strip()
            elif очищенная == "-":
                continue
            if очищенная:
                собранные.append(очищенная)
        return собранные


def разобрать(текст: str) -> Документ:
    """Разбирает текст документа. Заголовок необязателен, разделы необязательны.

    Текст между заголовком и первым разделом отбрасывается: место для него форматом не
    предусмотрено, а придумывать ему хранилище значило бы завести шестой раздел, о котором
    никто не знает.
    """
    # Отметка порядка байтов в начале файла — след правки чужим средством; без её снятия
    # первая строка не равна границе, и заголовок целиком читался бы как ничто.
    строки = текст.lstrip("\ufeff").splitlines()
    заголовок: dict[str, str] = {}
    начало = 0
    # Пустые строки перед заголовком пропускаем: одна лишняя пустая строка впереди — самый
    # частый след ручной правки, и терять из-за неё весь заголовок значило бы наказывать
    # человека за то, ради чего формат и выбран.
    первая = 0
    while первая < len(строки) and not строки[первая].strip():
        первая += 1
    строки = строки[первая:]
    if строки and строки[0].strip() == ГРАНИЦА:
        # Ищем закрывающую границу. Не нашли — заголовка нет вовсе: считать остаток файла
        # заголовком значило бы потерять всё тело из-за одной лишней строки «---».
        конец = None
        for номер in range(1, len(строки)):
            if строки[номер].strip() == ГРАНИЦА:
                конец = номер
                break
        if конец is not None:
            for строка in строки[1:конец]:
                ключ, разделитель, значение = строка.partition(":")
                if not разделитель:
                    continue
                имя = ключ.strip()
                if имя:
                    # Двоеточие внутри значения сохраняется: `partition` режет по первому.
                    заголовок[имя] = значение.strip()
            начало = конец + 1

    собранные: list[list[str]] = []          # [имя, тело] в порядке первого появления
    места: dict[str, int] = {}               # очищенное имя → место в списке
    имя: str | None = None
    тело: list[str] = []

    def сложить(имя: str, тело: list[str]) -> None:
        """Кладёт раздел, приклеивая тело к одноимённому, если он уже встречался.

        Повтор заголовка — обычный исход ручной правки: человек дописал раздел в конец, не
        заметив, что такой уже есть. Читай мы только первый, второй не увидел бы никто, а
        следующая запись стёрла бы его молча."""
        ключ = имя.strip().casefold()
        текст_тела = "\n".join(тело).strip("\n")
        место = места.get(ключ)
        if место is None:
            места[ключ] = len(собранные)
            собранные.append([имя, текст_тела])
            return
        прежнее = собранные[место][1]
        собранные[место][1] = f"{прежнее}\n{текст_тела}".strip("\n") if прежнее else текст_тела

    for строка in строки[начало:]:
        if строка.startswith(НАЧАЛО_РАЗДЕЛА):
            if имя is not None:
                сложить(имя, тело)
            имя = строка[len(НАЧАЛО_РАЗДЕЛА):].strip()
            тело = []
        elif имя is not None:
            тело.append(строка)
    if имя is not None:
        сложить(имя, тело)
    return Документ(
        заголовок=заголовок,
        разделы=[(название, тело_раздела) for название, тело_раздела in собранные],
    )


def собрать(заголовок: Mapping[str, str], разделы: Iterable[tuple[str, str]]) -> str:
    """Собирает документ обратно в текст. Порядок ключей и разделов сохраняется.

    Пустые разделы пишутся, а пустые значения заголовка — нет. Разница намеренная: пустой
    раздел показывает человеку, куда писать, а пустая строка заголовка не показывает ничего
    и при следующем чтении вернётся пустым значением, неотличимым от незаполненного.
    """
    куски: list[str] = []
    пары = [(ключ, значение) for ключ, значение in заголовок.items() if str(значение).strip()]
    if пары:
        куски.append(ГРАНИЦА)
        куски.extend(f"{ключ}: {значение}" for ключ, значение in пары)
        куски.append(ГРАНИЦА)
        куски.append("")
    for имя, тело in разделы:
        куски.append(f"{НАЧАЛО_РАЗДЕЛА}{имя}")
        очищенное = тело.strip("\n")
        if очищенное:
            куски.append(очищенное)
        куски.append("")
    # Хвостовые пустые строки не копим: файл кончается ровно одним переводом строки.
    while куски and куски[-1] == "":
        куски.pop()
    return "\n".join(куски) + "\n"
