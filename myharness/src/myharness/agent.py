@dataclass(frozen=True)
class Якорь:
    """Снимок состояния памяти на тот миг, когда из неё сняли пары для сжатия.

    Заготовка описывает НЕ ЧИСЛО ПАР, а конкретные пары — те, что лежали в памяти, когда
    фоновая задача их снимала. Сдвинься память между снятием и принятием (обрезка успела
    выбросить блок, человек отдал `/clear`), и пересказ приписался бы ДРУГИМ парам молча:
    числа сошлись бы, а речь в выжимке шла бы о другом куске разговора.

    Двух чисел довольно, и оба обязательны. Счёт пройденных пар растёт ровно тогда, когда
    пары уходят из памяти навсегда, — то есть ловит любой сдвиг СТАРОГО края памяти, за
    который заготовка и отвечает. Поколение ловит очистку разговора, при которой счёт
    обнуляется и сам по себе ничего не сказал бы. Пополнение памяти новой парой не трогает
    ни то, ни другое — и правильно: старые пары от него не сдвигаются.

    Снимается якорь ВМЕСТЕ с парами, одним вызовом `снять_для_сжатия`, и только им: возьми
    фоновая задача пары в одну секунду, а якорь в другую — сверять было бы нечего, потому что
    якорь описывал бы не тот миг, из которого взяты пары.
    """

    пройдено: int
    поколение: int


@dataclass
class Ограничитель:
    """Один ограничитель обрезки, измеренный в СВОИХ единицах: сколько набрано из скольких.

    Заведён затем, чтобы «который сработает первым» считалось в ОДНОМ месте. Считающих
    двое — заготовка выжимки и полоска занятости над строкой ввода, — и разойдись они хоть
    в правиле выбора, отметка на восьми десятых стояла бы не там, где что-то происходит.

    Единицы не приводятся к общей мерке намеренно: пересчитать пары в токены можно, а обратно
    — нет, и «9 из 15 пар» человеку понятнее любой пересчитанной доли. Сравнимой величиной
    остаётся только ДОЛЯ — сколько пути до срабатывания пройдено.
    """

    имя: str
    единицы: str  # «пар» или «токенов» — ими подписаны числа в строке под полоской
    текущее: int
    порог: int

    @property
    def доля(self) -> float:
        """Сколько пути до срабатывания пройдено — число от нуля до единицы.

        За единицу не уходит: доля отвечает «сколько пройдено», а пройденного больше, чем
        весь путь, не бывает. Насколько запрос ушёл СВЕРХ порога, говорит `перебор` — двумя
        числами, а не одним, потому что заполнение полоски и величина перебора отвечают на
        разные вопросы, и слив их в одно число, полоску пришлось бы рисовать длиннее жёлоба.
        """
        if self.порог <= 0:
            return 0.0
        return min(1.0, self.текущее / self.порог)

    @property
    def перебор(self) -> int:
        """На сколько уже ушли сверх порога; ноль — ещё не ушли."""
        return max(0, self.текущее - self.порог)


def usage_tokens(usage: dict[str, Any] | None) -> int:
    """Сколько токенов стоил обмен по данным `usage`.

    Считать нечем — считаем нулём, а не падаем: `usage` приходит от сервера, и при обрыве
    потока или отказе его может не быть вовсе. Уронить на этом сбор статистики значило бы
    потерять и сам ответ, который уже получен.

    `total_tokens` предпочитаем сумме слагаемых: сервер кладёт туда собственный итог, и он
    учитывает то, чего в двух слагаемых нет, — например попадания в кэш начала запроса."""
    # Разбор `usage` живёт в одном месте — `tokens.normalize`. Своя копия правила была
    # здесь до появления модуля счёта и успела разойтись с ним на кривых данных: при
    # `total_tokens: 0` с непустыми слагаемыми она давала ноль, при `total_tokens: true` —
    # единицу (в Python `True` это `1`). В списке агентов рядом со строкой ожидания вставало
    # «Σ 0», и человек шёл искать поломку в учёте, которой нет.
    return tokens.normalize(usage)["total_tokens"]


@dataclass
class Turn:
    """Итог одного обмена с моделью — тем, кто позвал: тексту ответа и цене.

    Запись полная: по ней видно не только что ответила модель, но и что именно ей
    ушло, — вызывающему не приходится лезть внутрь агента за подробностями."""

    status: str
    text: str = ""
    reasoning: str = ""
    finish_reason: str | None = None
    usage: dict[str, Any] = field(default_factory=dict)
    elapsed_ms: int = 0
    error: str | None = None
    # что фактически ушло в модель — иначе прогон не воспроизвести и не сверить
    request_messages: list[dict] = field(default_factory=list)
    # какой моделью получен ответ: модель меняется на лету, а запись остаётся
    model: str = ""
    # слепок профиля для журнала — инструкция и параметры на момент запроса
    profile_snapshot: dict[str, Any] = field(default_factory=dict)
    # сколько пар выброшено окном памяти перед этим запросом — чтобы показать усечение
    dropped_pairs: int = 0
    # Из них: сколько пар заменено выжимкой и сколько потеряно ДОСЛОВНО. Два числа, а не
    # одно, потому что это два разных исхода с разной ценой: замена дословного текста
    # пересказом заметна по ответам, но необъяснима, если о ней не сказали, — а дословная
    # потеря невозвратна. По этой паре чисел человек и решает, звать ли сжатие руками.
    compacted_pairs: int = 0
    forgotten_pairs: int = 0
    # Сколько пар ПРОЙДЕНО разговором на этот момент: обе потери вместе, за всю его жизнь.
    # Третье число, а не разность двух первых: те описывают один ход, а человеку надо знать,
    # сколько разговора уже стоит за выжимкой. По ходовым числам это не восстановить.
    passed_pairs: int = 0
    # какой это по счёту обмен в сеансе — по нему кривая расхода строится без домыслов
    index: int = 0
    # сколько весила память на момент ЭТОГО запроса: цена того, что агент помнит
    history_tokens: int = 0
    # предсказание веса запроса, сделанное ДО отправки: рядом с настоящим `usage` по нему
    # видно, насколько предсказание врёт, — иначе судить о точности счёта было бы не по чему
    predicted_prompt: int = 0
    # расход сеанса нарастающим итогом на конец этого обмена
    # Расход ЭТОГО агента за сеанс — не итог сеанса целиком: агент про соседей не знает.
    # Имя названо по смыслу, чтобы не спутать с общим итогом на экране и в /tokens.
    agent_session_tokens: int = 0
    # предел веса задан, обрезка сделала что могла, а запрос всё равно ушёл тяжелее предела
    over_budget: bool = False
    # текст ошибки записи журнала: сам обмен удался, а предупредить надо снаружи
    journal_error: str | None = None
    # то же самое про запись разговора на диск: обмен состоялся и оплачен, а память между
    # запусками не сохранилась — молчать об этом нельзя, ронять обмен из-за этого тоже
    store_error: str | None = None

    @property
    def ok(self) -> bool:
        return self.status == "ok"


class Agent:
    """Собеседник со своей памятью: имя, профиль и накопленные пары «вопрос — ответ»."""

    def __init__(
        self,
        name: str,
        profile: Profile,
        *,
        store: memory.SessionStore | None = None,
        facts: Callable[[], list[str]] | None = None,
    ) -> None:
        self.name = name
        self.profile = profile
        # Хранилище разговора между запусками. Умолчание — ВЫКЛЮЧЕНО, и это не осторожность,
        # а необходимость: агентов в процессе много, а разговор пользователя один. Наряд из
        # ста заданий и панели исполнителей группы, заведи они хранилище сами, писали бы в
        # каталог состояния наперегонки поверх переписки человека.
        self._store = store
        # Глобальные факты о пользователе — ВЫЗЫВАЕМЫЙ объект, а не готовый список. Факты
        # меняются по ходу сеанса (командой `/remember` и архивариусом), и список, снятый
        # при создании агента, отстал бы от них к первому же запросу.
        self._facts = facts
        # Идёт загрузка прежнего разговора: пополнение памяти на диск не пишется. Иначе
        # чтение файла тут же переписывало бы его самим собой, удваивая каждую пару.
        self._restoring = False
        # Чем кончилась последняя попытка записи разговора на диск. Поле, а не исключение:
        # хранилище — вспомогательный механизм, и ронять им уже оплаченный обмен нельзя.
        self.store_error: str | None = None
        self._messages: list[dict] = []
        # Выжимка — пересказ пройденного куска разговора, который встаёт в системную часть
        # запроса вместо выброшенных обрезкой пар. Заводится и хранится СНАРУЖИ (фоновой
        # задачей сжимателя, файлом рядом с разговором), сюда приходит готовой: агент про
        # сеть и диск не знает и знать не должен.
        self._summary: compact.Выжимка | None = None
        # Заготовка: выжимка, собранная заранее — при подходе к ближайшему ограничителю. Она
        # ждёт своего часа отдельно от действующей и встаёт на её место в тот момент, когда
        # обрезка что-то выбросила. Готовить заранее нужно потому, что иначе человек ждал бы
        # лишний обмен ровно тогда, когда разговор уже длинный и ответы и так идут дольше.
        self._prepared: compact.Выжимка | None = None
        # сколько пар выбросила обрезка перед последней сборкой запроса — отсюда в `Turn`
        self._dropped_pairs = 0
        # из них: сколько подобрано выжимкой и сколько потеряно дословно — туда же
        self._compacted_pairs = 0
        self._forgotten_pairs = 0
        # Сколько пар ушло из памяти НАВСЕГДА за всю жизнь этого разговора — и пересказанных,
        # и забытых дословно. Копится, а не считается по памяти: в памяти их уже нет, а
        # человеку по этому числу видно, сколько разговора стоит за выжимкой.
        self.passed_pairs = 0
        # не удержался ли последний запрос в пределе веса — оттуда же в `Turn` и в журнал
        self._over_budget = False
        # Поколение памяти: `forget` его увеличивает. Обмен запоминает поколение в начале и
        # пополняет память, только если оно не сменилось. Без этого счётчика `/clear`,
        # отданный посреди идущего обмена, «очищал» бы память на словах: обмен доходит до
        # своего `finally` уже после команды и кладёт пару обратно.
        self._generation = 0
        # Счётчики за всё время жизни агента: их показывает список агентов под строкой ввода.
        # СЧИТАЕМ И НЕУДАЧНЫЕ, И ОТМЕНЁННЫЕ ОБМЕНЫ — это не недосмотр, а решение.
        # Время на упавший запрос потрачено, токены на него у поставщика списаны, и список,
        # показывающий только удачные обмены, рисует агента дешевле, чем он есть.
        # Дороже всего обходится как раз агент, который падает и уходит на повтор.
        self.runs = 0  # сколько обменов было — всего, при любом исходе
        self.total_ms = 0  # сколько времени на них ушло
        self.total_tokens = 0  # сколько токенов израсходовано
        # Расход ТЕКУЩЕГО сеанса, покомпонентно: вход, выход, попадания в кэш, рассуждения.
        # Заведён рядом с `total_tokens`, а не вместо него: на том счётчике держится колонка
        # списка агентов, и подменить его разбивкой значило бы тихо сменить смысл колонки.
        # Разбивка нужна там, где считают деньги: вход из кэша стоит в тридцать раз дешевле
        # промаха, и по одной сумме цену не назвать.
        # Пустым словарём не заводим, хотя до первого обмена расходовать было нечего: форма
        # у накопителя обязана быть одна и та же с первой секунды. Иначе строка ожидания и
        # `/tokens`, спросив `session_usage["total_tokens"]` на чистом запуске, получили бы
        # `KeyError` — причём не на проверках, а у человека сразу после старта.
        self.session_usage: dict[str, int] = tokens.total_usage([])
        # Надбавка обёртки разговора: сколько токенов сервер прибавляет к тексту реплик.
        # 83 — живой замер 2026-09-09, то есть начальное приближение, а не закон: DeepSeek
        # вправе изменить обёртку, ничего нам не сказав, и тогда предсказание начнёт врать
        # молча. Поэтому после каждого обмена, где сервер назвал `prompt_tokens`, число
        # подстраивается под него. Калибровка живёт на агенте и только на сеанс, в файл не
        # пишется: сохранённое число пережило бы и смену профиля, а характер запросов у
        # профилей разный — вышла бы уверенная ложь вместо честного приближения.
        #
        # Хранится ПО МОДЕЛЯМ, а не одним числом, по двум причинам сразу. Первая: модель
        # меняется на лету командой `/model`, и надбавка, снятая на `v4-pro`, к
        # `flash-vision-exp` отношения не имеет. Вторая важнее: в это число оседает не только
        # обёртка, но и вся систематическая разница нашего счёта с серверным, а она растёт с
        # длиной запроса — расхождение в 2% на разговоре в 8000 токенов даёт надбавку под 250
        # вместо 83. Смешай такую поправку между моделями — и короткий вопрос к другой модели
        # предсказывался бы втрое дороже, чем стоит.
        self._overhead: dict[str, int] = {}
        # Сколько пар поднято с диска при запуске. Обмен, которому предшествовал подъём
        # прежнего разговора, стоит дороже обмена с чистой памятью, и по записи прогона
        # должно быть видно, откуда взялся такой вход, — иначе кривая расхода необъяснима.
        self.restored_pairs = 0
        # Над чем агент работает: содержание последнего запроса. Список агентов показывает
        # это в колонке занятия, пока агент занят. Держим здесь, а не в панели: работу знает
        # тот, кто её делает, и агент без панели (пакетный наряд) знает её точно так же.
        self.task = ""

    def set_store(self, store: memory.SessionStore | None) -> None:
        """Сменить хранилище разговора — например, когда `/clear` открывает новую сессию.

        Отдельный метод, а не открытое поле: тогда место, где хранилище появляется и
        исчезает, одно, и его видно в дереве вызовов."""
        self._store = store

    def history(self) -> list[dict]:
        """Память разговора — копией.

        Отдай сам список — и любой снаружи сможет незаметно дописать или стереть память
        агента, минуя `remember`. Тогда инкапсуляция перестаёт что-либо значить: правил
        пополнения памяти больше нет, а искать, кто её испортил, придётся по всему коду."""
        return [dict(m) for m in self._messages]

    def выжимка(self) -> compact.Выжимка | None:
        """Действующая выжимка — та, что уходит в системную часть запроса.

        Метод, а не открытое поле, по той же причине, что и `history`: подмена выжимки —
        событие того же веса, что и подмена памяти, и мест, где оно происходит, должно быть
        ровно столько, сколько видно в дереве вызовов.
        """
        return self._summary

    def запомнить_выжимку(self, готовая: compact.Выжимка | None) -> None:
        """Поставить выжимку действующей — при подъёме разговора с диска или ручном сжатии."""
        self._summary = готовая

    def заготовка(self) -> compact.Выжимка | None:
        """Заготовка, ждущая ближайшей обрезки; `None` — заготовки нет."""
        return self._prepared

    def снять_для_сжатия(self, пар: int) -> tuple[list[tuple[str, str]], Якорь]:
        """Самые старые `пар` пар памяти и якорь её состояния — снятые ОДНИМ мигом.

        Единственный способ получить якорь, и это главное в устройстве: подделать его нельзя
        не потому, что он спрятан, а потому, что годным его делает совпадение с нынешним
        состоянием агента — тем самым, при котором заготовку и надо принять. Возьми фоновая
        задача пары здесь, а якорь отдельным вызовом позже — и сверка потеряла бы смысл,
        подтверждая не «память не двигалась», а «на момент второго вызова не двигалась».

        Пары отдаются копией и с проверкой чередования ролей: непарного хвоста в памяти не
        бывает (`remember` кладёт обе половины разом), но складывать пары из списка нечётной
        длины значило бы приписать вопросу чужой ответ — и это уехало бы в пересказ.
        """
        пары: list[tuple[str, str]] = []
        for номер in range(0, min(пар * 2, len(self._messages)) - 1, 2):
            вопрос, ответ = self._messages[номер], self._messages[номер + 1]
            if вопрос["role"] == "user" and ответ["role"] == "assistant":
                пары.append((вопрос["content"], ответ["content"]))
        return пары, self._якорь()

    def _якорь(self) -> Якорь:
        """Якорь нынешнего состояния памяти — одно место, где он собирается."""
        return Якорь(self.passed_pairs, self._generation)

    def принять_заготовку(self, готовая: compact.Выжимка | None, *, якорь: Якорь) -> None:
        """Положить заготовку, собранную фоновой задачей.

        Действующей выжимкой она НЕ становится: пока обрезка ничего не выбросила, заменять
        нечего, а подставь мы её сразу — в запросе оказались бы разом и пересказ пар, и сами
        эти пары, то есть один и тот же кусок разговора дважды и за двойные деньги.

        Агент без хранилища разговора заготовку не принимает вовсе, и заслон стоит ИМЕННО
        ЗДЕСЬ — в одном месте, а не в двух. Так «сжатие доступно только агенту с хранилищем»
        становится свойством самого агента, а не обещанием того, кто его заводит. Цена
        ошибки денежная: наряд из ста заданий завёл бы сто сжимателей, каждый со своим
        запросом на дорогой модели, а класть получившиеся выжимки было бы некуда — файл
        выжимки лежит рядом с файлом сессии, которого у такого агента нет.

        Якорь сверяется здесь и только здесь: память могла сдвинуться, пока фоновая задача
        ходила к модели, и тогда заготовка описывает не то, что в памяти лежит теперь.
        Несовпадение — это ВЫБРОС заготовки, а не откладывание: пары, под которые она
        собрана, уже ушли, и дождавшись своего часа, она приписала бы пересказ чужим парам.

        Отпечаток инструкции — та же история и тот же исход: заготовка с чужим отпечатком
        выбрасывается, а не ждёт возврата прежней роли. РАЗНИЦА С ПРИМЕНЁННОЙ ВЫЖИМКОЙ здесь
        неочевидна, и стирать её нельзя: `_summary` при несовпавшем отпечатке НЕ выбрасывается
        — её просто не подставляют, потому что собрана она за деньги, а роль могут вернуть.
        Заготовка же ещё не применена, и её пары ЛЕЖАТ В ПАМЯТИ дословно — пока она ждёт, их
        выбросит обрезка, и ждать станет незачем.
        """
        if self._store is None or якорь != self._якорь() or not self._подставляется(готовая):
            return
        self._prepared = готовая

    def forget(self) -> None:
        """Забыть разговор целиком — например, когда сменился профиль.

        Смена поколения — не украшение: команда `/clear` исполняется немедленно, мимо очереди
        запросов, и запросто попадает в середину идущего обмена. Тот обмен свой результат в
        память после этого не вернёт (см. `exchange`) — это и есть смысл слова «забудь».

        Счёт поднятых с диска пар обнуляется вместе с памятью: после `/clear` поднятого не
        осталось ни одной пары, а записи прогонов продолжали бы уверять, что обмену
        предшествовал подъём разговора, — и объяснять расход было бы нечем.

        Выжимка живёт ровно столько, сколько разговор, и уходит вместе с ним — вместе с
        заготовкой. Оставь заготовку — и выжимка стёртого разговора вернулась бы при первой
        же обрезке, уже после того, как человеку сказали «забыто». Идущую фоновую задачу это
        не отменяет и отменять не может: её итог отсекается сверкой поколения на стороне
        того, кто её завёл."""
        self._messages.clear()
        self._generation += 1
        self.restored_pairs = 0
        self._summary = None
        self._prepared = None
        # Счёт пройденного обнуляется вместе с разговором: пройденное принадлежит ЕМУ, а не
        # агенту. Оставь число — и новый разговор с первого же хода уверял бы, что за ним
        # стоят десять пар пересказа, которых нет ни в выжимке, ни на диске.
        self.passed_pairs = 0

    def remember(self, question: str, answer: str, *, model: str = "") -> None:
        """Положить в память готовую пару «вопрос — ответ» и сохранить её на диск.

        ЕДИНСТВЕННАЯ точка записи в память. `exchange` и восстановление пополняют память
        тоже через этот метод, а не напрямую через `self._messages`, — второй точки записи
        заводить нельзя, иначе правила пополнения снова разъедутся по разным местам.

        Раз точка одна — здесь же и запись на диск, со всеми тремя условиями сразу.

        `keep_history` проверяется ИМЕННО ЗДЕСЬ, а не у вызывающего. Вызывающих двое:
        `exchange` эту проверку делал, `output.deliver` — нет, и профиль с выключенной
        историей завёл бы на диске разговор, которого нет ни в одном запросе к модели:
        `build_messages` память такого профиля не берёт.

        Пометки кладутся на ответ, а не на вопрос: через месяц по файлу должно быть видно,
        каким профилем и какой моделью получен ответ и не правили ли с тех пор инструкцию.
        У вопроса такого прошлого нет — его написал человек."""
        self._messages.append({"role": "user", "content": question})
        self._messages.append({"role": "assistant", "content": answer})
        if self._store is None or self._restoring or not self.profile.keep_history:
            return
        # Ошибку берём первую: причина у обеих строк одна и та же (нет прав, нет места), и
        # второй раз повторять её человеку незачем.
        ошибка = self._store.append("user", question)
        ошибка = ошибка or self._store.append(
            "assistant",
            answer,
            {
                "profile": self.profile.name,
                "model": model,
                "system_fp": memory.fingerprint(self.profile.system),
            },
        )
        self.store_error = ошибка

    def restore(self, pairs: list[tuple[str, str]]) -> None:
        """Поднять прежний разговор — тем же единственным методом пополнения.

        Запись на диск на время загрузки выключена: пары пришли из того самого файла, и
        сохранять их обратно значило бы удваивать разговор при каждом запуске.

        Признак снимается в `finally`: сорвись загрузка на середине — и агент до конца
        сеанса молча не писал бы на диск ничего, а обнаружилось бы это только при следующем
        запуске, когда разговора на месте не окажется."""
        self._restoring = True
        try:
            for question, answer in pairs:
                self.remember(question, answer)
                # Считаем ПОСЛЕ пополнения памяти: сорвись загрузка на этой паре — и в счёте
                # оказалась бы пара, которой в памяти нет.
                self.restored_pairs += 1
        finally:
            self._restoring = False

    def history_tokens(self) -> int:
        """Вес памяти в токенах — то, что уйдёт в следующий запрос помимо всего прочего.

        Ни системной инструкции, ни нового вопроса, ни надбавки обёртки здесь нет: это цена
        того, что агент помнит, и по ней человек решает, пора ли звать `/clear`. Подмешай
        сюда инструкцию — и число перестало бы отвечать на вопрос, ради которого заведено.

        У профиля с выключенной историей вес нулевой, сколько бы пар в памяти ни лежало:
        `build_messages` эту память в запрос не кладёт. Считай её здесь — и журнал уверял бы,
        что обмен из одной реплики тащил за собой две тысячи токенов памяти, а по такому
        числу человек полез бы чистить разговор, который ни на что не влияет.

        Реплики с нетекстовым содержимым пропускаем: сегодня их в памяти не бывает (пары
        кладёт `remember`, и обе половины у него строки), но счёт токенов — удобство, и
        ронять на нём весь harness нельзя даже ради собственной уверенности."""
        if not self.profile.keep_history:
            return 0
        return sum(
            tokens.count_text(m["content"]) for m in self._messages if isinstance(m.get("content"), str)
        )

    def overhead(self, model: str) -> int:
        """Надбавка обёртки для этой модели: подстроенная, если её уже мерили, иначе замер.

        Незнакомая модель получает базовое значение, а не поправку соседа: надбавка тянет в
        себе систематическую разницу счёта, и у другой модели она другая."""
        return self._overhead.get(model, tokens.BASE_OVERHEAD)

    def _система(self, факты: str) -> str:
        """Собрать системную часть из готового блока фактов: инструкция, факты, выжимка.

        Порядок задан требованием и стоит денег буквально. Попадание в кэш поставщика
        ломается начиная с точки изменения и до конца запроса, а выжимка — самая изменчивая
        часть системного сообщения: она меняется при каждом сжатии. Поставь её раньше фактов
        — и каждое пересжатие выбрасывало бы из кэша ещё и блок фактов, который не менялся, а
        вход из кэша дешевле промаха в тридцать раз.

        Блок фактов приходит ГОТОВЫМ, а не читается здесь: источник фактов живёт снаружи и
        ходит на диск, а эту сборку взвешивание зовёт столько раз, сколько блоков выбросит
        обрезка. Один запрос человека оборачивался бы тремя чтениями диска.

        Подставлять ли выжимку — решает `_блок_выжимки`, одно место на все поводы отказа
        (её нет, сжатие выключено, отпечаток инструкции разошёлся). Здесь остаётся только
        порядок.
        """
        куски = [кусок for кусок in (self.profile.system or "", факты, self._блок_выжимки()) if кусок]
        return "\n\n".join(куски)

    def _подставляется(self, выжимка: compact.Выжимка | None) -> bool:
        """Пойдёт ли ЭТА выжимка в системную часть запроса.

        Один предикат на все места, где спрашивают одно и то же: сборка системной части,
        признак отказа для ленты и применение заготовки при обрезке. Разведи их — и заготовка
        применилась бы там, где блок в запрос не идёт: человеку сказали бы «пять пар заменены
        пересказом», а модель не увидела бы ни пересказа, ни самих пар.

        Отпечаток сверяется у ТОЙ выжимки, о которой спрашивают, а не у действующей: заготовка
        собрана под инструкцию, действовавшую в момент её сборки, и та могла смениться, пока
        фоновая задача ходила к модели.
        """
        return (
            выжимка is not None
            and self.profile.compact_at > 0
            and выжимка.system_fp == memory.fingerprint(self.profile.system)
        )

    def выжимка_отвергнута(self) -> bool:
        """Есть ли выжимка, которую мы НЕ подставляем из-за несовпавшего отпечатка инструкции.

        Наружу — потому что решение принимает агент, а сказать о нём человеку обязан
        интерфейс: молча пропавший кусок памяти отлаживается как «модель отвечает не на то»,
        и час уходит на поиск поломки, которой нет. То же правило, что у строки о правке
        инструкции между запусками.

        Выключенное сжатие сюда не попадает: там выжимки нет не потому, что она не подошла, а
        потому, что человек сам выключил механизм, — и строка об этом была бы шумом.
        """
        return (
            self._summary is not None
            and self.profile.compact_at > 0
            and not self._подставляется(self._summary)
        )

    def _блок_выжимки(self) -> str:
        """Блок выжимки для системной части — либо пустая строка, если подставлять нельзя.

        Единственное место, где решается «подставляем или нет», и решается по трём поводам
        сразу: выжимки нет, сжатие выключено, отпечаток инструкции разошёлся. Разведи их по
        разным местам — и однажды взвешивание посчитало бы блок, которого в запросе не будет.

        Отпечаток проверяется потому, что выжимка — прочтение разговора КОНКРЕТНОЙ ролью, а
        не протокол: смени инструкцию, и пересказ прежней роли продолжил бы влиять на ответы
        новой, причём молча. Сама выжимка при этом не выбрасывается: инструкцию могут вернуть
        назад, а собрана выжимка за деньги.
        """
        if not self._подставляется(self._summary):
            return ""
        return self._summary.блок()

    def system_text(self) -> str:
        """Системная часть запроса целиком: инструкция, блок глобальных фактов, блок выжимки.

        Нужна снаружи затем, чтобы показ и предупреждение о переполнении считали ТО ЖЕ, что
        уйдёт в модель. Сборка запроса эту часть собирает сама, но звать её ради взвешивания
        нельзя: `build_messages` обрезает память, то есть меняет состояние.

        Ошибку чтения фактов здесь глотаем: это взвешивание, а не отправка, и падать на нём
        нельзя — настоящую жалобу человек всё равно получит при сборке запроса.
        """
        block = ""
        if self._facts is not None:
            try:
                block = memory.facts_block(self._facts())
            except Exception:  # noqa: BLE001 — источник фактов приходит снаружи
                block = ""
        return self._система(block)

    def порог_сжатия(self) -> int:
        """Порог сжатия в токенах: доля окна модели, заданная профилем. Ноль — выключено.

        Доля, а не число токенов в профиле, потому что вопрос, на который отвечает порог, —
        «много ли занято от ОКНА». Модель здесь не спрашивается: у всех моделей DeepSeek окно
        одно и то же, и `tokens.CONTEXT_WINDOW` — это оно. Появится модель с другим окном —
        число придётся брать у неё, и метод получит имя модели доводом; сегодня такой модели
        нет, и заводить довод, который некому передать, значило бы обещать несуществующее.

        Прежний аварийный потолок памяти в знаках занимал место этого ограничителя и был
        снят: он мерил ЗНАКИ там, где считают токены, и взвешивал одну накопленную историю
        без нового вопроса — то есть на своём единственном случае («человек вставил файл в
        вопрос») опаздывал ровно на ход, когда деньги уже потрачены.
        """
        доля = self.profile.compact_at
        if доля <= 0:
            return 0
        return int(доля * tokens.CONTEXT_WINDOW)

    def ограничители(self, content: str, *, facts: str, model: str = "") -> list[Ограничитель]:
        """Действующие ограничители обрезки, каждый со своей долей заполнения.

        Наружу — потому что считающих двое: заготовка выжимки заводится при подходе к
        ближайшему, и полоска занятости над строкой ввода рисуется по нему же. Спрячь этот
        счёт внутри обрезки — и второе место доопределило бы правило по-своему, а отметка на
        восьми десятых стояла бы не там, где что-то происходит.

        Порядок списка — тот же, в каком ограничители режут память в `_trim`. На него
        опирается выбор ближайшего при равных долях: раз доли сравнялись, честнее назвать
        того, кто сработает раньше.

        Вес считается ОДИН раз на оба весовых ограничителя: он стоит прохода по словарю
        токенов, а полоска пересчитывается на каждое нажатие клавиши.

        Выключенный ограничитель в список не попадает вовсе: полоска, привязанная к
        выключенному окну, мерила бы дорогу к событию, которого не будет.

        Блок фактов приходит ДОВОДОМ, и это не удобство вызывающего, а запрет: источник фактов
        ходит на диск, а на этом методе стоит полоска занятости, пересчитываемая на каждое
        нажатие клавиши. Читай его здесь — и каждая набранная буква оборачивалась бы обходом
        каталога памяти с чтением файлов. Обязательный довод, а не умолчание: забытый блок
        фактов молча занизил бы вес, а по весу режется память.
        """
        список: list[Ограничитель] = []
        окно = self.profile.history_window
        if окно > 0:
            список.append(
                Ограничитель(ОКНО_ПО_ПАРАМ, "пар", len(self._messages) // 2, окно + WINDOW_SLACK_PAIRS)
            )
        # У профиля с выключенной историей порог сжатия не действует: память в запрос не
        # идёт, сжимать нечего, и обрезка его не применяет — см. `_trim`.
        порог = self.порог_сжатия() if self.profile.keep_history else 0
        предел = self.profile.budget_tokens
        if порог > 0 or предел > 0:
            вес = self._вес(content, facts, model)
            if порог > 0:
                список.append(Ограничитель(ПОРОГ_СЖАТИЯ, "токенов", вес, порог))
            if предел > 0:
                список.append(Ограничитель(ПРЕДЕЛ_ВЕСА, "токенов", вес, предел))
        return список

    def ближайший_ограничитель(self, content: str, *, facts: str, model: str = "") -> Ограничитель | None:
        """Тот, что сработает ПЕРВЫМ, — по наибольшей доле заполнения. `None` — ни одного.

        Сравниваются доли, а не величины: общего знаменателя у пар и токенов нет и быть не
        может — пары в токены переводятся, обратно нет. Доля есть у каждого своя, и она
        отвечает ровно на нужный вопрос: сколько пути до срабатывания пройдено.
        """
        список = self.ограничители(content, facts=facts, model=model)
        if not список:
            return None
        return max(список, key=lambda ограничитель: ограничитель.доля)

    def predict_tokens(self, messages: list[dict], model: str = "") -> int:
        """Предсказание веса запроса — с надбавкой, подстроенной ЭТИМ агентом под ЭТУ модель.

        Метод агента, а не прямой вызов `tokens.count_messages` у вызывающего: надбавка
        живёт здесь и меняется по ходу сеанса, и второе место, где её берут, разъехалось бы
        с первым на первом же обмене.

        Модель без имени берёт базовый замер — так отвечает и `overhead`. Умолчание оставлено
        ради вызывающих, которым модель неизвестна (предпросмотр запроса до выбора модели):
        подставить им чужую поправку было бы хуже, чем честное приближение."""
        return tokens.count_messages(messages, overhead=self.overhead(model))

    def _preview(self, content: str, system: str) -> list[dict]:
        """Каким выйдет запрос при нынешней памяти — чтобы взвесить его в обрезке.

        Системная часть приходит готовой — с блоком фактов и блоком выжимки, — а не
        собирается здесь. Причина в двух требованиях сразу, и оба обязательны. Первое:
        взвешивать надо РОВНО ТО, что уйдёт в модель, — недосчитай блок фактов или блок
        выжимки, и обрезка решит «влезает» там, где не влезает, а запрос уйдёт тяжелее
        бюджета, то есть предел не сработает ровно там, ради чего заведён. Второе: источник
        фактов живёт снаружи и ходит на диск, а взвешивание зовут столько раз, сколько блоков
        выброшено, — читать его на каждом витке нельзя. Оба выполняются, если блок фактов
        прочесть один раз до обрезки; этим и занят `build_messages`.

        Память берётся по тому же условию, что и там: профиль с выключенной историей её в
        запрос не кладёт, а значит и в вес она не входит. Считай её здесь безусловно — и
        бюджет выбрасывал бы пары, которых в запросе нет вовсе."""
        preview: list[dict] = []
        if system:
            preview.append({"role": "system", "content": system})
        if self.profile.keep_history:
            preview.extend(self._messages)
        preview.append({"role": "user", "content": content})
        return preview

    def _вес(self, content: str, facts: str, model: str) -> int:
        """Предсказанный вес будущего запроса при нынешней памяти и нынешней выжимке.

        Системная часть пересобирается на каждый замер намеренно: посреди обрезки заготовка
        может стать действующей выжимкой, а это меняет системное сообщение — то есть вес.
        Считай мы по системной части, снятой до обрезки, — оставшиеся ограничители мерили бы
        запрос легче того, что уйдёт в модель, и предел молча не сработал бы. Дорого это не
        обходится: чтение фактов уже сделано (`facts` приходит готовым), а счёт токенов
        одного и того же текста берётся из запомненного.
        """
        return self.predict_tokens(self._preview(content, self._система(facts)), model)

    def _выбросить(self, требуется: int) -> int:
        """Выбросить старейшие пары — не меньше, чем требует ограничитель. Возвращает сколько.

        ЕДИНСТВЕННОЕ место, где пары уходят из памяти, и единственное, где заготовка
        становится действующей выжимкой. Одно, потому что эти два решения связаны намертво:
        сколько выбросить, зависит от того, на сколько пар собрана заготовка.

        Правило — `max(требует ограничитель, покрывает заготовка)`. Ограничитель говорит «уйти
        должно не меньше пяти», заготовка говорит «я собрана на восемь» — уходят восемь. Иначе
        пары с шестой по восьмую уехали бы в модель ДВАЖДЫ: пересказом в системной части и
        дословно в памяти, — мы платили бы за них два раза, а модель видела бы один обмен в
        двух видах. Память при этом ужимается чуть сильнее, чем требовал ограничитель, но ни
        одна пара не теряется: те три пары в выжимке.

        Край: заготовка покрывает больше, чем вообще можно выбросить (последняя пара защищена
        всегда). Тогда она не применяется ВОВСЕ, а пары теряются дословно, и это видно в
        прогоне. Частично применить нельзя — пункт выжимки парам не сопоставлен, вырезать из
        него «часть про три пары» нечем. Случай означает, что память между сборкой заготовки и
        её применением уменьшилась; он редкий, и честная дословная потеря здесь дешевле
        молчаливого вранья. Непригодную заготовку выбрасываем: пары, под которые она собрана,
        только что потеряны дословно, и примени её обрезка следующим ходом — она приписала бы
        свой пересказ уже ДРУГИМ парам.

        Заготовка, чей блок в запрос не пойдёт (сжатие выключено, отпечаток инструкции
        разошёлся), не применяется тоже — по тому же предикату `_подставляется`.
        """
        # Последнюю пару не выбрасываем никогда: без неё агент забудет вопрос, на который сам
        # только что ответил, а человек мог сослаться на этот ответ.
        допустимо = len(self._messages) // 2 - 1
        if допустимо <= 0 or требуется <= 0:
            return 0
        if not self._подставляется(self._prepared):
            # Заготовка перестала годиться уже после принятия: человек сменил роль командой
            # `/system` или выключил сжатие. Выбрасываем по тому же доводу, по какому её не
            # принимают, — её пары сейчас уйдут из памяти, и ждать ей больше нечего.
            self._prepared = None
        заготовка = self._prepared
        покрыто = заготовка.покрыто_пар if заготовка is not None else 0
        сколько = min(требуется, допустимо)
        if заготовка is not None:
            if покрыто > допустимо:
                self._prepared = None
                заготовка = None
                покрыто = 0
            else:
                сколько = max(сколько, покрыто)
        del self._messages[: сколько * 2]
        if заготовка is not None:
            self._summary = заготовка
            self._prepared = None
        self._compacted_pairs += покрыто
        self._forgotten_pairs += сколько - покрыто
        return сколько

    def _срезать_по_весу(self, предел: int, content: str, facts: str, model: str) -> int:
        """Резать блоками, пока вес запроса не уложится в предел. Возвращает число пар.

        Общий цикл для двух весовых ограничителей — порога сжатия и предела профиля. Они
        меряют один и тот же вес в одних и тех же единицах, но отвечают на разные вопросы:
        порог — «пора ли сжимать», предел — «не дороже ли, чем я разрешил». Разные вопросы,
        одно правило резки: два экземпляра этого цикла разошлись бы на первой же правке.

        Режем блоками по `WINDOW_SLACK_PAIRS`, а не по одной паре за ход, по той же причине,
        что и окно по парам: границу усечения нельзя двигать каждый ход, иначе рушится
        повторное использование неизменного начала запроса на стороне сервера — а вход из
        кэша дешевле промаха в тридцать раз (0.022 против 0.66 за миллион у v4-pro).
        """
        if предел <= 0:
            return 0
        выброшено = 0
        while len(self._messages) > 2 and self._вес(content, facts, model) > предел:
            ушло = self._выбросить(WINDOW_SLACK_PAIRS)
            if ушло <= 0:
                # Выбрасывать больше нечего: осталась защищённая последняя пара. Здесь же
                # страховка от нечётной памяти — сегодня её не бывает, но ценой ошибки в
                # другом месте был бы замерший без единого сообщения harness: цикл, которому
                # нечего удалять, крутится вечно, и проявится это только зависанием.
                break
            выброшено += ушло
        return выброшено

    def _trim(self, content: str, *, facts: str = "", model: str = "") -> int:
        """Обрезать память. Возвращает число выброшенных пар — сжатых и забытых вместе.

        `content` — текст нового вопроса, `facts` — готовый блок глобальных фактов: без них
        двоих вес будущего запроса неизвестен, а два ограничителя из трёх меряют именно его.
        Оба довеска именованы честно: обрезка не собирает запрос, ей его дают. `model` нужен
        там же: надбавка обёртки подстраивается под каждую модель отдельно, и взвешивать
        запрос к `flash` поправкой, снятой на `pro`, значило бы резать память по чужой мерке.

        Ограничителей три, и третий условный. Все обязаны резать ТОЛЬКО целыми парами:
        начнись память с ответа — сервер откажет в запросе, причём в случайный момент работы,
        а не при проверках.

        Первый — по числу пар, про КАЧЕСТВО: модель не тянет тему и формат из обменов
        получасовой давности. Он срабатывает не на превышении окна, а на превышении окна с
        запасом, и выбрасывает сразу весь запас: обрезка на каждом ходу меняла бы начало
        запроса на каждом ходу.

        Второй — порог сжатия, про ВЕС: доля окна модели, взвешивающая ВЕСЬ будущий запрос —
        инструкцию, факты, выжимку, память и новый вопрос — в токенах и ДО отправки. На его
        месте стоял аварийный потолок памяти в ЗНАКАХ; он снят, а не дополнен, потому что две
        мерки одной величины расходятся в показаниях, и объяснить человеку, почему обрезана
        память, становится нечем.

        Третий — предел веса из профиля, если тот его задал: не «пора ли сжимать», а «за
        какую сумму не выходить». Вес он меряет тот же, а вопрос решает другой — свойство
        разговора против решения человека о своих деньгах, — и потому живёт рядом законно.

        Всё выброшенное ЛЮБЫМ из троих сперва уходит в выжимку, если та готова, и теряется
        дословно, если нет. Своей мерки выброшенного у сжатия нет: перехват — не второе место
        принятия решения, а подбор того, что решила выбросить обрезка."""
        dropped = 0
        self._compacted_pairs = 0
        self._forgotten_pairs = 0
        window = self.profile.history_window
        if window > 0 and len(self._messages) // 2 >= window + WINDOW_SLACK_PAIRS:
            dropped += self._выбросить(WINDOW_SLACK_PAIRS)
        # У профиля с выключенной историей весовым ограничителям резать нечего: память в
        # запрос не идёт, на вес не влияет, и цикл, не проверяй он этого, выбрасывал бы пару
        # за парой, ничего не добиваясь, — пока не упёрся бы в последнюю.
        порог = self.порог_сжатия() if self.profile.keep_history else 0
        dropped += self._срезать_по_весу(порог, content, facts, model)
        budget = self.profile.budget_tokens if self.profile.keep_history else 0
        dropped += self._срезать_по_весу(budget, content, facts, model)
        # Признак «предел не сработал»: обрезка сделала что могла, а запрос всё равно тяжелее
        # бюджета — потому что системная часть с фактами и сам вопрос уже перевешивают предел,
        # а их выбросить нельзя. Молчать об этом нельзя: предел, который тихо не сработал,
        # хуже отсутствующего — на отсутствующий человек хотя бы не рассчитывает.
        # Считаем по ПРЕДЕЛУ ПРОФИЛЯ, а не по `budget`: у профиля с выключенной историей
        # `budget` обнулён, потому что резать нечего, — но это не значит, что предел
        # соблюдён. Инструкция и вопрос могут перевешивать его и там, и молчать об этом
        # нельзя: получилось бы, что предел не срабатывает и не жалуется именно у того
        # профиля, где его нельзя выправить обрезкой.
        предел = self.profile.budget_tokens
        self._over_budget = bool(предел > 0 and self._вес(content, facts, model) > предел)
        # Поднятых с диска пар не может быть больше, чем пар в памяти: обрезка только что
        # могла выбросить как раз их. Оставь число прежним — и запись прогона утверждала бы,
        # что обмену предшествовал подъём десяти пар, которых в запросе нет ни одной.
        self.restored_pairs = min(self.restored_pairs, len(self._messages) // 2)
        # Пройденное копится ЗДЕСЬ, в единственном месте, где пары уходят из памяти навсегда.
        # Считай его вызывающий — и счёт разошёлся бы с обрезкой на первой же правке.
        self.passed_pairs += dropped
        return dropped

    def build_messages(self, content: str, model: str = "") -> list[dict]:
        """Политика входа: что именно уйдёт в модель на этот вопрос.

        Имя модели нужно не сборке, а обрезке внутри неё: надбавка обёртки подстраивается
        под каждую модель отдельно. Умолчание — пустое имя, то есть базовый замер: у
        вызывающего, который просто смотрит, каким выйдет запрос, модели может и не быть.

        Системная инструкция всегда первая: так её видно отдельно от ввода пользователя,
        и так же работает кэширование общего начала запроса на стороне DeepSeek. Глобальные
        факты о пользователе подмешиваются в неё же, отдельным блоком после пустой строки:
        это знание о собеседнике, а не его реплика, и в разговор его класть нельзя — модель
        стала бы отвечать на него как на сказанное только что. Факты запрашиваются на каждой
        сборке: между двумя запросами человек мог добавить факт командой `/remember`.

        Третьим блоком, после фактов, идёт выжимка — пересказ пройденного куска разговора.
        Репликой памяти она не становится никогда: модель ответила бы на пересказ как на
        сказанное сейчас, разговор пошёл бы по кругу, а лишнее сообщение сломало бы строгое
        чередование ролей, на котором держится и чтение сессии, и сам запрос к API.

        Вопрос в память здесь НЕ дописывается. Память пополняется только после успешного
        ответа, в `exchange`. Причина: неотвеченный вопрос не должен оседать в памяти —
        иначе после сетевого сбоя модель на следующем ходу увидит вопрос, на который
        никто не отвечал, и станет отвечать на него повторно.

        Список собирается новый, а сообщения памяти копируются: наружу не уходит ничего,
        через что вызывающий мог бы переписать память агента.

        Порядок работы такой: сперва читается блок фактов, потом им и памятью обрезка
        взвешивает будущий запрос, и только потом собирается сам список сообщений. Обрезка
        по-прежнему идёт ДО сборки списка: обрежь после — и запрос ушёл бы полным, а урезанной
        осталась бы одна память, то есть ограничение не работало бы ровно там, ради чего
        заведено.

        Взвешивать надо РОВНО ТО, что уйдёт в модель. Недосчитай обрезка блок фактов или блок
        выжимки — и она решила бы «влезает» там, где не влезает: запрос ушёл бы тяжелее
        бюджета, и предел не сработал бы ровно в том случае, ради которого заведён. Ошибка в
        другую сторону стоила бы лишней выброшенной пары, то есть дёшево, — но это не повод
        считать неверно.

        Факты читаются ровно ОДИН РАЗ за сборку: источник живёт снаружи и ходит на диск, а
        взвешивание обрезка зовёт столько раз, сколько блоков выбросит. Сама системная часть
        собирается из них внутри обрезки на каждом замере — посреди неё заготовка может стать
        действующей выжимкой, и вес системного сообщения меняется.

        Системную часть для готового списка собираем ПОСЛЕ обрезки по той же причине: до неё
        выжимка была прежней, и запрос ушёл бы с пересказом, которого модель уже не увидит
        рядом с теми парами, что он заменил.

        Текст вопроса уходит в обрезку по той же причине: без него вес запроса неизвестен."""
        block = ""
        if self._facts is not None:
            try:
                block = memory.facts_block(self._facts())
            except Exception as exc:  # noqa: BLE001 — источник фактов приходит снаружи
                # Сборка запроса идёт ДО начала обмена, и исключение отсюда улетело бы мимо
                # всей обработки: ни ответа, ни записи прогона в журнал. Сегодня чтение фактов
                # не бросает по построению, но гарантия «вспомогательный механизм не роняет
                # обмен» не имеет права держаться на чужом обещании.
                self.store_error = f"не удалось прочитать глобальную память: {exc}"
        self._dropped_pairs = self._trim(content, facts=block, model=model)
        # Профиль без инструкции, но с фактами получает системное сообщение из одного блока
        # фактов: иначе факты пропадали бы ровно у встроенного `default`, которым пользуются
        # чаще всего. То же и с выжимкой.
        system = self._система(block)
        messages: list[dict] = []
        if system:
            messages.append({"role": "system", "content": system})
        if self.profile.keep_history:
            messages.extend(dict(m) for m in self._messages)
        messages.append({"role": "user", "content": content})
        return messages

    async def exchange(
        self,
        client,
        model: str,
        content: str,
        *,
        on_event: Callable[[api.StreamEvent], None] | None = None,
        agent: str | None = None,
        run_id: str | None = None,
    ) -> Turn:
        """Обмен с моделью: отправить вопрос, собрать поток ответа, записать прогон."""
        # Ошибка описывает ИМЕННО этот обмен. Не сбрось её здесь — и вчерашний отказ диска
        # показывался бы после каждого следующего запроса до конца сеанса. Сброс стоит ДО
        # сборки запроса: сборка читает глобальную память и при её сбое сама кладёт сюда
        # текст, а сброс после сборки стирал бы его, не показав никому.
        self.store_error = None
        request_messages = self.build_messages(content, model)
        # Вес памяти снимаем ЗДЕСЬ: обрезка уже прошла, а ответ в память ещё не лёг. Сними
        # его после обмена — и число описывало бы память следующего запроса, а не этого.
        history_tokens = self.history_tokens()
        # Вес одного текста, без надбавки, — мерка для калибровки: сервер пришлёт
        # `prompt_tokens` за ровно то же самое, и разность двух чисел и есть обёртка разговора.
        text_tokens = tokens.count_messages(request_messages, overhead=0)
        predicted = self.predict_tokens(request_messages, model)
        self.task = content
        # Поколение памяти на момент начала обмена: если к концу оно сменилось, память этого
        # обмена уже забыли, и пополнять её результатом нельзя.
        generation = self._generation
        answer_text = ""
        reasoning_text = ""
        finish_reason: str | None = None
        usage: dict[str, Any] = {}
        status = "error"
        error_text: str | None = None
        render_error: str | None = None
        started = time.monotonic()
        try:
            async for event in client.stream_chat(model, request_messages, self.profile.params):
                if on_event is not None:
                    try:
                        on_event(event)
                    except Exception as exc:
                        # `on_event` — это отрисовка, она живёт СНАРУЖИ агента. Выпусти её
                        # исключение отсюда — и оно попадёт в общий обработчик ошибок обмена
                        # ниже, а пользователь увидит «ошибка запроса к DeepSeek» при
                        # полностью живой сети: прямая ложь, из-за которой он пойдёт чинить
                        # то, что не сломано. Проглотить совсем тоже нельзя — причину
                        # запоминаем и отдаём в `Turn.error`, но только если обмен в
                        # остальном удался, и текстом, где нет слова DeepSeek.
                        render_error = f"ответ получен, но показать его не удалось: {exc}"
                if event.kind == "meta":
                    finish_reason = event.finish_reason
                    usage = event.usage
                    continue
                if event.kind == "reasoning":
                    reasoning_text += event.text
                else:
                    answer_text += event.text
            status = "ok"
        except asyncio.CancelledError:
            status = "cancelled"
            raise
        except Exception as exc:  # сеть, лимиты, ошибки API — не роняем harness
            error_text = str(exc)
        finally:
            elapsed = time.monotonic() - started
            snapshot = self.profile.snapshot()
            if status == "ok" and not answer_text:
                # Поток дошёл до конца, а ответа нет. Наверх обязан уйти внятный отказ,
                # а не бодрое «успех» с пустой строкой, которую вызывающий покажет
                # пользователю как ответ модели.
                #
                # Причину называем, когда она известна, и называем ТУ САМУЮ. Обрыв по длине
                # (`length`) бывает по двум разным причинам, и совет у них противоположный:
                #
                #   * упёрлись в свой `max_tokens` — лечится увеличением предела;
                #   * места не осталось в самом окне модели: разговор занял его почти целиком,
                #     и на ответ ничего не оставил. Увеличивать тут нечего — надо укорачивать
                #     разговор. Замечено на живом прогоне: вход занял 1 048 495 из 1 048 576,
                #     и совет «увеличьте max_tokens» отправлял чинить то, чего нет.
                #
                # Отличаем по остатку окна: если вход почти доверху, дело в окне, а не в пределе.
                status = "error"
                if finish_reason == "length":
                    вход = tokens.normalize(usage)["prompt_tokens"]
                    остаток = tokens.CONTEXT_WINDOW - вход
                    предел = self.profile.params.get("max_tokens")
                    if вход and остаток < ОСТАТОК_НА_ОТВЕТ:
                        error_text = (
                            f"в окне модели не осталось места на ответ: занято {вход} "
                            f"из {tokens.CONTEXT_WINDOW}, свободно {остаток} — "
                            "очистите историю командой /clear или задайте вопрос короче"
                        )
                    elif предел:
                        error_text = (
                            "весь max_tokens ушёл на рассуждения, ответ не начат — увеличьте max_tokens"
                        )
                    else:
                        error_text = "ответ оборван по длине, не начавшись"
                else:
                    error_text = "модель вернула пустой ответ"
            if status == "ok":
                if render_error:
                    error_text = render_error
                # Пара кладётся ТОЛЬКО через `remember` — второй точки записи в память нет.
                # Поколение сверяем здесь: `forget`, пришедший посреди обмена (командой
                # `/clear` или сменой профиля), означает, что этот разговор уже забыт, — и
                # дописывать в него ответ на давно снятый вопрос нельзя.
                if self.profile.keep_history and self._generation == generation:
                    # Запись на диск живёт внутри `remember` и своих исключений не выпускает:
                    # мы в `finally`, до записи в журнал и до сборки результата, и исключение
                    # отсюда уничтожило бы и полученный ответ, и запись прогона. Перехват
                    # всё же ставим: гарантия «не бросает» обязана быть с обеих сторон, а
                    # не только в чужом модуле, который завтра поправят.
                    try:
                        self.remember(content, answer_text, model=model)
                    except Exception as exc:  # обмен дороже любой записи на диск
                        self.store_error = f"не удалось сохранить разговор: {exc}"
            # При любом неуспехе память не трогаем вовсе: вопроса там нет, `build_messages`
            # его туда не клал, — вычищать нечего.
            # Счётчики пополняем здесь, в `finally`: сюда приходит и успех, и отказ, и отмена
            # (после `raise` тело `finally` всё равно выполняется). Пополни их в ветке успеха —
            # и статистика молча потеряла бы самые дорогие обмены.
            self.runs += 1
            self.total_ms += int(elapsed * 1000)
            self.total_tokens += usage_tokens(usage)
            self.session_usage = tokens.add_usage(self.session_usage, usage)
            # Самокалибровка надбавки: сервер только что назвал вес того же самого текста,
            # и разность — это обёртка разговора, какой она есть сегодня, а не какой её
            # замерили однажды. Подстраивается надбавка ИМЕННО ЭТОЙ модели: у соседней она
            # своя. `bool` отсеиваем отдельно: в Python он подкласс `int`.
            #
            # Принимаем только правдоподобное значение — от нуля до `OVERHEAD_LIMIT`.
            # Отрицательная обёртка означала бы, что разговор отнимает токены; надбавка в
            # сотни тысяч — что сервер прислал счёт не от нашего запроса. И то и другое надо
            # не «поджать к границе», а ОТВЕРГНУТЬ целиком, оставив прежнее число: поджатая
            # к тысяче нелепость точно так же выбросила бы половину памяти. Молча: это сбой
            # чужой стороны, а не событие разговора, и человеку тут делать нечего.
            prompt_tokens = usage.get("prompt_tokens") if isinstance(usage, dict) else None
            if isinstance(prompt_tokens, int) and not isinstance(prompt_tokens, bool):
                measured = prompt_tokens - text_tokens
                if 0 <= measured <= OVERHEAD_LIMIT:
                    self._overhead[model] = measured
            entry: dict[str, Any] = {
                "status": status,
                "model": model,
                "profile": snapshot,
                "query": content,
                "messages": request_messages,
                "response": answer_text or None,
                "reasoning": reasoning_text or None,
                "finish_reason": finish_reason,
                "usage": usage or None,
                # Номер обмена в сеансе: `self.runs` уже пополнен, значит первый обмен — 1.
                # Без номера кривая расхода по журналу строилась бы по времени записи, а оно
                # у одновременных обменов группы совпадает.
                "index": self.runs,
                "history_tokens": history_tokens,
                "predicted_prompt_tokens": predicted,
                "agent_session_tokens": self.session_usage["total_tokens"],
                "elapsed_ms": int(elapsed * 1000),
                "error": error_text,
            }
            # Денег в записи нет намеренно: тариф — не источник правды, он живёт на странице
            # цен поставщика и протухнет молча. Записанная цена через полгода была бы враньём,
            # которое уже не проверить, а токены останутся токенами: деньги считаются поверх
            # журнала, действующим тарифом.
            if self._over_budget:
                # Ключ появляется только при превышении: у обмена, уместившегося в предел,
                # «over_budget: false» в каждой строке журнала — шум, за которым перестают
                # замечать настоящие случаи.
                entry["over_budget"] = True
            if self.restored_pairs:
                # Ключ появляется только когда пары действительно поднимались с диска: у
                # чистого сеанса ноль здесь ничего не объясняет, а строку записи удлиняет.
                entry["restored_pairs"] = self.restored_pairs
            if agent:
                entry["agent"] = agent
            if run_id:
                entry["run_id"] = run_id
            journal_error = journal.append(entry)
            turn = Turn(
                status=status,
                text=answer_text,
                reasoning=reasoning_text,
                finish_reason=finish_reason,
                usage=usage,
                elapsed_ms=int(elapsed * 1000),
                error=error_text,
                request_messages=request_messages,
                model=model,
                profile_snapshot=snapshot,
                dropped_pairs=self._dropped_pairs,
                compacted_pairs=self._compacted_pairs,
                forgotten_pairs=self._forgotten_pairs,
                passed_pairs=self.passed_pairs,
                index=self.runs,
                history_tokens=history_tokens,
                predicted_prompt=predicted,
                agent_session_tokens=self.session_usage["total_tokens"],
                over_budget=self._over_budget,
                journal_error=journal_error,
                store_error=self.store_error,
            )
        return turn
