"""Сущность-собеседник: имя, профиль, память разговора и правила сборки запроса.

Здесь живёт вся логика разговора с моделью, отделённая от того, кто её показывает.
Модуль намеренно не знает ни про терминал, ни про панели: ему разрешены только `api`,
`journal`, `memory`, `profiles`, `tokens` и стандартная библиотека. Поэтому агента можно проверить без
терминала, без окон и без единого нажатия клавиши. `memory` в этот список входит по праву:
он такая же чистая логика — ни сети, ни терминала, только файлы состояния.

Наружу агент отдаёт только результат — запись `Turn`. Внутренняя память остаётся
внутренней: её выдают копией, а пополняют единственным методом `remember`.

Того, что переживает запуск, агент себе не заводит: и хранилище разговора, и глобальные
факты приходят снаружи, а умолчание у обоих — «ничего нет». Причина в том, что агентов в
процессе много: пакетный наряд на сто заданий и панели исполнителей группы завели бы себе
по записи на диске каждый и переписали бы разговор пользователя. Хранилище включает ровно
тот, кто ведёт разговор человека, — главный экран.
"""

from __future__ import annotations

import asyncio
import time
from collections.abc import Callable
from dataclasses import dataclass, field
from typing import TYPE_CHECKING, Any

from . import api, journal, memory, tokens

if TYPE_CHECKING:  # только подсказка типов — на выполнении профиль сюда не импортируется
    # Умолчание окна памяти живёт здесь, рядом с правилом обрезки, а поле профиля берёт его
    # отсюда — значение одно на весь harness. Значит, `profiles` импортирует `agent`, и
    # обычный импорт `Profile` замкнул бы круг. Замыкать его нечем: `Profile` нужен агенту
    # только как аннотация, а `from __future__ import annotations` делает аннотации строками.
    from .profiles import Profile

# Сколько пар «вопрос — ответ» держим по умолчанию. Десять пар — это обмены примерно на
# полчаса разговора: свежую инструкцию модель ещё слышит, а формат и тему из обменов
# получасовой давности уже не тянет. Дрейф на длинной истории заметен обменов с тридцати.
DEFAULT_WINDOW_PAIRS = 10

# Запас сверх окна: режем не на одиннадцатой паре, а на пятнадцатой — и сразу блоком в пять.
# Сдвигай окно каждый ход по одной паре — и начало запроса менялось бы каждый ход, обнуляя
# повторное использование неизменного начала на стороне сервера. Блоком полную цену платим
# раз в пять ходов вместо каждого.
WINDOW_SLACK_PAIRS = 5

# Аварийный потолок объёма памяти в знаках. Окно по числу пар не спасает от единственного
# случая: пользователь вставил в вопрос файл, и одна пара весит больше всего окна контекста.
# 60 000 знаков — это порядка 20 000 токенов, около трети окна: остаётся место и на
# системную инструкцию, и на новый вопрос, и на сам ответ.
HISTORY_CHARS_MAX = 60_000

# Потолок правдоподобия для подстроенной надбавки обёртки. Обёртка — это разделители ролей,
# то есть десятки токенов; тысяча взята с запасом в десять раз от замеренных 83. Всё, что
# выше, — не обёртка, а сбой чужой стороны: ответ другой модели, склеенный счёт, поле не от
# того запроса. Принять такое число нельзя, и вот почему это важнее аккуратности счёта:
# надбавка входит в вес запроса, по весу режется память, а выброшенная пара не возвращается.
# Один нелепый ответ сервера уничтожил бы разговор целиком, и выправившаяся на следующем
# обмене надбавка память бы уже не вернула.
OVERHEAD_LIMIT = 1000


def usage_tokens(usage: dict[str, Any] | None) -> int:
    """Сколько токенов стоил обмен по данным `usage`.

    Считать нечем — считаем нулём, а не падаем: `usage` приходит от сервера, и при обрыве
    потока или отказе его может не быть вовсе. Уронить на этом сбор статистики значило бы
    потерять и сам ответ, который уже получен.

    `total_tokens` предпочитаем сумме слагаемых: сервер кладёт туда собственный итог, и он
    учитывает то, чего в двух слагаемых нет, — например попадания в кэш начала запроса."""
    # Разбор `usage` живёт в одном месте — `tokens.normalize`. Своя копия правила была
    # здесь до появления модуля счёта и успела разойтись с ним на кривых данных: при
    # `total_tokens: 0` с непустыми слагаемыми она давала ноль, при `total_tokens: true` —
    # единицу (в Python `True` это `1`). В списке агентов рядом со строкой ожидания вставало
    # «Σ 0», и человек шёл искать поломку в учёте, которой нет.
    return tokens.normalize(usage)["total_tokens"]


@dataclass
class Turn:
    """Итог одного обмена с моделью — тем, кто позвал: тексту ответа и цене.

    Запись полная: по ней видно не только что ответила модель, но и что именно ей
    ушло, — вызывающему не приходится лезть внутрь агента за подробностями."""

    status: str
    text: str = ""
    reasoning: str = ""
    finish_reason: str | None = None
    usage: dict[str, Any] = field(default_factory=dict)
    elapsed_ms: int = 0
    error: str | None = None
    # что фактически ушло в модель — иначе прогон не воспроизвести и не сверить
    request_messages: list[dict] = field(default_factory=list)
    # какой моделью получен ответ: модель меняется на лету, а запись остаётся
    model: str = ""
    # слепок профиля для журнала — инструкция и параметры на момент запроса
    profile_snapshot: dict[str, Any] = field(default_factory=dict)
    # сколько пар выброшено окном памяти перед этим запросом — чтобы показать усечение
    dropped_pairs: int = 0
    # какой это по счёту обмен в сеансе — по нему кривая расхода строится без домыслов
    index: int = 0
    # сколько весила память на момент ЭТОГО запроса: цена того, что агент помнит
    history_tokens: int = 0
    # предсказание веса запроса, сделанное ДО отправки: рядом с настоящим `usage` по нему
    # видно, насколько предсказание врёт, — иначе судить о точности счёта было бы не по чему
    predicted_prompt: int = 0
    # расход сеанса нарастающим итогом на конец этого обмена
    # Расход ЭТОГО агента за сеанс — не итог сеанса целиком: агент про соседей не знает.
    # Имя названо по смыслу, чтобы не спутать с общим итогом на экране и в /tokens.
    agent_session_tokens: int = 0
    # предел веса задан, обрезка сделала что могла, а запрос всё равно ушёл тяжелее предела
    over_budget: bool = False
    # текст ошибки записи журнала: сам обмен удался, а предупредить надо снаружи
    journal_error: str | None = None
    # то же самое про запись разговора на диск: обмен состоялся и оплачен, а память между
    # запусками не сохранилась — молчать об этом нельзя, ронять обмен из-за этого тоже
    store_error: str | None = None

    @property
    def ok(self) -> bool:
        return self.status == "ok"


class Agent:
    """Собеседник со своей памятью: имя, профиль и накопленные пары «вопрос — ответ»."""

    def __init__(
        self,
        name: str,
        profile: Profile,
        *,
        store: memory.SessionStore | None = None,
        facts: Callable[[], list[str]] | None = None,
    ) -> None:
        self.name = name
        self.profile = profile
        # Хранилище разговора между запусками. Умолчание — ВЫКЛЮЧЕНО, и это не осторожность,
        # а необходимость: агентов в процессе много, а разговор пользователя один. Наряд из
        # ста заданий и панели исполнителей группы, заведи они хранилище сами, писали бы в
        # каталог состояния наперегонки поверх переписки человека.
        self._store = store
        # Глобальные факты о пользователе — ВЫЗЫВАЕМЫЙ объект, а не готовый список. Факты
        # меняются по ходу сеанса (командой `/remember` и архивариусом), и список, снятый
        # при создании агента, отстал бы от них к первому же запросу.
        self._facts = facts
        # Идёт загрузка прежнего разговора: пополнение памяти на диск не пишется. Иначе
        # чтение файла тут же переписывало бы его самим собой, удваивая каждую пару.
        self._restoring = False
        # Чем кончилась последняя попытка записи разговора на диск. Поле, а не исключение:
        # хранилище — вспомогательный механизм, и ронять им уже оплаченный обмен нельзя.
        self.store_error: str | None = None
        self._messages: list[dict] = []
        # сколько пар выбросила обрезка перед последней сборкой запроса — отсюда в `Turn`
        self._dropped_pairs = 0
        # не удержался ли последний запрос в пределе веса — оттуда же в `Turn` и в журнал
        self._over_budget = False
        # Поколение памяти: `forget` его увеличивает. Обмен запоминает поколение в начале и
        # пополняет память, только если оно не сменилось. Без этого счётчика `/clear`,
        # отданный посреди идущего обмена, «очищал» бы память на словах: обмен доходит до
        # своего `finally` уже после команды и кладёт пару обратно.
        self._generation = 0
        # Счётчики за всё время жизни агента: их показывает список агентов под строкой ввода.
        # СЧИТАЕМ И НЕУДАЧНЫЕ, И ОТМЕНЁННЫЕ ОБМЕНЫ — это не недосмотр, а решение.
        # Время на упавший запрос потрачено, токены на него у поставщика списаны, и список,
        # показывающий только удачные обмены, рисует агента дешевле, чем он есть.
        # Дороже всего обходится как раз агент, который падает и уходит на повтор.
        self.runs = 0  # сколько обменов было — всего, при любом исходе
        self.total_ms = 0  # сколько времени на них ушло
        self.total_tokens = 0  # сколько токенов израсходовано
        # Расход ТЕКУЩЕГО сеанса, покомпонентно: вход, выход, попадания в кэш, рассуждения.
        # Заведён рядом с `total_tokens`, а не вместо него: на том счётчике держится колонка
        # списка агентов, и подменить его разбивкой значило бы тихо сменить смысл колонки.
        # Разбивка нужна там, где считают деньги: вход из кэша стоит в тридцать раз дешевле
        # промаха, и по одной сумме цену не назвать.
        # Пустым словарём не заводим, хотя до первого обмена расходовать было нечего: форма
        # у накопителя обязана быть одна и та же с первой секунды. Иначе строка ожидания и
        # `/tokens`, спросив `session_usage["total_tokens"]` на чистом запуске, получили бы
        # `KeyError` — причём не на проверках, а у человека сразу после старта.
        self.session_usage: dict[str, int] = tokens.total_usage([])
        # Надбавка обёртки разговора: сколько токенов сервер прибавляет к тексту реплик.
        # 83 — живой замер 2026-09-09, то есть начальное приближение, а не закон: DeepSeek
        # вправе изменить обёртку, ничего нам не сказав, и тогда предсказание начнёт врать
        # молча. Поэтому после каждого обмена, где сервер назвал `prompt_tokens`, число
        # подстраивается под него. Калибровка живёт на агенте и только на сеанс, в файл не
        # пишется: сохранённое число пережило бы и смену профиля, а характер запросов у
        # профилей разный — вышла бы уверенная ложь вместо честного приближения.
        #
        # Хранится ПО МОДЕЛЯМ, а не одним числом, по двум причинам сразу. Первая: модель
        # меняется на лету командой `/model`, и надбавка, снятая на `v4-pro`, к
        # `flash-vision-exp` отношения не имеет. Вторая важнее: в это число оседает не только
        # обёртка, но и вся систематическая разница нашего счёта с серверным, а она растёт с
        # длиной запроса — расхождение в 2% на разговоре в 8000 токенов даёт надбавку под 250
        # вместо 83. Смешай такую поправку между моделями — и короткий вопрос к другой модели
        # предсказывался бы втрое дороже, чем стоит.
        self._overhead: dict[str, int] = {}
        # Сколько пар поднято с диска при запуске. Обмен, которому предшествовал подъём
        # прежнего разговора, стоит дороже обмена с чистой памятью, и по записи прогона
        # должно быть видно, откуда взялся такой вход, — иначе кривая расхода необъяснима.
        self.restored_pairs = 0
        # Над чем агент работает: содержание последнего запроса. Список агентов показывает
        # это в колонке занятия, пока агент занят. Держим здесь, а не в панели: работу знает
        # тот, кто её делает, и агент без панели (пакетный наряд) знает её точно так же.
        self.task = ""

    def set_store(self, store: memory.SessionStore | None) -> None:
        """Сменить хранилище разговора — например, когда `/clear` открывает новую сессию.

        Отдельный метод, а не открытое поле: тогда место, где хранилище появляется и
        исчезает, одно, и его видно в дереве вызовов."""
        self._store = store

    def history(self) -> list[dict]:
        """Память разговора — копией.

        Отдай сам список — и любой снаружи сможет незаметно дописать или стереть память
        агента, минуя `remember`. Тогда инкапсуляция перестаёт что-либо значить: правил
        пополнения памяти больше нет, а искать, кто её испортил, придётся по всему коду."""
        return [dict(m) for m in self._messages]

    def forget(self) -> None:
        """Забыть разговор целиком — например, когда сменился профиль.

        Смена поколения — не украшение: команда `/clear` исполняется немедленно, мимо очереди
        запросов, и запросто попадает в середину идущего обмена. Тот обмен свой результат в
        память после этого не вернёт (см. `exchange`) — это и есть смысл слова «забудь».

        Счёт поднятых с диска пар обнуляется вместе с памятью: после `/clear` поднятого не
        осталось ни одной пары, а записи прогонов продолжали бы уверять, что обмену
        предшествовал подъём разговора, — и объяснять расход было бы нечем."""
        self._messages.clear()
        self._generation += 1
        self.restored_pairs = 0

    def remember(self, question: str, answer: str, *, model: str = "") -> None:
        """Положить в память готовую пару «вопрос — ответ» и сохранить её на диск.

        ЕДИНСТВЕННАЯ точка записи в память. `exchange` и восстановление пополняют память
        тоже через этот метод, а не напрямую через `self._messages`, — второй точки записи
        заводить нельзя, иначе правила пополнения снова разъедутся по разным местам.

        Раз точка одна — здесь же и запись на диск, со всеми тремя условиями сразу.

        `keep_history` проверяется ИМЕННО ЗДЕСЬ, а не у вызывающего. Вызывающих двое:
        `exchange` эту проверку делал, `output.deliver` — нет, и профиль с выключенной
        историей завёл бы на диске разговор, которого нет ни в одном запросе к модели:
        `build_messages` память такого профиля не берёт.

        Пометки кладутся на ответ, а не на вопрос: через месяц по файлу должно быть видно,
        каким профилем и какой моделью получен ответ и не правили ли с тех пор инструкцию.
        У вопроса такого прошлого нет — его написал человек."""
        self._messages.append({"role": "user", "content": question})
        self._messages.append({"role": "assistant", "content": answer})
        if self._store is None or self._restoring or not self.profile.keep_history:
            return
        # Ошибку берём первую: причина у обеих строк одна и та же (нет прав, нет места), и
        # второй раз повторять её человеку незачем.
        ошибка = self._store.append("user", question)
        ошибка = ошибка or self._store.append(
            "assistant",
            answer,
            {
                "profile": self.profile.name,
                "model": model,
                "system_fp": memory.fingerprint(self.profile.system),
            },
        )
        self.store_error = ошибка

    def restore(self, pairs: list[tuple[str, str]]) -> None:
        """Поднять прежний разговор — тем же единственным методом пополнения.

        Запись на диск на время загрузки выключена: пары пришли из того самого файла, и
        сохранять их обратно значило бы удваивать разговор при каждом запуске.

        Признак снимается в `finally`: сорвись загрузка на середине — и агент до конца
        сеанса молча не писал бы на диск ничего, а обнаружилось бы это только при следующем
        запуске, когда разговора на месте не окажется."""
        self._restoring = True
        try:
            for question, answer in pairs:
                self.remember(question, answer)
                # Считаем ПОСЛЕ пополнения памяти: сорвись загрузка на этой паре — и в счёте
                # оказалась бы пара, которой в памяти нет.
                self.restored_pairs += 1
        finally:
            self._restoring = False

    def history_tokens(self) -> int:
        """Вес памяти в токенах — то, что уйдёт в следующий запрос помимо всего прочего.

        Ни системной инструкции, ни нового вопроса, ни надбавки обёртки здесь нет: это цена
        того, что агент помнит, и по ней человек решает, пора ли звать `/clear`. Подмешай
        сюда инструкцию — и число перестало бы отвечать на вопрос, ради которого заведено.

        У профиля с выключенной историей вес нулевой, сколько бы пар в памяти ни лежало:
        `build_messages` эту память в запрос не кладёт. Считай её здесь — и журнал уверял бы,
        что обмен из одной реплики тащил за собой две тысячи токенов памяти, а по такому
        числу человек полез бы чистить разговор, который ни на что не влияет.

        Реплики с нетекстовым содержимым пропускаем: сегодня их в памяти не бывает (пары
        кладёт `remember`, и обе половины у него строки), но счёт токенов — удобство, и
        ронять на нём весь harness нельзя даже ради собственной уверенности."""
        if not self.profile.keep_history:
            return 0
        return sum(
            tokens.count_text(m["content"]) for m in self._messages if isinstance(m.get("content"), str)
        )

    def overhead(self, model: str) -> int:
        """Надбавка обёртки для этой модели: подстроенная, если её уже мерили, иначе замер.

        Незнакомая модель получает базовое значение, а не поправку соседа: надбавка тянет в
        себе систематическую разницу счёта, и у другой модели она другая."""
        return self._overhead.get(model, tokens.BASE_OVERHEAD)

    def system_text(self) -> str:
        """Системная часть запроса целиком: инструкция профиля плюс блок глобальных фактов.

        Нужна снаружи затем, чтобы показ и предупреждение о переполнении считали ТО ЖЕ, что
        уйдёт в модель. Сборка запроса эту часть собирает сама, но звать её ради взвешивания
        нельзя: `build_messages` обрезает память, то есть меняет состояние.

        Ошибку чтения фактов здесь глотаем: это взвешивание, а не отправка, и падать на нём
        нельзя — настоящую жалобу человек всё равно получит при сборке запроса.
        """
        system = self.profile.system or ""
        block = ""
        if self._facts is not None:
            try:
                block = memory.facts_block(self._facts())
            except Exception:  # noqa: BLE001 — источник фактов приходит снаружи
                block = ""
        if block:
            return f"{system}\n\n{block}" if system else block
        return system

    def predict_tokens(self, messages: list[dict], model: str = "") -> int:
        """Предсказание веса запроса — с надбавкой, подстроенной ЭТИМ агентом под ЭТУ модель.

        Метод агента, а не прямой вызов `tokens.count_messages` у вызывающего: надбавка
        живёт здесь и меняется по ходу сеанса, и второе место, где её берут, разъехалось бы
        с первым на первом же обмене.

        Модель без имени берёт базовый замер — так отвечает и `overhead`. Умолчание оставлено
        ради вызывающих, которым модель неизвестна (предпросмотр запроса до выбора модели):
        подставить им чужую поправку было бы хуже, чем честное приближение."""
        return tokens.count_messages(messages, overhead=self.overhead(model))

    def _preview(self, content: str, system: str) -> list[dict]:
        """Каким выйдет запрос при нынешней памяти — чтобы взвесить его в обрезке.

        Системная часть приходит готовой, вместе с блоком глобальных фактов, а не собирается
        здесь. Причина в двух требованиях сразу, и оба обязательны. Первое: взвешивать надо
        РОВНО ТО, что уйдёт в модель, — недосчитай блок фактов, и обрезка решит «влезает» там,
        где не влезает, а запрос уйдёт тяжелее бюджета, то есть предел не сработает ровно
        там, ради чего заведён. Второе: источник фактов живёт снаружи и ходит на диск, а
        взвешивание зовут столько раз, сколько блоков выброшено, — читать его на каждом витке
        нельзя. Оба выполняются, если системную часть собрать один раз до обрезки; этим и
        занят `build_messages`.

        Память берётся по тому же условию, что и там: профиль с выключенной историей её в
        запрос не кладёт, а значит и в вес она не входит. Считай её здесь безусловно — и
        бюджет выбрасывал бы пары, которых в запросе нет вовсе."""
        preview: list[dict] = []
        if system:
            preview.append({"role": "system", "content": system})
        if self.profile.keep_history:
            preview.extend(self._messages)
        preview.append({"role": "user", "content": content})
        return preview

    def _trim(self, content: str, *, system: str = "", model: str = "") -> int:
        """Обрезать память до окна. Возвращает число выброшенных пар.

        `content` — текст нового вопроса, `system` — готовая системная часть вместе с блоком
        фактов: без них двоих вес будущего запроса неизвестен, а третий ограничитель меряет
        именно его. Оба довеска именованы честно: обрезка не собирает запрос, ей его дают.
        `model` нужен там же: надбавка обёртки подстраивается под каждую модель отдельно,
        и взвешивать запрос к `flash` поправкой, снятой на `pro`, значило бы резать память
        по чужой мерке.

        Три ограничителя подряд, и все обязаны резать ТОЛЬКО целыми парами: начнись память
        с ответа — сервер откажет в запросе, причём в случайный момент работы, а не при
        проверках.

        Первый ограничитель — по числу пар. Он срабатывает не на превышении окна, а на
        превышении окна с запасом, и выбрасывает сразу весь запас: обрезка на каждом ходу
        меняла бы начало запроса на каждом ходу.

        Второй — аварийный, по объёму в знаках: одна пара со вставленным файлом весит больше
        любого разумного окна по парам. Он режет по одной старейшей паре, но последнюю пару
        не трогает никогда — иначе агент забудет то, о чём его только что спросили, и
        останется без ответа, к которому пользователь мог отослаться.

        Третий — по весу запроса в токенах, если профиль назвал бюджет. Он нужен потому, что
        первые два меряют не то, чем считает контекст и деньги поставщик: пар может быть
        немного, а весить они могут сколько угодно, и знаки в токены переводятся по-разному
        для кода, русского текста и английского.

        Пересказ истории отдельным вызовом модели сюда сознательно не заводится: он вносит
        в разговор текст, которого никто не говорил, и отладить это потом нечем. Забывание
        честнее."""
        dropped = 0
        window = self.profile.history_window
        if window > 0 and len(self._messages) // 2 >= window + WINDOW_SLACK_PAIRS:
            del self._messages[: WINDOW_SLACK_PAIRS * 2]
            dropped += WINDOW_SLACK_PAIRS
        while len(self._messages) > 2 and sum(len(m["content"]) for m in self._messages) > HISTORY_CHARS_MAX:
            del self._messages[:2]
            dropped += 1
        # У профиля с выключенной историей третьему ограничителю резать нечего: память в
        # запрос не идёт, на вес не влияет, и цикл, не проверяй он этого, выбрасывал бы пару
        # за парой, ничего не добиваясь, — пока не упёрся бы в последнюю.
        budget = self.profile.budget_tokens if self.profile.keep_history else 0
        # Режем блоками по `WINDOW_SLACK_PAIRS`, а не по одной паре за ход, по той же причине,
        # что и окно по парам: границу усечения нельзя двигать каждый ход, иначе рушится
        # повторное использование неизменного начала запроса на стороне сервера — а вход из
        # кэша дешевле промаха в тридцать раз (0.022 против 0.66 за миллион у v4-pro).
        # Полную цену блоком платим раз в несколько ходов вместо каждого.
        while (
            budget > 0
            and len(self._messages) > 2
            and self.predict_tokens(self._preview(content, system), model) > budget
        ):
            # Последнюю пару не выбрасываем никогда, поэтому блок ужимается до остатка сверх
            # неё. Без этого ограничения цикл дошёл бы до пустой памяти, и агент забыл бы
            # вопрос, на который сам только что ответил.
            portion = min(WINDOW_SLACK_PAIRS, len(self._messages) // 2 - 1)
            if portion <= 0:
                # Условие выхода из цикла держится на том, что память состоит из целых пар.
                # Сегодня это так, и нарушить это может только ошибка в другом месте — но
                # ценой ошибки будет замерший без единого сообщения harness: `del [:0]` не
                # удаляет ничего, и цикл крутится вечно. Строка страховки дешевле такого
                # отказа, и её отсутствие ничем себя не проявит до самого зависания.
                break
            del self._messages[: portion * 2]
            dropped += portion
        # Признак «предел не сработал»: обрезка сделала что могла, а запрос всё равно тяжелее
        # бюджета — потому что системная часть с фактами и сам вопрос уже перевешивают предел,
        # а их выбросить нельзя. Молчать об этом нельзя: предел, который тихо не сработал,
        # хуже отсутствующего — на отсутствующий человек хотя бы не рассчитывает.
        # Считаем по ПРЕДЕЛУ ПРОФИЛЯ, а не по `budget`: у профиля с выключенной историей
        # `budget` обнулён, потому что резать нечего, — но это не значит, что предел
        # соблюдён. Инструкция и вопрос могут перевешивать его и там, и молчать об этом
        # нельзя: получилось бы, что предел не срабатывает и не жалуется именно у того
        # профиля, где его нельзя выправить обрезкой.
        предел = self.profile.budget_tokens
        self._over_budget = bool(
            предел > 0 and self.predict_tokens(self._preview(content, system), model) > предел
        )
        # Поднятых с диска пар не может быть больше, чем пар в памяти: обрезка только что
        # могла выбросить как раз их. Оставь число прежним — и запись прогона утверждала бы,
        # что обмену предшествовал подъём десяти пар, которых в запросе нет ни одной.
        self.restored_pairs = min(self.restored_pairs, len(self._messages) // 2)
        return dropped

    def build_messages(self, content: str, model: str = "") -> list[dict]:
        """Политика входа: что именно уйдёт в модель на этот вопрос.

        Имя модели нужно не сборке, а обрезке внутри неё: надбавка обёртки подстраивается
        под каждую модель отдельно. Умолчание — пустое имя, то есть базовый замер: у
        вызывающего, который просто смотрит, каким выйдет запрос, модели может и не быть.

        Системная инструкция всегда первая: так её видно отдельно от ввода пользователя,
        и так же работает кэширование общего начала запроса на стороне DeepSeek. Глобальные
        факты о пользователе подмешиваются в неё же, отдельным блоком после пустой строки:
        это знание о собеседнике, а не его реплика, и в разговор его класть нельзя — модель
        стала бы отвечать на него как на сказанное только что. Факты запрашиваются на каждой
        сборке: между двумя запросами человек мог добавить факт командой `/remember`.

        Вопрос в память здесь НЕ дописывается. Память пополняется только после успешного
        ответа, в `exchange`. Причина: неотвеченный вопрос не должен оседать в памяти —
        иначе после сетевого сбоя модель на следующем ходу увидит вопрос, на который
        никто не отвечал, и станет отвечать на него повторно.

        Список собирается новый, а сообщения памяти копируются: наружу не уходит ничего,
        через что вызывающий мог бы переписать память агента.

        Порядок работы такой: сперва собирается системная часть — инструкция и блок фактов, —
        потом ею и памятью обрезка взвешивает будущий запрос, и только потом собирается сам
        список сообщений. Обрезка по-прежнему идёт ДО сборки списка: обрежь после — и запрос
        ушёл бы полным, а урезанной осталась бы одна память, то есть ограничение не работало
        бы ровно там, ради чего заведено.

        Системная часть считается первой не для красоты порядка, а потому что взвешивать надо
        РОВНО ТО, что уйдёт в модель. Недосчитай обрезка блок фактов — и она решила бы
        «влезает» там, где не влезает: запрос ушёл бы тяжелее бюджета, и предел не сработал
        бы ровно в том случае, ради которого заведён. Ошибка в другую сторону стоила бы лишней
        выброшенной пары, то есть дёшево, — но это не повод считать неверно.

        И собирается системная часть ровно ОДИН РАЗ за сборку: источник фактов живёт снаружи
        и ходит на диск, а взвешивание обрезка зовёт столько раз, сколько блоков выбросит.

        Текст вопроса уходит в обрезку по той же причине: без него вес запроса неизвестен."""
        system = self.profile.system or ""
        block = ""
        if self._facts is not None:
            try:
                block = memory.facts_block(self._facts())
            except Exception as exc:  # noqa: BLE001 — источник фактов приходит снаружи
                # Сборка запроса идёт ДО начала обмена, и исключение отсюда улетело бы мимо
                # всей обработки: ни ответа, ни записи прогона в журнал. Сегодня чтение фактов
                # не бросает по построению, но гарантия «вспомогательный механизм не роняет
                # обмен» не имеет права держаться на чужом обещании.
                self.store_error = f"не удалось прочитать глобальную память: {exc}"
        if block:
            # Профиль без инструкции, но с фактами получает системное сообщение из одного
            # блока фактов: иначе факты пропадали бы ровно у встроенного `default`, которым
            # пользуются чаще всего.
            system = f"{system}\n\n{block}" if system else block
        self._dropped_pairs = self._trim(content, system=system, model=model)
        messages: list[dict] = []
        if system:
            messages.append({"role": "system", "content": system})
        if self.profile.keep_history:
            messages.extend(dict(m) for m in self._messages)
        messages.append({"role": "user", "content": content})
        return messages

    async def exchange(
        self,
        client,
        model: str,
        content: str,
        *,
        on_event: Callable[[api.StreamEvent], None] | None = None,
        agent: str | None = None,
        run_id: str | None = None,
    ) -> Turn:
        """Обмен с моделью: отправить вопрос, собрать поток ответа, записать прогон."""
        # Ошибка описывает ИМЕННО этот обмен. Не сбрось её здесь — и вчерашний отказ диска
        # показывался бы после каждого следующего запроса до конца сеанса. Сброс стоит ДО
        # сборки запроса: сборка читает глобальную память и при её сбое сама кладёт сюда
        # текст, а сброс после сборки стирал бы его, не показав никому.
        self.store_error = None
        request_messages = self.build_messages(content, model)
        # Вес памяти снимаем ЗДЕСЬ: обрезка уже прошла, а ответ в память ещё не лёг. Сними
        # его после обмена — и число описывало бы память следующего запроса, а не этого.
        history_tokens = self.history_tokens()
        # Вес одного текста, без надбавки, — мерка для калибровки: сервер пришлёт
        # `prompt_tokens` за ровно то же самое, и разность двух чисел и есть обёртка разговора.
        text_tokens = tokens.count_messages(request_messages, overhead=0)
        predicted = self.predict_tokens(request_messages, model)
        self.task = content
        # Поколение памяти на момент начала обмена: если к концу оно сменилось, память этого
        # обмена уже забыли, и пополнять её результатом нельзя.
        generation = self._generation
        answer_text = ""
        reasoning_text = ""
        finish_reason: str | None = None
        usage: dict[str, Any] = {}
        status = "error"
        error_text: str | None = None
        render_error: str | None = None
        started = time.monotonic()
        try:
            async for event in client.stream_chat(model, request_messages, self.profile.params):
                if on_event is not None:
                    try:
                        on_event(event)
                    except Exception as exc:
                        # `on_event` — это отрисовка, она живёт СНАРУЖИ агента. Выпусти её
                        # исключение отсюда — и оно попадёт в общий обработчик ошибок обмена
                        # ниже, а пользователь увидит «ошибка запроса к DeepSeek» при
                        # полностью живой сети: прямая ложь, из-за которой он пойдёт чинить
                        # то, что не сломано. Проглотить совсем тоже нельзя — причину
                        # запоминаем и отдаём в `Turn.error`, но только если обмен в
                        # остальном удался, и текстом, где нет слова DeepSeek.
                        render_error = f"ответ получен, но показать его не удалось: {exc}"
                if event.kind == "meta":
                    finish_reason = event.finish_reason
                    usage = event.usage
                    continue
                if event.kind == "reasoning":
                    reasoning_text += event.text
                else:
                    answer_text += event.text
            status = "ok"
        except asyncio.CancelledError:
            status = "cancelled"
            raise
        except Exception as exc:  # сеть, лимиты, ошибки API — не роняем harness
            error_text = str(exc)
        finally:
            elapsed = time.monotonic() - started
            snapshot = self.profile.snapshot()
            if status == "ok" and not answer_text:
                # Поток дошёл до конца, а ответа нет. Наверх обязан уйти внятный отказ,
                # а не бодрое «успех» с пустой строкой, которую вызывающий покажет
                # пользователю как ответ модели.
                #
                # Причину называем, когда она известна. Самый частый случай при включённых
                # рассуждениях: модель израсходовала весь `max_tokens` на размышление и
                # оборвалась, не начав ответ, — тогда сервер отдаёт причину остановки
                # `length`. Сказать просто «пустой ответ» значит заставить человека гадать,
                # хотя ответ лежит в тех же данных: лечится увеличением `max_tokens`.
                status = "error"
                if finish_reason == "length":
                    error_text = (
                        "весь max_tokens ушёл на рассуждения, ответ не начат — увеличьте max_tokens"
                    )
                else:
                    error_text = "модель вернула пустой ответ"
            if status == "ok":
                if render_error:
                    error_text = render_error
                # Пара кладётся ТОЛЬКО через `remember` — второй точки записи в память нет.
                # Поколение сверяем здесь: `forget`, пришедший посреди обмена (командой
                # `/clear` или сменой профиля), означает, что этот разговор уже забыт, — и
                # дописывать в него ответ на давно снятый вопрос нельзя.
                if self.profile.keep_history and self._generation == generation:
                    # Запись на диск живёт внутри `remember` и своих исключений не выпускает:
                    # мы в `finally`, до записи в журнал и до сборки результата, и исключение
                    # отсюда уничтожило бы и полученный ответ, и запись прогона. Перехват
                    # всё же ставим: гарантия «не бросает» обязана быть с обеих сторон, а
                    # не только в чужом модуле, который завтра поправят.
                    try:
                        self.remember(content, answer_text, model=model)
                    except Exception as exc:  # обмен дороже любой записи на диск
                        self.store_error = f"не удалось сохранить разговор: {exc}"
            # При любом неуспехе память не трогаем вовсе: вопроса там нет, `build_messages`
            # его туда не клал, — вычищать нечего.
            # Счётчики пополняем здесь, в `finally`: сюда приходит и успех, и отказ, и отмена
            # (после `raise` тело `finally` всё равно выполняется). Пополни их в ветке успеха —
            # и статистика молча потеряла бы самые дорогие обмены.
            self.runs += 1
            self.total_ms += int(elapsed * 1000)
            self.total_tokens += usage_tokens(usage)
            self.session_usage = tokens.add_usage(self.session_usage, usage)
            # Самокалибровка надбавки: сервер только что назвал вес того же самого текста,
            # и разность — это обёртка разговора, какой она есть сегодня, а не какой её
            # замерили однажды. Подстраивается надбавка ИМЕННО ЭТОЙ модели: у соседней она
            # своя. `bool` отсеиваем отдельно: в Python он подкласс `int`.
            #
            # Принимаем только правдоподобное значение — от нуля до `OVERHEAD_LIMIT`.
            # Отрицательная обёртка означала бы, что разговор отнимает токены; надбавка в
            # сотни тысяч — что сервер прислал счёт не от нашего запроса. И то и другое надо
            # не «поджать к границе», а ОТВЕРГНУТЬ целиком, оставив прежнее число: поджатая
            # к тысяче нелепость точно так же выбросила бы половину памяти. Молча: это сбой
            # чужой стороны, а не событие разговора, и человеку тут делать нечего.
            prompt_tokens = usage.get("prompt_tokens") if isinstance(usage, dict) else None
            if isinstance(prompt_tokens, int) and not isinstance(prompt_tokens, bool):
                measured = prompt_tokens - text_tokens
                if 0 <= measured <= OVERHEAD_LIMIT:
                    self._overhead[model] = measured
            entry: dict[str, Any] = {
                "status": status,
                "model": model,
                "profile": snapshot,
                "query": content,
                "messages": request_messages,
                "response": answer_text or None,
                "reasoning": reasoning_text or None,
                "finish_reason": finish_reason,
                "usage": usage or None,
                # Номер обмена в сеансе: `self.runs` уже пополнен, значит первый обмен — 1.
                # Без номера кривая расхода по журналу строилась бы по времени записи, а оно
                # у одновременных обменов группы совпадает.
                "index": self.runs,
                "history_tokens": history_tokens,
                "predicted_prompt_tokens": predicted,
                "agent_session_tokens": self.session_usage["total_tokens"],
                "elapsed_ms": int(elapsed * 1000),
                "error": error_text,
            }
            # Денег в записи нет намеренно: тариф — не источник правды, он живёт на странице
            # цен поставщика и протухнет молча. Записанная цена через полгода была бы враньём,
            # которое уже не проверить, а токены останутся токенами: деньги считаются поверх
            # журнала, действующим тарифом.
            if self._over_budget:
                # Ключ появляется только при превышении: у обмена, уместившегося в предел,
                # «over_budget: false» в каждой строке журнала — шум, за которым перестают
                # замечать настоящие случаи.
                entry["over_budget"] = True
            if self.restored_pairs:
                # Ключ появляется только когда пары действительно поднимались с диска: у
                # чистого сеанса ноль здесь ничего не объясняет, а строку записи удлиняет.
                entry["restored_pairs"] = self.restored_pairs
            if agent:
                entry["agent"] = agent
            if run_id:
                entry["run_id"] = run_id
            journal_error = journal.append(entry)
            turn = Turn(
                status=status,
                text=answer_text,
                reasoning=reasoning_text,
                finish_reason=finish_reason,
                usage=usage,
                elapsed_ms=int(elapsed * 1000),
                error=error_text,
                request_messages=request_messages,
                model=model,
                profile_snapshot=snapshot,
                dropped_pairs=self._dropped_pairs,
                index=self.runs,
                history_tokens=history_tokens,
                predicted_prompt=predicted,
                agent_session_tokens=self.session_usage["total_tokens"],
                over_budget=self._over_budget,
                journal_error=journal_error,
                store_error=self.store_error,
            )
        return turn
