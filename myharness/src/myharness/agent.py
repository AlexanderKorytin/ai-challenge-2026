@dataclass(frozen=True)
class Якорь:
    """Снимок состояния памяти на тот миг, когда из неё сняли пары для сжатия.

    Заготовка описывает НЕ ЧИСЛО ПАР, а конкретные пары — те, что лежали в памяти, когда
    фоновая задача их снимала. Сдвинься память между снятием и принятием (обрезка успела
    выбросить блок, человек отдал `/clear`), и пересказ приписался бы ДРУГИМ парам молча:
    числа сошлись бы, а речь в выжимке шла бы о другом куске разговора.

    Двух чисел довольно, и оба обязательны. Счёт пройденных пар растёт ровно тогда, когда
    пары уходят из памяти навсегда, — то есть ловит любой сдвиг СТАРОГО края памяти, за
    который заготовка и отвечает. Поколение ловит очистку разговора, при которой счёт
    обнуляется и сам по себе ничего не сказал бы. Пополнение памяти новой парой не трогает
    ни то, ни другое — и правильно: старые пары от него не сдвигаются.

    Снимается якорь ВМЕСТЕ с парами, одним вызовом `снять_для_сжатия`, и только им: возьми
    фоновая задача пары в одну секунду, а якорь в другую — сверять было бы нечего, потому что
    якорь описывал бы не тот миг, из которого взяты пары.
    """

    пройдено: int
    поколение: int


@dataclass
class Ограничитель:
    """Один ограничитель обрезки, измеренный в СВОИХ единицах: сколько набрано из скольких.

    Заведён затем, чтобы «который сработает первым» считалось в ОДНОМ месте. Считающих
    двое — заготовка выжимки и полоска занятости над строкой ввода, — и разойдись они хоть
    в правиле выбора, отметка на восьми десятых стояла бы не там, где что-то происходит.

    Единицы не приводятся к общей мерке намеренно: пересчитать пары в токены можно, а обратно
    — нет, и «9 из 15 пар» человеку понятнее любой пересчитанной доли. Сравнимой величиной
    остаётся только ДОЛЯ — сколько пути до срабатывания пройдено.
    """

    имя: str
    единицы: str  # «пар» или «токенов» — ими подписаны числа в строке под полоской
    текущее: int
    порог: int

    @property
    def доля(self) -> float:
        """Сколько пути до срабатывания пройдено — число от нуля до единицы.

        За единицу не уходит: доля отвечает «сколько пройдено», а пройденного больше, чем
        весь путь, не бывает. Насколько запрос ушёл СВЕРХ порога, говорит `перебор` — двумя
        числами, а не одним, потому что заполнение полоски и величина перебора отвечают на
        разные вопросы, и слив их в одно число, полоску пришлось бы рисовать длиннее жёлоба.
        """
        if self.порог <= 0:
            return 0.0
        return min(1.0, self.текущее / self.порог)

    @property
    def перебор(self) -> int:
        """На сколько уже ушли сверх порога; ноль — ещё не ушли."""
        return max(0, self.текущее - self.порог)


def usage_tokens(usage: dict[str, Any] | None) -> int:
    """Сколько токенов стоил обмен по данным `usage`.

    Считать нечем — считаем нулём, а не падаем: `usage` приходит от сервера, и при обрыве
    потока или отказе его может не быть вовсе. Уронить на этом сбор статистики значило бы
    потерять и сам ответ, который уже получен.

    `total_tokens` предпочитаем сумме слагаемых: сервер кладёт туда собственный итог, и он
    учитывает то, чего в двух слагаемых нет, — например попадания в кэш начала запроса."""
    # Разбор `usage` живёт в одном месте — `tokens.normalize`. Своя копия правила была
    # здесь до появления модуля счёта и успела разойтись с ним на кривых данных: при
    # `total_tokens: 0` с непустыми слагаемыми она давала ноль, при `total_tokens: true` —
    # единицу (в Python `True` это `1`). В списке агентов рядом со строкой ожидания вставало
    # «Σ 0», и человек шёл искать поломку в учёте, которой нет.
    return tokens.normalize(usage)["total_tokens"]


def _годное_приложение(приложение: dict | None) -> dict[str, Any]:
    """Оставляет от приложения только его два поля и только непустыми.

    Пустое приложение — то же, что его отсутствие: ключ `"приложение"` у ответа без
    содержимого лишь заставлял бы каждого читателя памяти проверять пустоту второй раз.

    Звенья проверяются тем же правилом, что при чтении файла (`memory.звенья_годны`): звено
    с чужой ролью нарушило бы чередование в раскрытом запросе, и пропусти его память — файл
    при следующем запуске отверг бы то, что память сегодня приняла."""
    if not isinstance(приложение, dict):
        return {}
    годное: dict[str, Any] = {}
    рассуждения = приложение.get("reasoning_content")
    if isinstance(рассуждения, str) and рассуждения:
        годное["reasoning_content"] = рассуждения
    звенья = приложение.get("звенья")
    if звенья and memory.звенья_годны(звенья):
        годное["звенья"] = звенья
    return годное


def _вес_памяти(сообщения: list[dict]) -> list[dict]:
    """Вид памяти, по которому она ВЗВЕШИВАЕТСЯ: всегда полное раскрытие, без копий.

    Вес — не описание последней сборки, а обещание о любой следующей. Взвешивай память по
    виду прошлого запроса — и между сборками (подъём при запуске, заготовка выжимки, снятие
    паузы) разговор с тяжёлыми звеньями весил бы голым, а первый же запрос с инструментами
    выбросил бы пары дословно, без пересказа. Перевес запроса без инструментов — безопасная
    сторона: пара уйдёт в пересказ чуть раньше. У профиля без карты стадий приложений нет, и
    полный вид совпадает с голым байт в байт — вес прежний."""
    return раскрыть(сообщения, True, копировать=False)


def раскрыть(сообщения: list[dict], полные: bool, *, копировать: bool = True) -> list[dict]:
    """Память → сообщения запроса. Единственное правило, по которому пара уходит в API.

    `полные=False` — голый вид: у каждого сообщения только роль и текст. Так уходил любой
    запрос до инструментов, и так он уходит без них: ключ `"приложение"` из памяти в API не
    попадает.

    `полные=True` — запрос с инструментами. DeepSeek требует вернуть ему цепочку круга
    целиком: вопрос, затем звенья (ответы модели с вызовами и результаты инструментов), затем
    итоговый ответ со своими рассуждениями. `reasoning_content` ставится, только если он
    записан: живой замер показал, что сервер не отказывает паре без рассуждений даже при
    `tools`, а выдумывать пустую строку значило бы писать в запрос то, чего не было.

    Всё отдаётся новыми списками и словарями (звенья — глубокой копией): через результат
    переписать память нельзя.

    `копировать=False` — только для взвешивания: звенья отдаются теми же словарями, что лежат
    в памяти. Обрезка взвешивает запрос на каждом витке, и глубокая копия всей памяти там
    стоила бы времени без всякой пользы — результат счёта наружу не уходит."""
    итог: list[dict] = []
    for сообщение in сообщения:
        голое = {"role": сообщение.get("role"), "content": сообщение.get("content")}
        if not полные or сообщение.get("role") != "assistant":
            итог.append(голое)
            continue
        приложение = сообщение.get("приложение")
        if not isinstance(приложение, dict):
            итог.append(голое)
            continue
        звенья = приложение.get("звенья")
        if isinstance(звенья, list):
            итог.extend(copy.deepcopy(звенья) if копировать else звенья)
        рассуждения = приложение.get("reasoning_content")
        if isinstance(рассуждения, str) and рассуждения:
            голое["reasoning_content"] = рассуждения
        итог.append(голое)
    return итог


@dataclass
class Инструменты:
    """Набор инструментов одного обмена: что предложить модели и как исполнить вызов.

    Агент смысла инструментов не знает — схемы уходят в запрос как есть, а вызов уходит
    исполнителю именем и строкой доводов JSON как пришла. Исполнитель возвращает текст
    результата; его исключение агент превращает в текст «ошибка инструмента: …», и круг
    продолжается: модель должна узнать о сбое, а не потерять весь обмен."""

    схемы: list[dict]
    исполнить: Callable[[str, str], Awaitable[str]]


@dataclass
class Turn:
    """Итог одного обмена с моделью — тем, кто позвал: тексту ответа и цене.

    Запись полная: по ней видно не только что ответила модель, но и что именно ей
    ушло, — вызывающему не приходится лезть внутрь агента за подробностями."""

    status: str
    text: str = ""
    reasoning: str = ""
    finish_reason: str | None = None
    usage: dict[str, Any] = field(default_factory=dict)
    elapsed_ms: int = 0
    error: str | None = None
    # что фактически ушло в модель — иначе прогон не воспроизвести и не сверить
    request_messages: list[dict] = field(default_factory=list)
    # какой моделью получен ответ: модель меняется на лету, а запись остаётся
    model: str = ""
    # слепок профиля для журнала — инструкция и параметры на момент запроса
    profile_snapshot: dict[str, Any] = field(default_factory=dict)
    # сколько пар выброшено окном памяти перед этим запросом — чтобы показать усечение
    dropped_pairs: int = 0
    # Из них: сколько пар заменено выжимкой и сколько потеряно ДОСЛОВНО. Два числа, а не
    # одно, потому что это два разных исхода с разной ценой: замена дословного текста
    # пересказом заметна по ответам, но необъяснима, если о ней не сказали, — а дословная
    # потеря невозвратна. По этой паре чисел человек и решает, звать ли сжатие руками.
    compacted_pairs: int = 0
    forgotten_pairs: int = 0
    # Сколько пар ПРОЙДЕНО разговором на этот момент: обе потери вместе, за всю его жизнь.
    # Третье число, а не разность двух первых: те описывают один ход, а человеку надо знать,
    # сколько разговора уже стоит за выжимкой. По ходовым числам это не восстановить.
    passed_pairs: int = 0
    # какой это по счёту обмен в сеансе — по нему кривая расхода строится без домыслов
    index: int = 0
    # сколько весила память на момент ЭТОГО запроса: цена того, что агент помнит
    history_tokens: int = 0
    # предсказание веса запроса, сделанное ДО отправки: рядом с настоящим `usage` по нему
    # видно, насколько предсказание врёт, — иначе судить о точности счёта было бы не по чему
    predicted_prompt: int = 0
    # расход сеанса нарастающим итогом на конец этого обмена
    # Расход ЭТОГО агента за сеанс — не итог сеанса целиком: агент про соседей не знает.
    # Имя названо по смыслу, чтобы не спутать с общим итогом на экране и в /tokens.
    agent_session_tokens: int = 0
    # предел веса задан, обрезка сделала что могла, а запрос всё равно ушёл тяжелее предела
    over_budget: bool = False
    # текст ошибки записи журнала: сам обмен удался, а предупредить надо снаружи
    journal_error: str | None = None
    # то же самое про запись разговора на диск: обмен состоялся и оплачен, а память между
    # запусками не сохранилась — молчать об этом нельзя, ронять обмен из-за этого тоже
    store_error: str | None = None
    # Фактическая политика и выбор завершённых пар для этого запроса. У строгих стратегий
    # исключённые пары остаются в полной памяти, поэтому эти числа не выводятся из dropped.
    context_strategy: str = context_strategy.CONTEXT_STANDARD
    selected_pairs: int = 0
    omitted_pairs: int = 0
    # Sticky Facts: редакция, которую видел основной запрос, отдельно от редакции после
    # извлечения. Отсутствующий серверный расход остаётся None, а не локальной оценкой.
    facts_revision: int | None = None
    facts_revision_after: int | None = None
    facts_usage: dict[str, Any] | None = None
    facts_error: str | None = None
    # Branching описывает путь на миг отправки: прежнюю голову, от которой вырос успешный
    # узел, и неизменяемую контрольную точку разделения.
    branch: str | None = None
    branch_head: str | None = None
    branch_checkpoint: str | None = None
    # Сообщения круга инструментов по порядку: ответы модели с вызовами и результаты с ролью
    # `tool`. Пусто, если модель ничего не вызывала или инструментов в обмене не было.
    звенья: list[dict] = field(default_factory=list)

    @property
    def ok(self) -> bool:
        return self.status == "ok"


class Agent:
    """Собеседник со своей памятью: имя, профиль и накопленные пары «вопрос — ответ»."""

    def __init__(
        self,
        name: str,
        profile: Profile,
        *,
        store: memory.SessionStore | None = None,
        facts: Callable[[], list[str]] | None = None,
        facts_store: memory.FactsStore | None = None,
        branch_store: memory.BranchStore | None = None,
        branch: str | None = None,
        project: Callable[[], str] | None = None,
        work: Callable[[], str] | None = None,
        инструменты: Callable[[], Инструменты | None] | None = None,
    ) -> None:
        self.name = name
        self.profile = profile
        # Хранилище разговора между запусками. Умолчание — ВЫКЛЮЧЕНО, и это не осторожность,
        # а необходимость: агентов в процессе много, а разговор пользователя один. Наряд из
        # ста заданий и панели исполнителей группы, заведи они хранилище сами, писали бы в
        # каталог состояния наперегонки поверх переписки человека.
        self._store = store
        # Глобальные факты о пользователе — ВЫЗЫВАЕМЫЙ объект, а не готовый список. Факты
        # меняются по ходу сеанса (командой `/remember` и архивариусом), и список, снятый
        # при создании агента, отстал бы от них к первому же запросу.
        self._facts = facts
        # Карточка проекта и состояние текущей задачи — тоже ВЫЗЫВАЕМЫЕ, и ровно по той же
        # причине, что факты. Карточку человек правит руками между двумя вопросами, а задача
        # меняется командой `/task` прямо посреди разговора: блок, снятый при создании агента,
        # отстал бы от обоих. Умолчание — `None`, то есть слоёв нет вовсе: исполнители группы,
        # пакетный наряд и архивариус собирают ровно тот же запрос, что и до появления слоёв.
        self._project = project
        self._work = work
        # Поставщик инструментов — ВЫЗЫВАЕМЫЙ по той же причине, что `work`: есть ли у
        # обмена инструменты, решает состояние задачи на миг запроса (пауза, закрытая
        # задача), а не миг создания агента. Зовётся ровно один раз за обмен, в его начале:
        # набор, сменившийся посреди круга, предложил бы модели не те инструменты, что
        # взвешены и отправлены. Умолчание — `None`: служебные агенты (архивариус,
        # сжиматель, извлекатель фактов, исполнители группы) инструментов не получают.
        self._инструменты = инструменты
        # Вес описаний инструментов ПОСЛЕДНЕГО обмена — для тех, кто взвешивает запрос вне
        # обмена (полоска занятости, заготовка выжимки, строка ожидания). Звать поставщика на
        # каждое нажатие клавиши нельзя: он читает состояние задачи. Цена — отставание на один
        # обмен: после включения или снятия паузы и после смены стадии задачи (схема
        # консилиума есть не во всякой стадии) первый расчёт вне обмена ещё несёт прежний
        # вес. Сама обрезка внутри обмена получает точный вес доводом.
        self._вес_инструментов = 0
        # Хранилища новых стратегий тоже приходят готовыми. Агент не знает рабочего каталога
        # и не выбирает путь сам: пакетный агент может законно жить вообще без диска.
        self._facts_store = facts_store
        self._conversation_facts = memory.ConversationFacts()
        self._branch_store = branch_store
        self._branch = branch
        self._branch_head: str | None = None
        self._branch_checkpoint: str | None = None
        # Непригодный путь и корень после разделения не имеют права даже обратиться к
        # модели: родитель становится закрытым в момент записи события split.
        self._branch_error: str | None = None
        # Идёт загрузка прежнего разговора: пополнение памяти на диск не пишется. Иначе
        # чтение файла тут же переписывало бы его самим собой, удваивая каждую пару.
        self._restoring = False
        # Чем кончилась последняя попытка записи разговора на диск. Поле, а не исключение:
        # хранилище — вспомогательный механизм, и ронять им уже оплаченный обмен нельзя.
        self.store_error: str | None = None
        self._messages: list[dict] = []
        # Выжимка — пересказ пройденного куска разговора, который встаёт в системную часть
        # запроса вместо выброшенных обрезкой пар. Заводится и хранится СНАРУЖИ (фоновой
        # задачей сжимателя, файлом рядом с разговором), сюда приходит готовой: агент про
        # сеть и диск не знает и знать не должен.
        self._summary: compact.Выжимка | None = None
        # Заготовка: выжимка, собранная заранее — при подходе к ближайшему ограничителю. Она
        # ждёт своего часа отдельно от действующей и встаёт на её место в тот момент, когда
        # обрезка что-то выбросила. Готовить заранее нужно потому, что иначе человек ждал бы
        # лишний обмен ровно тогда, когда разговор уже длинный и ответы и так идут дольше.
        self._prepared: compact.Выжимка | None = None
        # сколько пар выбросила обрезка перед последней сборкой запроса — отсюда в `Turn`
        self._dropped_pairs = 0
        # из них: сколько подобрано выжимкой и сколько потеряно дословно — туда же
        self._compacted_pairs = 0
        self._forgotten_pairs = 0
        # Сколько пар ушло из памяти НАВСЕГДА за всю жизнь этого разговора — и пересказанных,
        # и забытых дословно. Копится, а не считается по памяти: в памяти их уже нет, а
        # человеку по этому числу видно, сколько разговора стоит за выжимкой.
        self.passed_pairs = 0
        # не удержался ли последний запрос в пределе веса — оттуда же в `Turn` и в журнал
        self._over_budget = False
        # Фактический выбор последней сборки запроса. Снимается до отправки и потому не
        # пересчитывается по памяти, уже пополненной ответом.
        self._selected_pairs = 0
        self._omitted_pairs = 0
        self._request_branch_head: str | None = None
        # Ушёл ли в ПОСЛЕДНИЙ собранный запрос блок выжимки. Признак, а не пересчёт условий
        # задним числом: между сборкой запроса и записью прогона выжимка не меняется, но
        # завтра появится повод, по которому она сменится, — и запись прогона начала бы
        # уверять, что модель видела пересказ, которого она не видела. По этому полю по
        # журналу отличают обмен с дословным разговором от обмена с его пересказом, а это
        # два разных обмена с разной ценой и разным качеством ответа.
        self._summary_sent = False
        # Поколение памяти: `forget` его увеличивает. Обмен запоминает поколение в начале и
        # пополняет память, только если оно не сменилось. Без этого счётчика `/clear`,
        # отданный посреди идущего обмена, «очищал» бы память на словах: обмен доходит до
        # своего `finally` уже после команды и кладёт пару обратно.
        self._generation = 0
        # Сигналы очистки для исполняемых сейчас инструментов: `forget` взводит их все и
        # забывает, следующий исполнитель заводит новый. Сигнал заводится на каждое
        # исполнение внутри работающего цикла, а не хранится на поколение: `asyncio.Event`
        # привязывается к циклу при первом ожидании, а `forget` зовётся и вне цикла, и
        # между разными `asyncio.run`.
        self._сигналы_очистки: set[asyncio.Event] = set()
        # Счётчики за всё время жизни агента: их показывает список агентов под строкой ввода.
        # СЧИТАЕМ И НЕУДАЧНЫЕ, И ОТМЕНЁННЫЕ ОБМЕНЫ — это не недосмотр, а решение.
        # Время на упавший запрос потрачено, токены на него у поставщика списаны, и список,
        # показывающий только удачные обмены, рисует агента дешевле, чем он есть.
        # Дороже всего обходится как раз агент, который падает и уходит на повтор.
        self.runs = 0  # сколько обменов было — всего, при любом исходе
        self.total_ms = 0  # сколько времени на них ушло
        self.total_tokens = 0  # сколько токенов израсходовано
        # Расход ТЕКУЩЕГО сеанса, покомпонентно: вход, выход, попадания в кэш, рассуждения.
        # Заведён рядом с `total_tokens`, а не вместо него: на том счётчике держится колонка
        # списка агентов, и подменить его разбивкой значило бы тихо сменить смысл колонки.
        # Разбивка нужна там, где считают деньги: вход из кэша стоит в тридцать раз дешевле
        # промаха, и по одной сумме цену не назвать.
        # Пустым словарём не заводим, хотя до первого обмена расходовать было нечего: форма
        # у накопителя обязана быть одна и та же с первой секунды. Иначе строка ожидания и
        # `/tokens`, спросив `session_usage["total_tokens"]` на чистом запуске, получили бы
        # `KeyError` — причём не на проверках, а у человека сразу после старта.
        self.session_usage: dict[str, int] = tokens.total_usage([])
        # Надбавка обёртки разговора: сколько токенов сервер прибавляет к тексту реплик.
        # 83 — живой замер 2026-09-09, то есть начальное приближение, а не закон: DeepSeek
        # вправе изменить обёртку, ничего нам не сказав, и тогда предсказание начнёт врать
        # молча. Поэтому после каждого обмена, где сервер назвал `prompt_tokens`, число
        # подстраивается под него. Калибровка живёт на агенте и только на сеанс, в файл не
        # пишется: сохранённое число пережило бы и смену профиля, а характер запросов у
        # профилей разный — вышла бы уверенная ложь вместо честного приближения.
        #
        # Хранится ПО МОДЕЛЯМ, а не одним числом, по двум причинам сразу. Первая: модель
        # меняется на лету командой `/model`, и надбавка, снятая на `v4-pro`, к
        # `flash-vision-exp` отношения не имеет. Вторая важнее: в это число оседает не только
        # обёртка, но и вся систематическая разница нашего счёта с серверным, а она растёт с
        # длиной запроса — расхождение в 2% на разговоре в 8000 токенов даёт надбавку под 250
        # вместо 83. Смешай такую поправку между моделями — и короткий вопрос к другой модели
        # предсказывался бы втрое дороже, чем стоит.
        self._overhead: dict[str, int] = {}
        # Сколько пар поднято с диска при запуске. Обмен, которому предшествовал подъём
        # прежнего разговора, стоит дороже обмена с чистой памятью, и по записи прогона
        # должно быть видно, откуда взялся такой вход, — иначе кривая расхода необъяснима.
        self.restored_pairs = 0
        # Над чем агент работает: содержание последнего запроса. Список агентов показывает
        # это в колонке занятия, пока агент занят. Держим здесь, а не в панели: работу знает
        # тот, кто её делает, и агент без панели (пакетный наряд) знает её точно так же.
        self.task = ""
        self._load_strategy_state()

    def _load_strategy_state(self) -> None:
        """Поднять переданные состояние фактов или путь ветви, не выбирая им место на диске."""
        strategy = self.profile.context_strategy
        if strategy == context_strategy.CONTEXT_FACTS and self._facts_store is not None:
            restored, warnings = self._facts_store.load()
            self._conversation_facts = restored
            if warnings:
                self.store_error = "; ".join(warnings)

        if strategy != context_strategy.CONTEXT_BRANCHING or self._branch_store is None:
            return
        restored = self._branch_store.load()
        self._branch_checkpoint = restored.checkpoint_id
        if restored.warnings:
            self.store_error = "; ".join(restored.warnings)
        if restored.checkpoint_id is None:
            if self._branch is not None:
                self._branch_error = f"ветвь {self._branch!r} ещё не создана"
                self.store_error = self._branch_error
                return
            self._branch_head = restored.root_head
        else:
            if self._branch is None:
                self._branch_error = "родительский разговор уже разделён и недоступен"
                self.store_error = self._branch_error
                return
            if self._branch not in restored.branches:
                self._branch_error = f"неизвестная активная ветвь {self._branch!r}"
                self.store_error = self._branch_error
                return
            if self._branch in restored.unavailable or self._branch not in restored.heads:
                self._branch_error = (
                    f"ветвь {self._branch!r} недоступна из-за повреждения графа"
                )
                self.store_error = self._branch_error
                return
            self._branch_head = restored.heads[self._branch]
        self.restore(restored.path(self._branch))

    def conversation_facts(self) -> tuple[dict[str, str], int]:
        """Словарь текущего разговора и его редакция — копией."""
        return dict(self._conversation_facts.values), self._conversation_facts.revision

    def _apply_conversation_facts(
        self,
        set_values: dict[str, str],
        forget_keys: tuple[str, ...],
        *,
        turn_id: str,
        source: str,
    ) -> str | None:
        """Применить одну проверенную операцию; при отказе диска редакцию не менять."""
        from . import sticky_facts

        current = self._conversation_facts
        changes = sticky_facts.FactChanges(dict(set_values), tuple(forget_keys))
        updated = sticky_facts.apply_changes(current.values, changes)
        if self._facts_store is None:
            self._conversation_facts = memory.ConversationFacts(updated, current.revision + 1)
            return None

        error = self._facts_store.append(
            changes.set_values,
            changes.forget_keys,
            turn_id=turn_id,
            source=source,
        )
        if error is not None:
            return error
        restored, warnings = self._facts_store.load()
        self._conversation_facts = restored
        return "; ".join(warnings) or None

    def set_conversation_fact(self, key: str, value: str) -> str | None:
        """Записать правку человека в словарь текущего разговора."""
        if not isinstance(key, str) or not key.strip():
            return "ключ факта должен быть непустым текстом"
        if not isinstance(value, str) or not value.strip():
            return "значение факта должно быть непустым текстом"
        return self._apply_conversation_facts(
            {key.strip(): value.strip()},
            (),
            turn_id=uuid4().hex,
            source="user",
        )

    def forget_conversation_fact(self, key: str) -> str | None:
        """Записать удаление ключа человеком; отсутствие ключа безопасно."""
        if not isinstance(key, str) or not key.strip():
            return "ключ факта должен быть непустым текстом"
        return self._apply_conversation_facts(
            {},
            (key.strip(),),
            turn_id=uuid4().hex,
            source="user",
        )

    def split_branches(
        self, left: str, right: str
    ) -> tuple[dict[str, Agent] | None, str | None]:
        """Разделить корень у его головы и вернуть два агента с независимыми путями.

        Дочерние агенты наследуют ВСЕ ТРИ слоя памяти, а не один. Сегодня это ничего не
        меняет: ветвление живёт на экране стратегий, где слоёв нет вовсе, и слои получает
        только собеседник главного экрана. Но наследовать ровно один слой из трёх — мина с
        отложенным сроком: как только ветвление окажется на главном экране, разделение молча
        отняло бы у обеих ветвей карточку проекта и рабочее состояние, а искали бы поломку в
        карточке. Разделение разделяет разговор, а не память о человеке, папке и задаче.
        """
        if self.profile.context_strategy != context_strategy.CONTEXT_BRANCHING:
            return None, "разделение доступно только в режиме branching"
        if self._branch_store is None:
            return None, "для разделения не передано хранилище ветвей"
        if self._branch is not None:
            return None, "активную ветвь нельзя разделить повторно"
        error = self._branch_store.split(self._branch_head, left, right)
        if error is not None:
            return None, error
        self._branch_checkpoint = self._branch_head
        self._branch_error = "родительский разговор уже разделён и недоступен"
        branches = {
            name: Agent(
                f"{self.name}:{name}",
                self.profile,
                facts=self._facts,
                project=self._project,
                work=self._work,
                branch_store=self._branch_store,
                branch=name,
            )
            for name in (left.strip(), right.strip())
        }
        return branches, None

    def set_store(self, store: memory.SessionStore | None) -> None:
        """Сменить линейное хранилище и связанное с ним хранилище Sticky Facts.

        При `/clear` прежний FactsStore уже отвязан в `forget`, а новая сессия приходит
        сюда одним объектом. Вывести путь фактов из пути пары надёжнее, чем заставить
        вызывающего синхронно переставить два поля: забытый второй вызов воскресил бы
        старый словарь при ближайшей операции append → load."""
        self._store = store
        if self.profile.context_strategy == context_strategy.CONTEXT_FACTS:
            self._facts_store = (
                memory.FactsStore(store.path)
                if store is not None
                else None
            )

    def history(self) -> list[dict]:
        """Память разговора — копией.

        Отдай сам список — и любой снаружи сможет незаметно дописать или стереть память
        агента, минуя `remember`. Тогда инкапсуляция перестаёт что-либо значить: правил
        пополнения памяти больше нет, а искать, кто её испортил, придётся по всему коду."""
        # Глубокая копия, а не поверхностная: у ответа бывает приложение — словарь со списком
        # звеньев, — и поверхностная копия отдала бы наружу ссылку на него, то есть способ
        # переписать память мимо `remember`.
        return copy.deepcopy(self._messages)

    def выжимка(self) -> compact.Выжимка | None:
        """Действующая выжимка — та, что уходит в системную часть запроса.

        Метод, а не открытое поле, по той же причине, что и `history`: подмена выжимки —
        событие того же веса, что и подмена памяти, и мест, где оно происходит, должно быть
        ровно столько, сколько видно в дереве вызовов.
        """
        return self._summary

    def запомнить_выжимку(self, готовая: compact.Выжимка | None) -> None:
        """Поставить выжимку действующей — при подъёме разговора с диска или ручном сжатии."""
        self._summary = готовая

    def заготовка(self) -> compact.Выжимка | None:
        """Заготовка, ждущая ближайшей обрезки; `None` — заготовки нет."""
        return self._prepared

    def снять_для_сжатия(self, пар: int) -> tuple[list[tuple[str, str]], Якорь]:
        """Самые старые `пар` пар памяти и якорь её состояния — снятые ОДНИМ мигом.

        Единственный способ получить якорь, и это главное в устройстве: подделать его нельзя
        не потому, что он спрятан, а потому, что годным его делает совпадение с нынешним
        состоянием агента — тем самым, при котором заготовку и надо принять. Возьми фоновая
        задача пары здесь, а якорь отдельным вызовом позже — и сверка потеряла бы смысл,
        подтверждая не «память не двигалась», а «на момент второго вызова не двигалась».

        Пары отдаются копией и с проверкой чередования ролей: непарного хвоста в памяти не
        бывает (`remember` кладёт обе половины разом), но складывать пары из списка нечётной
        длины значило бы приписать вопросу чужой ответ — и это уехало бы в пересказ.
        """
        пары: list[tuple[str, str]] = []
        for номер in range(0, min(пар * 2, len(self._messages)) - 1, 2):
            вопрос, ответ = self._messages[номер], self._messages[номер + 1]
            if вопрос["role"] == "user" and ответ["role"] == "assistant":
                пары.append((вопрос["content"], ответ["content"]))
        return пары, self._якорь()

    def _якорь(self) -> Якорь:
        """Якорь нынешнего состояния памяти — одно место, где он собирается."""
        return Якорь(self.passed_pairs, self._generation)

    def принять_заготовку(self, готовая: compact.Выжимка | None, *, якорь: Якорь) -> None:
        """Положить заготовку, собранную фоновой задачей.

        Действующей выжимкой она НЕ становится: пока обрезка ничего не выбросила, заменять
        нечего, а подставь мы её сразу — в запросе оказались бы разом и пересказ пар, и сами
        эти пары, то есть один и тот же кусок разговора дважды и за двойные деньги.

        Агент без хранилища разговора заготовку не принимает вовсе, и заслон стоит ИМЕННО
        ЗДЕСЬ — в одном месте, а не в двух. Так «сжатие доступно только агенту с хранилищем»
        становится свойством самого агента, а не обещанием того, кто его заводит. Цена
        ошибки денежная: наряд из ста заданий завёл бы сто сжимателей, каждый со своим
        запросом на дорогой модели, а класть получившиеся выжимки было бы некуда — файл
        выжимки лежит рядом с файлом сессии, которого у такого агента нет.

        Якорь сверяется здесь и только здесь: память могла сдвинуться, пока фоновая задача
        ходила к модели, и тогда заготовка описывает не то, что в памяти лежит теперь.
        Несовпадение — это ВЫБРОС заготовки, а не откладывание: пары, под которые она
        собрана, уже ушли, и дождавшись своего часа, она приписала бы пересказ чужим парам.

        Отпечаток инструкции — та же история и тот же исход: заготовка с чужим отпечатком
        выбрасывается, а не ждёт возврата прежней роли. РАЗНИЦА С ПРИМЕНЁННОЙ ВЫЖИМКОЙ здесь
        неочевидна, и стирать её нельзя: `_summary` при несовпавшем отпечатке НЕ выбрасывается
        — её просто не подставляют, потому что собрана она за деньги, а роль могут вернуть.
        Заготовка же ещё не применена, и её пары ЛЕЖАТ В ПАМЯТИ дословно — пока она ждёт, их
        выбросит обрезка, и ждать станет незачем.
        """
        if self._store is None or якорь != self._якорь() or not self._подставляется(готовая):
            return
        self._prepared = готовая

    def сжать_сейчас(self) -> int:
        """Применить готовую заготовку немедленно, не дожидаясь обрезки. Сколько пар ушло.

        ЕДИНСТВЕННОЕ исключение из правила «сжатие перехватывает обрезку, а не решает само», и
        оно названо вслух: человек не механизм, и его прямая команда старше расписания. Второе
        место принятия решения появилось бы, заведи повод сжать САМ ИНСТРУМЕНТ; команда таким
        поводом не является. Зовётся только из обработчика команды человека — заведи отсюда
        расписание, и правило рухнет молча.

        Пары выбрасывает та же единственная точка, что и обрезка, и счёт пройденного растёт
        здесь ровно так же, как растёт в `_trim`. Удали мы сообщения напрямую — заготовка не
        стала бы действующей выжимкой, а пройденное разошлось бы с памятью в первом же прогоне
        и в первой же записи журнала.

        Ходовые счётчики обнуляются перед выбросом по той же причине, по какой их обнуляет
        `_trim`: они описывают ОДИН ход, и сложенные с прошлым ходом показали бы человеку
        замену пар, которой на этом ходу не было.
        """
        заготовка = self._prepared
        if заготовка is None:
            return 0
        self._compacted_pairs = 0
        self._forgotten_pairs = 0
        ушло = self._выбросить(заготовка.покрыто_пар)
        self.passed_pairs += ушло
        return ушло

    def подобрать_с_конца(
        self,
        пары: list[tuple[str, str]],
        *,
        приложения: list[dict] | None = None,
        facts: str = "",
        card: str = "",
        tail: str = "",
        model: str = "",
    ) -> int:
        """Сколько ПОСЛЕДНИХ пар из данных поднимется в память: столько, сколько влезет в порог.

        Правило ОДНО на два случая — и посреди разговора, и при подъёме с диска. Разведи их, и
        разговор, поднятый с диска, поехал бы в модель по одной мерке, а тот же разговор через
        десять ходов резался бы по другой; объяснить человеку, почему после перезапуска модель
        помнит больше или меньше, чем помнила минуту назад, было бы нечем.

        Порог выключен (`compact_at` равен нулю) либо профиль не хранит историю — берутся все
        поданные пары: окно по числу пар накладывает вызывающий, как накладывал до появления
        сжатия.

        Взвешивается ВЕСЬ будущий запрос — системная часть с блоком фактов и блоком выжимки
        плюс сами пары, — а не одна история: так же считает и обрезка. Нового вопроса в этом
        весе нет, и это единственная разница с обрезкой: при подъёме с диска человек ещё
        ничего не набрал. Ошибка идёт в безопасную сторону — подняв на один вопрос меньше
        веса, инструмент поднимет не больше пар, чем удержит следующим ходом.

        А вот эфемерный хвост рабочего состояния в весе ЕСТЬ и приходит доводом `tail`: он
        уедет в каждый следующий запрос независимо от того, что человек наберёт. Недосчитай
        мы его — подняли бы больше пар, чем влезает, и первый же вопрос выбросил бы лишние;
        при неготовой заготовке выжимки — выбросил бы дословно, то есть насовсем.

        Хотя бы одна пара поднимается всегда, даже если она одна тяжелее порога: последнюю
        пару обрезка не выбрасывает никогда, и восстановление не имеет права быть строже её —
        иначе разговор, упёршийся в порог, поднимался бы совершенно пустым.

        Блоки записей и карточки приходят готовыми и с пустым умолчанием — по тем же доводам,
        что у `ограничители`: источники ходят на диск, а вызывающий уже прочёл их один раз.

        `приложения` — те же, что пойдут в `restore`, по номеру пары; пары взвешиваются
        ПОЛНЫМ раскрытием, как и память посреди разговора (см. `_вес_памяти`). Взвесь их
        голыми — и разговор с тяжёлыми звеньями поднялся бы сверх порога, а первый запрос с
        инструментами выбросил бы лишнее дословно, без пересказа. Приложения иной длины в вес
        не идут: `restore` их тоже отбросит.
        """
        порог = self.порог_сжатия() if self.profile.keep_history else 0
        if порог <= 0 or not пары:
            return len(пары)
        система = self._система(facts, card)
        основа: list[dict] = [{"role": "system", "content": система}] if система else []
        if tail:
            # Хвост весит как текст сообщения, а не как часть системной части: он и уйдёт
            # текстом последнего сообщения. Считаем его отдельной строкой, чтобы не путать с
            # парами — выбрасывать его обрезка не может, он не пара.
            основа.append({"role": "user", "content": tail})
        if приложения is None or len(приложения) != len(пары):
            приложения = [{}] * len(пары)
        собранные: list[dict] = []
        взято = 0
        for (вопрос, ответ), приложение in zip(reversed(пары), reversed(приложения), strict=True):
            пара = [
                {"role": "user", "content": вопрос},
                {"role": "assistant", "content": ответ, "приложение": приложение},
            ]
            следующие = [*раскрыть(пара, True, копировать=False), *собранные]
            if self.predict_tokens([*основа, *следующие], model) > порог and взято > 0:
                break
            собранные = следующие
            взято += 1
        return взято

    def forget(self) -> None:
        """Забыть разговор целиком — например, когда сменился профиль.

        Смена поколения — не украшение: команда `/clear` исполняется немедленно, мимо очереди
        запросов, и запросто попадает в середину идущего обмена. Тот обмен свой результат в
        память после этого не вернёт (см. `exchange`) — это и есть смысл слова «забудь».

        Счёт поднятых с диска пар обнуляется вместе с памятью: после `/clear` поднятого не
        осталось ни одной пары, а записи прогонов продолжали бы уверять, что обмену
        предшествовал подъём разговора, — и объяснять расход было бы нечем.

        Выжимка живёт ровно столько, сколько разговор, и уходит вместе с ним — вместе с
        заготовкой. Оставь заготовку — и выжимка стёртого разговора вернулась бы при первой
        же обрезке, уже после того, как человеку сказали «забыто». Идущую фоновую задачу это
        не отменяет и отменять не может: её итог отсекается сверкой поколения на стороне
        того, кто её завёл."""
        self._messages.clear()
        self._generation += 1
        # Идущий инструмент (консилиум тратит деньги) снимается сразу, не дожидаясь конца:
        # забытый разговор не тратит. Круг `exchange` ждёт этот сигнал вместе с исполнением.
        for сигнал in self._сигналы_очистки:
            сигнал.set()
        self._сигналы_очистки = set()
        if self.profile.context_strategy == context_strategy.CONTEXT_FACTS:
            # Факты принадлежат тому же разговору, что и пары. `/clear` не должен оставить
            # после себя системный блок от уже забытой задачи.
            self._conversation_facts = memory.ConversationFacts()
            # Старый дописываемый файл остаётся нетронутым, но больше не принадлежит этому
            # очищенному разговору. Следующее хранилище привяжет `set_store`.
            self._facts_store = None
        self.restored_pairs = 0
        self._summary = None
        self._prepared = None
        # Счёт пройденного обнуляется вместе с разговором: пройденное принадлежит ЕМУ, а не
        # агенту. Оставь число — и новый разговор с первого же хода уверял бы, что за ним
        # стоят десять пар пересказа, которых нет ни в выжимке, ни на диске.
        self.passed_pairs = 0

    def remember(
        self,
        question: str,
        answer: str,
        *,
        model: str = "",
        приложение: dict | None = None,
    ) -> None:
        """Положить в память готовую пару «вопрос — ответ» и сохранить её на диск.

        ЕДИНСТВЕННАЯ точка записи в память. `exchange` и восстановление пополняют память
        тоже через этот метод, а не напрямую через `self._messages`, — второй точки записи
        заводить нельзя, иначе правила пополнения снова разъедутся по разным местам.

        Раз точка одна — здесь же и запись на диск, со всеми тремя условиями сразу.

        `keep_history` проверяется ИМЕННО ЗДЕСЬ, а не у вызывающего. Вызывающих двое:
        `exchange` эту проверку делал, `output.deliver` — нет, и профиль с выключенной
        историей завёл бы на диске разговор, которого нет ни в одном запросе к модели:
        `build_messages` память такого профиля не берёт.

        Пометки кладутся на ответ, а не на вопрос: через месяц по файлу должно быть видно,
        каким профилем и какой моделью получен ответ и не правили ли с тех пор инструкцию.
        У вопроса такого прошлого нет — его написал человек.

        `приложение` — рассуждения итогового ответа и звенья круга инструментов. Оно живёт
        ключом `"приложение"` у сообщения ответа, поэтому память по-прежнему строго чередует
        вопрос и ответ, и окно, обрезка, сжатие и стратегии считают пары как раньше. В запрос
        ключ как есть не уходит никогда — пару раскрывает `раскрыть`. Кладётся копией: словарь
        вызывающего не должен оставаться дверью в память.

        Стратегия `branching` приложения не берёт ни в память, ни на диск: инструментов у неё
        нет (Р9), а граф ветвей хранит только текст пары."""
        ветвление = self.profile.context_strategy == context_strategy.CONTEXT_BRANCHING
        if ветвление:
            приложение = None
        приложение = _годное_приложение(приложение)
        ответ: dict[str, Any] = {"role": "assistant", "content": answer}
        if приложение:
            ответ["приложение"] = copy.deepcopy(приложение)
        self._messages.append({"role": "user", "content": question})
        self._messages.append(ответ)
        if self._restoring or not self.profile.keep_history:
            return
        meta = {
            "profile": self.profile.name,
            "model": model,
            "system_fp": memory.fingerprint(self.profile.system),
        }
        if ветвление:
            if self._branch_store is None:
                return
            turn, error = self._branch_store.append_turn(
                self._branch,
                self._branch_head,
                question,
                answer,
                **meta,
            )
            if turn is not None:
                self._branch_head = turn.id
            self.store_error = error
            return
        if self._store is None:
            return
        # Пара сериализуется и дописывается одним обращением: несериализуемая пометка или
        # обрыв до записи не могут оставить на диске одинокий вопрос.
        self.store_error = self._store.append_pair(question, answer, meta, приложение=приложение)

    def restore(
        self,
        pairs: list[tuple[str, str]],
        приложения: list[dict] | None = None,
    ) -> None:
        """Поднять прежний разговор — тем же единственным методом пополнения.

        `приложения` сопоставляются парам по номеру. Списки разной длины означают, что
        вызывающий обрезал одно и не обрезал другое, — тогда приложения отбрасываются
        ЦЕЛИКОМ: приписать паре чужие звенья хуже, чем поднять разговор без них.

        Запись на диск на время загрузки выключена: пары пришли из того самого файла, и
        сохранять их обратно значило бы удваивать разговор при каждом запуске.

        Признак снимается в `finally`: сорвись загрузка на середине — и агент до конца
        сеанса молча не писал бы на диск ничего, а обнаружилось бы это только при следующем
        запуске, когда разговора на месте не окажется."""
        self._restoring = True
        try:
            if приложения is not None and len(приложения) != len(pairs):
                # Молча терять звенья нельзя: без них следующий запрос с инструментами уйдёт
                # без цепочки, и искать причину было бы не по чему.
                self.store_error = (
                    f"приложения не совпали с парами ({len(приложения)} против {len(pairs)})"
                    " — разговор поднят без них"
                )
            if приложения is None or len(приложения) != len(pairs):
                приложения = [{}] * len(pairs)
            for (question, answer), приложение in zip(pairs, приложения, strict=True):
                self.remember(question, answer, приложение=приложение)
                # Считаем ПОСЛЕ пополнения памяти: сорвись загрузка на этой паре — и в счёте
                # оказалась бы пара, которой в памяти нет.
                self.restored_pairs += 1
        finally:
            self._restoring = False

    def history_tokens(self) -> int:
        """Вес памяти в токенах — то, что уйдёт в следующий запрос помимо всего прочего.

        Ни системной инструкции, ни нового вопроса, ни надбавки обёртки здесь нет: это цена
        того, что агент помнит, и по ней человек решает, пора ли звать `/clear`. Подмешай
        сюда инструкцию — и число перестало бы отвечать на вопрос, ради которого заведено.

        У профиля с выключенной историей вес нулевой, сколько бы пар в памяти ни лежало:
        `build_messages` эту память в запрос не кладёт. Считай её здесь — и журнал уверял бы,
        что обмен из одной реплики тащил за собой две тысячи токенов памяти, а по такому
        числу человек полез бы чистить разговор, который ни на что не влияет.

        Реплики с нетекстовым содержимым пропускаем: сегодня их в памяти не бывает (пары
        кладёт `remember`, и обе половины у него строки), но счёт токенов — удобство, и
        ронять на нём весь harness нельзя даже ради собственной уверенности.

        Вес считается по ПОЛНОМУ раскрытию (`_вес_памяти`), какой бы ни была следующая
        сборка."""
        if not self.profile.keep_history:
            return 0
        selected = context_strategy.select_history(
            self._messages,
            self.profile.context_strategy,
            self.profile.strategy_window,
        )
        return sum(tokens.count_message(message) for message in _вес_памяти(selected.messages))

    def overhead(self, model: str) -> int:
        """Надбавка обёртки для этой модели: подстроенная, если её уже мерили, иначе замер.

        Незнакомая модель получает базовое значение, а не поправку соседа: надбавка тянет в
        себе систематическую разницу счёта, и у другой модели она другая."""
        return self._overhead.get(model, tokens.BASE_OVERHEAD)

    def _система(self, факты: str, карточка: str = "") -> str:
        """Собрать системную часть из готовых блоков: записи, инструкция, карточка, выжимка.

        Порядок задан требованием и стоит денег буквально. Попадание в кэш поставщика
        ломается начиная с точки изменения и до конца запроса, поэтому блоки, начиная со
        второго, стоят ПО ВОЗРАСТАНИЮ ЧАСТОТЫ ИЗМЕНЕНИЯ:

        — записи о человеке идут первыми, ВЫШЕ инструкции, и это ЕДИНСТВЕННОЕ ИСКЛЮЧЕНИЕ из
          правила частоты, названное вслух вместе с ценой. Меняются они не реже инструкции, а
          чаще: архивариус переписывает их раз в пять обменов, инструкцию персоны человек
          меняет раз за сеанс. Наверх они поставлены за другое свойство — одинаковость у всех
          персон: так кэш поставщика делится ими между персонами, тогда как ниже инструкции
          каждое переключение персоны начинало бы его заново. Платим за это тем, что находка
          архивариуса выбрасывает из кэша ещё и инструкцию, которая не менялась: при
          инструкции в тысячу токенов и сотне обменов в день — порядка полутора центов. Цена
          названа, порядок взят из утверждённого дизайна, и менять его надо не здесь, а там;
        — инструкция персоны меняется реже карточки: карточку человек дописывает по ходу
          работы в папке, а роль выбирает раз в сеанс;
        — карточка проекта меняется реже выжимки;
        — выжимка последняя: она — самая изменчивая часть системного сообщения, меняется при
          каждом сжатии. Поставь её раньше — и каждое пересжатие выбрасывало бы из кэша ещё и
          блоки, которые не менялись, а вход из кэша дешевле промаха в тридцать раз.

        Записи и карточка приходят ГОТОВЫМИ, а не читаются здесь: их источники живут снаружи и
        ходят на диск, а эту сборку взвешивание зовёт столько раз, сколько блоков выбросит
        обрезка. Один запрос человека оборачивался бы тремя чтениями диска на каждый слой.

        Подставлять ли выжимку — решает `_блок_выжимки`, одно место на все поводы отказа
        (её нет, сжатие выключено, отпечаток инструкции разошёлся). Здесь остаётся только
        порядок.
        """
        куски = [
            кусок
            for кусок in (факты, self.profile.system or "", карточка, self._блок_выжимки())
            if кусок
        ]
        return "\n\n".join(куски)

    def _подставляется(self, выжимка: compact.Выжимка | None) -> bool:
        """Пойдёт ли ЭТА выжимка в системную часть запроса.

        Один предикат на все места, где спрашивают одно и то же: сборка системной части,
        признак отказа для ленты и применение заготовки при обрезке. Разведи их — и заготовка
        применилась бы там, где блок в запрос не идёт: человеку сказали бы «пять пар заменены
        пересказом», а модель не увидела бы ни пересказа, ни самих пар.

        Отпечаток сверяется у ТОЙ выжимки, о которой спрашивают, а не у действующей: заготовка
        собрана под инструкцию, действовавшую в момент её сборки, и та могла смениться, пока
        фоновая задача ходила к модели.
        """
        return (
            self.profile.context_strategy == context_strategy.CONTEXT_STANDARD
            and выжимка is not None
            and self.profile.compact_at > 0
            and выжимка.system_fp == memory.fingerprint(self.profile.system)
        )

    def выжимка_отвергнута(self) -> bool:
        """Есть ли выжимка, которую мы НЕ подставляем из-за несовпавшего отпечатка инструкции.

        Наружу — потому что решение принимает агент, а сказать о нём человеку обязан
        интерфейс: молча пропавший кусок памяти отлаживается как «модель отвечает не на то»,
        и час уходит на поиск поломки, которой нет. То же правило, что у строки о правке
        инструкции между запусками.

        Выключенное сжатие сюда не попадает: там выжимки нет не потому, что она не подошла, а
        потому, что человек сам выключил механизм, — и строка об этом была бы шумом.
        """
        return (
            self._summary is not None
            and self.profile.compact_at > 0
            and not self._подставляется(self._summary)
        )

    def _блок_выжимки(self) -> str:
        """Блок выжимки для системной части — либо пустая строка, если подставлять нельзя.

        Единственное место, где решается «подставляем или нет», и решается по трём поводам
        сразу: выжимки нет, сжатие выключено, отпечаток инструкции разошёлся. Разведи их по
        разным местам — и однажды взвешивание посчитало бы блок, которого в запросе не будет.

        Отпечаток проверяется потому, что выжимка — прочтение разговора КОНКРЕТНОЙ ролью, а
        не протокол: смени инструкцию, и пересказ прежней роли продолжил бы влиять на ответы
        новой, причём молча. Сама выжимка при этом не выбрасывается: инструкцию могут вернуть
        назад, а собрана выжимка за деньги.
        """
        if not self._подставляется(self._summary):
            return ""
        return self._summary.блок()

    def блок_фактов(self) -> str:
        """Готовый блок глобальных фактов — ровно тот, что уйдёт в системную часть запроса.

        Наружу — потому что спрашивают его снаружи, и не от удобства. `ограничители` требуют
        блок ДОВОДОМ (источник фактов ходит на диск, а полоска занятости пересчитывается на
        каждое нажатие клавиши), и зовут их двое: полоска и фоновая задача сжимателя. Не будь
        этого метода, каждый из них собирал бы блок по-своему, и вес, по которому режется
        память, считался бы в двух местах по-разному — а расходятся такие счёты молча.

        Ошибку чтения глотаем: это взвешивание, а не отправка, и падать на нём нельзя.
        Настоящую жалобу человек получит при сборке запроса, где она ложится в `store_error`.
        """
        if self._facts is None:
            return ""
        try:
            return memory.facts_block(self._facts(), перекрытые=self.profile.overrides)
        except Exception:  # noqa: BLE001 — источник фактов приходит снаружи
            return ""

    def блок_карточки(self) -> str:
        """Готовый блок карточки проекта — ровно тот, что уйдёт в системную часть запроса.

        Наружу и с той же защитой, что `блок_фактов`, и по тем же двум причинам. Первая:
        поставщик ходит на диск (карточка — файл папки, который человек правит руками), а
        сборку системной части взвешивание зовёт столько раз, сколько блоков выбросит обрезка;
        значит, читать его надо ОДИН раз за сборку и дальше передавать готовым. Вторая:
        ошибка чтения — это взвешивание, а не отправка, и ронять ею оплаченный обмен нельзя.
        Настоящую жалобу человек получит при сборке запроса, где она ложится в `store_error`.
        """
        if self._project is None:
            return ""
        try:
            блок = self._project()
        except Exception:  # noqa: BLE001 — поставщик карточки приходит снаружи
            return ""
        # Тип проверяем, а не доверяем: поставщик живёт снаружи, и в карточку сегодня пишет
        # интервью с ответом модели. Не-строка отсюда уронила бы сборку системной части
        # посреди уже оплаченного обмена — `build_messages` в `exchange` ничем не обёрнут.
        return блок if isinstance(блок, str) else ""

    def work_block(self) -> str:
        """Эфемерный хвост запроса: состояние текущей задачи. Пусто, если поставщика нет.

        Наружу — потому что его печатает `/system`: точный текст запроса человек обязан
        видеть целиком, а хвост в системную часть не входит и через `system_text` не виден.

        Хвост НЕ оседает нигде: он собирается на каждую сборку запроса заново и в память
        агента не попадает — см. `build_messages`. Иначе через три хода в истории лежали бы
        три противоречивых состояния задачи, и модель отвечала бы по первому.

        Ошибку глотаем по тому же правилу, что у двух блоков выше: рабочая память —
        вспомогательный механизм, и обмен из-за неё не падает.
        """
        if self._work is None:
            return ""
        try:
            return self._work()
        except Exception:  # noqa: BLE001 — поставщик рабочего состояния приходит снаружи
            return ""

    async def _исполнить_инструмент(self, набор: Инструменты, имя: str, доводы: str) -> str | None:
        """Исполнить один вызов, снимая его при `/clear`; `None` — разговор очищен.

        Исполнение идёт отдельной задачей и ждётся вместе с сигналом очистки: консилиум ждёт
        участников долго и платит за каждого, и очистка посреди него обязана снять запросы,
        а не дождаться их. Внешняя отмена обмена снимает исполнение так же и пробрасывается.
        Исключение исполнителя становится текстом «ошибка инструмента: …».
        """

        async def исполнить() -> str:
            return await набор.исполнить(имя, доводы)

        задача = asyncio.create_task(исполнить())
        сигнал = asyncio.Event()
        self._сигналы_очистки.add(сигнал)
        ожидание = asyncio.create_task(сигнал.wait())
        try:
            await asyncio.wait({задача, ожидание}, return_when=asyncio.FIRST_COMPLETED)
        except asyncio.CancelledError:
            задача.cancel()
            await asyncio.gather(задача, return_exceptions=True)
            raise
        finally:
            ожидание.cancel()
            self._сигналы_очистки.discard(сигнал)
        if not задача.done():
            задача.cancel()
            await asyncio.gather(задача, return_exceptions=True)
            return None
        if задача.cancelled():
            # Исполнитель сам отменил себя — для круга это отмена обмена.
            raise asyncio.CancelledError
        exc = задача.exception()
        if exc is not None:
            return f"ошибка инструмента: {exc}"
        return задача.result()

    @property
    def вес_инструментов(self) -> int:
        """Вес описаний инструментов последнего обмена; отстаёт на один обмен (см. `__init__`)."""
        return self._вес_инструментов

    def с_местом_под_ответ(self, предсказание: int) -> int:
        """Вес запроса вместе с местом под ответ — то, что сервер сравнивает с окном модели.

        Место под ответ входит в окно, а не идёт сверх него: живой отказ 2026-09-09 сложил
        1 047 324 токена сообщений и 2000 запрошенного ответа и сравнил сумму с окном. Одно
        правило на двоих: предупреждение до отправки (`output._warn_if_over_window`) и
        остановку круга инструментов перед очередным потоком."""
        место = self.profile.params.get("max_tokens") or 0
        if isinstance(место, bool) or not isinstance(место, int):
            место = 0
        return предсказание + место

    def _набор_инструментов(self) -> tuple[Инструменты | None, str | None]:
        """Набор инструментов этого обмена и жалоба: поставщик зовётся здесь и один раз.

        Сбой поставщика — «инструментов нет» плюс жалоба, по образцу `_с_хвостом`: обмен
        без инструментов остаётся годным ответом, а молча пропавшие инструменты отлаживались
        бы как «модель не хочет вести задачу». Набор чужого вида — тоже жалоба."""
        if self._инструменты is None:
            return None, None
        try:
            набор = self._инструменты()
        except Exception as exc:  # noqa: BLE001 — поставщик инструментов приходит снаружи
            return None, f"не удалось получить инструменты: {exc}"
        if набор is None:
            return None, None
        if not isinstance(набор, Инструменты):
            return None, f"поставщик инструментов вернул не набор ({type(набор).__name__})"
        if not набор.схемы:
            # Пустой набор — то же, что его отсутствие: `tools` без элементов в запрос не
            # уходит, а раскрывать пары и ждать вызовов тогда незачем.
            return None, None
        return набор, None

    def _с_хвостом(self, content: str) -> tuple[str, str | None]:
        """Текст последнего сообщения запроса и жалоба: рабочее состояние, пустая строка, вопрос.

        Одно место, где вопрос человека склеивается с хвостом, — и оно же единственное, через
        которое хвост вообще попадает в запрос. Пока склейка одна, свойство «в память уходит
        исходный `content`, а в модель — `payload`» держится по построению: `remember` и
        `exchange` работают с доводом, которого эта функция не касается.

        Хвост стоит ПЕРЕД вопросом, а не после: вопрос обязан быть последним, что модель
        прочтёт, иначе состояние работы дочитывается как часть вопроса и отвечать начинают
        на него.

        Поставщик читается здесь, а не через `work_block`, по той же причине, по какой
        `build_messages` читает записи сам, а не через `блок_фактов`: на пути запроса об
        ошибке надо СКАЗАТЬ. Молча пропавшее состояние задачи отлаживается как «модель
        отвечает не на то», и час уходит на поиск поломки, которой нет. Жалоба возвращается
        вторым значением: складывать её в `store_error` отсюда нельзя — тогда две жалобы за
        одну сборку затирали бы друг друга.
        """
        if self._work is None:
            return content, None
        try:
            хвост = self._work()
        except Exception as exc:  # noqa: BLE001 — поставщик рабочего состояния приходит снаружи
            return content, f"не удалось прочитать рабочую память: {exc}"
        if not isinstance(хвост, str):
            # Не-строка тут не падает, а молча уезжает в запрос: `f"{42}"` — законный текст.
            # Поэтому тип проверяем здесь, а не надеемся на исключение ниже.
            return content, f"поставщик рабочей памяти вернул не текст ({type(хвост).__name__})"
        if not хвост:
            return content, None
        return f"{хвост}\n\n{content}", None

    def system_text(self) -> str:
        """Системная часть следующего запроса без изменения памяти.

        Хвоста здесь нет намеренно: он не системная часть, а кусок последнего сообщения. Кому
        нужен точный текст запроса целиком — берёт его вместе с `work_block()`.
        """
        global_facts = self.блок_фактов()
        card = self.блок_карточки()
        if self.profile.context_strategy == context_strategy.CONTEXT_STANDARD:
            return self._система(global_facts, card)
        conversation = ""
        if self.profile.context_strategy == context_strategy.CONTEXT_FACTS:
            conversation = context_strategy.conversation_facts_block(
                self._conversation_facts.values
            )
        # Порядок тот же, что у обычной стратегии: записи, инструкция, карточка и последним —
        # самый изменчивый блок. У строгих стратегий место выжимки занимают факты разговора.
        return "\n\n".join(
            block
            for block in (global_facts, self.profile.system or "", card, conversation)
            if block
        )

    def порог_сжатия(self) -> int:
        """Порог сжатия в токенах: доля окна модели, заданная профилем. Ноль — выключено.

        Доля, а не число токенов в профиле, потому что вопрос, на который отвечает порог, —
        «много ли занято от ОКНА». Модель здесь не спрашивается: у всех моделей DeepSeek окно
        одно и то же, и `tokens.CONTEXT_WINDOW` — это оно. Появится модель с другим окном —
        число придётся брать у неё, и метод получит имя модели доводом; сегодня такой модели
        нет, и заводить довод, который некому передать, значило бы обещать несуществующее.

        Прежний аварийный потолок памяти в знаках занимал место этого ограничителя и был
        снят: он мерил ЗНАКИ там, где считают токены, и взвешивал одну накопленную историю
        без нового вопроса — то есть на своём единственном случае («человек вставил файл в
        вопрос») опаздывал ровно на ход, когда деньги уже потрачены.
        """
        if self.profile.context_strategy != context_strategy.CONTEXT_STANDARD:
            return 0
        доля = self.profile.compact_at
        if доля <= 0:
            return 0
        return int(доля * tokens.CONTEXT_WINDOW)

    def ограничители(
        self, content: str, *, facts: str, card: str = "", model: str = ""
    ) -> list[Ограничитель]:
        """Действующие ограничители обрезки, каждый со своей долей заполнения.

        Наружу — потому что считающих двое: заготовка выжимки заводится при подходе к
        ближайшему, и полоска занятости над строкой ввода рисуется по нему же. Спрячь этот
        счёт внутри обрезки — и второе место доопределило бы правило по-своему, а отметка на
        восьми десятых стояла бы не там, где что-то происходит.

        Порядок списка — тот же, в каком ограничители режут память в `_trim`. На него
        опирается выбор ближайшего при равных долях: раз доли сравнялись, честнее назвать
        того, кто сработает раньше.

        Вес считается ОДИН раз на оба весовых ограничителя: он стоит прохода по словарю
        токенов, а полоска пересчитывается на каждое нажатие клавиши.

        Выключенный ограничитель в список не попадает вовсе: полоска, привязанная к
        выключенному окну, мерила бы дорогу к событию, которого не будет.

        Блок фактов приходит ДОВОДОМ, и это не удобство вызывающего, а запрет: источник фактов
        ходит на диск, а на этом методе стоит полоска занятости, пересчитываемая на каждое
        нажатие клавиши. Читай его здесь — и каждая набранная буква оборачивалась бы обходом
        каталога памяти с чтением файлов. Обязательный довод, а не умолчание: забытый блок
        фактов молча занизил бы вес, а по весу режется память.

        Блок карточки проекта приходит доводом по той же причине — поставщик ходит на диск.
        Умолчание «пусто» оставлено для вызывающих, у которых карточки нет вовсе (агент
        группы, пакетный наряд), а оба настоящих вызывающих — полоска занятости и заготовка
        выжимки — её передают. Не передай они её, показанная занятость занижалась бы на вес
        карточки, и заготовка не заводилась бы вовремя: обрезка выбросила бы пары дословно
        вместо пересказа.
        """
        if self.profile.context_strategy != context_strategy.CONTEXT_STANDARD:
            return []
        список: list[Ограничитель] = []
        окно = self.profile.history_window
        if окно > 0:
            список.append(
                Ограничитель(ОКНО_ПО_ПАРАМ, "пар", len(self._messages) // 2, окно + WINDOW_SLACK_PAIRS)
            )
        # У профиля с выключенной историей порог сжатия не действует: память в запрос не
        # идёт, сжимать нечего, и обрезка его не применяет — см. `_trim`.
        порог = self.порог_сжатия() if self.profile.keep_history else 0
        предел = self.profile.budget_tokens
        if порог > 0 or предел > 0:
            вес = self._вес(content, facts, card, model, self._вес_инструментов)
            if порог > 0:
                список.append(Ограничитель(ПОРОГ_СЖАТИЯ, "токенов", вес, порог))
            if предел > 0:
                список.append(Ограничитель(ПРЕДЕЛ_ВЕСА, "токенов", вес, предел))
        return список

    def ближайший_ограничитель(
        self, content: str, *, facts: str, card: str = "", model: str = ""
    ) -> Ограничитель | None:
        """Тот, что сработает ПЕРВЫМ, — по наибольшей доле заполнения. `None` — ни одного.

        Сравниваются доли, а не величины: общего знаменателя у пар и токенов нет и быть не
        может — пары в токены переводятся, обратно нет. Доля есть у каждого своя, и она
        отвечает ровно на нужный вопрос: сколько пути до срабатывания пройдено.
        """
        список = self.ограничители(content, facts=facts, card=card, model=model)
        if not список:
            return None
        return max(список, key=lambda ограничитель: ограничитель.доля)

    def predict_tokens(self, messages: list[dict], model: str = "") -> int:
        """Предсказание веса запроса — с надбавкой, подстроенной ЭТИМ агентом под ЭТУ модель.

        Метод агента, а не прямой вызов `tokens.count_messages` у вызывающего: надбавка
        живёт здесь и меняется по ходу сеанса, и второе место, где её берут, разъехалось бы
        с первым на первом же обмене.

        Модель без имени берёт базовый замер — так отвечает и `overhead`. Умолчание оставлено
        ради вызывающих, которым модель неизвестна (предпросмотр запроса до выбора модели):
        подставить им чужую поправку было бы хуже, чем честное приближение."""
        return tokens.count_messages(messages, overhead=self.overhead(model))

    def _preview(self, content: str, system: str) -> list[dict]:
        """Каким выйдет запрос при нынешней памяти — чтобы взвесить его в обрезке.

        Системная часть приходит готовой — с блоком фактов и блоком выжимки, — а не
        собирается здесь. Причина в двух требованиях сразу, и оба обязательны. Первое:
        взвешивать надо РОВНО ТО, что уйдёт в модель, — недосчитай блок фактов или блок
        выжимки, и обрезка решит «влезает» там, где не влезает, а запрос уйдёт тяжелее
        бюджета, то есть предел не сработает ровно там, ради чего заведён. Второе: источник
        фактов живёт снаружи и ходит на диск, а взвешивание зовут столько раз, сколько блоков
        выброшено, — читать его на каждом витке нельзя. Оба выполняются, если блок фактов
        прочесть один раз до обрезки; этим и занят `build_messages`.

        Память берётся по тому же условию, что и там: профиль с выключенной историей её в
        запрос не кладёт, а значит и в вес она не входит. Считай её здесь безусловно — и
        бюджет выбрасывал бы пары, которых в запросе нет вовсе.

        Память взвешивается полным раскрытием (`_вес_памяти`) при любой сборке."""
        preview: list[dict] = []
        if system:
            preview.append({"role": "system", "content": system})
        if self.profile.keep_history:
            preview.extend(_вес_памяти(self._messages))
        preview.append({"role": "user", "content": content})
        return preview

    def _вес(
        self, content: str, facts: str, card: str, model: str, вес_инструментов: int = 0
    ) -> int:
        """Предсказанный вес будущего запроса при нынешней памяти и нынешней выжимке.

        Системная часть пересобирается на каждый замер намеренно: посреди обрезки заготовка
        может стать действующей выжимкой, а это меняет системное сообщение — то есть вес.
        Считай мы по системной части, снятой до обрезки, — оставшиеся ограничители мерили бы
        запрос легче того, что уйдёт в модель, и предел молча не сработал бы. Дорого это не
        обходится: чтение фактов уже сделано (`facts` приходит готовым), а счёт токенов
        одного и того же текста берётся из запомненного.

        `content` здесь — текст последнего сообщения ЦЕЛИКОМ, то есть с эфемерным хвостом
        рабочего состояния, если он есть: взвешивать надо ровно то, что уйдёт в модель.
        Склейку делает вызывающий, `build_messages`, и делает её один раз на всю обрезку.

        `вес_инструментов` — вес описаний инструментов этого запроса (`tokens.count_tools`),
        посчитанный вызывающим один раз: описания уходят в запрос рядом с разговором, и
        обрезка, не знающая их веса, решала бы «влезает» там, где не влезает. Числом, а не
        признаком «запрос с инструментами», — набор меняется от обмена к обмену, и взвешивать
        надо тот, что уйдёт сейчас. Ноль — инструментов нет, вес прежний.
        """
        система = self._система(facts, card)
        return self.predict_tokens(self._preview(content, система), model) + вес_инструментов

    def _выбросить(self, требуется: int) -> int:
        """Выбросить старейшие пары — не меньше, чем требует ограничитель. Возвращает сколько.

        ЕДИНСТВЕННОЕ место, где пары уходят из памяти, и единственное, где заготовка
        становится действующей выжимкой. Одно, потому что эти два решения связаны намертво:
        сколько выбросить, зависит от того, на сколько пар собрана заготовка.

        Правило — `max(требует ограничитель, покрывает заготовка)`. Ограничитель говорит «уйти
        должно не меньше пяти», заготовка говорит «я собрана на восемь» — уходят восемь. Иначе
        пары с шестой по восьмую уехали бы в модель ДВАЖДЫ: пересказом в системной части и
        дословно в памяти, — мы платили бы за них два раза, а модель видела бы один обмен в
        двух видах. Память при этом ужимается чуть сильнее, чем требовал ограничитель, но ни
        одна пара не теряется: те три пары в выжимке.

        Край: заготовка покрывает больше, чем вообще можно выбросить (последняя пара защищена
        всегда). Тогда она не применяется ВОВСЕ, а пары теряются дословно, и это видно в
        прогоне. Частично применить нельзя — пункт выжимки парам не сопоставлен, вырезать из
        него «часть про три пары» нечем. Случай означает, что память между сборкой заготовки и
        её применением уменьшилась; он редкий, и честная дословная потеря здесь дешевле
        молчаливого вранья. Непригодную заготовку выбрасываем: пары, под которые она собрана,
        только что потеряны дословно, и примени её обрезка следующим ходом — она приписала бы
        свой пересказ уже ДРУГИМ парам.

        Заготовка, чей блок в запрос не пойдёт (сжатие выключено, отпечаток инструкции
        разошёлся), не применяется тоже — по тому же предикату `_подставляется`.
        """
        # Последнюю пару не выбрасываем никогда: без неё агент забудет вопрос, на который сам
        # только что ответил, а человек мог сослаться на этот ответ.
        допустимо = len(self._messages) // 2 - 1
        if допустимо <= 0 or требуется <= 0:
            return 0
        if not self._подставляется(self._prepared):
            # Заготовка перестала годиться уже после принятия: человек сменил роль командой
            # `/system` или выключил сжатие. Выбрасываем по тому же доводу, по какому её не
            # принимают, — её пары сейчас уйдут из памяти, и ждать ей больше нечего.
            self._prepared = None
        заготовка = self._prepared
        покрыто = заготовка.покрыто_пар if заготовка is not None else 0
        сколько = min(требуется, допустимо)
        if заготовка is not None:
            if покрыто > допустимо:
                self._prepared = None
                заготовка = None
                покрыто = 0
            else:
                сколько = max(сколько, покрыто)
        del self._messages[: сколько * 2]
        if заготовка is not None:
            self._summary = заготовка
            self._prepared = None
        self._compacted_pairs += покрыто
        self._forgotten_pairs += сколько - покрыто
        return сколько

    def _срезать_по_весу(
        self,
        предел: int,
        content: str,
        facts: str,
        card: str,
        model: str,
        вес_инструментов: int = 0,
    ) -> int:
        """Резать блоками, пока вес запроса не уложится в предел. Возвращает число пар.

        Общий цикл для двух весовых ограничителей — порога сжатия и предела профиля. Они
        меряют один и тот же вес в одних и тех же единицах, но отвечают на разные вопросы:
        порог — «пора ли сжимать», предел — «не дороже ли, чем я разрешил». Разные вопросы,
        одно правило резки: два экземпляра этого цикла разошлись бы на первой же правке.

        Режем блоками по `WINDOW_SLACK_PAIRS`, а не по одной паре за ход, по той же причине,
        что и окно по парам: границу усечения нельзя двигать каждый ход, иначе рушится
        повторное использование неизменного начала запроса на стороне сервера — а вход из
        кэша дешевле промаха в тридцать раз (0.022 против 0.66 за миллион у v4-pro).
        """
        if предел <= 0:
            return 0
        выброшено = 0
        while (
            len(self._messages) > 2
            and self._вес(content, facts, card, model, вес_инструментов) > предел
        ):
            ушло = self._выбросить(WINDOW_SLACK_PAIRS)
            if ушло <= 0:
                # Выбрасывать больше нечего: осталась защищённая последняя пара. Здесь же
                # страховка от нечётной памяти — сегодня её не бывает, но ценой ошибки в
                # другом месте был бы замерший без единого сообщения harness: цикл, которому
                # нечего удалять, крутится вечно, и проявится это только зависанием.
                break
            выброшено += ушло
        return выброшено

    def _trim(
        self,
        content: str,
        *,
        facts: str = "",
        card: str = "",
        model: str = "",
        вес_инструментов: int = 0,
    ) -> int:
        """Обрезать память. Возвращает число выброшенных пар — сжатых и забытых вместе.

        `content` — текст последнего сообщения целиком, то есть вопрос вместе с эфемерным
        хвостом рабочего состояния; `facts` и `card` — готовые блоки записей о человеке и
        карточки проекта: без них троих вес будущего запроса неизвестен, а два ограничителя из
        трёх меряют именно его. Недосчитай обрезка хвост — и предел не сработал бы ровно там,
        ради чего заведён, причём тем вернее, чем длиннее состояние задачи.
        Все довески именованы честно: обрезка не собирает запрос, ей его дают. `model` нужен
        там же: надбавка обёртки подстраивается под каждую модель отдельно, и взвешивать
        запрос к `flash` поправкой, снятой на `pro`, значило бы резать память по чужой мерке.

        Ограничителей три, и третий условный. Все обязаны резать ТОЛЬКО целыми парами:
        начнись память с ответа — сервер откажет в запросе, причём в случайный момент работы,
        а не при проверках.

        Первый — по числу пар, про КАЧЕСТВО: модель не тянет тему и формат из обменов
        получасовой давности. Он срабатывает не на превышении окна, а на превышении окна с
        запасом, и выбрасывает сразу весь запас: обрезка на каждом ходу меняла бы начало
        запроса на каждом ходу.

        Второй — порог сжатия, про ВЕС: доля окна модели, взвешивающая ВЕСЬ будущий запрос —
        инструкцию, факты, выжимку, память и новый вопрос — в токенах и ДО отправки. На его
        месте стоял аварийный потолок памяти в ЗНАКАХ; он снят, а не дополнен, потому что две
        мерки одной величины расходятся в показаниях, и объяснить человеку, почему обрезана
        память, становится нечем.

        Третий — предел веса из профиля, если тот его задал: не «пора ли сжимать», а «за
        какую сумму не выходить». Вес он меряет тот же, а вопрос решает другой — свойство
        разговора против решения человека о своих деньгах, — и потому живёт рядом законно.

        Всё выброшенное ЛЮБЫМ из троих сперва уходит в выжимку, если та готова, и теряется
        дословно, если нет. Своей мерки выброшенного у сжатия нет: перехват — не второе место
        принятия решения, а подбор того, что решила выбросить обрезка."""
        dropped = 0
        self._compacted_pairs = 0
        self._forgotten_pairs = 0
        window = self.profile.history_window
        if window > 0 and len(self._messages) // 2 >= window + WINDOW_SLACK_PAIRS:
            dropped += self._выбросить(WINDOW_SLACK_PAIRS)
        # У профиля с выключенной историей весовым ограничителям резать нечего: память в
        # запрос не идёт, на вес не влияет, и цикл, не проверяй он этого, выбрасывал бы пару
        # за парой, ничего не добиваясь, — пока не упёрся бы в последнюю.
        порог = self.порог_сжатия() if self.profile.keep_history else 0
        dropped += self._срезать_по_весу(порог, content, facts, card, model, вес_инструментов)
        budget = self.profile.budget_tokens if self.profile.keep_history else 0
        dropped += self._срезать_по_весу(budget, content, facts, card, model, вес_инструментов)
        # Признак «предел не сработал» ставит `build_messages` по собранному запросу, а не
        # обрезка по полному весу памяти: см. там.
        # Поднятых с диска пар не может быть больше, чем пар в памяти: обрезка только что
        # могла выбросить как раз их. Оставь число прежним — и запись прогона утверждала бы,
        # что обмену предшествовал подъём десяти пар, которых в запросе нет ни одной.
        self.restored_pairs = min(self.restored_pairs, len(self._messages) // 2)
        # Пройденное копится ЗДЕСЬ, в единственном месте, где пары уходят из памяти навсегда.
        # Считай его вызывающий — и счёт разошёлся бы с обрезкой на первой же правке.
        self.passed_pairs += dropped
        return dropped

    def build_messages(
        self,
        content: str,
        model: str = "",
        *,
        полные: bool = False,
        вес_инструментов: int = 0,
    ) -> list[dict]:
        """Политика входа: что именно уйдёт в модель на этот вопрос.

        Имя модели нужно не сборке, а обрезке внутри неё: надбавка обёртки подстраивается
        под каждую модель отдельно. Умолчание — пустое имя, то есть базовый замер: у
        вызывающего, который просто смотрит, каким выйдет запрос, модели может и не быть.

        Системная инструкция всегда первая: так её видно отдельно от ввода пользователя,
        и так же работает кэширование общего начала запроса на стороне DeepSeek. Глобальные
        факты о пользователе подмешиваются в неё же, отдельным блоком после пустой строки:
        это знание о собеседнике, а не его реплика, и в разговор его класть нельзя — модель
        стала бы отвечать на него как на сказанное только что. Факты запрашиваются на каждой
        сборке: между двумя запросами человек мог добавить факт командой `/remember`.

        Третьим блоком, после фактов, идёт выжимка — пересказ пройденного куска разговора.
        Репликой памяти она не становится никогда: модель ответила бы на пересказ как на
        сказанное сейчас, разговор пошёл бы по кругу, а лишнее сообщение сломало бы строгое
        чередование ролей, на котором держится и чтение сессии, и сам запрос к API.

        Вопрос в память здесь НЕ дописывается. Память пополняется только после успешного
        ответа, в `exchange`. Причина: неотвеченный вопрос не должен оседать в памяти —
        иначе после сетевого сбоя модель на следующем ходу увидит вопрос, на который
        никто не отвечал, и станет отвечать на него повторно.

        Список собирается новый, а сообщения памяти копируются: наружу не уходит ничего,
        через что вызывающий мог бы переписать память агента.

        Порядок работы такой: сперва читается блок фактов, потом им и памятью обрезка
        взвешивает будущий запрос, и только потом собирается сам список сообщений. Обрезка
        по-прежнему идёт ДО сборки списка: обрежь после — и запрос ушёл бы полным, а урезанной
        осталась бы одна память, то есть ограничение не работало бы ровно там, ради чего
        заведено.

        Взвешивать надо РОВНО ТО, что уйдёт в модель. Недосчитай обрезка блок фактов или блок
        выжимки — и она решила бы «влезает» там, где не влезает: запрос ушёл бы тяжелее
        бюджета, и предел не сработал бы ровно в том случае, ради которого заведён. Ошибка в
        другую сторону стоила бы лишней выброшенной пары, то есть дёшево, — но это не повод
        считать неверно.

        Факты читаются ровно ОДИН РАЗ за сборку: источник живёт снаружи и ходит на диск, а
        взвешивание обрезка зовёт столько раз, сколько блоков выбросит. Сама системная часть
        собирается из них внутри обрезки на каждом замере — посреди неё заготовка может стать
        действующей выжимкой, и вес системного сообщения меняется.

        Системную часть для готового списка собираем ПОСЛЕ обрезки по той же причине: до неё
        выжимка была прежней, и запрос ушёл бы с пересказом, которого модель уже не увидит
        рядом с теми парами, что он заменил.

        Текст вопроса уходит в обрезку по той же причине: без него вес запроса неизвестен.

        Карточка проекта читается здесь же и ровно один раз за сборку — по тем же двум
        требованиям, что и записи: взвешивать надо то, что уйдёт, а поставщик ходит на диск.

        Последнее сообщение запроса — это `payload`: эфемерный хвост рабочего состояния,
        пустая строка, вопрос человека. Склейка делается ОДИН раз, здесь, до обрезки, и
        дальше в этом методе `content` не участвует нигде. Отсюда оба свойства хвоста
        держатся по построению, а не по внимательности читателя:

        — обрезка и предсказание веса меряют `payload`, то есть ровно то, что уйдёт в модель;
        — в память уходит `content`: `remember` и `exchange` работают с доводом, до которого
          склейка не дотягивается. Осядь хвост в памяти — и через три хода в истории лежали
          бы три противоречивых состояния задачи, а модель отвечала бы по первому.

        У агента без поставщика рабочего состояния `payload` — это сам `content`, байт в
        байт: слоёв нет, и запрос собирается точно так же, как собирался до их появления.

        `полные` — запрос уходит с инструментами, и пары раскрываются в полную цепочку со
        звеньями и рассуждениями (этого требует DeepSeek). Без него пара уходит вопросом и
        ответом, как до инструментов. Раскрытие стоит в ОДНОМ месте — над выбранными парами
        обеих ветвей, — а счёт пар берётся по памяти до раскрытия: у раскрытой пары сообщений
        больше двух, и деление пополам дало бы неверное число.

        Обрезка при этом взвешивает память полным раскрытием и при `полные=False` — см.
        `_вес_памяти`.

        `вес_инструментов` — вес описаний инструментов, которые уйдут рядом с запросом; он
        входит и в обрезку, и в признак перевеса (см. `_вес`)."""
        # Жалобы копятся списком и ложатся в `store_error` разом. Присваивай их по очереди —
        # и вторая затирала бы первую: человеку сказали бы про карточку и промолчали про
        # записи, хотя пропали оба слоя.
        жалобы: list[str] = []
        block = ""
        if self._facts is not None:
            try:
                block = memory.facts_block(self._facts(), перекрытые=self.profile.overrides)
            except Exception as exc:  # noqa: BLE001 — источник фактов приходит снаружи
                жалобы.append(f"не удалось прочитать глобальную память: {exc}")
        card = ""
        if self._project is not None:
            try:
                прочитанное = self._project()
            except Exception as exc:  # noqa: BLE001 — поставщик карточки приходит снаружи
                жалобы.append(f"не удалось прочитать карточку проекта: {exc}")
            else:
                # Тип проверяем и на пути запроса, а не только во взвешивании: не-строка
                # уронила бы сборку системной части посреди уже оплаченного обмена —
                # `build_messages` в `exchange` ничем не обёрнут.
                if isinstance(прочитанное, str):
                    card = прочитанное
                else:
                    жалобы.append(
                        f"поставщик карточки проекта вернул не текст ({type(прочитанное).__name__})"
                    )
        payload, жалоба = self._с_хвостом(content)
        if жалоба:
            жалобы.append(жалоба)
        if жалобы:
            self.store_error = "; ".join(жалобы)

        strategy = self.profile.context_strategy
        self._request_branch_head = (
            self._branch_head
            if strategy == context_strategy.CONTEXT_BRANCHING
            else None
        )
        if strategy == context_strategy.CONTEXT_STANDARD:
            self._dropped_pairs = self._trim(
                payload,
                facts=block,
                card=card,
                model=model,
                вес_инструментов=вес_инструментов,
            )
            system = self._система(block, card)
            self._summary_sent = bool(self._блок_выжимки())
            selected_messages = list(self._messages) if self.profile.keep_history else []
            self._selected_pairs = len(selected_messages) // 2
            self._omitted_pairs = 0
        else:
            # Строгий выбор не меняет полную память и не прикасается к выжимке. Новый вопрос
            # добавляется только после выбора и поэтому не занимает место завершённой пары.
            self._dropped_pairs = 0
            self._compacted_pairs = 0
            self._forgotten_pairs = 0
            self._summary_sent = False
            selection = context_strategy.select_history(
                self._messages if self.profile.keep_history else [],
                strategy,
                self.profile.strategy_window,
            )
            selected_messages = selection.messages
            self._selected_pairs = selection.selected_pairs
            self._omitted_pairs = selection.omitted_pairs
            conversation = (
                context_strategy.conversation_facts_block(
                    self._conversation_facts.values
                )
                if strategy == context_strategy.CONTEXT_FACTS
                else ""
            )
            # Тот же порядок, что у обычной стратегии: записи, инструкция, карточка и
            # последним самый изменчивый блок — здесь им вместо выжимки служат факты
            # разговора.
            system = "\n\n".join(
                part
                for part in (block, self.profile.system or "", card, conversation)
                if part
            )

        messages: list[dict] = []
        if system:
            messages.append({"role": "system", "content": system})
        # Единственное место раскрытия. Оно же делает копии: память не уходит наружу ни одним
        # словарём, и ключ `"приложение"` в API не попадает ни при каком `полные`.
        messages.extend(раскрыть(selected_messages, полные))
        # Хвост приклеен и у строгих стратегий тоже: рабочее состояние — часть политики входа,
        # а не свойство выбора истории. Пропусти его здесь — и слой памяти молча исчезал бы у
        # трёх стратегий из четырёх, причём узнать об этом человеку было бы неоткуда.
        messages.append({"role": "user", "content": payload})
        # Признак «предел не сработал»: обрезка сделала что могла, а запрос всё равно тяжелее
        # предела — системная часть, вопрос и описания инструментов уже перевешивают его, а
        # их выбросить нельзя. Молчать об этом нельзя: предел, который тихо не сработал, хуже
        # отсутствующего — на отсутствующий человек хотя бы не рассчитывает.
        #
        # Считаем по СОБРАННОМУ запросу у всех стратегий, а не по полному весу памяти, как
        # взвешивает обрезка: полный вес включает звенья и рассуждения, которые голый запрос
        # (пауза автомата) не несёт, и человеку сказали бы «запрос тяжелее предела» про
        # запрос, ушедший в пределе. Предел берём ПРОФИЛЯ, а не обнулённый у профиля без
        # истории: там инструкция и вопрос тоже могут его перевешивать, и жаловаться надо
        # именно там, где обрезка ничего не выправит.
        limit = self.profile.budget_tokens
        self._over_budget = bool(
            limit > 0 and self.predict_tokens(messages, model) + вес_инструментов > limit
        )
        return messages

    async def exchange(
        self,
        client,
        model: str,
        content: str,
        *,
        on_event: Callable[[api.StreamEvent], None] | None = None,
        agent: str | None = None,
        run_id: str | None = None,
    ) -> Turn:
        """Обмен с моделью; Sticky Facts завершает его только после обоих обращений."""
        # Ошибка описывает именно этот обмен. Сборка ниже может записать сюда сбой чтения
        # глобальной памяти, поэтому сброс обязан стоять перед ней.
        self.store_error = None
        strategy = self.profile.context_strategy
        facts_revision = (
            self._conversation_facts.revision
            if strategy == context_strategy.CONTEXT_FACTS
            else None
        )
        facts_revision_after = facts_revision
        effective_run_id = run_id
        if strategy == context_strategy.CONTEXT_FACTS and effective_run_id is None:
            effective_run_id = uuid4().hex
        набор, жалоба_набора = self._набор_инструментов()
        вес_инструментов = tokens.count_tools(набор.схемы) if набор is not None else 0
        self._вес_инструментов = вес_инструментов
        request_messages = self.build_messages(
            content,
            model,
            полные=набор is not None,
            вес_инструментов=вес_инструментов,
        )
        if жалоба_набора:
            # После сборки: она сама пишет в `store_error`, и жалоба на набор, положенная
            # раньше, была бы затёрта жалобой на записи или карточку.
            self.store_error = "; ".join(
                part for part in (self.store_error, жалоба_набора) if part
            )
        selected_pairs = self._selected_pairs
        omitted_pairs = self._omitted_pairs
        branch_head = self._request_branch_head
        branch_checkpoint = self._branch_checkpoint
        # Оба числа снимаются до ответа: память и запрос ещё описывают один и тот же ход.
        history_tokens = self.history_tokens()
        # Описания инструментов — часть входа, за который сервер назовёт `prompt_tokens`:
        # без них калибровка списала бы их вес на обёртку разговора.
        text_tokens = tokens.count_messages(request_messages, overhead=0) + вес_инструментов
        predicted = self.predict_tokens(request_messages, model) + вес_инструментов
        self.task = content
        generation = self._generation

        answer_text = ""
        reasoning_text = ""
        # Рассуждения итогового круга отдельно от общих: в приложение пары ложатся только
        # они, рассуждения промежуточных кругов уже лежат в своих звеньях.
        final_reasoning = ""
        finish_reason: str | None = None
        usage: dict[str, Any] = {}
        # Расход каждого круга как прислал сервер; сумма собирается после обмена.
        round_usages: list[dict[str, Any]] = []
        звенья: list[dict] = []
        # Почему круг остановлен до ответа модели: разговор очищен или следующий запрос не
        # влезет в окно. `None` — круг дошёл до итогового ответа или не начинался.
        круг_прерван: str | None = None
        # Предупреждения «следующий круг не влезет в окно» — по одному на круг, где оценка
        # превысила окно. Запрос при этом уходил; см. сверку перед потоком.
        предупреждения_окна: list[str] = []
        status = "error"
        error_text: str | None = None
        render_error: str | None = None
        facts_usage: dict[str, Any] | None = None
        facts_error: str | None = None
        cancelled = False
        started = time.monotonic()

        async def consume_main() -> None:
            """Круг «поток → вызовы → результаты → поток», пока модель не ответит без вызовов.

            Предела числа кругов нет — это решение пользователя и правило проекта: круг
            кончает модель, а человек в любой миг останавливает его отменой. Звенья каждого
            круга дописываются к запросу, и следующий поток видит всю цепочку, — так требует
            DeepSeek. `answer_text` — текст ТЕКУЩЕГО круга: к концу обмена это текст
            итогового, а текст промежуточных живёт в их звеньях."""
            nonlocal answer_text, reasoning_text, final_reasoning, finish_reason
            nonlocal render_error, request_messages, круг_прерван
            рассуждения_кругов: list[str] = []
            номер_вызова = 0
            первый_круг = True
            while True:
                if not первый_круг:
                    # Перед КАЖДЫМ следующим потоком две сверки. Первая: `/clear` посреди
                    # круга — забытый разговор не должен ни уходить в модель, ни тратить
                    # деньги. Вторая: результат инструмента мог раздуть запрос сверх окна.
                    # Тогда запрос всё равно УХОДИТ, а человеку говорится заранее — то же
                    # правило, что у первого запроса (`output._warn_if_over_window`): своя
                    # оценка веса звеньев приблизительна, отвергнутый запрос не оплачивается,
                    # а побочные действия инструментов к этому мигу уже случились.
                    if self._generation != generation:
                        круг_прерван = ОЧИЩЕН_ПОСРЕДИ_КРУГА
                        return
                    вес = self.predict_tokens(request_messages, model) + вес_инструментов
                    всего = self.с_местом_под_ответ(вес)
                    if всего > tokens.CONTEXT_WINDOW:
                        предупреждения_окна.append(
                            f"следующий круг занял бы по оценке {всего} из "
                            f"{tokens.CONTEXT_WINDOW} (включая место под ответ) — "
                            "сервер может отказать"
                        )
                первый_круг = False
                answer_text = ""
                round_reasoning = ""
                calls: list[dict] = []
                # `tools` передаётся ключевым доводом только при наборе: клиенты без
                # инструментов (и поддельные в проверках) знают лишь три довода.
                доводы = {"tools": набор.схемы} if набор is not None else {}
                async for event in client.stream_chat(
                    model, request_messages, self.profile.params, **доводы
                ):
                    if on_event is not None:
                        try:
                            on_event(event)
                        except Exception as exc:
                            # Отрисовка живёт снаружи агента: её сбой не является сетевым.
                            render_error = (
                                f"ответ получен, но показать его не удалось: {exc}"
                            )
                    if event.kind == "meta":
                        finish_reason = event.finish_reason
                        round_usages.append(event.usage or {})
                        continue
                    if event.kind == "tool_calls":
                        calls.extend(event.calls)
                    elif event.kind == "reasoning":
                        round_reasoning += event.text
                        # Общие рассуждения копятся по ходу, а не после круга: при сбое
                        # посреди потока журнал должен нести то, что уже пришло.
                        reasoning_text = "\n\n".join([*рассуждения_кругов, round_reasoning])
                    else:
                        answer_text += event.text
                if round_reasoning:
                    рассуждения_кругов.append(round_reasoning)
                if not calls or набор is None:
                    final_reasoning = round_reasoning
                    return
                # Пустой `id` от сервера заменяется местным: результат обязан сослаться на свой
                # вызов, а пустая ссылка не отличает двух вызовов. Номер сквозной на обмен —
                # местные имена не совпадут и между кругами.
                calls = [
                    вызов if вызов.get("id") else {**вызов, "id": f"call_{номер_вызова + i}"}
                    for i, вызов in enumerate(calls)
                ]
                номер_вызова += len(calls)
                звено: dict[str, Any] = {
                    "role": "assistant",
                    "content": answer_text,
                    "tool_calls": calls,
                }
                # Ключ ставится только у непустых рассуждений — то же правило, что у
                # `раскрыть`: продолжение после результата законно приходит без них.
                if round_reasoning:
                    звено["reasoning_content"] = round_reasoning
                круг = [звено]
                for вызов in calls:
                    if self._generation != generation:
                        круг_прерван = ОЧИЩЕН_ПОСРЕДИ_КРУГА
                        # Частичный круг — звено с вызовами и готовые результаты — уходит в
                        # звенья журнала: побочные действия уже случились, и при разборе их
                        # должно быть видно. В память он не ляжет: исход обмена — ошибка.
                        звенья.extend(круг)
                        return
                    функция = вызов.get("function") or {}
                    исполнение = await self._исполнить_инструмент(
                        набор, функция.get("name", ""), функция.get("arguments", "")
                    )
                    if исполнение is None:
                        # `/clear` пришёл, пока инструмент исполнялся: исполнение снято, его
                        # результата нет, а частичный круг уходит в звенья журнала.
                        круг_прерван = ОЧИЩЕН_ПОСРЕДИ_КРУГА
                        звенья.extend(круг)
                        return
                    результат = исполнение
                    # Исполнитель мог поймать отмену и вернуть строку. Запрос на отмену при
                    # этом остаётся на задаче — его и уважаем, иначе Ctrl+C посреди
                    # инструмента молча продолжил бы круг.
                    текущая = asyncio.current_task()
                    if текущая is not None and текущая.cancelling():
                        raise asyncio.CancelledError
                    круг.append(
                        {
                            "role": "tool",
                            "tool_call_id": вызов["id"],
                            "content": результат,
                        }
                    )
                    if on_event is not None:
                        # Результат показывает отрисовка, а не исполнитель: автомат задачи не
                        # знает экрана, и показ вызова одинаков для любого инструмента.
                        try:
                            on_event(api.StreamEvent("tool_result", результат, calls=[вызов]))
                        except Exception as exc:
                            render_error = f"ответ получен, но показать его не удалось: {exc}"
                звенья.extend(круг)
                # Новый список, а не дописывание на месте: запрос первого круга мог уже
                # уйти наружу (поддельный клиент, отрисовка), и правка задним числом
                # переписала бы то, что тот видел.
                request_messages = [*request_messages, *круг]

        main_task: asyncio.Task[None] | None = None
        facts_task: asyncio.Task[Turn] | None = None
        if strategy == context_strategy.CONTEXT_FACTS:
            # Поздний импорт разрывает действующий круг profiles → agent: профиль
            # извлекателя можно собирать только после полной загрузки обоих модулей.
            from . import sticky_facts

            previous_values = dict(self._conversation_facts.values)
            extractor = Agent(
                sticky_facts.EXTRACTOR_NAME,
                sticky_facts.extractor_profile(self.profile),
            )
            # `content`, а не текст с эфемерным хвостом, и это решение, а не место вызова.
            # Дай извлекателю хвост — и рабочее состояние осело бы в фактах разговора, то есть
            # ровно там, где слой запрещён наравне с выжимкой: он живёт свою жизнь и умирает
            # вместе с задачей, а факты разговора переживают её.
            extraction_request = sticky_facts.extract_request(
                previous_values, content
            )
            # Обе задачи созданы до первого ожидания: ни быстрый основной ответ, ни быстрый
            # извлекатель не превращают договор одновременного старта в последовательный.
            main_task = asyncio.create_task(consume_main())
            facts_task = asyncio.create_task(
                extractor.exchange(
                    client,
                    model,
                    extraction_request,
                    agent=sticky_facts.EXTRACTOR_NAME,
                    run_id=effective_run_id,
                )
            )

        if (
            strategy == context_strategy.CONTEXT_BRANCHING
            and self._branch_error is not None
        ):
            error_text = self._branch_error
        else:
            try:
                if main_task is None:
                    await consume_main()
                else:
                    await main_task
                status = "ok"
            except asyncio.CancelledError:
                cancelled = True
                status = "cancelled"
                if main_task is not None and not main_task.done():
                    main_task.cancel()
                if facts_task is not None and not facts_task.done():
                    facts_task.cancel()
            except Exception as exc:  # сеть, лимиты, ошибки API — не роняем harness
                error_text = str(exc)

        facts_turn: Turn | None = None
        if facts_task is not None:
            if cancelled and not facts_task.done():
                facts_task.cancel()
            try:
                facts_turn = await facts_task
            except asyncio.CancelledError:
                # Сюда попадает как отмена во время основного потока, так и Ctrl+C после
                # готового основного ответа, пока извлекатель ещё работает.
                cancelled = True
                status = "cancelled"
                facts_task.cancel()
                await asyncio.gather(facts_task, return_exceptions=True)
            except Exception as exc:  # собственный сбой вспомогательного агента
                facts_error = f"извлекатель фактов завершился с ошибкой: {exc}"

        if facts_turn is not None and facts_turn.usage:
            # Только серверные числа. Предсказанный расход одноразового агента сюда не
            # подставляется даже при пустом usage.
            facts_usage = dict(facts_turn.usage)

        if strategy == context_strategy.CONTEXT_FACTS:
            if cancelled:
                facts_error = facts_error or "извлечение фактов отменено"
            elif self._generation != generation:
                facts_error = (
                    "результат извлечения фактов отброшен: разговор уже очищен"
                )
            elif facts_turn is None:
                facts_error = facts_error or "извлекатель фактов не вернул результат"
            elif not facts_turn.ok:
                facts_error = facts_turn.error or (
                    f"извлечение фактов завершилось со статусом {facts_turn.status}"
                )
            else:
                try:
                    changes = sticky_facts.parse_changes(facts_turn.text)
                except (TypeError, ValueError) as exc:
                    facts_error = str(exc)
                else:
                    facts_error = self._apply_conversation_facts(
                        changes.set_values,
                        changes.forget_keys,
                        turn_id=uuid4().hex,
                        source="extractor",
                    )
            # После `/clear` редакция уже нулевая; при любой ошибке — прежняя. Поле должно
            # описывать реальное состояние на выходе, а не только успешную запись.
            facts_revision_after = self._conversation_facts.revision

        # Один круг — расход как прислал сервер, байт в байт прежний. Несколько — сумма
        # накопителем: обмен стоил все свои запросы, и счётчики, журнал и `Turn` называют
        # одну и ту же сумму.
        if len(round_usages) == 1:
            usage = round_usages[0]
        elif round_usages:
            usage = tokens.total_usage(round_usages)
        elapsed = time.monotonic() - started
        snapshot = self.profile.snapshot()
        if status == "ok" and круг_прерван is not None:
            # Раньше проверки пустоты: у прерванного круга текст может быть, но это текст
            # промежуточного круга, а не ответ, и в память он лечь не должен.
            status = "error"
            error_text = круг_прерван
        elif status == "ok" and not answer_text:
            status = "error"
            if finish_reason == "length":
                # Вход ПОСЛЕДНЕГО круга: сумма входа всех кругов с окном не сравнима и дала
                # бы ложное «в окне не осталось места».
                последний = round_usages[-1] if round_usages else usage
                вход = tokens.normalize(последний)["prompt_tokens"]
                остаток = tokens.CONTEXT_WINDOW - вход
                предел = self.profile.params.get("max_tokens")
                if вход and остаток < ОСТАТОК_НА_ОТВЕТ:
                    error_text = (
                        f"в окне модели не осталось места на ответ: занято {вход} "
                        f"из {tokens.CONTEXT_WINDOW}, свободно {остаток} — "
                        "очистите историю командой /clear или задайте вопрос короче"
                    )
                elif предел:
                    error_text = (
                        "весь max_tokens ушёл на рассуждения, ответ не начат — "
                        "увеличьте max_tokens"
                    )
                else:
                    error_text = "ответ оборван по длине, не начавшись"
            else:
                error_text = "модель вернула пустой ответ"

        if status == "ok":
            if render_error:
                error_text = render_error
            if self.profile.keep_history and self._generation == generation:
                try:
                    приложение = (
                        {"reasoning_content": final_reasoning, "звенья": звенья}
                        if набор is not None
                        else None
                    )
                    self.remember(content, answer_text, model=model, приложение=приложение)
                except Exception as exc:  # обмен дороже любой записи на диск
                    self.store_error = f"не удалось сохранить разговор: {exc}"

        # Один пользовательский обмен — один run, но расход у facts состоит из двух
        # независимых серверных usage. Они входят в накопитель ровно здесь и ровно по разу.
        self.runs += 1
        self.total_ms += int(elapsed * 1000)
        self.total_tokens += usage_tokens(usage)
        self.session_usage = tokens.add_usage(self.session_usage, usage)
        if facts_usage is not None:
            self.total_tokens += usage_tokens(facts_usage)
            self.session_usage = tokens.add_usage(self.session_usage, facts_usage)

        # Самокалибровка относится только к основному запросу: у извлекателя свой одноразовый
        # Agent и своя надбавка, смешивать их измерения нельзя. И только к ПЕРВОМУ кругу:
        # предсказан его запрос, а у следующих к нему приросли звенья, и сумма входа всех
        # кругов с предсказанием не сравнима.
        первый = round_usages[0] if round_usages else {}
        prompt_tokens = первый.get("prompt_tokens") if isinstance(первый, dict) else None
        if isinstance(prompt_tokens, int) and not isinstance(prompt_tokens, bool):
            measured = prompt_tokens - text_tokens
            if 0 <= measured <= OVERHEAD_LIMIT:
                self._overhead[model] = measured

        if предупреждения_окна:
            # После записи разговора: её сбой присваивает `store_error` целиком и затёр бы
            # предупреждение.
            self.store_error = "; ".join(
                part for part in (self.store_error, *предупреждения_окна) if part
            )
        entry: dict[str, Any] = {
            "status": status,
            "model": model,
            "profile": snapshot,
            "query": content,
            # Запрос ПОСЛЕДНЕГО круга: он содержит запрос первого целиком и дописанные к
            # нему звенья, то есть всё, что модель видела за обмен. Без круга это и есть
            # единственный запрос, как прежде.
            "messages": request_messages,
            "response": answer_text or None,
            "reasoning": reasoning_text or None,
            "finish_reason": finish_reason,
            "usage": usage or None,
            "context_strategy": strategy,
            "selected_pairs": selected_pairs,
            "omitted_pairs": omitted_pairs,
            "index": self.runs,
            "history_tokens": history_tokens,
            "predicted_prompt_tokens": predicted,
            "agent_session_tokens": self.session_usage["total_tokens"],
            "elapsed_ms": int(elapsed * 1000),
            "error": error_text,
        }
        if self._over_budget:
            entry["over_budget"] = True
        if self.restored_pairs:
            entry["restored_pairs"] = self.restored_pairs
        if self._summary_sent and self._summary is not None:
            entry["summary_used"] = True
            entry["passed_pairs"] = self.passed_pairs
            entry["summary_generation"] = self._summary.поколение
        if self._compacted_pairs:
            entry["compacted_pairs"] = self._compacted_pairs
        if self._forgotten_pairs:
            entry["forgotten_pairs"] = self._forgotten_pairs
        if strategy == context_strategy.CONTEXT_FACTS:
            entry["facts_revision"] = facts_revision
            entry["facts_revision_after"] = facts_revision_after
            if facts_usage is not None:
                entry["facts_usage"] = facts_usage
            if facts_error is not None:
                entry["facts_error"] = facts_error
        if strategy == context_strategy.CONTEXT_BRANCHING:
            entry["branch"] = self._branch
            entry["branch_head"] = branch_head
            entry["branch_checkpoint"] = branch_checkpoint
        if agent:
            entry["agent"] = agent
        if effective_run_id:
            entry["run_id"] = effective_run_id
        if звенья:
            entry["звенья"] = звенья
        if предупреждения_окна:
            # Строкой, как `error`: по журналу видно, что сервер мог отказать из-за оценки
            # веса звеньев, а не из-за сети. Несколько кругов — через «; ».
            entry["window_warning"] = "; ".join(предупреждения_окна)
        journal_error = journal.append(entry)

        turn = Turn(
            status=status,
            text=answer_text,
            reasoning=reasoning_text,
            finish_reason=finish_reason,
            usage=usage,
            elapsed_ms=int(elapsed * 1000),
            error=error_text,
            request_messages=request_messages,
            model=model,
            profile_snapshot=snapshot,
            dropped_pairs=self._dropped_pairs,
            compacted_pairs=self._compacted_pairs,
            forgotten_pairs=self._forgotten_pairs,
            passed_pairs=self.passed_pairs,
            index=self.runs,
            history_tokens=history_tokens,
            predicted_prompt=predicted,
            agent_session_tokens=self.session_usage["total_tokens"],
            over_budget=self._over_budget,
            journal_error=journal_error,
            store_error=self.store_error,
            context_strategy=strategy,
            selected_pairs=selected_pairs,
            omitted_pairs=omitted_pairs,
            facts_revision=facts_revision,
            facts_revision_after=facts_revision_after,
            facts_usage=facts_usage,
            facts_error=facts_error,
            branch=self._branch if strategy == context_strategy.CONTEXT_BRANCHING else None,
            branch_head=branch_head,
            branch_checkpoint=branch_checkpoint,
            звенья=звенья,
        )
        if cancelled:
            raise asyncio.CancelledError
        return turn
