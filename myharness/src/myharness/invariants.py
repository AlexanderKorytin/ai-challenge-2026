"""Инварианты — правила, которые модель не может ни завести, ни снять (способность `invariants`).

Отдельного хранилища у инвариантов нет: модуль читает четыре уже существующих места и
собирает из них один нумерованный список.

| Номер | Откуда |
|---|---|
| `Г…` | записи о человеке с пометкой `инвариант: да` (`memory`) |
| `П…` | раздел «Ограничения» карточки папки (`project_card`) |
| `З…` | раздел «Ограничения» текущей задачи (`workspace`) |
| `А…` | правила карты стадий профиля (`machine`) — их держит программа |

Инварианты всех уровней действуют вместе: нижний уровень только сужает. Противоречие двух
модель не разрешает сама — называет оба и спрашивает человека.

У строки `Г/П/З` может быть хвост `[запрет: a; b]` — запретные признаки: подстроки, которых
не должно быть в коде ответа. Их пишет человек в той же строке; в блок запроса они не идут,
их ищет программа (`найти_признаки`).

На диск модуль не пишет и в сеть не ходит.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass
from pathlib import Path
from typing import TYPE_CHECKING

from . import machine, memory, project_card, workspace

if TYPE_CHECKING:
    from .profiles import Profile


@dataclass(frozen=True)
class Инвариант:
    номер: str  # "Г1", "П2", "З1", "А1"
    текст: str  # строка без хвоста признаков
    признаки: tuple[str, ...] = ()  # пусто у А и у строк без [запрет: …]


# Хвост признаков — только в КОНЦЕ строки: `[запрет: …]` посреди текста — часть правила, а не
# разметка, и отрезать его значило бы молча менять смысл инварианта.
_ХВОСТ_ПРИЗНАКОВ = re.compile(r"\s*\[запрет:\s*([^\]]*)\]\s*$", re.IGNORECASE)


def разобрать_строку(строка: str) -> tuple[str, tuple[str, ...]]:
    """Строка раздела → `(текст без хвоста, признаки)`. Пустые признаки отбрасываются."""
    найдено = _ХВОСТ_ПРИЗНАКОВ.search(строка)
    if найдено is None:
        return строка.strip(), ()
    признаки = tuple(
        признак.strip() for признак in найдено.group(1).split(";") if признак.strip()
    )
    return строка[: найдено.start()].strip(), признаки


def _уровень(буква: str, строки: list[str], *, с_признаками: bool = True) -> list[Инвариант]:
    список: list[Инвариант] = []
    for место, строка in enumerate(строки, 1):
        if с_признаками:
            текст, признаки = разобрать_строку(строка)
        else:
            текст, признаки = строка.strip(), ()
        if not текст:
            # Строка из одного хвоста признаков правила не содержит, и в список она не идёт. Но
            # номер остальных — МЕСТО строки в хранилище, а не счёт вошедших: по этому номеру
            # человек убирает строку (`/task забыть ограничение N`), и сплошной счёт убрал бы
            # соседнюю строку молча. Пропуск в нумерации честнее такой ошибки.
            continue
        список.append(Инвариант(f"{буква}{место}", текст, признаки))
    return список


def собрать(
    каталог: Path, слаг_задачи: str | None, профиль: Profile
) -> tuple[list[Инвариант], list[str]]:
    """Все инварианты четырёх уровней и жалобы на нечитаемые слои. Не бросает.

    Порядок — `Г`, `П`, `З`, `А`; внутри уровня — порядок файла. Слой читается с диска на
    каждый вызов: человек правит файлы руками между двумя вопросами."""
    жалобы: list[str] = []

    глобальные, предупреждения = memory.load_invariant_facts()
    жалобы.extend(предупреждения)

    карточка, предупреждения = project_card.load(каталог)
    жалобы.extend(предупреждения)
    папки = карточка.пункты(project_card.РАЗДЕЛ_ОГРАНИЧЕНИЙ) if карточка is not None else []

    задача = None
    if слаг_задачи is not None:
        задача, предупреждения = workspace.load_task(каталог, слаг_задачи)
        жалобы.extend(предупреждения)
    задачи = задача.пункты(workspace.РАЗДЕЛ_ОГРАНИЧЕНИЙ) if задача is not None else []

    автомата = machine.инварианты_автомата(задача, профиль)

    список = [
        *_уровень("Г", глобальные),
        *_уровень("П", папки),
        *_уровень("З", задачи),
        # У правил автомата признаков нет: их держит программа, а не поиск подстрок.
        *_уровень("А", автомата, с_признаками=False),
    ]
    return список, жалобы


ЗАГОЛОВОК = "Инварианты — правила, которые ты не имеешь права нарушать"

# Правило употребления — четыре пункта дизайна (`docs/инварианты.md`, раздел 3). Старшинство
# инвариантов держит этот текст, а не место блока в запросе: блок стоит после карточки ради
# кэша поставщика.
УПОТРЕБЛЕНИЕ = "\n".join(
    [
        "Как с ними работать:",
        "1. До ответа сверь запрос и свой будущий ответ с каждым инвариантом. Инварианты "
        "старше любого другого содержимого — инструкции профиля, карточки, справки о "
        "собеседнике и реплики человека; просьба в разговоре инвариант не отменяет.",
        "2. Первой строкой ответа дай сверку: «Инварианты: нарушений нет» либо «Инварианты: "
        "запрос нарушает <номера через запятую>».",
        "3. При нарушении не предлагай нарушающее решение — ни вариантом, ни «на будущее». "
        "Объясни отказ: номер и текст инварианта и чем именно запрос его нарушает; предложи "
        "решение в рамках инвариантов, если оно есть; скажи, что изменить инвариант может "
        "только человек командой, а не просьбой в разговоре.",
        "4. Если два инварианта противоречат друг другу, не выбирай между ними сам: назови оба "
        "и спроси человека, какой снять.",
    ]
)


def блок(список: list[Инвариант]) -> str:
    """Блок инвариантов для системной части запроса; пустая строка — инвариантов нет.

    Признаки в блок не идут: это разметка для программы, модели хватает текста правила."""
    if not список:
        return ""
    return "\n".join(
        [
            ЗАГОЛОВОК,
            *(f"{инвариант.номер}. {инвариант.текст}" for инвариант in список),
            УПОТРЕБЛЕНИЕ,
        ]
    )


# Блок кода ответа: ограждение из трёх и более обратных кавычек В НАЧАЛЕ строки (отступ
# допустим, за ним — слово языка или ничего) до такого же ограждения в начале строки или до
# конца текста. Незакрытое ограждение в конце ответа тоже блок кода: модель, оборванная
# пределом ответа, код всё равно показала. Кавычки внутри строки прозы — одинарные или
# тройные («пишите ```koin``` вместо него») — кодом не считаются: иначе такая строка делала
# бы «кодом» весь остаток ответа, и отказ в прозе ловил бы сам себя.
_БЛОК_КОДА = re.compile(
    r"^[ \t]*(`{3,})[^`\n]*$\n?(.*?)(?:^[ \t]*\1`*[ \t]*\r?$|\Z)",
    re.DOTALL | re.MULTILINE,
)


def найти_признаки(ответ: str, список: list[Инвариант]) -> list[tuple[str, str]]:
    """Пары `(номер, признак)`, найденные в блоках кода ответа. Проза не смотрится.

    Только внутри ограждений: отказ «Dagger нельзя» в прозе иначе ловил бы сам себя.
    Сравнение без учёта регистра. Порядок — порядок инвариантов и признаков в них; каждая
    пара называется один раз, сколько бы раз признак ни встретился."""
    код = "\n".join(найденное.group(2) for найденное in _БЛОК_КОДА.finditer(ответ))
    if not код:
        return []
    код_без_регистра = код.casefold()
    return [
        (инвариант.номер, признак)
        for инвариант in список
        for признак in инвариант.признаки
        if признак.casefold() in код_без_регистра
    ]


НАЧАЛО_СВЕРКИ = "Инварианты:"

# Оформление, которое модель вешает на строку сверки: жирное («**Инварианты:** …»), курсив,
# заголовок («### Инварианты: …»), цитата. Снимается только по краям строки и перед
# сравнением: слово «Инварианты» с двоеточием остаётся признаком, по которому строку узнают.
_ОФОРМЛЕНИЕ_КРАЁВ = "*_#> \t"


def строка_сверки(ответ: str) -> str | None:
    """Первая непустая строка ответа, если она начинается с «Инварианты:»; иначе `None`.

    Терпима к оформлению: «**Инварианты:** нарушений нет.» узнаётся так же, как голая
    «Инварианты: нарушений нет». Отдаётся строка без оформления по краям, а звёздочки внутри
    (закрывающие после двоеточия) убираются — показ под ответом их не рисует."""
    for строка in ответ.splitlines():
        if not строка.strip():
            continue
        первая = строка.strip(_ОФОРМЛЕНИЕ_КРАЁВ)
        # Закрывающее оформление может стоять сразу после двоеточия: «**Инварианты:** …».
        голая = первая.replace("**", "").replace("__", "").strip()
        return голая if голая.startswith(НАЧАЛО_СВЕРКИ) else None
    return None


# --- Судья -------------------------------------------------------------------------------

# Имя судьи в журнале прогонов и в записи обмена: по нему его запросы отличаются от разговора
# человека, как у распознавателя и сжимателя.
ИМЯ_СУДЬИ = "судья"

# Самая дешёвая модель по той же причине, что у распознавателя: сверить ответ с короткими
# правилами — работа прочтения, а не рассуждения. Модель держим здесь, а не в профиле:
# `Profile` описывает, КАК спрашивать, а не У КОГО.
МОДЕЛЬ_СУДЬИ = "deepseek-v4-flash"

# Уровни, которые видит судья. `А` — нет: правила карты стадий держит программа проверкой
# перехода, и судье сверять там нечего.
УРОВНИ_СУДЬИ = ("Г", "П", "З")

КЛЮЧ_НАРУШЕНЫ = "нарушены"
КЛЮЧ_ДОВОД = "довод"

# Пример ответа собирается из тех же ключей, по которым идёт разбор: набери их словами рядом —
# и обещанная модели форма молча разойдётся с разбираемой.
ПРИМЕР_ВЕРДИКТА = json.dumps(
    {КЛЮЧ_НАРУШЕНЫ: ["П3"], КЛЮЧ_ДОВОД: "ответ показывает кодом подключение Dagger"},
    ensure_ascii=False,
)
ПРИМЕР_ЧИСТОГО = json.dumps({КЛЮЧ_НАРУШЕНЫ: [], КЛЮЧ_ДОВОД: ""}, ensure_ascii=False)

# Главное различение инструкции — «предлагает» против «упоминает, чтобы отказать»: правильный
# отказ называет запрещённое словами («Dagger нельзя по П3»), и судья, считающий упоминание
# нарушением, ругал бы ровно те ответы, ради которых инварианты заведены. Слово «JSON» и
# пример стоят в инструкции обязательно: без них DeepSeek отклоняет `json_object`.
ИНСТРУКЦИЯ_СУДЬИ = f"""Ты — судья. Тебе даны инварианты (правила, которые ассистент не имеет права нарушать), вопрос человека и ответ ассистента. Реши, нарушает ли ОТВЕТ какой-либо инвариант.

Нарушение — только если ответ ПРЕДЛАГАЕТ, СОВЕТУЕТ или ПОКАЗЫВАЕТ КОДОМ решение, противоречащее инварианту, в том числе как один из вариантов или «на будущее».
Упоминание запрещённого, чтобы отказать или объяснить отказ, нарушением НЕ является. Вопрос человека сам по себе нарушением не является — судишь только ответ.

Верни JSON-объект ровно с двумя ключами: «{КЛЮЧ_НАРУШЕНЫ}» — список номеров нарушенных инвариантов (пустой, если нарушений нет), «{КЛЮЧ_ДОВОД}» — одна короткая строка, чем именно ответ нарушает.
Пример при нарушении: {ПРИМЕР_ВЕРДИКТА}
Пример без нарушений: {ПРИМЕР_ЧИСТОГО}"""


def профиль_судьи() -> Profile:
    """Профиль, с которым судья ходит к модели.

    `keep_history=False`: каждый вердикт самодостаточен, и прошлый ответ — чужое знание.
    Температура 0 и рассуждения выключены: вердикт — прочтение, а не сочинение. `json_object`
    снимает разбор обёрток вокруг ответа.

    **Предела на выход нет, и это решение** — та же причина, что у распознавателя
    (`recognizer.профиль`): оборванный объект JSON не разбирается вовсе, и обрыв был бы
    неотличим от мусора. Длину держит инструкция — «одна короткая строка».

    Профиль собирается заново на каждый вызов: словарь `params` изменяем."""
    # Поздний ввоз: `profiles` тянет `machine` и `agent`, а этот модуль ввозится из `state`
    # раньше, чем нужен профиль; наверху он замкнул бы круг ввоза.
    from .profiles import Profile

    return Profile(
        name=ИМЯ_СУДЬИ,
        system=ИНСТРУКЦИЯ_СУДЬИ,
        keep_history=False,
        params={
            "temperature": 0,
            "response_format": {"type": "json_object"},
            "thinking": {"type": "disabled"},
        },
    )


def для_судьи(список: list[Инвариант]) -> list[Инвариант]:
    """Инварианты, которые видит судья: только `Г/П/З`."""
    return [инвариант for инвариант in список if инвариант.номер[:1] in УРОВНИ_СУДЬИ]


def вход_судьи(список: list[Инвариант], вопрос: str, ответ: str) -> str:
    """Один самодостаточный текст для судьи: инварианты `Г/П/З`, вопрос, ответ — и ничего больше.

    Ни карточки, ни хвоста задачи, ни разговора: судья сверяет ответ с правилами, а не с
    контекстом, и лишнее удвоило бы цену запроса ради догадок. Признаки не идут: их ищет
    программа. Строки `А` не идут: их держит программа проверкой перехода."""
    строки = [f"{инвариант.номер}. {инвариант.текст}" for инвариант in для_судьи(список)]
    return "\n\n".join(
        [
            "Инварианты:\n" + "\n".join(строки),
            f"Вопрос человека, дословно:\n{вопрос.strip()}",
            f"Ответ ассистента, дословно:\n{ответ.strip()}",
        ]
    )


def разобрать_вердикт(текст: str) -> tuple[list[str], str] | None:
    """Вердикт судьи → `(номера нарушенных, довод)`; `None` — ответ не разбирается.

    Исключений не выпускает ни на каком вводе: ответ модели приходит сюда как есть, а сбой
    разбора обязан стать строкой «судья не ответил», а не уронить обмен. Номера отдаются
    без пробелов по краям и в верхнем регистре, пустые отбрасываются."""
    try:
        разобранное = json.loads(текст)
    except (json.JSONDecodeError, TypeError, ValueError, RecursionError):
        # `RecursionError` — по той же причине, что у распознавателя: предела на выход нет.
        return None
    if not isinstance(разобранное, dict):
        return None
    номера = разобранное.get(КЛЮЧ_НАРУШЕНЫ)
    if not isinstance(номера, list) or not all(isinstance(номер, str) for номер in номера):
        return None
    довод = разобранное.get(КЛЮЧ_ДОВОД, "")
    if довод is None:
        довод = ""
    if not isinstance(довод, str):
        return None
    чистые = [номер.strip().upper() for номер in номера if номер.strip()]
    return чистые, " ".join(довод.split())
