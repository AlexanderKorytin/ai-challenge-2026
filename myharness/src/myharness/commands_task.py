"""Команда `/task` — рабочая память задачи руками человека.

Третий слой памяти правит только человек: программа пишет в него состояние, но заводит,
переводит по этапам и закрывает задачу он сам. Причина та же, по которой у `/remember` нет
собственного разбора «а не пора ли записать»: слой, который заводится сам собой, никто не
закрывает, и через неделю в нём лежит десяток мёртвых задач.

Модуль знает про состояние сеанса и про хранилище, но не про окно: всё, что он говорит
человеку, уходит в ленту через `output`, как и всё прочее в инструменте.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

from . import machine, ui, workspace
from .conversation import забыть_счёт_занятости
from .output import append_log
from .state import State

# Слова команды, за которыми стоит раздел задачи. Родительный падеж человеку набирать
# неудобно, поэтому раздел зовётся так, как о нём говорят: «/task план», «/task находка».
РАЗДЕЛ_ПО_СЛОВУ = {
    "ограничение": "Ограничения",
    "ограничения": "Ограничения",
    "план": "План",
    "сделано": "Сделано",
    "сейчас": "Сейчас",
    "находка": "Находки",
    "находки": "Находки",
}

# Слова автомата задачи (способность `task-machine`): ворота открывает только человек.
СЛОВО_УТВЕРДИТЬ = "утвердить"
СЛОВО_ОТКЛОНИТЬ = "отклонить"
СЛОВО_ПАУЗА = "пауза"
СЛОВО_ПРОДОЛЖИТЬ = "продолжить"
# Хвост `/task этап <X> силой`: человек вправе идти мимо карты, но не случайно.
СЛОВО_СИЛОЙ = "силой"

СЛОВА_КОМАНДЫ = {
    "new",
    "list",
    "open",
    "done",
    "этап",
    "забыть",
    СЛОВО_УТВЕРДИТЬ,
    СЛОВО_ОТКЛОНИТЬ,
    СЛОВО_ПАУЗА,
    СЛОВО_ПРОДОЛЖИТЬ,
    *РАЗДЕЛ_ПО_СЛОВУ,
}

ПОДСКАЗКА = (
    "/task new <название> — завести; /task list — список; /task open <название> — выбрать; "
    "/task этап <этап>; /task план|сделано|сейчас|ограничение|находка <текст> — дописать; "
    "/task забыть <раздел> <номер> — убрать строку; /task done — закрыть задачу; "
    "/task утвердить | отклонить <замечание> — ответить на предложенный переход; "
    "/task пауза | продолжить — остановить и вернуть автомат"
)


def _нет_задачи(state: State) -> None:
    append_log(
        state,
        ui.hint_fragments("сейчас нет рабочей задачи — /task new <название> заведёт её"),
    )


def _обновить_вес(state: State) -> None:
    """Рабочее состояние уходит в запрос и весит. Полоска занятости о нём не знает —
    её отпечаток ловит память и профиль, а слой лежит на диске, как и записи о человеке."""
    забыть_счёт_занятости(state)


def свежая(state: State, каталог: Path, панель: Any = None) -> Any:
    """Активная задача, ПРОЧИТАННАЯ С ДИСКА. `None` — задачи нет либо файл не читается.

    Читаем перед каждой правкой и перед каждым показом, а не держим снимок. Причина названа
    просмотром и стоила бы человеку написанного: запись идёт файлом целиком, и правка,
    сделанная руками между двумя командами, была бы затёрта молча — ровно в том файле,
    который и задуман как правимый руками.

    Жалобу печатаем здесь же: нечитаемый файл — не «задачи нет», и путать их нельзя, иначе
    человек заводит задачу заново поверх своей.

    **Имя без подчёркивания не случайно: зовущий у неё есть и вне этого модуля** —
    `recognizer.записать` берёт активную задачу ею же. Своя копия этих строк у второго входа
    в рабочую память разошлась бы с командой на первой правке, и разошлась бы молча.

    Отсюда и предупреждение для второго зовущего: **у неё есть побочные действия**, и
    пустого возврата мало, чтобы понять, что случилось.

    - печатает в ленту жалобы на нечитаемый файл и подсказку, что с ним делать;
    - если файл рабочей задачи исчез, говорит об этом и **обнуляет `state.слаг_задачи`** —
      то есть после вызова «задача не выбрана» может стать правдой, которой до вызова не было;
    - в этом же случае обновляет вес запроса (`забыть_счёт_занятости`).

    Проще говоря: вернула `None` — о беде человеку уже сказано, второй раз о том же говорить
    не надо. Своё сообщение уместно ровно в одном случае: задачи не было и до вызова.

    `панель` — куда писать эти жалобы. Команде `/task` она не нужна: та печатает сразу, и
    экран под человеком за это время не меняется. Нужна она второму зовущему: естественная
    запись зовёт `свежая` ПОСЛЕ секундного запроса к модели, а за эту секунду человек успевает
    уйти на соседний экран клавишей Tab. Без панели жалоба уезжает туда, где он оказался, —
    и на главном экране, где стоит его эхо, не остаётся ничего либо остаётся половина беды,
    рассказанной на двух экранах сразу.
    """
    if state.слаг_задачи is None:
        return None
    задача, жалобы = workspace.load_task(каталог, state.слаг_задачи)
    for предупреждение in жалобы:
        append_log(state, ui.error_fragments(предупреждение), панель)
    if жалобы:
        # Договариваем, что делать: отказ без выхода запирает человека — закрыть такую задачу
        # командой нельзя, а заводить её заново поверх собственного файла инструмент не даст.
        append_log(
            state,
            ui.hint_fragments("поправьте файл руками или уберите его — затирать его я не буду"),
            панель,
        )
    if задача is None and not жалобы:
        # Файл унесли руками, пока инструмент работал. Имя задачи держать незачем.
        append_log(
            state,
            ui.error_fragments("файл рабочей задачи исчез — задача больше не активна"),
            панель,
        )
        state.слаг_задачи = None
        _обновить_вес(state)
    return задача


def cmd_task(state: State, arg: str) -> None:
    """`/task` во всех видах. Без довода — показать задачу, над которой работаем."""
    части = arg.split(maxsplit=1)
    слово = части[0].lower() if части else ""
    остаток = части[1].strip() if len(части) > 1 else ""
    каталог = Path.cwd()

    if not слово:
        задача = свежая(state, каталог)
        if задача is not None:
            append_log(state, ui.task_fragments(задача))
            return
        if state.слаг_задачи is not None:
            return  # о беде уже сказано
        задачи, жалобы = workspace.list_tasks(каталог)
        for предупреждение in жалобы:
            append_log(state, ui.error_fragments(предупреждение))
        if задачи:
            append_log(state, ui.tasks_list_fragments(задачи, каталог))
            return
        _нет_задачи(state)
        return

    if слово == "new":
        # Профиль с картой стадий: задача начинает с начальной стадии и помнит профиль — одной
        # записью. Профиль без карты — задача дня 11 байт в байт.
        карта = state.profile.стадии
        доводы = (
            {"этап": карта.начальная.имя, "профиль": state.profile.name}
            if карта is not None
            else {}
        )
        задача, сообщение, новая = workspace.create_task(каталог, остаток, **доводы)
        if задача is None:
            append_log(state, ui.error_fragments(сообщение))
            return
        state.слаг_задачи = задача.слаг
        _обновить_вес(state)
        if новая:
            append_log(state, ui.system_fragments(f"рабочая задача: «{задача.название}», этап {задача.этап}"))
            append_log(state, ui.hint_fragments(ПОДСКАЗКА))
            return
        # Продолжаем прежнюю задачу — и показываем её целиком. Иначе в хвост каждого запроса
        # уедет старый план, о котором человеку не сказали ни слова.
        append_log(state, ui.system_fragments(сообщение))
        append_log(state, ui.task_fragments(задача))
        if карта is not None and not задача.профиль:
            # Продолжение этапа не трогает — и профиля задаче не приписывает: человек должен
            # знать, что автомат этого профиля её не поведёт.
            append_log(state, ui.hint_fragments("эту задачу автомат не ведёт: она заведена без карты"))
        return

    if слово == "list":
        задачи, жалобы = workspace.list_tasks(каталог)
        for предупреждение in жалобы:
            append_log(state, ui.error_fragments(предупреждение))
        if not задачи:
            _нет_задачи(state)
            return
        append_log(state, ui.tasks_list_fragments(задачи, каталог))
        return

    if слово == "open":
        if not остаток:
            append_log(state, ui.hint_fragments("нужно название или слаг: /task open разделение cli.py"))
            return
        задачи, жалобы = workspace.list_tasks(каталог)
        for предупреждение in жалобы:
            append_log(state, ui.error_fragments(предупреждение))
        искомое = " ".join(остаток.split()).casefold()
        # Ищем и по названию, и по слагу: в списке человек видит оба, и требовать от него
        # одного написания значило бы заставлять набирать имя файла по буквам.
        найденная = next(
            (
                з
                for з in задачи
                if з.название.casefold() == искомое or з.слаг.casefold() == искомое
            ),
            None,
        )
        if найденная is None:
            append_log(state, ui.error_fragments(f"нет задачи «{остаток}» — /task list покажет, какие есть"))
            return
        state.слаг_задачи = найденная.слаг
        _обновить_вес(state)
        append_log(state, ui.task_fragments(найденная))
        return

    if слово not in СЛОВА_КОМАНДЫ:
        # Неизвестное слово называем ДО проверки активной задачи: иначе опечатка отправляла бы
        # человека заводить задачу, которой его никто не просил заводить.
        append_log(state, ui.error_fragments(f"не понимаю «{слово}»"))
        append_log(state, ui.hint_fragments(ПОДСКАЗКА))
        return

    задача = свежая(state, каталог)
    if задача is None:
        if state.слаг_задачи is None:
            _нет_задачи(state)
        return

    if слово == "этап":
        _этап(state, задача, остаток)
        return

    if слово == СЛОВО_УТВЕРДИТЬ:
        _утвердить(state, задача)
        return

    if слово == СЛОВО_ОТКЛОНИТЬ:
        _отклонить(state, задача, остаток)
        return

    if слово in (СЛОВО_ПАУЗА, СЛОВО_ПРОДОЛЖИТЬ):
        _пауза(state, задача, слово == СЛОВО_ПАУЗА)
        return

    if слово == "забыть":
        куски = остаток.rsplit(maxsplit=1)
        номер = номер_строки(куски[1]) if len(куски) == 2 else None
        if номер is None:
            append_log(
                state,
                ui.hint_fragments("нужен раздел и номер строки: /task забыть план 2 (номера показывает /task)"),
            )
            return
        # Раздел называем ТЕМ ЖЕ словом, каким в него пишут: человек дописывал строку командой
        # `/task находка <текст>` и уберёт её `/task забыть находка 1`. Отправлять его за
        # «находками» значило бы завести два имени одного раздела.
        раздел_забыть = РАЗДЕЛ_ПО_СЛОВУ.get(куски[0].lower(), куски[0])
        убрана, сообщение = workspace.remove_line(задача, раздел_забыть, номер)
        if not убрана:
            append_log(state, ui.error_fragments(сообщение))
            return
        _обновить_вес(state)
        append_log(state, ui.system_fragments(f"убрано из задачи: {сообщение}"))
        return

    if слово in РАЗДЕЛ_ПО_СЛОВУ:
        раздел = РАЗДЕЛ_ПО_СЛОВУ[слово]
        записано, сообщение = workspace.add_line(задача, раздел, остаток)
        if not записано:
            append_log(state, ui.error_fragments(сообщение))
            return
        _обновить_вес(state)
        append_log(state, ui.system_fragments(f"{раздел.lower()}: {сообщение}"))
        return

    # слово == "done"
    # Печатаем файл целиком ДО удаления, и печатаем прочитанный только что с диска: в
    # «Находках» лежит то, за что заплачено разговором, и показать снимок вместо настоящего
    # содержимого значило бы скрыть от человека ровно те строки, которые он дописал руками.
    append_log(state, ui.task_fragments(задача))
    закрыта, сообщение = workspace.close_task(задача)
    if not закрыта:
        append_log(state, ui.error_fragments(сообщение))
        return
    state.слаг_задачи = None
    _обновить_вес(state)
    append_log(state, ui.system_fragments(f"задача «{сообщение}» закрыта — рабочая память удалена"))
    append_log(
        state,
        ui.hint_fragments("то, что переживает задачу, кладите в записи о себе: /remember <текст>"),
    )


def _чужой_профиль(state: State, задача: Any) -> str:
    """Отказ для задачи, заведённой в другом профиле; пустая строка — профиль свой или не назван."""
    if задача.профиль and задача.профиль != state.profile.name:
        return f"задача заведена в профиле «{задача.профиль}» — откройте его: /profile {задача.профиль}"
    return ""


def _карта_задачи(state: State, задача: Any) -> tuple[machine.Карта | None, str]:
    """Карта, по которой человек отвечает автомату; `None` — ответить нельзя, и почему.

    Карта берётся у профиля главного экрана и годится только задаче, заведённой в нём же:
    ворота задачи другого профиля открываются по ЕГО карте, и сверять переход с чужой картой
    значило бы утвердить то, чего в её карте может не быть вовсе.
    """
    чужой = _чужой_профиль(state, задача)
    if чужой:
        return None, чужой
    if not задача.профиль:
        return None, "задача заведена без автомата — ворот у неё нет, этап ставится /task этап <стадия>"
    if state.profile.стадии is None:
        return None, (
            f"у профиля «{state.profile.name}» нет карты стадий — верните stages в профиль "
            f"или ставьте этап сами: /task этап <стадия>"
        )
    return state.profile.стадии, ""


def _после_перехода(state: State, задача: Any, карта: machine.Карта, куда: str, незакрытые: str) -> None:
    """Подсказки после перехода, применённого человеком: что стало с планом и что дальше."""
    if незакрытые:
        append_log(state, ui.hint_fragments(f"в плане не были закрыты — перенесены в «Находки»: {незакрытые}"))
    if карта.конечная(куда):
        append_log(
            state,
            ui.hint_fragments(f"задача дошла до конечной стадии {куда} — /task done закроет её"),
        )
        return
    if задача.пауза:
        append_log(state, ui.hint_fragments("задача на паузе — /task продолжить вернёт модели инструменты"))
        return
    append_log(state, ui.hint_fragments(f"напишите модели — она продолжит работу в стадии {куда}"))


def _этап(state: State, задача: Any, остаток: str) -> None:
    """`/task этап X`.

    Задача без профиля — поведение дня 11: этап — любое слово. Задача другого профиля —
    отказ: её стадии знает её карта. Задача своего профиля без карты — этап ставится без
    сверки, и это говорится вслух.

    Задача своего профиля с картой: стадии не из карты не бывает (автомат перестал бы вести
    задачу); стадия из карты ставится тем же переходом, что и утверждение, — итог в
    «Сделано», план прежней стадии очищен, незакрытые шаги в «Находки».

    Переход МИМО карты человеку по-прежнему разрешён — это его ворота, — но требует слова
    `силой`. Прежде он делался молча и объявлялся уже post factum, когда план стёрт, а итог
    уехал в «Сделано»: одна опечатка в имени стадии проводила задачу через три стадии, и день
    про контролируемые переходы держался на том, что человек не ошибётся. Право остаётся,
    случайность уходит.
    """
    чужой = _чужой_профиль(state, задача)
    if чужой:
        append_log(state, ui.error_fragments(чужой))
        return
    карта = state.profile.стадии
    if not задача.профиль or карта is None:
        сменён, сообщение = workspace.set_stage(задача, остаток)
        if not сменён:
            append_log(state, ui.error_fragments(сообщение))
            return
        _обновить_вес(state)
        append_log(state, ui.system_fragments(f"этап задачи «{задача.название}»: {сообщение}"))
        if задача.профиль:
            append_log(
                state,
                ui.hint_fragments(f"у профиля «{state.profile.name}» нет карты стадий — этап поставлен без сверки"),
            )
        return

    стадии = ", ".join(с.имя for с in карта.стадии)
    слова = остаток.split()
    силой = bool(слова) and слова[-1].lower() == СЛОВО_СИЛОЙ
    имя = machine.имя_стадии(" ".join(слова[:-1]) if силой else остаток)
    if not имя:
        append_log(state, ui.hint_fragments(f"нужна стадия: /task этап <стадия> — есть: {стадии}"))
        return
    if карта.стадия(имя) is None:
        append_log(
            state,
            ui.error_fragments(f"стадии {имя} нет в карте профиля «{state.profile.name}» — есть: {стадии}"),
        )
        return
    откуда = задача.этап
    if имя == откуда:
        append_log(state, ui.system_fragments(f"задача уже в стадии {имя}"))
        return
    текущая = карта.стадия(откуда)
    вне_карты = текущая is None or имя not in текущая.дальше
    if вне_карты and not силой:
        if текущая is None:
            дальше = f"никуда — стадии {откуда} нет в карте"
        else:
            дальше = ", ".join(текущая.дальше) or "никуда — стадия конечная"
        append_log(
            state,
            ui.error_fragments(f"из стадии {откуда} по карте можно в: {дальше} — этап не поставлен"),
        )
        append_log(
            state,
            ui.hint_fragments(f"перейти мимо карты: /task этап {имя} {СЛОВО_СИЛОЙ}"),
        )
        return
    применён, незакрытые = machine.применить_переход(задача, карта, имя, задача.итог)
    if not применён:
        append_log(state, ui.error_fragments(f"этап не поставлен: {незакрытые}"))
        return
    _обновить_вес(state)
    append_log(state, ui.system_fragments(f"этап задачи «{задача.название}»: {откуда} → {имя}"))
    if вне_карты:
        append_log(state, ui.hint_fragments(f"переход вне карты сделан человеком: {откуда} → {имя}"))
        workspace.add_line(задача, "Находки", f"переход вне карты человеком: {откуда} → {имя}")
    _после_перехода(state, задача, карта, имя, незакрытые)


def _утвердить(state: State, задача: Any) -> None:
    """`/task утвердить` — открыть ворота: применить переход, который предложила модель.

    Предложенная стадия сверяется с картой заново: ключ лежит в файле, который человек правит
    руками, и утвердить можно только переход, который карта разрешает из текущей стадии.
    """
    if not задача.предложено:
        append_log(state, ui.error_fragments("утверждать нечего — модель не предлагала перехода"))
        return
    карта, причина = _карта_задачи(state, задача)
    if карта is None:
        append_log(state, ui.error_fragments(причина))
        return
    откуда, куда = задача.этап, задача.предложено
    текущая = карта.стадия(откуда)
    if текущая is None:
        append_log(
            state,
            ui.error_fragments(
                f"этап {откуда} не из карты профиля — утвердить переход нельзя; "
                f"поставьте этап сами: /task этап <стадия>"
            ),
        )
        return
    if куда not in текущая.дальше:
        можно = f"из {откуда} можно в {', '.join(текущая.дальше)}" if текущая.дальше else f"стадия {откуда} конечная"
        append_log(
            state,
            ui.error_fragments(
                f"предложенного перехода {откуда} → {куда} нет в карте: {можно} — поправьте "
                f"«предложено» в файле задачи или поставьте этап сами: /task этап <стадия>"
            ),
        )
        return
    применён, подробность = machine.применить_переход(задача, карта, куда, задача.итог)
    if not применён:
        append_log(state, ui.error_fragments(f"переход не применён: {подробность}"))
        return
    _обновить_вес(state)
    append_log(state, ui.system_fragments(f"утверждено: {откуда} → {куда}"))
    _после_перехода(state, задача, карта, куда, подробность)


def _отклонить(state: State, задача: Any, замечание: str) -> None:
    """`/task отклонить <замечание>` — ворота остаются закрытыми, ход возвращается модели.

    Этап прежний. Одной записью снимаются предложение и итог, ставится «ждёт модель» и
    ожидание с замечанием — его модель прочтёт в состоянии задачи, — а само замечание ложится в
    «Находки»: ожидание перепишет следующий план, а находка останется.
    """
    ждёт_без_предложения = not задача.предложено and задача.ждёт == workspace.ЖДЁТ_ЧЕЛОВЕК
    if not задача.предложено and not ждёт_без_предложения:
        append_log(state, ui.error_fragments("отклонять нечего — модель не предлагала перехода"))
        return
    замечание = " ".join(замечание.split())
    if not замечание:
        append_log(
            state,
            ui.hint_fragments("нужно замечание — что не так: /task отклонить нужен второй вариант"),
        )
        return
    карта, причина = _карта_задачи(state, задача)
    if карта is None:
        append_log(state, ui.error_fragments(причина))
        return
    откуда, куда = задача.этап, задача.предложено
    if ждёт_без_предложения:
        # Ожидание без предложения бывает после правки файла руками. Выход из него обязан
        # быть командой: иначе задача стоит, пока человек снова не полезет в файл.
        записано, ошибка = workspace.обновить(
            задача,
            итог="",
            ждёт=workspace.ЖДЁТ_МОДЕЛЬ,
            ожидается=f"продолжить стадию {откуда} по замечанию: {замечание}",
            дописать={"Находки": f"ожидание снято: {замечание}"},
        )
        if not записано:
            append_log(state, ui.error_fragments(ошибка))
            return
        _обновить_вес(state)
        append_log(state, ui.system_fragments(f"ожидание снято, ход у модели — стадия {откуда}"))
        append_log(
            state,
            ui.hint_fragments("напишите модели, что делать дальше, — она получит замечание в состоянии задачи"),
        )
        return
    записано, ошибка = workspace.обновить(
        задача,
        предложено="",
        итог="",
        ждёт=workspace.ЖДЁТ_МОДЕЛЬ,
        ожидается=f"переделать итог стадии {откуда} по замечанию: {замечание}",
        дописать={"Находки": f"отклонено: {замечание}"},
    )
    if not записано:
        append_log(state, ui.error_fragments(ошибка))
        return
    _обновить_вес(state)
    append_log(state, ui.system_fragments(f"отклонено: переход {откуда} → {куда}, этап прежний — {откуда}"))
    append_log(
        state,
        ui.hint_fragments("напишите модели, что делать дальше, — она получит замечание в состоянии задачи"),
    )


def _пауза(state: State, задача: Any, поставить: bool) -> None:
    """`/task пауза` и `/task продолжить` — признак поверх этапа.

    Пауза нужна только задаче, которую ведёт автомат; снять же её можно у любой задачи —
    отметку могли поставить руками.
    """
    if поставить:
        if задача.пауза:
            append_log(state, ui.error_fragments("задача уже на паузе — /task продолжить снимет её"))
            return
        if not задача.профиль:
            append_log(
                state,
                ui.error_fragments(
                    f"задачу «{задача.название}» автомат не ведёт — ставить её на паузу незачем"
                ),
            )
            return
    elif not задача.пауза:
        append_log(state, ui.error_fragments("задача не на паузе"))
        return
    записано, ошибка = workspace.обновить(задача, пауза=поставить)
    if not записано:
        append_log(state, ui.error_fragments(ошибка))
        return
    _обновить_вес(state)
    if поставить:
        append_log(state, ui.system_fragments(f"задача «{задача.название}» на паузе — инструменты автомата сняты"))
        append_log(state, ui.hint_fragments("/task продолжить вернёт их"))
        return
    append_log(state, ui.system_fragments(f"задача «{задача.название}» продолжается — автомат снова ведёт её"))


def номер_строки(текст: str) -> int | None:
    """Номер строки из набранного человеком слова; `None` — это не номер.

    Через `try/except`, а не `isdigit`: `'²'.isdigit()` истинно, а `int('²')` бросает — и
    исключение уходит в задачу отправки, где его глотают. Человек при этом видит пустую
    строку ввода и НИЧЕГО больше: ни ответа, ни ошибки. Тот же разбор стоит у `/forget`.

    Имя открытое: этим же разбором пользуется `/project забыть`, и два разбора одного числа
    разошлись бы на первой правке.
    """
    try:
        return int(текст)
    except ValueError:
        return None
