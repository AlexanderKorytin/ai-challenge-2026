def найти(слово: str) -> list[Раздел]:
    """Разделы, подходящие к набранному: точное слово — ровно он, иначе все, чьё слово
    начинается с набранного. Пустой список — такого раздела нет; больше одного — начало
    неоднозначно, и выбирать за человека первый по порядку нельзя: он увидел бы не тот
    раздел, не поняв почему."""
    набранное = слово.strip().lower()
    if not набранное:
        return []
    for раздел in РАЗДЕЛЫ:
        if раздел.слово == набранное:
            return [раздел]
    return [раздел for раздел in РАЗДЕЛЫ if раздел.слово.startswith(набранное)]


def фрагменты(раздел: Раздел) -> Fragments:
    return [
        ("class:system", f"Справка · {раздел.заголовок}\n"),
        ("", "\n" + раздел.текст() + "\n"),
        ("class:dim", "/help — все разделы · /help <слово> — сразу нужный\n"),
    ]


def ошибка(слово: str, подходящие: list[Раздел]) -> Fragments:
    if подходящие:
        слова = ", ".join(раздел.слово for раздел in подходящие)
        return ui.error_fragments(f"«{слово.strip()}» подходит к нескольким разделам справки: {слова}")
    слова = ", ".join(раздел.слово for раздел in РАЗДЕЛЫ)
    return ui.error_fragments(f"нет раздела справки «{слово.strip()}»; разделы: {слова}")
