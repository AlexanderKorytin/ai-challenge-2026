"""Справка `/help` разделами: перечень разделов, их текст и поиск раздела по набранному слову.

Справка разрослась до полутора сотен строк, и нужный абзац в сплошном полотне стало не найти.
Поэтому она разбита на разделы: `/help` открывает меню разделов, `/help <слово>` печатает один
раздел сразу. У раздела два имени — слово для набора и заголовок для показа: подстановка при
наборе делит строку по пробелам, и заголовок из двух слов в ней целиком не подставился бы.

Модуль ничего не открывает и в ленту не пишет — это дело команды. `ui` его не ввозит: иначе
замкнулся бы круг `ui → helpdoc → recognizer → … → ui`.
"""

from __future__ import annotations

import textwrap
from collections.abc import Callable
from dataclasses import dataclass

from . import recognizer, ui

Fragments = ui.Fragments

# Ширина, по которой переносится единственный абзац справки, набираемый не руками, а из
# живого списка зачинов. Поведения она не ограничивает: ничего не режется и не отклоняется,
# число решает только, где перенести строку. Взято оно замером соседей — около этого края
# набраны абзацы справки, — а не выбрано: строки таблиц команд и слоёв шире, до 97 знаков, и
# равняться на них абзацу связного текста незачем.
ШИРИНА_АБЗАЦА_СПРАВКИ = 84


@dataclass(frozen=True)
class Раздел:
    слово: str  # то, что набирают после /help: строчные, без пробелов
    заголовок: str  # то, что показывают в меню и над текстом
    подсказка: str  # правый столбец меню: о чём раздел
    # Текст строится при показе, а не при ввозе: таблица команд и список зачинов живые.
    текст: Callable[[], str]


def _строка_зачинов() -> str:
    """Обороты естественной записи — из того же места, где их узнают, и с тем же переносом.

    Переписать список словами рядом было бы дешевле на один ввоз и дороже на молчаливое
    расхождение: справка обещала бы оборот, на который инструмент не отзывается.

    Переносим по ширине, а не одной строкой: список растёт — сегодня в нём шесть оборотов, —
    и строка, вылезшая за край, в терминале не переносится по словам, а рвётся посреди слова
    либо уезжает под обрез.
    """
    обороты = ", ".join(f"«{зачин}»" for зачин in recognizer.ЗАЧИНЫ)
    return textwrap.fill(
        f"Начните реплику словом {обороты} — и она уйдёт одним дешёвым запросом к модели: "
        "та называет слой памяти и раздел, а кладёт строку сам инструмент.",
        width=ШИРИНА_АБЗАЦА_СПРАВКИ,
    )


def _команды() -> str:
    """Здесь перечислены все команды, включая /auth: меню его после авторизации прячет,
    а узнать, чем сменить ключ, пользователь должен где-то в одном месте."""
    строки = []
    for name, arg, description, _ in ui.COMMANDS:
        signature = f"{name} {arg}".strip()
        строки.append(f"  {signature:<20} — {description}\n")
    return "".join(строки) + (
        "\n"
        "Ввод «/» открывает список команд прямо под строкой ввода: стрелки — выбор,\n"
        "Tab или Enter — подставить, Esc — закрыть.\n"
        "/set temperature открывает меню значений: стрелки — выбор, Enter — применить,\n"
        "Esc — выйти без изменений.\n"
    )


