@dataclass
class Адрес:
    """Куда и что кладём. `раздел` пуст только у слоя «человек» — у записей о нём разделов нет."""

    слой: str
    раздел: str
    текст: str


def есть_зачин(текст: str) -> bool:
    """Начинается ли реплика с оборота, за которым стоит просьба запомнить.

    Сравнение идёт по НАЧАЛУ строки, а не по вхождению: «я не знаю, запиши ли ты это» — вопрос
    к собеседнику, а не просьба, и распознавание за него платить не должно.

    Граница слова обязательна с той же строгостью: без неё «запишите план на неделю» —
    обычная просьба к модели — считалась бы зачином, и человек платил бы лишний запрос за
    каждую такую реплику.
    """
    # Слева снимаем не только пробелы: «— запиши, что мне 40» и «"запомни: …"» — та же просьба,
    # набранная человеком, который начал строку с тире или кавычки. Пропустить её значило бы
    # молча отказаться работать так, как он просил, — а лишнее срабатывание стоит одного
    # дешёвого запроса, которым распознаватель ответит «это не запись».
    строка = текст.casefold()
    начало = 0
    while начало < len(строка) and not строка[начало].isalnum():
        начало += 1
    строка = строка[начало:]
    for зачин in ЗАЧИНЫ:
        if not строка.startswith(зачин):
            continue
        хвост = строка[len(зачин) :]
        if not хвост or not хвост[0].isalnum():
            return True
    return False


def разобрать(raw: str) -> tuple[Адрес | None, str]:
    """Адрес из ответа распознавателя. `(адрес, "")` — удача, `(None, причина)` — нет.

    Исключений не выпускает ни на каком вводе: ответ модели приходит сюда как есть, и
    распознаватель, уронивший ввод человека, отнял бы у него набранную строку.

    Пустая причина при `None` означает ровно одно: слой «нет», то есть честный ответ «это не
    запись». Отличать его от сбоя обязательно — сбой оплачен и о нём говорят вслух, а «не
    запись» обычный ход дела, и строка о ней была бы шумом в каждой третьей реплике.
    """
    try:
        разобранное = json.loads(raw)
    except (json.JSONDecodeError, TypeError, ValueError, RecursionError):
        # `RecursionError` стоит здесь не для полноты списка: профиль распознавателя намеренно
        # без предела на выход, и выродившийся повтор модели — единственный вход, на котором
        # `json.loads` уходит вглубь. Выпущенное отсюда исключение прошло бы сквозь общую
        # развилку ввода и съело набранную человеком строку.
        return None, "ответ распознавателя не разбирается"
    if not isinstance(разобранное, dict):
        return None, "ответ распознавателя не объект"

    слой_как_есть = разобранное.get(КЛЮЧ_СЛОЙ)
    if слой_как_есть is None:
        return None, "в ответе распознавателя нет слоя"
    if not isinstance(слой_как_есть, str):
        # Причину читает человек в ленте. Скажи мы «нет слоя» там, где слой есть, но пришёл
        # объектом, — он искал бы поломку не там, где она случилась.
        return None, "слой в ответе распознавателя не строка"

    слой = " ".join(слой_как_есть.split()).casefold()
    if слой == СЛОЙ_НЕТ:
        return None, ""
    if слой not in СЛОИ:
        return None, f"слой «{слой_как_есть}» распознавателю не положен"

    текст_как_есть = разобранное.get(КЛЮЧ_ТЕКСТ)
    текст = " ".join(текст_как_есть.split()) if isinstance(текст_как_есть, str) else ""
    if not текст:
        return None, "распознаватель не назвал текст записи"

    раздел_как_есть = разобранное.get(КЛЮЧ_РАЗДЕЛ)
    раздел = раздел_как_есть if isinstance(раздел_как_есть, str) else ""

    if слой == СЛОЙ_ЧЕЛОВЕК:
        # Раздел затираем, а не терпим: у записей о человеке разделов не бывает, и названный
        # моделью раздел здесь означает, что она перепутала слой.
        return Адрес(СЛОЙ_ЧЕЛОВЕК, "", текст), ""

    if слой == СЛОЙ_ЗАДАЧА:
        # Разделов у задачи ровно пять, и канон берём у самого хранилища: заведи мы свой
        # список — он разошёлся бы с `workspace.РАЗДЕЛЫ` в первый же день, когда там что-то
        # поменяют.
        if раздел_как_есть is not None and not isinstance(раздел_как_есть, str):
            return None, "раздел в ответе распознавателя не строка"
        имя = workspace.нормализовать_раздел(раздел)
        if имя is None:
            return None, f"раздела «{раздел}» у задачи нет — есть: {', '.join(workspace.РАЗДЕЛЫ)}"
        return Адрес(СЛОЙ_ЗАДАЧА, имя, текст), ""

    # Слой «папка». Перечня разделов у карточки нет — человек называет их сам, — поэтому имя
    # только приводится к сравнимому виду. Пустое имя это отказ: раздел-призрак в карточке
    # хуже, чем неразобранный ответ.
    if раздел_как_есть is not None and not isinstance(раздел_как_есть, str):
        return None, "раздел в ответе распознавателя не строка"
    имя = project_card.привести_имя(раздел)
    if not имя:
        return None, "распознаватель не назвал раздел карточки"
    return Адрес(СЛОЙ_ПАПКА, имя, текст), ""


def профиль() -> Profile:
    """Профиль, с которым распознаватель ходит к модели.

    `keep_history=False`: заходов подряд у распознавателя не бывает — каждая реплика
    самодостаточна, и помни он прошлые, второй запрос платил бы за первый вторым разом. Здесь
    у этого есть вторая, своя причина: прошлая реплика человека — чужое знание о том, чего он
    в ЭТОЙ реплике не говорил, и адрес по ней угадывался бы, а не читался.

    Рассуждения выключены, температура низкая: адрес уже назван в самой реплике, и работа
    сводится к тому, чтобы его оттуда достать. `json_object` снимает разбор обёрток вроде
    «вот адрес:» вокруг ответа.

    **Предела на выход НЕТ, и это решение, а не упущение.** Причина у архивариуса записана
    днём 9, и на своей задаче она проверяется заново — сходится. Ответ распознавателя это
    объект JSON: оборви его на полуслове, и не разберётся НИЧЕГО — ни слой, ни текст. Хуже
    того, беда была бы неотличима от обычного хода дела: `разобрать` терпим, а `{"слой": "не`
    даёт ту же пару `(None, причина)`, что и любой другой мусор, — и человек, начавший реплику
    с зачина, молча не получал бы записи всякий раз, как его строка чуть длиннее обычного.
    Длину ответа держит инструкция — «одной короткой строкой», — а не число.

    Расхождение с архивариусом ровно одно, и оно в пользу отсутствия предела: архивариус
    возвращает СПИСОК фактов, и у него предел терял заход целиком, а здесь терялась бы
    вдобавок набранная человеком строка — она уходит обычным вопросом, то есть не в память.

    Профиль собирается заново на каждый вызов: словарь `params` изменяем, и общий на всех он
    однажды оказался бы поправлен соседом.
    """
    return Profile(
        name=ИМЯ_РАСПОЗНАВАТЕЛЯ,
        system=ИНСТРУКЦИЯ,
        keep_history=False,
        params={
            "temperature": 0.2,
            "response_format": {"type": "json_object"},
            "thinking": {"type": "disabled"},
        },
    )


def вход(state: State, реплика: str) -> str:
    """Всё, что нужно модели, чтобы назвать адрес, — одним самодостаточным текстом.

    Разговор сюда НЕ идёт, и это решение дизайна: адрес читается из самой реплики, а кусок
    разговора удвоил бы цену запроса ради догадок — и ровно теми догадками подменил бы
    прочтение. Человек, сказавший «запиши это», обращается к своей же строке, а не к тому,
    о чём шла речь тремя ходами раньше.

    Имена разделов карточки и наличие рабочей задачи зависят от РАБОЧЕГО КАТАЛОГА, поэтому
    берутся здесь, на каждый запрос, а не откладываются в поле: человек меняет папку, не
    выходя из инструмента.

    Функция ничего не печатает — она собирает текст. Это не мелочь: сведения о задаче ниже
    берутся в обход `commands_task.свежая` именно потому, что у той есть побочные действия.
    """
    каталог = Path.cwd()
    куски: list[str] = []

    название = ""
    if state.слаг_задачи:
        # `load_task`, а не `commands_task.свежая`: та печатает жалобы в ленту и обнуляет
        # `state.слаг_задачи`. Позови мы её здесь — человек получил бы одну и ту же жалобу
        # дважды, потому что `записать` зовёт её же и по делу.
        задача, _ = workspace.load_task(каталог, state.слаг_задачи)
        # Нечитаемую задачу называем слагом, а не прячем. Скажи мы «задачи нет» — модель
        # выбрала бы папку, и строка о задаче легла бы в карточку МОЛЧА, не туда. Пусть уж
        # назовёт задачу: отказ о нечитаемом файле напечатает `записать`, и он будет честным.
        название = задача.название if задача is not None else state.слаг_задачи
    куски.append(
        f"Рабочая задача сейчас: «{название}»" if название else "Рабочей задачи сейчас нет"
    )
    # Разделы задачи называем ВСЕГДА, в том числе когда задачи нет: иначе модель, выбравшая
    # слой «задача» по явной просьбе человека («запиши в задачи: …»), назвала бы раздел
    # наугад, и к отказу «рабочей задачи нет» добавился бы второй, про неузнанный раздел.
    куски.append(f"Разделы задачи — ровно эти и никаких других: {', '.join(workspace.РАЗДЕЛЫ)}")

    # Имена существующих разделов — единственное, чем лечится «Стек» против «Технологий».
    # Совсем это не лечится: придуманный синоним видно строкой показа и убирается одной
    # командой, а вот молчаливого второго раздела о том же самом не заметил бы никто.
    #
    # Подаём перечень СУХИМ ФАКТОМ — «уже есть», — и ни слова о том, что с ним делать.
    # Живой прогон показал, чем кончается менее осторожная подача: перечень читается как
    # «клади в то, что есть», и названный человеком раздел теряется молча. Правило выбора
    # целиком лежит в инструкции, где рядом стоят оба примера; здесь его нет намеренно —
    # два места с одним правилом разошлись бы, а разошлись бы молча.
    карточка, жалобы_карточки = project_card.load(каталог)
    имена = list(карточка.разделы) if карточка is not None else []
    if имена:
        куски.append(f"В карточке этой папки уже есть разделы: {', '.join(имена)}")
    elif карточка is None and жалобы_карточки:
        # Файл лежит и карточкой не читается. «Карточки нет» тут было бы враньём той же
        # породы, что и «задачи нет» у нечитаемой задачи: модель назвала бы раздел, запись
        # честно отказала бы жалобой хранилища, и оплаченный запрос заведомо кончился бы
        # ничем. Сказать правду дешевле — и она видна человеку в той же ленте.
        куски.append("Карточка этой папки лежит, но не читается — какие в ней разделы, неизвестно")
    else:
        куски.append("Карточки у этой папки ещё нет — разделов в ней пока никаких")

    # Реплика — последней и дословно. Последней потому, что она и есть работа; дословно
    # потому, что «текст» ответа собирается из её слов, и любая правка по дороге ушла бы в
    # память вместо сказанного человеком.
    куски.append(f"Реплика человека, дословно:\n{реплика.strip()}")
    return "\n\n".join(куски)


async def спросить(state: State, реплика: str) -> tuple[Адрес | None, str]:
    """Один дешёвый обмен: модель называет адрес. `(адрес, "")` — удача, иначе `(None, причина)`.

    Пустая причина при `None` значит «говорить человеку нечего»: либо модель честно ответила
    «это не запись», либо запроса не было вовсе — некому было его сделать. Оба случая ведут
    к одному: реплика молча уходит обычным вопросом.

    Непустая причина значит сбой обмена, который БЫЛ СДЕЛАН, и о нём говорят вслух. Правило,
    которого договор держится: причина непуста ровно тогда, когда запрос ушёл к серверу, —
    то есть когда он МОГ быть оплачен. Слово «мог» здесь точное, и сильнее его обещать
    нельзя: обмен, оборвавшийся на неудавшемся соединении, денег не стоил, а причину даёт.
    Человеку это не видно и видно быть не должно — строка о сбое об оплате не утверждает
    ничего; зато счёт сеанса помечается неточным, и `/tokens` не врёт вниз.

    Скажи мы «клиента нет» непустой причиной — человек без ключа получил бы лишнюю жалобу
    поверх честной «ключа нет», и обе о том же самом. Поэтому запроса не было — причины нет.

    Агент одноразовый: памяти у распознавателя нет, каждая реплика самодостаточна.

    **Расход обмена уходит в итог сеанса на любом пути, включая оборвавшийся.** Распознаватель
    живёт вне панелей, а значит и вне обхода агентов сеанса: без `retire` его токены не попали
    бы в `/tokens` никогда. И это единственная трата, которую человек не заказывал вручную, —
    промолчать именно о ней было бы хуже всего: он увидел бы итог, который врёт вниз, молча и
    всегда. Поэтому учёт стоит в `finally`, а не после удачного ответа: обмен, оборванный на
    полуслове, тоже мог быть оплачен.

    Исключение наружу выпускаем, а не глотаем: отмену (выход из инструмента) глотать нельзя
    вовсе, а прочие беды разбирает развилка ввода — она же и решает, что делать с набранной
    человеком строкой. Здесь такого решения принять не из чего.
    """
    if state.client is None:
        # Спрашивать некого, и денег не потрачено — значит и причины нет. Строка человека при
        # этом не теряется: развилка ввода отправит её обычным вопросом, и об отсутствии ключа
        # он услышит оттуда, один раз и по делу.
        return None, ""
    # Вход собираем ДО `try`, и это не косметика. Внутри `try` его исключение — а `Path.cwd()`
    # падает в унесённом каталоге, и диск отказывает — ушло бы в `finally` с `обмен is None`,
    # то есть объявило бы рублёвый итог неточным, не потратив ни цента. Портился бы ровно тот
    # показ, ради честности которого здесь всё и заведено.
    запрос = вход(state, реплика)
    агент = Agent(ИМЯ_РАСПОЗНАВАТЕЛЯ, профиль())
    обмен = None
    try:
        обмен = await агент.exchange(
            state.client, МОДЕЛЬ_РАСПОЗНАВАТЕЛЯ, запрос, agent=ИМЯ_РАСПОЗНАВАТЕЛЯ
        )
    finally:
        state.retire([агент])
        # Деньги считаем ОТДЕЛЬНО от токенов: копилка выбывших несёт токены, а рубли копятся
        # по ходу и по тарифу той модели, которой сделан обмен, — а модель у распознавателя
        # своя, дешёвая, и она не совпадает с моделью разговора.
        if обмен is not None:
            цена = turn_price(обмен)
            if цена is None:
                state.session_cost_known = False
            else:
                state.session_cost += цена
        else:
            # Обмен оборвался (выход из инструмента посреди запроса). Копилка забрала то, что
            # успело прийти, — а придти обычно не успевает ничего: `usage` присылают последним
            # событием. Тем более нельзя выдавать рублёвый итог за точный: человек прочёл бы
            # его как «вот столько потрачено», недосчитав запрос, который мог быть оплачен.
            state.session_cost_known = False
    if not обмен.ok:
        return None, обмен.error or "неизвестная причина"
    if обмен.finish_reason == "length":
        # Три разные беды, которые нельзя сваливать в одну. Отказ сервера — запроса не было
        # или он не дошёл. Обрыв по длине — ответ был, но нам не дали его дочитать, и
        # оборванный JSON не разбирается вовсе. «Ответить нечего» — вообще не беда. Разбор
        # терпим и первые две отдал бы одинаковым мусором, поэтому различаются они здесь.
        return None, "ответ оборван по длине"
    return разобрать(обмен.text)


def записать(state: State, адрес: Адрес, панель: screens_mod.Pane) -> bool:
    """Кладёт строку в названный адресом слой и говорит, что легло и чем это убрать.

    Возвращает, легла ли строка в хранилище: отказ замка и отказ диска — это `False`.

    `панель` — куда писать то, что говорится человеку. Она есть у КАЖДОГО сообщения этого
    модуля, и не ради порядка: естественная запись идёт после секундного запроса, а за эту
    секунду человек успевает уйти на соседний экран клавишей Tab. Без явной панели
    подтверждение уехало бы туда, где человек оказался к моменту ответа, — а его эхо и строка
    ожидания остались бы на главном экране в виде, неотличимом от молча съеденной строки.
    Панель здесь обязана быть ТОЙ ЖЕ, в которой напечатано эхо, и захваченной вместе с ним.

    Довод ОБЯЗАТЕЛЬНЫЙ, и умолчания у него нет намеренно. Умолчание, которым пользуются
    одни проверки, — заготовленная дыра: следующий вызов из нового места забудет панель,
    промолчит на чужом экране и будет выглядеть исправным. Правило живёт в подписи, где его
    нельзя не выполнить, а не в этом пояснении, где его можно не прочесть.

    Второй двери в хранилища здесь нет: пишем теми же `memory.add_fact`, `workspace.add_line`
    и `project_card.add_line`, какими пишет человек командами. Обойди мы их — права на файлы,
    запись снимком и сохранение чужих разделов оказались бы сделаны второй раз и по-другому,
    а такие пары расходятся молча.
    """
    if адрес.слой == СЛОЙ_ЧЕЛОВЕК:
        return _в_записи_о_человеке(state, адрес, панель)
    if адрес.слой == СЛОЙ_ЗАДАЧА:
        return _в_рабочую_задачу(state, адрес, панель)
    if адрес.слой == СЛОЙ_ПАПКА:
        return _в_карточку_папки(state, адрес, панель)
    # Слой не из тех, куда пишет память. `разобрать` такого не выпустит, но `записать`
    # открыто и для собранного руками адреса, и молчаливое `False` отправило бы искать
    # поломку в диске — там, где её нет.
    append_log(state, ui.error_fragments(f"памяти не принадлежит слой «{адрес.слой}»"), панель)
    return False


def команда_записи(адрес: Адрес) -> str:
    """Чем человек повторит эту запись руками, если программа её не осилила.

    Нужна там, где адрес уже разобран, а запись не состоялась по причине, о которой сказать
    можно, а сделать нельзя: отказал диск, упал счёт номера. Набранное человеком в этот миг
    живёт только эхом в ленте, и заставлять его перенабирать строку, глядя на собственное
    эхо, — тот же молчаливый промах, только вежливый. Замок «Ограничений» и отказ «рабочей
    задачи нет» команду возвращают; третий отказ одного звена вести себя иначе не вправе.

    Слово раздела задачи берётся тем же обратным отображением, что и в показе, — своим
    списком оно разошлось бы с командой `/task` на первой же правке.
    """
    if адрес.слой == СЛОЙ_ЧЕЛОВЕК:
        return f"/remember {адрес.текст}"
    if адрес.слой == СЛОЙ_ЗАДАЧА:
        return f"/task {_слово_раздела(адрес.раздел)} {адрес.текст}"
    if адрес.слой == СЛОЙ_ПАПКА:
        return f"/project {адрес.раздел}: {адрес.текст}"
    # Слоя не из тех, куда пишет память, `разобрать` не выпустит. Пустая строка здесь значит
    # «команды нет», и зовущий обязан её проверить: строка-обрубок вида «/ …» была бы хуже
    # молчания — человек нажал бы её и получил «неизвестная команда».
    return ""


def _номер_факта(текст: str) -> int:
    """Номер записи о человеке, каким его покажет `/memory`. `0` — такой записи в списке нет.

    Ищем перечитыванием слоя, а не считаем «записали последней, значит крайняя»: записи
    упорядочены по времени добавления, а в пределах одной секунды — по имени файла, и новая
    запись не обязана оказаться в конце. Номер, разошедшийся с показанным `/memory`, хуже
    отсутствующего: `/forget` по нему уберёт чужую строку.
    """
    ключ = " ".join(текст.split()).casefold()
    факты, _ = memory.load_facts()
    for номер, факт in enumerate(факты, 1):
        if " ".join(факт.split()).casefold() == ключ:
            return номер
    return 0


def _отказ_хранилища(state: State, адрес: Адрес, сообщение: str, панель: screens_mod.Pane) -> bool:
    """Отказ хранилища человеку: его словами, а при внешней беде — с готовой командой.

    Слова хранилища уходят как есть: «уже записано», «память полна» и отказ в правах — три
    разные беды с тремя разными лечениями, и пересказ своими словами сравнял бы их в одно
    «не получилось».

    Команду даём только там, где она МОЖЕТ сработать. Отказы, зависящие от самой строки —
    повтор, пустой текст, слишком длинный факт, замок раздела, — от повторения не изменятся:
    нажатая команда дала бы тот же отказ, и две строки в ленте спорили бы друг с другом.
    Список таких отказов держит каждое хранилище само (`ОТКАЗЫ_ПРО_СТРОКУ`): гадать по
    подстрокам чужих сообщений значило бы разойтись с ними молча при первой же правке слов.

    Внешняя беда — нет прав, полон диск, память полна — другое дело: слова человека живут в
    этот миг только эхом в ленте, и заставлять его перенабирать строку, глядя в собственное
    эхо, было бы тем же молчаливым промахом, только вежливым.

    Отказ диска приходит именно сюда: запись возвращает беду СТРОКОЙ, а не бросает её, — то
    есть обработчик исключений вокруг записи этого пути не видит вовсе.
    """
    append_log(state, ui.error_fragments(сообщение), панель)
    про_строку = {
        СЛОЙ_ЧЕЛОВЕК: memory.ОТКАЗЫ_ПРО_СТРОКУ,
        СЛОЙ_ЗАДАЧА: workspace.ОТКАЗЫ_ПРО_СТРОКУ,
        СЛОЙ_ПАПКА: project_card.ОТКАЗЫ_ПРО_СТРОКУ,
    }.get(адрес.слой, ())
    приведённое = " ".join(сообщение.split()).casefold()
    if any(приведённое.startswith(начало.casefold()) for начало in про_строку):
        return False
    команда = команда_записи(адрес)
    if команда:
        append_log(state, ui.hint_fragments(f"записать самому: {команда}"), панель)
    return False


def _в_записи_о_человеке(state: State, адрес: Адрес, панель: screens_mod.Pane) -> bool:
    """Слой «человек»: то, что верно в любой папке и не перестаёт быть правдой."""
    добавлена, сообщение = memory.add_fact(адрес.текст)
    if not добавлена:
        return _отказ_хранилища(state, адрес, сообщение, панель)
    забыть_счёт_занятости(state)
    номер = _номер_факта(сообщение)
    убрать = f"убрать: /forget {номер}" if номер else "номер покажет /memory"
    append_log(state, ui.system_fragments(f"записано о вас: «{сообщение}» — {убрать}"), панель)
    return True


def _слово_раздела(раздел: str) -> str:
    """Слово, которым человек назовёт этот раздел задачи в `/task забыть`.

    Берём обратным отображением у самой команды, а не своим списком: назови мы разделы
    по-своему — подсказка обещала бы слово, которого `/task` не знает, и узнал бы человек об
    этом, только нажав Enter.
    """
    # Поздний ввоз по той же причине, что и в `_в_рабочую_задачу`: ввоз вверх по слоям.
    from . import commands_task

    слова: dict[str, str] = {}
    for слово, имя in commands_task.РАЗДЕЛ_ПО_СЛОВУ.items():
        слова.setdefault(имя, слово)
    return слова.get(раздел, раздел)


def _в_рабочую_задачу(state: State, адрес: Адрес, панель: screens_mod.Pane) -> bool:
    """Слой «задача»: то, что умирает вместе с задачей. Задачи нет — записи нет."""
    # Задачу поднимаем ТОЙ ЖЕ функцией, какой поднимает её команда `/task`, — с диска и перед
    # каждой правкой. Своя копия этих строк разошлась бы с командой на первой же правке, и
    # разошлась бы там, где человек правит файл руками: запись идёт файлом целиком, и работа
    # из устаревшего снимка стёрла бы написанное им молча.
    #
    # Ввоз поздний, и круга тут нет — он проверен запуском и с ввозом наверху тоже проходит.
    # Причина в направлении: `commands_*` лежит НАД распознавателем и сам его позовёт, и
    # единственный ввоз вверх по слоям держим точечным, внутри той функции, которой он нужен.
    from . import commands_task

    # Замок «Ограничений» задачи — первым делом, до чтения задачи, и по тому же доводу, что у
    # карточки (`_в_карточку_папки`): слова в строке человека, но АДРЕС выбрала модель, а
    # правило, по которому программа судит её ответы, она себе писать не вправе. Имя
    # приводим `нормализовать_раздел`: сравнение строкой обходилось бы регистром.
    if workspace.нормализовать_раздел(адрес.раздел) == workspace.РАЗДЕЛ_ОГРАНИЧЕНИЙ:
        append_log(
            state,
            ui.error_fragments(
                f"раздел «{workspace.РАЗДЕЛ_ОГРАНИЧЕНИЙ}» задачи пишете только вы:"
                " здесь адрес выбрала модель"
            ),
            панель,
        )
        append_log(
            state,
            ui.hint_fragments(
                f"/task {_слово_раздела(workspace.РАЗДЕЛ_ОГРАНИЧЕНИЙ)} {адрес.текст}"
            ),
            панель,
        )
        return False

    # Панель отдаём и ей: у `свежая` своя печать, и зовётся она ПОСЛЕ секундного запроса —
    # ровно в том окне, ради которого панель и захватывали. Без этого довода нечитаемый файл
    # задачи рассказывался бы на том экране, куда человек ушёл, а `_в_рабочую_задачу` при
    # этом молчит намеренно: на главном остались бы эхо и пустое место.
    задача = commands_task.свежая(state, Path.cwd(), панель)
    if задача is None:
        # О нечитаемом файле и об унесённом руками `свежая` сказала сама, и повторять за ней
        # нечего. Но один её случай выглядит иначе, чем работает, и потому назван вслух:
        # унесённый файл она не только называет, но и ОБНУЛЯЕТ `слаг_задачи` — условие ниже
        # от этого становится истинным, и человек получает ещё две строки поверх её
        # собственной. Три строки на одну беду многовато; ровно так же ведёт себя команда
        # `/task`, и разойтись с ней в поведении хуже, чем напечатать лишнее.
        if state.слаг_задачи is None:
            # Задачу естественная запись не заводит, и это решение, а не упущение: у задачи
            # есть название и есть закрытие, а слой, который заводится сам, никто не
            # закрывает — через неделю в нём десяток мёртвых задач.
            append_log(
                state,
                ui.error_fragments("естественная запись в задачу: рабочей задачи нет"),
                панель,
            )
            append_log(
                state,
                ui.hint_fragments("заведите её сами: /task new <название> — закрывать её тоже вам"),
                панель,
            )
            # Текст записи возвращаем человеку готовой строкой — ровно как это делает замок
            # «Ограничений». Без неё отказ несимметричен: там набранное возвращают, а здесь
            # человек перенабирает его сам, глядя в своё эхо, — и перенабирает не дословно.
            # Раздел называем тем же словом, каким в него пишет команда.
            append_log(
                state,
                ui.hint_fragments(
                    f"а строку потом: /task {_слово_раздела(адрес.раздел)} {адрес.текст}"
                ),
                панель,
            )
        return False
    # Имя раздела приводим к канону сами, хотя `add_line` приведёт его и у себя: по этому же
    # имени мы СЧИТАЕМ строки для номера отмены, и «план» с маленькой буквы дал бы пустой
    # список и номер 0 — указатель на строку, которой нет. Неузнанное имя оставляем как
    # есть: отказать о нём словами хранилища лучше, чем своими.
    имя = workspace.нормализовать_раздел(адрес.раздел) or адрес.раздел
    записано, сообщение = workspace.add_line(задача, имя, адрес.текст)
    if not записано:
        return _отказ_хранилища(state, адрес, сообщение, панель)
    забыть_счёт_занятости(state)
    номер = len(задача.пункты(имя))
    append_log(
        state,
        ui.system_fragments(
            f"{имя.lower()} задачи «{задача.название}»: «{сообщение}»"
            f" — убрать: /task забыть {_слово_раздела(имя)} {номер}"
        ),
        панель,
    )
    return True


def _в_карточку_папки(state: State, адрес: Адрес, панель: screens_mod.Pane) -> bool:
    """Слой «папка»: то, что перестаёт быть правдой в другой папке.

    Здесь же стоит замок на разделе «Ограничения», и стоит он ЗДЕСЬ по существу дела.
    Источник этой записи — человек: слова в строке его, модель назвала только адрес, — а
    замок внутри `project_card.add_line` держится как раз на источнике и такую запись
    пропустил бы. Запрет же сказан про АДРЕС: выбрала его модель, а правило, по которому
    программа начнёт судить её же ответы, она себе писать не вправе.
    """
    каталог = Path.cwd()
    карточка, жалобы = project_card.load(каталог)
    # Имя приводим `нормализовать_раздел`, а не сравнением строк: оно одно канонизирует
    # «ограничения» при любом написании. Сравнивай мы имя как строку — замок обходился бы
    # регистром, и строки, написанные с подсказки модели, легли бы туда, где их читает судья.
    имя = project_card.нормализовать_раздел(адрес.раздел, карточка)
    if имя is None:
        append_log(state, ui.error_fragments("распознаватель не назвал раздел карточки"), панель)
        return False
    if имя == project_card.РАЗДЕЛ_ОГРАНИЧЕНИЙ:
        append_log(
            state,
            ui.error_fragments(
                f"раздел «{project_card.РАЗДЕЛ_ОГРАНИЧЕНИЙ}» карточки пишете только вы:"
                " здесь адрес выбрала модель"
            ),
            панель,
        )
        append_log(
            state,
            ui.hint_fragments(f"/project {project_card.РАЗДЕЛ_ОГРАНИЧЕНИЙ}: {адрес.текст}"),
            панель,
        )
        return False

    строка = " ".join(адрес.текст.split())
    заведена = False
    if карточка is None:
        if жалобы:
            # Файл лежит и карточкой не читается. Заводить поверх него нельзя — `create`
            # откажется, — и сказать «карточки нет» значило бы позвать человека на отказ.
            for предупреждение in жалобы:
                append_log(state, ui.error_fragments(предупреждение), панель)
            append_log(
                state,
                ui.hint_fragments("поправьте файл руками или уберите его — затирать его я не буду"),
                панель,
            )
            return False
        # Первая строка заводит карточку — ровно как `/project Стек: …`. Два поведения у
        # одного хранилища были бы хуже любого из них: человек не знал бы, когда карточка
        # заведётся, а когда ему откажут.
        карточка, сообщение = project_card.create(каталог, {имя: [строка]}, источник="человек")
        if карточка is None:
            return _отказ_хранилища(state, адрес, сообщение, панель)
        заведена = True
        # Новым раздел в заведённой карточке не называем, хотя он, разумеется, нов: новость
        # здесь уже сказана — «карточка заведена», — и второе «новый раздел» рядом с ней
        # ничего не добавляет, а вес имеет. Команда `/project` в том же случае говорит одну
        # новость, и разойтись с ней в словах хуже, чем недосказать.
        новый_раздел = False
    else:
        # Новый раздел или знакомый — решаем ДО записи: после неё он в карточке в любом случае.
        # Здесь это нужнее, чем в команде: там имя назвал человек, а тут его выбрала модель, и
        # «завела свой раздел» от «дописала в знакомый» человек не отличит ничем другим.
        новый_раздел = имя not in карточка.разделы
        записано, сообщение = project_card.add_line(карточка, имя, строка, источник="человек")
        if not записано:
            return _отказ_хранилища(state, адрес, сообщение, панель)
    забыть_счёт_занятости(state)
    номер = len(карточка.пункты(имя))
    начало = "карточка заведена, " if заведена else "карточка, "
    раздел = f"новый раздел «{имя}»" if новый_раздел else имя
    append_log(
        state,
        ui.system_fragments(
            f"{начало}{раздел}: «{строка}» — убрать: /project забыть {имя} {номер}"
        ),
        панель,
    )
    return True
