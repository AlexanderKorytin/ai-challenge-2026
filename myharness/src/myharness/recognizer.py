"""Распознаватель: куда человек просит положить сказанное, когда говорит обычными словами.

Команды называют слой памяти явно — `/remember`, `/task план`, `/project Стек`. В разговоре
человек говорит иначе: «запиши в задачи проекта: вынести команды памяти», «вот тебе факт обо
мне: зовут Александр», — и адрес в этих словах уже назван, просто не командой.

Почему адрес называет ОТДЕЛЬНЫЙ дешёвый запрос, а не тот собеседник, что ведёт разговор. У
образца — памяти Claude Code — адрес выбирает та же модель, что отвечает человеку, потому что у
неё есть инструмент записи. У DeepSeek инструментов нет, и запись тут устроена так же, как у
архивариуса: модель НАЗЫВАЕТ, программа ПИШЕТ. Появятся инструменты — распознаватель заменяется
самозаписью агента без изменения хранилищ.

Почему обязателен зачин. Гонять распознавание на каждой реплике значило бы удвоить число
запросов на ровном месте: платных обменов стало бы два там, где человек задал один вопрос.
Зачин — это и выключатель: не начинай реплику с него, и распознавание не заводится вовсе.

Модуль не знает ни про окно, ни про клавиатуру: всё, что он говорит человеку, уходит в ленту
через `output`, и вся его логика проверяется без терминала и без ключа API.
"""

from __future__ import annotations

import json
from dataclasses import dataclass

from . import project_card, workspace

# Обороты, с которых начинается просьба запомнить. Список закрытый и лежит в ОДНОМ месте: из
# него же справка печатает то, что показывает человеку, — два списка одного набора неизбежно
# разойдутся, и разойдутся молча.
#
# Цена ошибки в этом списке несимметрична, поэтому он скорее широк, чем узок: лишний оборот
# стоит одного дешёвого запроса, которым распознаватель ответит «это не запись», а недостающий —
# молчаливого отказа работать так, как человек просил.
ЗАЧИНЫ: tuple[str, ...] = (
    "запиши",
    "запомни",
    "добавь в",
    "отметь",
    "вот тебе факт",
    "вот тебе факты",
)

# Слои, в которые кладёт естественная запись. Разговора среди них нет: он пишется сам и
# дословно, просить его о записи незачем.
СЛОЙ_ЧЕЛОВЕК = "человек"
СЛОЙ_ЗАДАЧА = "задача"
СЛОЙ_ПАПКА = "папка"
СЛОИ: tuple[str, ...] = (СЛОЙ_ЧЕЛОВЕК, СЛОЙ_ЗАДАЧА, СЛОЙ_ПАПКА)

# Ответ «это не запись в память»: реплика начиналась с зачина, но записывать в ней нечего.
СЛОЙ_НЕТ = "нет"

# Ключи объекта, который возвращает распознаватель. Из них же собирается пример ответа внутри
# инструкции (шаг 3): набери его словами рядом — и разбор с инструкцией разойдутся молча.
КЛЮЧ_СЛОЙ = "слой"
КЛЮЧ_РАЗДЕЛ = "раздел"
КЛЮЧ_ТЕКСТ = "текст"


@dataclass
class Адрес:
    """Куда и что кладём. `раздел` пуст только у слоя «человек» — у записей о нём разделов нет."""

    слой: str
    раздел: str
    текст: str


def есть_зачин(текст: str) -> bool:
    """Начинается ли реплика с оборота, за которым стоит просьба запомнить.

    Сравнение идёт по НАЧАЛУ строки, а не по вхождению: «я не знаю, запиши ли ты это» — вопрос
    к собеседнику, а не просьба, и распознавание за него платить не должно.

    Граница слова обязательна с той же строгостью: без неё «запишите план на неделю» —
    обычная просьба к модели — считалась бы зачином, и человек платил бы лишний запрос за
    каждую такую реплику.
    """
    # Слева снимаем не только пробелы: «— запиши, что мне 40» и «"запомни: …"» — та же просьба,
    # набранная человеком, который начал строку с тире или кавычки. Пропустить её значило бы
    # молча отказаться работать так, как он просил, — а лишнее срабатывание стоит одного
    # дешёвого запроса, которым распознаватель ответит «это не запись».
    строка = текст.casefold()
    начало = 0
    while начало < len(строка) and not строка[начало].isalnum():
        начало += 1
    строка = строка[начало:]
    for зачин in ЗАЧИНЫ:
        if not строка.startswith(зачин):
            continue
        хвост = строка[len(зачин) :]
        if not хвост or not хвост[0].isalnum():
            return True
    return False


def разобрать(raw: str) -> tuple[Адрес | None, str]:
    """Адрес из ответа распознавателя. `(адрес, "")` — удача, `(None, причина)` — нет.

    Исключений не выпускает ни на каком вводе: ответ модели приходит сюда как есть, и
    распознаватель, уронивший ввод человека, отнял бы у него набранную строку.

    Пустая причина при `None` означает ровно одно: слой «нет», то есть честный ответ «это не
    запись». Отличать его от сбоя обязательно — сбой оплачен и о нём говорят вслух, а «не
    запись» обычный ход дела, и строка о ней была бы шумом в каждой третьей реплике.
    """
    try:
        разобранное = json.loads(raw)
    except (json.JSONDecodeError, TypeError, ValueError, RecursionError):
        # `RecursionError` стоит здесь не для полноты списка: профиль распознавателя намеренно
        # без предела на выход, и выродившийся повтор модели — единственный вход, на котором
        # `json.loads` уходит вглубь. Выпущенное отсюда исключение прошло бы сквозь общую
        # развилку ввода и съело набранную человеком строку.
        return None, "ответ распознавателя не разбирается"
    if not isinstance(разобранное, dict):
        return None, "ответ распознавателя не объект"

    слой_как_есть = разобранное.get(КЛЮЧ_СЛОЙ)
    if слой_как_есть is None:
        return None, "в ответе распознавателя нет слоя"
    if not isinstance(слой_как_есть, str):
        # Причину читает человек в ленте. Скажи мы «нет слоя» там, где слой есть, но пришёл
        # объектом, — он искал бы поломку не там, где она случилась.
        return None, "слой в ответе распознавателя не строка"

    слой = " ".join(слой_как_есть.split()).casefold()
    if слой == СЛОЙ_НЕТ:
        return None, ""
    if слой not in СЛОИ:
        return None, f"слой «{слой_как_есть}» распознавателю не положен"

    текст_как_есть = разобранное.get(КЛЮЧ_ТЕКСТ)
    текст = " ".join(текст_как_есть.split()) if isinstance(текст_как_есть, str) else ""
    if not текст:
        return None, "распознаватель не назвал текст записи"

    раздел_как_есть = разобранное.get(КЛЮЧ_РАЗДЕЛ)
    раздел = раздел_как_есть if isinstance(раздел_как_есть, str) else ""

    if слой == СЛОЙ_ЧЕЛОВЕК:
        # Раздел затираем, а не терпим: у записей о человеке разделов не бывает, и названный
        # моделью раздел здесь означает, что она перепутала слой.
        return Адрес(СЛОЙ_ЧЕЛОВЕК, "", текст), ""

    if слой == СЛОЙ_ЗАДАЧА:
        # Разделов у задачи ровно пять, и канон берём у самого хранилища: заведи мы свой
        # список — он разошёлся бы с `workspace.РАЗДЕЛЫ` в первый же день, когда там что-то
        # поменяют.
        if раздел_как_есть is not None and not isinstance(раздел_как_есть, str):
            return None, "раздел в ответе распознавателя не строка"
        имя = workspace.нормализовать_раздел(раздел)
        if имя is None:
            return None, f"раздела «{раздел}» у задачи нет — есть: {', '.join(workspace.РАЗДЕЛЫ)}"
        return Адрес(СЛОЙ_ЗАДАЧА, имя, текст), ""

    # Слой «папка». Перечня разделов у карточки нет — человек называет их сам, — поэтому имя
    # только приводится к сравнимому виду. Пустое имя это отказ: раздел-призрак в карточке
    # хуже, чем неразобранный ответ.
    if раздел_как_есть is not None and not isinstance(раздел_как_есть, str):
        return None, "раздел в ответе распознавателя не строка"
    имя = project_card.привести_имя(раздел)
    if not имя:
        return None, "распознаватель не назвал раздел карточки"
    return Адрес(СЛОЙ_ПАПКА, имя, текст), ""
