"""Помощник по проекту — агент команды `/help <вопрос>`.

Человек спрашивает о проекте, в котором запущен инструмент: где что лежит, как устроена
способность, в какой он ветке, что изменено. Отвечает отдельный агент со своим контекстом:
вопрос и ответ в память разговора не попадают и от активного профиля не зависят. Образец —
Claude Code: там на вопросы о самом инструменте отвечает свой помощник, и основной разговор
получает только его ответ.

Знание помощник берёт из двух мест, и оба — действующие каналы, своих здесь нет:

- база знаний — сервер поиска, названный полем `rag` профиля (README, `docs`, требования);
- состояние рабочей копии — инструменты разрешённых серверов MCP (`git`, `filesystem`).

Слоёв памяти, блока «Инварианты» и судьи у помощника нет: он отвечает о проекте, а не ведёт
задачу человека. Обмен идёт общей очередью главного экрана и показывается тем же `run_turn`,
что и обычный вопрос, — второго показа обмена рядом с ним не заведено.
"""

from __future__ import annotations

from pathlib import Path
from typing import TYPE_CHECKING

from . import profiles
from .agent import Agent
from .profiles import Profile

if TYPE_CHECKING:
    from .state import State

ИМЯ_ПОМОЩНИКА = "помощник"

ИНСТРУКЦИЯ = """\
Ты помощник разработчика по этому проекту. Отвечай на вопрос о проекте: о его структуре,
устройстве, командах, требованиях и о состоянии рабочей копии.

Откуда брать ответ:
- Блок «Найдено в базе знаний» перед вопросом — куски документации проекта. Отвечай по ним.
- Вопрос о ветке, изменениях или истории git — вызови инструмент git. Не догадывайся.
- Вопрос о содержимом каталога или файла — вызови инструмент чтения файлов, если он есть.
- Ты только читаешь. Инструменты, которые что-то меняют (запись файла, фиксация в git),
  не вызывай, даже если они есть.
- Своих знаний о проекте у тебя нет. Чего нет в найденном и в ответах инструментов —
  того ты не знаешь.

Как отвечать:
- Коротко и по делу, на русском языке.
- Имена файлов, команд и полей пиши как есть.
- В конце ответа дай строку «Источники:» и перечисли пути и разделы найденных кусков, по
  которым ответил, в виде «путь › раздел». Ответил по инструменту — назови инструмент.
- Если в найденном нет ответа и инструменты не помогли, ответь одной фразой:
  «В документации проекта этого нет» — и ничего не выдумывай.
"""


def встроенный() -> Profile:
    """Профиль помощника, зашитый в код, — на случай, когда пары файлов нет.

    Поле `rag` называет сервер поиска по имени `rag`: так он записан в `.mcp.json` проекта.
    Истории нет: каждый вопрос заводит нового агента. Рассуждения выключены: ответ собирается
    из найденного, а местная модель с рассуждениями отвечает за минуты вместо секунд (замер
    2026-10-06: 100–428 с против 25–52 с)."""
    return Profile(
        name=ИМЯ_ПОМОЩНИКА,
        description="помощник по проекту: отвечает по документации и состоянию рабочей копии",
        system=ИНСТРУКЦИЯ,
        keep_history=False,
        rag="rag",
        params={"thinking": {"type": "disabled"}},
    )


def профиль() -> tuple[Profile, list[str]]:
    """Профиль помощника и предупреждения загрузки.

    Пара файлов `помощник.json` + `помощник.md` в каталогах поиска профилей перекрывает
    встроенный профиль — обычным правилом перекрытия, без своего порядка. Имя намеренно не
    защищено: человек вправе заменить инструкцию и модельные ручки помощника своими."""
    for каталог in profiles.search_dirs():
        if (каталог / f"{ИМЯ_ПОМОЩНИКА}.json").is_file():
            свой, предупреждения = profiles.load(ИМЯ_ПОМОЩНИКА)
            if свой.source is None:
                # Пара не прочиталась, и `load` отдал `default` — без инструкции и без поиска.
                # Оплаченный вопрос о проекте с таким профилем был бы ответом наугад.
                return встроенный(), [*предупреждения, "помощник отвечает встроенным профилем"]
            return свой, предупреждения
    return встроенный(), []


def агент(state: State) -> tuple[Agent, list[str]]:
    """Новый агент помощника на один вопрос и предупреждения загрузки его профиля.

    Хранилища нет, слоёв памяти, инвариантов и проверки нет. Поиск — тем же соединением
    сеанса, что у собеседника (`state.поиск`), инструменты — разрешённые серверы MCP без
    инструментов автомата задачи: вести задачу человека помощник не вправе."""
    from . import state as state_mod  # здесь, а не наверху: `state` тянет полдерева модулей

    свой, предупреждения = профиль()

    async def набор():
        return await state.mcp.набор(Path.cwd())

    return (
        Agent(
            ИМЯ_ПОМОЩНИКА,
            свой,
            инструменты=набор,
            поиск=state_mod.поставщик_поиска(state, свой),
        ),
        предупреждения,
    )
