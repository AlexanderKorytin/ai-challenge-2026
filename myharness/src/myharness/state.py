"""Состояние сеанса — всё, что инструмент помнит о текущем запуске, без единой строки про окно.

Раньше `State` жил в `cli.py` вместе с раскладкой, клавишами и командами. Из-за этого всякий,
кому нужно было лишь заглянуть в состояние, упирался в `cli`: `archivist`, `compact` и `output`
ввозили `State` под `TYPE_CHECKING`, потому что обычный ввоз замкнул бы круг — сам `cli`
импортирует их всех. Отсюда `State` и уехал: этот модуль лёгкий и не знает ни `prompt_toolkit`,
ни команд, ни экранов сверх `screens`.

Лёгкость здесь — свойство, за которым надо следить, а не подарок от переезда. Стоило состоянию
ввезти архивариуса и сжимателя ради двух строк с их именами — и вместе с ними приезжали `ui` и
`output`, то есть весь терминал: сто с лишним частей `prompt_toolkit` ради двух слов. Поэтому
имена служб лежат в лёгком `background`, а сами службы отсюда не ввозятся вовсе. Заодно это
развязало и обратную сторону: `archivist`, `compact` и `output` ввозят состояние обычным
образом — круга больше нет, и прятать его под `TYPE_CHECKING` не приходится.

Под `TYPE_CHECKING` остались только те четверо, кто тянет за собой окно: приложение
`prompt_toolkit`, панель выбора, подпись ленты и исполнитель очереди панели.

Утверждение «состояние не тянет терминал» проверяется в отдельном процессе
(`tests/check_units.py`, раздел про изоляцию): вернуть сюда тяжёлый ввоз, не заметив, нельзя.
"""

