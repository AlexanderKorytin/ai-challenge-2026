def profile_for_strategy(source: Profile, strategy: str) -> Profile:
    """Независимый рабочий профиль режима из одной исходной пары файлов.

    Изменяемые поля копируются: `/strategy window` и очереди заготовок одного экрана не
    вправе менять соседний режим или главный разговор.
    """

    return replace(
        source,
        context_strategy=strategy,
        prefills=list(source.prefills),
        branch_prefills={
            name: list(prefills) for name, prefills in source.branch_prefills.items()
        },
        agents=list(source.agents),
        screens=list(source.screens),
        methods=list(source.methods),
        result=list(source.result),
        overrides=list(source.overrides),
        vars=dict(source.vars),
        params=dict(source.params),
    )


@dataclass


class Request:
    """Единица очереди с точным местом назначения.

    `lead` задаётся только для разового запуска группы через `/team`. Обычный разговор,
    группа и набор способов остаются в общей очереди главной панели; интерактивные
    неглавные панели передают такие единицы собственному `PaneWorker`.
    """

    content: str
    pane: screens_mod.Pane
    lead: Profile | None = None


@dataclass


class State:
    config: Config
    client: DeepSeekClient | None
    model: str
    profile: Profile
    app: Application | None = None
    screens: list[screens_mod.Screen] = field(default_factory=lambda: [screens_mod.main_screen()])
    active: int = 0
    queue: asyncio.Queue[Request] = field(default_factory=asyncio.Queue)
    current_task: asyncio.Task | None = None
    # Главный разговор, группа и набор способов сохраняют прежние общие поля выше.
    # Неглавная интерактивная панель получает собственный последовательный исполнитель:
    # ключом служит тождество панели, а сам объект повторно проверяется при поиске.
    pane_workers: dict[int, PaneWorker] = field(default_factory=dict)
    # Обработчик Enter запускает короткую асинхронную передачу запроса. Эти задачи тоже
    # принадлежат приложению: при выходе их отменяют и дожидаются вместе с исполнителями,
    # иначе Enter непосредственно перед выходом мог пережить закрытие клиента.
    submission_tasks: set[asyncio.Task[None]] = field(default_factory=set)
    # Пока смена профиля дожидается старых очередей, новые команды и вопросы не должны
    # попасть ни в старое дерево экранов, ни в ещё не установленный новый профиль.
    switching_profile: bool = False
    busy: bool = False
    awaiting_key: bool = False
    awaiting_custom: str | None = None  # имя параметра, для которого ждём своё значение
    picker: picker_mod.Picker | None = None
    profile_dirty: bool = False  # параметры меняли, но профиль не сохранён
    # Режим, записанный в исходном профиле, открывается после восстановления standard.
    # Сам главный собеседник при этом остаётся прежним standard и прежним путём на диске.
    initial_strategy: str = field(init=False, default=context_strategy.CONTEXT_STANDARD)
    known_models: list[str] = field(default_factory=lambda: list(api.FALLBACK_MODELS))
    journal_warned: bool = False
    # Расход агентов, которых в дереве экранов больше нет: собеседника, смещённого сменой
    # профиля, и экспертов закрытой группы. Сеанс — это запуск процесса, а не жизнь одного
    # собеседника: деньги за прежний разговор списаны и никуда не делись оттого, что человек
    # сменил профиль. Без копилки итог падал бы посреди работы почти до нуля — то есть врал.
    retired_usage: dict[str, int] = field(default_factory=dict)
    # Число завершённых обменов выбывших агентов нужно `/tokens` по той же причине, что и
    # расход: смена профиля или разделение ветви не отменяют уже сделанной работы.
    retired_runs: int = 0
    # Неизвестный серверный расход нельзя превращать в ноль. Общий признак переживает
    # удаление панели, множество тождеств сохраняет ту же правду для живого активного Agent.
    session_usage_known: bool = True
    unknown_usage_agent_ids: set[int] = field(default_factory=set)
    # Деньги за сеанс копим по ходу, а не считаем задним числом по накопленным токенам:
    # тариф зависит от модели и от часа, а модель меняется на лету. Пересчёт по текущей
    # модели врал втрое — расход, сделанный на `pro`, дешевел от одной лишь команды /model.
    session_cost: float = 0.0
    # Был ли хоть один обмен моделью с известным тарифом. Нужен, чтобы отличить «бесплатно»
    # от «тариф неизвестен»: ноль на экране читается как «денег не потрачено».
    session_cost_known: bool = True
    store_warned: bool = False  # о сбое записи разговора говорим один раз за сеанс
    input_buffer: Any = None  # общее отображение черновика активной интерактивной панели
    # Мышь включена всегда: своего выделения harness не ведёт и отслеживание перетаскивания не
    # просит (см. click_only_mouse). Текст при этом выделяется с клавишей обхода перехвата,
    # принятой в терминале, — она свойство терминала, а не наших настроек. Команда /mouse
    # оставлена аварийным выходом для терминала, у которого такой клавиши нет вовсе.
    mouse_enabled: bool = True
    # Куда пишется главный разговор между запусками. Заводится в `conversation`, а НЕ здесь:
    # конструктор состояния зовут проверки напрямую, и любое состояние начало бы читать и
    # писать в каталог состояния пользователя.
    store: memory.SessionStore | None = None
    # Сколько пар легло в главный разговор с прошлого захода архивариуса.
    since_archive: int = 0
    # Слаг задачи, над которой человек работает сейчас, — ИМЯ, а не снимок содержимого.
    # Снимок был бы вторым источником правды рядом с файлом: человек правит файл руками, и
    # команда, пишущая из устаревшего снимка, стёрла бы написанное им молча. Какая задача
    # активна — выбор человека и живёт здесь; что в ней написано — свойство файла и читается
    # с диска, ровно как карточка проекта.
    слаг_задачи: str | None = None
    # Идущее интервью о проекте: пока оно здесь, строка человека — это ответ на заданный
    # вопрос, а не вопрос модели. `Any`, а не тип из `interview`: подсказка типа не стоит
    # ввоза модуля, который тянет за собой агента и клиент.
    интервью: Any = None
    # Идёт ли сейчас запрос распознавателя естественной записи. Вторая реплика с зачином,
    # пришедшая в это время, второго запроса не заводит: два запроса подряд стоят вдвое, а
    # человек, набравший вторую строку, ещё не видел судьбы первой, — и она уходит обычным
    # вопросом. Отдельным полем, а не через `background.Служба`: распознавание ожидается прямо
    # в развилке ввода и своей задачей не заводится — ждать его некому, кроме самой развилки.
    идёт_распознавание: bool = False
    # Фоновая служба архивариуса: идущий заход, счёт отказов и признак «о сбое уже сказали».
    # Одним полем, а не россыпью: скелет у фоновых служб общий и живёт в `background`, и
    # разложить его части по отдельным полям состояния значило бы собирать их заново в каждой
    # службе — со своими именами и своими расхождениями.
    # Имя берём готовое из `background`, а не пишем строкой второй раз: под ним служба известна
    # журналу прогонов и ленте, и два написания одного имени однажды разъехались бы. Из самого
    # архивариуса его брать нельзя: ввоз ради имени притащил бы сюда весь терминал.
    архивариус: background.Служба = field(default_factory=lambda: background.Служба(background.ИМЯ_АРХИВАРИУСА))
    # Фоновая служба сжимателя — та же по устройству, что у архивариуса, и заведена тем же
    # скелетом, и имя взято оттуда же и по той же причине, что у архивариуса.
    сжиматель: background.Служба = field(default_factory=lambda: background.Служба(background.ИМЯ_СЖИМАТЕЛЯ))
    # Счёт занятости контекста для полоски над строкой ввода. Заводится в `layout` вместе с
    # самой раскладкой, а не здесь: его незачем иметь состоянию, собранному проверками без окна.
    # Держим его на состоянии, потому что сбрасывать запомненную постоянную часть приходится
    # оттуда, где меняются глобальные факты, — они живут на диске, отпечаток памяти их не
    # видит, а сторожить их опросом значило бы ходить на диск на каждую букву.
    занятость: Any = None
    # Сколько пар файла сессии осталось за спиной К НАЧАЛУ работы с этим файлом: пары до
    # границы прежней выжимки и пары, не поместившиеся в порог при подъёме. Дальше граница
    # разговора считается от него плюс пройденное агентом (`compact.граница_разговора`).
    #
    # Число живёт здесь, а не в агенте: оно про ФАЙЛ сессии, а файл принадлежит состоянию —
    # его меняют `/clear` и смена профиля. Агент про файл не знает и знать не должен.
    база_границы: int = 0

    @property
    def main(self) -> screens_mod.Screen:
        """Экран пользователя: сюда идут команды, вопросы и сводка группы."""
        return self.screens[0]

    @property
    def screen(self) -> screens_mod.Screen:
        """Показываемый сейчас экран — он же и прокручивается."""
        return self.screens[self.active if 0 <= self.active < len(self.screens) else 0]

    @property
    def focus(self) -> screens_mod.Screen:
        """Куда писать вывод команд: на рабочем экране — в него, на экране агента (он только
        для чтения) — в главный, иначе сообщение осталось бы незамеченным."""
        current = self.screen
        return current if current.interactive else self.main

    @property
    def log(self) -> Fragments:
        return self.main.first.log

    @property
    def main_agent(self) -> Agent:
        """Собеседник главного экрана — тот, с кем разговаривает пользователь."""
        return self.main.first.agent

    def agents(self) -> list[Agent]:
        """Все поднятые собеседники сеанса, каждый по одному разу.

        Агентов ищем там, где они живут, — в панелях экранов: собственного списка агентов
        состояние не ведёт, и второй список разошёлся бы с панелями на первом же экране,
        заведённом мимо него. Собеседник главного экрана попадает сюда тем же обходом: его
        панель — первая панель первого экрана.

        Одного и того же агента отдаём один раз: панель может показывать чужого собеседника,
        и сложенный дважды расход выглядел бы ростом вдвое там, где ничего не росло.
        """
        агенты: list[Agent] = []
        for screen in self.screens:
            for pane in screen.panes:
                if pane.agent is not None and not any(pane.agent is уже for уже in агенты):
                    агенты.append(pane.agent)
        return агенты

    def retire(self, агенты: list[Agent]) -> None:
        """Проводить агентов: их расход уходит в копилку выбывших.

        Звать ТОЛЬКО там, где агент действительно покидает дерево экранов, и до того, как
        ссылка на него потеряна. Проводи живого — и его расход посчитался бы дважды: раз в
        копилке, раз при обходе панелей."""
        for агент in агенты:
            self.retired_usage = tokens.add_usage(
                self.retired_usage, агент.session_usage
            )
            self.retired_runs += агент.runs
            self.unknown_usage_agent_ids.discard(id(агент))

    def session_usage_total(self) -> dict[str, int]:
        """Расход за сеанс по ВСЕМ поднятым агентам, одной суммой.

        Считать по одному главному агенту нельзя: группа экспертов, цепочка способов и
        рабочие экраны ходят к модели своими агентами, и их обмены оплачены из того же
        кошелька. Итог, показывающий один главный разговор, занижал бы расход ровно в тот
        день, когда он вырос, — когда человек запустил четыре способа сразу.
        """
        живые = [agent.session_usage for agent in self.agents()]
        return tokens.total_usage([self.retired_usage, *живые])

    def __post_init__(self) -> None:
        # `context_strategy` в файле выбирает экран при запуске, а не превращает главный
        # разговор в другой режим. Главный экран всегда standard и сохраняет прежний путь.
        self.initial_strategy = self.profile.context_strategy
        if self.initial_strategy != context_strategy.CONTEXT_STANDARD:
            self.profile = profile_for_strategy(
                self.profile, context_strategy.CONTEXT_STANDARD
            )
        # Панель главного экрана заводит `screens.main_screen()`, профиля у неё нет, а
        # собеседник нужен: главный разговор ведёт он. Заводим здесь, а не в `_main`, чтобы
        # у любого состояния — в том числе собранного проверками — главный агент был на месте.
        self.main.first.agent = главный_агент(self, self.profile)


def user_facts() -> list[str]:
    """Глобальные факты о человеке — для системной инструкции ГЛАВНОГО разговора.

    Отдаётся вызываемым, а не готовым списком: факты меняются по ходу сеанса — их кладёт
    `/remember` и выписывает архивариус, — и список, снятый при создании агента, отстал бы
    от них к первому же запросу.

    Получают их только собеседник главного экрана. Исполнителям группы, шагам цепочки и
    пакетному наряду нужна их роль, а не любимый цвет пользователя: наряд ещё и обязан быть
    воспроизводимым, а факты о человеке меняются между прогонами.

    Предупреждения о попорченных файлах здесь отбрасываются намеренно: сборка запроса — не
    то место, где о них говорить (она молчалива и идёт на каждый вопрос), их показывает
    `/memory`, куда человек за памятью и приходит.

    Записи-инварианты сюда не входят: они уходят блоком инвариантов с номерами `Г…`
    (`invariants_block`), и пометка перекрытия профиля на них не действует."""
    записи, _ = memory.load_records()
    return [текст for текст, инвариант in записи if not инвариант]


def project_block() -> str:
    """Блок карточки проекта для системной инструкции ГЛАВНОГО разговора.

    Карточка читается с диска на каждую сборку запроса — ровно как записи о человеке и по той
    же причине: человек правит этот файл руками, и слепок, снятый при запуске, отстал бы от
    него к первому же вопросу.

    Карточка берётся по ТЕКУЩЕМУ рабочему каталогу. Это и есть договор слоя: знание о папке
    поднимается в той папке, о которой оно, и ни в какой другой.

    Предупреждения о попорченном файле здесь отбрасываются намеренно, как и у записей: сборка
    запроса молчалива и идёт на каждый вопрос, а жалобы человек получает от `/project`, куда
    он за карточкой и приходит.
    """
    карточка, жалобы = project_card.load(Path.cwd())
    if карточка is None and жалобы:
        # Файл карточки лежит и не разбирается — об этом надо СКАЗАТЬ, а не вернуть пустой
        # блок. Довод тот же, что у рабочего состояния: молча пропавший слой отлаживается как
        # «модель отвечает не на то», и час уходит на поиск поломки, которой нет. Исключение
        # здесь — законный путь: `build_messages` его ловит и кладёт жалобу в `store_error`.
        raise RuntimeError("; ".join(жалобы))
    return project_card.блок(карточка) if карточка is not None else ""


def work_block(state: State) -> str:
    """Эфемерный хвост запроса: состояние текущей задачи, прочитанное с диска.

    Из состояния сеанса берётся только ИМЯ задачи, а тело читается файлом на каждую сборку —
    как и карточка проекта, и по той же причине: человек правит этот файл руками между двумя
    вопросами, и снимок, снятый при выборе задачи, отстал бы от него к первому же запросу.

    Спора с выбором человека тут нет: какая задача активна, решает он, а что в ней написано
    — решает файл.

    Карта стадий идёт в блок, только если задача заведена в профиле главного собеседника
    (`state.profile` — его профиль: его же получает `главный_агент`). Задаче чужого профиля
    карта этого профиля не указ — блок остаётся прежним.
    """
    if state.слаг_задачи is None:
        return ""
    задача, жалобы = workspace.load_task(Path.cwd(), state.слаг_задачи)
    if задача is None and жалобы:
        # Файл задачи испорчен — и об этом надо СКАЗАТЬ, а не вернуть пустой хвост. Молча
        # пропавшее состояние задачи отлаживается как «модель отвечает не на то», и час
        # уходит на поиск поломки, которой нет. Исключение здесь — законный путь: его ловит
        # `_с_хвостом` и кладёт жалобу в `store_error`, ради чего тот канал и заведён.
        raise RuntimeError("; ".join(жалобы))
    if задача is None:
        return ""
    карта = state.profile.стадии if задача.профиль == state.profile.name else None
    return workspace.блок(задача, карта)


def invariants_block(state: State, profile: Profile | None = None) -> str:
    """Блок инвариантов для системной части запроса ГЛАВНОГО разговора.

    Читается с диска на каждую сборку — все четыре слоя правятся по ходу сеанса. Карта стадий
    берётся у профиля главного собеседника: `главный_агент` передаёт ТОТ ЖЕ профиль, что и
    `machine.набор`, — строки `А` обязаны появляться ровно при тех условиях, при которых
    выдаются инструменты. Без довода — `state.profile`. Задача — выбранная человеком.

    Блок собирается из того, что прочитано, и уходит в запрос ВСЕГДА. Жалобы слоёв здесь не
    поднимаются намеренно: подними их исключением — и один испорченный файл мягкой записи о
    человеке выбрасывал бы из каждого запроса весь блок, вместе со строками `П`, `З` и `А`,
    которые прочитаны исправно. Жалобы при этом не теряются: испорченные записи показывают
    `/memory` и `/invariants`, а нечитаемые карточку и задачу в том же запросе уже поднимают
    `project_block` и `work_block` — второй раз та же жалоба была бы шумом.
    """
    список, _ = invariants.собрать(
        Path.cwd(), state.слаг_задачи, profile if profile is not None else state.profile
    )
    return invariants.блок(список)


def главный_агент(state: State, profile: Profile) -> Agent:
    """Собеседник главного экрана со всеми тремя слоями памяти.

    Одно место сборки на весь инструмент: главного агента заводят дважды — при запуске и при
    смене профиля, — и набор слоёв у них обязан быть один. Разведи их, и смена профиля тихо
    отнимала бы у собеседника карточку проекта, а искали бы поломку в карточке.

    Слои передаются ВЫЗЫВАЕМЫМИ, а не готовым текстом: и записи, и карточка, и задача
    меняются по ходу сеанса, а снятый при создании агента текст отстал бы от них к первому же
    запросу.

    Получает их только собеседник главного экрана. Исполнителям группы, шагам цепочки и
    пакетному наряду нужна их роль, а не задача пользователя: наряд ещё и обязан быть
    воспроизводимым, а слои памяти меняются между прогонами.

    Инструменты автомата задачи (`machine.набор`) — тоже только ему и тоже вызываемым: пауза,
    смена задачи и правка файла руками решают, будут ли они в следующем обмене.
    """
    return Agent(
        screens_mod.MAIN_KEY,
        profile,
        facts=user_facts,
        project=project_block,
        work=lambda: work_block(state),
        инварианты=lambda: invariants_block(state, profile),
        инструменты=lambda: machine.набор(state, profile),
    )
