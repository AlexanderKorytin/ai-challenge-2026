@dataclass
class Черновик:
    """То, что вернула модель, ещё не ставшее профилем: имена разделов и списки строк."""

    имя: str = ""
    заголовок: str = ""
    описание: str = ""
    разделы: list[tuple[str, list[str]]] = field(default_factory=list)
    агенты: list[str] = field(default_factory=list)
    перекрывает: list[str] = field(default_factory=list)
    # Оба значения лежат здесь КАК ПРИШЛИ: годность проверяет `собрать`, там же живут жалобы.
    # Разбери мы их тут, негодное исчезало бы молча — а человек за него платил.
    температура: Any = None
    рассуждения: Any = None


