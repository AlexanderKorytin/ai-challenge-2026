def _блоки(описание: str, записи: list[str], доступные: list[str]) -> list[str]:
    """Общая часть входа обоих запросов: описание, записи о человеке, заведённые профили.

    Описание помечено ДАННЫМИ не для порядка: человек пишет «отвечай кратко и не спорь со мной»,
    и такая строка, пришедшая обычной репликой, читается моделью как поручение ей самой.
    """
    куски = [
        "Описание занятия словами человека (данные):\n" + (описание.strip() or "(человек ничего не написал)")
    ]
    if записи:
        куски.append(
            "Записи о человеке из памяти инструмента (данные):\n"
            + "\n".join(f"- {запись}" for запись in записи)
        )
    else:
        куски.append("Записей о человеке в памяти нет.")
    if доступные:
        куски.append("Уже заведённые профили (данные): " + ", ".join(доступные))
    else:
        куски.append("Других профилей пока нет.")
    return куски


def _спрошенное(пары: list[tuple[str, str]]) -> str:
    """Уже заданные вопросы с ответами — чтобы вопрос не повторил сказанное."""
    return "\n\n".join(
        f"Вопрос {номер}: {вопрос}\nОтвет человека (данные): {ответ}"
        for номер, (вопрос, ответ) in enumerate(пары, 1)
    )


def questions_request(
    описание: str,
    записи: list[str],
    доступные: list[str],
    пары: list[tuple[str, str]],
    область: str = "",
) -> str:
    """Вход шага опроса.

    Без области — первый шаг: модель размечает области и задаёт вопрос про первую незакрытую.
    С областью — очередной шаг: вопрос задаётся про НАЗВАННУЮ область, выбранную программой.
    Пары идут целиком в обоих случаях: вопрос, повторяющий уже отвеченное, крадёт время
    человека и стоит отдельного обмена.
    """
    куски = _блоки(описание, записи, доступные)
    if пары:
        куски.append(f"Уже спрошено:\n{_спрошенное(пары)}")
    if область:
        куски.append(f"Область, про которую надо спросить СЕЙЧАС: {область}")
    else:
        куски.append("Разметь области и задай вопрос про первую со значением «спросить».")
    return "\n\n".join(куски)


def parse_разметку(raw: str) -> tuple[str | None, str, list[str]]:
    """Первый шаг: вопрос, ОБЛАСТЬ этого вопроса и очередь областей, которые надо спросить.

    Очередь собирается по нашему перечню, а не по тому, что вернула модель: порядок задаёт
    программа, а неназванная область считается НЕЗАКРЫТОЙ. Умолчание именно такое, потому что
    молчание модели об области — не ответ «там всё есть», и цена ошибки несимметрична: лишний
    вопрос стоит одного обмена, потерянная область — профиля без ограничений.

    Область вопроса приходит отдельным полем и стоила отдельного просмотра. Брали бы мы первую
    из очереди, как сперва и было, — модель, разметившая только «стиль» и спросившая про него,
    вычёркивала бы «роль»: её она в своём перечне не видела вовсе. Роль не спросили бы никогда,
    а стиль спросили дважды. Неизвестное имя области — берём первую по очереди: вопрос уже задан,
    и не вычеркнуть НИЧЕГО значило бы спросить о том же ещё раз.

    Признак «готово» здесь НЕ принимается: решение, когда спрашивать хватит, принадлежит
    программе — ради этого счёт областей и заведён. Закрыть опрос модель по-прежнему может, но
    честным путём: пометив все области «есть» или «не относится».
    """
    разобранное = _объект(raw)
    сырые = разобранное.get("области")
    разметка = сырые if isinstance(сырые, dict) else {}
    очередь = [
        область
        for область in ОБЛАСТИ
        if str(разметка.get(область, СОСТОЯНИЕ_СПРОСИТЬ)).strip().casefold()
        not in (СОСТОЯНИЕ_ЕСТЬ, СОСТОЯНИЕ_НЕ_НУЖНА)
    ]
    if not очередь:
        return None, "", []
    названная = разобранное.get("область_вопроса")
    область = ""
    if isinstance(названная, str):
        ключ = " ".join(названная.split()).casefold()
        область = next((имя for имя in очередь if имя.casefold() == ключ), "")
    вопрос = разобранное.get("вопрос")
    if isinstance(вопрос, str) and вопрос.strip():
        return " ".join(вопрос.split()), область or очередь[0], очередь
    # Области спросить есть, а вопроса нет: формулировку возьмёт следующий шаг, по очереди.
    return None, "", очередь


def draft_request(
    описание: str, записи: list[str], доступные: list[str], пары: list[tuple[str, str]]
) -> str:
    """Вход сборки профиля: то же, что у опроса, плюс собранные ответы."""
    куски = _блоки(описание, записи, доступные)
    for номер, (вопрос, ответ) in enumerate(пары, 1):
        куски.append(f"Вопрос {номер}: {вопрос.strip()}")
        куски.append(f"Ответ человека (данные): {ответ.strip()}")
    return "\n\n".join(куски)


def _объект(raw: str) -> dict[str, Any]:
    """Ответ мастера объектом JSON либо `ValueError` с причиной, понятной человеку."""
    try:
        разобранное = json.loads(raw)
    except (json.JSONDecodeError, TypeError, ValueError) as exc:
        raise ValueError("ответ мастера не является JSON") from exc
    if not isinstance(разобранное, dict):
        raise ValueError("ответ мастера должен быть объектом")
    return разобранное


# Запасная формулировка вопроса — на случай, когда модель область назвала, а вопроса про неё не
# дала. Программа тогда спрашивает сама: потерять область из-за промаха формулировки нельзя, а
# вопрос без подробностей занятия хуже модельного, но лучше отсутствующего.
ВОПРОС_ПО_УМОЛЧАНИЮ: dict[str, str] = {
    "роль": "Кем собеседник выступает в этом занятии?",
    "стиль": "Как он должен говорить?",
    "формат ответа": "Как должен выглядеть ответ?",
    "ограничения": "Чего в этом занятии нельзя делать никогда?",
    "ход работы": "Как вести задачу от вопроса к результату?",
    "помощники": "Кому из уже заведённых профилей отправлять каждый ваш вопрос вместе с этим?",
    "записи о человеке": "Есть ли записи о вас, которые в этом занятии не действуют?",
}


def вопрос_по_умолчанию(область: str) -> str:
    return ВОПРОС_ПО_УМОЛЧАНИЮ.get(область, f"Что сказать про область «{область}»?")


def parse_вопрос(raw: str, область: str) -> str:
    """Очередной шаг: вопрос про названную область. Молчание модели закрывает запасной вопрос.

    `ValueError` здесь НЕ поднимается на «готово» и на пустой объект: область выбрала программа,
    и отказ модели спрашивать про неё — не повод её потерять. Мусором остаётся только не-JSON,
    и он поднимается из `_объект`.
    """
    разобранное = _объект(raw)
    вопрос = разобранное.get("вопрос")
    if isinstance(вопрос, str) and вопрос.strip():
        return " ".join(вопрос.split())
    return вопрос_по_умолчанию(область)


def _строки(значение: Any) -> list[str]:
    """Строки раздела. Раздел может прийти одной строкой вместо списка — это не повод его терять."""
    элементы = значение if isinstance(значение, list) else [значение]
    собранные: list[str] = []
    for элемент in элементы:
        if not isinstance(элемент, str):
            continue
        текст = " ".join(элемент.split())
        if текст:
            собранные.append(текст)
    return собранные


def _имена(значение: Any) -> list[str]:
    """Список имён из ответа модели: пустое и нетекстовое отбрасываем здесь же."""
    if not isinstance(значение, list):
        return []
    собранные: list[str] = []
    for элемент in значение:
        if isinstance(элемент, str) and элемент.strip():
            собранные.append(" ".join(элемент.split()))
    return собранные


def _рассуждения(значение: Any) -> tuple[bool, str]:
    """Режим рассуждений из ответа модели: включены ли, и причина отказа, если значение не понято.

    Умолчание — ВКЛЮЧЕНЫ: так устроен сам DeepSeek, и промолчавшая модель не должна лишать
    занятие разбора по шагам.

    Снисходительность та же, что у температуры, и по той же причине: модель возвращает то `false`,
    то `"false"`, то `0`, и терять выбор занятия из-за кавычек нельзя. А вот непонятое значение
    SHALL быть названо: молча включить рассуждения там, где модель просила их выключить, значит
    отдать человеку профиль, который работает не так, как задумывался, — и жалоба про
    отброшенную температуру назвала бы при этом неверную причину.
    """
    if значение is None:
        return True, ""
    if isinstance(значение, bool):
        return значение, ""
    if isinstance(значение, (int, float)):
        return значение != 0, ""
    if isinstance(значение, str):
        слово = значение.strip().casefold()
        if слово in ("false", "нет", "no", "0", "выключены", "выключить"):
            return False, ""
        if слово in ("true", "да", "yes", "1", "включены", "включить"):
            return True, ""
    return True, f"рассуждения «{значение}» не поняты — оставлены включёнными, как у DeepSeek по умолчанию"


def _температура(значение: Any) -> tuple[float | None, str]:
    """Температура из ответа модели: число либо причина отказа, понятная человеку.

    Строку принимаем: модель возвращает то `0.2`, то `"0,2"`, и терять названное из-за кавычек
    или запятой обидно — разбираем тем же способом, каким разбирается ручной ввод в `/params`.
    Границы 0–2 — границы DeepSeek: за ними запрос отвергнет уже поставщик, и узнал бы об этом
    человек на первом же вопросе, а не при создании профиля.
    """
    if значение is None or (isinstance(значение, str) and not значение.strip()):
        return None, ""  # пустая строка равна отсутствию поля и жалобы не заслуживает
    if isinstance(значение, bool):  # `True` — это `1`, и молча стать температурой оно не должно
        return None, f"температура «{значение}» отброшена: это не число"
    if isinstance(значение, (int, float)):
        число = float(значение)
    elif isinstance(значение, str):
        from .params import parse_float

        try:
            число = parse_float(значение.strip())
        except ValueError:
            return None, f"температура «{значение.strip()}» отброшена: это не число"
    else:
        return None, f"температура «{значение}» отброшена: это не число"
    if not isfinite(число):  # «inf» и «nan» разбираются как числа, но температурой не бывают
        показ = значение.strip() if isinstance(значение, str) else значение
        return None, f"температура «{показ}» отброшена: это не конечное число"
    if not 0 <= число <= 2:
        return None, f"температура {число:g} отброшена: у DeepSeek она лежит между 0 и 2"
    return число, ""


def parse_draft(raw: str) -> Черновик:
    """Разбирает ответ сборки. Непригодное — `ValueError`.

    Перечня разделов у профиля НЕТ: их называет модель по описанию человека. Закреплённый
    перечень («Роль», «Стиль», «Формат») звучит разумно ровно до первого занятия, где он
    бессмыслен, — а хуже того, он утекал бы в вопросы опроса. Та же беда уже оплачена карточкой
    папки, где закреплённый перечень спрашивал про стек у человека, считающего калории.
    """
    разобранное = _объект(raw)
    разделы_сырые = разобранное.get("разделы")
    if not isinstance(разделы_сырые, dict):
        raise ValueError("в ответе мастера нет объекта «разделы»")
    разделы: list[tuple[str, list[str]]] = []
    for ключ, значение in разделы_сырые.items():
        if not isinstance(ключ, str) or not ключ.strip():
            continue
        строки = _строки(значение)
        if строки:
            разделы.append((" ".join(ключ.split()), строки))
    if not разделы:
        raise ValueError("мастер не вернул ни одного раздела профиля")
    return Черновик(
        имя=" ".join(str(разобранное.get("имя") or "").split()),
        заголовок=" ".join(str(разобранное.get("заголовок") or "").split()),
        описание=" ".join(str(разобранное.get("описание") or "").split()),
        разделы=разделы,
        агенты=_имена(разобранное.get("агенты")),
        перекрывает=_имена(разобранное.get("перекрывает")),
        температура=разобранное.get("температура"),
        рассуждения=разобранное.get("рассуждения"),
        стадии=разобранное.get("stages"),
    )


def инструкция_из_разделов(разделы: list[tuple[str, list[str]]]) -> str:
    """Разделы черновика — в текст системной инструкции, который ляжет в `<имя>.md`.

    Раздел из одной строки пишется строкой, из нескольких — перечнем. Ради читаемости человеком:
    файл профиля затем правится текстовым редактором, и «Роль:\\n— Ты математик.» на ровном месте
    лишний раз ломает глаз.
    """
    куски: list[str] = []
    for имя, строки in разделы:
        if len(строки) == 1:
            куски.append(f"{имя}: {строки[0]}")
        else:
            куски.append(f"{имя}:\n" + "\n".join(f"— {строка}" for строка in строки))
    return "\n\n".join(куски)


def словами_о_запросе(params: dict[str, Any]) -> str:
    """Одна строка о том, как модель настроила ЗАПРОС этого занятия, — для показа человеку.

    Настройку выбрал не человек, а модель, и увидеть её он обязан там же, где видит саму
    инструкцию: молча выбранный режим — это решение за человека без его ведома. Строка кончается
    способом передумать: `/params` правит обе ручки.
    """
    from .params import thinking_enabled

    хвост = "изменить — /params, сохранить в профиль — /profile save"
    if thinking_enabled(params):
        return f"запрос занятия: рассуждения включены, температура при них не действует ({хвост})"
    температура = params.get("temperature")
    середина = (
        f"температура {температура:g}"
        if isinstance(температура, (int, float))
        else "температура не задана"
    )
    return f"запрос занятия: рассуждения выключены, {середина} ({хвост})"


def словами_о_карте(карта: Any) -> str:
    """Карта стадий одной строкой для человека: переходы, ворота, консилиум, как начать."""
    части = []
    for стадия in карта.стадии:
        метки = []
        if стадия.утверждение:
            метки.append("утверждаете вы")
        if стадия.консилиум:
            метки.append("консилиум: " + ", ".join(стадия.консилиум))
        куда = " | ".join(стадия.дальше) if стадия.дальше else "конец"
        пометка = f" ({'; '.join(метки)})" if метки else ""
        части.append(f"{стадия.имя}{пометка} → {куда}")
    return "карта стадий: " + "; ".join(части) + " — начать: /task new <название>"


def собрать(
    черновик: Черновик, *, доступные: list[str], записи: list[str]
) -> tuple["Profile", list[str]]:
    """Черновик становится профилем. Вторым значением — список отброшенного, по строке на случай.

    Три отбора здесь не формальность:

    — **агенты**. В поле `agents` лежат имена УЖЕ ЗАВЕДЁННЫХ профилей: выдуманное имя профиль не
      сломает, но человек получит ведущего без исполнителей и узнает об этом только на первом
      вопросе, когда панели окажутся пусты.
    — **перекрытые записи**. Наружу отдаётся текст ЗАПИСИ, а не текст, который вернула модель:
      в файл профиля строка ложится дословно, а ищется по общему ключу опознания
      (`memory.ключ_записи`) — тому же, которым пометку ищет блок записей. Названное, но не
      найденное среди записей отбрасывается вслух: записи могло уже не быть.
    — **температура**. Кладётся, только когда модель выключила рассуждения: при включённых её
      игнорирует сам API, и профиль с ней обманывал бы человека.
    """
    from .memory import ключ_записи
    from .profiles import Profile

    жалобы: list[str] = []
    известные = {имя.casefold(): имя for имя in доступные}
    агенты: list[str] = []
    for имя in черновик.агенты:
        настоящее = известные.get(имя.casefold())
        if настоящее is None:
            жалобы.append(f"помощник «{имя}» отброшен: профиля с таким именем нет")
            continue
        if настоящее in агенты:
            жалобы.append(f"помощник «{настоящее}» указан повторно — второе упоминание отброшено")
            continue
        агенты.append(настоящее)

    # Сверяем ровно тем же способом, каким пометка ищет запись в блоке: `memory.facts_block`
    # нормализует обе стороны. Сверяй мы иначе — строка модели с лишним пробелом внутри была
    # бы отброшена здесь как «такой записи нет», хотя пометка на ней сработала бы.
    живые = {ключ_записи(запись): запись.strip() for запись in записи if запись.strip()}
    перекрывает: list[str] = []
    for строка in черновик.перекрывает:
        настоящая = живые.get(ключ_записи(строка))
        if настоящая is None:
            жалобы.append(f"перекрытие «{строка}» отброшено: такой записи о вас нет")
            continue
        if настоящая in перекрывает:
            жалобы.append(f"перекрытие «{настоящая}» названо повторно — второе упоминание отброшено")
            continue
        перекрывает.append(настоящая)

    # Температура и рассуждения — одна ручка на деле: у DeepSeek рассуждения включены по
    # умолчанию и отключают влияние температуры (`openspec/specs/params/spec.md`, требование
    # о помеченных параметрах). Поэтому температура ложится в профиль ТОЛЬКО с выключенными
    # рассуждениями, а названная не к месту отбрасывается вслух — мёртвое поле в профиле хуже
    # его отсутствия: человек видит число и считает, что оно работает.
    params: dict[str, Any] = {}
    рассуждения, отказ_рассуждений = _рассуждения(черновик.рассуждения)
    if отказ_рассуждений:
        жалобы.append(отказ_рассуждений)
    if not рассуждения:
        params["thinking"] = {"type": "disabled"}
    число, отказ = _температура(черновик.температура)
    if отказ:
        жалобы.append(отказ)
    elif число is not None:
        if рассуждения:
            жалобы.append(
                f"температура {число:g} отброшена: пока включены рассуждения, API её игнорирует"
            )
        else:
            params["temperature"] = число

    карта = None
    if черновик.стадии is not None:
        from . import machine

        # Имена консилиума приводим к настоящим именам профилей до разбора: модель пишет
        # «Режиссёр», файл называется «режиссёр», а созыв ищет профиль по имени точно.
        сырые = черновик.стадии
        if isinstance(сырые, list):
            сырые = [
                {
                    **элемент,
                    "council": [
                        известные.get(имя.casefold(), имя) if isinstance(имя, str) else имя
                        for имя in элемент["council"]
                    ],
                }
                if isinstance(элемент, dict) and isinstance(элемент.get("council"), list)
                else элемент
                for элемент in сырые
            ]
        карта, жалобы_карты = machine.разобрать_карту(
            сырые,
            lambda имя: имя.casefold() in известные,
            свой_профиль=черновик.имя,
        )
        жалобы.extend(жалобы_карты)
        # Участник консилиума, попавший ещё и в `agents`, получал бы КАЖДЫЙ вопрос человека, а не
        # только вопросы своей стадии. Живой прогон это показал дважды: инструкция сборщика
        # влияет на поведение, но договора не держит — держит программа.
        #
        # Созываемых берём из СЫРЫХ стадий, а не из принятой карты: карту могла отвергнуть
        # опечатка в переходе, и тогда консилиум молча остался бы группой на каждый вопрос —
        # ровно та беда, от которой отсев и заведён.
        созываемые = {
            имя
            for элемент in (сырые if isinstance(сырые, list) else [])
            if isinstance(элемент, dict) and isinstance(элемент.get("council"), list)
            for имя in элемент["council"]
            if isinstance(имя, str)
        }
        for имя in [a for a in агенты if a in созываемые]:
            агенты.remove(имя)
            жалобы.append(
                f"помощник «{имя}» убран из группы на каждый вопрос: он созывается на стадии"
            )

    if карта is not None and "thinking" in params:
        # Живой замер дня 13: без рассуждений (у «творческих» занятий мастер их гасит и ставит
        # температуру 1.3) модель на длинном входе с инструментами уходит в бессвязный текст и
        # вызовов не делает. Автомат стадий без вызовов стоит — поэтому у профиля с картой
        # рассуждения включены всегда, а температура, которую они обесценивают, снята.
        params.pop("thinking", None)
        снята = params.pop("temperature", None) is not None
        жалобы.append(
            "рассуждения включены: профиль ведёт задачу по стадиям, а без рассуждений модель "
            "не держит вызовы инструментов"
            + ("; температура при них не действует и снята" if снята else "")
        )

    профиль = Profile(
        name=черновик.имя,
        title=черновик.заголовок,
        description=черновик.описание,
        system=инструкция_из_разделов(черновик.разделы),
        agents=агенты,
        overrides=перекрывает,
        params=params,
        стадии=карта,
    )
    return профиль, жалобы
