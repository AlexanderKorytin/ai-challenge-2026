"""Карточка проекта: долговременное знание о ПАПКЕ, в которой запущен инструмент.

Четвёртый слой памяти. Признак принадлежности объективный и проверяется без догадок: запись
перестаёт быть правдой в другой папке. Стек, ограничения, порядок работы, где что лежит — всё
это про проект, а не про человека, и в соседнем каталоге неверно.

Устройство взято с образца, который у нас перед глазами: `CLAUDE.md` в корне репозитория
отдельно, память о человеке отдельно. Поэтому карточка привязана к папке, а НЕ к персоне: две
персоны в одной папке видят одну карточку, и это не упущение, а решение — знание о папке не
зависит от того, кто о ней говорит.

Раздел «Ограничения» заперт от модели НА ОБОИХ путях записи: его не пишет ни архивариус, ни
интервью. Причина узкая: по этим строкам программа однажды начнёт судить ответы модели на
нарушение, и правило, сочинённое самой моделью для проверки собственных ответов, — это не
проверка, а её видимость. Заполняет раздел человек командой, и инструмент об этом просит.

Заполняется карточка интервью: первый запрос спрашивает у модели, что выяснить у человека,
вопросы задаёт программа, второй запрос раскладывает ответы по разделам. Здесь живут только
сборка запросов и разбор ответов — сам обмен ведёт тот, у кого есть клиент.
"""

