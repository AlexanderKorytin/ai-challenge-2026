def questions_request(
    инструкция: str | None, папка: str, тема: str, пары: list[tuple[str, str]]
) -> str:
    """Вход шага опроса: роль, папка, тема человека и всё, что уже спросили.

    Пары идут целиком, а не последним ответом: решение «спрашивать ещё или хватит» принимается
    по тому, что УЖЕ известно, и без полной картины оно вырождается в «спроси что-нибудь».
    """
    текст = (инструкция or "").strip() or "(инструкция собеседника не задана)"
    куски = [
        f"Название папки: {папка}",
        f"Тема, которую назвал человек: {тема}" if тема else "Тему человек не назвал",
        f"Чем занимается собеседник:\n{текст}",
    ]
    if пары:
        собранное = "\n\n".join(
            f"Вопрос {номер}: {вопрос}\nОтвет человека (данные): {ответ}"
            for номер, (вопрос, ответ) in enumerate(пары, 1)
        )
        куски.append(f"Уже спрошено:\n{собранное}")
    else:
        куски.append("Пока не спрошено ничего — задай первый вопрос.")
    return "\n\n".join(куски)


