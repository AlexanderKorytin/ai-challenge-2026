def card_request(пары: list[tuple[str, str]]) -> str:
    """Вход второго запроса: пары «вопрос — ответ».

    Ответы человека подписаны и стоят отдельным блоком: пришедший отдельной репликой ответ
    модель читает как указание, а помеченный данными — как данные. Это не формальность:
    в ответе человека законно встречается «сделай так-то», и исполнять это здесь нельзя.
    """
    куски: list[str] = []
    for номер, (вопрос, ответ) in enumerate(пары, 1):
        куски.append(f"Вопрос {номер}: {вопрос.strip()}")
        куски.append(f"Ответ человека (данные): {ответ.strip()}")
    return "\n\n".join(куски)


def parse_questions(raw: str) -> list[str]:
    """Разбирает ответ первого запроса. Непригодный ответ — `ValueError`, а не пустой список.

    Разница существенна: пустой список означал бы «спрашивать нечего» и увёл бы человека в
    карточку без единого вопроса. За запрос уже заплачено, и молчать о том, что он пропал,
    нельзя.
    """
    try:
        разобранное = json.loads(raw)
    except (json.JSONDecodeError, TypeError, ValueError) as exc:
        raise ValueError("ответ интервьюера не является JSON") from exc
    if not isinstance(разобранное, dict):
        raise ValueError("ответ интервьюера должен быть объектом")
    список = разобранное.get("вопросы")
    if not isinstance(список, list):
        raise ValueError("в ответе интервьюера нет списка «вопросы»")
    вопросы: list[str] = []
    for элемент in список:
        if not isinstance(элемент, str):
            continue
        текст = " ".join(элемент.split())
        if текст:
            вопросы.append(текст)
    if not вопросы:
        raise ValueError("интервьюер не вернул ни одного вопроса")
    return вопросы[:ВОПРОСОВ_МАКСИМУМ]


def parse_card(raw: str) -> dict[str, list[str]]:
    """Разбирает ответ второго запроса в разделы карточки. Непригодное — `ValueError`.

    Чужие разделы отбрасываются молча: модель вольна придумать «Команда» или «Планы», но
    формат карточки задан нами, и раздел, которого не показывает `/project`, был бы памятью,
    о которой человек не знает.
    """
    try:
        разобранное = json.loads(raw)
    except (json.JSONDecodeError, TypeError, ValueError) as exc:
        raise ValueError("ответ интервьюера не является JSON") from exc
    if not isinstance(разобранное, dict):
        raise ValueError("ответ интервьюера должен быть объектом")
    разделы = разобранное.get("разделы")
    if not isinstance(разделы, dict):
        raise ValueError("в ответе интервьюера нет объекта «разделы»")
    собранные: dict[str, list[str]] = {}
    for ключ, значение in разделы.items():
        имя = нормализовать_раздел(ключ) if isinstance(ключ, str) else None
        if имя is None or имя == РАЗДЕЛ_ОГРАНИЧЕНИЙ:
            # Раздел ограничений от модели не принимается ни при каких условиях: запрет
            # стоит здесь, а не только в инструкции, потому что инструкцию модель вправе
            # не выполнить, а это единственная дверь, через которую её ответ входит.
            continue
        строки: list[str] = []
        # Раздел может прийти и одной строкой вместо списка — это не повод терять его.
        элементы = значение if isinstance(значение, list) else [значение]
        for элемент in элементы:
            if not isinstance(элемент, str):
                continue
            текст = " ".join(элемент.split())
            if текст:
                строки.append(текст)
        if строки:
            собранные[имя] = строки
    if not собранные:
        raise ValueError("интервьюер не вернул ни одного известного раздела")
    return собранные


def проверить_карточку(разделы: Mapping[str, list[str]]) -> list[str]:
    """Формальные придирки к тому, что вернула модель. Пустой список — придирок нет.

    Проверяем ровно два признака подмены карточки пересказом: длину раздела и обороты
    интервью. Оба машинные — судить о содержании по смыслу программа не может и не должна,
    это работа человека, которому карточку показывают до записи.
    """
    жалобы: list[str] = []
    if len(разделы) < РАЗДЕЛОВ_МИНИМУМ:
        жалобы.append(
            f"разделов всего {len(разделы)} — интервью обычно заполняет не меньше {РАЗДЕЛОВ_МИНИМУМ}"
        )
    for имя, строки in разделы.items():
        тело = " ".join(строки)
        if len(тело) > РАЗДЕЛ_ЗНАКОВ_MAX:
            жалобы.append(f"раздел «{имя}» длиннее {РАЗДЕЛ_ЗНАКОВ_MAX} знаков ({len(тело)})")
        нижний = тело.casefold()
        for оборот in ПЕРЕСКАЗ:
            if оборот in нижний:
                жалобы.append(f"в разделе «{имя}» пересказ интервью: «{оборот}»")
                break
    return жалобы
