def _сейчас() -> str:
    return f"{datetime.now(UTC):%Y-%m-%dT%H:%M:%SZ}"


@dataclass
class Карточка:
    """Карточка одной папки: заголовок и разделы."""

    проект: str
    каталог: str
    заполнена: str
    источник: str
    путь: Path
    разделы: dict[str, list[str]] = field(default_factory=dict)
    # Чужие ключи заголовка: карточку человек правит руками, и написанное им сверх известной
    # формы обязано пережить запись. Чужих РАЗДЕЛОВ у карточки не бывает — перечня нет, и
    # любой заголовок файла становится её разделом; поле оставлено пустым ради одного вида
    # у обоих хранилищ.
    прочее: dict[str, str] = field(default_factory=dict)
    чужие_разделы: list[tuple[str, str]] = field(default_factory=list)

    def пункты(self, раздел: str) -> list[str]:
        return list(self.разделы.get(раздел, []))

    def текст(self) -> str:
        заголовок: dict[str, str] = {
            "проект": self.проект,
            "каталог": self.каталог,
            "заполнена": self.заполнена,
            "источник": self.источник,
        }
        заголовок.update(self.прочее)
        # Порядок — тот, в каком разделы появились, а «Ограничения» уходят в конец: их пишет
        # человек и дописывает по ходу, и место у них постоянное, чтобы он его не искал.
        имена = [имя for имя in self.разделы if имя != РАЗДЕЛ_ОГРАНИЧЕНИЙ]
        if self.разделы.get(РАЗДЕЛ_ОГРАНИЧЕНИЙ):
            имена.append(РАЗДЕЛ_ОГРАНИЧЕНИЙ)
        разделы = [
            (имя, "\n".join(f"- {строка}" for строка in self.разделы.get(имя, [])))
            for имя in имена
        ]
        разделы.extend(self.чужие_разделы)
        return mddoc.собрать(заголовок, разделы)

    def копия(self) -> Карточка:
        """Отдельный снимок: правка на нём не видна исходному объекту, пока не записана."""
        return Карточка(
            проект=self.проект,
            каталог=self.каталог,
            заполнена=self.заполнена,
            источник=self.источник,
            путь=self.путь,
            разделы={имя: list(строки) for имя, строки in self.разделы.items()},
            прочее=dict(self.прочее),
            чужие_разделы=list(self.чужие_разделы),
        )

    def принять(self, другая: Карточка) -> None:
        """Перенять состояние успешно записанного снимка."""
        self.заполнена = другая.заполнена
        self.источник = другая.источник
        self.разделы = другая.разделы
        self.прочее = другая.прочее
        self.чужие_разделы = другая.чужие_разделы


def card_dir(cwd: Path) -> Path:
    """Каталог карточки этой папки — ключ тот же, что у разговоров и рабочей памяти."""
    return memory.state_dir() / "project" / memory.project_key(cwd)


def card_path(cwd: Path) -> Path:
    return card_dir(cwd) / ИМЯ_ФАЙЛА


def прежний_путь(cwd: Path) -> Path:
    """Куда ложится карточка, которую заменило интервью. Одна, самая свежая: две прежние
    карточки человеку не нужны, а вот последняя нужна всегда."""
    return card_dir(cwd) / ИМЯ_ПРЕЖНЕГО


def load(cwd: Path) -> tuple[Карточка | None, list[str]]:
    """Читает карточку этой папки. Не бросает: испорченная карточка не мешает работе."""
    путь = card_path(cwd)
    try:
        содержимое = путь.read_text(encoding="utf-8")
    except FileNotFoundError:
        return None, []
    except (OSError, UnicodeDecodeError) as exc:
        return None, [f"карточка проекта не прочитана ({путь}): {exc}"]
    документ = mddoc.разобрать(содержимое)
    # Ключи заголовка сверяем без учёта регистра и краевых пробелов — так же, как имена
    # разделов. Человек правит файл руками, и «Проект: челлендж» не должен молча сбрасывать
    # имя проекта на имя папки.
    заголовок = {ключ.strip().casefold(): значение for ключ, значение in документ.заголовок.items()}
    # Разделом становится ЛЮБОЙ заголовок файла: перечня у карточки нет, и «чужих» разделов
    # у неё теперь тоже нет — все свои. Пустые заголовки сохраняем именем: человек мог
    # завести раздел заранее, чтобы заполнить его позже.
    разделы: dict[str, list[str]] = {}
    for имя, _тело in документ.разделы:
        пункты = документ.пункты(имя)
        if not пункты:
            # Пустой заголовок в карточке не держим: он ничего не сообщает ни модели, ни
            # человеку, а при записи всё равно исчез бы — пусть лучше не притворяется.
            continue
        приведённое = привести_имя(имя)
        # Любое написание закреплённого раздела сворачивается к каноническому: замок не
        # должен обходиться заглавной буквой в заголовке, набранном руками.
        if приведённое.casefold() == РАЗДЕЛ_ОГРАНИЧЕНИЙ.casefold():
            приведённое = РАЗДЕЛ_ОГРАНИЧЕНИЙ
        разделы.setdefault(приведённое, []).extend(пункты)
    чужие: list[tuple[str, str]] = []
    свои_ключи = {ключ.casefold() for ключ in КЛЮЧИ_ЗАГОЛОВКА}
    прочее = {
        ключ: значение
        for ключ, значение in документ.заголовок.items()
        if ключ.strip().casefold() not in свои_ключи
    }
    if not разделы:
        # «Карточка пуста» и «файл не читается как карточка» — разные положения, и путать их
        # нельзя. Человек, стёрший строки разделов, сказал этим «переспроси меня заново»; объяви
        # мы его файл нечитаемым, `/project new` отказался бы навсегда, и выхода изнутри
        # инструмента не было бы вовсе.
        похоже_на_карточку = bool(заголовок.keys() & свои_ключи) or bool(документ.разделы)
        if not похоже_на_карточку:
            return None, [f"файл не читается как карточка проекта — в нём нет ни заголовка, ни известных разделов ({путь})"]
    return (
        Карточка(
            проект=заголовок.get("проект", "").strip() or cwd.name,
            каталог=заголовок.get("каталог", "").strip() or str(cwd),
            заполнена=заголовок.get("заполнена", "").strip(),
            источник=заголовок.get("источник", "").strip() or "человек",
            путь=путь,
            разделы=разделы,
            прочее=прочее,
            чужие_разделы=чужие,
        ),
        [],
    )


def save(карточка: Карточка) -> str | None:
    """Пишет карточку целиком. Ошибка — строкой."""
    return memory.write_private(карточка.путь, карточка.текст(), subject="карточку проекта")


def create(cwd: Path, разделы: Mapping[str, list[str]], *, источник: str) -> tuple[Карточка | None, str]:
    """Заводит карточку папки из готовых разделов. Прежняя карточка ЗАМЕНЯЕТСЯ.

    Замена, а не дописывание: интервью проводят, когда карточки нет или она устарела, и
    сшивать старое с новым значило бы оставить в карточке строки, которых человек уже не
    подтверждал.

    Замена эта не полная, и оба исключения названы:

    - **раздел «Ограничения», записанный человеком, переживает любое интервью.** Он заперт от
      модели на обоих путях записи, и «замена целиком» была бы третьим путём, которым запрет
      обходится: по этим строкам программа начнёт судить ответы модели, и переписать их она
      не вправе;
    - **чужие ключи заголовка и чужие разделы человека сохраняются.** Он правит файл руками,
      и написанное им сверх известной формы не наше, чтобы его выбрасывать.

    Файл, который лежит, но не читается как карточка, НЕ затирается: это ровно тот файл, в
    который человек только что полез руками.
    """
    путь = card_path(cwd)
    прежняя, жалобы = load(cwd)
    if прежняя is None and жалобы:
        return None, f"{жалобы[0]}; поправьте файл руками или уберите его — затирать его я не буду"
    отобранные: dict[str, list[str]] = {}
    for имя, строки in разделы.items():
        приведённое = нормализовать_раздел(имя) if имя else None
        if приведённое is None:
            continue
        очищенные = [" ".join(строка.split()) for строка in строки if строка.strip()]
        if очищенные:
            отобранные.setdefault(приведённое, []).extend(очищенные)
    подпись = " ".join(источник.split()) or "человек"
    ограничения_человека: list[str] = []
    if not это_человек(подпись):
        if прежняя is not None:
            ограничения_человека = прежняя.пункты(РАЗДЕЛ_ОГРАНИЧЕНИЙ)
        отобранные.pop(РАЗДЕЛ_ОГРАНИЧЕНИЙ, None)
        if ограничения_человека:
            отобранные[РАЗДЕЛ_ОГРАНИЧЕНИЙ] = ограничения_человека
    if not отобранные:
        return None, "карточка пуста — записывать нечего"
    if ограничения_человека:
        # Подпись относится теперь не ко всей карточке: ограничения в ней — человеческие, и
        # через месяц, разбирая карточку, это надо знать без догадок.
        подпись = f"{подпись} (ограничения — человек)"
    if прежняя is not None and _копить_копию(cwd, прежняя):
        # Прежняя карточка кладётся рядом ДО замены. Причина названа просмотром и стоила бы
        # человеку написанного: интервью заменяет карточку целиком, и хорошая карточка из
        # пяти разделов могла бы уехать в никуда ради одного раздела, который сама программа
        # объявила сомнительным. Восстановить её было бы нечем — только памятью или ещё
        # двумя оплаченными запросами.
        ошибка_копии = memory.write_private(
            прежний_путь(cwd), прежняя.текст(), subject="прежнюю карточку"
        )
        if ошибка_копии:
            # Не смогли сохранить прежнюю — не заменяем: потерять её молча хуже, чем не
            # записать новую, за которую хотя бы известно, что заплачено.
            return None, f"{ошибка_копии}; карточка не заменена"
    карточка = Карточка(
        проект=(прежняя.проект if прежняя is not None else "") or cwd.name,
        каталог=(прежняя.каталог if прежняя is not None else "") or str(cwd),
        заполнена=_сейчас(),
        источник=подпись,
        путь=путь,
        разделы=отобранные,
        прочее=dict(прежняя.прочее) if прежняя is not None else {},
        чужие_разделы=list(прежняя.чужие_разделы) if прежняя is not None else [],
    )
    ошибка = save(карточка)
    if ошибка:
        return None, ошибка
    return карточка, карточка.проект


def это_человек(источник: str) -> bool:
    """Человек ли записал. Одна проверка на оба пути записи — `create` и `add_line`.

    Разведи их, и подпись « человек » с пробелами оказалась бы человеком на одном пути и
    моделью на другом. Мягкая сторона расхождения сидела как раз там, куда приходит ответ
    модели, — а замок на разделе ограничений обязан быть одинаков с обеих сторон.
    """
    return " ".join(источник.split()).casefold() == "человек"


def _копить_копию(cwd: Path, заменяемая: Карточка) -> bool:
    """Класть ли эту карточку в запасную копию поверх того, что там уже лежит.

    Копия одна, и она должна хранить ПОСЛЕДНЮЮ карточку, которую модель не писала. Иначе сеть
    рвётся ровно на втором шаге, а он самый вероятный: человек видит «карточка вышла
    сомнительной», повторяет `/project new`, и второе интервью кладёт в копию мусор первого.
    Хорошей карточки не остаётся ни в одном файле, а строка в ленте продолжает звать вернуть
    её оттуда.

    Поэтому карточку, подписанную интервью, поверх существующей копии не кладём. Копии ещё
    нет — кладём любую: лучше мусор в запасе, чем пустота.
    """
    if not человеческая(заменяемая) and прежний_путь(cwd).exists():
        return False
    return True


ПОМЕТКА_ПРАВКИ = "правлена человеком"


# Насколько позже времени `заполнена` должен быть изменён файл, чтобы это считалось правкой
# руками. Инструмент ставит `заполнена` непосредственно перед записью, и разница между меткой
# и временем файла у него — доли секунды. Две секунды с запасом отделяют запись инструмента от
# правки текстовым редактором; порог назван вслух, потому что он о времени, а не о вкусе.
ПРАВКА_РУКАМИ_СЕКУНД = 2.0


def _человеческая_подпись(источник: str) -> bool:
    """Говорит ли сама подпись, что карточку писал или правил человек.

    Одно место разбора на два вопроса — «человеческая ли карточка» и «дописывать ли отметку»:
    разведи их, и два разбора одной подписи разойдутся на первой же правке формата.
    """
    куски = [кусок.strip() for кусок in источник.split(";")]
    if any(кусок.casefold() == ПОМЕТКА_ПРАВКИ for кусок in куски):
        return True
    # Слово до первой скобки: «интервью (ограничения — человек)» писала модель, и
    # человеческой такая подпись не считается — раздел перенесён механически.
    return это_человек(куски[0].split("(")[0])


def правлена_руками(карточка: Карточка) -> bool:
    """Правил ли человек ФАЙЛ карточки мимо инструмента — текстовым редактором.

    Формат `.md` выбран ровно ради этого, и не заметить такую правку значило бы потерять её
    при следующей замене: карточка осталась бы подписана интервью, копия её не приняла бы, а
    дописанные руками строки исчезли бы из всех файлов.

    Признак объективный: инструмент ставит `заполнена` при каждой своей записи, поэтому файл,
    изменённый заметно позже этой метки, тронут не им.
    """
    if not карточка.заполнена:
        return False
    try:
        изменён = карточка.путь.stat().st_mtime
    except OSError:
        return False
    try:
        заполнена = datetime.strptime(карточка.заполнена, "%Y-%m-%dT%H:%M:%SZ").replace(tzinfo=UTC)
    except ValueError:
        # Метку правил человек — значит он файл и трогал.
        return True
    return изменён - заполнена.timestamp() > ПРАВКА_РУКАМИ_СЕКУНД


def человеческая(карточка: Карточка) -> bool:
    """Трогал ли карточку человек — сам заполнил, правил командой или правил файл руками.

    От этого зависит, беречь ли запасную копию: копия одна, и хранить в ней надо последнюю
    карточку, к которой человек приложил руку.
    """
    return _человеческая_подпись(карточка.источник) or правлена_руками(карточка)


def привести_имя(раздел: str) -> str:
    """Имя раздела, приведённое к сравнимому виду: одно правило на весь модуль.

    Двойные пробелы и краевые — долой: карточку правят руками, и «## Порядок  работы» с
    двойным пробелом обязан быть тем же разделом, что «Порядок работы». Разведи это правило
    по двум местам — и одна и та же карточка получит два раздела с одинаковым на вид именем.
    """
    return " ".join(раздел.split())


def нормализовать_раздел(раздел: str, карточка: Карточка | None = None) -> str | None:
    """Имя раздела в том виде, в каком оно лежит в карточке. Пустое имя — `None`.

    Перечня разделов у карточки нет, поэтому «канон» берётся из неё самой: человек написал
    «стек», а в карточке раздел называется «Стек» — это один раздел, и заводить второй по
    разнице в регистре нельзя. Раздела с таким именем нет — значит это новый раздел, и имя
    возвращается как набрано: карточка о любой папке, и придумывать её разделы не нам.

    Единственное исключение — ЗАКРЕПЛЁННЫЙ раздел «Ограничения»: его имя канонизируется
    всегда, даже если в карточке его ещё нет. Иначе замок обходится регистром: `/project
    ограничения: …` завёл бы второй раздел, человек видел бы в карточке свои строки и тут же
    подпись «Ограничения — пусты», судья ответов их не увидел бы, а следующее интервью стёрло
    бы их молча.
    """
    имя = привести_имя(раздел)
    if not имя:
        return None
    if имя.casefold() == РАЗДЕЛ_ОГРАНИЧЕНИЙ.casefold():
        return РАЗДЕЛ_ОГРАНИЧЕНИЙ
    if карточка is not None:
        ключ = имя.casefold()
        for существующий in карточка.разделы:
            if существующий.casefold() == ключ:
                return существующий
    return имя


def add_line(
    карточка: Карточка,
    раздел: str,
    текст: str,
    *,
    источник: str = "человек",
) -> tuple[bool, str]:
    """Дописывает строку в раздел карточки.

    Раздел «Ограничения» правит ТОЛЬКО человек. Это не общая осторожность: по этим строкам
    программа начнёт судить ответы модели на нарушение, и правило, которое модель написала
    себе сама, проверкой не является.
    """
    имя = нормализовать_раздел(раздел, карточка)
    if имя is None:
        return False, "нужно имя раздела: /project Ограничения: <текст>"
    if имя == РАЗДЕЛ_ОГРАНИЧЕНИЙ and not это_человек(источник):
        return False, f"раздел «{РАЗДЕЛ_ОГРАНИЧЕНИЙ}» правит только человек — источник «{источник}» отклонён"
    строка = " ".join(текст.split())
    if not строка:
        return False, f"нужен текст: /project {имя}: <текст>"
    # Правим снимок: отказ диска не должен оставлять в памяти строку, которой на диске нет,
    # — она ушла бы к модели и записалась при следующем удачном сохранении, хотя человеку
    # уже сказали «не удалось записать».
    снимок = карточка.копия()
    снимок.разделы.setdefault(имя, []).append(строка)
    снимок.заполнена = _сейчас()
    снимок.источник = _подпись_после_правки(снимок.источник, источник)
    ошибка = save(снимок)
    if ошибка:
        return False, ошибка
    карточка.принять(снимок)
    return True, строка


def remove_line(
    карточка: Карточка, раздел: str, номер: int, *, источник: str = "человек"
) -> tuple[bool, str]:
    """Убирает строку раздела карточки по номеру, каким она показана человеку.

    Замок на разделе «Ограничения» действует и на удаление: право стереть правило, по
    которому судят ответы модели, — это то же право, что и право его написать.
    """
    имя = нормализовать_раздел(раздел, карточка)
    if имя is None or имя not in карточка.разделы:
        есть = ", ".join(карточка.разделы) or "ни одного"
        return False, f"нет раздела «{раздел}» — в карточке есть: {есть}"
    if имя == РАЗДЕЛ_ОГРАНИЧЕНИЙ and not это_человек(источник):
        return False, f"раздел «{РАЗДЕЛ_ОГРАНИЧЕНИЙ}» правит только человек — источник «{источник}» отклонён"
    строки = карточка.пункты(имя)
    if not строки:
        return False, f"раздел «{имя}» пуст — удалять нечего"
    if not 1 <= номер <= len(строки):
        return False, f"в разделе «{имя}» нет строки {номер} — сейчас их {len(строки)}"
    снимок = карточка.копия()
    убранная = снимок.разделы[имя].pop(номер - 1)
    if not снимок.разделы[имя]:
        снимок.разделы.pop(имя)
    снимок.заполнена = _сейчас()
    снимок.источник = _подпись_после_правки(снимок.источник, источник)
    ошибка = save(снимок)
    if ошибка:
        return False, ошибка
    карточка.принять(снимок)
    return True, убранная


def _подпись_после_правки(подпись: str, источник: str) -> str:
    """Подпись карточки после правки. Ручная правка отмечается, машинная — нет.

    Знание «карточку собрало интервью» не теряем, а дополняем: иначе через месяц по карточке
    не понять, откуда в ней строки. А отметка нужна затем, чтобы запасная копия считала такую
    карточку человеческой и не дала следующему интервью её затереть.
    """
    if not это_человек(источник):
        return подпись
    if _человеческая_подпись(подпись):
        return подпись
    return f"{подпись}; {ПОМЕТКА_ПРАВКИ}"


def remove_card(cwd: Path) -> tuple[bool, str, tuple[Path | None, bool]]:
    """Убирает карточку папки целиком, сохранив её рядом запасной копией.

    Третьим значением — пара «путь копии, копия постарше». Признак «постарше» нужен словами:
    когда убираемую карточку писала модель, копию мы не заменяем, и человеку надо сказать, что
    рядом лежит не она, а более ранняя.

    Копия здесь обязательна, а не любезна: карточку собирали интервью или руками, и
    необратимое удаление по одной команде стоило бы дороже, чем лишний файл на диске.
    """
    карточка, жалобы = load(cwd)
    путь = card_path(cwd)
    if карточка is None and жалобы:
        # Файл лежит, но карточкой не читается. Удалить его молча нельзя: там могут быть
        # заметки человека, а копию с нечитаемого файла мы не снимем. `create` в этом же
        # положении отказывается — удаление обязано вести себя так же.
        return (
            False,
            f"{жалобы[0]}; поправьте файл руками или уберите его — удалять его я не буду",
            (None, False),
        )
    if карточка is None and not путь.exists():
        return False, "карточки у этой папки нет — удалять нечего", (None, False)
    путь_копии: Path | None = None
    копия_постарше = False
    if карточка is not None and _копить_копию(cwd, карточка):
        ошибка_копии = memory.write_private(
            прежний_путь(cwd), карточка.текст(), subject="прежнюю карточку"
        )
        if ошибка_копии:
            # Не смогли сохранить копию — не удаляем: необратимая потеря хуже, чем невыполненная
            # команда, которую можно повторить.
            return False, f"{ошибка_копии}; карточка не удалена", (None, False)
        путь_копии = прежний_путь(cwd)
    elif карточка is not None and прежний_путь(cwd).exists():
        # Копию не кладём: там лежит карточка, к которой человек прикладывал руку, а эту
        # писала модель. Путь называем, но отдельным признаком — иначе человек прочтёт
        # «копия лежит рядом» про ту карточку, которую только что видел напечатанной, а
        # лежит там другая, постарше.
        путь_копии = прежний_путь(cwd)
        копия_постарше = True
    try:
        путь.unlink()
    except FileNotFoundError:
        return True, "карточка уже убрана", (путь_копии, копия_постарше)
    except OSError as exc:
        return False, f"не удалось убрать карточку ({путь}): {exc}", (None, False)
    return True, "карточка убрана", (путь_копии, копия_постарше)


def блок(карточка: Карточка) -> str:
    """Блок карточки для системной части запроса.

    Первая строка называет, что это и насколько это верно: без неё модель принимает карточку
    за указание человека, сказанное только что, и начинает отвечать на неё.
    """
    if not any(карточка.разделы.values()):
        # Пустая карточка в запрос не идёт: заголовок без сведений сообщил бы модели, что о
        # папке известно, что о ней ничего не известно, и она стала бы это обыгрывать.
        return ""
    куски = [
        f"Карточка проекта (папка {карточка.проект}). Сведения верны для этой папки; "
        "при противоречии со справкой о собеседнике верна карточка.",
    ]
    for имя, пункты in карточка.разделы.items():
        if not пункты:
            continue
        куски.append(f"## {имя}")
        куски.extend(f"- {строка}" for строка in пункты)
    return "\n".join(куски)


