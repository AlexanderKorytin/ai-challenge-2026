def card_request(пары: list[tuple[str, str]], тема: str = "") -> str:
    """Вход сборки карточки: тема человека и пары «вопрос — ответ».

    Ответы подписаны и стоят отдельным блоком: пришедший отдельной репликой ответ модель
    читает как указание, а помеченный данными — как данные. Это не формальность: в ответе
    человека законно встречается «сделай так-то», и исполнять это здесь нельзя.
    """
    куски: list[str] = [f"Тема: {тема}"] if тема else []
    for номер, (вопрос, ответ) in enumerate(пары, 1):
        куски.append(f"Вопрос {номер}: {вопрос.strip()}")
        куски.append(f"Ответ человека (данные): {ответ.strip()}")
    return "\n\n".join(куски)


def parse_step(raw: str) -> str | None:
    """Разбирает шаг опроса: текст следующего вопроса либо `None` — «хватит».

    Непригодный ответ поднимает `ValueError`: отличить «спрашивать больше нечего» от «модель
    ответила мусором» обязательно — за шаг заплачено, и молча превратить сбой в готовую
    карточку значило бы записать её по неполным ответам.
    """
    try:
        разобранное = json.loads(raw)
    except (json.JSONDecodeError, TypeError, ValueError) as exc:
        raise ValueError("ответ интервьюера не является JSON") from exc
    if not isinstance(разобранное, dict):
        raise ValueError("ответ интервьюера должен быть объектом")
    if разобранное.get("готово") is True:
        return None
    вопрос = разобранное.get("вопрос")
    if not isinstance(вопрос, str) or not вопрос.strip():
        raise ValueError("в ответе интервьюера нет ни вопроса, ни признака «готово»")
    return " ".join(вопрос.split())


def parse_card(raw: str) -> tuple[dict[str, list[str]], list[str]]:
    """Разбирает ответ второго запроса в разделы карточки. Непригодное — `ValueError`.

    Разделы модель называет сама — перечня у карточки нет. Отбрасывается только закреплённый
    «Ограничения» и всё, что с него начинается: раздел вроде «Ограничения по еде» человек
    прочтёт как тот самый, а судить программа будет по другому, и выйдет видимость проверки.
    """
    try:
        разобранное = json.loads(raw)
    except (json.JSONDecodeError, TypeError, ValueError) as exc:
        raise ValueError("ответ интервьюера не является JSON") from exc
    if not isinstance(разобранное, dict):
        raise ValueError("ответ интервьюера должен быть объектом")
    разделы = разобранное.get("разделы")
    if not isinstance(разделы, dict):
        raise ValueError("в ответе интервьюера нет объекта «разделы»")
    собранные: dict[str, list[str]] = {}
    # Отброшенное возвращаем ВТОРЫМ значением, а не выбрасываем молча: в разделе «Ограничения
    # по еде» лежит строка про аллергию, за которую заплачен обмен, и человек должен узнать,
    # что она не записана и где её место.
    отброшенные: list[str] = []
    for ключ, значение in разделы.items():
        имя = привести_имя(ключ) if isinstance(ключ, str) else None
        # Отбрасываем не только точное имя, но и всё, что с него начинается: «Ограничения по
        # еде» от модели человек прочтёт как тот самый раздел, а судить программа будет по
        # другому — и получится видимость проверки вместо проверки.
        if not имя:
            continue
        if имя.casefold().startswith(НАЧАЛО_ЗАКРЕПЛЁННОГО):
            # Раздел ограничений от модели не принимается ни при каких условиях: запрет стоит
            # здесь, а не только в инструкции, потому что инструкцию модель вправе не
            # выполнить, а это единственная дверь, через которую её ответ входит.
            отброшенные.append(имя)
            continue
        строки: list[str] = []
        # Раздел может прийти и одной строкой вместо списка — это не повод терять его.
        элементы = значение if isinstance(значение, list) else [значение]
        for элемент in элементы:
            if not isinstance(элемент, str):
                continue
            текст = " ".join(элемент.split())
            if текст:
                строки.append(текст)
        if строки:
            собранные[имя] = строки
    if not собранные:
        raise ValueError("интервьюер не вернул ни одного раздела, который мы принимаем")
    return собранные, отброшенные


def проверить_карточку(разделы: Mapping[str, list[str]]) -> list[str]:
    """Формальные придирки к тому, что вернула модель. Пустой список — придирок нет.

    Проверяем ровно два признака подмены карточки пересказом: длину раздела и обороты
    интервью. Оба машинные — судить о содержании по смыслу программа не может и не должна,
    это работа человека, которому карточку показывают до записи.
    """
    жалобы: list[str] = []
    if len(разделы) < РАЗДЕЛОВ_МИНИМУМ:
        жалобы.append(
            f"разделов всего {len(разделы)} — обычно из разговора выходит не меньше {РАЗДЕЛОВ_МИНИМУМ}"
        )
    for имя, строки in разделы.items():
        тело = " ".join(строки)
        if len(тело) > РАЗДЕЛ_ЗНАКОВ_MAX:
            жалобы.append(f"раздел «{имя}» длиннее {РАЗДЕЛ_ЗНАКОВ_MAX} знаков ({len(тело)})")
        нижний = тело.casefold()
        for оборот in ПЕРЕСКАЗ:
            if оборот in нижний:
                жалобы.append(f"в разделе «{имя}» пересказ интервью: «{оборот}»")
                break
    return жалобы
