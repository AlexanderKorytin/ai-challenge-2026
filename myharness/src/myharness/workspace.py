"""Рабочая память: состояние текущей задачи, живущее ровно столько, сколько живёт задача.

Третий слой памяти инструмента. Разговор помнит, что было сказано; записи помнят человека;
карточка помнит папку; а этот слой помнит **работу**: что за задача, на каком она этапе, что
уже сделано и что делается сейчас. Признак принадлежности слою объективный: запись умирает,
когда задача закрыта. Умерла не по решению человека «это уже неважно», а по команде `/task
done`, и вместе с ней уходит файл.

Назначение названо пользователем прямо: **продолжить в следующей сессии с нужного места**. Это
то же самое, что делает `docs/состояние-<задача>.md` в нашем собственном конвейере, только
внутри инструмента и для его собственного собеседника.

Формат — `.md` с заголовком и разделами, а не JSON: человек правит этот файл руками и читает
его глазами. Разбор и сборка живут в `mddoc` — тот же формат читает карточка проекта, и двух
разборов одного формата в инструменте быть не должно.

Модуль не знает ни про сеть, ни про терминал. Ошибку возвращает текстом: рабочая память —
вспомогательный механизм, и ронять ею оплаченный обмен нельзя.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import UTC, datetime
from pathlib import Path

from . import mddoc, memory

# Разделы задачи и их порядок. Это ровно `TaskContext` из материалов ментора: ограничения,
# план, сделано, сейчас, находки. Порядок постоянный: человек привыкает к месту на экране.
РАЗДЕЛЫ: tuple[str, ...] = ("Ограничения", "План", "Сделано", "Сейчас", "Находки")

# Раздел «Сейчас» — одна строка, а не список: «над чем работаем прямо сейчас» во множественном
# числе означает, что ни над чем. Команда его ЗАМЕНЯЕТ; написанное человеком руками при этом
# сохраняется как есть — усекать чужую правку до первой строки инструмент права не имеет.
РАЗДЕЛ_СЕЙЧАС = "Сейчас"

# Ключи заголовка, которые инструмент ведёт сам. Всё прочее, что человек допишет в заголовок
# руками, сохраняется нетронутым — см. `Задача.прочее`.
КЛЮЧИ_ЗАГОЛОВКА: tuple[str, ...] = ("задача", "этап", "создана", "изменена")

# Этап по умолчанию у новой задачи. Списка допустимых этапов здесь НЕТ намеренно: карта
# переходов конечного автомата придёт отдельным днём, и предел, заведённый сегодня «пока так»,
# стал бы потолком, о который она упрётся.
ЭТАП_ПО_УМОЛЧАНИЮ = "PLANNING"

# Запасное начало имени файла: название из одних знаков препинания слагом не описать.
ЗАПАСНЫЙ_СЛАГ = "задача"


def _сейчас() -> str:
    """Время в том же виде, что у записей: один вид времени на весь каталог состояния."""
    return f"{datetime.now(UTC):%Y-%m-%dT%H:%M:%SZ}"


def _приведённое(название: str) -> str:
    """Название в том виде, в каком два написания одной задачи считаются одним."""
    return " ".join(название.split()).casefold()


def _имя_файла(название: str) -> str:
    """Имя файла задачи: читаемое начало плюс отпечаток названия.

    Отпечаток здесь по той же причине, по какой он стоит у записей: слаг режется по 80
    байтам, то есть примерно по сорока знакам кириллицы, и два длинных названия, различных
    только в хвосте, дали бы один файл — вторая задача молча продолжила бы первую.
    """
    слаг = memory.слаг(название)
    if слаг == "факт":  # запасное слово записей; у задачи оно своё
        слаг = ЗАПАСНЫЙ_СЛАГ
    # Отпечаток берётся от ПРИВЕДЁННОГО названия, а не от набранного. Слаг и так приводит
    # текст к нижнему регистру, и считай мы отпечаток от исходного, «разделение cli.py» и
    # «Разделение cli.py» дали бы два файла и двух близнецов в списке задач — ровно то, от
    # чего оберегает обещание «продолжаем прежнюю задачу».
    return f"{слаг}-{memory.fingerprint(_приведённое(название))}"


def безопасный_слаг(слаг: str) -> str | None:
    """Слаг, пригодный для имени файла, либо `None`.

    Из слага собирается путь внутри каталога состояния — того самого, где лежат ключ API и
    переписка. Разделитель пути или `..` в слаге увели бы чтение и запись наружу, а слаг
    приходит в том числе из набранной человеком команды.
    """
    очищенный = слаг.strip()
    if not очищенный or очищенный in (".", ".."):
        return None
    if "/" in очищенный or "\\" in очищенный or "\x00" in очищенный:
        return None
    return очищенный


@dataclass
class Задача:
    """Одна задача рабочей памяти со всеми разделами и путём своего файла."""

    слаг: str
    название: str
    этап: str
    создана: str
    изменена: str
    путь: Path
    разделы: dict[str, list[str]] = field(default_factory=dict)
    # Чужие ключи заголовка и чужие разделы: человек правит файл руками, и написанное им
    # сверх известной формы обязано пережить запись. Инструмент их не понимает, но и не
    # выбрасывает — в блок для модели они не идут, а в файле остаются на своём месте.
    прочее: dict[str, str] = field(default_factory=dict)
    чужие_разделы: list[tuple[str, str]] = field(default_factory=list)

    def пункты(self, раздел: str) -> list[str]:
        return list(self.разделы.get(раздел, []))

    @property
    def сейчас(self) -> str:
        return "\n".join(self.разделы.get(РАЗДЕЛ_СЕЙЧАС, []))

    def текст(self) -> str:
        """Файл задачи целиком — то, что ложится на диск и что человек правит руками."""
        заголовок: dict[str, str] = {
            "задача": self.название,
            "этап": self.этап,
            "создана": self.создана,
            "изменена": self.изменена,
        }
        заголовок.update(self.прочее)
        разделы: list[tuple[str, str]] = []
        for имя in РАЗДЕЛЫ:
            строки = self.разделы.get(имя, [])
            тело = "\n".join(строки) if имя == РАЗДЕЛ_СЕЙЧАС else "\n".join(f"- {с}" for с in строки)
            разделы.append((имя, тело))
        разделы.extend(self.чужие_разделы)
        return mddoc.собрать(заголовок, разделы)

    def копия(self) -> Задача:
        """Отдельный снимок задачи: правки на нём не видны исходному объекту.

        Нужен затем, чтобы отказ диска не оставлял в памяти строки, которой на диске нет:
        такая строка ушла бы к модели и была бы записана при следующем удачном сохранении,
        хотя человеку уже сказали «не удалось записать».
        """
        return Задача(
            слаг=self.слаг,
            название=self.название,
            этап=self.этап,
            создана=self.создана,
            изменена=self.изменена,
            путь=self.путь,
            разделы={имя: list(строки) for имя, строки in self.разделы.items()},
            прочее=dict(self.прочее),
            чужие_разделы=list(self.чужие_разделы),
        )

    def принять(self, другая: Задача) -> None:
        """Перенять состояние успешно записанного снимка."""
        self.этап = другая.этап
        self.изменена = другая.изменена
        self.разделы = другая.разделы
        self.прочее = другая.прочее
        self.чужие_разделы = другая.чужие_разделы


def work_dir(cwd: Path) -> Path:
    """Каталог рабочей памяти этой папки. Ключ — тот же, что у разговоров: новых способов
    адресации не заводим, иначе одна и та же папка получила бы два разных имени."""
    return memory.state_dir() / "work" / memory.project_key(cwd)


def task_path(cwd: Path, слаг: str) -> Path | None:
    """Путь к файлу задачи; `None` — слаг непригоден для имени файла."""
    очищенный = безопасный_слаг(слаг)
    if очищенный is None:
        return None
    return work_dir(cwd) / f"{очищенный}.md"


def _разобрать(путь: Path, содержимое: str) -> Задача | None:
    """Собирает задачу из текста файла; `None` — файла как задачи не существует.

    Непригоден файл без названия: всё остальное восстановимо умолчанием, а задача без имени
    не показывается человеку и не адресуется командой.
    """
    документ = mddoc.разобрать(содержимое)
    # Ключи заголовка сверяем так же, как имена разделов: без учёта регистра и краевых
    # пробелов. Человек правит файл руками и напишет «Этап: VALIDATION» — точное сравнение
    # молча вернуло бы задачу в PLANNING, и модель получила бы неверное состояние работы.
    заголовок = {ключ.strip().casefold(): значение for ключ, значение in документ.заголовок.items()}
    название = заголовок.get("задача", "").strip()
    if not название:
        return None
    разделы: dict[str, list[str]] = {}
    for имя in РАЗДЕЛЫ:
        # «Сейчас» читаем строками как есть: это не список пунктов, и снимать с него тире
        # значило бы терять знак, который человек написал руками.
        пункты = (
            [с for с in документ.раздел(имя).splitlines() if с.strip()]
            if имя == РАЗДЕЛ_СЕЙЧАС
            else документ.пункты(имя)
        )
        if пункты:
            разделы[имя] = пункты
    известные = {имя.strip().casefold() for имя in РАЗДЕЛЫ}
    чужие = [(имя, тело) for имя, тело in документ.разделы if имя.strip().casefold() not in известные]
    свои_ключи = {ключ.casefold() for ключ in КЛЮЧИ_ЗАГОЛОВКА}
    прочее = {
        ключ: значение
        for ключ, значение in документ.заголовок.items()
        if ключ.strip().casefold() not in свои_ключи
    }
    return Задача(
        слаг=путь.stem,
        название=название,
        этап=заголовок.get("этап", "").strip() or ЭТАП_ПО_УМОЛЧАНИЮ,
        создана=заголовок.get("создана", "").strip(),
        изменена=заголовок.get("изменена", "").strip(),
        путь=путь,
        разделы=разделы,
        прочее=прочее,
        чужие_разделы=чужие,
    )


def load_task(cwd: Path, слаг: str) -> tuple[Задача | None, list[str]]:
    """Читает одну задачу по слагу. Возвращает `(задача, предупреждения)` и не бросает.

    Пустой список предупреждений при `None` означает ровно одно: задачи нет. Непустой —
    файл есть, но прочитать его как задачу не удалось, и трогать его нельзя.
    """
    путь = task_path(cwd, слаг)
    if путь is None:
        return None, [f"непригодное имя задачи: «{слаг}»"]
    try:
        содержимое = путь.read_text(encoding="utf-8")
    except FileNotFoundError:
        return None, []
    except (OSError, UnicodeDecodeError) as exc:
        return None, [f"рабочая память {путь.name} не прочитана: {exc}"]
    задача = _разобрать(путь, содержимое)
    if задача is None:
        return None, [f"рабочая память {путь.name} не разбирается — в ней нет строки «задача:»"]
    return задача, []


def list_tasks(cwd: Path) -> tuple[list[Задача], list[str]]:
    """Все задачи этой папки, свежая первой. Порядок — по времени изменения.

    Обход через `iterdir`, а не `glob`: `glob` молча глотает отказ в правах и отдаёт пустой
    список, и недоступная рабочая память была бы неотличима от пустой.
    """
    каталог = work_dir(cwd)
    предупреждения: list[str] = []
    if not каталог.exists():
        return [], предупреждения
    try:
        файлы = sorted(п for п in каталог.iterdir() if п.suffix == ".md")
    except OSError as exc:
        return [], [f"рабочая память недоступна ({каталог}): {exc}"]
    задачи: list[Задача] = []
    for файл in файлы:
        задача, жалобы = load_task(cwd, файл.stem)
        предупреждения.extend(жалобы)
        if задача is not None:
            задачи.append(задача)
    # Порядок: время из заголовка, затем время файла, затем имя. Заголовок пишет инструмент и
    # точность его — секунда; время файла ловит правку руками, после которой задача обязана
    # стать последней. Имя файла третьим ключом — чтобы порядок был один и тот же в двух
    # запущенных копиях инструмента: иначе «последняя задача» у них разная.
    def _ключ(з: Задача) -> tuple[str, float, str]:
        try:
            время_файла = з.путь.stat().st_mtime
        except OSError:
            время_файла = 0.0
        return (з.изменена, время_файла, з.путь.name)

    задачи.sort(key=_ключ, reverse=True)
    return задачи, предупреждения


def _записать(задача: Задача, снимок: Задача) -> tuple[bool, str]:
    """Пишет снимок на диск и, только при успехе, переносит его в саму задачу."""
    снимок.изменена = _сейчас()
    ошибка = memory.write_private(снимок.путь, снимок.текст(), subject="рабочую память")
    if ошибка:
        return False, ошибка
    задача.принять(снимок)
    return True, ""


def save_task(задача: Задача) -> str | None:
    """Пишет задачу на диск целиком, отметив время изменения. Ошибка — строкой."""
    снимок = задача.копия()
    записана, сообщение = _записать(задача, снимок)
    return None if записана else сообщение


def create_task(cwd: Path, название: str) -> tuple[Задача | None, str, bool]:
    """Заводит задачу. Возвращает `(задача, сообщение, новая ли)`.

    Задача с тем же названием не заводится второй раз, а возвращается прежняя: человек,
    набравший `/task new` дважды, хочет продолжить свою задачу, а не завести её близнеца,
    который молча заберёт себе место в списке. Третьим значением возвращается признак «новая»:
    продолжение прежней задачи и заведение новой — разные события, и вызывающий обязан сказать
    человеку, какое из них случилось. Иначе в хвост каждого запроса уедет старый план, о
    котором не сказали ни слова.

    Файл, который лежит, но не читается как задача, НЕ затирается: это ровно тот файл, в
    который человек только что полез руками, и в нём его находки. Отказ с путём дешевле
    молчаливой потери.
    """
    имя = " ".join(название.split())
    if not имя:
        return None, "нужно название задачи: /task new разделение cli.py", False
    слаг = _имя_файла(имя)
    прежняя, жалобы = load_task(cwd, слаг)
    if прежняя is not None:
        return прежняя, f"задача «{прежняя.название}» уже заведена — продолжаем её", False
    if жалобы:
        return None, f"{жалобы[0]}; поправьте файл руками или уберите его — затирать его я не буду", False
    # `task_path` здесь вернуть `None` не может: слаг собран нами из букв, цифр и дефисов,
    # а не пришёл снаружи. Разворачиваем сразу — ветка «а вдруг» была бы кодом, который
    # нечем вызвать и нечем проверить.
    путь = work_dir(cwd) / f"{слаг}.md"
    время = _сейчас()
    задача = Задача(
        слаг=слаг,
        название=имя,
        этап=ЭТАП_ПО_УМОЛЧАНИЮ,
        создана=время,
        изменена=время,
        путь=путь,
    )
    ошибка = save_task(задача)
    if ошибка:
        return None, ошибка, False
    return задача, имя, True


def нормализовать_раздел(раздел: str) -> str | None:
    """Имя раздела, как его набрал человек, приводится к каноническому. Чужое — `None`."""
    ключ = " ".join(раздел.split()).casefold()
    for имя in РАЗДЕЛЫ:
        if имя.casefold() == ключ:
            return имя
    return None


def add_line(задача: Задача, раздел: str, текст: str) -> tuple[bool, str]:
    """Дописывает строку в раздел задачи. `Сейчас` заменяется, остальные разделы копятся.

    Замена, а не накопление, у `Сейчас` потому, что это единственный раздел, у которого нет
    истории: «сейчас» бывает одно, и список из трёх «сейчас» не сообщает модели ничего.
    """
    имя = нормализовать_раздел(раздел)
    if имя is None:
        return False, f"нет раздела «{раздел}» — есть: {', '.join(РАЗДЕЛЫ)}"
    строка = " ".join(текст.split())
    if not строка:
        return False, f"нужен текст: /task {имя.lower()} <текст>"
    снимок = задача.копия()
    if имя == РАЗДЕЛ_СЕЙЧАС:
        снимок.разделы[имя] = [строка]
    else:
        снимок.разделы.setdefault(имя, []).append(строка)
    записано, сообщение = _записать(задача, снимок)
    return (True, строка) if записано else (False, сообщение)


def remove_line(задача: Задача, раздел: str, номер: int) -> tuple[bool, str]:
    """Убирает строку раздела по НОМЕРУ, каким она показана человеку, — то есть с единицы.

    Симметрично `/forget` у записей о человеке, и номер тот же, что на экране: искать строку
    по тексту человек не должен — он видит список и называет место в нём.
    """
    имя = нормализовать_раздел(раздел)
    if имя is None:
        return False, f"нет раздела «{раздел}» — есть: {', '.join(РАЗДЕЛЫ)}"
    строки = задача.пункты(имя)
    if not строки:
        return False, f"раздел «{имя}» пуст — удалять нечего"
    if not 1 <= номер <= len(строки):
        # Номер приходит из набранной вручную команды. Промах — не поломка инструмента.
        return False, f"в разделе «{имя}» нет строки {номер} — сейчас их {len(строки)}"
    снимок = задача.копия()
    убранная = снимок.разделы[имя].pop(номер - 1)
    if not снимок.разделы[имя]:
        снимок.разделы.pop(имя)
    записано, сообщение = _записать(задача, снимок)
    return (True, убранная) if записано else (False, сообщение)


def set_stage(задача: Задача, этап: str) -> tuple[bool, str]:
    """Ставит этап задачи. Слово любое: карта переходов придёт отдельным днём."""
    слово = " ".join(этап.split()).upper()
    if not слово:
        return False, "нужен этап: /task этап EXECUTION"
    снимок = задача.копия()
    снимок.этап = слово
    записано, сообщение = _записать(задача, снимок)
    return (True, слово) if записано else (False, сообщение)


def close_task(задача: Задача) -> tuple[bool, str]:
    """Закрывает задачу: файл рабочей памяти удаляется.

    Удаление — это и есть договор слоя: рабочая память, пережившая задачу, стала бы второй
    свалкой рядом с записями о человеке, и через месяц никто не отличил бы живое от мёртвого.
    Переживающее выносится человеком в записи до закрытия — команда показывает файл целиком.
    """
    try:
        задача.путь.unlink()
    except FileNotFoundError:
        # Файл уже убрали — второй копией инструмента или руками. Цель достигнута.
        return True, задача.название
    except OSError as exc:
        return False, f"не удалось закрыть задачу ({задача.путь}): {exc}"
    return True, задача.название


def блок(задача: Задача) -> str:
    """Эфемерный хвост запроса: состояние задачи в том виде, в каком его видит модель.

    Обрамление тегами, а не заголовком: блок стоит в хвосте, рядом с вопросом человека, и
    граница между «состоянием работы» и «тем, что человек спросил» обязана быть видна без
    догадок — иначе модель читает состояние как часть вопроса.

    Пустые разделы в блок не идут: пустой заголовок «План» сообщил бы модели, что план пуст,
    хотя он просто не заведён, и она начала бы это обыгрывать. Чужие разделы не идут тоже —
    формат блока задаём мы, а не тот, кто правил файл.
    """
    куски = [
        f"Текущая задача: «{задача.название}», этап {задача.этап}.",
        "Это состояние работы, а не вопрос. При противоречии с карточкой проекта и справкой "
        "о собеседнике верно оно.",
    ]
    for имя in РАЗДЕЛЫ:
        пункты = задача.пункты(имя)
        if not пункты:
            continue
        куски.append(f"## {имя}")
        if имя == РАЗДЕЛ_СЕЙЧАС:
            куски.extend(пункты)
        else:
            куски.extend(f"- {строка}" for строка in пункты)
    тело = "\n".join(куски)
    return f"<рабочее-состояние>\n{тело}\n</рабочее-состояние>"
