ОТВЕТ_НЕ_ЗАПИСЬ = '{"слой": "нет", "раздел": "", "текст": ""}'
ВОПРОС_ИНТЕРВЬЮ = '{"вопрос": "чем собираете проект?"}'


class FakeClient:
    """Подставной собеседник, который отличает запрос распознавателя от всех прочих.

    Отвечать одинаково всем нельзя: распознаватель ждёт объект JSON с адресом, а «ответ
    модели» для него — неразбираемый мусор, то есть оплаченный сбой. С одним ответом на всех
    сценарий не проверил бы ни записи, ни честного «это не запись»: обе дороги кончались бы
    одной и той же жалобой на разбор.

    Узнаём распознавателя по его ИНСТРУКЦИИ, а не по `response_format`. Своим объектом JSON
    в этом инструменте ходит не он один: тем же способом спрашивает интервью о папке, и
    отличать одного от другого по ручке запроса значило бы кормить обряд чужими ответами —
    молча и ровно в той проверке, где обряд и проверяется.
    """

    def __init__(self):
        self.calls = []
        # Ответы распознавателю по очереди: у каждой реплики сценария своя судьба, и задать
        # её надо до того, как реплика отправлена.
        self.ответы_распознавателя = []
        # Ворота ответа распознавателю: пока они стоят и закрыты, разбор висит. Так проверкам
        # достаётся сам ход разбора — живая строка в ленте, вторая реплика посреди него, уход
        # человека на соседний экран, — и достаётся ПОРЯДКОМ, а не выпрошенным у планировщика
        # числом секунд.
        self.ворота_распознавателя = None
        # Такие же ворота для обычного ответа собеседника. Нужны одной проверке: живая строка
        # разбора снимается из ленты, и в этот миг ниже неё обязан идти ЧУЖОЙ обмен со своей
        # живой строкой ожидания — он помнит её номер и обновляет заменой среза. Без ворот
        # подставной собеседник успевает ответить раньше, и самое опасное совпадение сценарий
        # не воспроизводит вовсе.
        self.ворота_собеседника = None

    async def stream_chat(self, model, messages, params=None):
        params = dict(params or {})
        self.calls.append({"model": model, "messages": messages, "params": params})
        системная = messages[0]["content"] if messages else ""
        if системная == recognizer.ИНСТРУКЦИЯ:
            ворота = self.ворота_распознавателя
            if ворота is not None:
                await ворота.wait()
            текст = (
                self.ответы_распознавателя.pop(0)
                if self.ответы_распознавателя
                else ОТВЕТ_НЕ_ЗАПИСЬ
            )
        elif params.get("response_format"):
            # Второй ходок с объектом JSON — шаг интервью о папке. Ответ ему нужен разбираемый,
            # иначе обряд обрывается на первом же шаге и проверять в нём нечего.
            текст = ВОПРОС_ИНТЕРВЬЮ
        else:
            ворота = self.ворота_собеседника
            if ворота is not None:
                await ворота.wait()
            текст = "ответ модели"
        yield api.StreamEvent("content", текст)
        yield api.StreamEvent("meta", finish_reason="stop", usage={"prompt_tokens": 5, "completion_tokens": 2})

    async def list_models(self):
        return list(api.FALLBACK_MODELS)

    async def aclose(self):
        pass


def запросы_распознавателя(fake):
    return [
        обращение
        for обращение in fake.calls
        if обращение["messages"] and обращение["messages"][0]["content"] == recognizer.ИНСТРУКЦИЯ
    ]


def лента_экрана(screen):
    """Лента произвольного экрана — проверкам нужно видеть и НЕ главный."""
    return "".join(ф[1] for ф in screen.first.log)


