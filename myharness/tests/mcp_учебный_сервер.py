"""Учебный сервер MCP для проверок: местный, по stdio, без сети.

Проверки клиента `mcp_client` нуждаются в настоящем сервере по ту сторону протокола — подделка
ответов проверила бы подделку, а не согласование версий и разбор списка инструментов. Сервер
запускается проверкой как `sys.executable` + путь к этому файлу, поэтому работает в том же
окружении, где стоит библиотека `mcp`.

Имена инструментов латиницей: имя с кириллицей нарушает SEP-986, и библиотека жалуется на него
в поток ошибок. Описание `add` — из двух строк нарочно: команда показывает только первую, а
клиент обязан отдать описание целиком.

Режим `--молчать <файл>`: процесс записывает свой номер в файл и спит, не читая ввода и не
отвечая. Так проверяется предел опроса: без него зависший сервер вешал бы опрос навсегда, а
номер процесса позволяет убедиться, что по истечении предела процесс убран.
"""

import os
import sys
import time

from mcp.server.mcpserver import MCPServer

srv = MCPServer("учебный")


@srv.tool()
def add(a: int, b: int) -> int:
    """Складывает два целых числа.

    Вторая строка описания: её показ не выводит, но клиент хранит полностью."""
    return a + b


@srv.tool()
def echo(text: str) -> str:
    """Возвращает текст без изменений."""
    return text


if __name__ == "__main__":
    if len(sys.argv) == 3 and sys.argv[1] == "--молчать":
        with open(sys.argv[2], "w", encoding="utf-8") as f:
            f.write(str(os.getpid()))
        while True:
            time.sleep(3600)
    srv.run()
