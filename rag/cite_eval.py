"""Отчёт дня 24: источники, цитаты и режим «не знаю» по журналу наряда `myharness`.

Наряд — по заданию на вопрос, имя `<набор><NN>-<режим>`: `q` — 10 вопросов `rag/answers.jsonl`,
`n` — вопросы `rag/negative.jsonl` (про проект, но ответа в базе нет), `f` — далёкие от темы
вопросы `rag/far.jsonl`. Из `n` и `f` в отчёт идут только задания, бывшие в наряде.

По вопросу набора `q` — три пункта условия дня:

- **источники есть** — раздел «Источники» непуст, и каждая строка годна: номер в пределах
  найденного и `chunk_id` тот, что у куска с этим номером;
- **цитаты есть** — раздел «Цитаты» непуст, и каждая цитата дословно стоит в куске со своим
  номером (сверка — `cite.py`, прощаются только пробельные символы);
- **смысл совпадает** — вердикт судьи: отдельный запрос к DeepSeek получает вопрос, раздел
  «Ответ» и одни только дословные цитаты и отвечает «следует», «частично» либо «не следует».
  Пункт условия — «совпадает ли смысл ответа с цитатами» — это «следует» и «частично» вместе:
  ответ с цитатами не расходится. «Частично» значит, что под какую-то подробность ответа цитата
  не приведена; это более строгая мера сверх условия, и отчёт называет её отдельным числом.

Сверх условия — доля фактов (`eval.доля_фактов`, для связи с днями 22–23) и ложный отказ.

По вопросу наборов `n` и `f` — режим «не знаю»: ответ начинается словами «Не знаю», содержит
просьбу уточнить (вопросительный знак либо слово от «уточнить»), и какой слой дал отказ: **порог** (в блоке найденного ноль кусков — сервер
отсёк всё ниже порога) либо **модель** (куски были, ответа в них нет).

Задание, в отправленном сообщении которого нет ни кусков, ни строки пустого итога сервера,
помечается «поиск не состоялся» и в меры не идёт (то же правило, что в `eval.py`): ответ без
базы, засчитанный верным отказом либо провалом формата, врал бы в обе стороны.

Вердикты судьи пишутся файлом `--verdicts` и берутся из него, пока ответ задания тот же
(`sha256`): отчёт пересобирается без повторной оплаты.

Запуск: `uv run --project rag rag/cite_eval.py --journal <журнал> --run <run_id> [--run <повтор>]
--verdicts <файл.json> --out <файл.md>`.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import sys
from pathlib import Path
from typing import Callable

import cite
import eval as оценка
import rewrite as пер

КОРЕНЬ = Path(__file__).resolve().parent.parent
ДАЛЁКИЕ = КОРЕНЬ / "rag" / "far.jsonl"
МОДЕЛЬ_СУДЬИ = "deepseek-v4-pro"
ВЕРДИКТЫ = ("следует", "частично", "не следует")
НЕТ_ЦИТАТ = "нет цитат"
_ПРИМЕР = json.dumps({"вердикт": "частично", "довод": "срок в 30 секунд цитатами не подтверждён"}, ensure_ascii=False)
# Слово «JSON» и пример стоят в инструкции обязательно: без них DeepSeek отклоняет `json_object`.
ИНСТРУКЦИЯ_СУДЬИ = f"""Ты — проверяющий. Тебе даны вопрос человека, ОТВЕТ ассистента и ЦИТАТЫ из документов, на которые ассистент сослался. Реши, следует ли ОТВЕТ из ЦИТАТ. Суди только по цитатам: своих знаний о предмете не привлекай.

«следует» — каждое утверждение ответа по существу вопроса подтверждено цитатами.
«частично» — часть утверждений подтверждена, часть опоры в цитатах не имеет.
«не следует» — ответ противоречит цитатам либо на них не опирается.
Утверждение о том, что чего-то в найденных документах нет, опоры в цитатах не требует.

Верни JSON-объект ровно с двумя ключами: «вердикт» — одно из трёх: «следует», «частично», «не следует»; «довод» — одна короткая строка.
Пример: {_ПРИМЕР}"""

Спросить = Callable[[dict], str]


def судить(вопрос: str, ответ: str, цитаты: list[str], спросить: Спросить = пер.спросить) -> dict:
    """Вердикт судьи `{"вердикт", "довод"}`; ответ судьи не того вида — `ValueError`."""
    вход = f"Вопрос:\n{вопрос}\n\nОТВЕТ:\n{ответ}\n\nЦИТАТЫ:\n" + "\n".join(f"- «{ц}»" for ц in цитаты)
    # Рассуждения — умолчание API (включены): вердикт о следовании требует сопоставления.
    тело = {"model": МОДЕЛЬ_СУДЬИ, "response_format": {"type": "json_object"},
            "messages": [{"role": "system", "content": ИНСТРУКЦИЯ_СУДЬИ}, {"role": "user", "content": вход}]}
    сырой = спросить(тело)
    try:
        данные = json.loads(сырой)
    except ValueError:
        raise ValueError(f"судья вернул не JSON: {сырой[:200]!r}") from None
    вердикт = данные.get("вердикт") if isinstance(данные, dict) else None
    if вердикт not in ВЕРДИКТЫ:
        raise ValueError(f"судья вернул вердикт не из {ВЕРДИКТЫ}: {сырой[:200]!r}")
    return {"вердикт": вердикт, "довод": " ".join(str(данные.get("довод") or "").split())}


class Вердикты:
    """Файл вердиктов: имя задания → `{"sha", "вердикт", "довод"}`; судья зовётся раз на ответ."""

    def __init__(self, путь: Path, спросить: Спросить = пер.спросить) -> None:
        self._путь = путь
        self._спросить = спросить
        self._данные: dict[str, dict] = json.loads(путь.read_text("utf-8")) if путь.is_file() else {}

    def вердикт(self, имя: str, вопрос: str, ответ: str, цитаты: list[str]) -> dict:
        # Отпечаток — весь вход судьи: инструкция, вопрос, ответ и дословные цитаты. Сменилось
        # любое из четырёх — прежний вердикт вынесен о другом.
        отпечаток = hashlib.sha256(json.dumps([ИНСТРУКЦИЯ_СУДЬИ, вопрос, ответ, цитаты], ensure_ascii=False).encode()).hexdigest()
        прежний = self._данные.get(имя)
        if прежний and прежний.get("sha") == отпечаток:
            return прежний
        self._данные[имя] = {"sha": отпечаток, **судить(вопрос, ответ, цитаты, self._спросить)}
        временный = self._путь.with_name(self._путь.name + ".tmp")
        временный.write_text(json.dumps(self._данные, ensure_ascii=False, indent=1) + "\n", "utf-8")
        os.replace(временный, self._путь)
        return self._данные[имя]


def оценить(набор: str, вопросы: list[dict], записи: dict, режим: str, вердикты: Вердикты | None) -> list[dict]:
    """По вопросу набора, у которого есть запись режима: разбор ответа, сверка, для `q` — судья."""
    итог = []
    for вопрос in вопросы:
        запись = записи.get((набор, вопрос["n"], режим))
        if запись is None:
            continue
        имя = f"{набор}{вопрос['n']:02d}"
        ответ = запись.get("response") or ""
        отправленное = (запись.get("messages") or [{}])[-1].get("content") or ""
        куски = cite.найденное(отправленное, вопрос["вопрос"])
        # Порог — только по строке пустого итога сервера: «заголовков не разобрано» без неё —
        # это сломанный формат либо несостоявшийся поиск, а не отсечение.
        порог = куски == [] and cite.ПУСТО in отправленное
        разбор = cite.разобрать(ответ)
        источники = [cite.источник_годен(с, куски or []) for с in разбор.источники]
        цитаты = [cite.цитата_дословна(ц, куски or []) for ц in разбор.цитаты]
        строка = {
            "имя": имя, "вопрос": вопрос, "ответ": ответ, "разбор": разбор,
            "поиск_был": bool(куски) or порог, "кусков": len(куски or []),
            "источники": источники, "цитаты": цитаты,
            "источники_есть": bool(источники) and all(источники),
            "цитаты_есть": bool(цитаты) and all(цитаты),
            "слой": "порог" if порог else "модель",
            "факты": оценка.доля_фактов(ответ, вопрос.get("факты") or []),
            "вердикт": None,
        }
        if набор == "q" and вердикты is not None and not разбор.отказ and строка["поиск_был"]:
            дословные = [ц.текст for ц, годна in zip(разбор.цитаты, цитаты) if годна]
            строка["вердикт"] = (вердикты.вердикт(f"{имя}-{режим}", вопрос["вопрос"], разбор.ответ, дословные)
                                 if дословные else {"вердикт": НЕТ_ЦИТАТ, "довод": "дословных цитат в ответе нет"})
        итог.append(строка)
    return итог


def _да(условие: bool) -> str:
    return "да" if условие else "**нет**"


def _цитатой(текст: str) -> str:
    return "> " + текст.strip().replace("\n", "\n> ")


def отчёт(основные: list[dict], без_ответа: list[dict], режим: str, run_id: str) -> str:
    пропуски = [с["имя"] for с in основные + без_ответа if not с["поиск_был"]]
    все_основные, все_без_ответа = основные, без_ответа
    основные = [с for с in основные if с["поиск_был"]]
    без_ответа = [с for с in без_ответа if с["поиск_был"]]
    всего = len(основные)
    цитат = [г for с in основные for г in с["цитаты"]]
    следует = sum((с["вердикт"] or {}).get("вердикт") == "следует" for с in основные)
    частично = sum((с["вердикт"] or {}).get("вердикт") == "частично" for с in основные)
    не_следует = sum((с["вердикт"] or {}).get("вердикт") == "не следует" for с in основные)
    ложных = sum(с["разбор"].отказ for с in основные)
    с_фактами = [с["факты"] for с in основные if с["факты"] is not None]
    отказов = [с for с in без_ответа if с["разбор"].отказ]
    строки = [
        "# Проверка: источники, цитаты и режим «не знаю»\n",
        f"Наряд `run_id` = `{run_id}`, режим `{режим}`. Судья смысла — `{МОДЕЛЬ_СУДЬИ}`.\n",
        "## Итог\n",
        f"Основных вопросов — {всего}:\n",
        f"- **источники есть: {sum(с['источники_есть'] for с in основные)} из {всего}** — раздел непуст, каждый `chunk_id` был в найденном;",
        f"- **цитаты есть: {sum(с['цитаты_есть'] for с in основные)} из {всего}** — раздел непуст, каждая цитата дословна;",
        f"- все цитаты дословны: {sum(цитат)} из {len(цитат)} цитат;",
        f"- **смысл ответа совпадает с цитатами: {следует + частично} из {всего}** — судья не нашёл расхождения "
        f"(вердикт «не следует» — {не_следует});",
        f"- сверх условия — каждая подробность ответа покрыта цитатой: {следует} из {всего} "
        f"(«частично», подробность без цитаты — {частично});",
        f"- ложных отказов: {ложных} из {всего};",
        f"- доля фактов (мера дней 22–23): {оценка._доля(sum(с_фактами) / len(с_фактами) if с_фактами else None)}.\n",
    ]
    if без_ответа:
        строки += [
            f"Вопросов без ответа в базе — {len(без_ответа)}:\n",
            f"- **«Не знаю»: {len(отказов)} из {len(без_ответа)}**, из них порогом — "
            f"{sum(с['слой'] == 'порог' for с in отказов)}, моделью — {sum(с['слой'] == 'модель' for с in отказов)};",
            f"- с просьбой уточнить: {sum(с['разбор'].уточнение for с in отказов)} из {len(отказов)}.\n",
        ]
    if пропуски:
        строки.append(f"**Поиск не состоялся** в {', '.join(пропуски)} — ни кусков, ни строки пустого итога в запросе нет; "
                      "в меры эти задания не вошли.\n")

    строки += ["## Основные вопросы\n",
               "| # | вопрос | источники: годных из названных | цитаты: дословных из приведённых | смысл | факты |",
               "|---|---|---|---|---|---|"]
    for с in все_основные:
        if not с["поиск_был"]:
            строки.append(f"| {с['имя']} | {с['вопрос']['вопрос']} | поиск не состоялся | — | — | — |")
            continue
        смысл = "отказ" if с["разбор"].отказ else (с["вердикт"] or {}).get("вердикт", "—")
        строки.append(f"| {с['имя']} | {с['вопрос']['вопрос']} | {sum(с['источники'])} из {len(с['источники'])} | "
                      f"{sum(с['цитаты'])} из {len(с['цитаты'])} | {смысл} | {оценка._доля(с['факты'])} |")
    if все_без_ответа:
        строки += ["", "## Вопросы без ответа в базе\n", "| # | вопрос | «Не знаю» | просит уточнить | слой | кусков найдено |",
                   "|---|---|---|---|---|---|"]
        for с in все_без_ответа:
            if not с["поиск_был"]:
                строки.append(f"| {с['имя']} | {с['вопрос']['вопрос']} | поиск не состоялся | — | — | — |")
                continue
            строки.append(f"| {с['имя']} | {с['вопрос']['вопрос']} | {_да(с['разбор'].отказ)} | {_да(с['разбор'].уточнение)} | "
                          f"{с['слой']} | {с['кусков']} |")

    строки.append("\n## Ответы\n")
    for с in все_основные + все_без_ответа:
        строки.append(f"### {с['имя']}. {с['вопрос']['вопрос']}\n")
        строки.append(_цитатой(с["ответ"]) + "\n")
        if not с["поиск_был"]:
            строки.append("- поиск не состоялся: ответ дан без базы, в меры не вошёл")
        elif с["имя"].startswith("q"):
            for ссылка, годна in zip(с["разбор"].источники, с["источники"]):
                строки.append(f"- {'✓' if годна else '✗'} источник [{ссылка.номер}] `{ссылка.chunk_id}`")
            for цитата, годна in zip(с["разбор"].цитаты, с["цитаты"]):
                строки.append(f"- {'✓ дословна' if годна else '✗ в куске не найдена'}: цитата [{цитата.номер}] "
                              f"«{' '.join(цитата.текст.split())[:80]}…»")
            if с["вердикт"]:
                строки.append(f"- судья: **{с['вердикт']['вердикт']}** — {с['вердикт']['довод']}")
        else:
            строки.append(f"- «Не знаю»: {_да(с['разбор'].отказ)}; просит уточнить: {_да(с['разбор'].уточнение)}; "
                          f"слой — {с['слой']} (кусков найдено: {с['кусков']})")
        строки.append("")
    return "\n".join(строки) + "\n"


def главная(argv: list[str] | None = None) -> None:
    разбор = argparse.ArgumentParser(prog="cite_eval", description="Отчёт дня 24 по журналу наряда")
    разбор.add_argument("--journal", type=Path, required=True)
    разбор.add_argument("--run", required=True, action="append",
                        help="run_id наряда; повтор упавших заданий — ещё один --run, он старше прежнего")
    разбор.add_argument("--mode", default="cite", help="режим из имени задания <набор><NN>-<режим>")
    разбор.add_argument("--verdicts", type=Path, required=True, help="файл вердиктов судьи (заводится)")
    разбор.add_argument("--answers", type=Path, default=оценка.НАБОР)
    разбор.add_argument("--negative", type=Path, default=оценка.ОТРИЦАТЕЛЬНЫЕ)
    разбор.add_argument("--far", type=Path, default=ДАЛЁКИЕ)
    разбор.add_argument("--out", type=Path)
    доводы = разбор.parse_args(argv)
    записи, _ = оценка.загрузить(доводы.journal, доводы.run)
    вердикты = Вердикты(доводы.verdicts)
    try:
        основные = оценить("q", оценка._читать(доводы.answers), записи, доводы.mode, вердикты)
    except (пер.ОшибкаПереписывания, ValueError) as exc:
        sys.exit(f"cite_eval: судья не ответил: {exc}")
    if not основные:
        sys.exit(f"cite_eval: в {доводы.journal} нет удачных записей нарядов {', '.join(доводы.run)} с именами q<NN>-{доводы.mode}")
    без_ответа = (оценить("n", оценка._читать(доводы.negative), записи, доводы.mode, None)
                  + оценить("f", оценка._читать(доводы.far), записи, доводы.mode, None))
    текст = отчёт(основные, без_ответа, доводы.mode, ", ".join(доводы.run))
    if доводы.out:
        доводы.out.write_text(текст, "utf-8")
        print(f"записано: {доводы.out}")
    else:
        print(текст)


if __name__ == "__main__":
    главная()
