"""Сравнение ответов по режимам поиска по журналу наряда `myharness`.

Наряд — по заданию на вопрос и режим, все с одним `run_id`. Имя задания `q<NN>-<режим>` —
вопрос контрольного набора `rag/answers.jsonl` (`n`, `вопрос`, `ожидание`, `факты`,
`источники`), `n<NN>-<режим>` — отрицательный вопрос `rag/negative.jsonl`, ответа на который в
базе нет. Режимы берутся из журнала в порядке первой встречи; `plain` — режим без поиска, все
прочие — с поиском. Наряд дня 22 (`q<NN>-plain|rag`) — частный случай.

Мера по вопросу и режиму:

- **факты** — доля строк `факты`, найденных в ответе подстрокой; сравнение без учёта регистра и
  без пробелов (`30 000` и `30000` — одно число);
- **источник найден** (только RAG) — хоть один путь из `источники` стоит в строках `[n] <путь> ›`
  блока найденного в отправленном последнем сообщении (формат — договор `server.py`);
- **источник назван** — хоть один путь из `источники` назван в тексте ответа, либо в ответе стоит
  ссылка `[n]` на найденный кусок с таким путём (инструкция профиля просит ссылаться номерами);
- **отказ** — ответ начинается словами «В базе нет ответа» (без учёта регистра и знаков): на
  отрицательном вопросе это верный отказ, на вопросе контрольного набора — ложный.

Задание режима с поиском, в отправленном сообщении которого нет блока найденного, помечается
«поиск не состоялся» и в меры режима не идёт: ответ без базы, засчитанный режиму с поиском, врал
бы в его пользу или против.

Запуск: `uv run --project rag rag/eval.py --journal <журнал> --run <run_id> [--run <повтор>] --out <файл.md>`.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
НАБОР = КОРЕНЬ / "rag" / "answers.jsonl"
ОТРИЦАТЕЛЬНЫЕ = КОРЕНЬ / "rag" / "negative.jsonl"
ЗАГОЛОВОК_НАЙДЕННОГО = "Найдено в базе знаний по вопросу:"  # myharness.agent.ЗАГОЛОВОК_НАЙДЕННОГО
БЕЗ_ПОИСКА = "plain"
ОТКАЗ = "в базе нет ответа"


def _сжать(текст: str) -> str:
    return re.sub(r"\s+", "", текст).casefold()


def доля_фактов(ответ: str, факты: list[str]) -> float | None:
    if not факты:
        return None
    сжатый = _сжать(ответ)
    return sum(_сжать(ф) in сжатый for ф in факты) / len(факты)


def отказ(ответ: str) -> bool:
    return " ".join(re.findall(r"\w+", ответ.casefold())).startswith(ОТКАЗ)


def найденные_источники(отправленное: str) -> list[str] | None:
    """Пути кусков блока найденного по порядку номеров; `None` — блока нет, поиска не было."""
    if not отправленное.startswith(ЗАГОЛОВОК_НАЙДЕННОГО):
        return None
    # Заголовки ищутся ПО ПОРЯДКУ номеров, каждый — после пустой строки и с близостью в конце:
    # в тексте самих кусков бывают строки того же вида (пример формата в плане дня 22), и
    # поиск по всему блоку засчитал бы их найденными источниками и сбил бы номера ссылок `[n]`.
    пути: list[str] = []
    место = 0
    while True:
        заголовок = re.compile(rf"(?:\A|\n\n)\[{len(пути) + 1}\] (.+?) › [^\n]*\(-?\d+\.\d{{3}}\)$", re.M)
        совпало = заголовок.search(отправленное, место)
        if совпало is None:
            return пути
        пути.append(совпало[1])
        место = совпало.end()


def назван(ответ: str, источники: list[str], найдено: list[str]) -> bool:
    """Путь источника в ответе либо ссылка `[n]` на найденный кусок с этим путём."""
    if any(и in ответ for и in источники):
        return True
    номера = {int(н) for н in re.findall(r"\[(\d+)\]", ответ)}
    return any(1 <= н <= len(найдено) and найдено[н - 1] in источники for н in номера)


def загрузить(журнал: Path, run_ids: list[str]) -> tuple[dict[tuple[str, int, str], dict], list[str]]:
    """Записи нарядов по ключу (набор `q`|`n`|`f`, номер, режим) и режимы в порядке первой встречи.

    Набор `f` — далёкие от темы вопросы `rag/far.jsonl` дня 24; их читает `cite_eval.py`.

    Задание со сбоем (`status` не `ok`) ответом не считается. Нарядов несколько, когда упавшие
    задания повторены отдельно: у задания берётся запись наряда, названного в `run_ids` позже.
    """
    записи: dict[tuple[str, int, str], dict] = {}
    режимы: list[str] = []
    for строка in журнал.read_text("utf-8").splitlines():
        if not строка.strip():
            continue
        запись = json.loads(строка)
        совпало = re.fullmatch(r"([qnf])(\d+)-([\w+]+)", запись.get("agent") or "")
        if запись.get("run_id") not in run_ids or not совпало or запись.get("status") != "ok":
            continue
        if совпало[3] not in режимы:
            режимы.append(совпало[3])
        ключ = (совпало[1], int(совпало[2]), совпало[3])
        прежняя = записи.get(ключ)
        if прежняя is None or run_ids.index(запись["run_id"]) >= run_ids.index(прежняя["run_id"]):
            записи[ключ] = запись
    return записи, режимы


def оценить(набор: str, вопросы: list[dict], записи: dict, режимы: list[str]) -> list[dict]:
    """По вопросу набора `q` либо `n` — данные каждого режима; `None`, если записи нет."""
    итог = []
    for вопрос in вопросы:
        строка: dict = {"вопрос": вопрос, "режимы": {}}
        источники = вопрос.get("источники") or []
        for режим in режимы:
            запись = записи.get((набор, вопрос["n"], режим))
            if запись is None:
                строка["режимы"][режим] = None
                continue
            ответ = запись.get("response") or ""
            отправленное = (запись.get("messages") or [{}])[-1].get("content") or ""
            найдено = None if режим == БЕЗ_ПОИСКА else найденные_источники(отправленное)
            строка["режимы"][режим] = {
                "ответ": ответ,
                "факты": доля_фактов(ответ, вопрос.get("факты") or []),
                "поиск_был": режим == БЕЗ_ПОИСКА or найдено is not None,
                "найдено": найдено or [],
                "источник_найден": bool(set(источники) & set(найдено or [])) if источники and режим != БЕЗ_ПОИСКА else None,
                "источник_назван": назван(ответ, источники, найдено or []) if источники else None,
                "отказ": отказ(ответ),
                "токены": (запись.get("usage") or {}).get("total_tokens"),
            }
        итог.append(строка)
    return итог


def _доля(значение: float | None) -> str:
    return "—" if значение is None else f"{значение:.2f}"


def _среднее(значения: list[float]) -> float | None:
    return sum(значения) / len(значения) if значения else None


def меры(режим: str, обычные: list[dict], отрицательные: list[dict]) -> dict:
    """Меры режима по заданиям, где поиск состоялся; без записи или без поиска — в `пропущено`."""
    о = [с["режимы"][режим] for с in обычные if с["режимы"].get(режим) and с["режимы"][режим]["поиск_был"]]
    н = [с["режимы"][режим] for с in отрицательные if с["режимы"].get(режим) and с["режимы"][режим]["поиск_был"]]
    пропущено = [f"q{с['вопрос']['n']:02d}" for с in обычные if с["режимы"].get(режим) and not с["режимы"][режим]["поиск_был"]]
    пропущено += [f"n{с['вопрос']['n']:02d}" for с in отрицательные if с["режимы"].get(режим) and not с["режимы"][режим]["поиск_был"]]
    без_записи = [f"q{с['вопрос']['n']:02d}" for с in обычные if с["режимы"].get(режим) is None]
    без_записи += [f"n{с['вопрос']['n']:02d}" for с in отрицательные if с["режимы"].get(режим) is None]
    с_фактами = [д["факты"] for д in о if д["факты"] is not None]
    найден = [д["источник_найден"] for д in о if д["источник_найден"] is not None]
    токены = [д["токены"] for д in о + н if д["токены"] is not None]
    return {
        "факты": _среднее(с_фактами),
        "полных": sum(ф == 1 for ф in с_фактами), "с_фактами": len(с_фактами),
        "найден": sum(найден), "с_источниками": len(найден),
        "верных_отказов": sum(д["отказ"] for д in н), "отрицательных": len(н),
        "ложных_отказов": sum(д["отказ"] for д in о), "обычных": len(о),
        "токены": _среднее(токены),
        "пропущено": пропущено,
        "без_записи": без_записи,
    }


def отчёт(обычные: list[dict], отрицательные: list[dict], режимы: list[str], run_id: str) -> str:
    строки = ["# Сравнение ответов по режимам\n", f"Наряд `run_id` = `{run_id}`. Режим `{БЕЗ_ПОИСКА}` — без поиска.\n",
              "| режим | доля фактов | полных ответов | источник найден | верных отказов | ложных отказов | токенов в среднем |",
              "|---|---|---|---|---|---|---|"]
    пропуски = []
    for режим in режимы:
        м = меры(режим, обычные, отрицательные)
        найден = "—" if режим == БЕЗ_ПОИСКА or not м["с_источниками"] else f"{м['найден']} из {м['с_источниками']}"
        токены = "—" if м["токены"] is None else f"{м['токены']:.0f}"
        верных = f"{м['верных_отказов']} из {м['отрицательных']}" if м["отрицательных"] else "—"
        строки.append(f"| {режим} | {_доля(м['факты'])} | {м['полных']} из {м['с_фактами']} | {найден} | "
                      f"{верных} | {м['ложных_отказов']} из {м['обычных']} | {токены} |")
        if м["пропущено"]:
            пропуски.append(f"- `{режим}`: **поиск не состоялся** в {', '.join(м['пропущено'])} — в меры режима не вошли")
        if м["без_записи"]:
            пропуски.append(f"- `{режим}`: **нет удачной записи** для {', '.join(м['без_записи'])} — в меры режима не вошли")
    строки.append("")
    строки += пропуски
    строки += ["", "## Доля фактов по вопросам\n", "| # | вопрос | " + " | ".join(режимы) + " |",
               "|---|---|" + "---|" * len(режимы)]
    for с in обычные:
        клетки = []
        for режим in режимы:
            д = с["режимы"][режим]
            клетка = "нет записи" if д is None else "поиск не состоялся" if not д["поиск_был"] else _доля(д["факты"])
            клетки.append(клетка + (" · отказ" if д and д["отказ"] else ""))
        строки.append(f"| q{с['вопрос']['n']:02d} | {с['вопрос']['вопрос']} | " + " | ".join(клетки) + " |")
    if отрицательные:
        строки += ["", "## Отрицательные вопросы\n", "| # | вопрос | " + " | ".join(режимы) + " |",
                   "|---|---|" + "---|" * len(режимы)]
        for с in отрицательные:
            клетки = []
            for режим in режимы:
                д = с["режимы"][режим]
                клетки.append("нет записи" if д is None else "поиск не состоялся" if not д["поиск_был"]
                              else "отказ" if д["отказ"] else "**ответил**")
            строки.append(f"| n{с['вопрос']['n']:02d} | {с['вопрос']['вопрос']} | " + " | ".join(клетки) + " |")
    строки.append("\n## Ответы\n")
    for метка, набор in (("q", обычные), ("n", отрицательные)):
        for с in набор:
            в = с["вопрос"]
            строки.append(f"### {метка}{в['n']:02d}. {в['вопрос']}\n")
            if метка == "q":
                строки.append(f"**Ожидание:** {в['ожидание']}  ")
                строки.append(f"**Факты:** {', '.join(f'`{ф}`' for ф in в['факты']) or '—'}  ")
                строки.append(f"**Источники:** {', '.join(f'`{и}`' for и in в['источники']) or '— (не применимо)'}\n")
            else:
                строки.append("**Ожидание:** ответа в базе нет — верен отказ.\n")
            for режим in режимы:
                д = с["режимы"][режим]
                if д is None:
                    строки.append(f"**{режим}:** записи в журнале нет\n")
                    continue
                подробно = [f"факты {_доля(д['факты'])}"] if метка == "q" else []
                if режим != БЕЗ_ПОИСКА:
                    подробно.append("найдено: " + (", ".join(f"`{п}`" for п in д["найдено"]) or "ничего") if д["поиск_был"]
                                    else "поиск не состоялся")
                if д["отказ"]:
                    подробно.append("отказ")
                строки.append(f"**{режим}**" + (f" ({'; '.join(подробно)})" if подробно else "") + ":\n")
                строки.append("> " + д["ответ"].strip().replace("\n", "\n> ") + "\n")
    return "\n".join(строки) + "\n"


def _читать(путь: Path) -> list[dict]:
    return [json.loads(с) for с in путь.read_text("utf-8").splitlines() if с.strip()]


def главная(argv: list[str] | None = None) -> None:
    разбор = argparse.ArgumentParser(prog="eval", description="Сравнение ответов по режимам поиска по журналу наряда")
    разбор.add_argument("--journal", type=Path, required=True)
    разбор.add_argument("--run", required=True, action="append",
                        help="run_id наряда; повтор упавших заданий — ещё один --run, он старше прежнего")
    разбор.add_argument("--answers", type=Path, default=НАБОР)
    разбор.add_argument("--negative", type=Path, default=ОТРИЦАТЕЛЬНЫЕ)
    разбор.add_argument("--out", type=Path)
    доводы = разбор.parse_args(argv)
    записи, режимы = загрузить(доводы.journal, доводы.run)
    if not записи:
        sys.exit(f"eval: в {доводы.journal} нет удачных записей нарядов {', '.join(доводы.run)} с именами q<NN>-<режим>|n<NN>-<режим>")
    обычные = оценить("q", _читать(доводы.answers), записи, режимы)
    # Отрицательные — только те, что были в наряде: в наряд идёт одна часть набора.
    отрицательные = [с for с in оценить("n", _читать(доводы.negative), записи, режимы) if any(с["режимы"].values())]
    текст = отчёт(обычные, отрицательные, режимы, ", ".join(доводы.run))
    if доводы.out:
        доводы.out.write_text(текст, "utf-8")
        print(f"записано: {доводы.out}")
    else:
        print(текст)


if __name__ == "__main__":
    главная()
