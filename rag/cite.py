"""Сверка источников и цитат ответа с тем, что было найдено на этот вопрос.

Ответ режима с цитатами (инструкция профиля дня 24) — три раздела:

    ## Ответ
    <текст>

    ## Источники
    - [1] <путь> › <раздел> · <chunk_id>

    ## Цитаты
    - [1] «<дословный отрывок куска 1>»

Отказ — ответ без разделов, начинающийся словами «Не знаю», с уточняющим вопросом человеку.

Образец — Citations в Claude API: там цитату достаёт программа по указателю модели, и выдуманной
цитаты не бывает по построению. Здесь модель набирает цитату сама, поэтому то же свойство
берётся сверкой: цитата засчитывается, только если дословно стоит в тексте куска с её номером, а
источник — только если его `chunk_id` совпал с `chunk_id` куска с его номером. Куски берутся из
блока найденного того же запроса (формат строки — договор `server.py`), а не из индекса: судим по
тому, что модель действительно видела.

Сети модуль не знает, на диск не ходит; кривой ответ даёт пустые разделы, а не исключение.
"""

from __future__ import annotations

import re
from dataclasses import dataclass

ЗАГОЛОВОК_НАЙДЕННОГО = "Найдено в базе знаний по вопросу:"  # myharness.agent.ЗАГОЛОВОК_НАЙДЕННОГО
ПУСТО = "В базе не нашлось достаточно близкого"  # начало строки пустого итога `server.найти_текст`
ОТКАЗ = "не знаю"

_РАЗДЕЛ = re.compile(r"^#{1,6}\s*(ответ|источники|цитаты)\s*:?\s*$", re.I | re.M)
_ПУНКТ = re.compile(r"^\s*[-*]\s*\[(\d+)\]\s*", re.M)
_КАВЫЧКИ = (("«", "»"), ('"', '"'), ("“", "”"))


@dataclass(frozen=True)
class Найденное:
    """Один кусок блока найденного."""
    номер: int
    источник: str
    раздел: str
    chunk_id: str
    текст: str


@dataclass(frozen=True)
class Ссылка:
    """Строка раздела «Источники»."""
    номер: int | None
    chunk_id: str | None
    строка: str


@dataclass(frozen=True)
class Цитата:
    """Пункт раздела «Цитаты»; текст — без внешних кавычек, переносы строк сохранены."""
    номер: int | None
    текст: str


@dataclass(frozen=True)
class Разбор:
    ответ: str  # текст раздела «Ответ»; без такого раздела — текст до первого раздела
    источники: list[Ссылка]
    цитаты: list[Цитата]
    отказ: bool  # ответ начинается словами «Не знаю» (без учёта регистра и знаков)
    уточнение: bool  # в ответе есть вопросительный знак либо слово от «уточнить» («уточните, что…»)


def _сжать(текст: str) -> str:
    """Любая последовательность пробельных символов — один пробел; больше ничего не прощается."""
    return " ".join(текст.split())


def найденное(отправленное: str, вопрос: str) -> list[Найденное] | None:
    """Куски блока найденного по порядку номеров.

    `None` — блока нет (поиск не состоялся), `[]` — блок есть, кусков ноль (сработал порог).
    """
    if not отправленное.startswith(ЗАГОЛОВОК_НАЙДЕННОГО):
        return None
    хвост = "\n\n" + вопрос
    тело = отправленное[: -len(хвост)] if вопрос and отправленное.endswith(хвост) else отправленное
    # Заголовки ищутся ПО ПОРЯДКУ номеров, каждый после пустой строки и со счётом в конце: в
    # тексте самих кусков бывают строки того же вида (пример формата в планах дней 22–24).
    заголовки: list[re.Match[str]] = []
    место = 0
    while True:
        образец = re.compile(rf"(?:\A|\n\n)\[{len(заголовки) + 1}\] (.+?) › (.*) · (\S+) \(-?\d+\.\d{{3}}\)$", re.M)
        совпало = образец.search(тело, место)
        if совпало is None:
            break
        заголовки.append(совпало)
        место = совпало.end()
    куски = []
    for номер, заголовок in enumerate(заголовки, 1):
        конец = заголовки[номер].start() if номер < len(заголовки) else len(тело)
        куски.append(Найденное(номер, заголовок[1], заголовок[2], заголовок[3], тело[заголовок.end():конец].strip()))
    return куски


def _без_кавычек(текст: str) -> str:
    текст = текст.strip()
    for левая, правая in _КАВЫЧКИ:
        if len(текст) >= 2 and текст.startswith(левая) and текст.endswith(правая):
            return текст[1:-1].strip()
    return текст


def разобрать(ответ: str) -> Разбор:
    разделы: dict[str, str] = {}
    заголовки = list(_РАЗДЕЛ.finditer(ответ))
    for и, заголовок in enumerate(заголовки):
        конец = заголовки[и + 1].start() if и + 1 < len(заголовки) else len(ответ)
        разделы.setdefault(заголовок[1].casefold(), ответ[заголовок.end():конец].strip())
    до_разделов = ответ[: заголовки[0].start()] if заголовки else ответ

    источники = []
    for строка in разделы.get("источники", "").splitlines():
        пункт = _ПУНКТ.match(строка)
        if пункт is None:
            continue
        остаток = строка[пункт.end():].strip()
        chunk_id = остаток.rsplit(" · ", 1)[1].strip() if " · " in остаток else None
        источники.append(Ссылка(int(пункт[1]), chunk_id or None, строка.strip()))

    # Цитата может занимать несколько строк: модель копирует отрывок вместе с переносами. Пункт
    # тянется от своего `- [n]` до следующего такого начала строки либо до конца раздела.
    цитаты = []
    текст_цитат = разделы.get("цитаты", "")
    начала = list(_ПУНКТ.finditer(текст_цитат))
    for и, пункт in enumerate(начала):
        конец = начала[и + 1].start() if и + 1 < len(начала) else len(текст_цитат)
        цитаты.append(Цитата(int(пункт[1]), _без_кавычек(текст_цитат[пункт.end():конец])))

    слова = " ".join(re.findall(r"\w+", ответ.casefold()))
    return Разбор(разделы.get("ответ", до_разделов.strip()), источники, цитаты,
                  слова.startswith(ОТКАЗ), "?" in ответ or re.search(r"\bуточни", слова) is not None)


def _кусок(номер: int | None, куски: list[Найденное]) -> Найденное | None:
    return куски[номер - 1] if номер is not None and 1 <= номер <= len(куски) else None


def источник_годен(ссылка: Ссылка, куски: list[Найденное]) -> bool:
    """Номер в пределах найденного; путь и `chunk_id` строки — те, что у куска с этим номером."""
    кусок = _кусок(ссылка.номер, куски)
    # Путь — в начале строки, сразу за `- [n]`: искать его по всей строке нельзя, он же входит
    # в `chunk_id`, и выдуманный путь прошёл бы за счёт настоящего `chunk_id`.
    return (кусок is not None and ссылка.chunk_id == кусок.chunk_id
            and _ПУНКТ.sub("", ссылка.строка, count=1).startswith(кусок.источник + " ›"))


def цитата_дословна(цитата: Цитата, куски: list[Найденное]) -> bool:
    """Отрывок стоит в тексте куска с номером цитаты; прощаются только пробельные символы."""
    кусок = _кусок(цитата.номер, куски)
    отрывок = _сжать(цитата.текст)
    return кусок is not None and bool(отрывок) and отрывок in _сжать(кусок.текст)
