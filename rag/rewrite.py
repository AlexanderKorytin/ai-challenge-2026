"""Переписывание вопроса в поисковый запрос и разворот уточняющей реплики через DeepSeek.

Разговорный вопрос («что там с правами на настройки?») эмбеддинг и BM25 ловят хуже, чем
поисковый запрос с развёрнутыми сокращениями, синонимами и возможными именами. Переписывает
`deepseek-v4-flash` при `temperature` 0 без рассуждений: ответ — одна строка запроса.

В многоходовом разговоре реплика бывает непонятна без прошлого («а кто их открывает?»).
`развернуть` по контексту разговора — фактам и последним репликам — делает из неё самостоятельный
вопрос; дальше он идёт прежним путём, в том числе через `переписать`.

Ключ — поле `api_key` файла настроек `myharness`: `$MYHARNESS_CONFIG_DIR/config.json`, иначе
`~/.config/myharness/config.json`. Файл только читается — ключ остаётся в одном месте, копии не
заводятся. Ключ не попадает ни в текст исключений, ни в вывод. На диск модуль не пишет.
"""

from __future__ import annotations

import json
import os
import urllib.request
from pathlib import Path
from urllib.parse import urlsplit

import httpx2

МОДЕЛЬ = "deepseek-v4-flash"
АДРЕС_DEEPSEEK = "https://api.deepseek.com/chat/completions"
# Те же пределы, что у клиента DeepSeek в myharness (`api.REQUEST_TIMEOUT`); пакет `rag` от
# `myharness` не зависит, поэтому числа повторены, как в `mcp_servers/pipeline`.
ОЖИДАНИЕ = httpx2.Timeout(connect=20.0, read=600.0, write=20.0, pool=20.0)
# Сколько раз повторять НЕУДАВШУЮСЯ УСТАНОВКУ СОЕДИНЕНИЯ (и только её: запрос ещё не ушёл, двойной
# оплаты нет). Число — как у Claude Code, решение пользователя 2026-10-02 по замеру: 8 из 20
# новых соединений с DeepSeek не вставали, а этот модуль открывает соединение на каждый запрос.
# Паузу между попытками задаёт библиотека: 0, 0,5, 1, 2, 4 с и далее вдвое.
ПОВТОРОВ_СОЕДИНЕНИЯ = 10
ИНСТРУКЦИЯ = (
    "Ты переписываешь вопрос пользователя в поисковый запрос к базе знаний программного проекта: "
    "требования, дизайны, планы, рабочий договор. Разверни сокращения, добавь синонимы и "
    "возможные имена терминов, параметров, команд и файлов по-русски и по-английски. Не отвечай "
    "на вопрос и ничего не выдумывай о проекте. Ответь одной строкой — только запрос, без пояснений."
)
ИНСТРУКЦИЯ_РАЗВОРОТА = (
    "Тебе даны контекст разговора (зафиксированные факты и последние реплики) и последняя реплика "
    "человека. Перепиши последнюю реплику в самостоятельный вопрос, понятный без разговора: раскрой "
    "местоимения и отсылки («он», «их», «этот», «там», «второй»), подставь вместо зафиксированных "
    "терминов их определения. Если в реплике кроме вопроса есть сообщение о цели, термине или "
    "ограничении — оставь только вопрос. Реплику, понятную и без контекста, верни как есть. Не "
    "отвечай на вопрос и ничего не добавляй от себя. Ответь одной строкой — только вопрос."
)


class ОшибкаПереписывания(RuntimeError):
    pass


def путь_настроек() -> Path:
    каталог = os.environ.get("MYHARNESS_CONFIG_DIR")
    база = Path(каталог).expanduser() if каталог else Path.home() / ".config" / "myharness"
    return база / "config.json"


def _ключ() -> str:
    путь = путь_настроек()
    try:
        данные = json.loads(путь.read_text("utf-8"))
    except FileNotFoundError:
        raise ОшибкаПереписывания(f"нет ключа DeepSeek: файла {путь} нет") from None
    except (OSError, ValueError) as exc:
        raise ОшибкаПереписывания(f"файл настроек {путь} не читается: {type(exc).__name__}") from None
    ключ = данные.get("api_key") if isinstance(данные, dict) else None
    if not isinstance(ключ, str) or not ключ.strip():
        raise ОшибкаПереписывания(f"нет ключа DeepSeek: в {путь} нет поля api_key")
    return ключ.strip()


def посредник_из_окружения(адрес: str) -> str | None:
    """Посредник из окружения (и настроек системы) для этого адреса; `None` — идти напрямую.

    Клиент со СВОИМ транспортом посредника из окружения сам не читает: библиотека делает это
    только пока строит транспорт сама. Без этой функции запросы с ключом пошли бы мимо
    `HTTPS_PROXY` молча. То же сделано в `myharness.api`; пакет `rag` от него не зависит."""
    хост = urlsplit(адрес).hostname or ""
    if urllib.request.proxy_bypass(хост):
        return None
    посредники = urllib.request.getproxies()
    посредник = посредники.get(urlsplit(адрес).scheme) or посредники.get("all")
    if not посредник:
        return None
    return посредник if "://" in посредник else f"http://{посредник}"


def новый_клиент() -> httpx2.Client:
    """Клиент DeepSeek с пределами ожидания и повтором неудавшейся установки соединения.

    Худший случай при сети, где соединение не встаёт вовсе: 11 попыток по 20 с и паузы 255,5 с —
    около 8 минут до сообщения о сбое. При посреднике из окружения повтор НЕ действует:
    библиотека `httpx2` число повторов в пул посредника не передаёт."""
    транспорт = httpx2.HTTPTransport(retries=ПОВТОРОВ_СОЕДИНЕНИЯ, proxy=посредник_из_окружения(АДРЕС_DEEPSEEK))
    return httpx2.Client(timeout=ОЖИДАНИЕ, transport=транспорт)


def спросить(тело: dict, *, клиент: httpx2.Client | None = None) -> str:
    """Один запрос к DeepSeek: текст ответа модели как есть (пустой ответ — пустая строка).

    Общий вызов для переписывания и судьи смысла (`cite_eval.py`): ключ, пределы ожидания и
    разбор сбоев живут в одном месте."""
    ключ = _ключ()
    свой = клиент is None
    клиент = клиент or новый_клиент()
    try:
        try:
            ответ = клиент.post(АДРЕС_DEEPSEEK, json=тело, headers={"Authorization": f"Bearer {ключ}"})
        except httpx2.TimeoutException:
            raise ОшибкаПереписывания("DeepSeek не ответил вовремя") from None
        except httpx2.HTTPError as exc:
            raise ОшибкаПереписывания(f"нет связи с DeepSeek: {type(exc).__name__}") from None
    finally:
        if свой:
            клиент.close()
    if ответ.status_code >= 400:
        текст = " ".join(ответ.text.split()).replace(ключ, "***")
        raise ОшибкаПереписывания(f"DeepSeek ответил HTTP {ответ.status_code}: {текст}")
    try:
        return ответ.json()["choices"][0]["message"]["content"] or ""
    except (ValueError, KeyError, IndexError, TypeError):
        raise ОшибкаПереписывания("DeepSeek вернул ответ непонятного вида") from None


def переписать(вопрос: str, *, клиент: httpx2.Client | None = None) -> str:
    """Поисковый запрос одной строкой."""
    тело = {"model": МОДЕЛЬ, "temperature": 0, "thinking": {"type": "disabled"},
            "messages": [{"role": "system", "content": ИНСТРУКЦИЯ}, {"role": "user", "content": вопрос}]}
    запрос = " ".join(спросить(тело, клиент=клиент).split())
    if not запрос:
        raise ОшибкаПереписывания("DeepSeek вернул пустой запрос")
    return запрос


def развернуть(вопрос: str, контекст: str, *, клиент: httpx2.Client | None = None) -> str:
    """Самостоятельный вопрос одной строкой: реплика, развёрнутая по контексту разговора."""
    тело = {"model": МОДЕЛЬ, "temperature": 0, "thinking": {"type": "disabled"},
            "messages": [{"role": "system", "content": ИНСТРУКЦИЯ_РАЗВОРОТА},
                         {"role": "user", "content": f"Контекст разговора:\n{контекст}\n\nПоследняя реплика человека:\n{вопрос}"}]}
    развёрнутый = " ".join(спросить(тело, клиент=клиент).split())
    if not развёрнутый:
        raise ОшибкаПереписывания("DeepSeek вернул пустой вопрос")
    return развёрнутый
