"""Сравнение стратегий нарезки на контрольном наборе.

Контрольный набор `control.jsonl`: вопрос своими словами и **ключевой фрагмент** — дословная
короткая строка из текста, где лежит ответ. Попадание — фрагмент целиком лежит в тексте
найденного куска (пробельные символы в обоих свёрнуты в один пробел). Порогов перекрытия нет:
фрагмент, разрезанный границей куска, не лежит ни в одном — это и есть беда нарезки.
"""

from __future__ import annotations

import json
import re
import statistics
from pathlib import Path

import numpy as np

from store import ПОЛЯ_СБОРКИ

ПРОБЕЛЫ = re.compile(r"\s+")


def свернуть(текст: str) -> str:
    return ПРОБЕЛЫ.sub(" ", текст).strip()


def загрузить_набор(путь: Path, корпус: list[tuple[str, str]]) -> list[dict]:
    """Записи набора; фрагмент обязан встречаться в корпусе ровно один раз и в своём источнике."""
    свёрнутый = [(source, свернуть(текст)) for source, текст in корпус]
    набор = []
    for номер, строка in enumerate(путь.read_text("utf-8").splitlines(), 1):
        if not строка.strip():
            continue
        запись = json.loads(строка)
        if set(запись) != {"вопрос", "фрагмент", "источник"}:
            raise ValueError(f"строка {номер}: поля {sorted(запись)}")
        фрагмент = свернуть(запись["фрагмент"])
        где = [source for source, текст in свёрнутый for _ in range(текст.count(фрагмент))]
        if где != [запись["источник"]]:
            raise ValueError(f"строка {номер}: фрагмент «{фрагмент}» найден в {где or 'нигде'}, "
                             f"ожидался ровно один раз в {запись['источник']}")
        набор.append(запись)
    return набор


def место(выдача: list, фрагмент: str, источник: str) -> int | None:
    """Номер (с 1) первого куска выдачи из `источник`, целиком содержащего фрагмент; None — ни одного.

    Источник сверяется, потому что единственность фрагмента проверена по текущему корпусу, а
    куски взяты из индекса прошлой сборки: цитата фрагмента в другом файле, убранная после
    сборки, иначе засчиталась бы попаданием."""
    фрагмент = свернуть(фрагмент)
    for номер, кусок in enumerate(выдача, 1):
        if кусок.source == источник and фрагмент in свернуть(кусок.text):
            return номер
    return None


def меры(места: list[int | None]) -> dict[str, float]:
    n = len(места)
    return {"hit@1": sum(1 for м in места if м == 1) / n,
            "hit@5": sum(1 for м in места if м is not None and м <= 5) / n,
            "MRR": sum(1 / м for м in места if м is not None) / n}


def пересечения(fixed: list, structure: list) -> int:
    """Сколько кусков fixed содержат внутри себя границу раздела structure (режут его)."""
    границы: dict[str, list[int]] = {}
    for к in structure:
        границы.setdefault(к.source, []).append(к.start)
    return sum(1 for к in fixed if any(к.start < г < к.end for г in границы.get(к.source, ())))


def _длины(список: list) -> str:
    длины = [len(к.text) for к in список]
    # Медиана — как в chunking.размер_fixed, иначе две «медианы» расходились бы на единицу.
    return f"{min(длины)} / {int(statistics.median(длины))} / {max(длины)}"


def места_стратегии(список: list, матрица: np.ndarray, набор: list[dict], векторы_вопросов: np.ndarray) -> list[int | None]:
    """Место каждого вопроса во всей выдаче стратегии: полный перебор упорядочивает все куски,
    поэтому глубину выдачи выдумывать не нужно. None — фрагмент не лежит целиком ни в одном куске."""
    return [место([список[и] for и in np.argsort(-(матрица @ в), kind="stable")], з["фрагмент"], з["источник"])
            for з, в in zip(набор, векторы_вопросов)]


def _строка(имя: str, значения: list) -> str:
    return f"| {имя} | " + " | ".join(str(з) for з in значения) + " |"


def отчёт(сборки: dict[str, dict], данные: dict[str, tuple[list, np.ndarray]],
          набор: list[dict], векторы_вопросов: np.ndarray) -> str:
    """Markdown сравнения. данные: strategy -> (куски, матрица нормированных векторов)."""
    порядок = sorted(данные)
    места = {s: места_стратегии(*данные[s], набор, векторы_вопросов) for s in порядок}
    шапка = ["| | " + " | ".join(порядок) + " |", "|---|" + "---|" * len(порядок)]
    строки = ["# Сравнение стратегий нарезки", "", "## Сборки", "", *шапка]
    for поле in ПОЛЯ_СБОРКИ:
        строки.append(_строка(f"`{поле}`", [сборки[s].get(поле) for s in порядок]))
    строки += ["", "## Куски", "", *шапка,
               _строка("кусков", [len(данные[s][0]) for s in порядок]),
               _строка("длина, символов: мин / медиана / макс", [_длины(данные[s][0]) for s in порядок])]
    if {"fixed", "structure"} <= set(порядок):
        режут = пересечения(данные["fixed"][0], данные["structure"][0])
        строки.append(_строка("кусков, режущих раздел `structure`",
                              [f"{режут} из {len(данные[s][0])}" if s == "fixed" else "—" for s in порядок]))
    строки.append(_строка("фрагментов набора, разрезанных нарезкой",
                          [f"{места[s].count(None)} из {len(набор)}" for s in порядок]))
    итоги = {s: меры(места[s]) for s in порядок}
    строки += ["", "## Поиск по контрольному набору", "",
               f"Вопросов: {len(набор)}. Место — номер первого куска всей выдачи, целиком содержащего "
               "ключевой фрагмент; «разрезан» — фрагмент не лежит целиком ни в одном куске (вклад в MRR 0).",
               "", "| мера | " + " | ".join(порядок) + " |", "|---|" + "---|" * len(порядок)]
    for мера in ("hit@1", "hit@5", "MRR"):
        строки.append(_строка(мера, [f"{итоги[s][мера]:.3f}" for s in порядок]))
    строки += ["", "## По вопросам", "", "| # | вопрос | источник | " + " | ".join(порядок) + " |",
               "|---|---|---|" + "---|" * len(порядок)]
    for номер, з in enumerate(набор):
        ячейки = [места[s][номер] if места[s][номер] is not None else "разрезан" for s in порядок]
        строки.append(f"| {номер + 1} | {з['вопрос']} | `{з['источник']}` | " + " | ".join(map(str, ячейки)) + " |")
    return "\n".join(строки) + "\n"
