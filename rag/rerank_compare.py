"""Сравнение поиска со вторым этапом: сетка K₁ × K₂, кривые порогов, итог на проверке, «до / после».

Наборы делятся на две части, чтобы порог не проверялся на тех же вопросах, на которых подобран:

- **подбор** — 30 вопросов `control.jsonl` (попадание — кусок из источника, целиком содержащий
  ключевой фрагмент, как в дне 21) и отрицательные вопросы части `подбор`;
- **проверка** — 10 вопросов `answers.jsonl` (попадание — кусок из `источники`, как в дне 22) и
  отрицательные вопросы части `проверка`.

Варианты — 4 режима `rerank.РЕЖИМЫ` × {без переписывания, с ним}. Вопрос переписывается один раз
за всю работу: переписанные запросы лежат файлом, и каждый прогон отчёта читает их оттуда.
Отчёт строится по мере того, сколько чисел выбрано:

1. всегда — сетка K₁ × K₂ без порога на части «подбор»;
2. с `k1`, `k2` — кривые порогов: доля потерянных попаданий против доли отрицательных вопросов,
   отсечённых начисто; точки кривой — сами значения счёта из данных, шага у перебора нет;
3. с `τ`, `θ` — выбранные числа и итог на обеих частях, переписанные запросы и разбор по
   вопросам «кандидатов → прошло → отдано».
"""

from __future__ import annotations

import json
import statistics
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Callable

import numpy as np

import compare as ср
import rerank as рр
from chunking import Кусок

K1_СЕТКА = (5, 10, 20, 30, 50)
K2_СЕТКА = (3, 5, 10)
РЕЖИМЫ_С_ПОРОГОМ = ("threshold", "heuristic", "model")


@dataclass(frozen=True)
class Вопрос:
    метка: str  # c07 — control, q03 — answers, n06 — negative
    текст: str
    часть: str  # подбор | проверка
    попал: Callable[[Кусок], bool] | None  # None — отрицательный вопрос: ответа в базе нет


@dataclass(frozen=True)
class Вариант:
    режим: str
    переписывать: bool

    @property
    def имя(self) -> str:
        return self.режим + ("+rw" if self.переписывать else "")


ВАРИАНТЫ = [Вариант(р, п) for р in рр.РЕЖИМЫ for п in (False, True)]


def загрузить(control: Path, answers: Path, negative: Path) -> list[Вопрос]:
    вопросы = []
    for номер, строка in enumerate(control.read_text("utf-8").splitlines(), 1):
        з = json.loads(строка)
        фрагмент = ср.свернуть(з["фрагмент"])
        вопросы.append(Вопрос(f"c{номер:02d}", з["вопрос"], "подбор",
                              lambda к, ф=фрагмент, и=з["источник"]: к.source == и and ф in ср.свернуть(к.text)))
    for строка in answers.read_text("utf-8").splitlines():
        з = json.loads(строка)
        вопросы.append(Вопрос(f"q{з['n']:02d}", з["вопрос"], "проверка",
                              lambda к, и=frozenset(з["источники"]): к.source in и))
    for строка in negative.read_text("utf-8").splitlines():
        з = json.loads(строка)
        if з["часть"] not in ("подбор", "проверка"):
            raise ValueError(f"negative n{з['n']}: часть {з['часть']!r}")
        вопросы.append(Вопрос(f"n{з['n']:02d}", з["вопрос"], з["часть"], None))
    return вопросы


def переписанные(вопросы: list[Вопрос], путь: Path, переписать: Callable[[str], str]) -> dict[str, str]:
    """Переписанные запросы по метке вопроса из файла `путь`; недостающие переписываются и
    дописываются в файл по одному.

    Зачем файл: DeepSeek и при `temperature` 0 не обещает тот же ответ, а сетка, кривые и итог
    строятся разными прогонами — без файла они считались бы на разных переписанных запросах. И
    сбой сети на одном вопросе теряет только его: следующий прогон продолжает с него же."""
    готовые: dict[str, dict] = json.loads(путь.read_text("utf-8")) if путь.is_file() else {}
    for номер, вопрос in enumerate(вопросы, 1):
        if готовые.get(вопрос.метка, {}).get("вопрос") == вопрос.текст:
            continue
        print(f"\rпереписывание: {номер}/{len(вопросы)}", end="", file=sys.stderr, flush=True)
        готовые[вопрос.метка] = {"вопрос": вопрос.текст, "запрос": переписать(вопрос.текст)}
        временный = путь.with_name(путь.name + ".tmp")  # обрыв посреди записи не портит файл
        временный.write_text(json.dumps(готовые, ensure_ascii=False, indent=1) + "\n", "utf-8")
        временный.replace(путь)
    print(file=sys.stderr)
    return {в.метка: готовые[в.метка]["запрос"] for в in вопросы}


def с_памятью_векторов(считать):
    """`считать` с памятью по тексту: сетка спрашивает одни и те же вопросы десятки раз."""
    память: dict[str, np.ndarray] = {}

    def обёртка(тексты: list[str]) -> np.ndarray:
        новые = [т for т in dict.fromkeys(тексты) if т not in память]
        if новые:
            память.update(zip(новые, считать(новые)))
        return np.array([память[т] for т in тексты])

    return обёртка


def с_памятью_оценок(оценщик: рр.Оценщик) -> рр.Оценщик:
    """Оценщик с памятью по паре: кодировщик считает каждую пару один раз за весь отчёт."""
    память: dict[tuple[str, str], float] = {}

    def обёртка(вопрос: str, тексты: list[str]) -> list[float]:
        новые = [т for т in dict.fromkeys(тексты) if (вопрос, т) not in память]
        if новые:
            память.update(zip(((вопрос, т) for т in новые), оценщик(вопрос, новые)))
        return [память[(вопрос, т)] for т in тексты]

    return обёртка


def место(куски: list[рр.Найденный], вопрос: Вопрос) -> int | None:
    return next((н for н, найденный in enumerate(куски, 1) if вопрос.попал(найденный.кусок)), None)


class Замер:
    """Итоги поиска по вопросам с памятью: одна клетка отчёта не пересчитывает другую."""

    def __init__(self, поиск: рр.Поиск, вопросы: list[Вопрос], переписанные: dict[str, str]) -> None:
        self.поиск = поиск
        self.вопросы = вопросы
        self.переписанные = переписанные
        self._упорядоченные: dict[tuple, list[рр.Найденный]] = {}

    def упорядоченные(self, вопрос: Вопрос, вариант: Вариант, k1: int) -> list[рр.Найденный]:
        ключ = (вопрос.метка, вариант, k1)
        if ключ not in self._упорядоченные:
            переписанный = self.переписанные[вопрос.метка] if вариант.переписывать else None
            self._упорядоченные[ключ] = self.поиск.упорядочить(вопрос.текст, вариант.режим, k1, переписанный)
        return self._упорядоченные[ключ]

    def итог(self, вопрос: Вопрос, вариант: Вариант, k1: int, k2: int, порог: float | None) -> рр.Итог:
        """То же, что `Поиск.отобрать`, поверх упорядоченного с памятью."""
        if вариант.режим == "base":
            k1, порог = k2, None
        найденные = self.упорядоченные(вопрос, вариант, k1)
        прошедшие = найденные if порог is None else [н for н in найденные if not рр.отсечён(н, вариант.режим, порог)]
        return рр.Итог(прошедшие[:k2], len(найденные), len(прошедшие))

    def меры(self, часть: str, вариант: Вариант, k1: int, k2: int, порог: float | None) -> dict[str, float]:
        положительные, отрицательные, итоги = [], [], []
        for вопрос in self.вопросы:
            if вопрос.часть != часть:
                continue
            итог = self.итог(вопрос, вариант, k1, k2, порог)
            итоги.append(итог)
            if вопрос.попал is None:
                отрицательные.append(not итог.куски)
            else:
                положительные.append(место(итог.куски, вопрос))
        n = len(положительные)
        return {"hit@1": sum(м == 1 for м in положительные) / n,
                "hit@K2": sum(м is not None for м in положительные) / n,
                "MRR": sum(1 / м for м in положительные if м is not None) / n,
                "начисто": sum(отрицательные) / len(отрицательные) if отрицательные else 0.0,
                "кандидатов": statistics.mean(и.кандидатов for и in итоги),
                "прошло": statistics.mean(и.прошло for и in итоги),
                "отдано": statistics.mean(len(и.куски) for и in итоги),
                "символов": statistics.mean(sum(len(н.кусок.text) for н in и.куски) for и in итоги)}

    def кривая(self, вариант: Вариант, k1: int, k2: int) -> list[tuple[float, int, int, int, int]]:
        """(порог, потеряно, попаданий без порога, отсечено начисто, отрицательных) на части «подбор».

        Точки — значения, по которым режим отсекает (косинус или вероятность): у положительного
        вопроса — значения его попавших кусков, у отрицательного — наибольшее значение. Между
        соседними точками обе меры постоянны, поэтому перебор точен без шага."""
        по = lambda н: н.счёт if вариант.режим == "model" else н.косинус
        вопросы = [в for в in self.вопросы if в.часть == "подбор"]
        точки: set[float] = set()
        for вопрос in вопросы:
            найденные = self.упорядоченные(вопрос, вариант, k1)
            if вопрос.попал is None:
                точки.add(max(по(н) for н in найденные))
            else:
                точки.update(по(н) for н in найденные if вопрос.попал(н.кусок))
        без_порога = {в.метка: место(self.итог(в, вариант, k1, k2, None).куски, в) for в in вопросы if в.попал}
        попаданий = sum(м is not None for м in без_порога.values())
        отрицательных = sum(в.попал is None for в in вопросы)
        строки = []
        for порог in sorted(точки):
            потеряно = начисто = 0
            for вопрос in вопросы:
                итог = self.итог(вопрос, вариант, k1, k2, порог)
                if вопрос.попал is None:
                    начисто += not итог.куски
                elif без_порога[вопрос.метка] is not None and место(итог.куски, вопрос) is None:
                    потеряно += 1
            строки.append((порог, потеряно, попаданий, начисто, отрицательных))
        # Подряд идущие точки с теми же мерами ничего не добавляют: оставляем наибольший порог.
        return [с for и, с in enumerate(строки) if и + 1 == len(строки) or строки[и + 1][1:] != с[1:]]


def _доля(x: float) -> str:
    return f"{x:.3f}"


def порог_варианта(вариант: Вариант, tau: float | None, theta: float | None) -> float | None:
    return None if вариант.режим == "base" else theta if вариант.режим == "model" else tau


def отчёт(замер: Замер, k1: int | None = None, k2: int | None = None, tau: float | None = None,
          theta: float | None = None, причина: str = "") -> str:
    части = ["# Сравнение поиска: второй этап (день 23)", "",
             f"Вопросов: подбор — {sum(в.часть == 'подбор' for в in замер.вопросы)}, проверка — "
             f"{sum(в.часть == 'проверка' for в in замер.вопросы)} (из них отрицательных "
             f"{sum(в.попал is None for в in замер.вопросы)}). Вариант `+rw` — с переписанным запросом.", ""]

    части += ["## 1. Сетка K₁ × K₂ без порога (подбор)", "",
              "В клетке — hit@K₂ / MRR по 30 вопросам `control.jsonl`. У `base` второго этапа нет: K₁ = K₂.", "",
              "| вариант | K₁ | " + " | ".join(f"K₂ = {k}" for k in K2_СЕТКА) + " |",
              "|---|---|" + "---|" * len(K2_СЕТКА)]
    for вариант in ВАРИАНТЫ:
        for k1_ in ((K2_СЕТКА[0],) if вариант.режим == "base" else K1_СЕТКА):
            клетки = []
            for k2_ in K2_СЕТКА:
                м = замер.меры("подбор", вариант, k1_, k2_, None)
                клетки.append(f"{_доля(м['hit@K2'])} / {_доля(м['MRR'])}")
            части.append(f"| {вариант.имя} | {'= K₂' if вариант.режим == 'base' else k1_} | " + " | ".join(клетки) + " |")
    части += ["", "Цена размера итога — средняя длина отданных кусков у `base`, символов:", "",
              "| K₂ | " + " | ".join(str(k) for k in K2_СЕТКА) + " |", "|---|" + "---|" * len(K2_СЕТКА),
              "| символов | " + " | ".join(f"{замер.меры('подбор', ВАРИАНТЫ[0], k, k, None)['символов']:.0f}"
                                         for k in K2_СЕТКА) + " |", ""]
    if k1 is None or k2 is None:
        return "\n".join(части)

    части += [f"## 2. Кривые порогов (подбор, K₁ = {k1}, K₂ = {k2})", "",
              "Отсекается всё, что ниже порога; кусок ровно на пороге проходит. «Потеряно» — вопросы, у "
              "которых попадание было в K₂ без порога и пропало с ним; «начисто» — отрицательные вопросы, "
              "на которые не отдано ни куска. Порог — косинус у `threshold`/`heuristic`, вероятность "
              "кодировщика у `model`.", ""]
    for вариант in ВАРИАНТЫ:
        if вариант.режим not in РЕЖИМЫ_С_ПОРОГОМ:
            continue
        части += [f"### {вариант.имя}", "", "| порог | потеряно | отрицательных начисто |", "|---|---|---|"]
        for порог, потеряно, попаданий, начисто, отрицательных in замер.кривая(вариант, k1, k2):
            части.append(f"| {порог:.4g} | {потеряно} из {попаданий} | {начисто} из {отрицательных} |")
        части.append("")
    if tau is None or theta is None:
        return "\n".join(части)

    части += ["## 3. Выбранные числа и итог", "",
              f"K₁ = {k1}, K₂ = {k2}, τ = {tau} (косинус: `threshold`, `heuristic`), θ = {theta} (вероятность: `model`).",
              "", причина or "Причина выбора не названа.", "",
              "Проверка — вопросы, на которых числа не подбирались; подбор — для сравнения. «До → прошло → "
              "отдано» — средние по всем вопросам части.", "",
              "| вариант | часть | hit@1 | hit@K₂ | MRR | отрицательных начисто | до → прошло → отдано | символов |",
              "|---|---|---|---|---|---|---|---|"]
    for вариант in ВАРИАНТЫ:
        порог = порог_варианта(вариант, tau, theta)
        for часть in ("проверка", "подбор"):
            м = замер.меры(часть, вариант, k1, k2, порог)
            части.append(f"| {вариант.имя} | {часть} | {_доля(м['hit@1'])} | {_доля(м['hit@K2'])} | {_доля(м['MRR'])} "
                         f"| {_доля(м['начисто'])} | {м['кандидатов']:.1f} → {м['прошло']:.1f} → {м['отдано']:.1f} "
                         f"| {м['символов']:.0f} |")

    части += ["", "## 4. Переписанные запросы", "", "| вопрос | исходный | переписанный |", "|---|---|---|"]
    for вопрос in замер.вопросы:
        части.append(f"| {вопрос.метка} | {вопрос.текст} | {замер.переписанные[вопрос.метка]} |")

    части += ["", "## 5. По вопросам", "",
              "В клетке — место попадания среди отданных (— нет попадания; у отрицательного `пусто` — "
              "не отдано ни куска, верно) и «кандидатов → прошло → отдано».", "",
              "| вопрос | часть | " + " | ".join(в.имя for в in ВАРИАНТЫ) + " |",
              "|---|---|" + "---|" * len(ВАРИАНТЫ)]
    for вопрос in замер.вопросы:
        клетки = []
        for вариант in ВАРИАНТЫ:
            итог = замер.итог(вопрос, вариант, k1, k2, порог_варианта(вариант, tau, theta))
            if вопрос.попал is None:
                суть = "пусто" if not итог.куски else "отдано"
            else:
                суть = str(место(итог.куски, вопрос) or "—")
            клетки.append(f"{суть} ({итог.кандидатов}→{итог.прошло}→{len(итог.куски)})")
        части.append(f"| {вопрос.метка} | {вопрос.часть} | " + " | ".join(клетки) + " |")
    return "\n".join(части) + "\n"
