    проверить("cite: цитата с иным переносом строки дословна, с заменённым словом — нет (парная)", годны[:2] == [True, False], repr(годны))
    проверить("cite: цитата куска 1 под номером 2 — нет; многострочная с пунктами списка — да (парная)", годны[2:4] == [False, True], repr(годны))
    проверить("cite: вопрос из хвоста сообщения цитатой не считается; номер вне найденного — нет", годны[4:] == [False, False], repr(годны))
    без = cite.разобрать("Просто текст без разделов.")
