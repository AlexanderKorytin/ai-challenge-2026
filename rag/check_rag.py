"""Проверки проекта `rag` без Ollama.

Эмбеддер подменён `httpx2.MockTransport`, индекс пишется во временный каталог: проверка не
трогает ни настоящий `rag/index.sqlite`, ни службу Ollama.

Запуск: `uv run --project rag rag/check_rag.py` из корня репозитория. Каждая проверка печатает
«ок» или «ПРОВАЛ»; код выхода 1 при хоть одном провале.
"""

