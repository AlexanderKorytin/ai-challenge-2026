АЛФАВИТ = "абвгдеёжзийклмнопрстуфхцчшщъыьэюя"


def _вектор(текст: str) -> list[float]:
    """Подставной эмбеддинг: счётчики букв."""
    return [float(текст.lower().count(б)) for б in АЛФАВИТ]


def _кусок(n: int, текст: str, strategy: str = "structure", source: str = "a.md") -> ч.Кусок:
    return ч.Кусок(f"{strategy}:{source}:{n}", strategy, source, "A", "", n * 100, n * 100 + len(текст), текст)


def эмбеддер_и_индекс() -> None:
    просьбы: list[dict] = []

    def ответ(запрос: httpx2.Request) -> httpx2.Response:
        тело = json.loads(запрос.content)
        просьбы.append(тело)
        if any(len(т) > 40 for т in тело["input"]):
            return httpx2.Response(400, json={"error": "the input length exceeds the context length"})
        return httpx2.Response(200, json={"embeddings": [_вектор(т) for т in тело["input"]]})

    клиент = httpx2.Client(transport=httpx2.MockTransport(ответ))
    считать = lambda тексты: эм.эмбеддинги(тексты, клиент=клиент)
    считать(["кот"])
    проверить("эмбеддер: truncate false, num_ctx и num_batch 8192",
              просьбы[-1]["truncate"] is False and просьбы[-1]["options"] == {"num_ctx": 8192, "num_batch": 8192}
              and просьбы[-1]["model"] == "bge-m3")
    try:
        считать(["я" * 41])
        класс = None
    except эм.ОшибкаЭмбеддера as e:
        класс = type(e)
    проверить("эмбеддер: отказ по длине — ПереполнениеОкна", класс is эм.ПереполнениеОкна)

    длинный = "абв где\n\nжзи клм\n\nноп рст\n\nуфх цчш\n\nщыэ юяа"
    assert len(длинный) > 40 and len(длинный) // 2 <= 40, "предусловие: длинный не влезает, половина влезает"
    куски, матрица = cli.векторы([_кусок(0, "кот"), _кусок(1, длинный)], считать)
    проверить("переполнение: длинный кусок делится надвое по абзацу",
              [к.chunk_id for к in куски] == ["structure:a.md:0", "structure:a.md:1.0", "structure:a.md:1.1"]
              and куски[1].text + куски[2].text == длинный and куски[1].text.endswith("\n\n")
              and куски[2].start == куски[1].end and len(матрица) == 3, repr([к.chunk_id for к in куски]))
    куски, _ = cli.векторы([_кусок(1, "а" * 40)], считать)
    проверить("переполнение: кусок ровно в окно не делится (парная)", [к.chunk_id for к in куски] == ["structure:a.md:1"])

    with tempfile.TemporaryDirectory() as каталог:
        индекс = Path(каталог) / "i.sqlite"
        сведения = {"model": "bge-m3", "dim": len(АЛФАВИТ), "chunks": 2}
        s = [_кусок(0, "кот кот"), _кусок(1, "пёс")]
        f = [_кусок(0, "дом", "fixed")]
        store.записать(индекс, "structure", s, np.array([_вектор(к.text) for к in s]), сведения)
        store.записать(индекс, "fixed", f, np.array([_вектор(к.text) for к in f]), сведения)
        новые = [_кусок(0, "сыр"), _кусок(1, "кот"), _кусок(2, "пёс кот")]
        store.записать(индекс, "structure", новые, np.array([_вектор(к.text) for к in новые]), сведения)
        прочитано, векторы = store.куски(индекс, "structure")
        проверить("индекс: повторная сборка заменяет куски своей стратегии",
                  [к.text for к in прочитано] == ["сыр", "кот", "пёс кот"])
        проверить("индекс: чужую стратегию не трогает", [к.text for к in store.куски(индекс, "fixed")[0]] == ["дом"])
        проверить("индекс: векторы нормированы", np.allclose(np.linalg.norm(векторы, axis=1), 1, atol=1e-6))
        выдача = store.найти(индекс, "structure", np.array(_вектор("кот")), 3)
        проверить("индекс: поиск по убыванию косинуса",
                  [к.text for _, к in выдача] == ["кот", "пёс кот", "сыр"]
                  and выдача[0][0] >= выдача[1][0] >= выдача[2][0], repr([(round(б, 3), к.text) for б, к in выдача]))
        проверить("индекс: сведения сборки читаются", set(store.стратегии(индекс)) == {"fixed", "structure"})


def чужой_корпус() -> None:
    import argparse
    считать = lambda тексты: np.array([_вектор(т) for т in тексты])
    with tempfile.TemporaryDirectory() as каталог:
        корень = Path(каталог)
        (корень / "книга" / "глава").mkdir(parents=True)
        (корень / "книга" / "а.md").write_text("# Книга\n\n## Кот\nкот кот\n\n## Пёс\nпёс\n", "utf-8")
        (корень / "книга" / "глава" / "б.md").write_text("## Сыр\nсыр\n", "utf-8")
        (корень / "книга" / "в.txt").write_text("## Не Markdown\nмимо\n", "utf-8")
        (корень / "пусто").mkdir()
        пары = ч.корпус_каталога(корень / "книга")
        проверить("чужой корпус: все .md рекурсивно, путь от каталога, прочие файлы мимо",
                  [источник for источник, _ in пары] == ["а.md", "глава/б.md"], repr([и for и, _ in пары]))

        индекс = корень / "свой.sqlite"
        cli.команда_index(argparse.Namespace(index=индекс, corpus=корень / "книга", strategy="structure"), считать)
        прочитано, _ = store.куски(индекс, "structure")
        сборка = store.стратегии(индекс)["structure"]
        проверить("чужой корпус: индекс собран из каталога",
                  {к.source for к in прочитано} == {"а.md", "глава/б.md"} and any("сыр" in к.text for к in прочитано),
                  repr([к.chunk_id for к in прочитано]))
        проверить("чужой корпус: commit_hash и dirty сборки пусты — корпус вне git",
                  сборка["commit_hash"] is None and сборка["dirty"] is None, repr(сборка))

        # Отказы: индекс по умолчанию подменён временным путём — настоящий `rag/index.sqlite` проверка не трогает.
        прежний = cli.ИНДЕКС
        cli.ИНДЕКС = корень / "умолчание.sqlite"
        try:
            def выход(argv: list[str]) -> str:
                try:
                    cli.главная(argv)
                except SystemExit as e:
                    return str(e.code)
                return ""
            сообщение = выход(["index", "--corpus", str(корень / "книга"), "--strategy", "structure"])
            проверить("чужой корпус: без --index отказ, индекс по умолчанию не создан",
                      сообщение == "rag: --corpus требует --index" and not cli.ИНДЕКС.exists(), сообщение)
            # Без --corpus и без --index команда получает индекс по умолчанию (парная к отказу выше).
            увидено: list[Path] = []
            прежняя_команда = cli.команда_search
            cli.команда_search = lambda доводы: увидено.append(доводы.index)
            try:
                выход(["search", "кот"])
            finally:
                cli.команда_search = прежняя_команда
            проверить("индекс по умолчанию: без --index команда получает его", увидено == [cli.ИНДЕКС], repr(увидено))
            пустой = корень / "пустой.sqlite"
            сообщение = выход(["--index", str(пустой), "index", "--corpus", str(корень / "пусто")])
            проверить("чужой корпус: каталог без .md — отказ, индекс не создан",
                      "нет файлов .md" in сообщение and not пустой.exists(), сообщение)
        finally:
            cli.ИНДЕКС = прежний


def сравнение() -> None:
    куски = [_кусок(0, "начало ключевой"), _кусок(1, "фраза тут"), _кусок(2, "здесь ключевой фразы нет"),
             _кусок(3, "целая ключевая  фраза\nздесь")]
    проверить("место: первый кусок, целиком содержащий фрагмент (пробелы свёрнуты)",
              ср.место(куски, "ключевая фраза здесь", "a.md") == 4)
    проверить("место: кусок чужого источника не засчитывается (парная)", ср.место(куски, "ключевая фраза здесь", "b.md") is None)
    проверить("место: разрезанный фрагмент не находится ни в одном", ср.место(куски[:3], "ключевой фраза", "a.md") is None)
    итог = ср.меры([1, 3, None, 6])
    проверить("меры: hit@1, hit@5, MRR", итог == {"hit@1": 0.25, "hit@5": 0.5, "MRR": (1 + 1 / 3 + 1 / 6) / 4}, repr(итог))
    structure = [_кусок(0, "а" * 100), _кусок(1, "б" * 100)]
    fixed = [ч.Кусок("fixed:a.md:0", "fixed", "a.md", "A", "", 0, 100, ""),
             ч.Кусок("fixed:a.md:1", "fixed", "a.md", "A", "", 80, 180, "")]
    проверить("пересечения: режет только кусок, внутри которого граница раздела",
              ср.пересечения(fixed, structure) == 1)

    # Главный путь сравнения: подставной индекс из трёх кусков, векторы — счётчики букв.
    индекс = [_кусок(0, "шшш щщщ"), _кусок(1, "ааа ббб ключ"), _кусок(2, "ааа ббб")]
    матрица = store.нормировать(np.array([_вектор(к.text) for к in индекс]))
    набор = [{"вопрос": "ааа ббб", "фрагмент": "ббб ключ", "источник": "a.md"},
             {"вопрос": "шшш", "фрагмент": "шшш щщщ", "источник": "a.md"},
             {"вопрос": "ааа", "фрагмент": "ключ ааа", "источник": "a.md"}]
    вопросы = store.нормировать(np.array([_вектор(з["вопрос"]) for з in набор]))
    места = ср.места_стратегии(индекс, матрица, набор, вопросы)
    assert (матрица[2] @ вопросы[0]) > (матрица[1] @ вопросы[0]), "предусловие: ответ на 1-й вопрос не первый в выдаче"
    проверить("места_стратегии: место по убыванию косинуса, разрезанный — None", места == [2, 1, None], repr(места))
    текст = ср.отчёт({"structure": {"model": "m"}}, {"structure": (индекс, матрица)}, набор, вопросы)
    проверить("отчёт: hit@1, hit@5, MRR и «разрезан» из мест",
              "| hit@1 | 0.333 |" in текст and "| hit@5 | 0.667 |" in текст and "| MRR | 0.500 |" in текст
              and "| 3 | ааа | `a.md` | разрезан |" in текст and "| фрагментов набора, разрезанных нарезкой | 1 из 3 |" in текст)


def сервер_поиска() -> None:
    считать = lambda тексты: np.array([_вектор(т) for т in тексты])
    with tempfile.TemporaryDirectory() as каталог:
        индекс = Path(каталог) / "i.sqlite"
        s = [_кусок(0, "сыр", source="x.md"), _кусок(1, "кот", source="y.md"), _кусок(2, "пёс кот", source="z.md")]
        store.записать(индекс, "structure", s, np.array([_вектор(к.text) for к in s]), {"model": "m"})
        оценки = {"сыр": 0.1, "кот": 0.3, "пёс кот": 0.8}
        поиск = server.открыть_поиск(индекс, считать, lambda вопрос, тексты: [оценки[т] for т in тексты])
        base = server.настройки_из_окружения({})
        текст = server.найти_текст("кот", поиск, base, 2)
        заголовки = [с for с in текст.splitlines() if с.startswith("[")]
        проверить("сервер: заголовки `[n] <путь> ›` по убыванию близости, ровно k",
                  len(заголовки) == 2 and заголовки[0].startswith("[1] y.md › A · structure:y.md:1 (")
                  and заголовки[1].startswith("[2] z.md › A · structure:z.md:2 (")
                  and текст.split("\n\n")[1].endswith("пёс кот"), repr(текст))
        проверить("сервер: k=1 — один кусок (парная)", server.найти_текст("кот", поиск, base, 1).count("\n[") == 0)
        проверить("сервер: без довода k — K₂ из настроек, умолчание 5 как в дне 22",
                  base.k2 == 5 and server.найти_текст("кот", поиск, base).count("\n\n[") == 2
                  and server.найти_текст("кот", поиск, server.настройки_из_окружения({"RAG_K2": "1"})).count("\n[") == 0)

        model = server.настройки_из_окружения({"RAG_MODE": "model", "RAG_K1": "3", "RAG_THRESHOLD": "0.3"})
        текст = server.найти_текст("кот", поиск, model)
        проверить("сервер: model — порядок и счёт кодировщика в заголовке, отсечение порогом",
                  текст.startswith("[1] z.md › A · structure:z.md:2 (0.800)\n")
                  and "[2] y.md › A · structure:y.md:1 (0.300)" in текст and "x.md" not in текст, repr(текст))
        блок = оценка.ЗАГОЛОВОК_НАЙДЕННОГО + "\n\n" + текст + "\n\nкот?"
        проверить("сервер: строку с chunk_id eval читает по-прежнему — те же пути",
                  оценка.найденные_источники(блок) == ["z.md", "y.md"], repr(оценка.найденные_источники(блок)))
        пустой = server.найти_текст("кот", поиск, server.Настройки("model", False, 3, 5, 0.9))
        блок = оценка.ЗАГОЛОВОК_НАЙДЕННОГО + "\n\n" + пустой + "\n\nкот?"
        проверить("сервер: пустой итог — непустая строка, eval разбирает её в []",
                  пустой == "В базе не нашлось достаточно близкого (режим model, порог 0.9, лучшая близость 0.800)."
                  and оценка.найденные_источники(блок) == [], repr(пустой))
        проверить("сервер: порог ниже лучшей близости — итог непуст (парная)",
                  server.найти_текст("кот", поиск, server.Настройки("model", False, 3, 5, 0.8)).startswith("[1] z.md"))
        эвристика = server.найти_текст("кот", поиск, server.Настройки("heuristic", False, 3, 5, 1.5))
