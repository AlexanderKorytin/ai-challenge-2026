def проверить(название: str, условие: bool, подробно: str = "") -> None:
    global провалов
    if условие:
        print(f"ок      {название}")
    else:
        провалов += 1
        print(f"ПРОВАЛ  {название}" + (f": {подробно}" if подробно else ""))


ОБРАЗЕЦ = """Вступление без заголовка.

# Имя файла

## Раздел А
текст А
```bash
# комментарий, а не заголовок
```
### Требование Б
текст Б
#### Сценарий В
текст В
## Раздел Г
текст Г
"""


def нарезка() -> None:
    куски = ч.нарезать_structure("docs/образец.md", ОБРАЗЕЦ)
    начала = [ОБРАЗЕЦ[к.start:].split("\n", 1)[0] for к in куски]
    проверить("structure: разделы ровно по заголовкам уровней 1–3",
              начала == ["Вступление без заголовка.", "# Имя файла", "## Раздел А",
                         "### Требование Б", "## Раздел Г"], repr(начала))
    проверить("structure: #### остаётся внутри своего ###", "#### Сценарий В" in куски[3].text)
    проверить("structure: # в ограждении раздела не открывает", "# комментарий" in куски[2].text)
    проверить("structure: куски покрывают файл встык",
              куски[0].start == 0 and куски[-1].end == len(ОБРАЗЕЦ)
              and all(а.end == б.start for а, б in zip(куски, куски[1:])))
    проверить("structure: title — заголовок # файла", куски[0].title == "Имя файла", куски[0].title)
    проверить("structure: section — цепочка уровней 2–4",
              куски[3].section == "Раздел А › Требование Б" and куски[0].section == "",
              repr([к.section for к in куски]))
    проверить("structure: chunk_id по порядку в файле",
              [к.chunk_id for к in куски[:2]] == ["structure:docs/образец.md:0", "structure:docs/образец.md:1"])
    проверить("title без # — имя файла", ч.заглавие("docs/без.md", "## только второй") == "без")

    проверить("fixed: окна 10 на 25 — шаг 8", ч.окна(25, 10) == [(0, 10), (8, 18), (16, 25)], repr(ч.окна(25, 10)))
    проверить("fixed: окна 11 — шаг 9 (парная)", [с for с, _ in ч.окна(25, 11)] == [0, 9, 18])
    сценарий = ОБРАЗЕЦ.index("текст В")
    кусок = next(к for к in ч.нарезать_fixed("docs/образец.md", ОБРАЗЕЦ, 12) if к.start >= сценарий)
    проверить("fixed: section куска внутри #### — полная цепочка",
              кусок.section == "Раздел А › Требование Б › Сценарий В", кусок.section)
    проверить("fixed: пробельных кусков нет",
              all(к.text.strip() for к in ч.нарезать_fixed("x.md", "а" + " " * 30, 10)))

    всего = 0
    нарушений = []
    for source, текст in ч.корпус(КОРЕНЬ):
        s = ч.нарезать_structure(source, текст)
        for к in [*s, *ч.нарезать_fixed(source, текст, 500)]:
            всего += 1
            if к.text != текст[к.start:к.end]:
                нарушений.append(к.chunk_id)
    проверить(f"корпус: text == файл[start:end] у всех {всего} кусков", not нарушений and всего > 0, str(нарушений[:3]))


