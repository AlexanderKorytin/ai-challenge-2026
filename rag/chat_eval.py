МОДЕЛЬ_СУДЬИ = "deepseek-v4-pro"
ВЕРДИКТЫ = ("служит", "уходит в сторону", "нарушает")
ЗАГОЛОВОК_ФАКТОВ = "Факты текущего разговора (Sticky Facts):"  # myharness.context_strategy
ВОПРОС_ДЛЯ_ПОИСКА = "Вопрос для поиска: "  # server.ВОПРОС_ДЛЯ_ПОИСКА
ИЗВЛЕКАТЕЛЬ = "извлекатель фактов"  # myharness.sticky_facts.EXTRACTOR_NAME
МЕТКА_РЕПЛИКИ = "Новое сообщение пользователя:\n"  # myharness.sticky_facts.extract_request
_ПРИМЕР = json.dumps({"вердикт": "нарушает", "довод": "ограничение «только требования» — а ответ опирается на план"},
                     ensure_ascii=False)
# Слово «JSON» и пример стоят в инструкции обязательно: без них DeepSeek отклоняет `json_object`.
ИНСТРУКЦИЯ_СУДЬИ = f"""Ты — проверяющий длинного разговора. Тебе даны ЦЕЛЬ разговора, ПАМЯТЬ ЗАДАЧИ — то, что человек зафиксировал раньше (цель, термины, ограничения, уточнения), очередная РЕПЛИКА человека и ОТВЕТ ассистента. Реши, удержал ли ассистент цель и зафиксированное.

«служит» — ответ отвечает на реплику, не противоречит цели и соблюдает всё зафиксированное в памяти задачи. Честное «в найденном ответа на это нет» тоже служит цели.
«уходит в сторону» — ответ отвечает не на то, о чём спрошено в свете цели, либо понимает зафиксированный термин иначе, чем он определён.
«нарушает» — ответ нарушает зафиксированное ограничение или уточнение.
То, что человек фиксирует в самой РЕПЛИКЕ, тоже считается зафиксированным. Верность фактов ответа не проверяй — только цель и зафиксированное.

Верни JSON-объект ровно с двумя ключами: «вердикт» — одно из трёх: «служит», «уходит в сторону», «нарушает»; «довод» — одна короткая строка.
Пример: {_ПРИМЕР}"""

Спросить = Callable[[dict], str]


def судить(цель: str, словарь: dict[str, str], реплика: str, ответ: str, спросить: Спросить = пер.спросить) -> dict:
    """Вердикт судьи цели `{"вердикт", "довод"}`; ответ судьи не того вида — `ValueError`."""
    память = "\n".join(f"- {ключ}: {значение}" for ключ, значение in словарь.items()) or "(пусто)"
    вход = f"ЦЕЛЬ:\n{цель}\n\nПАМЯТЬ ЗАДАЧИ:\n{память}\n\nРЕПЛИКА:\n{реплика}\n\nОТВЕТ:\n{ответ}"
    # Рассуждения — умолчание API (включены): вердикт требует сопоставления с несколькими правилами.
    тело = {"model": МОДЕЛЬ_СУДЬИ, "response_format": {"type": "json_object"},
            "messages": [{"role": "system", "content": ИНСТРУКЦИЯ_СУДЬИ}, {"role": "user", "content": вход}]}
    сырой = спросить(тело)
    try:
        данные = json.loads(сырой)
    except ValueError:
        raise ValueError(f"судья вернул не JSON: {сырой[:200]!r}") from None
    вердикт = данные.get("вердикт") if isinstance(данные, dict) else None
    if вердикт not in ВЕРДИКТЫ:
        raise ValueError(f"судья вернул вердикт не из {ВЕРДИКТЫ}: {сырой[:200]!r}")
    return {"вердикт": вердикт, "довод": " ".join(str(данные.get("довод") or "").split())}


class Вердикты:
    """Файл вердиктов: `<agent>:<index>` → `{"sha", "вердикт", "довод"}`; судья зовётся раз на ответ."""

    def __init__(self, путь: Path, спросить: Спросить = пер.спросить) -> None:
        self._путь = путь
        self._спросить = спросить
        self._данные: dict[str, dict] = json.loads(путь.read_text("utf-8")) if путь.is_file() else {}

    def вердикт(self, имя: str, цель: str, словарь: dict[str, str], реплика: str, ответ: str) -> dict:
        # Отпечаток — весь вход судьи: сменилось что-то из него — прежний вердикт вынесен о другом.
        отпечаток = hashlib.sha256(
            json.dumps([ИНСТРУКЦИЯ_СУДЬИ, цель, словарь, реплика, ответ], ensure_ascii=False).encode()).hexdigest()
        прежний = self._данные.get(имя)
        if прежний and прежний.get("sha") == отпечаток:
            return прежний
        self._данные[имя] = {"sha": отпечаток, **судить(цель, словарь, реплика, ответ, self._спросить)}
        временный = self._путь.with_name(self._путь.name + ".tmp")
        временный.write_text(json.dumps(self._данные, ensure_ascii=False, indent=1) + "\n", "utf-8")
        os.replace(временный, self._путь)
        return self._данные[имя]


def словарь_фактов(системное: str) -> dict[str, str]:
    """Словарь из блока фактов системного сообщения; блока нет — пустой словарь.

    Берётся ПОСЛЕДНЕЕ вхождение заголовка отдельной строкой: инструкция профиля сама упоминает
    блок по имени. Ключ — до первого «: »: пробелов в ключе нет, а двоеточие бывает (`термин:ворота`).
    Строка значения, сама начинающаяся с `- ` и несущая «: », неотличима от нового факта — такой
    словарь разберётся с лишним ключом; в отчёте словарь печатается целиком, это видно глазами.
    """
    строки = системное.splitlines()
    начала = [н for н, строка in enumerate(строки) if строка.strip() == ЗАГОЛОВОК_ФАКТОВ]
    if not начала:
        return {}
    словарь: dict[str, str] = {}
    ключ = None
    for строка in строки[начала[-1] + 1:]:
        if строка.startswith("- ") and ": " in строка:
            ключ, значение = строка[2:].split(": ", 1)
            словарь[ключ] = значение
        elif ключ is not None:
            # Блок фактов стоит в системной части последним, а значение факта бывает многострочным:
            # строка не вида `- ключ: значение` — продолжение прежнего значения, а не конец блока.
            # Оборви разбор здесь — судья получил бы усечённую память, а ключи ниже по алфавиту
            # выглядели бы снятыми.
            словарь[ключ] += "\n" + строка
    return словарь


def вопрос_поиска(отправленное: str) -> str | None:
    """Развёрнутый вопрос, по которому искал сервер, — первая строка блока найденного БЕЗ заголовка
    блока; `None` — разворота не было."""
    первая = отправленное.split("\n", 1)[0]
    return первая[len(ВОПРОС_ДЛЯ_ПОИСКА):].strip() if первая.startswith(ВОПРОС_ДЛЯ_ПОИСКА) else None


def подходит(ключ: str, значение: str, ожидание: dict) -> bool:
    вместе = f"{ключ}: {значение}".casefold()
    return ключ.casefold().startswith(ожидание["приставка"].casefold()) and all(
        подстрока.casefold() in вместе for подстрока in ожидание.get("содержит", []))


def записи_сценария(журнал: Path, наряды: list[str], agent: str) -> tuple[dict[int, dict], str | None]:
    """Записи реплик задания `agent` по номеру обмена — из ПОСЛЕДНЕГО названного наряда, где оно есть."""
    по_нарядам: dict[str, dict[int, dict]] = {}
    with журнал.open(encoding="utf-8") as файл:
        for строка in файл:
            if not строка.strip():
                continue
            запись = json.loads(строка)
            if запись.get("run_id") in наряды and запись.get("agent") == agent and isinstance(запись.get("index"), int):
                по_нарядам.setdefault(запись["run_id"], {})[запись["index"]] = запись
    for наряд in reversed(наряды):
        if наряд in по_нарядам:
            return по_нарядам[наряд], наряд
    return {}, None


def _ключ_операций(реплика: str, словарь: dict) -> tuple[str, str]:
    return реплика, json.dumps(словарь, ensure_ascii=False, sort_keys=True)


def операции_извлекателя(журнал: Path, наряд: str) -> dict[tuple[str, str], dict]:
    """Операции извлекателя фактов наряда по паре «реплика, прежний словарь».

    Запись извлекателя своего задания не называет (его `agent` — имя извлекателя), зато её вход —
    прежний словарь и сама реплика. Одного текста реплики мало: задания наряда идут одновременно
    под одним `run_id`, и две одинаковые реплики разных заданий перепутались бы; прежний словарь
    у них свой. Ответ не JSON — пустые операции.
    """
    операции: dict[tuple[str, str], dict] = {}
    with журнал.open(encoding="utf-8") as файл:
        for строка in файл:
            if not строка.strip():
                continue
            запись = json.loads(строка)
            вход = запись.get("query") or ""
            if запись.get("run_id") != наряд or запись.get("agent") != ИЗВЛЕКАТЕЛЬ or МЕТКА_РЕПЛИКИ not in вход:
                continue
            начало, реплика = вход.rsplit(МЕТКА_РЕПЛИКИ, 1)
            try:
                прежний = json.loads(начало.split("\n", 1)[1])
                ответ = json.loads(запись.get("response") or "{}")
            except (ValueError, IndexError):
                continue
            if isinstance(прежний, dict):
                операции[_ключ_операций(реплика, прежний)] = ответ if isinstance(ответ, dict) else {}
    return операции


def оценить(сценарий: dict, записи: dict[int, dict], вердикты: Вердикты | None,
            операции: dict[tuple[str, str], dict] | None = None) -> dict:
    """Оценка сценария: по записи на реплику ожиданий и сверка словаря последней реплики.

    `операции` — что извлекатель фактов сделал на каждой реплике (`операции_извлекателя`): по ним
    видно, не изменила ли словарь сама последняя реплика."""
    реплики = []
    for номер, ожидание in enumerate(сценарий["реплики"], 1):
        запись = записи.get(номер)
        if запись is None or запись.get("status") != "ok":
            причина = "записи в журнале нет" if запись is None else (запись.get("error") or f"статус {запись.get('status')}")
            реплики.append({"n": номер, "вид": ожидание["вид"], "нет_записи": True, "ошибка": причина})
            continue
        реплика = запись.get("query") or ""
        ответ = запись.get("response") or ""
        сообщения = запись.get("messages") or [{}]
        отправленное = сообщения[-1].get("content") or ""
        куски = cite.найденное(отправленное, реплика)
        разбор = cite.разобрать(ответ)
        словарь = словарь_фактов(сообщения[0].get("content") or "") if сообщения[0].get("role") == "system" else {}
        начало = ожидание.get("источники_из")
        дословных = sum(cite.цитата_дословна(ц, куски or []) for ц in разбор.цитаты)
        годны = bool(разбор.источники) and all(cite.источник_годен(с, куски or []) for с in разбор.источники)
        # Ограничение сверяется по НАЙДЕННЫМ кускам, на которые ответ опирается, — и источниками, и
        # цитатами: путь, напечатанный в строке источника, модель могла выдумать, а цитату взять из
        # запретного куска при разрешённом источнике. Негодные источники — ограничение не доказано.
        номера = [с.номер for с in разбор.источники] + [ц.номер for ц in разбор.цитаты]
        опора = [(куски or [])[н - 1].источник if н is not None and 1 <= н <= len(куски or []) else None for н in номера]
        итог = {
            "n": номер, "вид": ожидание["вид"], "нет_записи": False, "реплика": реплика, "ответ": ответ,
            "ссылка": bool(ожидание.get("ссылка")), "вопрос_поиска": вопрос_поиска(отправленное[len(cite.ЗАГОЛОВОК_НАЙДЕННОГО):].lstrip())
            if куски is not None else None,
            "поиск_был": куски is not None, "порог": куски == [] and cite.ПУСТО in отправленное,
            "отказ": разбор.отказ, "уточнение": разбор.уточнение, "словарь": словарь,
            "источников": len(разбор.источники),
            "источники_годны": годны,
            "цитат": len(разбор.цитаты), "дословных": дословных,
            "цитаты_годны": bool(разбор.цитаты) and дословных == len(разбор.цитаты),
            "источники_из": начало,
            "ограничение": None if not начало else годны and all(путь is not None and путь.startswith(начало) for путь in опора),
            "судья": None,
        }
        if ожидание["вид"] == "ответ" and not разбор.отказ and вердикты is not None:
            итог["судья"] = вердикты.вердикт(f"{сценарий['agent']}:{номер}", сценарий["цель"], словарь, реплика, разбор.ответ)
        реплики.append(итог)

    последний = next((р["словарь"] for р in reversed(реплики) if not р["нет_записи"]), {})
    нет = [о for о in сценарий.get("словарь", []) if not any(подходит(к, з, о) for к, з in последний.items())]
    лишние = [о for о in сценарий.get("снято", []) if any(подходит(к, з, о) for к, з in последний.items())]
    число = len(сценарий["реплики"])
    последние = (операции or {}).get(_ключ_операций((записи.get(число) or {}).get("query") or "", последний), {})
    return {"agent": сценарий["agent"], "цель": сценарий["цель"], "реплики": реплики, "словарь": последний,
            "нет_в_словаре": нет, "не_снято": лишние,
            "словарь_целиком": not реплики[-1]["нет_записи"],
            # Записей больше, чем ожиданий, — ожидания сдвинуты относительно наряда.
            "лишние_записи": sorted(н for н in записи if н > число),
            # Словарь реплики — состояние ДО неё. Последняя реплика сама изменила словарь — сверен
            # не итог. Редакция словаря для этого не годится: она растёт на каждой реплике, и при
            # пустых операциях извлекателя.
            "словарь_изменён_последней": bool(последние.get("set") or последние.get("forget")),
            "сбои_извлекателя": sorted(н for н, з in записи.items() if н <= число and з.get("facts_error"))}


def _да(условие: bool | None) -> str:
    return "—" if условие is None else ("да" if условие else "**нет**")


def _цитатой(текст: str) -> str:
    return "\n".join("> " + строка for строка in текст.strip().splitlines()) or "> (пусто)"


def _ожидание(ожидание: dict) -> str:
    return "`" + ожидание["приставка"] + "`" + "".join(f" + «{п}»" for п in ожидание.get("содержит", []))


def сводка(оценка: dict) -> dict:
    """Числа сценария — те же, что в отчёте: ими же пользуется README дня."""
    есть = [р for р in оценка["реплики"] if not р["нет_записи"]]
    ответы = [р for р in есть if р["вид"] == "ответ"]
    отказы = [р for р in есть if р["вид"] == "отказ"]
    с_ограничением = [р for р in ответы if р["источники_из"] and not р["отказ"]]
    судимые = [р for р in ответы if р["судья"] is not None]
    return {
        "реплик": len(оценка["реплики"]), "записей": len(есть),
        "поиск": sum(р["поиск_был"] for р in есть),
        "ответов": len(ответы),
        "источники": sum(р["источники_годны"] for р in ответы),
        "цитаты": sum(р["цитаты_годны"] for р in ответы),
        "цитат_всего": sum(р["цитат"] for р in ответы), "дословных": sum(р["дословных"] for р in ответы),
        "ложных_отказов": sum(р["отказ"] for р in ответы),
        "с_ограничением": len(с_ограничением), "ограничение": sum(bool(р["ограничение"]) for р in с_ограничением),
        "судимых": len(судимые), "служит": sum(р["судья"]["вердикт"] == "служит" for р in судимые),
        "отказов": len(отказы), "верных_отказов": sum(р["отказ"] and р["уточнение"] for р in отказы),
    }


def отчёт(оценки: list[dict], наряды: str, фиксация: str | None) -> str:
    строки = ["# Проверка дня 25: мини-чат с RAG и памятью задачи", "",
              f"Наряд `{наряды}`" + (f"; сценарии и ожидания зафиксированы до прогона — `{фиксация}`" if фиксация else "") + ".",
              "Память задачи — словарь фактов разговора (Sticky Facts); в запрос уходят только четыре последние пары,",
              "так что зафиксированное в начале доходит до модели только через словарь.", ""]
    for оценка in оценки:
        ч = сводка(оценка)
        строки += [f"## Сценарий «{оценка['agent']}»", "", f"Цель: {оценка['цель']}", ""]
        if ч["записей"] < ч["реплик"]:
            нет = ", ".join(f"{р['n']} ({р['ошибка']})" for р in оценка["реплики"] if р["нет_записи"])
            строки += [f"**Реплик в журнале {ч['записей']} из {ч['реплик']}** — нет: {нет}. Числа ниже — по имеющимся.", ""]
        строки += [
            f"- **поиск состоялся: {ч['поиск']} из {ч['записей']}** реплик;",
            f"- **источники в ответе: {ч['источники']} из {ч['ответов']}** — раздел непуст и каждый источник найден на эту реплику;",
            f"- **цитаты: {ч['цитаты']} из {ч['ответов']}** ответов — раздел непуст и все цитаты дословны ({ч['дословных']} из {ч['цитат_всего']} цитат);",
            f"- **ограничение на источники соблюдено: {ч['ограничение']} из {ч['с_ограничением']}** реплик, где оно действует;",
            f"- **цель удержана: {ч['служит']} из {ч['судимых']}** ответов по существу — вердикт судьи «служит»;",
            f"- ложных отказов на вопросы по базе: {ч['ложных_отказов']} из {ч['ответов']};",
            f"- **«Не знаю» с просьбой уточнить на далёкий вопрос: {ч['верных_отказов']} из {ч['отказов']}**;",
            "- **память задачи на последней реплике:** "
            + ("реплики нет — не сверено" if not оценка["словарь_целиком"] else
               ("всё ожидаемое на месте" if not оценка["нет_в_словаре"] else
                "нет " + ", ".join(_ожидание(о) for о in оценка["нет_в_словаре"]))
               + ("; отменённое снято" if not оценка["не_снято"] else
                  "; **не снято** " + ", ".join(_ожидание(о) for о in оценка["не_снято"]))) + ".",
        ]
        if оценка["лишние_записи"]:
            строки.append(f"- **в журнале есть реплики сверх ожиданий: {оценка['лишние_записи']}** — ожидания сдвинуты относительно наряда;")
        if оценка["словарь_изменён_последней"]:
            строки.append("- **последняя реплика изменила словарь** — сверено состояние до неё, а не итог;")
        if оценка["сбои_извлекателя"]:
            строки.append(f"- **извлечение фактов не удалось на репликах {оценка['сбои_извлекателя']}** — память задачи могла не обновиться;")
        строки += ["", "| № | реплика | поиск по | источники | цитаты | ограничение | цель | отказ |", "|---|---|---|---|---|---|---|---|"]
        for р in оценка["реплики"]:
            if р["нет_записи"]:
                строки.append(f"| {р['n']} | — | — | — | — | — | — | нет записи: {р['ошибка']} |")
                continue
            искали = "поиска не было" if not р["поиск_был"] else (
                "развёрнут" if р["вопрос_поиска"] else ("**не развёрнут**" if р["ссылка"] else "как есть"))
            if р["порог"]:
                искали += ", порог"
            # Ложный отказ в сводке — провал по источникам и цитатам; в таблице он показан тем же
            # «нет», а не прочерком, чтобы счёт по таблице сходился со сводкой.
            отвечал = р["вид"] == "ответ"
            отказ = {("ответ", False): "", ("ответ", True): "**ложный**", ("отказ", True): "верный" if р["уточнение"] else "без уточнения",
                     ("отказ", False): "**ответил**"}[(р["вид"], р["отказ"])]
            коротко = " ".join(р["реплика"].split())[:70]
            источники = _да(р["источники_годны"]) if отвечал else "—"
            цитаты = f"{_да(р['цитаты_годны'])} ({р['дословных']}/{р['цитат']})" if отвечал else "—"
            # У отказа ограничение не судится — как в сводке, где отказы в его знаменатель не входят.
            ограничение = _да(р["ограничение"]) if отвечал and not р["отказ"] else "—"
            цель = р["судья"]["вердикт"] if р["судья"] else "—"
            строки.append(f"| {р['n']} | {коротко} | {искали} | {источники} | {цитаты} | {ограничение} | {цель} | {отказ} |")
        строки += ["", "### Память задачи на последней реплике" + ("" if оценка["словарь_целиком"] else " из имеющихся"), ""]
        строки += [f"- `{ключ}`: {значение}" for ключ, значение in оценка["словарь"].items()] or ["(словарь пуст)"]
        строки += ["", "### Реплики и ответы", ""]
        for р in оценка["реплики"]:
            if р["нет_записи"]:
                continue
            строки += [f"**{р['n']}. {р['реплика']}**", ""]
            if р["вопрос_поиска"]:
                строки += [f"Поиск по: «{р['вопрос_поиска']}»" + (" — реплика с отсылкой" if р["ссылка"] else ""), ""]
            строки += [_цитатой(р["ответ"]), ""]
            if р["судья"]:
                строки += [f"Судья: **{р['судья']['вердикт']}** — {р['судья']['довод']}", ""]
    return "\n".join(строки).rstrip() + "\n"


def главная(argv: list[str] | None = None) -> None:
    разбор = argparse.ArgumentParser(prog="chat_eval", description="Отчёт дня 25 по журналу наряда из реплик")
    разбор.add_argument("--journal", type=Path, required=True)
    разбор.add_argument("--run", required=True, action="append",
                        help="run_id наряда; повтор задания после сетевого сбоя — ещё один --run")
    разбор.add_argument("--expect", type=Path, required=True, help="файл ожиданий сценариев")
    разбор.add_argument("--verdicts", type=Path, required=True, help="файл вердиктов судьи (заводится)")
    разбор.add_argument("--commit", help="фиксация, в которой сценарии и ожидания легли до прогона")
    разбор.add_argument("--out", type=Path)
    доводы = разбор.parse_args(argv)
    сценарии = json.loads(доводы.expect.read_text("utf-8"))["сценарии"]
    вердикты = Вердикты(доводы.verdicts)
    оценки, наряды = [], []
    for сценарий in сценарии:
        записи, наряд = записи_сценария(доводы.journal, доводы.run, сценарий["agent"])
        if наряд is None:
            sys.exit(f"chat_eval: в {доводы.journal} нет записей задания «{сценарий['agent']}» нарядов {', '.join(доводы.run)}")
        if наряд not in наряды:
            наряды.append(наряд)
        try:
            оценки.append(оценить(сценарий, записи, вердикты, операции_извлекателя(доводы.journal, наряд)))
        except пер.ОшибкаПереписывания as exc:
            sys.exit(f"chat_eval: судья не ответил: {exc}")
        except ValueError as exc:
            sys.exit(f"chat_eval: {exc}")
    текст = отчёт(оценки, ", ".join(наряды), доводы.commit)
    if доводы.out:
        доводы.out.write_text(текст, "utf-8")
        print(f"записано: {доводы.out}")
    else:
        print(текст)


if __name__ == "__main__":
    главная()
