"""Отчёт дня 25: длинные диалоги с RAG и памятью задачи — по журналу наряда `myharness`.

Наряд несёт задания из нескольких реплик (`asks`): каждая реплика — запись журнала с именем
задания в `agent` и номером обмена в `index`. По каждой реплике отчёт отвечает на вопросы условия:

1. **Источники.** Раздел «Источники» непуст, и каждый названный источник — кусок, найденный на
   ЭТУ реплику (`cite.источник_годен`): источник, перенесённый из прошлого ответа, не годен.
2. **Цитаты.** Раздел «Цитаты» непуст, и каждая цитата дословно стоит в названном куске.
3. **Ограничение на источники**, зафиксированное человеком в разговоре: источники годны, и путь
   каждого найденного куска, на который ответ сослался источником ИЛИ цитатой, начинается с
   разрешённого начала (поле `источники_из` ожиданий).
4. **Цель.** Судья (`deepseek-v4-pro`, рассуждения включены) получает цель, словарь фактов, с
   которым отвечала модель, реплику и раздел «Ответ» и решает: «служит», «уходит в сторону»,
   «нарушает».
5. **Отказ.** На далёкий вопрос (`вид: отказ`) ответ начинается с «Не знаю» и просит уточнить; на
   вопрос по базе отказ — ложный.
6. **Память задачи.** Словарь фактов последней реплики сверяется с ожидаемыми ключами сценария:
   что обязано быть и что обязано быть снято.

Словарь реплики — блок «Факты текущего разговора (Sticky Facts):» системного сообщения ЕЁ запроса,
то есть состояние памяти ДО этой реплики: сценарий строится так, что последние реплики ничего не
фиксируют. Развёрнутый вопрос поиска — первая строка блока найденного (`server.ВОПРОС_ДЛЯ_ПОИСКА`).

Файл ожиданий (`--expect`):

    {"сценарии": [{"agent": "<имя задания>", "цель": "<словами>",
                   "словарь": [{"приставка": "цель", "содержит": ["памятк"]}],
                   "снято":   [{"приставка": "ограничение", "содержит": ["openspec"]}],
                   "реплики": [{"вид": "ответ", "ссылка": false, "источники_из": null}]}]}

`реплики` — по записи на реплику наряда, в том же порядке. Ключ подходит под ожидание, когда он
начинается с `приставка`, а ключ вместе со значением содержит каждую подстроку из `содержит` (без
учёта регистра).

Повтор задания после сетевого сбоя — ещё один `--run`: у каждого сценария берутся записи
ПОСЛЕДНЕГО из названных нарядов, где он есть, целиком — реплики разных прогонов не смешиваются.

Вердикты судьи пишутся файлом `--verdicts`: отчёт пересобирается без повторной оплаты.

Запуск: `uv run --project rag rag/chat_eval.py --journal <журнал> --run <run_id> --expect <файл>
--verdicts <файл.json> [--commit <фиксация сценариев>] [--out <отчёт.md>]`.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import sys
from pathlib import Path
from typing import Callable

import cite
