#!/usr/bin/env python3
"""Расход задачи в токенах и деньгах — по обеим средам разработки.

Считает две базы сразу:
  * записи Claude Code — `~/.claude/projects/<копия>/*.jsonl` (ведущий)
    и `<сеанс>/subagents/*.jsonl` (помощники). Без второго видно меньше половины расхода:
    за 2026-09-10 ведущий дал 189 млн входа, помощники — ещё 110 млн;
  * `~/.omp/stats.db` — записи OMP, где у задачи может идти другой день.

Задание дня живёт в своей рабочей копии, а правки инструмента — в `main`, поэтому по умолчанию
берутся ВСЕ рабочие копии челленджа: расход одной задачи иначе распадается на две половины.

Ничего не пишет и не меняет. Запуск:
    python3 bin/расход.py                        все дни, все рабочие копии
    python3 bin/расход.py --день 2026-09-10      один день
    python3 bin/расход.py --с 2026-09-10 --по 2026-09-11    задача, занявшая два дня
    python3 bin/расход.py --копия ~/challenge/w2d4          только одна рабочая копия
"""

from __future__ import annotations

import argparse
import collections
import json
import re
import sqlite3
from datetime import datetime
from pathlib import Path

# Тарифы за миллион токенов: вход, запись запомненного начала, чтение запомненного, выход.
# Сверять с действующим прейскурантом: цена меняется, а число в коде — нет.
ТАРИФЫ = {
    "opus": (15.0, 18.75, 1.5, 75.0),
    "sonnet": (3.0, 3.75, 0.3, 15.0),
    "haiku": (1.0, 1.25, 0.1, 5.0),
}

ДОМ_ЧЕЛЛЕНДЖА = Path.home() / "challenge"


def тариф(модель: str) -> tuple[float, float, float, float] | None:
    """Тариф по имени модели. Неизвестная модель — None, а не молчаливый ноль."""
    for ключ, значения in ТАРИФЫ.items():
        if ключ in модель:
            return значения
    return None


class Счёт:
    """Накопитель расхода. Деньги неизвестной модели не подменяются нулём."""

    def __init__(self) -> None:
        self.обменов = 0
        self.вход = 0          # свежий вход плюс запись запомненного начала
        self.кэш = 0           # чтение запомненного начала
        self.выход = 0
        self.деньги = 0.0
        self.без_тарифа = 0

    def добавить(self, u: dict, модель: str) -> None:
        свежий = u.get("input_tokens", 0)
        запись = u.get("cache_creation_input_tokens", 0)
        чтение = u.get("cache_read_input_tokens", 0)
        выход = u.get("output_tokens", 0)
        self.обменов += 1
        self.вход += свежий + запись
        self.кэш += чтение
        self.выход += выход
        т = тариф(модель)
        if т is None:
            self.без_тарифа += 1
            return
        цв, цз, цч, цо = т
        self.деньги += (свежий * цв + запись * цз + чтение * цч + выход * цо) / 1e6

    def влить(self, другой: "Счёт") -> None:
        self.обменов += другой.обменов
        self.вход += другой.вход
        self.кэш += другой.кэш
        self.выход += другой.выход
        self.деньги += другой.деньги
        self.без_тарифа += другой.без_тарифа

    @property
    def всего_входа(self) -> int:
        return self.вход + self.кэш


def пустой_день() -> dict[str, Счёт]:
    return {"ведущий": Счёт(), "помощники": Счёт()}


def имя_каталога(копия: Path) -> str:
    """Имя каталога записей Claude Code. Все знаки, кроме букв и цифр, становятся дефисом:
    так закодирован, например, путь с пробелами и тильдами внутри облачной папки."""
    return re.sub(r"[^A-Za-z0-9]", "-", str(копия))


def имя_omp(копия: Path) -> str:
    """Имя папки в записях OMP: путь без домашнего каталога, знаки — дефисами.
    `~/challenge/main` там записан как `-challenge-main`."""
    try:
        хвост = копия.relative_to(Path.home())
    except ValueError:
        хвост = копия
    return "-" + re.sub(r"[^A-Za-z0-9]", "-", str(хвост))


def рабочие_копии(заданные: list[str] | None) -> list[Path]:
    if заданные:
        return [Path(п).expanduser().resolve() for п in заданные]
    if ДОМ_ЧЕЛЛЕНДЖА.is_dir():
        копии = [д for д in sorted(ДОМ_ЧЕЛЛЕНДЖА.iterdir()) if (д / ".git").exists()]
        if копии:
            return копии
    return [Path.cwd()]


def местный_день(метка: str) -> str:
    """День по местному времени. Рабочий день кончается около местной полуночи, а не UTC:
    по UTC вечерняя работа уехала бы в следующие сутки."""
    try:
        return datetime.fromisoformat(метка.replace("Z", "+00:00")).astimezone().strftime("%Y-%m-%d")
    except ValueError:
        return метка[:10]


def собрать_claude(копии: list[Path]) -> tuple[dict[str, dict[str, Счёт]], list[Path]]:
    """Расход Claude Code по дням: ведущий и помощники раздельно. Возвращает ещё и список
    копий, для которых записей не нашлось, — молчаливый ноль здесь опаснее всего."""
    итог: dict[str, dict[str, Счёт]] = collections.defaultdict(пустой_день)
    без_записей: list[Path] = []
    видели: set[str] = set()
    for копия in копии:
        корень = Path.home() / ".claude" / "projects" / имя_каталога(копия)
        if not корень.is_dir():
            без_записей.append(копия)
            continue
        источники = [("ведущий", корень.glob("*.jsonl")), ("помощники", корень.glob("*/subagents/*.jsonl"))]
        for роль, файлы in источники:
            for файл in файлы:
                for строка in файл.open(encoding="utf-8", errors="replace"):
                    if '"usage"' not in строка:
                        continue
                    try:
                        запись = json.loads(строка)
                    except json.JSONDecodeError:
                        continue
                    сообщение = запись.get("message") or {}
                    расход = сообщение.get("usage") or {}
                    # Записи без единого токена — служебные: они не расход, а шум в счётчике.
                    if not any(расход.get(поле) for поле in
                               ("input_tokens", "output_tokens",
                                "cache_read_input_tokens", "cache_creation_input_tokens")):
                        continue
                    # Отметка ставится ПОСЛЕ проверки расхода: иначе пустая запись заняла бы
                    # ключ, а настоящая с тем же ключом молча выпала бы из счёта.
                    ключ = запись.get("requestId")
                    if ключ:
                        if ключ in видели:
                            continue
                        видели.add(ключ)
                    день = местный_день(запись.get("timestamp") or "")
                    итог[день][роль].добавить(расход, сообщение.get("model") or "")
    return итог, без_записей


def собрать_omp(копии: list[Path]) -> dict[str, dict[str, Счёт]]:
    """Расход OMP по дням. Деньги берём из самой базы: там свои тарифы поставщика.
    Отбор по папке — тот же, что у Claude Code, иначе чужие задачи попадут в счёт."""
    база = Path.home() / ".omp" / "stats.db"
    итог: dict[str, dict[str, Счёт]] = collections.defaultdict(пустой_день)
    if not база.exists():
        return итог
    связь = sqlite3.connect(f"file:{база}?mode=ro", uri=True)
    try:
        строки = связь.execute(
            "SELECT date(timestamp/1000,'unixepoch','localtime'), agent_type, folder,"
            "       SUM(input_tokens), SUM(cache_write_tokens), SUM(cache_read_tokens),"
            "       SUM(output_tokens), SUM(cost_total), COUNT(*)"
            " FROM messages GROUP BY 1,2,3"
        ).fetchall()
    finally:
        связь.close()
    # Голое имя каталога («main») в набор НЕ входит: папка с тем же именем из чужого проекта
    # прошла бы отбор и приписала бы его расход этой задаче.
    свои = {str(к) for к in копии} | {имя_каталога(к) for к in копии} | {имя_omp(к) for к in копии}
    чужие: set[str] = set()
    for день, роль_омп, папка, вход, запись, чтение, выход, деньги, обменов in строки:
        if папка and str(папка) not in свои:
            чужие.add(str(папка))
            continue
        счёт = итог[день]["ведущий" if роль_омп == "main" else "помощники"]
        счёт.обменов += обменов
        счёт.вход += (вход or 0) + (запись or 0)
        счёт.кэш += чтение or 0
        счёт.выход += выход or 0
        счёт.деньги += деньги or 0.0
    if чужие:
        print("записи OMP других папок пропущены: " + ", ".join(sorted(чужие)))
    return итог


def слить(*источники: dict[str, dict[str, Счёт]]) -> dict[str, dict[str, Счёт]]:
    дни: dict[str, dict[str, Счёт]] = collections.defaultdict(пустой_день)
    for источник in источники:
        for день, роли in источник.items():
            for роль, счёт in роли.items():
                дни[день][роль].влить(счёт)
    return дни


def напечатать(дни: dict[str, dict[str, Счёт]], с: str | None, по: str | None) -> None:
    шапка = (f"{'день':12}{'вед.':>7}{'пом.':>7}{'вход вед.':>15}{'вход пом.':>15}"
             f"{'ВСЕГО':>15}{'выход':>10}{'$':>9}")
    print(шапка)
    print("-" * len(шапка))
    итого = пустой_день()
    for день in sorted(дни):
        if с and день < с:
            continue
        if по and день > по:
            continue
        в, п = дни[день]["ведущий"], дни[день]["помощники"]
        итого["ведущий"].влить(в)
        итого["помощники"].влить(п)
        деньги = в.деньги + п.деньги
        пометка = f"{деньги:8.0f}$" if not (в.без_тарифа + п.без_тарифа) else f"{деньги:7.0f}$?"
        print(f"{день:12}{в.обменов:7}{п.обменов:7}{в.всего_входа:15,}{п.всего_входа:15,}"
              f"{в.всего_входа + п.всего_входа:15,}{в.выход + п.выход:10,}{пометка:>9}")
    в, п = итого["ведущий"], итого["помощники"]
    print("-" * len(шапка))
    print(f"{'ИТОГО':12}{в.обменов:7}{п.обменов:7}{в.всего_входа:15,}{п.всего_входа:15,}"
          f"{в.всего_входа + п.всего_входа:15,}{в.выход + п.выход:10,}{в.деньги + п.деньги:8.0f}$")
    if в.без_тарифа + п.без_тарифа:
        print(f"\nобменов с неизвестным тарифом: {в.без_тарифа + п.без_тарифа} — "
              f"деньги по ним не посчитаны (знак «?»)")


def main() -> int:
    разбор = argparse.ArgumentParser(description="Расход задачи по записям Claude Code и OMP")
    разбор.add_argument("--день", help="только этот день, вида 2026-09-10")
    разбор.add_argument("--с", dest="с", help="первый день задачи")
    разбор.add_argument("--по", dest="по", help="последний день задачи")
    разбор.add_argument("--копия", action="append",
                        help="рабочая копия; можно повторять. По умолчанию — все копии в ~/challenge")
    ключи = разбор.parse_args()
    if ключи.день and (ключи.с or ключи.по):
        разбор.error("--день и --с/--по вместе не имеют смысла: выберите одно")
    с, по = (ключи.день, ключи.день) if ключи.день else (ключи.с, ключи.по)

    копии = рабочие_копии(ключи.копия)
    claude, без_записей = собрать_claude(копии)
    дни = слить(claude, собрать_omp(копии))
    print("рабочие копии: " + ", ".join(str(к) for к in копии))
    if без_записей:
        print("записей Claude Code не найдено для: " + ", ".join(str(к) for к in без_записей))
    if not дни:
        print("записей не найдено")
        return 1
    напечатать(дни, с, по)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
