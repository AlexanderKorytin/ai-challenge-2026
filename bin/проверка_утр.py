#!/usr/bin/env python3
"""Проверки счётчика `bin/утр.py`. Запуск: python3 bin/проверка_утр.py

Пары «ровно на границе / за границей»: каждая пара отличается ровно тем, что правило считает.
Таблица запретных слов берётся из временного файла, настоящие правила не читаются.
"""

from __future__ import annotations

import importlib.util
import subprocess
import sys
import tempfile
from pathlib import Path

_описание = importlib.util.spec_from_file_location("утр", Path(__file__).with_name("утр.py"))
утр = importlib.util.module_from_spec(_описание)
_описание.loader.exec_module(утр)

ТАБЛИЦА = """# Правила

## Запретные слова

| Слово | Писать | Программа |
|---|---|---|
| коммит | фиксация | да |
| нет | цепь | нет |

## Дальше

| деплой | развёртывание | да |
"""


def ряд(число: int) -> str:
    return " ".join(["слово"] * число)


def имена(текст: str, начала: list[str] = []) -> list[str]:
    return [имя for _, имя, _ in утр.нарушения(текст, начала)]


def проверка_длины_на_границе() -> None:
    assert имена(ряд(20) + ".") == []
    assert имена(ряд(21) + ".") == ["длина 21"]


def проверка_подсчёта_слов() -> None:
    assert утр.слова("запусти `git rebase -i HEAD~3 --autosquash` сейчас") == 3
    assert утр.слова("он сказал «сойдёт для прототипа, потом поправим» и ушёл") == 5
    assert утр.слова("окно равно 1 048 576 токенов — много") == 5
    assert утр.слова("читай [раздел о памяти](https://example.org/a b) целиком") == 5
    assert утр.слова("кто-то — что-то") == 2


def проверка_скобок() -> None:
    assert имена(f"{ряд(18)} ({ряд(5)}).") == []
    assert имена(f"{ряд(18)} {ряд(5)}.") == ["длина 23"]
    assert имена(f"{ряд(3)} ({ряд(21)}).") == ["длина 21"]
    assert утр.предложения("Первое (вставка). Второе.") == ["Первое .", "Второе.", "вставка"]
    # Скобки внутри обратных кавычек — часть имени, а не вставка.
    assert утр.слова("вызови `f(a, b)` дважды") == 3
    assert утр.предложения("Вызови `f(a, b)` дважды.") == ["Вызови `f(a, b)` дважды."]


def проверка_пропусков() -> None:
    длинное = ряд(30) + "."
    assert имена(длинное) == ["длина 30"]
    assert имена(f"```\n{длинное}\n```") == []
    assert имена(f"| {длинное} |") == []
    assert имена(f"## {длинное}") == []
    assert имена(f"---\nname: {длинное}\n---\n\nКоротко.") == []
    assert имена(f"---\nname: а\n---\n\n{длинное}") == ["длина 30"]
    assert имена(f"> {длинное}") == ["длина 30"]


def проверка_абзаца_на_границе() -> None:
    assert имена(" ".join(["Одно предложение."] * 6)) == []
    assert имена(" ".join(["Одно предложение."] * 7)) == ["абзац 7"]
    assert имена("\n".join(["- Одно предложение."] * 7)) == []
    assert имена("- " + " ".join(["Одно предложение."] * 7)) == []


def проверка_запретных_слов() -> None:
    with tempfile.TemporaryDirectory() as каталог:
        правила = Path(каталог) / "правила.md"
        правила.write_text(ТАБЛИЦА, encoding="utf-8")
        начала = утр.запретные(правила)
        assert начала == ["коммит"], начала
        пустые = Path(каталог) / "пусто.md"
        пустые.write_text("# Правила без таблицы\n", encoding="utf-8")
        try:
            утр.запретные(пустые)
        except ValueError:
            pass
        else:
            raise AssertionError("файл без таблицы обязан дать ValueError")
    assert имена("Сделал два Коммита подряд.", начала) == ["слово коммит"]
    assert имена("Запусти `git commit` и `коммит`.", начала) == []
    assert имена("Слово «коммит» запрещено.", начала) == []
    assert имена("Комитет решил, что цепи нет.", начала) == []
    assert имена("Коммит и ещё коммиты.", начала) == ["слово коммит"]


def проверка_номеров_строк() -> None:
    текст = f"# Заголовок\n\nКоротко.\nВторое короткое. {ряд(21).capitalize()}.\n\n- пункт\n- {ряд(22)}.\n"
    assert [(строка, имя) for строка, имя, _ in утр.нарушения(текст, [])] == [
        (4, "длина 21"),
        (7, "длина 22"),
    ]
    перенос = f"Начало `имя\nс переносом` тут. {ряд(21).capitalize()}.\nХвост.\n{ряд(23).capitalize()}."
    assert [(строка, имя) for строка, имя, _ in утр.нарушения(перенос, [])] == [
        (2, "длина 21"),
        (4, "длина 23"),
    ]


def проверка_выделения_не_прячет_разрыв() -> None:
    assert имена(f"**{ряд(12).capitalize()}.** {ряд(12).capitalize()}.") == []
    assert имена(f"{ряд(12).capitalize()}. **{ряд(12).capitalize()}.**") == []
    assert имена(f"**{ряд(12).capitalize()}** {ряд(12)}.") == ["длина 24"]
    assert утр.предложения("**Первое.** Второе. **Третье.**") == ["**Первое.**", "Второе.", "**Третье.**"]


def проверка_вложенных_цитат() -> None:
    assert утр.слова(f"Он сказал «{ряд(10)} «внутри» {ряд(10)}» и ушёл совсем.") == 6
    assert утр.слова(f"Он сказал {ряд(10)} «внутри» {ряд(10)} и ушёл совсем.") == 26


def проверка_разрыва_перед_любым_началом() -> None:
    # Второе предложение начинается не с прописной буквы — разрыв всё равно есть.
    for начало in ("myharness", "—", "~70", "`имя`", "«цитата»"):
        assert имена(f"{ряд(11).capitalize()}. {начало} {ряд(10)}.") == [], начало
    assert имена(f"{ряд(11).capitalize()}, {ряд(11)}.") == ["длина 22"]


def проверка_сокращений() -> None:
    # После сокращения из списка разрыва нет: длинное предложение не прячется.
    for сокращение, длина in (("см. `docs/vps.md`", 25), ("т. е. «окно»", 26), ("п. 8.2.5.1", 25)):
        итог = имена(f"{ряд(12).capitalize()}, {сокращение} {ряд(11)}.")
        assert итог == [f"длина {длина}"], (сокращение, итог)
    # Сокращение с прописной буквы — то же сокращение.
    assert утр.предложения("См. `docs/vps.md` и т. п. Потом всё.") == [
        "См. `docs/vps.md` и т. п.",
        "Потом всё.",
    ]
    # Слово-двойник сокращения в конце предложения: перед прописной буквой разрыв есть.
    for конец in ("доверяют им.", "в 2026 г.", "длиной 5 см.", "около 0,2 млн.", "в 90-е."):
        assert имена(f"{ряд(10).capitalize()} {конец} {ряд(11).capitalize()}.") == [], конец
    assert имена(f"{ряд(10).capitalize()} длиной 5 см. {ряд(11)}.") == ["длина 24"]
    # Без сокращения та же точка предложение кончает.
    assert имена(f"{ряд(12).capitalize()}. Ленина {ряд(11)}.") == []
    # Сокращением «и т. д.» предложение кончаться может.
    assert имена(f"{ряд(12).capitalize()} и т. д. Потом {ряд(11)}.") == []
    assert имена(f"{ряд(12).capitalize()} и т. д. потом {ряд(11)}.") == ["длина 27"]
    # Ссылки на пункты счёт предложений абзаца не раздувают.
    пункты = "Правило взято из п. 8.2.5.1 и п. 8.2.6.1 стандарта. "
    assert имена(пункты * 6) == []
    assert имена(пункты * 7) == ["абзац 7"]


def проверка_полей_шага() -> None:
    поля = f"**Файлы**: {ряд(8)}\n**Ход**: быстрый\n**Проверка**: {ряд(12)}"
    assert имена(поля) == []
    assert имена(поля.replace("\n", " ")) == ["длина 24"]
    # Блок полей — не абзац: в счёт предложений строки полей не входят.
    assert имена("\n".join(f"**Поле{н}**: значение" for н in range(7))) == []
    assert имена("\n".join(f"Поле{н}: значение." for н in range(7))) == ["абзац 7"]


def проверка_приставки() -> None:
    assert имена("Надо закоммитить и перекоммитить.", ["коммит"]) == ["слово коммит"]
    assert имена("Комитет и закон.", ["коммит"]) == []


def проверка_заголовка_и_черты() -> None:
    длинное = ряд(30).capitalize() + "."
    assert имена(f"---\n\n{длинное}\n\n---\n\n{длинное}") == ["длина 30", "длина 30"]
    assert имена(f"Задача\n#3 {ряд(30)}.") == ["длина 32"]
    assert имена(f"Задача\n# {ряд(30)}.") == []


def проверка_запуска() -> None:
    программа = str(Path(__file__).with_name("утр.py"))
    with tempfile.TemporaryDirectory() as каталог:
        правила = Path(каталог) / "правила.md"
        правила.write_text(ТАБЛИЦА, encoding="utf-8")
        чистый = Path(каталог) / "чистый.md"
        чистый.write_text("Коротко.\n", encoding="utf-8")
        грязный = Path(каталог) / "грязный.md"
        грязный.write_text(f"Коротко.\n\nСделал коммит. {ряд(21).capitalize()}.\n", encoding="utf-8")

        def запуск(*доводы: str) -> subprocess.CompletedProcess[str]:
            return subprocess.run(
                [sys.executable, программа, *доводы], capture_output=True, text=True, check=False
            )

        итог = запуск(str(чистый), "--правила", str(правила))
        assert (итог.returncode, итог.stdout) == (0, "длина: 0, абзац: 0, слово: 0\n"), итог
        итог = запуск(str(грязный), "--правила", str(правила))
        assert итог.returncode == 1, итог
        assert итог.stdout.splitlines() == [
            f"{грязный}:3: слово коммит: Сделал коммит.",
            f"{грязный}:3: длина 21: " + (ряд(21).capitalize() + ".")[: утр.ДЛИНА_ОТРЫВКА],
            "длина: 1, абзац: 0, слово: 1",
        ], итог.stdout
        assert запуск(str(Path(каталог) / "нет.md"), "--правила", str(правила)).returncode == 2
        assert запуск(str(чистый), "--правила", str(чистый)).returncode == 2


def проверка_отрывка() -> None:
    ((_, _, отрывок),) = утр.нарушения(f"Имя `git commit` тут {ряд(21)}.", [])
    assert отрывок.startswith("Имя `git commit` тут слово"), отрывок
    assert len(отрывок) == утр.ДЛИНА_ОТРЫВКА


if __name__ == "__main__":
    проверки = [значение for имя, значение in list(globals().items()) if имя.startswith("проверка_")]
    for проверка in проверки:
        проверка()
    print(f"пройдено: {len(проверки)}")
    sys.exit(0)
