#!/usr/bin/env python3
"""Счётчик формы для упрощённого технического русского (ГОСТ Р 58049-2017, п. 8.2).

Считает в файлах Markdown только то, что считается точно:
  * `длина N`  — в предложении N слов, больше 20 (п. 8.2.5.1, 8.2.6.1);
  * `абзац N`  — в абзаце N предложений, больше шести (п. 8.2.6.2); пункты списка не проверяются;
  * `слово X`  — слово начинается с запретного начала X из таблицы «Запретные слова» файла правил.

Подсчёт слов — по примечанию к п. 8.2.5.1: имя в обратных кавычках, цитата в «ёлочках» и число
считаются одним словом, текст в круглых скобках — отдельным предложением. Заголовок YAML, блоки
кода, таблицы, заголовки и строки подключения `@…` пропускаются целиком.

Залог, обороты, цепочки существительных и синонимы программа не считает: это решает пишущий.

Где программа ошибается — названо здесь, чтобы её счёту не верили больше, чем он стоит:
  * сокращение с точкой узнаётся по списку `СОКРАЩЕНИЯ`; сокращение вне списка, как и
    многоточие посреди предложения, даёт лишний разрыв — длинное предложение будет пропущено,
    а счёт предложений абзаца завышен;
  * после сокращения из `ЗАВЕРШАЮЩИЕ` разрыв ставится только перед прописной буквой: «им.
    Ленина» рвётся надвое, а «и т. д. `имя` …» сливает два предложения в одно;
  * строка абзаца, начатая с `- `, `15. `, `|`, `@` или `# `, считается началом пункта списка,
    таблицы или заголовка, как и в Markdown: предложение, перенесённое так, рвётся надвое;
  * запретное слово ищется по началу слова с необязательной приставкой из `ПРИСТАВКИ`; начало
    «пуш» найдёт и «пушку» — строку `слово` пишущий проверяет глазами;
  * слово в «ёлочках» и в обратных кавычках не проверяется: так запретное слово упоминают.

Ничего не пишет и не меняет. Запуск:
    python3 bin/утр.py docs/грабли.md
    python3 bin/утр.py файл1.md файл2.md --правила путь/к/правила.md

Код возврата: 0 — нарушений нет, 1 — есть, 2 — файл или таблица правил не прочитаны.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ПРЕДЕЛ_СЛОВ = 20  # п. 8.2.5.1, 8.2.6.1
ПРЕДЕЛ_ПРЕДЛОЖЕНИЙ = 6  # п. 8.2.6.2
ПРАВИЛА = Path(__file__).resolve().parent.parent / ".claude" / "skills" / "утр" / "правила.md"
РАЗДЕЛ_СЛОВ = "## Запретные слова"
ДЛИНА_ОТРЫВКА = 60
# После этих сокращений точка предложение не кончает.
СОКРАЩЕНИЯ = frozenset(
    "т е д п г гг см им рис стр др пр напр тыс млн млрд табл англ ср н э".split()
)
# Этими сокращениями и их двойниками-словами предложение кончаться может («и т. д.», «5 см.»,
# «доверяют им.», «в 90-е.»): разрыв ставится, если дальше идёт прописная буква.
ЗАВЕРШАЮЩИЕ = frozenset("е д п г гг см им др пр тыс млн млрд э".split())
ПРИСТАВКИ = "за|от|пере|с|по|вы|на|при|раз|про|до"

# Свёрнутый отрезок: знаки личного употребления Юникода вокруг номера в хранилище.
_ОТКР, _ЗАКР = "", ""
_МЕТКА = re.compile(f"{_ОТКР}(\\d+){_ЗАКР}")
_КОД = re.compile(r"`[^`]*`")
_ССЫЛКА = re.compile(r"!?\[([^\]]*)\]\([^)]*\)")
_ЦИТАТА = re.compile(r"«[^«»]*»")
_СКОБКИ = re.compile(r"\(([^()]*)\)")
# Возможный конец предложения: знак, знаки выделения Markdown и закрывающие кавычки, пробел.
_КОНЕЦ = re.compile(r"[.!?…]+[*_\"”]*\s+")
_СЛОВО_ПЕРЕД_ТОЧКОЙ = re.compile(r"([^\W\d_]+)\.$")
# Строка вида `**Имя**: …` посреди абзаца — поле, оно начинает своё предложение.
_ПОЛЕ = re.compile(r"\n[ \t]*(?=\*\*[^*\n]+\*\*:)")
_НАЧАЛО_ПОЛЯ = re.compile(r"\*\*[^*\n]+\*\*:")
_РАЗРЯДЫ = re.compile(r"(?<=\d)[  ](?=\d{3}(?!\d))")
_ЗАГОЛОВОК = re.compile(r"^#{1,6}\s")
_ПУНКТ = re.compile(r"^\s*(?:[-*+]|\d+[.)])\s+")
_ОГРАДА = re.compile(r"^\s*(?:```|~~~)")


def _свернуть(текст: str, хранилище: list[str]) -> str:
    """Заменить отрезки в обратных кавычках и «ёлочках» метками, ссылки — их текстом.

    Число строк сохраняется: переводы строки свёрнутого отрезка ставятся следом за заменой.
    """

    def метка(совпадение: re.Match[str]) -> str:
        хранилище.append(совпадение.group())
        return f"{_ОТКР}{len(хранилище) - 1}{_ЗАКР}" + "\n" * совпадение.group().count("\n")

    текст = _КОД.sub(метка, текст)
    текст = _ССЫЛКА.sub(lambda с: с.group(1) + "\n" * с.group().count("\n"), текст)
    # Вложенные «ёлочки» сворачиваются изнутри наружу: внешняя цитата — тоже одно слово.
    while (свёрнуто := _ЦИТАТА.sub(метка, текст)) != текст:
        текст = свёрнуто
    return текст


def _развернуть(текст: str, хранилище: list[str]) -> str:
    """Вернуть свёрнутые отрезки на место — для показа отрывка человеку."""
    while _МЕТКА.search(текст):
        текст = _МЕТКА.sub(lambda с: хранилище[int(с.group(1))], текст)
    return " ".join(текст.split())


def _слова(свёрнутое: str) -> int:
    свёрнутое = _РАЗРЯДЫ.sub("", свёрнутое)
    return sum(1 for отрезок in свёрнутое.split() if re.search(r"\w", отрезок))


def слова(предложение: str) -> int:
    """Число слов предложения по правилам подсчёта ГОСТа."""
    return _слова(_свернуть(предложение, []))


def _границы(отрезок: str) -> list[int]:
    """Смещения начал предложений в отрезке и его конец."""
    итог = {0, len(отрезок)}
    for совпадение in _КОНЕЦ.finditer(отрезок):
        перед = _СЛОВО_ПЕРЕД_ТОЧКОЙ.search(отрезок, 0, совпадение.start() + 1)
        if перед and (слово := перед.group(1).lower()) in СОКРАЩЕНИЯ:
            дальше = отрезок[совпадение.end() : совпадение.end() + 1]
            if not (слово in ЗАВЕРШАЮЩИЕ and дальше.isupper()):
                continue
        итог.add(совпадение.end())
    итог.update(совпадение.end() for совпадение in _ПОЛЕ.finditer(отрезок))
    return sorted(итог)


def _разобрать(единица: str, хранилище: list[str]) -> tuple[list[tuple[int, str]], int]:
    """Предложения единицы как пары «сдвиг строки, свёрнутый текст» и число основных предложений.

    Текст в скобках вынимается и идёт отдельными предложениями после основных. Строки полей
    `**Имя**: …` в число основных не входят: блок полей — перечень, а не абзац.
    """
    основа = _свернуть(единица, хранилище)
    вынутое: list[tuple[int, str]] = []
    while True:
        найдено = list(_СКОБКИ.finditer(основа))
        if not найдено:
            break
        вынутое += [(с.start(1), с.group(1)) for с in найдено]
        # Скобки затираются пробелами той же длины: смещения следующего прохода не сдвигаются.
        основа = _СКОБКИ.sub(lambda с: re.sub(r"[^\n]", " ", с.group()), основа)

    итог: list[tuple[int, str]] = []
    основных = 0
    for начало, отрезок in [(None, основа), *sorted(вынутое)]:
        границы = _границы(отрезок)
        for от, до in zip(границы, границы[1:]):
            часть = отрезок[от:до]
            if not _слова(часть):
                continue
            место = (начало or 0) + от + len(часть) - len(часть.lstrip())
            итог.append((основа.count("\n", 0, место), часть.strip()))
            основных += начало is None and not _НАЧАЛО_ПОЛЯ.match(часть.strip())
    return итог, основных


def предложения(единица: str) -> list[str]:
    """Предложения единицы текста; текст в скобках — отдельными предложениями в конце."""
    хранилище: list[str] = []
    return [_развернуть(часть, хранилище) for _, часть in _разобрать(единица, хранилище)[0]]


def единицы(текст: str) -> list[tuple[int, str, bool]]:
    """Абзацы и пункты списка: номер строки начала, текст, признак пункта списка."""
    итог: list[tuple[int, str, bool]] = []
    текущая: list[str] = []
    начало, пункт = 0, False

    def закрыть() -> None:
        if текущая:
            итог.append((начало, "\n".join(текущая), пункт))
            текущая.clear()

    строки = текст.split("\n")
    номер = 0
    if len(строки) > 1 and строки[0].strip() == "---" and строки[1].strip():
        # Заголовок YAML: до закрывающей строки из трёх дефисов. Черта `---` с пустой строкой
        # следом — горизонтальная линия, а не заголовок.
        закрытие = next((н for н in range(1, len(строки)) if строки[н].strip() == "---"), None)
        номер = 0 if закрытие is None else закрытие + 1
    в_коде = False
    for номер in range(номер, len(строки)):
        строка = строки[номер]
        if _ОГРАДА.match(строка):
            в_коде = not в_коде
            закрыть()
            continue
        if в_коде:
            continue
        строка = re.sub(r"^\s*(?:>\s?)+", "", строка)
        голая = строка.strip()
        if not голая or голая[0] in "|@" or _ЗАГОЛОВОК.match(голая):
            закрыть()
            continue
        if _ПУНКТ.match(строка):
            закрыть()
            строка = _ПУНКТ.sub("", строка)
            начало, пункт = номер + 1, True
        elif not текущая:
            начало, пункт = номер + 1, False
        текущая.append(строка)
    закрыть()
    return итог


def запретные(путь_правил: Path) -> list[str]:
    """Начала запретных слов из таблицы правил, у которых в столбце «Программа» стоит «да»."""
    раздел = путь_правил.read_text(encoding="utf-8").partition(РАЗДЕЛ_СЛОВ)[2]
    раздел = re.split(r"^## ", раздел, maxsplit=1, flags=re.MULTILINE)[0]
    начала = []
    for строка in раздел.splitlines():
        ячейки = [ячейка.strip() for ячейка in строка.strip().strip("|").split("|")]
        слово = ячейки[0].strip("`«»").lower()
        if строка.strip().startswith("|") and len(ячейки) == 3 and ячейки[2] == "да" and слово:
            начала.append(слово)
    if not начала:
        raise ValueError(f"в {путь_правил} нет таблицы раздела «{РАЗДЕЛ_СЛОВ[3:]}»")
    return начала


def нарушения(текст: str, запретные: list[str]) -> list[tuple[int, str, str]]:
    """Нарушения формы: номер строки, имя правила, отрывок предложения."""
    образец = re.compile(
        rf"\b(?:{ПРИСТАВКИ})?(" + "|".join(map(re.escape, запретные)) + r")\w*", re.IGNORECASE
    )
    итог: list[tuple[int, str, str]] = []
    for начало, единица, пункт in единицы(текст):
        хранилище: list[str] = []
        части, основных = _разобрать(единица, хранилище)
        if not пункт and основных > ПРЕДЕЛ_ПРЕДЛОЖЕНИЙ:
            отрывок = _развернуть(части[0][1], хранилище)[:ДЛИНА_ОТРЫВКА]
            итог.append((начало, f"абзац {основных}", отрывок))
        for сдвиг, часть in части:
            отрывок = _развернуть(часть, хранилище)[:ДЛИНА_ОТРЫВКА]
            if (число := _слова(часть)) > ПРЕДЕЛ_СЛОВ:
                итог.append((начало + сдвиг, f"длина {число}", отрывок))
            if запретные:
                for слово in dict.fromkeys(с.group(1).lower() for с in образец.finditer(часть)):
                    итог.append((начало + сдвиг, f"слово {слово}", отрывок))
    return sorted(итог, key=lambda нарушение: нарушение[0])


def main() -> int:
    разбор = argparse.ArgumentParser(description="Счётчик формы упрощённого технического русского")
    разбор.add_argument("файлы", nargs="+", type=Path, metavar="файл")
    разбор.add_argument("--правила", type=Path, default=ПРАВИЛА, help="файл с таблицей запретных слов")
    доводы = разбор.parse_args()
    try:
        начала = запретные(доводы.правила)
        тексты = [(путь, путь.read_text(encoding="utf-8")) for путь in доводы.файлы]
    except (OSError, ValueError) as ошибка:
        print(f"утр: {ошибка}", file=sys.stderr)
        return 2
    счёт = {"длина": 0, "абзац": 0, "слово": 0}
    for путь, текст in тексты:
        for строка, имя, отрывок in нарушения(текст, начала):
            счёт[имя.split()[0]] += 1
            print(f"{путь}:{строка}: {имя}: {отрывок}")
    print(", ".join(f"{имя}: {число}" for имя, число in счёт.items()))
    return 1 if any(счёт.values()) else 0


if __name__ == "__main__":
    sys.exit(main())
